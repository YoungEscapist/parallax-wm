    #[test]
    fn четыре_стола_это_куб() {
        // Рёбра соседних граней сходятся: правый край грани 0 — левый край
        // грани 1.
        let w = 2560.0;
        let (м, _) = места(4, w);
        for k in 0..4 {
            let a = м[k];
            let b = м[(k + 1) % 4];
            let (s, c) = a.нормаль.sin_cos();
            let правый_a = (a.x + c * w * 0.5, a.z - s * w * 0.5);
            let (s, c) = b.нормаль.sin_cos();
            let левый_b = (b.x - c * w * 0.5, b.z + s * w * 0.5);
            assert!((правый_a.0 - левый_b.0).abs() < 1e-6 && (правый_a.1 - левый_b.1).abs() < 1e-6);
        }
    }

