    #[test]
    fn поднятые_окна_анфас_ложатся_на_стол() {
        // Передняя панель раскрытой карусели: точка, поднятая и ужатая, на
        // экране там же, где та же точка стола на панели.
        let (камера, панели) = разложить(&вид(1.0, 0.0), 6);
        let п = панели.iter().find(|п| п.колонка == 0).unwrap();
        let (поднятая, сжатие) = поднять(&камера, &п.плоскость, 300.0);
        assert!(сжатие < 1.0);
        assert!(камера.глубина_плоскости(&поднятая) < камера.глубина_плоскости(&п.плоскость), "ближе к зрителю");
        for (u, v) in [(0.0, 0.0), (-600.0, 300.0), (900.0, -400.0)] {
            let (x0, y0) = камера.проекция_на(&п.плоскость, u, v).unwrap();
            let (x1, y1) = камера.проекция_на(&поднятая, u * сжатие, v * сжатие).unwrap();
            assert!((x0 - x1).abs() < 2.0 && (y0 - y1).abs() < 2.0, "{u},{v}: {x0},{y0} против {x1},{y1}");
        }
    }

