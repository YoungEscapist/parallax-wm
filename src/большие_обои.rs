//! Режим «big picture»: одна ОГРОМНАЯ картинка на холсте в своём настоящем
//! размере, как gigapixel-обои у driftwm (`docs/gigapixel-wallpapers.md`).
//!
//! **Чем не годился cycle.** cycle повторяет текстуру фонового слоя, а это
//! один буфер wl_shm от plx-wall. Картинка 43200×21600 — 3.7 ГБ RGBA: ни в
//! общую память, ни в одну текстуру (у видеокарт предел 16–32 тысячи точек по
//! стороне) она не лезет, а на отдалении одна текстура без мипмапов рябит.
//!
//! **Как устроено.** plx-wall режет картинку на пирамиду плиток 512×512 на
//! диске (`~/.cache/plx-wall/big/<ключ>/`: уровень 0 — родной размер, каждый
//! следующий вдвое меньше) и говорит `wallpaper big <каталог>`. На фоновый
//! слой он кладёт только ОБЗОР — копию не больше 2048 по стороне, она же
//! следующий за последним уровень пирамиды. Композитор:
//!  - подложкой рисует обзор шейдером cycle, растянутым до НАСТОЯЩЕГО размера
//!    картинки (`udev::wallpaper_cycle_for`), — он закрывает плитки, которые
//!    ещё не доехали, и он же весь кадр на сильном отдалении;
//!  - поверх кладёт плитки того уровня, где точка уровня не крупнее точки
//!    экрана, и только видимые; недоехавшую плитку пока заменяет её
//!    родитель с уровня выше, если он уже залит;
//!  - файлы читают и распаковывают фоновые потоки, кадр только заливает
//!    готовое в текстуры, и не больше нескольких плиток за раз.
//!
//! Повтор и начало — как в cycle: период равен размеру картинки, середина
//! картинки у дома стоит в центре экрана.

use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Condvar, Mutex};
use std::time::{Duration, Instant};

use smithay::backend::allocator::Fourcc;
use smithay::backend::renderer::{
    element::Id,
    gles::{GlesRenderer, GlesTexture},
    ContextId, ImportMem, Renderer,
};
use smithay::reexports::calloop::channel;
use smithay::utils::{Physical, Rectangle};

use crate::state::Parallax;

/// Файл с описанием пирамиды в её каталоге. Пишет plx-wall последним, так что
/// он есть — значит, есть и все плитки.
const ОПИСАНИЕ: &str = "plx-big.txt";

/// Сколько потоков читают плитки. Один упирается в распаковку PNG (3–4 мс на
/// плитку): экран — это до семидесяти плиток, и первый показ шёл бы долго.
const ПОТОКОВ: usize = 3;

/// Сколько плиток держим в видеопамяти (по мегабайту на каждую). Экран
/// 2560×1080 — до 72 плиток уровня плюс родители, на два монитора с запасом.
const БЮДЖЕТ: usize = 256;

/// Сколько времени кадра можно отдать заливке плиток в текстуры. Одна плитка
/// на zink (nouveau) — 1.4 мс в среднем и до 4.5 в худшем (создание текстуры
/// с ограждением): восемь за кадр давали такт в 12–13 мс против 1.7 в cycle
/// (замер харнессом 29.10.2026). Хотя бы одна за кадр заливается всегда —
/// на этом железе это и выходит «одна за кадр», экран плиток за полсекунды.
const НА_ЗАЛИВКУ: Duration = Duration::from_millis(1);

/// Плитка проявляется, а не выскакивает поверх размытого обзора.
const ПОЯВЛЕНИЕ: Duration = Duration::from_millis(180);

/// Описание пирамиды (`plx-big.txt`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Описание {
    /// Настоящий размер картинки, он же период повтора на холсте.
    pub w: u32,
    pub h: u32,
    /// Сторона плитки.
    pub плитка: u32,
    /// Сколько уровней порезано на плитки. Обзор на фоновом слое — уровень
    /// `уровни`; ноль значит, что картинка целиком и есть обзор.
    pub уровни: u32,
}

impl Описание {
    pub fn прочитать(каталог: &Path) -> Option<Self> {
        Self::разобрать(&std::fs::read_to_string(каталог.join(ОПИСАНИЕ)).ok()?)
    }

    /// ```text
    /// plx-wall big 1
    /// size 43200 21600
    /// tile 512
    /// levels 5
    /// ```
    fn разобрать(текст: &str) -> Option<Self> {
        let mut строки = текст.lines();
        if строки.next()?.trim() != "plx-wall big 1" {
            return None;
        }
        let (mut размер, mut плитка, mut уровни) = (None, None, None);
        for строка in строки {
            let слова: Vec<&str> = строка.split_whitespace().collect();
            match слова.as_slice() {
                ["size", w, h] => размер = Some((w.parse().ok()?, h.parse().ok()?)),
                ["tile", t] => плитка = Some(t.parse().ok()?),
                ["levels", l] => уровни = Some(l.parse().ok()?),
                _ => {}
            }
        }
        let ((w, h), плитка, уровни): ((u32, u32), u32, u32) = (размер?, плитка?, уровни?);
        (w > 0 && h > 0 && плитка >= 16 && уровни < 32).then_some(Self { w, h, плитка, уровни })
    }

    /// Размер уровня `l`: каждый следующий вдвое меньше, с округлением вверх
    /// (так же уменьшает plx-wall).
    pub fn размер(&self, l: u32) -> (u32, u32) {
        let вверх = |v: u32| (((v as u64) + (1u64 << l) - 1) >> l).max(1) as u32;
        (вверх(self.w), вверх(self.h))
    }

    pub fn плиток(&self, l: u32) -> (u32, u32) {
        let (w, h) = self.размер(l);
        (w.div_ceil(self.плитка), h.div_ceil(self.плитка))
    }

    /// Уровень, на котором точка уровня не крупнее точки экрана; `к` — сколько
    /// точек экрана приходится на точку картинки (зум × масштаб выхода).
    /// `None` — хватает обзора.
    pub fn уровень(&self, к: f64) -> Option<u32> {
        if !к.is_finite() || к <= 0.0 {
            return None;
        }
        let l = (1.0 / к).log2().floor().max(0.0);
        (l < self.уровни as f64).then_some(l as u32)
    }
}

/// (уровень, x, y) плитки.
pub type Ключ = (u32, u32, u32);

/// Распакованная плитка от фонового потока.
pub struct Пришло {
    поколение: u64,
    ключ: Ключ,
    /// RGBA; `None` — файл не прочитался.
    пиксели: Option<(u32, u32, Vec<u8>)>,
}

struct Очередь {
    /// Что нужно кадру, ближние к центру экрана первыми. Кадр заменяет список
    /// целиком: уехавшее с экрана просто перестаёт в нём значиться.
    ждут: Vec<Ключ>,
    /// Что уже читается — кадр не просит это второй раз.
    в_работе: HashSet<Ключ>,
    закрыта: bool,
}

struct Залита {
    текстура: GlesTexture,
    id: Id,
    когда: Instant,
    /// Когда была в кадре последний раз — по этому выбрасываем лишние.
    нужна: Instant,
}

/// Кусок кадра: плитка и где она лежит на экране.
pub struct Кусок {
    pub текстура: GlesTexture,
    pub id: Id,
    pub место: Rectangle<i32, Physical>,
    pub альфа: f32,
}

pub struct Большие {
    pub каталог: PathBuf,
    pub описание: Описание,
    поколение: u64,
    очередь: Arc<(Mutex<Очередь>, Condvar)>,
    /// Пришли от потоков, но ещё не залиты (заливать можно только в кадре —
    /// там есть рендерер).
    готовые: Vec<(Ключ, u32, u32, Vec<u8>)>,
    кэш: HashMap<Ключ, Залита>,
    битые: HashSet<Ключ>,
    контекст: Option<ContextId<GlesTexture>>,
    /// Растёт с каждой залитой или выброшенной плиткой: по нему кэш блюра
    /// понимает, что картинка под ним стала другой.
    pub версия: u64,
}

impl Drop for Большие {
    fn drop(&mut self) {
        let (м, cv) = &*self.очередь;
        if let Ok(mut о) = м.lock() {
            о.закрыта = true;
            о.ждут.clear();
        }
        cv.notify_all();
    }
}

impl Большие {
    fn new(каталог: PathBuf, описание: Описание, поколение: u64, tx: channel::Sender<Пришло>) -> Self {
        let очередь = Arc::new((
            Mutex::new(Очередь { ждут: Vec::new(), в_работе: HashSet::new(), закрыта: false }),
            Condvar::new(),
        ));
        for _ in 0..ПОТОКОВ {
            let (к, о, tx) = (каталог.clone(), очередь.clone(), tx.clone());
            let _ = std::thread::Builder::new()
                .name("plx-big-tiles".into())
                .spawn(move || грузчик(к, поколение, о, tx));
        }
        Self {
            каталог,
            описание,
            поколение,
            очередь,
            готовые: Vec::new(),
            кэш: HashMap::new(),
            битые: HashSet::new(),
            контекст: None,
            версия: 0,
        }
    }

    /// Залить пришедшие плитки в текстуры. `true` — залито не всё, нужен
    /// ещё кадр.
    pub fn залить(&mut self, renderer: &mut GlesRenderer) -> bool {
        let ctx = renderer.context_id();
        if self.контекст.as_ref() != Some(&ctx) {
            // Текстуры другого рендерера этому не годятся.
            self.кэш.clear();
            self.контекст = Some(ctx);
        }
        let сейчас = Instant::now();
        let mut залито = 0;
        while !self.готовые.is_empty() && (залито == 0 || сейчас.elapsed() < НА_ЗАЛИВКУ) {
            залито += 1;
            // Ближние к центру экрана заказаны первыми, первыми и заливаются.
            let (ключ, w, h, пиксели) = self.готовые.remove(0);
            match renderer.import_memory(&пиксели, Fourcc::Abgr8888, (w as i32, h as i32).into(), false) {
                Ok(текстура) => {
                    self.кэш.insert(ключ, Залита { текстура, id: Id::new(), когда: сейчас, нужна: сейчас });
                    self.версия += 1;
                }
                Err(e) => {
                    tracing::warn!("plx/wallpaper: big picture tile {:?} upload failed: {:?}", ключ, e);
                    self.битые.insert(ключ);
                }
            }
        }
        if self.кэш.len() > БЮДЖЕТ {
            let mut по_давности: Vec<(Instant, Ключ)> =
                self.кэш.iter().map(|(к, з)| (з.нужна, *к)).collect();
            по_давности.sort_unstable_by_key(|(т, _)| *т);
            for (_, к) in по_давности.into_iter().take(self.кэш.len() - БЮДЖЕТ) {
                self.кэш.remove(&к);
            }
            self.версия += 1;
        }
        !self.готовые.is_empty()
    }

    /// Плитки кадра поверх обзора — от переднего плана к заднему, как список
    /// элементов. Заодно заказывает потокам недостающие. Второе значение —
    /// идёт ли проявление (тогда нужен следующий кадр).
    pub fn кадр(&mut self, раскладка: &crate::плитка_обоев::Раскладка) -> (Vec<Кусок>, bool) {
        let о = self.описание;
        let к = раскладка.плитка.0 / о.w as f64;
        let Some(l) = о.уровень(к) else {
            self.заказать(Vec::new());
            return (Vec::new(), false);
        };
        let (wl, hl) = о.размер(l);
        let ось_x = по_оси(раскладка.начало.0, раскладка.плитка.0, wl, о.плитка, раскладка.экран.0);
        let ось_y = по_оси(раскладка.начало.1, раскладка.плитка.1, hl, о.плитка, раскладка.экран.1);
        // Узкая полоса на огромном отдалении по одной оси дала бы тысячи
        // крошечных плиток — там хватает обзора.
        if ось_x.len() * ось_y.len() > 600 {
            self.заказать(Vec::new());
            return (Vec::new(), false);
        }

        let сейчас = Instant::now();
        let центр = (раскладка.экран.0 / 2.0, раскладка.экран.1 / 2.0);
        let mut свои = Vec::new();
        let mut родители: Vec<Кусок> = Vec::new();
        let mut взяты_родители = HashSet::new();
        let mut нет: Vec<(f64, Ключ)> = Vec::new();
        let mut проявление = false;

        for &(ty, y0, y1, копия_y) in &ось_y {
            for &(tx, x0, x1, копия_x) in &ось_x {
                let ключ = (l, tx, ty);
                let место = Rectangle::<i32, Physical>::new((x0, y0).into(), (x1 - x0, y1 - y0).into());
                if let Some(з) = self.кэш.get_mut(&ключ) {
                    з.нужна = сейчас;
                    let альфа = появление(з.когда, сейчас);
                    проявление |= альфа < 1.0;
                    свои.push(Кусок { текстура: з.текстура.clone(), id: з.id.clone(), место, альфа });
                    continue;
                }
                if !self.битые.contains(&ключ) {
                    let (cx, cy) = ((x0 + x1) as f64 / 2.0, (y0 + y1) as f64 / 2.0);
                    нет.push(((cx - центр.0).powi(2) + (cy - центр.1).powi(2), ключ));
                }
                // Пока своей нет — ближайший залитый предок.
                for шаг in 1..(о.уровни - l) {
                    let pl = l + шаг;
                    let pk = (pl, tx >> шаг, ty >> шаг);
                    let Some(з) = self.кэш.get_mut(&pk) else { continue };
                    з.нужна = сейчас;
                    let (pw, ph) = о.размер(pl);
                    let (px0, px1) = отрезок(копия_x, раскладка.плитка.0, pw, о.плитка, pk.1);
                    let (py0, py1) = отрезок(копия_y, раскладка.плитка.1, ph, о.плитка, pk.2);
                    if взяты_родители.insert((pk, px0, py0)) {
                        родители.push(Кусок {
                            текстура: з.текстура.clone(),
                            id: з.id.clone(),
                            место: Rectangle::new((px0, py0).into(), (px1 - px0, py1 - py0).into()),
                            альфа: появление(з.когда, сейчас),
                        });
                    }
                    break;
                }
            }
        }
        нет.sort_by(|a, b| a.0.total_cmp(&b.0));
        self.заказать(нет.into_iter().map(|(_, к)| к).collect());
        свои.extend(родители);
        (свои, проявление)
    }

    fn заказать(&mut self, mut нужно: Vec<Ключ>) {
        let пришли: HashSet<Ключ> = self.готовые.iter().map(|г| г.0).collect();
        let (м, cv) = &*self.очередь;
        let Ok(mut о) = м.lock() else { return };
        нужно.retain(|к| !о.в_работе.contains(к) && !пришли.contains(к));
        if о.ждут != нужно {
            let есть = !нужно.is_empty();
            о.ждут = нужно;
            if есть {
                cv.notify_all();
            }
        }
    }
}

fn появление(когда: Instant, сейчас: Instant) -> f32 {
    (сейчас.saturating_duration_since(когда).as_secs_f32() / ПОЯВЛЕНИЕ.as_secs_f32()).min(1.0)
}

/// Где на экране лежит плитка `t` одной копии картинки по одной оси.
/// `копия` — начало копии на экране, `размер` — вся копия на экране, `уровень`
/// — размер картинки на этом уровне в его точках.
///
/// Края округляются по отдельности: конец плитки и начало соседней считаются
/// одной формулой, поэтому щелей между плитками нет.
fn отрезок(копия: f64, размер: f64, уровень: u32, плитка: u32, t: u32) -> (i32, i32) {
    let f = размер / уровень as f64;
    let начало = (t as u64 * плитка as u64).min(уровень as u64) as f64;
    let конец = ((t as u64 + 1) * плитка as u64).min(уровень as u64) as f64;
    ((копия + начало * f).round() as i32, (копия + конец * f).round() as i32)
}

/// Видимые плитки по одной оси: (номер, начало, конец, начало копии).
/// `начало` — угол копии из раскладки, уже в `[0, размер)`.
fn по_оси(начало: f64, размер: f64, уровень: u32, плитка: u32, экран: f64) -> Vec<(u32, i32, i32, f64)> {
    let mut итог = Vec::new();
    if размер < 1.0 || уровень == 0 || плитка == 0 {
        return итог;
    }
    let n = уровень.div_ceil(плитка);
    let шаг = плитка as f64 * размер / уровень as f64;
    let mut копия = начало - размер;
    while копия < экран {
        let первая = ((-копия) / шаг).floor().max(0.0) as u32;
        let за_последней = (((экран - копия) / шаг).ceil().max(0.0) as u64).min(n as u64) as u32;
        for t in первая..за_последней {
            let (a, b) = отрезок(копия, размер, уровень, плитка, t);
            if b > a && b > 0 && (a as f64) < экран {
                итог.push((t, a, b, копия));
            }
        }
        копия += размер;
    }
    итог
}

fn путь_плитки(каталог: &Path, (l, x, y): Ключ) -> PathBuf {
    каталог.join(l.to_string()).join(format!("{x}_{y}.png"))
}

fn грузчик(каталог: PathBuf, поколение: u64, очередь: Arc<(Mutex<Очередь>, Condvar)>, tx: channel::Sender<Пришло>) {
    // Кадр важнее: плитка, распакованная на пару миллисекунд позже, видна
    // только как чуть позже проявившаяся.
    unsafe {
        libc::nice(5);
    }
    let (м, cv) = &*очередь;
    loop {
        let ключ = {
            let Ok(mut о) = м.lock() else { return };
            loop {
                if о.закрыта {
                    return;
                }
                if !о.ждут.is_empty() {
                    break;
                }
                let Ok(дальше) = cv.wait(о) else { return };
                о = дальше;
            }
            let к = о.ждут.remove(0);
            о.в_работе.insert(к);
            к
        };
        let пиксели = прочитать_плитку(&путь_плитки(&каталог, ключ));
        if tx.send(Пришло { поколение, ключ, пиксели }).is_err() {
            return;
        }
        // Снимаем ПОСЛЕ отправки: иначе кадр между этими двумя шагами не нашёл
        // бы плитку ни в работе, ни в пришедших и заказал бы её второй раз.
        if let Ok(mut о) = м.lock() {
            о.в_работе.remove(&ключ);
        }
    }
}

/// PNG плитки в RGBA.
fn прочитать_плитку(путь: &Path) -> Option<(u32, u32, Vec<u8>)> {
    let файл = std::fs::File::open(путь).ok()?;
    let mut декодер = png::Decoder::new(std::io::BufReader::new(файл));
    декодер.set_transformations(png::Transformations::normalize_to_color8());
    let mut чтение = декодер.read_info().ok()?;
    let (w, h) = (чтение.info().width, чтение.info().height);
    if w == 0 || h == 0 || w > 4096 || h > 4096 {
        return None;
    }
    let (цвет, _) = чтение.output_color_type();
    let mut буфер = vec![0u8; чтение.output_buffer_size()?];
    чтение.next_frame(&mut буфер).ok()?;
    let точек = (w * h) as usize;
    match цвет {
        png::ColorType::Rgba if буфер.len() >= точек * 4 => {
            буфер.truncate(точек * 4);
            Some((w, h, буфер))
        }
        png::ColorType::Rgb if буфер.len() >= точек * 3 => {
            let mut rgba = vec![255u8; точек * 4];
            for (d, s) in rgba.chunks_exact_mut(4).zip(буфер.chunks_exact(3)) {
                d[..3].copy_from_slice(s);
            }
            Some((w, h, rgba))
        }
        _ => None,
    }
}

impl Parallax {
    /// Обои лежат на холсте плитками — cycle или big picture.
    pub fn обои_плиткой(&self) -> bool {
        self.обои_цикл || self.обои_большие.is_some()
    }
}

/// `wallpaper big <каталог>`: включить big picture по пирамиде из этого
/// каталога. Тот же каталог второй раз ничего не сбрасывает — plx-wall
/// повторяет команду при каждом применении обоев.
pub fn включить(state: &mut Parallax, каталог: &Path) -> Result<(), String> {
    if state.обои_большие.as_ref().is_some_and(|б| б.каталог == каталог) {
        return Ok(());
    }
    let описание = Описание::прочитать(каталог)
        .ok_or_else(|| format!("{}: no {ОПИСАНИЕ} or it is broken", каталог.display()))?;
    let tx = match state.обои_большие_канал.clone() {
        Some(tx) => tx,
        None => {
            let (tx, rx) = channel::channel::<Пришло>();
            state
                .петля
                .insert_source(rx, |событие, _, state| {
                    if let channel::Event::Msg(м) = событие {
                        принять(state, м);
                    }
                })
                .map_err(|e| format!("{e:?}"))?;
            state.обои_большие_канал = Some(tx.clone());
            tx
        }
    };
    state.обои_большие_поколение += 1;
    tracing::info!(
        "plx/wallpaper: big picture {} ({}×{}, {} levels)",
        каталог.display(), описание.w, описание.h, описание.уровни,
    );
    state.обои_большие = Some(Большие::new(каталог.to_path_buf(), описание, state.обои_большие_поколение, tx));
    Ok(())
}

fn принять(state: &mut Parallax, м: Пришло) {
    let Some(б) = state.обои_большие.as_mut() else { return };
    // Плитка прошлой картинки — её потоки ещё дочитывали, когда сменили обои.
    if б.поколение != м.поколение {
        return;
    }
    match м.пиксели {
        Some((w, h, пиксели)) => б.готовые.push((м.ключ, w, h, пиксели)),
        None => {
            tracing::warn!("plx/wallpaper: big picture tile {:?} is unreadable", м.ключ);
            б.битые.insert(м.ключ);
        }
    }
    state.request_redraw();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn описание_читается() {
        let о = Описание::разобрать("plx-wall big 1\nsize 43200 21600\ntile 512\nlevels 5\n").unwrap();
        assert_eq!(о, Описание { w: 43200, h: 21600, плитка: 512, уровни: 5 });
        assert_eq!(о.размер(1), (21600, 10800));
        assert_eq!(о.размер(5), (1350, 675));
        assert_eq!(о.плиток(0), (85, 43));
        assert!(Описание::разобрать("что-то другое\nsize 1 1\n").is_none());
    }

    #[test]
    fn нечётный_размер_уменьшается_вверх() {
        let о = Описание { w: 6001, h: 3, плитка: 512, уровни: 2 };
        assert_eq!(о.размер(1), (3001, 2));
        assert_eq!(о.размер(2), (1501, 1));
    }

    #[test]
    fn уровень_по_зуму() {
        let о = Описание { w: 43200, h: 21600, плитка: 512, уровни: 5 };
        assert_eq!(о.уровень(2.0), Some(0));
        assert_eq!(о.уровень(1.0), Some(0));
        assert_eq!(о.уровень(0.6), Some(0));
        assert_eq!(о.уровень(0.5), Some(1));
        assert_eq!(о.уровень(0.26), Some(1));
        assert_eq!(о.уровень(1.0 / 16.0), Some(4));
        // Точка обзора уже не крупнее точки экрана.
        assert_eq!(о.уровень(1.0 / 32.0), None);
    }

    #[test]
    fn плитки_стыкуются_без_щелей_и_кроют_экран() {
        // Картинка 6000 точек, на экране в масштабе 0.7, экран 2560.
        let размер = 6000.0 * 0.7;
        let ось = по_оси(1234.5, размер, 6000, 512, 2560.0);
        assert!(ось.first().unwrap().1 <= 0);
        assert!(ось.last().unwrap().2 >= 2560);
        for пара in ось.windows(2) {
            assert_eq!(пара[0].2, пара[1].1, "щель или нахлёст между {:?} и {:?}", пара[0], пара[1]);
        }
        // Последняя плитка копии узкая (6000 = 11×512 + 368), и за ней сразу
        // первая плитка следующей копии.
        let стык = ось.windows(2).find(|п| п[0].0 == 11 && п[1].0 == 0).unwrap();
        assert_eq!(стык[0].2 - стык[0].1, (368.0f64 * 0.7).round() as i32);
    }

    #[test]
    fn картинка_крупнее_экрана_даёт_только_видимые_плитки() {
        let ось = по_оси(100.0, 43200.0, 43200, 512, 2560.0);
        // Экран 2560 при плитке 512 — пять-шесть плиток, не восемьдесят пять.
        assert!(ось.len() <= 7, "{}", ось.len());
        assert!(ось.iter().all(|&(_, a, b, _)| b > 0 && a < 2560));
    }
}
