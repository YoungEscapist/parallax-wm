    #[test]
    fn наклон_окна_обращается() {
        // Хит-тест наклонённого окна — обратная проекция; она обязана
        // возвращать ровно ту точку окна, которую нарисовала прямая.
        let к = Куб::плоскость(2560.0, 1.2, (900.0, 500.0));
        for (р, т, кр) in [(0.4f32, 0.0f32, 0.0f32), (0.0, -0.6, 0.0), (0.3, 0.5, 1.1), (-1.0, 0.2, -2.5)] {
            let п = Куб::плоскость_окна(р, т, кр);
            for (u, v) in [(0.0, 0.0), (-400.0, -250.0), (380.0, 260.0)] {
                let экран = к.проекция_на(&п, u, v).unwrap();
                let (u2, v2) = к.обратно_на(&п, экран).unwrap();
                assert!((u - u2).abs() < 0.05 && (v - v2).abs() < 0.05, "{u},{v} → {u2},{v2}");
            }
        }
    }

