//! Геометрия куба рабочих столов — чистая арифметика без единого вызова GL.
//!
//! Отдельным файлом, потому что нужна ОБЕИМ сборкам: полная рисует по ней
//! грани (см. `куб.rs`), минимальная — отвечает на вопрос «какой стол под
//! курсором», и два разных ответа в двух сборках были бы хуже, чем общий файл
//! (тот же приём, что у `vr/math.rs` в `vr_stub`).
//!
//! Вывод формул и знаков — в шапке `куб.rs`, рядом с шейдером, который эти
//! формулы обращает.

use smithay::backend::renderer::gles::Uniform;
use smithay::utils::{Physical, Point, Rectangle, Size};

/// Геометрия куба на конкретном экране.
#[derive(Clone, Copy, Debug)]
pub struct Куб {
    /// Сколько граней (столов) по кругу. Меньше трёх призмы не бывает.
    pub граней: u32,
    /// Поворот вокруг оси, радианы. 0 — грань 0 смотрит прямо на зрителя.
    pub поворот: f32,
    /// Радиус вписанной окружности: от оси до плоскости грани.
    pub радиус: f32,
    /// Расстояние от камеры до оси.
    pub камера: f32,
    /// Фокусное расстояние.
    pub фокус: f32,
    /// Куда проецируется ось (физические пиксели экрана).
    pub ось: (f32, f32),
    /// Затемнение дальнего края, 0…1.
    pub тень: f32,
    /// НАКЛОН куба к зрителю, радианы: поворот вокруг горизонтальной оси
    /// экрана, проходящей через центр куба. Применяется ПОСЛЕ `поворот` — как
    /// у поворотного стола: драг вбок крутит куб вокруг его собственной оси,
    /// драг вверх-вниз наклоняет всю эту ось. `> 0` — передняя грань уходит
    /// вверх, и снизу показывается дно.
    ///
    /// При нуле вся геометрия совпадает со старой одноосной до пикселя: та же
    /// плоскость, только записанная базисом, а не одной формулой.
    pub наклон: f32,
}

/// Плоскость в пространстве куба: начало (центр) и два ортонормированных
/// направления — вдоль `u` и вдоль `v`. Координаты: x вправо, y ВНИЗ (как на
/// экране), z на зрителя; камера стоит в `(0, 0, D)`.
///
/// Грань, крышка и развёрнутое окно — все плоскости одного вида, и шейдер
/// получает их одинаково: тремя векторами. Одноосная формула из шапки `куб.rs`
/// — частный случай при нулевом наклоне.
#[derive(Clone, Copy, Debug)]
pub struct Плоскость {
    pub начало: [f32; 3],
    pub вдоль_u: [f32; 3],
    pub вдоль_v: [f32; 3],
}

fn точка(a: [f32; 3], b: [f32; 3]) -> f32 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

fn векторное(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

impl Куб {
    /// Куб под экран.
    ///
    /// `сторона` — ширина грани (она же ширина экрана), `фокус` — фокусное
    /// расстояние в долях стороны, `доля` — какую часть ширины экрана обязана
    /// занять передняя грань. Последнее и есть настоящая ручка: расстояние до
    /// камеры подбирается под неё, а не задаётся в пикселях, которые на другом
    /// экране значили бы другое.
    pub fn новый(
        граней: u32,
        сторона: f32,
        фокус: f32,
        доля: f32,
        ось: (f32, f32),
        тень: f32,
    ) -> Self {
        let граней = граней.max(3);
        let сторона = сторона.max(1.0);
        let полуугол = std::f32::consts::PI / граней as f32;
        // r = (сторона/2)/tan(π/N): расстояние от оси до середины грани.
        let радиус = (сторона * 0.5) / полуугол.tan().max(1e-4);
        let фокус = (фокус.max(0.1)) * сторона;
        // Из x = F·(сторона/2)/(D − r) = доля·(сторона/2) следует D = r + F/доля.
        let камера = радиус + фокус / доля.clamp(0.05, 4.0);
        Self {
            граней,
            поворот: 0.0,
            радиус,
            камера,
            фокус,
            ось,
            тень: тень.clamp(0.0, 1.0),
            наклон: 0.0,
        }
    }

    /// ОДИНОЧНАЯ ПЛОСКОСТЬ, вращающаяся вокруг собственной вертикальной оси, —
    /// то есть окно, развёрнутое в 3D (см. `flip3d`, анимация открытия и
    /// закрытия в духе Compiz).
    ///
    /// Это тот же куб, у которого радиус равен нулю: плоскость грани проходит
    /// через саму ось, и «повернуть грань» значит повернуть окно вокруг его
    /// середины. Отдельного шейдера ради этого не заводится — обратное
    /// отображение у плоскости ровно то же самое, что у грани, с `r = 0`.
    ///
    /// Расстояние до камеры берётся РАВНЫМ фокусному намеренно: при `r = 0`
    /// масштаб проекции равен `F/D`, и только при `D = F` нулевой угол даёт
    /// картинку пиксель в пиксель. Разойдись эти двое — окно в последнем кадре
    /// анимации прыгнуло бы в размере, переходя на обычный путь отрисовки.
    pub fn плоскость(сторона: f32, фокус: f32, ось: (f32, f32)) -> Self {
        let фокус = фокус.max(0.1) * сторона.max(1.0);
        Self {
            граней: 4,
            поворот: 0.0,
            радиус: 0.0,
            камера: фокус,
            фокус,
            ось,
            тень: 0.0,
            наклон: 0.0,
        }
    }

    /// Та же геометрия, но плоскость грани отодвинута от оси на `подъём`, —
    /// то есть ПОДНЯТА НАД ГРАНЬЮ, ближе к зрителю.
    ///
    /// Ради этого куб и перестаёт быть одним целым с окнами: сам он остаётся
    /// коробкой из обоев на радиусе `r`, а каждое окно живёт на своей
    /// плоскости `r + подъём` (см. `build_cube_elements`). Окно от этого не
    /// просто рисуется поверх — оно ближе к камере, крупнее и перекрывает
    /// соседей по-настоящему, включая окна соседних граней.
    pub fn с_подъёмом(&self, подъём: f32) -> Self {
        Self {
            радиус: (self.радиус + подъём).max(0.0),
            ..*self
        }
    }

    /// Во сколько раз ужать координаты на плоскости, поднятой над этой гранью
    /// (`поднятый` — результат `с_подъёмом`), чтобы АНФАС она легла на грань
    /// пиксель в пиксель.
    ///
    /// Поднятая плоскость ближе к камере, и без поправки всё на ней крупнее
    /// грани в `(D − r)/(D − r')` раз. Пока подъём один на стол, это «стол
    /// чуть раздут», но у каждого окна стопки подъём СВОЙ (`cube_lift_step`),
    /// и раздувало их по-разному: соседние окна тайлинга налезали друг на
    /// друга, а нижние вылезали за край грани (жалоба 24.09.2026 «неправильное
    /// отображение окон в обзоре»). С поправкой раскладка на передней грани
    /// точная, а при повороте окна всё равно видно висящими над гранью —
    /// параллакс даёт разница глубин, а не размер.
    pub fn сжатие_подъёма(&self, поднятый: &Куб) -> f32 {
        let до_грани = (self.камера - self.радиус).max(1.0);
        ((self.камера - поднятый.радиус).max(1.0) / до_грани).clamp(0.05, 1.0)
    }

    /// Повернуть вектор НАКЛОНОМ — вокруг горизонтальной оси экрана.
    ///
    /// Знак: при `наклон > 0` точка передней грани (`z > 0`) уходит вверх
    /// (`y` убывает), то есть куб наклоняется ВЕРХОМ ОТ зрителя и показывает дно.
    fn наклонить(&self, [x, y, z]: [f32; 3]) -> [f32; 3] {
        let (s, c) = self.наклон.sin_cos();
        [x, y * c - z * s, y * s + z * c]
    }

    /// Плоскость грани, повёрнутой на `угол` вокруг оси куба (с наклоном).
    pub fn грань(&self, угол: f32) -> Плоскость {
        let (sa, ca) = угол.sin_cos();
        let r = self.радиус;
        Плоскость {
            начало: self.наклонить([r * sa, 0.0, r * ca]),
            вдоль_u: self.наклонить([ca, 0.0, -sa]),
            вдоль_v: self.наклонить([0.0, 1.0, 0.0]),
        }
    }

    /// КРЫШКА куба: верхняя (`верх`) или нижняя, на высоте `высота/2` от
    /// центра. Правильный `граней`-угольник с апофемой `радиус` — ровно тот,
    /// на рёбра которого опираются грани; в шейдере он вырезается из квадрата
    /// `±описанный_радиус` (см. `uniforms_крышки`).
    ///
    /// Крутится вместе с гранями (`поворот`): ось `v` смотрит туда же, куда
    /// нормаль грани 0, поэтому нормаль грани `i` в координатах крышки —
    /// `(sin iθ, cos iθ)`, и этого шейдеру достаточно, чтобы резать угольник.
    /// У нижней развёрнута ось `u`, а не `v`: набор нормалей правильного
    /// угольника симметричен относительно `u → −u` при любом числе граней, а
    /// относительно `v → −v` — только при чётном.
    pub fn крышка(&self, верх: bool, высота: f32) -> Плоскость {
        let (sp, cp) = self.поворот.sin_cos();
        let (y, знак_u) = if верх { (-высота * 0.5, 1.0) } else { (высота * 0.5, -1.0) };
        Плоскость {
            начало: self.наклонить([0.0, y, 0.0]),
            вдоль_u: self.наклонить([cp * знак_u, 0.0, -sp * знак_u]),
            вдоль_v: self.наклонить([sp, 0.0, cp]),
        }
    }

    /// Плоскость НАКЛОНЁННОГО окна (см. наклон.rs) с началом в середине окна.
    /// Камера — `Куб::плоскость`, то есть `D = F`, и без наклона окно ложится
    /// пиксель в пиксель туда же, куда его кладёт обычный путь.
    ///
    /// Порядок поворотов: сперва `крен` в плоскости экрана (`> 0` — по часовой
    /// стрелке, y смотрит вниз), потом `тангаж` вокруг горизонтальной оси
    /// (`> 0` — верх окна уходит от зрителя), потом `рыскание` вокруг
    /// вертикальной (`> 0` — правый край уходит от зрителя, как у грани куба
    /// с положительным углом). Так крен остаётся «картинка повёрнута на столе»,
    /// а два наклона — «стол повёрнут к зрителю», в каком бы порядке их ни крутили.
    pub fn плоскость_окна(рыскание: f32, тангаж: f32, крен: f32) -> Плоскость {
        let (sr, cr) = крен.sin_cos();
        let (sp, cp) = тангаж.sin_cos();
        let (sy, cy) = рыскание.sin_cos();
        let повернуть = |[x, y, z]: [f32; 3]| -> [f32; 3] {
            // Тангаж — тот же поворот, что `наклонить` у куба.
            let (y, z) = (y * cp - z * sp, y * sp + z * cp);
            // Рыскание — тот же, что разворачивает грань: u = (cos α, 0, −sin α).
            [x * cy + z * sy, y, -x * sy + z * cy]
        };
        Плоскость {
            начало: [0.0, 0.0, 0.0],
            вдоль_u: повернуть([cr, sr, 0.0]),
            вдоль_v: повернуть([-sr, cr, 0.0]),
        }
    }

    /// Радиус описанной окружности основания: полудиагональ квадрата, в
    /// который вписана крышка.
    pub fn описанный_радиус(&self) -> f32 {
        let полуугол = std::f32::consts::PI / self.граней.max(3) as f32;
        self.радиус / полуугол.cos().max(1e-4)
    }

    /// Видна ли крышка: её лицо обращено к КАМЕРЕ (честная перспектива, не
    /// ортографическое «нормаль к зрителю»). При нулевом наклоне камера стоит
    /// на уровне середины куба, и ни верха, ни дна не видно вовсе. Порог — чтобы
    /// не рисовать крышку, стоящую к камере почти ребром (полоска в пиксель).
    pub fn крышка_видна(&self, верх: bool, высота: f32) -> bool {
        let п = self.крышка(верх, высота);
        let нормаль = self.наклонить(if верх { [0.0, -1.0, 0.0] } else { [0.0, 1.0, 0.0] });
        let к_камере = [-п.начало[0], -п.начало[1], self.камера - п.начало[2]];
        let длина = точка(к_камере, к_камере).sqrt().max(1.0);
        точка(нормаль, к_камере) / длина > 0.03
    }

    /// Глубина центра плоскости: расстояние от камеры вдоль взгляда. По ней
    /// грани, крышки и окна сортируются от ближних к дальним.
    pub fn глубина_плоскости(&self, п: &Плоскость) -> f32 {
        self.камера - п.начало[2]
    }

    /// Глубина центра грани (`u = 0`) под углом `угол`.
    ///
    /// Именно центр, а не точка поверхности: по точке ближний край окна на
    /// грани, стоящей почти ребром, оказывался бы ДАЛЬШЕ подложки своей же
    /// грани — и подложка закрывала бы окно, лежащее на ней.
    pub fn глубина(&self, угол: f32) -> f32 {
        self.глубина_плоскости(&self.грань(угол))
    }

    /// Угол грани `i` с учётом текущего поворота.
    pub fn угол(&self, i: u32) -> f32 {
        let шаг = std::f32::consts::TAU / self.граней as f32;
        self.поворот + i as f32 * шаг
    }

    /// Обращена ли грань к зрителю.
    ///
    /// Строгое «нормаль смотрит в камеру» дало бы грани, вырожденные в
    /// вертикальную полоску толщиной в пиксель: у них `cos α → 0`, проекция
    /// схлопывается, а фрагментов при этом рисуется столько же. Порог 87°
    /// отсекает именно их. С наклоном нормаль грани к зрителю — `cos α·cos β`,
    /// и порог тот же: при нулевом наклоне это ровно прежнее `|α| < 87°`.
    pub fn видна(&self, i: u32) -> bool {
        let a = нормировать(self.угол(i));
        a.cos() * self.наклон.cos() > 87.0f32.to_radians().cos()
    }

    /// Проекция точки грани на экран. `None` — точка за камерой. Живым путям
    /// хватает `проекция_на`; эта — тестам, которые меряют грани по углу.
    #[allow(dead_code)]
    pub fn проекция(&self, угол: f32, u: f32, v: f32) -> Option<(f32, f32)> {
        self.проекция_на(&self.грань(угол), u, v)
    }

    /// Проекция точки `(u, v)` произвольной плоскости.
    pub fn проекция_на(&self, п: &Плоскость, u: f32, v: f32) -> Option<(f32, f32)> {
        let p = [
            п.начало[0] + u * п.вдоль_u[0] + v * п.вдоль_v[0],
            п.начало[1] + u * п.вдоль_u[1] + v * п.вдоль_v[1],
            п.начало[2] + u * п.вдоль_u[2] + v * п.вдоль_v[2],
        ];
        let d = self.камера - p[2];
        if d <= 1.0 {
            return None;
        }
        Some((
            self.ось.0 + self.фокус * p[0] / d,
            self.ось.1 + self.фокус * p[1] / d,
        ))
    }

    /// Обратная проекция: какая точка грани `угол` видна в точке экрана.
    ///
    /// Нужна на CPU для хит-теста «на какую грань показывает курсор» — на кубе
    /// окна лежат не там, где на холсте, и обычный `space.element_under`
    /// отвечает про другое место экрана.
    ///
    /// `None` — луч уходит мимо плоскости грани или за камеру.
    pub fn обратно(&self, угол: f32, точка_экрана: (f32, f32)) -> Option<(f32, f32)> {
        self.обратно_на(&self.грань(угол), точка_экрана)
    }

    /// Обратная проекция на произвольную плоскость: пересечение луча из камеры
    /// с плоскостью. Ровно то же считает шейдер (`куб.rs`), строка в строку.
    ///
    /// Луч `C + t·w`, `C = (0, 0, D)`, `w = (x, y, −F)`; плоскость — начало `O`
    /// и нормаль `n = eu × ev`. Тогда `t = n·(O − C) / n·w`, точка попадания
    /// `H = C + t·w`, координаты на плоскости — проекции `H − O` на `eu` и `ev`
    /// (базис ортонормирован), а глубина `d = D − H.z = t·F`.
    pub fn обратно_на(&self, п: &Плоскость, точка_экрана: (f32, f32)) -> Option<(f32, f32)> {
        let w = [точка_экрана.0 - self.ось.0, точка_экрана.1 - self.ось.1, -self.фокус];
        let n = векторное(п.вдоль_u, п.вдоль_v);
        let знаменатель = точка(n, w);
        if знаменатель.abs() < 1e-4 {
            return None;
        }
        let к_началу = [п.начало[0], п.начало[1], п.начало[2] - self.камера];
        let t = точка(n, к_началу) / знаменатель;
        if t * self.фокус <= 1.0 {
            return None;
        }
        let от_начала = [
            w[0] * t - к_началу[0],
            w[1] * t - к_началу[1],
            w[2] * t - к_началу[2],
        ];
        Some((точка(от_начала, п.вдоль_u), точка(от_начала, п.вдоль_v)))
    }

    /// Экранный прямоугольник, в который заведомо укладывается проекция куска
    /// грани `(u0, v0)…(u1, v1)`.
    ///
    /// Проекция прямоугольника — выпуклый четырёхугольник, и элементу кадра
    /// нужен объемлющий его прямоугольник: за пределами `dst` фрагментов нет,
    /// и всё, что туда не попало, было бы просто срезано. По углам считать
    /// достаточно — вершины выпуклой фигуры и есть её крайние точки, пока все
    /// четыре перед камерой.
    pub fn коробка(
        &self,
        угол: f32,
        rect: (f32, f32, f32, f32),
    ) -> Option<Rectangle<i32, Physical>> {
        self.коробка_на(&self.грань(угол), rect)
    }

    pub fn коробка_на(
        &self,
        п: &Плоскость,
        (u0, v0, u1, v1): (f32, f32, f32, f32),
    ) -> Option<Rectangle<i32, Physical>> {
        let углы = [(u0, v0), (u1, v0), (u0, v1), (u1, v1)];
        let mut минx = f32::MAX;
        let mut минy = f32::MAX;
        let mut максx = f32::MIN;
        let mut максy = f32::MIN;
        for (u, v) in углы {
            let (x, y) = self.проекция_на(п, u, v)?;
            минx = минx.min(x);
            минy = минy.min(y);
            максx = максx.max(x);
            максy = максy.max(y);
        }
        // Запас в пиксель с каждой стороны: округление вниз/вверх иначе
        // срезает крайний столбец фрагментов, и по краю грани идёт щель.
        let x = минx.floor() as i32 - 1;
        let y = минy.floor() as i32 - 1;
        let w = (максx.ceil() as i32 + 1) - x;
        let h = (максy.ceil() as i32 + 1) - y;
        if w <= 0 || h <= 0 {
            return None;
        }
        Some(Rectangle::new(
            Point::from((x, y)),
            Size::from((w, h)),
        ))
    }

    /// Uniform'ы для отрисовки куска грани. Зовёт `куб.rs` — в стандартной
    /// сборке не зовёт никто, и это ровно то, чего мы хотим.
    #[allow(dead_code)]
    pub fn uniforms(&self, угол: f32, rect: (f32, f32, f32, f32)) -> Vec<Uniform<'static>> {
        self.uniforms_на(&self.грань(угол), rect, None)
    }

    /// Uniform'ы крышки: квадрат `±описанный_радиус`, из которого шейдер
    /// вырезает правильный угольник, и приглушённая яркость — крышка того же
    /// цвета, что и грани, сливалась бы с ними, и ребро сверху не читалось.
    #[allow(dead_code)]
    pub fn uniforms_крышки(&self, п: &Плоскость, яркость: f32) -> Vec<Uniform<'static>> {
        let о = self.описанный_радиус();
        self.uniforms_на(п, (-о, -о, о, о), Some(яркость))
    }

    /// Uniform'ы куска произвольной плоскости с общей яркостью — панели
    /// карусели (соседние этажи приглушены).
    #[allow(dead_code)]
    pub fn uniforms_плоскости(
        &self,
        п: &Плоскость,
        rect: (f32, f32, f32, f32),
        яркость: f32,
    ) -> Vec<Uniform<'static>> {
        let mut u = self.uniforms_на(п, rect, None);
        if let Some(poly) = u.iter_mut().find(|u| u.name == "cube_poly") {
            *poly = Uniform::new("cube_poly", [0.0f32, 0.0, яркость]);
        }
        u
    }

    #[allow(dead_code)]
    fn uniforms_на(
        &self,
        п: &Плоскость,
        rect: (f32, f32, f32, f32),
        крышка: Option<f32>,
    ) -> Vec<Uniform<'static>> {
        // cube_poly: число граней (0 — не крышка), апофема, яркость.
        let poly = match крышка {
            Some(яркость) => [self.граней as f32, self.радиус, яркость],
            None => [0.0, 0.0, 1.0],
        };
        vec![
            Uniform::new("cube_geom", [self.радиус, self.камера, self.фокус, 0.0]),
            Uniform::new("cube_o", п.начало),
            Uniform::new("cube_eu", п.вдоль_u),
            Uniform::new("cube_ev", п.вдоль_v),
            Uniform::new("cube_rect", [rect.0, rect.1, rect.2, rect.3]),
            Uniform::new("cube_clip", [rect.0, rect.1, rect.2, rect.3]),
            Uniform::new("cube_axis", [self.ось.0, self.ось.1]),
            Uniform::new("cube_shade", self.тень),
            Uniform::new("cube_poly", poly),
            // Скругление углов окна (см. `скруглить`): по умолчанию выключено.
            // Задаётся ВСЕГДА — uniform живёт в программе между отрисовками, и
            // не заданный здесь достался бы грани от последнего наклонённого окна.
            Uniform::new("cube_round", [0.0f32, 0.0, 0.0, 0.0]),
            Uniform::new("cube_radius", 0.0f32),
        ]
    }

    /// Включить в готовых uniform'ах скругление углов: `rect` — видимая рамка
    /// окна в координатах плоскости, `радиус` — радиус дуги в тех же единицах.
    /// Нужно наклонённому окну: шейдер скругления на него не ложится (две
    /// программы на одно место кадра), и углы режет шейдер плоскости.
    #[allow(dead_code)]
    pub fn скруглить(uniforms: &mut [Uniform<'static>], rect: (f32, f32, f32, f32), радиус: f32) {
        for u in uniforms.iter_mut() {
            if u.name == "cube_round" {
                *u = Uniform::new("cube_round", [rect.0, rect.1, rect.2, rect.3]);
            } else if u.name == "cube_radius" {
                *u = Uniform::new("cube_radius", радиус.max(0.0));
            }
        }
    }
}

/// Какой стол лежит на грани `грань`, когда куб довёрнут до оборота `оборот`.
///
/// **Зачем.** Куб бесконечен: граней всегда `граней` (четыре, как в Compiz), а
/// столов в кольце сколько угодно. Раньше грань заводилась на КАЖДЫЙ стол, и
/// это ломалось с двух сторон: на десяти столах призма из десяти граней имеет
/// такой радиус, что грани почти не наклонены — куб выглядит плоской стеной, а
/// на четырёх столах кольцо кончалось, и дальше крутить было некуда.
///
/// **Как.** Слот `i` показывает стол `оборот + d`, где `d` — смещение слота от
/// переднего, приведённое к (−граней/2, граней/2]. Смещение считается в номерах
/// СЛОТОВ, а номер стола берётся по кольцу столов — то есть при повороте на
/// грань каждый слот получает следующий стол, и кольцо не кончается никогда.
///
/// Подмена случается на слоте, отстоящем от переднего на полкруга, — то есть на
/// ЗАДНЕЙ грани, которой не видно (см. [`Куб::видна`]). Ради этого смещение и
/// приводится к диапазону вокруг нуля: иначе стол менялся бы на грани, стоящей
/// к зрителю лицом, и куб мигал бы содержимым под руками.
///
/// `оборот` — сколько граней уже провернули (round(−поворот/шаг)), `столов` —
/// длина кольца столов. Возвращается индекс в этом кольце.
pub fn стол_грани(оборот: i64, грань: u32, граней: u32, столов: usize) -> usize {
    let столов = столов.max(1) as i64;
    let граней = граней.max(3) as i64;
    // Передний слот при этом обороте.
    let передний = оборот.rem_euclid(граней);
    // Смещение слота от переднего в (−граней/2, граней/2].
    let d = (грань as i64 - передний + граней / 2).rem_euclid(граней) - граней / 2;
    (оборот + d).rem_euclid(столов) as usize
}

/// Сколько столов ВПЕРЁД по кольцу от оборота `оборот` до стола `цель`.
///
/// Ближним путём: половину кольца идём вперёд, дальше — назад. `цель` —
/// индекс в кольце столов, `столов` — его длина.
///
/// ЗНАК ЗДЕСЬ В СТОЛАХ, А НЕ В УГЛАХ. Шаг вперёд по кольцу УМЕНЬШАЕТ угол
/// поворота на шаг грани (угол грани `i` равен −i·шаг), и вызывающий обязан
/// вычитать. Ровно на этом знаке куб и уехал на харнессе: столы шли вперёд, а
/// куб крутился назад — через три перехода передняя грань показывала стол, на
/// котором были два переключения назад.
pub fn шагов_до(оборот: i64, цель: usize, столов: usize) -> i64 {
    let столов = столов.max(1) as i64;
    let mut d = (цель as i64 - оборот).rem_euclid(столов);
    if d > столов / 2 {
        d -= столов;
    }
    d
}

/// Оборот (в гранях) по текущему углу поворота: сколько шагов от начала.
pub fn оборот(поворот: f64, граней: u32) -> i64 {
    let шаг = std::f64::consts::TAU / граней.max(3) as f64;
    (-поворот / шаг).round() as i64
}

/// Угол в (−π, π].
fn нормировать(a: f32) -> f32 {
    let tau = std::f32::consts::TAU;
    let mut a = a % tau;
    if a > std::f32::consts::PI {
        a -= tau;
    }
    if a <= -std::f32::consts::PI {
        a += tau;
    }
    a
}

