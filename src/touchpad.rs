//! Где именно лежат пальцы на тачпаде — и автодовод курсора по его краям.
//!
//! **Зачем понадобился отдельный путь к железу.** libinput сырых координат
//! тачпада не отдаёт вообще: он их СЪЕДАЕТ, превращая в относительное движение
//! указателя с ускорением. Для жестов этого хватает, а для «палец доехал до
//! края накладки» — нет: край накладки libinput не считает событием. Поэтому
//! рядом с libinput открывается тот же самый `/dev/input/eventN` вторым
//! читателем и разбирается протокол multitouch напрямую. Оба чтения мирно
//! сосуществуют: evdev рассылает события всем открывшим, а `EVIOCGRAB` мы,
//! разумеется, не берём — иначе отняли бы тачпад у самого libinput.
//!
//! **Открываем САМИ, мимо libseat.** Через сеанс — нельзя: libseat отдаёт
//! устройство ровно одному читателю, и открытый нами тачпад libinput уже не
//! получал вовсе. Симптом (замер 01.09.2026, ноут): клавиатура работает,
//! курсор мёртв намертво, а в логе среди «New device» есть все события, кроме
//! события тачпада. Обычный `open` рядом с libinput кернел разрешает без
//! оговорок — очереди evdev у разных открытий independentные (а вот `dup`
//! очередь как раз ДЕЛИТ, и подсмотреть дескриптор libinput нельзя: мы
//! отбирали бы у него события).
//!
//! Цена — права: `/dev/input/event*` это `root:input`, и без членства в группе
//! `input` (или udev-правила с ACL) открыть их обычному пользователю нечем.
//! Нет доступа — автодовода просто нет, и ни на что другое это не влияет.
//!
//! ## Автодовод: что это и почему по краям тачпада, а не экрана
//!
//! Накладка кончается раньше, чем экран: ведя окно через весь холст, палец
//! упирается в край, и дальше движение просто не продолжается. Автодовод
//! замечает, что палец лежит В КРАЕВОЙ ЗОНЕ, и продолжает двигать курсор сам,
//! тем быстрее, чем глубже палец зашёл в зону. Работает это ВЕЗДЕ и само
//! собой: движение уходит обычным путём указателя, поэтому его одинаково
//! видят и перетаскивание окна, и выделение рамкой, и любой активный захват —
//! ни одна из этих подсистем про тачпад не знает и знать не должна.
//!
//! Край ЭКРАНА — отдельная и уже существующая история (`edge_pan` у соседей);
//! здесь именно накладка.

use std::os::unix::fs::OpenOptionsExt;
use std::os::unix::io::{AsRawFd, OwnedFd};
use std::path::{Path, PathBuf};

// ── Кусочек evdev, который нам нужен ─────────────────────────────────────────

const EV_SYN: u16 = 0x00;
const EV_KEY: u16 = 0x01;
const EV_ABS: u16 = 0x03;
const SYN_REPORT: u16 = 0x00;

const ABS_MT_SLOT: u16 = 0x2f;
const ABS_MT_POSITION_X: u16 = 0x35;
const ABS_MT_POSITION_Y: u16 = 0x36;
const ABS_MT_TRACKING_ID: u16 = 0x39;

const BTN_TOOL_FINGER: u16 = 0x145;
const BTN_TOOL_PEN: u16 = 0x140;

/// Сколько слотов держим. Пальцев на тачпаде физически не бывает больше;
/// слоты сверх этого молча игнорируем, а не растим вектор по числу из сети.
const СЛОТОВ: usize = 10;

#[repr(C)]
#[derive(Clone, Copy)]
struct СобытиеВвода {
    время: libc::timeval,
    тип: u16,
    код: u16,
    значение: i32,
}

#[repr(C)]
#[derive(Clone, Copy, Default)]
struct ОписаниеОси {
    значение: i32,
    минимум: i32,
    максимум: i32,
    fuzz: i32,
    flat: i32,
    разрешение: i32,
}

/// `_IOR('E', nr, size)` — тот же расчёт, что в `linux/ioctl.h`.
///
/// Собран руками, а не взят из крейта: ради трёх ioctl-ов тянуть зависимость
/// незачем, а формула не менялась с девяностых.
const fn ior(nr: u32, размер: u32) -> libc::c_ulong {
    // dir=_IOC_READ(2)<<30 | size<<16 | 'E'<<8 | nr
    ((2u32 << 30) | (размер << 16) | ((b'E' as u32) << 8) | nr) as libc::c_ulong
}

fn eviocgabs(ось: u16) -> libc::c_ulong {
    ior(0x40 + ось as u32, std::mem::size_of::<ОписаниеОси>() as u32)
}

fn eviocgbit(тип: u16, длина: u32) -> libc::c_ulong {
    ior(0x20 + тип as u32, длина)
}

fn бит(биты: &[u8], н: u16) -> bool {
    let н = н as usize;
    биты.get(н / 8).is_some_and(|б| б & (1 << (н % 8)) != 0)
}

// ── Состояние ────────────────────────────────────────────────────────────────

/// Палец на накладке, координаты нормированы в 0..1: слева направо и сверху
/// вниз. Нормировка здесь не украшение — тачпады отдают сырые диапазоны вроде
/// 0..1300 на 0..700, и любое «до края осталось N» без неё зависело бы от
/// модели железа.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Палец {
    pub x: f64,
    pub y: f64,
}

/// Один тачпад.
pub struct Тачпад {
    pub путь: PathBuf,
    фд: OwnedFd,
    диапазон_x: (i32, i32),
    диапазон_y: (i32, i32),
    /// Сырые координаты по слотам; `None` — слот пуст.
    слоты: [Option<(i32, i32)>; СЛОТОВ],
    активный: usize,
    /// Снимок после `SYN_REPORT` — то, что читают снаружи.
    pub пальцы: Vec<Палец>,
}

impl Тачпад {
    /// Открыть устройство и убедиться, что это действительно тачпад.
    ///
    /// `Err(фд)` — не тачпад либо не открылось; и то и другое нормально: по
    /// `/dev/input` лежат десятки устройств, и перебирать их — обычный способ
    /// найти нужное. Дескриптор при отказе ВОЗВРАЩАЕТСЯ вызывающему: его
    /// обязан вернуть сеансу `Session::close`, а не закрыть молча (почему —
    /// см. [`найти`]).
    fn открыть(путь: &Path, фд: OwnedFd) -> Result<Self, OwnedFd> {
        let raw = фд.as_raw_fd();

        // Тачпад = есть multitouch-координаты И есть «палец» как инструмент.
        // Второе отсекает тачскрины: у них те же оси, но инструмент — касание,
        // а не палец накладки. Планшеты отсекаются по перу.
        let mut оси = [0u8; 128];
        let mut кнопки = [0u8; 128];
        unsafe {
            if libc::ioctl(raw, eviocgbit(EV_ABS, оси.len() as u32), оси.as_mut_ptr()) < 0 {
                return Err(фд);
            }
            if libc::ioctl(raw, eviocgbit(EV_KEY, кнопки.len() as u32), кнопки.as_mut_ptr()) < 0 {
                return Err(фд);
            }
        }
        if !бит(&оси, ABS_MT_POSITION_X) || !бит(&оси, ABS_MT_POSITION_Y) {
            return Err(фд);
        }
        if !бит(&кнопки, BTN_TOOL_FINGER) || бит(&кнопки, BTN_TOOL_PEN) {
            return Err(фд);
        }

        let диапазон = |ось: u16| -> Option<(i32, i32)> {
            let mut описание = ОписаниеОси::default();
            let ok = unsafe {
                libc::ioctl(raw, eviocgabs(ось), &mut описание as *mut ОписаниеОси) >= 0
            };
            // Вырожденный диапазон (минимум = максимум) сделал бы деление на
            // ноль в нормировке — такое устройство нам не подходит.
            if ok && описание.максимум > описание.минимум {
                Some((описание.минимум, описание.максимум))
            } else {
                None
            }
        };
        let (Some(диапазон_x), Some(диапазон_y)) =
            (диапазон(ABS_MT_POSITION_X), диапазон(ABS_MT_POSITION_Y))
        else {
            return Err(фд);
        };

        tracing::info!(
            "plx/touchpad: {} — touchpad, X {}..{}, Y {}..{}",
            путь.display(), диапазон_x.0, диапазон_x.1, диапазон_y.0, диапазон_y.1,
        );
        Ok(Self {
            путь: путь.to_path_buf(),
            фд,
            диапазон_x,
            диапазон_y,
            слоты: [None; СЛОТОВ],
            активный: 0,
            пальцы: Vec::new(),
        })
    }

    /// Прочитать всё, что накопилось. `true` — снимок пальцев обновился.
    pub fn прочитать(&mut self) -> bool {
        let mut обновилось = false;
        let размер = std::mem::size_of::<СобытиеВвода>();
        let mut буфер = [0u8; 24 * 64];
        loop {
            let прочитано = unsafe {
                libc::read(
                    self.фд.as_raw_fd(),
                    буфер.as_mut_ptr() as *mut libc::c_void,
                    буфер.len(),
                )
            };
            if прочитано <= 0 {
                break;
            }
            let прочитано = прочитано as usize;
            for кусок in буфер[..прочитано].chunks_exact(размер) {
                // Выравнивание у `input_event` — как у `timeval`, то есть
                // 8 байт; читаем через `read_unaligned`, чтобы не зависеть от
                // того, где именно легло начало буфера.
                let событие: СобытиеВвода =
                    unsafe { std::ptr::read_unaligned(кусок.as_ptr() as *const СобытиеВвода) };
                обновилось |= self.событие(событие);
            }
            if прочитано < буфер.len() {
                break;
            }
        }
        обновилось
    }

    fn событие(&mut self, с: СобытиеВвода) -> bool {
        match (с.тип, с.код) {
            (EV_ABS, ABS_MT_SLOT) => {
                self.активный = (с.значение.max(0) as usize).min(СЛОТОВ - 1);
            }
            (EV_ABS, ABS_MT_TRACKING_ID) => {
                // −1 = палец убран. Именно так evdev сообщает об отпускании:
                // отдельного «отпустил» в протоколе нет.
                if с.значение < 0 {
                    self.слоты[self.активный] = None;
                } else if self.слоты[self.активный].is_none() {
                    self.слоты[self.активный] = Some((
                        (self.диапазон_x.0 + self.диапазон_x.1) / 2,
                        (self.диапазон_y.0 + self.диапазон_y.1) / 2,
                    ));
                }
            }
            (EV_ABS, ABS_MT_POSITION_X) => {
                if let Some(слот) = self.слоты[self.активный].as_mut() {
                    слот.0 = с.значение;
                }
            }
            (EV_ABS, ABS_MT_POSITION_Y) => {
                if let Some(слот) = self.слоты[self.активный].as_mut() {
                    слот.1 = с.значение;
                }
            }
            (EV_SYN, SYN_REPORT) => {
                // Снимок собираем только на SYN_REPORT: до него набор событий —
                // это половина картины, и палец мог бы «съездить» по одной оси.
                self.пальцы.clear();
                let (x0, x1) = self.диапазон_x;
                let (y0, y1) = self.диапазон_y;
                for слот in self.слоты.iter().flatten() {
                    self.пальцы.push(Палец {
                        x: ((слот.0 - x0) as f64 / (x1 - x0) as f64).clamp(0.0, 1.0),
                        y: ((слот.1 - y0) as f64 / (y1 - y0) as f64).clamp(0.0, 1.0),
                    });
                }
                return true;
            }
            _ => {}
        }
        false
    }
}

/// Найти и открыть все тачпады.
///
/// Перебор `/dev/input/event*` — не эвристика от бедности: udev-имена
/// (`by-path`, `by-id`) у тачпадов разных ноутбуков не унифицированы, а
/// проверка по возможностям устройства однозначна и не зависит от вендора.
pub fn найти() -> Vec<Тачпад> {
    let mut найденные = Vec::new();
    let mut запретов = 0usize;
    let Ok(каталог) = std::fs::read_dir("/dev/input") else {
        tracing::warn!("plx/touchpad: /dev/input is not readable — no edge assist");
        return найденные;
    };
    for запись in каталог.flatten() {
        let путь = запись.path();
        let Some(имя) = путь.file_name().and_then(|и| и.to_str()) else { continue };
        if !имя.starts_with("event") {
            continue;
        }
        // O_NONBLOCK обязателен: читаем мы из главного цикла, и блокирующий
        // read на устройстве, где сейчас нет пальцев, остановил бы компоновщик.
        let фд = match std::fs::OpenOptions::new()
            .read(true)
            .custom_flags(libc::O_NONBLOCK)
            .open(&путь)
        {
            Ok(файл) => OwnedFd::from(файл),
            Err(e) => {
                if e.kind() == std::io::ErrorKind::PermissionDenied { запретов += 1; }
                continue;
            }
        };
        match Тачпад::открыть(&путь, фд) {
            Ok(т) => найденные.push(т),
            // ЧУЖОЙ дескриптор ОБЯЗАН уйти обратно в сеанс.
            //
            // libseat::open_device кладёт устройство в карту сеанса ПО НОМЕРУ
            // дескриптора и отдаёт наружу OwnedFd с тем же номером. Уронить
            // такой OwnedFd — значит закрыть номер, оставив запись в карте:
            // номер тут же переиспользует следующий open, а это уже клавиатура
            // и мышь, которые сразу за нами открывает libinput. Дальше сеанс
            // работает с чужими устройствами по совпавшему номеру — и весь
            // ввод в сеансе умирает целиком (замер 01.09.2026 на ноуте: обои
            // играют, панель на месте, курсор не двигается, клавиши мертвы).
            //
            // Здесь перебирается ВЕСЬ /dev/input — десятки устройств, из
            // которых тачпад один, — так что промахов ровно столько, сколько
            // в системе устройств ввода.
            // Не тачпад — просто закрываем: это наш собственный дескриптор,
            // сеанс о нём ничего не знает и возвращать его некому.
            Err(_) => {}
        }
    }
    if найденные.is_empty() {
        if запретов > 0 {
            tracing::warn!(
                "plx/touchpad: no access to /dev/input ({} devices) — there will \
                 be no edge motion. Fix it by adding the user to the input group.",
                запретов,
            );
        } else {
            tracing::info!("plx/touchpad: no touchpads found");
        }
    }
    найденные
}

