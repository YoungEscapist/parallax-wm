/// Настройки автодовода. Все — из `config.lua`.
#[derive(Clone, Copy, Debug)]
pub struct Автодовод {
    pub включён: bool,
    /// Доля накладки от края, считающаяся краевой зоной (0.08 = 8 %).
    pub зона: f64,
    /// Пикселей в секунду на самом краю.
    pub скорость: f64,
    /// Доводить ТОЛЬКО когда что-то тащат (зажата кнопка, идёт захват).
    ///
    /// По умолчанию выключено — Ярик просил «чтобы работал везде». Ручка
    /// нужна на случай, если это будет мешать: палец, просто лежащий у края
    /// накладки, при «везде» уводит курсор сам по себе, и человек, привыкший
    /// класть большой палец на кромку, увидит ровно это.
    pub только_при_тяге: bool,
}

impl Default for Автодовод {
    fn default() -> Self {
        // Зона 8 % — примерно ширина пальца на типовой накладке: меньше не
        // нащупать, больше начинает срабатывать посреди обычного движения.
        // Скорость 900 px/с — чуть быстрее, чем ведут руку, но не рывком.
        Self { включён: true, зона: 0.08, скорость: 900.0, только_при_тяге: false }
    }
}

/// Куда и насколько быстро довести курсор при таком положении пальцев.
///
/// Возвращает пиксели в секунду по каждой оси. Ноль — ни один палец не в
/// краевой зоне.
///
/// **Берётся САМЫЙ глубокий палец по каждой оси, а не первый и не средний.**
/// Пальцев на накладке может быть несколько (жест, «тап-и-тащи»), и решает
/// тот, кто действительно упёрся в край: усреднение размазало бы упор в ноль,
/// а первый попавшийся зависел бы от порядка слотов, то есть от того, каким
/// пальцем человек начал.
pub fn довод(пальцы: &[Палец], н: &Автодовод) -> (f64, f64) {
    if !н.включён || пальцы.is_empty() || н.зона <= 0.0 {
        return (0.0, 0.0);
    }
    let мимо = |к: f64| -> f64 {
        // Глубина захода в зону, 0..1. Слева — отрицательная, справа —
        // положительная, поэтому знак сразу задаёт направление.
        if к < н.зона {
            -(н.зона - к) / н.зона
        } else if к > 1.0 - н.зона {
            (к - (1.0 - н.зона)) / н.зона
        } else {
            0.0
        }
    };
    let mut dx = 0.0f64;
    let mut dy = 0.0f64;
    for п in пальцы {
        let край_x = мимо(п.x);
        let край_y = мимо(п.y);
        if край_x.abs() > dx.abs() {
            dx = край_x;
        }
        if край_y.abs() > dy.abs() {
            dy = край_y;
        }
    }
    // Квадрат глубины, а не сама глубина: у самой кромки зоны довод должен
    // быть еле заметен, иначе он дёргает курсор при обычном движении, — а у
    // самого края накладки быстрым.
    (dx * dx.abs() * н.скорость, dy * dy.abs() * н.скорость)
}

