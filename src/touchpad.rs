use crate::Parallax;

impl Parallax {
    /// Идёт ли автодовод прямо сейчас.
    ///
    /// Входит в `anim_busy`, и это обязательно: палец, ЛЕЖАЩИЙ у края, не
    /// порождает ни одного события — ни libinput, ни evdev. Держи мы тик
    /// редким, курсор полз бы рывками по пять раз в секунду, а на неподвижном
    /// экране не полз бы вовсе.
    pub fn автодовод_идёт(&self) -> bool {
        self.автодовод_был.is_some()
    }

    /// Тащат ли что-нибудь прямо сейчас.
    ///
    /// Захват указателя (`is_grabbed`) покрывает всё разом: перетаскивание
    /// окна, тягу за край, выделение рамкой и любой клиентский drag — все они
    /// в smithay проходят через один и тот же механизм захвата. Отдельно
    /// смотрим жест тачпада: он ведёт окно, не занимая указатель.
    fn что_то_тащат(&self) -> bool {
        let захват = self
            .seat
            .get_pointer()
            .is_some_and(|p| p.is_grabbed());
        захват
            || self.gesture_move_window.is_some()
            || self.gesture_resize_window.is_some()
            || self.touchpad_select_start.is_some()
            || self.жест.is_some()
    }

    /// Шаг автодовода. Зовётся из `anim::tick` — единственного места, которое
    /// тикает и на неподвижном экране.
    pub fn автодовод_шаг(&mut self) {
        if self.тачпады.is_empty() {
            return;
        }
        for т in self.тачпады.iter_mut() {
            т.прочитать();
        }
        let настройки = self.lua_config.автодовод;
        if настройки.только_при_тяге && !self.что_то_тащат() {
            self.автодовод_был = None;
            return;
        }
        let mut пальцы: Vec<Палец> = Vec::new();
        for т in &self.тачпады {
            пальцы.extend_from_slice(&т.пальцы);
        }
        let (vx, vy) = довод(&пальцы, &настройки);
        if vx == 0.0 && vy == 0.0 {
            self.автодовод_был = None;
            return;
        }
        let теперь = std::time::Instant::now();
        let Some(было) = self.автодовод_был else {
            // Первый кадр в зоне — только засекаем время. Двигать не от чего:
            // без прошлой отметки dt пришлось бы выдумывать, а выдуманный
            // первый шаг — это заметный рывок в самом начале.
            self.автодовод_был = Some(теперь);
            return;
        };
        // Потолок шага: если тик проспал (тяжёлый кадр, VT-переключение),
        // курсор не должен телепортироваться через полэкрана.
        let dt = (теперь - было).as_secs_f64().min(0.05);
        self.автодовод_был = Some(теперь);

        // Скорость задана в ЭКРАННЫХ пикселях, а `pointer_location` живёт в
        // холсте — делим на зум, иначе на отдалённой камере довод полз бы, а
        // на приближённой стрелял.
        let zoom = self.viewport.zoom.max(0.01);
        let цель = smithay::utils::Point::from((
            self.pointer_location.x + vx * dt / zoom,
            self.pointer_location.y + vy * dt / zoom,
        ));
        // Через `warp_pointer`, а не записью в `pointer_location`: он рассылает
        // motion, и поэтому довод одинаково видят перетаскивание окна,
        // выделение рамкой и любой активный захват. Ради этого «работает
        // везде» и не понадобилось ни строчки в самих подсистемах.
        self.warp_pointer(цель);
        self.request_redraw();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn настройки() -> Автодовод {
        Автодовод { включён: true, зона: 0.1, скорость: 1000.0, только_при_тяге: false }
    }

    #[test]
    fn середина_накладки_не_доводит() {
        let (dx, dy) = довод(&[Палец { x: 0.5, y: 0.5 }], &настройки());
        assert_eq!((dx, dy), (0.0, 0.0));
    }

    #[test]
    fn край_доводит_в_свою_сторону() {
        let (dx, _) = довод(&[Палец { x: 0.0, y: 0.5 }], &настройки());
        assert!(dx < 0.0, "левый край обязан вести влево, а вышло {dx}");
        let (dx, _) = довод(&[Палец { x: 1.0, y: 0.5 }], &настройки());
        assert!(dx > 0.0, "правый край обязан вести вправо, а вышло {dx}");
        let (_, dy) = довод(&[Палец { x: 0.5, y: 0.0 }], &настройки());
        assert!(dy < 0.0, "верх обязан вести вверх, а вышло {dy}");
        let (_, dy) = довод(&[Палец { x: 0.5, y: 1.0 }], &настройки());
        assert!(dy > 0.0, "низ обязан вести вниз, а вышло {dy}");
    }

    #[test]
    fn глубже_значит_быстрее() {
        let край = довод(&[Палец { x: 0.0, y: 0.5 }], &настройки()).0.abs();
        let кромка = довод(&[Палец { x: 0.09, y: 0.5 }], &настройки()).0.abs();
        assert!(край > кромка, "у края должно быть быстрее: {край} против {кромка}");
        assert!(кромка > 0.0, "на кромке зоны довод обязан быть, пусть и слабый");
    }

    #[test]
    fn решает_самый_глубокий_палец() {
        // Один палец в середине, второй упёрся в левый край: решает второй.
        let пальцы = [Палец { x: 0.5, y: 0.5 }, Палец { x: 0.0, y: 0.5 }];
        let (dx, _) = довод(&пальцы, &настройки());
        let один = довод(&[Палец { x: 0.0, y: 0.5 }], &настройки()).0;
        assert_eq!(dx, один, "средний палец не должен размазывать упор");
    }

    #[test]
    fn выключенный_молчит() {
        let н = Автодовод { включён: false, ..настройки() };
        assert_eq!(довод(&[Палец { x: 0.0, y: 0.0 }], &н), (0.0, 0.0));
    }

    #[test]
    fn без_пальцев_молчит() {
        assert_eq!(довод(&[], &настройки()), (0.0, 0.0));
    }
}
