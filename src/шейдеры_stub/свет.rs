//! Заглушка света на холсте для сборки без фичи `shaders` (plx-standard).
//!
//! Буфера заливки нет никогда, так что `build_light_element` в udev.rs выходит
//! первой же строкой, а окна не получают ни направления, ни силы. Тип держим
//! настоящий: он лежит полем в `Parallax`, и убирать его `#[cfg]`-ом значило бы
//! разносить условную компиляцию по состоянию композитора ради восьми байт.

use smithay::backend::renderer::element::memory::MemoryRenderBuffer;

use crate::обои::Палитра;

// Геометрия света — тот же файл, что и в полной сборке: вызывающему коду
// незачем считать место источника по-разному в двух сборках.
#[path = "../свет_math.rs"]
mod math;
pub use math::{Источник, на_прямоугольник, источник};

/// Сторона картинки заливки в текселях — та же, что в полной сборке: udev.rs
/// берёт её для `src` элемента и не обязан знать, какая из двух сборок идёт.
pub const СТОРОНА: i32 = 256;

#[derive(Debug, Default)]
pub struct Свет;

impl Свет {
    pub fn new() -> Self {
        Self
    }

    /// Всегда `None`: в этой сборке света не бывает.
    pub fn буфер(&mut self, _палитра: Option<Палитра>, _сила: f32) -> Option<&MemoryRenderBuffer> {
        None
    }
}

/// Та же формула, что в полной сборке (см. `src/свет.rs`).
pub fn гашение(_п: &Палитра) -> f32 {
    0.0
}
