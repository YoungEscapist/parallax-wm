//! Заглушка палитры обоев для сборки без фичи `shaders` (plx-standard).
//!
//! ТИП здесь настоящий, а не пустышка: `Палитра` ходит по сигнатурам
//! (`rounded::Свечение::для_окна`, поля `Parallax`), и её исчезновение
//! потребовало бы `#[cfg]` в десятке мест, ни одно из которых к шейдерам
//! отношения не имеет. Математика тоже настоящая — по той же причине, по
//! которой vr_stub подключает `math.rs`: одинаковое поведение в обеих сборках
//! дешевле, чем два расходящихся ответа на один вопрос.
//!
//! Пустое ровно одно — [`Палитра::перечесть`]. Она всегда `None`, и это
//! ЕДИНСТВЕННАЯ точка, через которую цвет обоев попадает в кадр: нет палитры —
//! нет ни свечения окон, ни солнца на холсте, и ни один шейдер не заводится.
//! Файл `~/.cache/plx-wall/palette.json` в минимальной сборке не читается
//! вовсе — ни одного stat на тик анимаций.

use std::time::SystemTime;

/// Цвета обоев, нужные компоновщику. См. `src/обои.rs`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Палитра {
    /// Самый заметный цвет обоев — им и светим.
    pub акцент: [f32; 3],
    /// Фон: самый частый тёмный цвет.
    pub фон: [f32; 3],
}

impl Палитра {
    /// Насколько светлы обои, 0…1 (Rec. 601). Та же формула, что в полной
    /// сборке: на ней стоят тесты `rounded.rs`, общие для обеих.
    pub fn светлота(&self) -> f32 {
        0.299 * self.фон[0] + 0.587 * self.фон[1] + 0.114 * self.фон[2]
    }

    /// Всегда `None`: в этой сборке цвет обоев не читается.
    pub fn перечесть(_когда: &mut Option<SystemTime>) -> Option<Палитра> {
        None
    }
}
