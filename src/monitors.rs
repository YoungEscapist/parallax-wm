//! Мониторы: у каждого выхода свой вид на холст и свои рабочие столы.
//!
//! **Как это было.** parallax писался под один монитор, и это было не допущением, а
//! устройством: `space.outputs().next()` (первый выход) стоял в полутора
//! десятках мест, `Parallax::layer_output` был ОДИН на весь компоновщик, а камера —
//! одна на всю программу. Второй коннектор поднимался (DRM-часть умеет сколько
//! угодно поверхностей, см. `udev::scan_connectors`), но:
//!
//! * `state.layer_output` затирался ВТОРЫМ коннектором, и обои с панелью
//!   пропадали на ОБОИХ мониторах — слои остались в карте первого выхода, а
//!   спрашивали их у второго. В логе это «на выходе "BOE105HDR-1-layers" нет
//!   слоя Background (всего слоёв 0)»;
//! * камера была одна, поэтому второй монитор показывал ТО ЖЕ место холста,
//!   что и первый, — зеркало, а не второй стол;
//! * курсор зажимался видимой частью холста ОДНОГО вида
//!   (`Parallax::set_pointer_canvas`) и на второй монитор не выходил вовсе.
//!
//! **Как стало.** Здесь живёт список [`Монитор`]ов. У каждого свой выход, своя
//! карта слоёв, свой [`Viewport`] (камера + зум + теги) и свой УГОЛ ХОЛСТА —
//! `дом`. Последнее — ключ ко всему: в parallax все рабочие столы собираются в
//! одном прямоугольнике холста (`tiling::screen_area`), теги лишь подменяют в
//! нём окна. Двум мониторам одного прямоугольника мало, поэтому каждый получает
//! свой, отнесённый по X на заведомо недостижимое расстояние
//! ([`ШАГ_ДОМА`]). Дальше всё работает само: отсечение окон в
//! `udev::собрать_элементы` идёт по видимой части холста, и монитор физически
//! не может нарисовать чужие окна.
//!
//! **Логика как в hyprland.** Стол принадлежит монитору
//! (`Parallax::tag_monitor`): переход на стол, живущий на другом мониторе,
//! переводит фокус туда, а не тащит стол к себе. Фокус идёт за мышью — курсор,
//! переехавший на соседний монитор, делает его активным. Раскладка мониторов
//! (`monitor{ x =, y = }`) задаёт, кто где стоит; без неё выходы выстраиваются
//! слева направо в порядке подключения.

use smithay::{
    output::Output,
    utils::{Logical, Point, Size},
};

use crate::state::Viewport;

/// Насколько разнесены «дома» соседних мониторов по холсту.
///
/// Это не расстояние на экране, а пропасть в координатах: пан рукой не должен
/// доводить с одного стола на другой случайно, а отсечение по видимой части
/// холста обязано разводить мониторы наверняка при любом зуме. При
/// минимальном зуме (0.05) в экран влезает 20 экранов холста — 1 000 000
/// оставляет запас в полсотни раз.
pub const ШАГ_ДОМА: i32 = 1_000_000;

/// Один физический выход со всем, что к нему привязано.
pub struct Монитор {
    /// wl_output, который видят клиенты.
    pub output: Output,
    /// Выход-призрак под layer-поверхности: масштаб всегда 1, глобала нет
    /// (см. `udev::add_surface`). У каждого монитора он СВОЙ — иначе обои и
    /// панель второго монитора ложились бы в карту первого.
    pub layer_output: Output,
    /// Имя коннектора из ядра: «DP-2», «HDMI-A-1». Стабильнее модели из EDID,
    /// по нему пишется `monitor{}` в config.lua и по нему же plx-wall помнит,
    /// какие обои на каком мониторе.
    pub коннектор: String,
    /// Логический размер экрана (режим, делённый на масштаб выхода).
    pub размер: Size<i32, Logical>,
    /// Где монитор стоит В РАСКЛАДКЕ относительно соседей — та самая пара
    /// `x`/`y` из `monitor{}`, ровно как в hyprland. По ней курсор понимает,
    /// на какой монитор он переезжает через край. К координатам ХОЛСТА
    /// отношения не имеет.
    pub раскладка: Point<i32, Logical>,
    /// Угол собственного прямоугольника холста: здесь монитор собирает свои
    /// рабочие столы (см. `ШАГ_ДОМА` и `tiling::screen_area`).
    pub дом: Point<i32, Logical>,
    /// Камера, зум и теги ЭТОГО монитора. У активного монитора живая копия
    /// лежит в `Parallax::viewport`; здесь она обновляется при уходе фокуса
    /// (см. `Parallax::сохранить_вид`).
    pub viewport: Viewport,
    /// Слайд обоев по столам ЭТОГО монитора (см. [`СлайдОбоев`]).
    pub обои: СлайдОбоев,
}

impl Монитор {
    /// Прямоугольник монитора в РАСКЛАДКЕ (для перехода курсора между
    /// мониторами).
    pub fn плитка(&self) -> smithay::utils::Rectangle<i32, Logical> {
        smithay::utils::Rectangle::new(self.раскладка, self.размер)
    }
}

/// Плавный переезд обоев при смене рабочего стола.
///
/// **Зачем.** Обои в parallax едут за камерой (`udev::wallpaper_placement`), а
/// камера при Super+N не двигается: все столы монитора собраны в ОДНОМ
/// прямоугольнике холста, теги лишь подменяют в нём окна. Отсюда жалоба Ярика
/// 26.08.2026 — «обои двигаются только если панить либо зумить». Расстояние
/// между столами приходится назначить (`udev::ОБОИ_ШАГ_СТОЛА`), а переход по
/// нему — проехать: мгновенный скачок картинки на полсотни пикселей читается
/// как рывок, а не как движение.
///
/// **Почему не общая машинерия анимаций.** `PosAnim`/`CameraAnim` из anim.rs
/// возят точки и требуют, чтобы кто-то каждый кадр звал `advance`. Здесь же
/// величина одна и читают её ДВА независимых места (кадр обоев и расчёт блюра
/// под панелью), причём второе — по `&Parallax`, без права что-либо двигать.
/// Поэтому фаза не хранится, а СЧИТАЕТСЯ от времени: два читателя в одном кадре
/// по построению получают одно и то же число.
#[derive(Clone, Copy, Debug)]
pub struct СлайдОбоев {
    откуда: f64,
    куда: f64,
    начат: std::time::Instant,
}

impl СлайдОбоев {
    pub fn новый(стол: f64) -> Self {
        Self { откуда: стол, куда: стол, начат: std::time::Instant::now() }
    }

    /// Где обои сейчас — в «столах», дробное во время переезда.
    pub fn фаза(&self, сейчас: std::time::Instant) -> f64 {
        let всего = crate::anim::дуг::слайд_стола().as_secs_f64();
        let прошло = сейчас.saturating_duration_since(self.начат).as_secs_f64();
        if всего <= 0.0 || прошло >= всего {
            return self.куда;
        }
        let t = crate::anim::ease_calm(прошло / всего);
        crate::anim::lerp(self.откуда, self.куда, t)
    }

    /// Ехать к новому столу. Отсчёт — от ТЕКУЩЕЙ фазы, а не от прежней цели:
    /// перелистывание столов подряд не должно дёргать обои назад.
    pub fn вести(&mut self, куда: f64, сейчас: std::time::Instant) {
        if (self.куда - куда).abs() < 1e-9 {
            return;
        }
        self.откуда = self.фаза(сейчас);
        self.куда = куда;
        self.начат = сейчас;
    }

    /// Идёт ли переезд прямо сейчас — по нему кадр решает, звать ли себя ещё раз.
    pub fn идёт(&self, сейчас: std::time::Instant) -> bool {
        (self.фаза(сейчас) - self.куда).abs() > 1e-4
    }
}

impl Default for СлайдОбоев {
    fn default() -> Self {
        Self::новый(0.0)
    }
}

/// Номер стола для слайда обоев: младший бит маски тегов.
///
/// Маска бывает и составной (показаны несколько столов разом) — берём младший
/// занятый бит: у обоев должно быть одно определённое место, а «показать все»
/// в parallax всегда включает первый стол.
pub fn стол_обоев(маска: u32) -> f64 {
    if маска == 0 {
        return 0.0;
    }
    маска.trailing_zeros() as f64
}

/// Что вернуть на место после отрисовки чужого монитора
/// (см. `Parallax::войти_в_монитор`).
pub struct ВидНаВремя {
    viewport: Viewport,
    layer_output: Option<Output>,
    активный: usize,
}

/// Куда смотрит край экрана.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Сторона {
    Слева,
    Справа,
    Сверху,
    Снизу,
}

impl crate::state::Parallax {
    /// Активный монитор — тот, на котором курсор и клавиатурный фокус.
    pub fn монитор(&self) -> Option<&Монитор> {
        self.мониторы.get(self.активный)
    }

    /// wl_output активного монитора. Пока реестр пуст (winit/headless до
    /// первого выхода) — первый выход из space, как было до мониторов.
    pub fn активный_выход(&self) -> Option<Output> {
        self.монитор().map(|m| m.output.clone())
            .or_else(|| self.space.outputs().next().cloned())
    }

    /// Стоит ли стрелка на том мониторе, чей кадр сейчас собирается.
    ///
    /// Пока реестр пуст (winit/headless без мониторов) — да: там выход один.
    pub fn курсор_здесь(&self) -> bool {
        self.мониторы.is_empty() || self.активный == self.курсор_монитор
    }

    /// Логический размер активного монитора.
    pub fn монитор_размер(&self) -> Size<i32, Logical> {
        self.монитор().map(|m| m.размер).unwrap_or_else(|| (1920, 1080).into())
    }

    /// Угол холста активного монитора — начало его прямоугольника столов.
    pub fn монитор_дом(&self) -> Point<i32, Logical> {
        self.монитор().map(|m| m.дом).unwrap_or_else(|| (0, 0).into())
    }

    /// Начать появление рабочего места (см. `anim::Вход`).
    ///
    /// Зовётся из бэкенда ровно один раз — когда поднялся ПЕРВЫЙ монитор, то
    /// есть в момент, когда экрану впервые есть что показать. Раньше нельзя
    /// (кадра ещё нет, и вход прошёл бы в темноте до появления картинки),
    /// позже незачем.
    pub fn начать_вход(&mut self) {
        if !self.lua_config.intro {
            return;
        }
        self.вход = Some(crate::anim::Вход::новый());
        // Панель приезжает сверху вместе с холстом: цель `bar_hide` и так 0,
        // достаточно отправить её в путь из убранного положения (ведёт
        // `anim::tick` своей экспонентой).
        self.bar_hide = 1.0;
        // Начальный зум ставим здесь, а не первым тиком: между появлением
        // монитора и тиком успевает пройти кадр, и он показал бы уже готовый
        // кадр — вход начинался бы с рывка обратно.
        let зум = crate::anim::ВХОД_ЗУМ;
        let размер = self.монитор_размер();
        self.viewport.zoom = зум;
        self.viewport.cam_x += размер.w as f64 / 2.0 * (1.0 - 1.0 / зум);
        self.viewport.cam_y += размер.h as f64 / 2.0 * (1.0 - 1.0 / зум);
    }

    /// Достижимо ли место на холсте с чьего-нибудь экрана.
    ///
    /// Холст бесконечен, и точка «−1025, −1552» — законная позиция окна, пока
    /// камера стоит рядом. Но камера при запуске стоит В ДОМЕ монитора, и окно,
    /// положенное туда по памяти прошлого сеанса, для человека просто исчезает
    /// (жалоба 03.09.2026 «первое окно уезжает в левый верхний угол»). Отсюда
    /// понятие обитаемой зоны: прямоугольник столов монитора, раздутый на экран
    /// в каждую сторону — то есть окно видно целиком или хотя бы краем после
    /// небольшого пана.
    ///
    /// Пока реестр мониторов пуст (winit/headless до первого выхода) считаем
    /// обитаемым всё: судить не по чему, а отбрасывать вслепую хуже.
    pub fn место_обитаемо(&self, точка: Point<i32, Logical>) -> bool {
        if self.мониторы.is_empty() {
            return true;
        }
        self.мониторы.iter().any(|m| {
            let зона = smithay::utils::Rectangle::new(
                Point::from((m.дом.x - m.размер.w, m.дом.y - m.размер.h)),
                Size::from((m.размер.w * 3, m.размер.h * 3)),
            );
            зона.contains(точка)
        })
    }

    /// Где обои АКТИВНОГО монитора стоят по столам — дробное во время переезда.
    ///
    /// «Активный» здесь значит «тот, чей кадр собирается»: на время отрисовки
    /// его подменяет [`войти_в_монитор`], поэтому каждый выход получает свой
    /// слайд, а не слайд того монитора, где сейчас мышь.
    pub fn обои_фаза(&self) -> f64 {
        match self.монитор() {
            Some(m) => m.обои.фаза(std::time::Instant::now()),
            None => стол_обоев(self.viewport.current_tags()),
        }
    }

    /// Едут ли обои прямо сейчас — по этому кадр решает, звать ли себя ещё раз.
    pub fn обои_едут(&self) -> bool {
        self.монитор()
            .is_some_and(|m| m.обои.идёт(std::time::Instant::now()))
    }

    /// Повести обои активного монитора к его нынешнему столу.
    ///
    /// Зовётся из `refresh_tags` — единственного места, через которое проходят
    /// ВСЕ смены тегов: Super+N, обзор, лента, «показать все». Поставить это в
    /// `view_tag` было бы неверно ровно настолько, насколько незаметно: тегами
    /// правят ещё четыре точки по коду.
    pub fn обновить_слайд_обоев(&mut self) {
        let стол = стол_обоев(self.viewport.current_tags());
        let сейчас = std::time::Instant::now();
        if let Some(m) = self.мониторы.get_mut(self.активный) {
            m.обои.вести(стол, сейчас);
        }
    }

    /// Индекс монитора по его выходу (по имени: `Output` не `PartialEq`
    /// по значению так, как нам нужно, а имена у выходов уникальны).
    pub fn монитор_по_выходу(&self, output: &Output) -> Option<usize> {
        let имя = output.name();
        self.мониторы.iter().position(|m| m.output.name() == имя)
    }

    /// Индекс монитора по имени коннектора либо по имени выхода.
    pub fn монитор_по_имени(&self, имя: &str) -> Option<usize> {
        self.мониторы.iter().position(|m| {
            m.коннектор == имя || m.output.name() == имя
        })
    }

    /// Выход-призрак под слои для ЭТОГО выхода. Для чужого/неизвестного —
    /// призрак активного монитора (так ведёт себя одномониторная сборка).
    pub fn слои_выход(&self, output: &Output) -> Output {
        self.монитор_по_выходу(output)
            .and_then(|i| self.мониторы.get(i))
            .map(|m| m.layer_output.clone())
            .or_else(|| self.layer_output.clone())
            .unwrap_or_else(|| output.clone())
    }

    /// Все карты слоёв, какие есть, — призраки мониторов плюс то, что успел
    /// поставить бэкенд без реестра (winit/headless).
    pub fn все_слои(&self) -> Vec<Output> {
        let mut v: Vec<Output> = self.мониторы.iter()
            .map(|m| m.layer_output.clone())
            .collect();
        if let Some(o) = self.layer_output.clone() {
            if !v.iter().any(|x| x.name() == o.name()) {
                v.push(o);
            }
        }
        v
    }

    /// В чьей карте слоёв лежит эта поверхность.
    ///
    /// Нужно везде, где слой надо найти ПО ЕГО ПОВЕРХНОСТИ (первый configure,
    /// повторный configure на смену размера, выдача клавиатуры): слой мог
    /// приехать на второй монитор, а спрашивали его всегда у активного —
    /// с двумя мониторами это значит «панель второго монитора не получает
    /// configure и стоит на первом кадре навсегда».
    pub fn слои_с_поверхностью(
        &self,
        surface: &smithay::reexports::wayland_server::protocol::wl_surface::WlSurface,
    ) -> Option<Output> {
        for o in self.все_слои() {
            let есть = {
                let map = smithay::desktop::layer_map_for_output(&o);
                map.layer_for_surface(surface, smithay::desktop::WindowSurfaceType::ALL)
                    .is_some()
            };
            if есть {
                return Some(o);
            }
        }
        None
    }

    /// Поверхность обоев — фоновый слой СВОЕГО монитора, с откатом на чужой.
    ///
    /// «Свой» — это слой активного монитора, а на время сборки кадра активным
    /// сделан рисуемый (см. [`войти_в_монитор`], он подменяет и `layer_output`).
    /// То есть каждый выход получает СВОЮ поверхность обоев, нужного ему
    /// размера, и `udev::build_wallpaper_backdrop` кладёт её от дома этого
    /// монитора — ровно в экран, без повторов.
    ///
    /// **Откат на чужой слой оставлен нарочно.** До 26.08.2026 plx-wall вешал
    /// поверхность только на ПЕРВЫЙ объявленный ему wl_output (`outputs.first()`
    /// по всему его коду), и второму монитору не доставалось ничего. Тогда
    /// плитка бралась размером с ЧУЖОЙ экран: на ультрашироком 2560×1080
    /// картинка шириной 1920 не сходилась с экраном и повторялась с видимым швом
    /// — это и была жалоба «обои дублируются». Теперь plx-wall держит фон на каждом
    /// выходе (см. `Фон` в его main.rs), но со СТАРЫМ его бинарём чужой слой
    /// по-прежнему лучше, чем чёрный экран, — поэтому запасная ветка живёт.
    ///
    /// Разные обои на разных мониторах отсюда всё ещё не получатся: plx-wall
    /// показывает один и тот же кадр на всех фонах, разводя их только
    /// прямоугольниками `wp_viewport`.
    pub fn фоновая_поверхность(
        &self,
    ) -> Option<smithay::reexports::wayland_server::protocol::wl_surface::WlSurface> {
        // Именно вложенная функция, а не замыкание: `layer_map_for_output`
        // отдаёт guard, и итератор по нему обязан кончиться раньше guard'а —
        // в теле замыкания-выражения он живёт дольше и borrowck это ловит.
        fn фон(
            o: &Output,
        ) -> Option<smithay::reexports::wayland_server::protocol::wl_surface::WlSurface> {
            use smithay::wayland::shell::wlr_layer::Layer;
            let map = smithay::desktop::layer_map_for_output(o);
            let найдено = map.layers()
                .find(|l| l.layer() == Layer::Background)
                .map(|l| l.wl_surface().clone());
            найдено
        }
        if let Some(o) = self.layer_output.clone() {
            if let Some(s) = фон(&o) {
                return Some(s);
            }
        }
        self.все_слои().iter().find_map(фон)
    }

    /// Монитор по wl_output, который назвал клиент (layer-shell: обои и панели
    /// просят конкретный выход).
    pub fn монитор_по_wl(
        &self,
        wl: &smithay::reexports::wayland_server::protocol::wl_output::WlOutput,
    ) -> Option<usize> {
        self.мониторы.iter().position(|m| m.output.owns(wl))
    }

    /// Сложить живой вид активного монитора обратно в его запись.
    ///
    /// `Parallax::viewport` — это ЖИВОЙ вид активного монитора, а не отдельная
    /// сущность: так все три сотни обращений к `self.viewport.*` по коду
    /// продолжают означать «то, на что человек сейчас смотрит», и их не
    /// пришлось переписывать. Плата — обязанность синхронизировать копию в
    /// двух точках: здесь (уходим с монитора) и в `загрузить_вид` (приходим).
    pub fn сохранить_вид(&mut self) {
        let вид = self.viewport;
        if let Some(m) = self.мониторы.get_mut(self.активный) {
            m.viewport = вид;
        }
    }

    /// Поднять вид монитора `i` в `Parallax::viewport` и сделать его активным.
    fn загрузить_вид(&mut self, i: usize) {
        if let Some(m) = self.мониторы.get(i) {
            self.viewport = m.viewport;
            // Тот же приём, что и с видом: `Parallax::layer_output` — призрак
            // слоёв АКТИВНОГО монитора. По нему идёт хит-тест панели и меню
            // (`layer_surface_under`), и он обязан ехать за фокусом.
            self.layer_output = Some(m.layer_output.clone());
            self.активный = i;
        }
    }

    /// Мгновенно довести до конца всё, что везёт камеру, на ТЕКУЩЕМ мониторе.
    ///
    /// **Зачем.** `camera_anim`, `zoom_anim`, `zoom_glide` и `momentum` — по
    /// ОДНОМУ полю на весь `Parallax`, а `anim::tick` пишет их результат в
    /// `Parallax::viewport`, то есть в вид АКТИВНОГО монитора. Пока монитор один,
    /// это и есть «камера»; на двух — источник движения не привязан ни к чему.
    /// Стоит активному смениться на середине перелёта (а он меняется от одного
    /// хода мыши через край — в живом логе это происходит по нескольку раз в
    /// минуту), и остаток анимации ложится на камеру УЖЕ ДРУГОГО экрана,
    /// уводя её в чужой дом. А дома мониторов — единственное, что разделяет
    /// столы: окна кладутся на холст по объединению видимых тегов, и в кадр
    /// попадает то, что накрыла камера. Две камеры в одном доме = **два
    /// монитора показывают одни и те же окна**, причём на любых своих столах.
    ///
    /// Лечится привязкой к моменту ухода: перелёт доигрывается здесь, до
    /// `сохранить_вид`, так что уходящий монитор получает свой законный
    /// конечный кадр, а новому достаётся его собственная камера.
    /// `ZoomAnim::target`/`ZoomGlide::target_frame` дают именно КОНЕЧНЫЙ кадр —
    /// оборвать на полпути значило бы оставить экран стоять криво.
    pub fn завершить_анимации_камеры(&mut self) {
        if let Some(a) = self.camera_anim.take() {
            self.viewport.cam_x = a.to.x;
            self.viewport.cam_y = a.to.y;
        }
        if let Some(a) = self.zoom_anim.take() {
            let (zoom, cam) = a.target();
            self.viewport.zoom = zoom;
            self.viewport.cam_x = cam.x;
            self.viewport.cam_y = cam.y;
        }
        if let Some(g) = self.zoom_glide.take() {
            let (zoom, cam) = g.target_frame();
            self.viewport.zoom = zoom;
            self.viewport.cam_x = cam.x;
            self.viewport.cam_y = cam.y;
        }
        // Инерция пана — тот же класс: её тик тоже прибавляет дельту к
        // `viewport.cam`, кто бы сейчас ни был активным.
        self.momentum.stop();
    }

    /// Сменить активный монитор: вид уходящего сохраняем, вид нового поднимаем.
    ///
    /// Возвращает `true`, если монитор действительно сменился.
    pub fn активировать_монитор(&mut self, i: usize) -> bool {
        if i >= self.мониторы.len() || i == self.активный {
            return false;
        }
        // СТРОГО ДО `сохранить_вид`: всё, что везёт камеру, обязано остаться на
        // уходящем мониторе. Подробности — в самом методе.
        self.завершить_анимации_камеры();
        self.сохранить_вид();
        let было = self.активный;
        self.загрузить_вид(i);
        self.курсор_монитор = i;
        // Раскладка (Tile/Float/Columns) — свойство СТОЛА, а стол теперь
        // свойство монитора: приезжая на монитор, поднимаем режим его текущего
        // стола, иначе тайловый стол на втором мониторе вёл бы себя как
        // плавающий, с которого мы ушли.
        let тег = self.viewport.current_tags();
        if let Some(&layout) = self.tag_layouts.get(&тег) {
            self.tile_config.layout = layout;
        }
        // Камера монитора могла остаться от прошлого визита — экран должен
        // показать именно её, а не то, что там нарисовано сейчас.
        //
        // `apply_camera_all`, а не `apply_camera`: последняя двигает ТОЛЬКО
        // активный выход, и привязка неактивных так и остаётся той, что была
        // выдана при подключении. На пути udev `apply_camera_all` не звалась
        // больше нигде (только при снятии монитора), поэтому разъехавшийся
        // выход было некому вернуть на свою камеру.
        self.apply_camera_all();
        tracing::info!(
            "plx/monitors: active monitor {} → {} ({})",
            было, i,
            self.мониторы.get(i).map(|m| m.коннектор.as_str()).unwrap_or("?"),
        );
        true
    }

    /// Убрать монитор из реестра: коннектор отключили.
    ///
    /// Окна с его столов НЕ трогаем — они остаются на своём куске холста и
    /// вернутся, как только монитор подключат обратно (дом выдаётся по
    /// свободному месту, а не по длине списка, — см. `свободный_дом`). Столы
    /// открепляем: иначе `монитор_стола` показывал бы на индекс, которого уже
    /// нет, и переход на такой стол молча никуда не вёл бы.
    ///
    /// Столы отключённого монитора переезжают на активный — так же ведёт себя
    /// hyprland, где воркспейсы исчезнувшего выхода собирает оставшийся.
    pub fn снять_монитор(&mut self, output: &Output) {
        let Some(i) = self.монитор_по_выходу(output) else { return };
        let имя = self.мониторы[i].коннектор.clone();
        // Живой вид уходящего монитора сначала складываем на место — иначе
        // потеряли бы его камеру, если снимают именно активный.
        self.сохранить_вид();
        self.мониторы.remove(i);
        if self.мониторы.is_empty() {
            self.активный = 0;
            self.layer_output = None;
            tracing::warn!("plx/monitors: the last monitor {} was removed", имя);
            return;
        }
        // Индексы правее сдвинулись — чиним привязку столов.
        let новый_хозяин = if i == 0 { 0 } else { i - 1 };
        let mut переехали: Vec<u32> = Vec::new();
        for (тег, м) in self.tag_monitor.iter_mut() {
            if *м == i {
                *м = новый_хозяин;
                переехали.push(*тег);
            } else if *м > i {
                *м -= 1;
            }
        }
        self.активный = if self.активный == i {
            новый_хозяин
        } else if self.активный > i {
            self.активный - 1
        } else {
            self.активный
        };
        let вид = self.мониторы[self.активный].viewport;
        self.viewport = вид;
        self.курсор_монитор = self.активный;
        self.layer_output = Some(self.мониторы[self.активный].layer_output.clone());
        self.apply_camera_all();
        self.refresh_tags();
        tracing::info!(
            "plx/monitors: {} removed (was {}), active {}, workspaces {:?} → monitor {}",
            имя, i, self.активный, переехали, новый_хозяин,
        );
    }

    /// Встать на точку зрения монитора `i` на время сборки кадра.
    ///
    /// **Зачем такой приём.** Камера, зум и теги живут в `Parallax::viewport`, и на
    /// него смотрят три сотни мест по коду — вся отрисовка, панель, миникарта,
    /// обзор, тайлинг. Переписывать их на «вид того монитора, который сейчас
    /// рисуется» значило бы протащить лишний аргумент через весь рендер. Вместо
    /// этого на время сборки кадра МЕНЯЕМ активный вид на вид рисуемого
    /// монитора, а потом возвращаем: код внутри как был написан под один
    /// монитор, так и остаётся, но выполняется столько раз, сколько выходов, и
    /// каждый раз со своими камерой, зумом и столом.
    ///
    /// Возвращает то, что надо отдать обратно в [`покинуть_монитор`]. Пара
    /// вызовов ОБЯЗАНА быть симметричной: между ними нельзя выходить из
    /// функции — иначе живой вид останется от чужого монитора.
    pub fn войти_в_монитор(&mut self, i: usize) -> Option<ВидНаВремя> {
        if i == self.активный || i >= self.мониторы.len() {
            return None;
        }
        let сохранён = ВидНаВремя {
            viewport: self.viewport,
            layer_output: self.layer_output.clone(),
            активный: self.активный,
        };
        // Живой вид активного складываем на место — иначе, вернувшись, мы
        // положим обратно копию, устаревшую на кадр.
        self.сохранить_вид();
        let m = &self.мониторы[i];
        self.viewport = m.viewport;
        self.layer_output = Some(m.layer_output.clone());
        self.активный = i;
        Some(сохранён)
    }

    /// Вернуть вид активного монитора после [`войти_в_монитор`].
    pub fn покинуть_монитор(&mut self, сохранён: Option<ВидНаВремя>) {
        let Some(с) = сохранён else { return };
        // Кадр мог подправить вид рисуемого монитора (доводка зума, пружины) —
        // сохраняем его, прежде чем вернуть свой.
        self.сохранить_вид();
        self.viewport = с.viewport;
        self.layer_output = с.layer_output;
        self.активный = с.активный;
    }

    /// Монитор, чей прямоугольник в раскладке содержит точку (экранные
    /// координаты раскладки, а не холст).
    pub fn монитор_в_точке(&self, p: Point<i32, Logical>) -> Option<usize> {
        self.мониторы.iter().position(|m| m.плитка().contains(p))
    }

    /// Сосед активного монитора с указанной стороны — то же правило, что и в
    /// hyprland: берём ближайший из тех, чьи прямоугольники ПЕРЕСЕКАЮТСЯ с
    /// нашим по другой оси, иначе монитор сверху забирал бы переход вправо.
    pub fn сосед(&self, откуда: usize, сторона: Сторона) -> Option<usize> {
        let свой = self.мониторы.get(откуда)?.плитка();
        let (свой_л, свой_п) = (свой.loc.x, свой.loc.x + свой.size.w);
        let (свой_в, свой_н) = (свой.loc.y, свой.loc.y + свой.size.h);
        self.мониторы.iter().enumerate()
            .filter(|(i, _)| *i != откуда)
            .filter_map(|(i, m)| {
                let r = m.плитка();
                let (л, п) = (r.loc.x, r.loc.x + r.size.w);
                let (в, н) = (r.loc.y, r.loc.y + r.size.h);
                // Расстояние по оси перехода; None — сосед не с той стороны.
                let d = match сторона {
                    Сторона::Справа if л >= свой_п => л - свой_п,
                    Сторона::Слева  if п <= свой_л => свой_л - п,
                    Сторона::Снизу  if в >= свой_н => в - свой_н,
                    Сторона::Сверху if н <= свой_в => свой_в - н,
                    _ => return None,
                };
                // Перекрытие по другой оси: без него «правее» оказывается и
                // монитор, стоящий правее-и-выше, до которого краем не дойти.
                let перекрытие = match сторона {
                    Сторона::Слева | Сторона::Справа => свой_н.min(н) - свой_в.max(в),
                    Сторона::Сверху | Сторона::Снизу => свой_п.min(п) - свой_л.max(л),
                };
                if перекрытие <= 0 { return None; }
                Some((i, d))
            })
            .min_by_key(|(_, d)| *d)
            .map(|(i, _)| i)
    }

    /// Перевести курсор через край на соседний монитор и отдать ему фокус.
    ///
    /// `доля` — где стрелка стояла по ДРУГОЙ оси, в долях экрана: выехал
    /// справа на трёх четвертях высоты — въехал слева на трёх четвертях
    /// высоты. Так это работает в hyprland, и так это единственно предсказуемо
    /// при разных размерах мониторов.
    ///
    /// Возвращает `false`, если с этой стороны никого нет — тогда курсор
    /// зажимается краем, как и раньше.
    pub fn перевести_курсор(&mut self, сторона: Сторона, доля: f64) -> bool {
        let донор = self.курсор_монитор;
        let Some(сосед) = self.сосед(self.курсор_монитор, сторона) else { return false };
        if !self.активировать_монитор(сосед) { return false; }
        // Встаём у ПРОТИВОПОЛОЖНОГО края нового монитора, на пиксель внутрь:
        // ровно на границе следующее же событие мыши снова считалось бы
        // выездом, и курсор прыгал бы между экранами.
        let vis = self.visible_canvas_size();
        let доля = доля.clamp(0.0, 1.0);
        const ВНУТРЬ: f64 = 1.0;
        let (sx, sy) = match сторона {
            Сторона::Справа => (ВНУТРЬ, доля * vis.h),
            Сторона::Слева  => (vis.w - ВНУТРЬ, доля * vis.h),
            Сторона::Снизу  => (доля * vis.w, ВНУТРЬ),
            Сторона::Сверху => (доля * vis.w, vis.h - ВНУТРЬ),
        };
        let pos = Point::from((self.viewport.cam_x + sx, self.viewport.cam_y + sy));
        self.warp_pointer(pos);
        // Через край тащат ОКНО — значит это перенос окна на соседний экран, а
        // не смена фокуса. Окно переводим на стол нового монитора прямо сейчас,
        // ещё под кнопкой: без тега нового стола `refresh_tags` сдул бы его с
        // холста на первом же обновлении, а с ним — на новом экране показалось
        // бы пустое место вместо окна на мыши.
        //
        // Позицию НЕ трогаем: её на каждом motion считает сам драг от
        // `start_data.location`, и та лежит в координатах покинутого монитора.
        // Курсор только что перепрыгнул на ШАГ_ДОМА вперёд, поэтому та же
        // дельта сама приводит окно в дом нового монитора — сдвинув позицию
        // ещё и здесь, мы уехали бы на миллион дважды.
        if let Some(окно) = self.dragged_window.clone() {
            let тег = self.viewport.current_tags();
            if self.перенести_окно_на_стол(&окно, тег, false) {
                // Стол-донор обязан сомкнуться СРАЗУ. `arrange` на отпускании
                // кнопки раскладывает монитор-приёмник (активный к тому
                // моменту), а покинутый так и остался бы с дырой на месте
                // уехавшего окна — на экране это половина пустого стола до
                // следующей операции с раскладкой.
                self.разложить_монитор(донор);
            }
            self.request_redraw();
            return true;
        }
        // Клавиатура идёт за мышью: на новом мониторе свой стол и своё окно в
        // фокусе. Без этого набор продолжал бы уходить в окно на покинутом
        // экране — то самое «печатаю не туда» из hyprland без focus-follows.
        self.refocus_visible();
        self.request_redraw();
        true
    }

    /// Разложить стол ЧУЖОГО монитора, не уходя с текущего.
    ///
    /// `arrange` работает по активному виду — камере, столу и экрану того
    /// монитора, на котором мы стоим (`tiling::screen_area`). Чтобы привести в
    /// порядок соседний экран, надо на время встать на его точку зрения — тем
    /// же приёмом, которым это делает отрисовка (см. [`войти_в_монитор`]).
    ///
    /// Раскладку берём ЕГО стола: режим — свойство стола (`tag_layouts`), и
    /// разложить тайловый стол соседа колонками своего значило бы пересобрать
    /// его чужой моделью.
    pub fn разложить_монитор(&mut self, i: usize) {
        if i == self.активный {
            self.arrange();
            return;
        }
        let вернуть = self.войти_в_монитор(i);
        let свой_layout = self.tile_config.layout;
        let тег = self.viewport.current_tags();
        if let Some(&layout) = self.tag_layouts.get(&тег) {
            self.tile_config.layout = layout;
        }
        self.arrange();
        self.tile_config.layout = свой_layout;
        self.покинуть_монитор(вернуть);
    }

    /// Дом того монитора, в чьём прямоугольнике холста лежит точка.
    ///
    /// Дома разнесены на [`ШАГ_ДОМА`] — заведомо дальше любого экрана, поэтому
    /// «чей это кусок холста» однозначно решается ближайшим домом. Нужно, чтобы
    /// узнать, ОТКУДА окно переезжает: тег стола-донора мог остаться от
    /// монитора, которого уже нет, а координаты окна всегда настоящие.
    pub fn дом_точки(&self, p: Point<i32, Logical>) -> Point<i32, Logical> {
        self.мониторы.iter()
            .map(|m| m.дом)
            .min_by_key(|дом| (дом.x as i64 - p.x as i64).abs() + (дом.y as i64 - p.y as i64).abs())
            .unwrap_or_else(|| (0, 0).into())
    }

    /// Номер монитора, в чьём прямоугольнике холста лежит точка.
    ///
    /// То же правило ближайшего дома, что и у [`дом_точки`], только результат —
    /// индекс. Нужно всему, что спрашивает «на каком экране это окно»: снимку
    /// экрана и демонстрации (кадр берётся с одного выхода, и надо знать,
    /// с какого именно).
    ///
    /// [`дом_точки`]: Self::дом_точки
    pub fn монитор_по_точке(&self, p: Point<i32, Logical>) -> Option<usize> {
        self.мониторы.iter()
            .enumerate()
            .min_by_key(|(_, m)| {
                (m.дом.x as i64 - p.x as i64).abs() + (m.дом.y as i64 - p.y as i64).abs()
            })
            .map(|(i, _)| i)
    }

    /// Перенести окно на стол `тег`, в том числе на ДРУГОЙ МОНИТОР.
    ///
    /// **Зачем отдельная операция.** Сменить окну тег недостаточно: столы
    /// принадлежат мониторам, а окна лежат на холсте от ДОМА своего монитора
    /// (`tiling::screen_area`), и дома разведены на [`ШАГ_ДОМА`]. Окно, которому
    /// просто переписали тег на чужой стол, остаётся стоять в доме прежнего
    /// монитора: на новом экране его не видно (до него миллион пикселей), а со
    /// старого оно пропало вместе с тегом. Замер 29.08.2026 на двухмониторном
    /// харнессе: `tag_window tag=2` дал `стол=2 монитор=2 слот=26,26` при том,
    /// что соседнее окно того же стола стоит в `1000026,26`, — ровно жалоба
    /// Ярика «содержимое столов смешивается».
    ///
    /// `двигать` — переставить ли окно в дом нового монитора здесь же. Так надо
    /// при переносе с клавиатуры (Win+Shift+N); при перетаскивании мышью
    /// позицию ведёт сам драг, и второй сдвиг увёл бы окно вдвое дальше (см.
    /// [`перевести_курсор`]).
    ///
    /// Из дерева стола-донора окно вынимаем сразу: `sync_dwindle_tree` вычистит
    /// его только при следующем `arrange` ТОГО стола, то есть когда на него
    /// вернутся, — а до тех пор на месте уехавшего окна оставалась бы дыра.
    ///
    /// Возвращает `true`, если окно сменило монитор.
    pub fn перенести_окно_на_стол(
        &mut self,
        окно: &smithay::desktop::Window,
        тег: u32,
        двигать: bool,
    ) -> bool {
        let Some((старый, позиция)) = self.tagged_windows.iter()
            .find(|tw| crate::dwindle::same_window(&tw.window, окно))
            .map(|tw| (tw.tags, tw.position))
        else {
            return false;
        };
        if старый == тег {
            return false;
        }
        // Дом-донор считаем ПО ПОЛОЖЕНИЮ окна, а не по монитору его стола:
        // стол мог быть ничей (окно с ещё не закреплённого стола) или
        // принадлежать снятому монитору, а координаты врать не умеют.
        let откуда = self.дом_точки(позиция);
        let куда = self.монитор_стола(тег)
            .and_then(|i| self.мониторы.get(i))
            .map(|m| m.дом)
            .unwrap_or_else(|| self.монитор_дом());
        let сдвиг = Point::from((куда.x - откуда.x, куда.y - откуда.y));

        if let Some(дерево) = self.dwindle_trees.get_mut(&старый) {
            дерево.remove(окно);
        }
        let mut новая = позиция;
        if let Some(tw) = self.tagged_windows.iter_mut()
            .find(|tw| crate::dwindle::same_window(&tw.window, окно))
        {
            tw.tags = тег;
            if двигать && (сдвиг.x != 0 || сдвиг.y != 0) {
                tw.position += сдвиг;
                tw.float_position += сдвиг;
                новая = tw.position;
            }
        }
        if двигать && (сдвиг.x != 0 || сдвиг.y != 0) {
            // В `space` окно переставляем сразу: `refresh_tags` кладёт окна по
            // `tw.position`, но между этими двумя точками успевает пройти кадр,
            // и окно мигнуло бы на старом мониторе.
            self.space.map_element(окно.clone(), новая, false);
        }
        tracing::info!(
            "plx/monitors: window {:#b} → workspace {:#b}, home {:?} → {:?}",
            старый, тег, откуда, куда,
        );
        сдвиг.x != 0 || сдвиг.y != 0
    }

    /// Свободный «дом» для нового монитора: первый шаг сетки, который ещё
    /// никем не занят. Считается по занятым, а не по длине списка, — иначе
    /// монитор, отключённый и подключённый заново, заезжал бы на чужие окна.
    pub fn свободный_дом(&self) -> Point<i32, Logical> {
        let mut n = 0;
        loop {
            let дом = Point::from((n * ШАГ_ДОМА, 0));
            if !self.мониторы.iter().any(|m| m.дом == дом) {
                return дом;
            }
            n += 1;
        }
    }

    /// Позиция нового монитора в раскладке, если её не задали в `monitor{}`:
    /// справа от самого правого, как `auto` в hyprland.
    pub fn авто_раскладка(&self) -> Point<i32, Logical> {
        let x = self.мониторы.iter()
            .map(|m| m.раскладка.x + m.размер.w)
            .max()
            .unwrap_or(0);
        Point::from((x, 0))
    }

    /// Монитор, которому принадлежит стол `tag`. `None` — стол ещё ничей.
    pub fn монитор_стола(&self, tag: u32) -> Option<usize> {
        self.tag_monitor.get(&tag).copied()
            .filter(|i| *i < self.мониторы.len())
    }

    /// Закрепить стол за монитором. Зовётся при первом входе на стол и при
    /// переносе стола на другой монитор.
    pub fn закрепить_стол(&mut self, tag: u32, монитор: usize) {
        self.tag_monitor.insert(tag, монитор);
    }

    /// Стол для нового монитора: `желаемый` (номер 1..=9 из `monitor{ tag }`),
    /// если он ещё ничей, иначе первый свободный. Всё занято — берём первый:
    /// два монитора на одном столе выглядят как зеркало, но это лучше, чем
    /// отказ поднять выход.
    pub fn свободный_тег(&self, желаемый: u32) -> u32 {
        let свободен = |n: u32| {
            let маска = 1u32 << (n - 1);
            self.монитор_стола(маска).is_none()
        };
        if (1..=9).contains(&желаемый) && свободен(желаемый) {
            return 1u32 << (желаемый - 1);
        }
        (1..=9).find(|n| свободен(*n)).map(|n| 1u32 << (n - 1)).unwrap_or(1)
    }

    /// Столы, живущие на мониторе (маски тегов).
    pub fn столы_монитора(&self, монитор: usize) -> Vec<u32> {
        let mut v: Vec<u32> = self.tag_monitor.iter()
            .filter(|(_, m)| **m == монитор)
            .map(|(t, _)| *t)
            .collect();
        v.sort_unstable();
        v
    }

    /// Объединение тегов, видимых ХОТЯ БЫ НА ОДНОМ мониторе.
    ///
    /// `refresh_tags` кладёт в `space` окна по этой маске, а не по тегам
    /// активного монитора: на втором мониторе в этот же момент открыт другой
    /// стол, и его окна обязаны оставаться на холсте. Разводит их не видимость,
    /// а «дома» мониторов — чужие окна просто не попадают в кадр (отсечение по
    /// видимой части холста в `udev::собрать_элементы`).
    pub fn видимые_теги(&self) -> u32 {
        if self.мониторы.is_empty() {
            return self.viewport.current_tags();
        }
        let mut маска = 0u32;
        for (i, m) in self.мониторы.iter().enumerate() {
            маска |= if i == self.активный {
                self.viewport.current_tags()
            } else {
                m.viewport.current_tags()
            };
        }
        маска
    }
}
