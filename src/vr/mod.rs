/// Полотно одного окна: текстура с его содержимым и своя история повреждений.
///
/// Damage tracker здесь не роскошь: без него каждое окно перерисовывалось бы
/// целиком 90 раз в секунду на глаз. С ним перерисовываются только те куски,
/// которые клиент действительно поменял, — то же самое, что dawn делает для
/// монитора.
pub(crate) struct Полотно {
    pub(crate) текстура: GlesTexture,
    pub(crate) размер: Size<i32, BufferCoords>,
    следы: OutputDamageTracker,
}

/// Что случилось с полотном за кадр — нужно тем, кто отдаёт пиксели наружу
/// (`mine`: по проводу в Minecraft уезжают только изменившиеся куски).
pub(crate) enum Повреждения {
    /// Полотно только что заведено или сменило размер: годится лишь целиком.
    Всё,
    /// Изменившиеся прямоугольники в пикселях полотна. Пустой список —
    /// клиент не рисовал ничего нового, слать нечего.
    Куски(Vec<smithay::utils::Rectangle<i32, Physical>>),
    /// Кадр не вышел (нет памяти под текстуру, bind не удался).
    Мимо,
}

/// Живой VR-режим.
pub struct ВР {
    pub шлем: xr::Шлем,
    рендер: render::Рендер,
    pub сцена: Сцена,
    полотна: HashMap<Ключ, Полотно>,
    /// Панель, в которую сейчас смотрит указка, и точка в пикселях.
    pub наведено: Option<(Ключ, f64, f64)>,
    /// Пульты dawn (пуск, клавиатура) — панели, которые рисует не клиент, а мы
    /// сами (см. ui.rs). Живут отдельно от `сцена.панели` потому, что `свести`
    /// каждый кадр строит список панелей по ОКНАМ; пульты в него добавляются
    /// после и своей позой владеют сами.
    пульты: Vec<ui::Пульт>,
    /// Текстуры пультов: холст → `import_memory`. Перезаливаются только когда
    /// содержимое пульта поменялось (залип модификатор), а не каждый кадр.
    текстуры: HashMap<Ключ, GlesTexture>,
    /// Кнопка пульта под указкой: ключ пульта и номер кнопки.
    наведена_кнопка: Option<(Ключ, usize)>,
    /// Что тащим: панель и расстояние, на котором её держим.
    тащим: Option<(usize, f32)>,
    /// Нажатие, отданное композитору: чтобы отпустить кнопку ровно один раз.
    кнопка_нажата: bool,
    /// Сколько кадров подряд не удалось нарисовать — по этому счётчику VR
    /// сам себя выключает, а не молча показывает чёрное.
    подряд_ошибок: u32,
    /// Куда положить снимок левого глаза на ближайшем кадре (команда
    /// `vr shot`). Снимок берётся ПОСЛЕ отрисовки и ДО release образа: это
    /// единственный момент, когда кадр шлема ещё наш.
    снимок: Option<std::path::PathBuf>,
    /// Первый кадр уже был: до него не двигаем курсор (сцена ещё пустая).
    был_кадр: bool,
    /// Куда курсор поставили МЫ на прошлом кадре. Если он с тех пор уехал —
    /// значит его двигала мышь, и указка обязана уступить (см. применить_ввод).
    наш_курсор: Option<Point<f64, smithay::utils::Logical>>,
    /// Когда мышь двигали в последний раз.
    мышь_вела: Option<std::time::Instant>,
}

/// Стабильный ключ окна.
///
/// Хранится в `UserDataMap` самого окна: указатель на объект не годится
/// (`Window` — `Arc`, адрес совпадает у клонов, но не переживает пересоздание),
/// а идентификатор поверхности у X11-окна появляется не сразу. Номер выдаётся
/// раз и живёт ровно столько же, сколько окно.
pub fn ключ_окна(окно: &Window) -> Ключ {
    struct ВрКлюч(u64);
    static СЛЕДУЮЩИЙ: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);
    окно.user_data().insert_if_missing(|| {
        ВрКлюч(СЛЕДУЮЩИЙ.fetch_add(1, std::sync::atomic::Ordering::Relaxed))
    });
    окно.user_data().get::<ВрКлюч>().map(|к| к.0).unwrap_or(0)
}

impl ВР {
    /// Скольких панелей касается сцена — для панели состояния и логов.
    pub fn панелей(&self) -> usize {
        self.сцена.панели.len()
    }
}

/// Попросить включить VR-режим.
///
/// Само подключение случится на ближайшем тике — там, где есть живой
/// `GlesRenderer`. Это не лень, а единственный способ поддержать оба бэкенда
/// разом: на DRM рендерер лежит в `state.udev_devices`, а в headless он живёт
/// внутри замыкания таймера (см. `headless.rs`) и снаружи его не достать.
/// Заодно это разводит «человек нажал бинд» и «мы действительно открыли
/// сессию»: между ними может пройти кадр, и ошибка приходит уведомлением.
pub fn включить(state: &mut Dawn) -> Result<(), String> {
    if state.vr.is_some() {
        return Ok(());
    }
    state.vr_просят = true;
    // Тик VR идёт в конце итерации главного цикла; чтобы он случился прямо
    // сейчас, а не после следующего события ввода, будим цикл.
    state.request_redraw();
    Ok(())
}

/// Сколько ждём, пока человек наденет шлем и запустит на нём клиент WiVRn.
///
/// Две минуты — это «дойти до полки, надеть Quest, войти в приложение», с
/// запасом. Ждать вечно нельзя: человек мог передумать, а мы бы каждую секунду
/// дёргали рантайм до конца сеанса.
const ЖДЁМ_ШЛЕМ: std::time::Duration = std::time::Duration::from_secs(120);

/// Как часто пробуем подключиться, пока ждём.
const ПАУЗА_МЕЖДУ_ПОПЫТКАМИ: std::time::Duration = std::time::Duration::from_secs(1);

/// Сколько даём серверу подняться, прежде чем стучаться к нему первый раз.
const СЕРВЕР_ПОДНИМАЕТСЯ: std::time::Duration = std::time::Duration::from_secs(3);

/// Ожидание живого шлема: сервер подняли, теперь ждём, когда наденут Quest.
///
/// Само ожидание крутится в отдельном потоке (`завести_поиск`); здесь только
/// то, что нужно главному циклу: до каких пор ждём (для `vr state`) и сказали
/// ли уже человеку об этом.
pub struct Ожидание {
    /// Когда сдаёмся.
    до: std::time::Instant,
    /// Сколько ждать перед ПЕРВОЙ попыткой: сервер, поднятый секунду назад, ещё
    /// не открыл свой сокет, и стучаться в него сразу — гарантированный отказ.
    первая_пауза: std::time::Duration,
    /// Сказали ли уже «жду шлем»: уведомление должно быть одно, а не по одному
    /// на каждую секунду ожидания.
    сказали: bool,
}

impl Ожидание {
    fn новое(сервер_только_что_подняли: bool) -> Ожидание {
        Ожидание {
            до: std::time::Instant::now() + ЖДЁМ_ШЛЕМ,
            первая_пауза: if сервер_только_что_подняли {
                СЕРВЕР_ПОДНИМАЕТСЯ
            } else {
                std::time::Duration::ZERO
            },
            сказали: false,
        }
    }
}

/// **Одна команда на весь вход в VR** (действие `vr_mode`, `Super+Alt+V`).
///
/// Делает всё, что раньше требовало отдельного скрипта от root и трёх шагов
/// вручную:
///
/// 1. проверяет, что рантайм OpenXR вообще есть (и подставляет манифест WiVRn
///    сам, не требуя ни `active_runtime.json` от root, ни переменной в
///    окружении сеанса);
/// 2. поднимает `wivrn-server`, если тот не идёт;
/// 3. ждёт, пока человек наденет шлем и запустит на нём клиент, — и входит в
///    VR в ту же секунду, как шлем появился;
/// 4. повторным нажатием отменяет ожидание, а из VR — выходит.
///
/// То есть от человека нужно ровно одно: нажать Super+Alt+V и надеть Quest.
pub fn режим(state: &mut Dawn) {
    // Уже в шлеме — значит это «снять».
    if state.vr.is_some() {
        выключить(state);
        state.уведомить("VR: шлем снят");
        return;
    }
    // Уже ждём — значит это «передумал». Иначе отменить ожидание было бы
    // нечем, кроме перезапуска.
    if state.vr_ожидание.take().is_some() {
        state.vr_просят = false;
        // Роняем приёмник: поток поиска, когда рантайм его наконец отпустит,
        // не сможет отправить результат и тихо кончится (см. `завести_поиск`).
        state.vr_поиск = None;
        // Переменную снимаем здесь же. Загрузчик OpenXR читает её один раз, в
        // самом начале `xrCreateInstance`, — то есть через доли секунды после
        // старта потока, а отмена приходит человеческим темпом, секундами
        // позже; к этому моменту читать её уже некому.
        wivrn::убрать_рантайм();
        state.уведомить("VR: ожидание шлема отменено");
        return;
    }

    if !wivrn::рантайм_есть() {
        state.уведомить(
            "VR: рантайм OpenXR не найден — нужен WiVRn (или Monado) и его манифест",
        );
        return;
    }

    // Сервер нужен только под WiVRn: проводной шлем через Monado и симулятор
    // в харнессе работают без него, и лишний процесс там был бы чистым вредом.
    let mut подняли = false;
    if wivrn::это_wivrn() && !wivrn::сервер_идёт() {
        if let Some(бинарь) = wivrn::сервер_путь() {
            state.spawn(&wivrn::команда_сервера(&бинарь));
            state.уведомить("VR: поднимаю сервер WiVRn");
            подняли = true;
        }
    }

    state.vr_ожидание = Some(Ожидание::новое(подняли));
    state.vr_просят = true;
    state.request_redraw();
}

/// Почему не вошли в VR — и стоит ли пробовать снова.
///
/// Разница здесь не косметическая. «Рантайм не установлен» и «шлем ещё не
/// надет» приходят из одного места одинаковыми строками, но первое означает
/// «сдавайся и скажи человеку», а второе — «подожди, он как раз идёт за
/// Quest'ом». Без этого различия команда `vr mode` либо сдавалась бы сразу,
/// либо минуту молчала бы при заведомо безнадёжной настройке.
pub struct ОшибкаВхода {
    pub текст: String,
    pub ждать: bool,
}

impl From<xr::Ошибка> for ОшибкаВхода {
    fn from(e: xr::Ошибка) -> Self {
        ОшибкаВхода {
            ждать: e.подождать_ли(),
            текст: e.to_string(),
        }
    }
}

impl From<String> for ОшибкаВхода {
    fn from(текст: String) -> Self {
        ОшибкаВхода { текст, ждать: false }
    }
}

/// Завести поиск шлема в ОТДЕЛЬНОМ ПОТОКЕ.
///
/// **Почему не в главном цикле, как было.** `xrCreateInstance` под WiVRn —
/// блокирующий вызов без таймаута: клиент Monado соединяется с `wivrn-server` и
/// спит в `recvmsg`, пока к серверу не подключится живой Quest (см. `xr.rs`,
/// `Заготовка`). Пока он спал в главном потоке, dawn не обрабатывал ни ввод, ни
/// клиентов, ни кадры — весь сеанс выглядел намертво зависшим, и выйти можно
/// было только жёсткой перезагрузкой. Замер 31.08.2026: харнесс перестал
/// отвечать на `vr state` сразу после `vr mode`, главный поток стоял в
/// `ipc_client_setup_shm`, потребление CPU 0.3 % — то есть спал, а не считал.
///
/// Теперь блокируется поток, которому это ничего не стоит, а главный цикл лишь
/// раз в тик заглядывает в канал (`try_recv`, никогда не ждёт).
///
/// **Отмена.** Отменить сам вызов нечем — рантайм не даёт такой возможности.
/// Поэтому отмена ожидания просто роняет приёмник: поток, когда рантайм его
/// наконец отпустит, не сможет отправить результат, уронит инстанс (а с ним и
/// соединение с сервером) и тихо кончится. Ровно поэтому же новый поиск заводим
/// только при пустом `vr_поиск`: пока приёмник наш, поток жив и второй не нужен.
fn завести_поиск(state: &mut Dawn) {
    if state.vr_поиск.is_some() {
        return;
    }
    // Рантайм подставляем ЗДЕСЬ, на главном потоке, а снимаем — когда придёт
    // ответ. Менять окружение из потока нельзя: `setenv` переписывает общий
    // `environ`, который главный поток в этот же миг читает на каждом
    // `Command::spawn`. Плата за это — на время ожидания шлема переменная
    // видна запускаемым программам; она невелика и берётся только там, где
    // активного рантайма в системе нет вовсе (у Ярика есть, и ветка молчит).
    let (до, пауза, сказать) = match state.vr_ожидание.as_mut() {
        Some(ож) => {
            let сказать = !ож.сказали;
            ож.сказали = true;
            (Some(ож.до), ож.первая_пауза, сказать)
        }
        // Без ожидания (`vr on`) попытка ровно одна, как было.
        None => (None, std::time::Duration::ZERO, false),
    };
    wivrn::подставить_рантайм();
    let (отправитель, приёмник) = std::sync::mpsc::channel();
    let поток = std::thread::Builder::new()
        .name("dawn-vr-поиск".into())
        .spawn(move || {
            if !пауза.is_zero() {
                std::thread::sleep(пауза);
            }
            loop {
                match xr::Заготовка::нащупать() {
                    Ok(з) => {
                        // Отправить не вышло — ожидание отменили. Инстанс
                        // уронится здесь же, соединение с сервером закроется.
                        let _ = отправитель.send(Ok(з));
                        return;
                    }
                    Err(e) => {
                        let о = ОшибкаВхода::from(e);
                        // «Шлема ещё нет» и есть время — пробуем снова. Под
                        // WiVRn сюда обычно не попадают вовсе: там ожидание
                        // живёт внутри самого `нащупать`, и срок ему не указ.
                        if о.ждать && до.is_some_and(|т| std::time::Instant::now() < т) {
                            std::thread::sleep(ПАУЗА_МЕЖДУ_ПОПЫТКАМИ);
                            continue;
                        }
                        let _ = отправитель.send(Err(о));
                        return;
                    }
                }
            }
        });
    match поток {
        Ok(_) => {
            state.vr_поиск = Some(приёмник);
            if сказать {
                state.уведомить("VR: жду шлем — надень Quest и запусти на нём WiVRn");
            }
        }
        Err(e) => {
            wivrn::убрать_рантайм();
            state.vr_просят = false;
            state.vr_ожидание = None;
            tracing::warn!("dawn/vr: поток поиска шлема не завёлся: {e}");
            state.уведомить("VR: не удалось завести поиск шлема");
        }
    }
}

/// Собственно подключение — с рендерером на руках и уже готовой заготовкой.
fn подключить(
    state: &mut Dawn,
    renderer: &mut GlesRenderer,
    заготовка: xr::Заготовка,
) -> Result<ВР, ОшибкаВхода> {
    let шлем = xr::Шлем::поднять(заготовка, renderer)?;
    let рендер = render::Рендер::собрать(renderer)?;
    // Зона: спрашиваем у рантайма границы игрового пространства. Нет —
    // круг по умолчанию (см. scene.rs).
    let зона = match шлем
        .session
        .reference_space_bounds_rect(openxr::ReferenceSpaceType::STAGE)
    {
        Ok(Some(р)) => {
            tracing::info!("dawn/vr: зона шлема {:.2}×{:.2} м", р.width, р.height);
            Зона::прямоугольная(р.width, р.height)
        }
        _ => {
            tracing::info!(
                "dawn/vr: зона неизвестна, беру круг {} м",
                Зона::РАДИУС_ПО_УМОЛЧАНИЮ
            );
            Зона::default()
        }
    };
    let наст = state.lua_config.vr.clone();
    let mut сцена = Сцена::default();
    сцена.зона = зона;
    // Раскладку берём ту, что человек выбрал В ЭТОЙ сессии (она переживает
    // снятие шлема), а при первом входе — из `vr{}` конфига.
    сцена.раскладка = state.vr_раскладка;
    сцена.метров_на_пиксель = наст.scale;
    if наст.radius > 0.0 {
        // Явный радиус из конфига сильнее зоны шлема: человек может хотеть
        // окна ближе, чем позволяет его комната.
        сцена.зона = Зона::круглая(наст.radius / 0.8);
    }
    let mut шлем = шлем;
    if наст.ar {
        // Просили дополненную сразу — но честно: рантайм без passthrough
        // останется в обычном VR, и в лог уйдёт предупреждение (см. xr.rs).
        шлем.дополненная(true);
    }
    Ok(ВР {
        шлем,
        рендер,
        сцена,
        полотна: HashMap::new(),
        наведено: None,
        пульты: Vec::new(),
        текстуры: HashMap::new(),
        наведена_кнопка: None,
        тащим: None,
        кнопка_нажата: false,
        подряд_ошибок: 0,
        снимок: None,
        был_кадр: false,
        наш_курсор: None,
        мышь_вела: None,
    })
}

/// Выключить VR-режим и вернуть GL-ресурсы.
pub fn выключить(state: &mut Dawn) {
    state.vr_просят = false;
    let Some(вр) = state.vr.take() else { return };
    let вр = *вр;
    state.vr_раскладка = вр.сцена.раскладка;
    let mut устройства = std::mem::take(&mut state.udev_devices);
    if let Some(устройство) = устройства.values_mut().next() {
        вр.рендер.разобрать(&mut устройство.gles);
    } else {
        // headless: рендерер живёт в замыкании таймера, и достать его отсюда
        // нечем. Программы и буферы уйдут вместе с контекстом при выходе —
        // единственное место, где мы это допускаем, и только потому, что
        // headless живёт ровно один прогон харнесса.
        tracing::debug!("dawn/vr: GL-ресурсы освободит контекст (headless)");
    }
    state.udev_devices = устройства;
    tracing::info!("dawn/vr: режим выключен");
    state.request_redraw();
}

/// Один шаг VR из главного цикла (DRM-бэкенд).
///
/// Внутри — `xrWaitFrame`, то есть ожидание своей очереди у шлема; на 90 Гц это
/// до 11 мс, и они же играют роль паузы главного цикла.
pub fn тик(state: &mut Dawn) {
    if state.vr.is_none() && !state.vr_просят {
        return;
    }
    // Забираем и режим, и устройства: и тому и другому нужен `&mut Dawn`
    // внутри (сцена читает окна, ввод двигает курсор). Тот же приём, что в
    // `udev::render_all`.
    let mut устройства = std::mem::take(&mut state.udev_devices);
    if let Some(устройство) = устройства.values_mut().next() {
        let гles = &mut устройство.gles as *mut GlesRenderer;
        // Безопасно по той же причине, что и в `render_all`: `state` больше не
        // владеет устройствами (они вынуты выше), так что второго пути к этому
        // рендереру внутри вызова нет.
        unsafe { тик_с(state, &mut *гles) };
    }
    state.udev_devices = устройства;
}

/// Тот же шаг, но с явно переданным рендерером — так VR работает и в headless,
/// где `GlesRenderer` живёт внутри замыкания таймера (см. `headless::такт`).
/// Благодаря этому весь VR-режим проверяется харнессом на симуляторе Monado,
/// без шлема и без живого сеанса.
pub fn тик_с(state: &mut Dawn, renderer: &mut GlesRenderer) {
    if state.vr_просят && state.vr.is_none() {
        // Поиск шлема идёт в своём потоке (см. `завести_поиск`) — здесь только
        // заглядываем в канал и НИКОГДА не ждём: любая блокировка в этой точке
        // — это замерший композитор.
        завести_поиск(state);
        let ответ = match state.vr_поиск.as_ref().map(|п| п.try_recv()) {
            // Поток ещё ищет: под WiVRn это значит «шлем не подключился к
            // серверу». Уходим до следующего тика, цикл свободен.
            Some(Err(std::sync::mpsc::TryRecvError::Empty)) | None => return,
            Some(Ok(готово)) => готово,
            // Поток умер, не ответив, — такого быть не должно, но молчать об
            // этом нельзя: иначе `vr_просят` висел бы до конца сеанса.
            Some(Err(std::sync::mpsc::TryRecvError::Disconnected)) => {
                Err(ОшибкаВхода::from("поиск шлема оборвался".to_string()))
            }
        };
        // Ответ пришёл — поиск кончился в любом случае, и повторные попытки
        // (если они были нужны) уже сделаны внутри потока.
        state.vr_поиск = None;
        wivrn::убрать_рантайм();
        state.vr_просят = false;
        let ждали = state.vr_ожидание.take().is_some();
        match ответ.and_then(|з| подключить(state, renderer, з)) {
            Ok(вр) => {
                tracing::info!(
                    "dawn/vr: режим включён, раскладка {}",
                    вр.сцена.раскладка.имя()
                );
                state.vr = Some(Box::new(вр));
                if ждали {
                    state.уведомить("VR: шлем на связи");
                }
            }
            Err(e) => {
                tracing::warn!("dawn/vr: не включился: {}", e.текст);
                state.уведомить(&if ждали && e.ждать {
                    "VR: шлем так и не появился".to_string()
                } else {
                    format!("VR: {}", e.текст)
                });
                return;
            }
        }
    }
    if state.vr.is_none() {
        return;
    }
    let mut вр = state.vr.take().unwrap();
    let жив = шаг(&mut вр, renderer, state);
    if жив {
        state.vr = Some(вр);
    } else {
        вр.рендер.разобрать(renderer);
        state.vr_раскладка = вр.сцена.раскладка;
        tracing::info!("dawn/vr: сессия закончилась, возвращаемся на мониторы");
        state.request_redraw();
    }
}

fn шаг(вр: &mut ВР, renderer: &mut GlesRenderer, state: &mut Dawn) -> bool {
    if !вр.шлем.события() {
        return false;
    }
    let кадр = вр.шлем.дождаться_кадра();
    let (время, виды) = match кадр {
        xr::Кадр::Рисуем { время, виды } => (время, виды),
        xr::Кадр::Пропуск => {
            вр.шлем.закрыть_пустой();
            return true;
        }
        xr::Кадр::Спим => return true,
    };

    // ── Ввод ────────────────────────────────────────────────────────────────
    // Опрашиваем ДО отрисовки: за кадр рука успевает уехать, и рисовать луч по
    // прошлому положению — это видимое запаздывание указки.
    let голова = виды[0].поза;
    // Середина между глазами: из неё считается «перед» и к ней разворачиваются
    // панели.
    let центр = Век3::new(
        (виды[0].поза.место.x + виды[1].поза.место.x) * 0.5,
        (виды[0].поза.место.y + виды[1].поза.место.y) * 0.5,
        (виды[0].поза.место.z + виды[1].поза.место.z) * 0.5,
    );
    // Якорь сцены — только по просьбе (вход в VR, пересбор, смена раскладки).
    // Брать высоту глаз каждым кадром значило бы таскать панели за головой по
    // вертикали, ровно как «перед» таскал бы их за поворотом.
    if вр.сцена.нужен_якорь {
        вр.сцена.якорь_по_голове(голова, центр.y);
        tracing::info!(
            "dawn/vr: якорь сцены — перед {:.0}°, глаза {:.2} м",
            вр.сцена.перед.to_degrees(),
            вр.сцена.высота_глаз
        );
    }
    let перед = вр.сцена.перед;
    if let Some(ввод) = &mut вр.шлем.ввод {
        let (сессия, сцена_xr) = (&вр.шлем.session, &вр.шлем.сцена);
        ввод.опросить(сессия, сцена_xr, время, перед);
    }

    // ── Сцена ───────────────────────────────────────────────────────────────
    let окна = окна_для_сцены(state);
    вр.сцена.свести(&окна.iter().map(|(_, о)| *о).collect::<Vec<_>>());
    вр.сцена.разложить();

    // ── Пульты dawn ─────────────────────────────────────────────────────────
    // Кнопки контроллеров и жесты рук — до того, как пульты попадут в сцену:
    // пульт, открытый в этом кадре, обязан в этом же кадре и появиться, иначе
    // между жестом и картинкой был бы видимый провал.
    жесты_ввода(вр, state);
    подмешать_пульты(вр, голова);

    // ── Полотна окон ────────────────────────────────────────────────────────
    for (окно, о) in &окна {
        нарисовать_окно(вр, renderer, окно, *о);
    }
    // Полотна закрытых окон освобождаем: текстура окна 2560×1080 это 11 МиБ,
    // и десяток забытых съедает больше, чем весь остальной dawn.
    let живые: std::collections::HashSet<Ключ> = окна.iter().map(|(_, о)| о.ключ).collect();
    вр.полотна.retain(|к, _| живые.contains(к));

    // ── Холсты пультов ──────────────────────────────────────────────────────
    обновить_текстуры(вр, renderer);

    // ── Указка → курсор dawn ────────────────────────────────────────────────
    let лучи = собрать_лучи(вр, голова);
    применить_ввод(вр, state, &лучи, центр);

    // ── Кадр ────────────────────────────────────────────────────────────────
    let прозрачный = вр.шлем.ар_включена();
    let mut беда = None;
    for глаз in 0..2 {
        let вид = виды[глаз];
        let проекция = Мат4::проекция(вид.углы, 0.05, f32::INFINITY);
        let vp = проекция.умножить(&Мат4::вид(вид.поза));
        let панели = к_показу(вр);
        let линии = линии_сцены(вр, &лучи);
        let (ширина, высота) = (
            вр.шлем.глаза[глаз].ширина as i32,
            вр.шлем.глаза[глаз].высота as i32,
        );
        let образ = match вр.шлем.глаза[глаз].swapchain.acquire_image() {
            Ok(i) => i,
            Err(e) => {
                беда = Some(format!("acquire_image: {e}"));
                break;
            }
        };
        if let Err(e) = вр.шлем.глаза[глаз]
            .swapchain
            .wait_image(openxr::Duration::INFINITE)
        {
            беда = Some(format!("wait_image: {e}"));
            break;
        }
        let текстура = вр.шлем.глаза[глаз].образы[образ as usize];
        let итог = вр.рендер.кадр_глаза(
            renderer, текстура, ширина, высота, vp, &панели, &линии, прозрачный,
        );
        if let Err(e) = итог {
            беда = Some(e);
        }
        // Снимок — с ЛЕВОГО глаза и строго здесь: образ ещё захвачен нами,
        // после release он принадлежит рантайму.
        if глаз == 0 {
            if let Some(путь) = вр.снимок.take() {
                снять_глаз(вр, renderer, текстура, ширина, высота, &путь);
            }
        }
        if let Err(e) = вр.шлем.глаза[глаз].swapchain.release_image() {
            беда = Some(format!("release_image: {e}"));
            break;
        }
    }

    match беда {
        None => {
            вр.подряд_ошибок = 0;
            вр.был_кадр = true;
            вр.шлем.отдать_кадр(виды);
            true
        }
        Some(e) => {
            вр.подряд_ошибок += 1;
            tracing::warn!("dawn/vr: кадр не вышел ({e}), подряд {}", вр.подряд_ошибок);
            вр.шлем.закрыть_пустой();
            // Десяток подряд — это не рябь, а сломанный конвейер: гасим VR,
            // чтобы человек не сидел в чёрном шлеме, гадая, что случилось.
            вр.подряд_ошибок < 10
        }
    }
}

/// Окна, которые показываем в шлеме: те же, что видны на холсте сейчас.
///
/// **Порядок здесь — это порядок панелей в комнате** (`Сцена::свести` берёт
/// его как есть, а раскладка расставляет панели по индексу). Поэтому брать
/// его у `space.elements()` НЕЛЬЗЯ: это порядок СТОПКИ, и он меняется каждый
/// раз, когда окно поднимается фокусом. Замерено: клик по правой панели, затем
/// «собрать заново» — и панели менялись сторонами, то есть окна прыгали по
/// комнате от простого нажатия.
///
/// Сортируем по месту окна на ХОЛСТЕ (слева направо, потом сверху вниз): окно,
/// которое на рабочем столе левее, и панелью висит левее — человек попадает в
/// уже знакомую ему раскладку. Ключ в хвосте сравнения — чтобы порядок был
/// определён и у окон, лежащих ровно друг на друге.
pub(crate) fn окна_для_сцены(state: &Dawn) -> Vec<(Window, ОкноВСцене)> {
    let mut окна: Vec<(i32, i32, Ключ, Window, ОкноВСцене)> = state
        .space
        .elements()
        .filter_map(|окно| {
            let г = state.space.element_geometry(окно)?;
            if г.size.w <= 0 || г.size.h <= 0 {
                return None;
            }
            let ключ = ключ_окна(окно);
            Some((
                г.loc.x,
                г.loc.y,
                ключ,
                окно.clone(),
                ОкноВСцене {
                    ключ,
                    ширина_пкс: г.size.w,
                    высота_пкс: г.size.h,
                },
            ))
        })
        .collect();
    окна.sort_by_key(|(x, y, ключ, _, _)| (*x, *y, *ключ));
    окна.into_iter().map(|(_, _, _, окно, о)| (окно, о)).collect()
}

/// Перерисовать содержимое окна в его полотно.
fn нарисовать_окно(вр: &mut ВР, renderer: &mut GlesRenderer, окно: &Window, о: ОкноВСцене) {
    нарисовать_в_полотно(&mut вр.полотна, renderer, окно, о);
}

/// Окно → его полотно, с возвратом того, что в полотне поменялось.
///
/// Вынесено из `нарисовать_окно` не ради красоты: этим же путём рисует режим
/// Minecraft (`mine`), и повторять здесь вычитание `geometry().loc` во второй
/// раз было бы приглашением к той же ошибке, которую оно и лечит (у клиентов с
/// клиентскими рамками — GTK, Firefox — вокруг окна невидимые поля под тень, и
/// без вычитания в полотно попадает пустота вместо содержимого).
pub(crate) fn нарисовать_в_полотно(
    полотна: &mut HashMap<Ключ, Полотно>,
    renderer: &mut GlesRenderer,
    окно: &Window,
    о: ОкноВСцене,
) -> Повреждения {
    let размер = Size::<i32, BufferCoords>::from((о.ширина_пкс.max(1), о.высота_пкс.max(1)));
    let свежее = match полотна.get(&о.ключ) {
        Some(п) if п.размер == размер => false,
        _ => true,
    };
    if свежее {
        let текстура: GlesTexture = match renderer.create_buffer(Fourcc::Abgr8888, размер) {
            Ok(т) => т,
            Err(e) => {
                tracing::warn!("dawn/vr: полотно {}×{}: {e:?}", размер.w, размер.h);
                return Повреждения::Мимо;
            }
        };
        полотна.insert(
            о.ключ,
            Полотно {
                текстура,
                размер,
                следы: OutputDamageTracker::new(
                    Size::<i32, Physical>::from((размер.w, размер.h)),
                    1.0,
                    Transform::Normal,
                ),
            },
        );
    }
    // Элементы собираем ДО того, как займём рендерер целью: `render_elements`
    // просит его изменяемо, и внутри `bind` этого уже не сделать.
    //
    // Начало дерева поверхностей — минус `geometry().loc`: у клиентов с
    // клиентскими рамками (GTK, Firefox) вокруг окна есть невидимые поля под
    // тень, и без вычитания в полотно попала бы пустота вместо содержимого.
    // Тот же расчёт, что и в главном пути отрисовки (см. udev.rs).
    let сдвиг = окно.geometry().loc;
    let элементы: Vec<WaylandSurfaceRenderElement<GlesRenderer>> = окно.render_elements(
        renderer,
        Point::<i32, Physical>::from((-сдвиг.x, -сдвиг.y)),
        Scale::from(1.0),
        1.0,
    );
    let Some(полотно) = полотна.get_mut(&о.ключ) else { return Повреждения::Мимо };
    let mut цель = полотно.текстура.clone();
    let mut fb = match renderer.bind(&mut цель) {
        Ok(fb) => fb,
        Err(e) => {
            tracing::warn!("dawn/vr: bind полотна: {e:?}");
            return Повреждения::Мимо;
        }
    };
    // Возраст 1: буфер тот же самый, что и в прошлом кадре, поэтому трекер
    // вправе перерисовать только повреждённое. У свежесозданного — 0, то есть
    // «нарисуй всё».
    let возраст = if свежее { 0 } else { 1 };
    match полотно
        .следы
        .render_output(renderer, &mut fb, возраст, &элементы, [0.0, 0.0, 0.0, 0.0])
    {
        Ok(итог) => {
            if свежее {
                Повреждения::Всё
            } else {
                // `damage: None` — трекер решил, что рисовать нечего: клиент за
                // кадр ничего не поменял. Это самый частый случай (окна стоят
                // неподвижно), и именно он экономит провод в Minecraft.
                Повреждения::Куски(итог.damage.cloned().unwrap_or_default())
            }
        }
        Err(e) => {
            tracing::warn!("dawn/vr: полотно окна: {e:?}");
            Повреждения::Мимо
        }
    }
}

// ── Пульты: пуск и клавиатура ───────────────────────────────────────────────

/// Кнопки контроллеров и жесты рук за этот кадр.
///
/// Жест не «делает что-то своё»: он выбирает обычное действие dawn — то же
/// самое, что вешается на клавиши в `bind{}`. Какое именно, решает `config.lua`
/// (`vr{ gestures = { fist = "vr_launcher" } }`), а если человек молчал —
/// [`input::Жест::по_умолчанию`]. Отсюда и главное свойство: любая функция
/// dawn доступна в шлеме без единой правки в этом файле.
fn жесты_ввода(вр: &mut ВР, state: &mut Dawn) {
    let жесты = match вр.шлем.ввод.as_mut() {
        Some(в) => в.жесты(),
        None => return,
    };
    for ж in жесты {
        // Пока панель тащат хватом, стик занят: он приближает её и меняет
        // размер (см. `применить_ввод`). Отдать тот же стик ещё и переключению
        // столов значило бы менять стол каждый раз, когда окно отодвигают.
        if matches!(ж, input::Жест::Стик(_)) && вр.тащим.is_some() {
            continue;
        }
        let действие = state
            .lua_config
            .vr
            .gestures
            .get(ж.имя())
            .cloned()
            .unwrap_or_else(|| ж.по_умолчанию());
        tracing::info!("dawn/vr: жест «{}» → {:?}", ж.имя(), действие);
        выполнить(вр, state, действие);
    }
}

/// Сделать действие dawn, попрошенное из шлема.
///
/// **Почему не просто `state.dispatch_action`.** На время кадра VR вынут из
/// состояния (`state.vr` сейчас `None` — см. `кадр`), а действия про шлем как
/// раз через `state.vr` и работают: `dispatch_action(VrLauncher)` ответил бы
/// «шлем не включён». Поэтому свои действия делаются здесь, прямо по `вр`, а
/// всё остальное уходит обычной дорогой — той же, что у клавиш.
fn выполнить(вр: &mut ВР, state: &mut Dawn, действие: crate::config::Action) {
    use crate::config::Action as Д;
    match действие {
        Д::VrLauncher => тумблер(вр, state, ui::Вид::Пуск),
        Д::VrKeyboard => тумблер(вр, state, ui::Вид::Клавиатура),
        Д::VrRecenter => {
            вр.сцена.расстановку_сбросить();
            вр.сцена.якорь_сбросить();
            вр.сцена.разложить();
        }
        Д::VrLayout => {
            let новая = state.vr_раскладка.следующая();
            state.vr_раскладка = новая;
            вр.сцена.раскладка = новая;
            if новая != Раскладка::Свободно {
                вр.сцена.расстановку_сбросить();
            }
            вр.сцена.разложить();
        }
        Д::VrAr => {
            let хочу = !вр.шлем.ар_включена();
            if !вр.шлем.дополненная(хочу) && хочу {
                tracing::warn!("dawn/vr: этот рантайм не показывает комнату — остаёмся в VR");
            }
        }
        // Выключать шлем изнутри шлема — верный способ остаться без картинки от
        // случайного жеста, и «включить обратно» оттуда уже нечем.
        Д::VrToggle | Д::VrMode => {
            tracing::warn!("dawn/vr: снимать шлем жестом нельзя — только с клавиатуры");
        }
        иное => state.dispatch_action(иное),
    }
}

/// Приложения пульта «Пуск»: из `vr{ apps = … }`, иначе набор по умолчанию.
fn приложения(state: &Dawn) -> Vec<(String, String)> {
    let свои = &state.lua_config.vr.apps;
    if свои.is_empty() {
        ui::приложения_по_умолчанию()
    } else {
        свои.clone()
    }
}

/// Показать пульт, если его нет, и спрятать, если есть.
pub fn тумблер(вр: &mut ВР, state: &Dawn, вид: ui::Вид) {
    if let Some(i) = вр.пульты.iter().position(|п| п.вид == вид) {
        let ключ = вр.пульты[i].ключ();
        вр.пульты.remove(i);
        вр.текстуры.remove(&ключ);
        // Панель пульта уходит из сцены немедленно: она попала бы в неё ещё раз
        // только на следующем кадре, но луч и клик считаются здесь и сейчас.
        вр.сцена.панели.retain(|п| п.ключ != ключ);
        tracing::info!("dawn/vr: пульт «{}» спрятан", вид.имя());
        return;
    }
    let пульт = match вид {
        ui::Вид::Пуск => ui::Пульт::пуск(&приложения(state)),
        ui::Вид::Клавиатура => ui::Пульт::клавиатура(),
    };
    tracing::info!(
        "dawn/vr: пульт «{}» открыт ({} кнопок)",
        вид.имя(),
        пульт.кнопки.len()
    );
    вр.пульты.push(пульт);
}

/// Поставить только что открытые пульты перед головой и добавить их панели в
/// сцену.
///
/// Делается каждым кадром, потому что `Сцена::свести` строит список панелей по
/// окнам и пульты из него выбрасывает. Пульт при этом сохраняет свою позу сам —
/// в том числе ту, куда его перетащили хватом (см. `применить_ввод`).
fn подмешать_пульты(вр: &mut ВР, голова: math::Поза) {
    let метров = вр.сцена.метров_на_пиксель;
    for п in &mut вр.пульты {
        if п.поза.is_none() {
            п.поставить(голова, метров);
        }
        let Some(поза) = п.поза else { continue };
        вр.сцена.панели.push(Панель {
            ключ: п.ключ(),
            поза,
            пол_ширина: п.пол_ширина,
            пол_высота: п.пол_высота,
            ширина_пкс: п.ширина_пкс,
            высота_пкс: п.высота_пкс,
            // Закреплена всегда: раскладка окон к пультам отношения не имеет,
            // и утащить пульт в дугу вместе с окнами было бы сюрпризом.
            закреплена: true,
        });
    }
}

/// Залить холсты пультов в текстуры — только те, что изменились.
fn обновить_текстуры(вр: &mut ВР, renderer: &mut GlesRenderer) {
    for п in &mut вр.пульты {
        let ключ = п.ключ();
        if !п.перерисовать && вр.текстуры.contains_key(&ключ) {
            continue;
        }
        let холст = п.нарисовать();
        let размер = Size::<i32, BufferCoords>::from((п.ширина_пкс, п.высота_пкс));
        // `Abgr8888` в памяти — это байты R,G,B,A, ровно как их кладёт text.rs.
        match renderer.import_memory(&холст, Fourcc::Abgr8888, размер, false) {
            Ok(т) => {
                вр.текстуры.insert(ключ, т);
                п.перерисовать = false;
            }
            Err(e) => {
                tracing::warn!("dawn/vr: холст пульта «{}» не залился: {e:?}", п.вид.имя());
                // Не пробуем снова каждым кадром: если формат не подошёл, он не
                // подойдёт и через кадр, а лог был бы завален.
                п.перерисовать = false;
            }
        }
    }
    let живые: std::collections::HashSet<Ключ> = вр.пульты.iter().map(|п| п.ключ()).collect();
    вр.текстуры.retain(|к, _| живые.contains(к));
}

/// Нажали кнопку пульта.
///
/// Возвращает `true`, если пульт после этого надо перерисовать (залип
/// модификатор).
fn нажать_кнопку(вр: &mut ВР, state: &mut Dawn, ключ: Ключ, номер: usize) {
    let Some(i) = вр.пульты.iter().position(|п| п.ключ() == ключ) else { return };
    let Some(действие) = вр.пульты[i].кнопки.get(номер).map(|к| к.действие.clone()) else {
        return;
    };
    match действие {
        ui::Действие::Запуск(команда) => {
            tracing::info!("dawn/vr: пульт → {команда}");
            state.spawn(&команда);
        }
        ui::Действие::Дать(действие) => state.dispatch_action(действие),
        ui::Действие::Клавиша(код) => {
            // Модификаторы обрамляют клавишу: без этого ни одно сочетание с
            // пульта не сработало бы, а именно ими открывают окна
            // (`Super+Enter`). Залипание снимается после клавиши — как у
            // sticky keys, и по той же причине: держать модификатор пальцем в
            // воздухе, целясь во вторую клавишу, нечем.
            let залипли = std::mem::take(&mut вр.пульты[i].залипли);
            for &м in &залипли {
                state.vr_клавиша(м, true);
            }
            state.vr_клавиша(код, true);
            state.vr_клавиша(код, false);
            for &м in залипли.iter().rev() {
                state.vr_клавиша(м, false);
            }
            вр.пульты[i].перерисовать = !залипли.is_empty();
        }
        ui::Действие::Модификатор(код) => вр.пульты[i].залипание(код),
        ui::Действие::Ар => {
            // Не через `dispatch_action`: на время кадра `state.vr` вынут из
            // состояния (см. `тик_с`), и общий путь решил бы, что шлем выключен.
            let хочу = !вр.шлем.ар_включена();
            let стало = вр.шлем.дополненная(хочу);
            tracing::info!(
                "dawn/vr: пульт → AR {}",
                if стало { "включена" } else { "не вышла" }
            );
        }
        ui::Действие::Раскладка => {
            let новая = вр.сцена.раскладка.следующая();
            вр.сцена.раскладка = новая;
            state.vr_раскладка = новая;
            if новая != Раскладка::Свободно {
                вр.сцена.расстановку_сбросить();
            }
            вр.сцена.разложить();
        }
        ui::Действие::Пересобрать => {
            вр.сцена.расстановку_сбросить();
            вр.сцена.якорь_сбросить();
            вр.сцена.разложить();
        }
        ui::Действие::Пульт(вид) => тумблер(вр, state, вид),
        ui::Действие::Закрыть => {
            let вид = вр.пульты[i].вид;
            тумблер(вр, state, вид);
        }
    }
}

/// Лучи, которыми целятся: сначала контроллеры/руки, потом взгляд.
fn собрать_лучи(вр: &ВР, голова: math::Поза) -> Vec<(usize, Луч)> {
    let mut лучи = Vec::new();
    if let Some(ввод) = &вр.шлем.ввод {
        for i in 0..2 {
            if let Some(л) = ввод.состояние[i].луч() {
                лучи.push((i, л));
            }
        }
    }
    if лучи.is_empty() {
        // Ни контроллеров, ни рук — целимся взглядом. Это же путь симулятора,
        // на котором VR-режим и проверяется без шлема.
        лучи.push((
            usize::MAX,
            Луч::new(
                голова.место,
                голова.поворот.повернуть(Век3::new(0.0, 0.0, -1.0)),
            ),
        ));
    }
    лучи
}

/// Указка → курсор и кнопки dawn.
fn применить_ввод(вр: &mut ВР, state: &mut Dawn, лучи: &[(usize, Луч)], глаз: Век3) {
    let ведущая = вр.шлем.ввод.as_ref().and_then(|в| в.ведущая());
    // Луч ведущей руки, иначе первый попавшийся (взгляд).
    let луч = лучи
        .iter()
        .find(|(i, _)| Some(*i) == ведущая)
        .or_else(|| лучи.first())
        .map(|(_, л)| *л);
    let Some(луч) = луч else { return };

    // ── Перетаскивание панели ───────────────────────────────────────────────
    let (хват_нажат, хват_отпущен, выбор_нажат, выбор_отпущен, стик) = match (&вр.шлем.ввод, ведущая)
    {
        (Some(в), Some(i)) => {
            let р = в.состояние[i];
            (
                р.хват_нажат,
                р.хват_отпущен,
                р.выбор_нажат || р.щипок_нажат,
                // Отпускание щипка обязано считаться наравне с курком, иначе
                // клик рукой уходит в окно нажатием — и НАВСЕГДА: левая кнопка
                // остаётся зажатой, а окно думает, что его тащат.
                р.выбор_отпущен || р.щипок_отпущен,
                р.стик,
            )
        }
        _ => (false, false, false, false, (0.0, 0.0)),
    };

    let попал = вр.сцена.навести(луч);
    вр.наведено = попал.map(|(i, x, y)| (вр.сцена.панели[i].ключ, x, y));
    вр.наведена_кнопка = вр.наведено.and_then(|(ключ, x, y)| {
        let пульт = вр.пульты.iter().find(|п| п.ключ() == ключ)?;
        Some((ключ, пульт.кнопка_в(x, y)?))
    });

    if хват_нажат {
        if let Some((i, _, _)) = попал {
            let d = вр.сцена.панели[i].поза.место.минус(луч.начало).длина();
            вр.тащим = Some((i, d));
        }
    }
    if хват_отпущен {
        вр.тащим = None;
    }
    if let Some((i, мут_расстояние)) = вр.тащим {
        // Стик по вертикали приближает и отдаляет схваченную панель, по
        // горизонтали — меняет её размер. Так работает большинство VR-оболочек,
        // и это единственная пара жестов, которую человек угадывает сам.
        let новое = (мут_расстояние + стик.1 * 0.04).clamp(0.35, 6.0);
        вр.тащим = Some((i, новое));
        if стик.0.abs() > 0.35 {
            вр.сцена.масштабировать(i, 1.0 + стик.0.signum() * 0.01);
        }
        вр.сцена.перенести(i, луч, новое, глаз);
        // Пульт своей позой владеет сам (в сцене он появляется заново каждым
        // кадром), поэтому перенос надо вернуть ему — иначе он на следующем же
        // кадре прыгнет обратно.
        let (ключ, поза, пол_ш, пол_в) = {
            let п = &вр.сцена.панели[i];
            (п.ключ, п.поза, п.пол_ширина, п.пол_высота)
        };
        if let Some(пульт) = вр.пульты.iter_mut().find(|п| п.ключ() == ключ) {
            пульт.поза = Some(поза);
            пульт.пол_ширина = пол_ш;
            пульт.пол_высота = пол_в;
        }
        // Пока тащим — курсор в окно не гоняем: иначе окно получало бы
        // «мышь ездит» на каждый кадр переноса.
        return;
    }

    // ── Кто ведёт курсор: указка или мышь ───────────────────────────────────
    //
    // Мышь в шлеме — это не запасной вариант, а главный способ работы (за
    // клавиатурой сидят и в VR). Поэтому правило простое: пока человек трогает
    // мышь, указка курсор НЕ трогает. Определяем это без правок в input.rs —
    // сравнением: если `pointer_location` изменился не нами, значит его
    // подвинул кто-то ещё, то есть мышь.
    let курсор_сейчас = state.pointer_location;
    let двигали_мышью = вр
        .наш_курсор
        .is_none_or(|наш: Point<f64, smithay::utils::Logical>| {
            (наш.x - курсор_сейчас.x).abs() + (наш.y - курсор_сейчас.y).abs() > 0.75
        });
    if двигали_мышью {
        вр.мышь_вела = Some(std::time::Instant::now());
    }
    // Две секунды после последнего движения мыши указка молчит: иначе стоит
    // отпустить мышь — и курсор тут же уедет туда, куда смотрит голова.
    let мышь_главная = вр
        .мышь_вела
        .is_some_and(|t| t.elapsed() < std::time::Duration::from_secs(2));

    // ── Курсор ──────────────────────────────────────────────────────────────
    let Some((индекс, пкс_x, пкс_y)) = попал else {
        // Указка в пустоту: кнопку, если держали, отпускаем — иначе окно
        // осталось бы с зажатой мышью навсегда.
        if вр.кнопка_нажата {
            crate::vr::клик(state, false);
            вр.кнопка_нажата = false;
        }
        return;
    };
    let ключ = вр.сцена.панели[индекс].ключ;

    // ── Пульт под указкой ───────────────────────────────────────────────────
    //
    // Курсор dawn сюда не едет вовсе: пульт — это не окно, за ним нет клиента,
    // и «навести мышь» на кнопку клавиатуры значило бы увести указатель с того
    // окна, в которое человек как раз собирается печатать.
    if ui::пульт_ли(ключ) {
        if вр.кнопка_нажата {
            клик(state, false);
            вр.кнопка_нажата = false;
        }
        if выбор_нажат {
            if let Some((_, номер)) = вр.наведена_кнопка {
                нажать_кнопку(вр, state, ключ, номер);
            }
        }
        return;
    }

    if !мышь_главная {
        if let Some(окно) = окно_по_ключу(state, ключ) {
            if let Some(г) = state.space.element_geometry(&окно) {
                // Пиксель панели → точка холста. Дальше dawn работает как всегда:
                // фокус по наведению, hit-test, клиенты.
                let точка = Point::<f64, smithay::utils::Logical>::from((
                    г.loc.x as f64 + пкс_x,
                    г.loc.y as f64 + пкс_y,
                ));
                state.переместить_курсор_в(точка);
                вр.наш_курсор = Some(state.pointer_location);
            }
        }
    } else {
        // Мышь ведёт: запоминаем её точку, чтобы на следующем кадре не
        // принять собственное бездействие за движение мыши.
        вр.наш_курсор = Some(курсор_сейчас);
        // И показываем крестик там, где МЫШЬ, а не куда смотрит голова: иначе
        // человек видит указатель в одном месте, а нажимает в другом.
        вр.наведено = окно_под_курсором(state, курсор_сейчас);
    }
    if выбор_нажат && !вр.кнопка_нажата {
        клик(state, true);
        вр.кнопка_нажата = true;
    }
    if (выбор_отпущен || !вр.был_кадр) && вр.кнопка_нажата {
        клик(state, false);
        вр.кнопка_нажата = false;
    }
}

/// Какая панель и какой её пиксель сейчас под курсором мыши.
///
/// Обратное к тому, что делает указка: там панель → пиксель → холст, здесь
/// холст → окно → пиксель панели. Одно и то же место в двух представлениях, и
/// сходятся они по построению — оба считают от `element_geometry` окна.
fn окно_под_курсором(
    state: &Dawn,
    точка: Point<f64, smithay::utils::Logical>,
) -> Option<(Ключ, f64, f64)> {
    let (окно, начало) = state.space.element_under(точка)?;
    let г = state.space.element_geometry(окно)?;
    let _ = начало;
    Some((
        ключ_окна(окно),
        точка.x - г.loc.x as f64,
        точка.y - г.loc.y as f64,
    ))
}

pub(crate) fn окно_по_ключу(state: &Dawn, ключ: Ключ) -> Option<Window> {
    state
        .space
        .elements()
        .find(|о| ключ_окна(о) == ключ)
        .cloned()
}

/// Нажать/отпустить левую кнопку от имени указки.
fn клик(state: &mut Dawn, нажать: bool) {
    state.vr_клик(нажать);
}

/// Панели в том виде, в каком их ждёт рендер.
fn к_показу(вр: &ВР) -> Vec<render::КПоказу> {
    вр.сцена
        .панели
        .iter()
        .filter_map(|п| {
            // Панель — это либо окно (полотно с его кадром), либо пульт dawn
            // (холст, который мы нарисовали сами).
            let текстура = match вр.полотна.get(&п.ключ) {
                Some(полотно) => полотно.текстура.tex_id(),
                None => вр.текстуры.get(&п.ключ)?.tex_id(),
            };
            Some(render::КПоказу {
                модель: модель_панели(п),
                текстура,
                альфа: 1.0,
                // Скругление в долях полуширины: 4 см при типичной панели.
                скругление: (0.04 / п.пол_ширина.max(0.05)).min(0.25),
                выделена: вр.наведено.map(|(к, _, _)| к) == Some(п.ключ),
            })
        })
        .collect()
}

fn модель_панели(п: &Панель) -> Мат4 {
    Мат4::из_позы(п.поза).умножить(&Мат4::масштаб(п.пол_ширина, п.пол_высота, 1.0))
}

/// Лучи указок и рамка зоны — тонкая вспомогательная графика.
fn линии_сцены(вр: &ВР, лучи: &[(usize, Луч)]) -> Vec<render::Линия> {
    let mut линии = Vec::new();
    for (_, л) in лучи {
        // Луч рисуем до первой панели, а если ни во что не упёрся — на два
        // метра: бесконечная линия в пустоте выглядит сломанной графикой.
        let длина = вр
            .сцена
            .панели
            .iter()
            .filter_map(|п| л.попал(п.поза, п.пол_ширина, п.пол_высота).map(|(t, _, _)| t))
            .fold(f32::INFINITY, f32::min);
        let длина = if длина.is_finite() { длина } else { 2.0 };
        let до = л.начало.плюс(л.направление * длина);
        линии.push(render::Линия {
            от: [л.начало.x, л.начало.y, л.начало.z],
            до: [до.x, до.y, до.z],
            цвет: [0.55, 0.72, 1.0, 0.9],
        });
    }
    // Рамка зоны по полу: человеку полезно видеть, где кончается его комната,
    // особенно когда панели расставлены по её краю.
    let з = вр.сцена.зона;
    let (ш, г) = (з.пол_ширина, з.пол_глубина);
    let угол = |x: f32, z: f32| [x, 0.01, z];
    let цвет = [0.35, 0.45, 0.6, 0.5];
    let углы = [
        (угол(-ш, -г), угол(ш, -г)),
        (угол(ш, -г), угол(ш, г)),
        (угол(ш, г), угол(-ш, г)),
        (угол(-ш, г), угол(-ш, -г)),
    ];
    for (от, до) in углы {
        линии.push(render::Линия { от, до, цвет });
    }

    // ── Кнопка пульта под указкой ───────────────────────────────────────────
    //
    // Обводка отрезками, а не перерисовкой холста: холст клавиатуры это два
    // мегабайта и полсотни глифов, и растеризовать его на каждое движение
    // указки значило бы отдать ей весь бюджет кадра.
    if let Some((ключ, номер)) = вр.наведена_кнопка {
        if let (Some(п), Some(пульт)) = (
            вр.сцена.панели.iter().find(|п| п.ключ == ключ),
            вр.пульты.iter().find(|п| п.ключ() == ключ),
        ) {
            if let Some(к) = пульт.кнопки.get(номер) {
                // Пиксели кнопки → координаты панели (−1..1), обратное к
                // `Панель::в_пиксели`.
                let в_панель = |x: f64, y: f64| -> (f32, f32) {
                    let u = (x / п.ширина_пкс.max(1) as f64) as f32 * 2.0 - 1.0;
                    let v = 1.0 - (y / п.высота_пкс.max(1) as f64) as f32 * 2.0;
                    (u * п.пол_ширина, v * п.пол_высота)
                };
                let (л, вх) = в_панель(к.x as f64, к.y as f64);
                let (пр, ни) = в_панель((к.x + к.ш) as f64, (к.y + к.в) as f64);
                let в_мир = |x: f32, y: f32| {
                    let точка = п
                        .поза
                        .место
                        .плюс(п.поза.поворот.повернуть(Век3::new(x, y, 0.002)));
                    [точка.x, точка.y, точка.z]
                };
                let цвет = [0.62, 0.82, 1.0, 0.95];
                let углы = [
                    ((л, вх), (пр, вх)),
                    ((пр, вх), (пр, ни)),
                    ((пр, ни), (л, ни)),
                    ((л, ни), (л, вх)),
                ];
                for ((x1, y1), (x2, y2)) in углы {
                    линии.push(render::Линия {
                        от: в_мир(x1, y1),
                        до: в_мир(x2, y2),
                        цвет,
                    });
                }
            }
        }
    }

    // ── Курсор на панели ────────────────────────────────────────────────────
    //
    // Без него в шлеме не видно, куда нажмёшь: содержимое панели — это кадр
    // окна, а стрелку dawn рисует ПОВЕРХ кадра монитора, то есть в полотно она
    // не попадает вовсе. Крестик рисуется в плоскости самой панели, поэтому
    // «прилипает» к ней при повороте головы, как настоящий курсор к экрану.
    if let Some((ключ, пкс_x, пкс_y)) = вр.наведено {
        if let Some(п) = вр.сцена.панели.iter().find(|п| п.ключ == ключ) {
            // Пиксель → координаты панели (−1..1 по полуразмерам), обратное к
            // `Панель::в_пиксели`.
            let u = (пкс_x / п.ширина_пкс.max(1) as f64) as f32 * 2.0 - 1.0;
            let v = 1.0 - (пкс_y / п.высота_пкс.max(1) as f64) as f32 * 2.0;
            let центр_x = u * п.пол_ширина;
            let центр_y = v * п.пол_высота;
            // Полтора сантиметра: крупнее — закрывает текст, мельче — теряется
            // в разрешении шлема.
            let р = 0.015f32;
            // Чуть вынести вперёд, иначе крестик утонет в самой панели
            // (z-fighting на её плоскости).
            let вперёд = 0.002f32;
            let в_мир = |x: f32, y: f32| {
                let местная = Век3::new(x, y, вперёд);
                let точка = п.поза.место.плюс(п.поза.поворот.повернуть(местная));
                [точка.x, точка.y, точка.z]
            };
            let цвет = [1.0, 1.0, 1.0, 0.95];
            линии.push(render::Линия {
                от: в_мир(центр_x - р, центр_y),
                до: в_мир(центр_x + р, центр_y),
                цвет,
            });
            линии.push(render::Линия {
                от: в_мир(центр_x, центр_y - р),
                до: в_мир(центр_x, центр_y + р),
                цвет,
            });
        }
    }
    линии
}

/// Сменить раскладку по кругу (действие `vr_layout`).
pub fn сменить_раскладку(state: &mut Dawn) -> Раскладка {
    let новая = state.vr_раскладка.следующая();
    state.vr_раскладка = новая;
    if let Some(вр) = state.vr.as_mut() {
        вр.сцена.раскладка = новая;
        // Раскладка снимает закрепление: человек попросил разложить заново
        // именно потому, что расстановка руками его больше не устраивает.
        // Кроме «свободно» — там закрепление и есть весь смысл режима.
        if новая != Раскладка::Свободно {
            вр.сцена.расстановку_сбросить();
        }
        вр.сцена.разложить();
    }
    новая
}

/// Чем кончилось переключение дополненной реальности.
///
/// Отказ рантайма — отдельный случай, а не «выключено»: у симулятора Monado и
/// у шлема без камер список режимов это `[OPAQUE]`, и просьба включить AR не
/// делает ничего. Пока оба исхода отвечали одинаково («выключена»), сломанный
/// passthrough на живом Quest выглядел бы ровно как нормальное выключение.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ар {
    Включена,
    Выключена,
    НеУмеет,
}

/// Переключить дополненную реальность (действие `vr_ar`).
pub fn переключить_ар(state: &mut Dawn) -> Ар {
    let Some(вр) = state.vr.as_mut() else { return Ар::НеУмеет };
    let хочу = !вр.шлем.ар_включена();
    let стало = вр.шлем.дополненная(хочу);
    let исход = match (хочу, стало) {
        (_, true) => Ар::Включена,
        (false, false) => Ар::Выключена,
        (true, false) => Ар::НеУмеет,
    };
    match исход {
        Ар::Включена => tracing::info!("dawn/vr: дополненная реальность включена"),
        Ар::Выключена => tracing::info!("dawn/vr: дополненная реальность выключена"),
        Ар::НеУмеет => {
            tracing::warn!("dawn/vr: этот рантайм не показывает комнату — остаёмся в VR")
        }
    }
    исход
}

/// Поставить панели заново вокруг текущего направления взгляда
/// (действие `vr_recenter`).
pub fn пересобрать(state: &mut Dawn) {
    let Some(вр) = state.vr.as_mut() else { return };
    // «Перед» — туда, куда человек смотрит сейчас. Взять это направление можно
    // только из последней позы головы, а она приходит с кадром; поэтому просто
    // помечаем, что на следующем кадре дугу надо построить заново.
    вр.сцена.расстановку_сбросить();
    вр.сцена.якорь_сбросить();
    вр.сцена.разложить();
}

/// Показать или спрятать пульт (действия `vr_launcher`, `vr_keyboard`, команды
/// `vr menu`, `vr keys`).
///
/// Снаружи — с бинда, из сокета — пульт переключается ровно так же, как
/// кнопкой контроллера: одна дорога и для человека в шлеме, и для харнесса.
pub fn пульт(state: &mut Dawn, вид: ui::Вид) -> Result<bool, String> {
    if state.vr.is_none() {
        return Err("шлем не включён".into());
    }
    // Берём VR из состояния на время вызова: `тумблер` хочет и `&mut ВР`, и
    // `&Dawn` (список приложений живёт в конфиге).
    let mut вр = state.vr.take().unwrap();
    тумблер(&mut вр, state, вид);
    let открыт = вр.пульты.iter().any(|п| п.вид == вид);
    state.vr = Some(вр);
    state.request_redraw();
    Ok(открыт)
}

/// Нажать кнопку пульта по номеру — измеритель для харнесса (`vr press`).
///
/// В шлеме кнопку нажимают лучом, а снаружи луча нет: без этой команды пульты
/// нельзя было бы проверить ничем, кроме как надев Quest.
pub fn нажать(state: &mut Dawn, вид: ui::Вид, номер: usize) -> Result<String, String> {
    if state.vr.is_none() {
        return Err("шлем не включён".into());
    }
    let mut вр = state.vr.take().unwrap();
    let ключ = ui::ключ(вид);
    let подпись = вр
        .пульты
        .iter()
        .find(|п| п.вид == вид)
        .and_then(|п| п.кнопки.get(номер))
        .map(|к| к.подпись.clone());
    let итог = match подпись {
        Some(п) => {
            нажать_кнопку(&mut вр, state, ключ, номер);
            Ok(п)
        }
        None => Err(format!("у пульта «{}» нет кнопки {номер}", вид.имя())),
    };
    state.vr = Some(вр);
    state.request_redraw();
    итог
}

/// Пульты и их кнопки построчно (команда `vr pults`).
pub fn пульты_строкой(state: &Dawn) -> String {
    let Some(вр) = state.vr.as_ref() else {
        return "шлем не включён".into();
    };
    if вр.пульты.is_empty() {
        return "пультов нет (Пуск — кулак, кнопка ☰ или нажатие на стик, \
                ладонь вверх, Super+Alt+M; вся раскладка — `vr gestures`)"
            .into();
    }
    let mut из = String::new();
    for п in &вр.пульты {
        из.push_str(&format!(
            "пульт «{}» {}×{} пкс, {} м в ширину, поза {}\n",
            п.вид.имя(),
            п.ширина_пкс,
            п.высота_пкс,
            format_args!("{:.2}", п.пол_ширина * 2.0),
            match п.поза {
                Some(поза) => format!(
                    "({:.2},{:.2},{:.2})",
                    поза.место.x, поза.место.y, поза.место.z
                ),
                None => "встанет на ближайшем кадре".into(),
            },
        ));
        for (i, к) in п.кнопки.iter().enumerate() {
            let наведена = вр.наведена_кнопка == Some((п.ключ(), i));
            из.push_str(&format!(
                "{}{i:>3} {}\n",
                if наведена { "*" } else { " " },
                к.подпись
            ));
        }
        if !п.залипли.is_empty() {
            из.push_str(&format!("  залипли модификаторы: {:?}\n", п.залипли));
        }
    }
    из
}

