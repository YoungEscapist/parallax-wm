/// Куда отклонили — по двум составляющим и порогу. Побеждает бо́льшая: жест
/// «влево» никогда не бывает чисто горизонтальным, и без этого правила один
/// взмах засчитывался бы сразу в две стороны.
///
/// Отдельной функцией, потому что считает это ДВОЕ: взмах ладонью (составляющие
/// — скорость в метрах в секунду) и стик (составляющие — его отклонение). Пусть
/// правило будет одно.
pub fn сторона(x: f32, y: f32, порог: f32) -> Option<Сторона> {
    if x.abs().max(y.abs()) <= порог {
        return None;
    }
    Some(if x.abs() > y.abs() {
        if x > 0.0 { Сторона::Вправо } else { Сторона::Влево }
    } else if y > 0.0 {
        Сторона::Вверх
    } else {
        Сторона::Вниз
    })
}

/// Согнут ли палец: кончик ближе к запястью, чем его же костяшка.
///
/// Мера ОТНОШЕНИЕМ, а не сантиметрами: у ребёнка и у взрослого руки разные, а
/// отношение одно. И никаких осей — только три точки, поэтому она не зависит от
/// того, как рантайм ориентирует суставы.
pub fn согнут(запястье: Век3, костяшка: Век3, кончик: Век3) -> bool {
    кончик.минус(запястье).длина() < костяшка.минус(запястье).длина() * 1.15
}

/// Одна рука: откуда светит луч и что на ней нажато.
#[derive(Debug, Clone, Copy, Default)]
pub struct Рука {
    /// Поза указки. `None` — контроллер не отслеживается (лежит на столе,
    /// вышел из поля зрения камер).
    pub указка: Option<Поза>,
    /// Куда указка смотрит, когда направление задано НЕ поворотом позы.
    /// Так целится рука: см. `луч`.
    pub направление: Option<Век3>,
    /// Курок нажат (левая кнопка мыши).
    pub выбор: bool,
    /// Курок нажали именно в этом кадре — по фронту работают клики.
    pub выбор_нажат: bool,
    pub выбор_отпущен: bool,
    /// Хват (перетаскивание панели).
    pub хват: bool,
    pub хват_нажат: bool,
    pub хват_отпущен: bool,
    /// Стик: X — поворот/размер, Y — приблизить/отдалить панель.
    pub стик: (f32, f32),
    /// Кнопка меню — вызывает пульт «Пуск» прямо в шлеме.
    ///
    /// Держат её человеческие доли секунды, то есть десятки кадров, поэтому
    /// рядом с самим состоянием обязателен ФРОНТ: без него зажатая кнопка
    /// открывала бы и закрывала пульт по разу на кадр.
    pub меню: bool,
    pub меню_нажато: bool,
    /// Кнопка A (правый контроллер) или X (левый) — пульт клавиатуры.
    pub кнопка_а: bool,
    pub кнопка_а_нажата: bool,
    /// Кнопка B (правый) или Y (левый) — терминал одним нажатием.
    pub кнопка_б: bool,
    pub кнопка_б_нажата: bool,
    /// Щипок пальцами (hand tracking), когда контроллера нет.
    pub щипок: bool,
    pub щипок_нажат: bool,
    /// Щипок ОТПУСТИЛИ. Обязателен наравне с нажатием: щипком кликают, а клик
    /// без отпускания — это зажатая навсегда левая кнопка мыши.
    pub щипок_отпущен: bool,
    /// Щипок большим и СРЕДНИМ — тумблер пульта «Пуск» рукой.
    pub щипок_средний: bool,
    pub щипок_средний_нажат: bool,
    /// Щипок большим и БЕЗЫМЯННЫМ — тумблер клавиатуры рукой.
    pub щипок_безымянный: bool,
    pub щипок_безымянный_нажат: bool,
    /// Щипок большим и МИЗИНЦЕМ — самый труднодоступный из четырёх, поэтому на
    /// нём висит то, что случайно вызывать нельзя.
    pub щипок_мизинец: bool,
    pub щипок_мизинец_нажат: bool,
    /// Кулак: все четыре пальца согнуты, большой не поднят. Главный жест —
    /// именно им открывается пульт «Пуск». Засчитывается после выдержки.
    pub кулак: bool,
    pub кулак_нажат: bool,
    /// Пальцы сжаты ПРЯМО СЕЙЧАС, без выдержки. Нужен, чтобы отличить кулак
    /// одной руки от начала жеста «два кулака», — см. [`Ввод::жесты`].
    pub сжат: bool,
    /// «Палец вверх»: кулак, но большой вытянут и смотрит в потолок.
    pub большой_вверх: bool,
    pub большой_вверх_нажат: bool,
    /// Взмах раскрытой ладонью в эту сторону — засчитан ровно в одном кадре.
    pub свайп: Option<Сторона>,
    /// Стик отклонили до упора в эту сторону — тоже один кадр на отклонение.
    pub стик_щелчок: Option<Сторона>,
    /// Ладонь развёрнута вверх (жест «показать меню»), удерживается.
    pub ладонь_вверх: bool,
    pub ладонь_вверх_нажат: bool,
    /// Насколько ладонь смотрит вверх: +1 — строго вверх, −1 — строго вниз.
    /// Нужно измерителю (`vr input`): по этому числу видно, дотягивается ли
    /// жест до порога, и не перепутан ли знак нормали у рантайма.
    pub ладонь_вверх_мера: f32,
    /// Указку дала ладонь, а не контроллер. Отличать обязательно: иначе по
    /// одному «луч есть» не понять, работает ли отслеживание рук вообще.
    pub от_руки: bool,
    /// Расстояние большой–указательный, метры. Только для измерителя: по нему
    /// видно, дотягивается ли щипок до порога.
    pub щепоть_м: f32,
}

impl Рука {
    /// Луч из указки: вперёд по −Z, как договорено в OpenXR для `aim`.
    ///
    /// У руки направление приходит отдельным вектором и `−Z` не используется
    /// вовсе. Причина: ориентация сустава ладони задана спецификацией так, что
    /// её `−Z` НЕ совпадает с «куда показывает рука», и разные рантаймы
    /// расходятся в трактовке. Направление, посчитанное по двум ТОЧКАМ
    /// указательного пальца, ни от какой договорённости об осях не зависит.
    pub fn луч(&self) -> Option<Луч> {
        let п = self.указка?;
        let напр = match self.направление {
            Some(н) => н,
            None => п.поворот.повернуть(Век3::new(0.0, 0.0, -1.0)),
        };
        Some(Луч::new(п.место, напр))
    }
}

/// Набор действий и всё, что нужно, чтобы их читать.
pub struct Ввод {
    набор: xr::ActionSet,
    /// Действие-поза. После создания пространств его больше не читают, но
    /// держать обязаны: с уничтожением действия рантайм уносит и пространства,
    /// а с ними — луч указки.
    #[allow(dead_code)]
    указка: xr::Action<xr::Posef>,
    выбор: xr::Action<bool>,
    хват: xr::Action<bool>,
    меню: xr::Action<bool>,
    /// A/X — пульт клавиатуры, B/Y — терминал. Это и есть «бинды в шлеме»:
    /// открыть окно, не снимая шлем и не нащупывая клавиатуру на столе.
    кнопка_а: xr::Action<bool>,
    кнопка_б: xr::Action<bool>,
    стик_x: xr::Action<f32>,
    стик_y: xr::Action<f32>,
    пути: [xr::Path; 2],
    пространства: [xr::Space; 2],
    /// Отслеживание рук — есть не всегда.
    руки: Option<[xr::HandTracker; 2]>,
    /// Какой профиль рантайм привязал к каждой руке. Нужен не коду, а
    /// измерителю (`vr input`): «пусто» здесь — единственный способ отличить
    /// «контроллер не в руках» от «профиль не подошёл и действия молчат».
    профиль: [String; 2],
    /// Направление луча, замороженное на время щипка. Без него клик рукой
    /// промахивается всегда: щипок — это движение кончика указательного к
    /// большому, то есть сам жест уводит луч в тот момент, когда по нему
    /// кликают. Замок ставится, едва пальцы НАЧАЛИ сходиться (6 см), — раньше,
    /// чем щипок засчитан (2 см), иначе замирать было бы уже поздно.
    щепоть_замок: [Option<Век3>; 2],
    /// С какого момента ладонь держат вверх. Жест засчитывается только после
    /// выдержки: мгновенный порог срабатывал бы на каждом взмахе руки, и пульт
    /// выскакивал бы сам по себе.
    ладонь_с: [Option<std::time::Instant>; 2],
    /// С какого момента держат кулак. Выдержка та же и по той же причине, что у
    /// ладони: пальцы проходят через «почти кулак» в середине каждого щипка, и
    /// без выдержки пульт открывался бы от любого клика.
    кулак_с: [Option<std::time::Instant>; 2],
    /// Где была ладонь на прошлом кадре и когда — по этой паре считается
    /// скорость, а по ней взмах. Хранить обязательно: суставы приходят
    /// позициями, скорости среди них нет.
    ладонь_была: [Option<(Век3, std::time::Instant)>; 2],
    /// Когда рука в последний раз взмахнула. Пауза после взмаха нужна, чтобы
    /// одно движение не засчиталось трижды подряд: рука пересекает порог
    /// скорости на десятке кадров.
    свайп_когда: [Option<std::time::Instant>; 2],
    /// Стик был отклонён до упора — нужен для фронта: щелчок засчитывается
    /// один раз на отклонение, а не каждый кадр, пока стик держат.
    стик_упор: [Option<Сторона>; 2],
    /// Кулаки на обеих руках были в прошлом кадре (фронт «двух кулаков»).
    два_кулака: bool,
    /// Прошлое состояние кнопок: фронты считаем сами, рантайм отдаёт только
    /// `changed_since_last_sync`, а его на пропущенном кадре легко потерять.
    было: [Рука; 2],
    pub состояние: [Рука; 2],
}


/// Жесты ОДНОЙ руки за этот кадр. Вынесено из [`Ввод::жесты`] ради проверки:
/// собрать `Ввод` в тесте нельзя (внутри живые ручки рантайма), а соответствие
/// «кнопка ↔ жест» проверять надо — перепутанные A и B в шлеме обнаруживаются
/// только на себе.
pub fn жесты_руки(р: &Рука) -> Vec<Жест> {
    let mut из = Vec::new();
    if р.меню_нажато {
        из.push(Жест::КнопкаМеню);
    }
    if р.кнопка_а_нажата {
        из.push(Жест::КнопкаА);
    }
    if р.кнопка_б_нажата {
        из.push(Жест::КнопкаБ);
    }
    if let Some(с) = р.стик_щелчок {
        из.push(Жест::Стик(с));
    }
    if р.кулак_нажат {
        из.push(Жест::Кулак);
    }
    if р.большой_вверх_нажат {
        из.push(Жест::БольшойВверх);
    }
    if р.ладонь_вверх_нажат {
        из.push(Жест::ЛадоньВверх);
    }
    if р.щипок_средний_нажат {
        из.push(Жест::ЩипокСредним);
    }
    if р.щипок_безымянный_нажат {
        из.push(Жест::ЩипокБезымянным);
    }
    if р.щипок_мизинец_нажат {
        из.push(Жест::ЩипокМизинцем);
    }
    if let Some(с) = р.свайп {
        из.push(Жест::Свайп(с));
    }
    из
}

/// Левая рука — индекс 0, правая — 1. Заводим константы, чтобы по коду не
/// гадать, кто где.
pub const ЛЕВАЯ: usize = 0;
pub const ПРАВАЯ: usize = 1;

impl Ввод {
    pub fn поднять(
        instance: &xr::Instance,
        session: &xr::Session<Egl>,
    ) -> Result<Ввод, xr::sys::Result> {
        let набор = instance.create_action_set("parallax", "Windows in space", 0)?;
        let пути = [
            instance.string_to_path("/user/hand/left")?,
            instance.string_to_path("/user/hand/right")?,
        ];
        // ИМЕНА ДЕЙСТВИЙ — ТОЛЬКО ЛАТИНИЦА И БЕЗ ЗАГЛАВНЫХ. Спецификация
        // OpenXR разрешает в `actionName` лишь `a-z`, `0-9`, `-`, `_`, `.`, и
        // рантайм отвергает всё остальное целиком: замер на симуляторе Monado
        // дал `XR_ERROR_PATH_FORMAT_INVALID: 0xffffffd1 is not a valid
        // character at position 0` — это первая буква слова «указка». Второе
        // поле (localizedName) человеческое, вот там кириллица уместна: его
        // рантайм показывает в своих настройках привязок.
        let указка = набор.create_action::<xr::Posef>("aim", "Pointer", &пути)?;
        let выбор = набор.create_action::<bool>("select", "Select", &пути)?;
        let хват = набор.create_action::<bool>("grab", "Grab", &пути)?;
        let меню = набор.create_action::<bool>("menu", "Menu", &пути)?;
        let кнопка_а = набор.create_action::<bool>("btn_a", "Keyboard", &пути)?;
        let кнопка_б = набор.create_action::<bool>("btn_b", "Terminal", &пути)?;
        let стик_x = набор.create_action::<f32>("stick_x", "Stick horizontal", &пути)?;
        let стик_y = набор.create_action::<f32>("stick_y", "Stick vertical", &пути)?;

        // ── Привязки ────────────────────────────────────────────────────────
        // Профили перечислены от частного к общему: Touch (Quest 3, наш
        // случай), Index, и «простой контроллер» — тот, который обязан
        // поддерживать ЛЮБОЙ рантайм, включая симулятор Monado. Без последнего
        // проверить VR-режим без шлема было бы нечем.
        let mut ошибки = 0usize;
        for профиль in [
            "/interaction_profiles/oculus/touch_controller",
            "/interaction_profiles/valve_index_controller",
            "/interaction_profiles/khr/simple_controller",
        ] {
            let простой = профиль.ends_with("simple_controller");
            let путь_профиля = instance.string_to_path(профиль)?;
            let mut связки: Vec<xr::Binding> = Vec::new();
            for рука in ["/user/hand/left", "/user/hand/right"] {
                let p = |с: &str| instance.string_to_path(&format!("{рука}{с}"));
                связки.push(xr::Binding::new(&указка, p("/input/aim/pose")?));
                if простой {
                    // У «простого» контроллера всего две кнопки: select и menu.
                    связки.push(xr::Binding::new(&выбор, p("/input/select/click")?));
                    связки.push(xr::Binding::new(&меню, p("/input/menu/click")?));
                } else {
                    связки.push(xr::Binding::new(&выбор, p("/input/trigger/value")?));
                    связки.push(xr::Binding::new(&хват, p("/input/squeeze/value")?));
                    связки.push(xr::Binding::new(&стик_x, p("/input/thumbstick/x")?));
                    связки.push(xr::Binding::new(&стик_y, p("/input/thumbstick/y")?));
                    // Лицевые кнопки. У Touch они называются по-разному на
                    // разных руках (A/B справа, X/Y слева) и путь у каждой свой;
                    // у Index обе руки одинаковы — a/b. Привязываем ОДНО
                    // действие к обеим парам: человеку всё равно, какой рукой
                    // открывать клавиатуру, а помнить две разные кнопки —
                    // лишняя работа.
                    let левая = рука.ends_with("left");
                    let (кн_а, кн_б) = if профиль.contains("oculus") && левая {
                        ("/input/x/click", "/input/y/click")
                    } else {
                        ("/input/a/click", "/input/b/click")
                    };
                    связки.push(xr::Binding::new(&кнопка_а, p(кн_а)?));
                    связки.push(xr::Binding::new(&кнопка_б, p(кн_б)?));
                    // Нажатие на стик — ВТОРОЕ меню, и оно есть на обеих руках.
                    // Без него правый контроллер пульт не открывает вовсе:
                    // кнопка ☰ у Touch физически только на левом, и человек с
                    // правым контроллером в руке остаётся без «Пуска».
                    связки.push(xr::Binding::new(&меню, p("/input/thumbstick/click")?));
                }
            }
            // Отдельная кнопка ☰: у Touch она только на левом контроллере.
            if профиль.contains("oculus") {
                связки.push(xr::Binding::new(
                    &меню,
                    instance.string_to_path("/user/hand/left/input/menu/click")?,
                ));
            }
            if let Err(e) = instance.suggest_interaction_profile_bindings(путь_профиля, &связки) {
                // Не смертельно: рантайм вправе не знать профиль. Смертельно
                // было бы, если не подошёл НИ ОДИН — это видно по счётчику.
                tracing::debug!("plx/vr: profile {профиль} was not accepted: {e}");
                ошибки += 1;
            }
        }
        if ошибки >= 3 {
            tracing::warn!("plx/vr: the runtime accepted no controller profile at all");
        }

        session.attach_action_sets(&[&набор])?;

        let пространства = [
            указка.create_space(session, пути[0], xr::Posef::IDENTITY)?,
            указка.create_space(session, пути[1], xr::Posef::IDENTITY)?,
        ];

        // Руки — по возможности. Отсутствие расширения не ошибка: на Index и в
        // симуляторе рук нет вовсе.
        let руки = match (
            session.create_hand_tracker(xr::HandEXT::LEFT),
            session.create_hand_tracker(xr::HandEXT::RIGHT),
        ) {
            (Ok(л), Ok(п)) => {
                tracing::info!("plx/vr: hand tracking is available");
                Some([л, п])
            }
            _ => None,
        };

        Ok(Ввод {
            набор,
            указка,
            выбор,
            хват,
            меню,
            кнопка_а,
            кнопка_б,
            стик_x,
            стик_y,
            пути,
            пространства,
            руки,
            профиль: [String::new(), String::new()],
            щепоть_замок: [None; 2],
            ладонь_с: [None; 2],
            кулак_с: [None; 2],
            ладонь_была: [None; 2],
            свайп_когда: [None; 2],
            стик_упор: [None; 2],
            два_кулака: false,
            было: [Рука::default(); 2],
            состояние: [Рука::default(); 2],
        })
    }

    /// Профиль сменился (человек взял контроллер в руки или положил его).
    /// Действия рантайм перепривязывает сам; мы лишь запоминаем имя, чтобы его
    /// было видно в `vr input`.
    pub fn профиль_сменился(&mut self, instance: &xr::Instance, session: &xr::Session<Egl>) {
        for i in 0..2 {
            let имя = session
                .current_interaction_profile(self.пути[i])
                .ok()
                .and_then(|п| instance.path_to_string(п).ok())
                .unwrap_or_default();
            tracing::info!(
                "plx/vr: hand {i} → profile {}",
                if имя.is_empty() { "—" } else { &имя }
            );
            self.профиль[i] = имя;
        }
    }

    /// Отдаёт ли рантайм суставы рук (`XR_EXT_hand_tracking`).
    pub fn руки_есть(&self) -> bool {
        self.руки.is_some()
    }

    /// Имя профиля, привязанного к руке; пусто — рантайм не привязал ни один.
    pub fn профиль(&self, рука: usize) -> &str {
        &self.профиль[рука]
    }

    /// Прочитать состояние ввода на текущем кадре.
    /// `перед` — рыскание сцены (`Сцена::перед`): в какую сторону человек
    /// смотрит. По нему взмах рукой переводится из осей мира в «влево от
    /// меня»; без него один и тот же взмах менял бы смысл, стоит развернуть
    /// кресло.
    pub fn опросить(
        &mut self,
        session: &xr::Session<Egl>,
        сцена: &xr::Space,
        время: xr::Time,
        перед: f32,
    ) {
        if let Err(e) = session.sync_actions(&[(&self.набор).into()]) {
            // Пока сессия не в фокусе (человек в системном меню шлема),
            // sync_actions законно отвечает отказом — это не ошибка.
            tracing::trace!("plx/vr: sync_actions: {e}");
            return;
        }
        self.было = self.состояние;
        for i in 0..2 {
            let путь = self.пути[i];
            let mut р = Рука::default();

            // Поза указки. `is_active` важнее самой позы: у выключенного
            // контроллера рантайм возвращает последнюю известную, и луч
            // застревал бы в воздухе.
            if let Ok(место) = self.пространства[i].locate(сцена, время) {
                // Годность спрашиваем у САМОЙ локации, а не у состояния
                // действия: у позы (`Action<Posef>`) состояния в этом смысле
                // нет вовсе, а `TRACKED` — единственный честный признак, что
                // контроллер сейчас видно. Без `TRACKED` (только `VALID`)
                // рантайм отдаёт последнюю известную позу — луч бы застревал
                // в воздухе там, где контроллер положили.
                let ф = место.location_flags;
                let годна = ф.contains(xr::SpaceLocationFlags::ORIENTATION_TRACKED)
                    && ф.contains(xr::SpaceLocationFlags::POSITION_TRACKED);
                if годна {
                    р.указка = Some(поза_из_xr(место.pose));
                }
            }

            let бул = |д: &xr::Action<bool>| -> bool {
                д.state(session, путь).map(|с| с.current_state).unwrap_or(false)
            };
            let вещ = |д: &xr::Action<f32>| -> f32 {
                д.state(session, путь).map(|с| с.current_state).unwrap_or(0.0)
            };
            р.выбор = бул(&self.выбор);
            р.хват = бул(&self.хват);
            р.меню = бул(&self.меню);
            р.кнопка_а = бул(&self.кнопка_а);
            р.кнопка_б = бул(&self.кнопка_б);
            р.стик = (вещ(&self.стик_x), вещ(&self.стик_y));

            // Руки: щипок как замена курка. Порог 2 см с гистерезисом 1 см —
            // без гистерезиса щипок «дребезжит» на границе и клик уходит
            // очередями.
            if let Some(руки) = &self.руки {
                if let Ok(Some(суставы)) = сцена.locate_hand_joints(&руки[i], время) {
                    let большой = суставы[xr::HandJointEXT::THUMB_TIP.into_raw() as usize];
                    let указательный =
                        суставы[xr::HandJointEXT::INDEX_TIP.into_raw() as usize];
                    let a = поза_из_xr(большой.pose).место;
                    let b = поза_из_xr(указательный.pose).место;
                    let d = a.минус(b).длина();
                    let порог = if self.было[i].щипок { 0.03 } else { 0.02 };
                    р.щипок = d < порог;
                    р.щепоть_м = d;

                    // ── Жесты пультов ───────────────────────────────────────
                    //
                    // Щипок ДРУГИМИ пальцами: средним — «Пуск», безымянным —
                    // клавиатура. Взяты именно щипки, а не «поза руки», по
                    // одной причине: щипок — это расстояние между двумя
                    // точками, и он не зависит ни от того, как рантайм
                    // ориентирует суставы, ни от того, где человек держит
                    // руку. Спутать его со случайным движением нельзя: пальцы
                    // сходятся на два сантиметра только нарочно.
                    let кончик = |j: xr::HandJointEXT| -> Option<Век3> {
                        let с = суставы[j.into_raw() as usize];
                        с.location_flags
                            .contains(xr::SpaceLocationFlags::POSITION_TRACKED)
                            .then(|| поза_из_xr(с.pose).место)
                    };

                    // ── Согнутые пальцы, кулак и «палец вверх» ──────────────
                    let согнут_ли = |прокс: xr::HandJointEXT, тип: xr::HandJointEXT| {
                        let з = кончик(xr::HandJointEXT::WRIST)?;
                        let (п, т) = (кончик(прокс)?, кончик(тип)?);
                        Some(согнут(з, п, т))
                    };
                    let пальцы = [
                        (xr::HandJointEXT::INDEX_PROXIMAL, xr::HandJointEXT::INDEX_TIP),
                        (xr::HandJointEXT::MIDDLE_PROXIMAL, xr::HandJointEXT::MIDDLE_TIP),
                        (xr::HandJointEXT::RING_PROXIMAL, xr::HandJointEXT::RING_TIP),
                        (xr::HandJointEXT::LITTLE_PROXIMAL, xr::HandJointEXT::LITTLE_TIP),
                    ];
                    let согнутость: Vec<Option<bool>> =
                        пальцы.iter().map(|(п, т)| согнут_ли(*п, *т)).collect();
                    let все_согнуты = согнутость.iter().all(|с| *с == Some(true));
                    let все_разогнуты = согнутость.iter().all(|с| *с == Some(false));

                    // Большой вверх: сам палец вытянут (та же мера отношением) и
                    // смотрит в потолок. Y в пространстве сцены — вверх, поэтому
                    // достаточно взглянуть на направление «костяшка → кончик».
                    let большой_вверх = (|| -> Option<bool> {
                        let з = кончик(xr::HandJointEXT::WRIST)?;
                        let п = кончик(xr::HandJointEXT::THUMB_PROXIMAL)?;
                        let вытянут = a.минус(з).длина() > п.минус(з).длина() * 1.3;
                        let напр = a.минус(п);
                        Some(вытянут && напр.длина() > 1e-4 && напр.нормаль().y > 0.6)
                    })()
                    .unwrap_or(false);
                    р.большой_вверх = все_согнуты && большой_вверх;
                    // Кулак — это кулак БЕЗ поднятого большого: иначе «палец
                    // вверх» срабатывал бы вместе с ним, и человек, показавший
                    // «хорошо», получал бы ещё и пульт.
                    let сжат = все_согнуты && !большой_вверх;
                    р.сжат = сжат;
                    match (сжат, self.кулак_с[i]) {
                        (true, None) => self.кулак_с[i] = Some(std::time::Instant::now()),
                        (false, _) => self.кулак_с[i] = None,
                        _ => {}
                    }
                    р.кулак = self.кулак_с[i]
                        .is_some_and(|т| т.elapsed() > std::time::Duration::from_millis(250));
                    // Сжатый кулак сводит большой и указательный почти вплотную,
                    // и без этой строки каждое сжатие кулака давало бы ещё и
                    // клик левой кнопкой — по тому окну, куда смотрел луч.
                    if сжат {
                        р.щипок = false;
                    }

                    // ── Взмах раскрытой ладонью ─────────────────────────────
                    //
                    // Меряется скорость ладони между кадрами и переводится в
                    // оси человека: «вправо» — это вправо от направления, куда
                    // смотрит сцена. Требование раскрытой ладони отсекает
                    // главный источник ложных взмахов — руку, которую просто
                    // опустили или потянулись ею за мышью.
                    if let Some(ладонь_сейчас) = кончик(xr::HandJointEXT::PALM) {
                        let теперь = std::time::Instant::now();
                        if let Some((было, когда)) = self.ладонь_была[i] {
                            let dt = теперь.duration_since(когда).as_secs_f32();
                            // Кадр длиннее пятой доли секунды — это не кадр, а
                            // пропуск (шлем сняли, сессия ушла из фокуса);
                            // скорость по нему считать нельзя.
                            let отдыхает = self.свайп_когда[i].is_some_and(|т| {
                                т.elapsed() < std::time::Duration::from_millis(600)
                            });
                            if все_разогнуты && !отдыхает && (0.002..0.2).contains(&dt) {
                                let d = ладонь_сейчас.минус(было);
                                let вправо = Век3::new(перед.cos(), 0.0, -перед.sin());
                                let vx = (d.x * вправо.x + d.z * вправо.z) / dt;
                                let vy = d.y / dt;
                                // Порог 0.8 м/с: обычное движение руки к
                                // клавиатуре втрое медленнее, а нарочный взмах —
                                // вдвое быстрее.
                                let куда = сторона(vx, vy, 0.8);
                                if куда.is_some() {
                                    self.свайп_когда[i] = Some(теперь);
                                }
                                р.свайп = куда;
                            }
                        }
                        self.ладонь_была[i] = Some((ладонь_сейчас, теперь));
                    } else {
                        self.ладонь_была[i] = None;
                    }

                    if let Some(мизинец) = кончик(xr::HandJointEXT::LITTLE_TIP) {
                        let d = a.минус(мизинец).длина();
                        let порог = if self.было[i].щипок_мизинец { 0.03 } else { 0.02 };
                        р.щипок_мизинец = d < порог && !сжат;
                    }
                    if let Some(средний) = кончик(xr::HandJointEXT::MIDDLE_TIP) {
                        let d = a.минус(средний).длина();
                        let порог = if self.было[i].щипок_средний { 0.03 } else { 0.02 };
                        // `!сжат` — по той же причине, что и у щипка
                        // указательным: в кулаке большой лежит НА пальцах, и
                        // без этой оговорки одно сжатие кулака выдавало бы
                        // разом три щипка.
                        р.щипок_средний = d < порог && !сжат;
                    }
                    if let Some(безымянный) = кончик(xr::HandJointEXT::RING_TIP) {
                        let d = a.минус(безымянный).длина();
                        let порог = if self.было[i].щипок_безымянный { 0.03 } else { 0.02 };
                        р.щипок_безымянный = d < порог && !сжат;
                    }

                    // Ладонь вверх — «посмотреть на часы»: раскрытая ладонь,
                    // повёрнутая к лицу, вызывает «Пуск». Нормаль ладони по
                    // спецификации XR_EXT_hand_tracking — это +Y сустава PALM
                    // (он смотрит из ТЫЛЬНОЙ стороны кисти), поэтому ладонь
                    // вверх — это когда +Y смотрит ВНИЗ. Знак легко перепутать,
                    // и молча: жест просто не сработает ни разу. Поэтому сама
                    // мера кладётся в состояние и печатается в `vr input` —
                    // посмотреть на число и увидеть знак можно за один замер.
                    let ладонь = суставы[xr::HandJointEXT::PALM.into_raw() as usize];
                    if ладонь
                        .location_flags
                        .contains(xr::SpaceLocationFlags::ORIENTATION_TRACKED)
                    {
                        let вверх = поза_из_xr(ладонь.pose)
                            .поворот
                            .повернуть(Век3::new(0.0, 1.0, 0.0));
                        р.ладонь_вверх_мера = -вверх.y;
                        // Пальцы при этом должны быть разведены: щипок с
                        // повёрнутой ладонью — это всё-таки щипок.
                        let раскрыта = d > 0.06;
                        let держит = р.ладонь_вверх_мера > 0.75 && раскрыта;
                        match (держит, self.ладонь_с[i]) {
                            (true, None) => self.ладонь_с[i] = Some(std::time::Instant::now()),
                            (false, _) => self.ладонь_с[i] = None,
                            _ => {}
                        }
                        // Выдержка 0.4 с: взмах рукой её не наберёт, а
                        // осознанный жест — наберёт незаметно для человека.
                        р.ладонь_вверх = self.ладонь_с[i].is_some_and(|т| {
                            т.elapsed() > std::time::Duration::from_millis(400)
                        });
                    }
                    // Рука годится в указку, только если контроллера нет:
                    // держать и то и другое разом — верный способ получить два
                    // курсора.
                    if р.указка.is_none() {
                        // Целимся указательным пальцем: начало — костяшка,
                        // направление — на кончик. Обе точки годные, только
                        // если рантайм их действительно отслеживает; иначе
                        // палец «показывает» туда, где его видели последний
                        // раз.
                        let к = суставы
                            [xr::HandJointEXT::INDEX_PROXIMAL.into_raw() as usize];
                        let годны = |с: &xr::HandJointLocation| {
                            с.location_flags
                                .contains(xr::SpaceLocationFlags::POSITION_TRACKED)
                        };
                        let начало = поза_из_xr(к.pose);
                        let напр = b.минус(начало.место);
                        if годны(&к) && годны(&указательный) && напр.длина() > 1e-4 {
                            р.указка = Some(начало);
                            р.от_руки = true;
                            // Пока пальцы разведены (7 см и больше), храним
                            // живое направление; едва они пошли навстречу —
                            // перестаём обновлять, и луч стоит до конца жеста.
                            // Проверять надо именно «рука открыта», а не
                            // «щипок начался»: между кадрами зазор прыгает
                            // сразу на сантиметры, и ловить одно значение
                            // бесполезно.
                            let свежее = напр.нормаль();
                            if d > 0.07 {
                                self.щепоть_замок[i] = Some(свежее);
                            }
                            р.направление = Some(self.щепоть_замок[i].unwrap_or(свежее));
                        }
                    }
                }
            }

            р.выбор_нажат = р.выбор && !self.было[i].выбор;
            р.выбор_отпущен = !р.выбор && self.было[i].выбор;
            р.хват_нажат = р.хват && !self.было[i].хват;
            р.хват_отпущен = !р.хват && self.было[i].хват;
            р.щипок_нажат = р.щипок && !self.было[i].щипок;
            р.щипок_отпущен = !р.щипок && self.было[i].щипок;
            р.щипок_средний_нажат = р.щипок_средний && !self.было[i].щипок_средний;
            р.щипок_безымянный_нажат = р.щипок_безымянный && !self.было[i].щипок_безымянный;
            р.щипок_мизинец_нажат = р.щипок_мизинец && !self.было[i].щипок_мизинец;
            р.кулак_нажат = р.кулак && !self.было[i].кулак;
            р.большой_вверх_нажат = р.большой_вверх && !self.было[i].большой_вверх;
            р.ладонь_вверх_нажат = р.ладонь_вверх && !self.было[i].ладонь_вверх;
            // Щелчок стиком. Порог отклонения 0.7, возврат 0.4 — обычный
            // гистерезис: без него стик, оставленный у края, щёлкал бы очередями
            // на дрожании в доли миллиметра.
            let (стик_x, стик_y) = р.стик;
            let куда = match сторона(стик_x, стик_y, 0.7) {
                Some(с) => Some(с),
                // Между порогом и возвратом держим прежнюю сторону: это и есть
                // гистерезис.
                None if стик_x.abs().max(стик_y.abs()) >= 0.4 => self.стик_упор[i],
                None => None,
            };
            р.стик_щелчок = match (куда, self.стик_упор[i]) {
                (Some(с), было) if Some(с) != было => Some(с),
                _ => None,
            };
            self.стик_упор[i] = куда;
            р.меню_нажато = р.меню && !self.было[i].меню;
            р.кнопка_а_нажата = р.кнопка_а && !self.было[i].кнопка_а;
            р.кнопка_б_нажата = р.кнопка_б && !self.было[i].кнопка_б;
            self.состояние[i] = р;
        }
    }

    /// Что человек показал в этом кадре — кнопкой контроллера или рукой.
    ///
    /// Собрано в одном месте нарочно: у большинства действий ДВА пути —
    /// контроллером и жестом, — и держать это соответствие размазанным по
    /// вызывающему коду значит однажды завести кнопку без жеста или наоборот.
    /// Что каждый жест делает, решает [`Жест::по_умолчанию`] и `config.lua`.
    pub fn жесты(&mut self) -> Vec<Жест> {
        let mut из: Vec<Жест> = self.состояние.iter().flat_map(жесты_руки).collect();
        // Два кулака — жест ОБЕИХ рук, поэтому его фронт нельзя посчитать в
        // `жесты_руки`: там видно только одну руку.
        //
        // Одиночный кулак при этом обязан молчать, причём НАЧИНАЯ С ПЕРВОГО
        // сжатия: жест обеих рук засчитывается после выдержки, а без этой
        // оговорки за те же четверть секунды успел бы сработать одиночный, и
        // человек получил бы разом и «Пуск», и пересбор сцены. Поэтому смотрим
        // на сырое «пальцы сжаты», а не на выдержанный кулак.
        let сжаты = self.состояние.iter().all(|р| р.сжат);
        if сжаты {
            из.retain(|ж| *ж != Жест::Кулак);
        }
        let оба = self.состояние.iter().all(|р| р.кулак);
        if оба && !self.два_кулака {
            из.push(Жест::ДваКулака);
        }
        self.два_кулака = оба;
        из
    }

    /// Рука, которой человек сейчас работает: та, где нажат курок или щипок, а
    /// если обе спокойны — правая, если её видно.
    ///
    /// Курсор в parallax один, и «активная рука» — это ответ на вопрос, чей луч
    /// им управляет. Без такого правила две указки дрались бы за один курсор.
    pub fn ведущая(&self) -> Option<usize> {
        let активна = |i: usize| {
            let р = &self.состояние[i];
            р.указка.is_some() && (р.выбор || р.хват || р.щипок)
        };
        if активна(ПРАВАЯ) {
            return Some(ПРАВАЯ);
        }
        if активна(ЛЕВАЯ) {
            return Some(ЛЕВАЯ);
        }
        if self.состояние[ПРАВАЯ].указка.is_some() {
            return Some(ПРАВАЯ);
        }
        if self.состояние[ЛЕВАЯ].указка.is_some() {
            return Some(ЛЕВАЯ);
        }
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::vr::math::Кватернион;

    fn близко(a: f32, b: f32) -> bool {
        (a - b).abs() < 1e-5
    }

    /// У контроллера направление берётся из поворота позы — это договорённость
    /// OpenXR про `aim`, и ломать её нельзя.
    #[test]
    fn контроллер_целится_по_минус_z() {
        let р = Рука {
            указка: Some(Поза {
                место: Век3::new(1.0, 2.0, 3.0),
                поворот: Кватернион::ЕДИНИЦА,
            }),
            ..Рука::default()
        };
        let л = р.луч().expect("луч есть");
        assert!(близко(л.начало.x, 1.0) && близко(л.начало.y, 2.0));
        assert!(близко(л.направление.z, -1.0), "{:?}", л.направление);
    }

    /// А у руки — из отдельного вектора, посчитанного по двум суставам, и
    /// поворот позы при этом не участвует вовсе.
    #[test]
    fn рука_целится_своим_направлением_мимо_поворота() {
        let р = Рука {
            указка: Some(Поза {
                место: Век3::new(0.0, 1.0, 0.0),
                поворот: Кватернион::ЕДИНИЦА,
            }),
            // Намеренно ненормированный: `Луч::new` обязан нормировать сам.
            направление: Some(Век3::new(5.0, 0.0, 0.0)),
            от_руки: true,
            ..Рука::default()
        };
        let л = р.луч().expect("луч есть");
        assert!(близко(л.направление.x, 1.0), "{:?}", л.направление);
        assert!(близко(л.направление.z, 0.0), "{:?}", л.направление);
    }

    /// Без указки луча нет — на этом держится «контроллер положили на стол».
    #[test]
    fn без_указки_луча_нет() {
        assert!(Рука::default().луч().is_none());
    }

    /// У каждого жеста — своя дорога, и кнопка с рукой обязаны вести в одно
    /// место.
    #[test]
    fn кнопки_и_жесты_дают_одно_и_то_же() {
        let проверить = |р: Рука, ждём: Жест| {
            assert_eq!(жесты_руки(&р), vec![ждём], "{:?}", р);
        };
        проверить(Рука { меню_нажато: true, ..Рука::default() }, Жест::КнопкаМеню);
        проверить(Рука { кулак_нажат: true, ..Рука::default() }, Жест::Кулак);
        проверить(Рука { ладонь_вверх_нажат: true, ..Рука::default() }, Жест::ЛадоньВверх);
        проверить(Рука { кнопка_а_нажата: true, ..Рука::default() }, Жест::КнопкаА);
        проверить(
            Рука { щипок_безымянный_нажат: true, ..Рука::default() },
            Жест::ЩипокБезымянным,
        );
        проверить(Рука { кнопка_б_нажата: true, ..Рука::default() }, Жест::КнопкаБ);
        проверить(
            Рука { свайп: Some(Сторона::Влево), ..Рука::default() },
            Жест::Свайп(Сторона::Влево),
        );
        проверить(
            Рука { стик_щелчок: Some(Сторона::Вверх), ..Рука::default() },
            Жест::Стик(Сторона::Вверх),
        );
        // Спокойные руки не показывают ничего: жест, срабатывающий сам по себе,
        // хуже отсутствующего.
        assert!(жесты_руки(&Рука::default()).is_empty());
        // И удержание — тоже: жесты считаются по ФРОНТУ, иначе зажатая кнопка
        // меню открывала бы и закрывала пульт по разу на кадр.
        let зажата = Рука { меню: true, кулак: true, ..Рука::default() };
        assert!(жесты_руки(&зажата).is_empty());
    }

    /// Взмах и стик считают сторону одним правилом, и «наискосок» достаётся
    /// той составляющей, что больше, — иначе одно движение засчиталось бы в две
    /// стороны разом.
    #[test]
    fn сторона_по_большей_составляющей() {
        assert_eq!(сторона(1.0, 0.0, 0.7), Some(Сторона::Вправо));
        assert_eq!(сторона(-1.0, 0.0, 0.7), Some(Сторона::Влево));
        assert_eq!(сторона(0.0, 1.0, 0.7), Some(Сторона::Вверх));
        assert_eq!(сторона(0.0, -1.0, 0.7), Some(Сторона::Вниз));
        // Наискосок с перевесом вбок — это «вбок».
        assert_eq!(сторона(0.9, 0.75, 0.7), Some(Сторона::Вправо));
        // Ниже порога — не жест вовсе: рука дрожит всегда.
        assert_eq!(сторона(0.5, -0.4, 0.7), None);
    }

    /// Согнутость меряется отношением к костяшке: кулак ребёнка и кулак
    /// взрослого обязаны читаться одинаково.
    #[test]
    fn согнутость_не_зависит_от_размера_руки() {
        for размер in [0.6f32, 1.0, 1.6] {
            let з = Век3::new(0.0, 0.0, 0.0);
            let костяшка = Век3::new(0.0, 0.08 * размер, 0.0);
            // Разогнутый палец уходит от запястья вдвое дальше костяшки.
            let прямой = Век3::new(0.0, 0.16 * размер, 0.0);
            // Согнутый — заворачивается обратно к ладони.
            let сжатый = Век3::new(0.0, 0.06 * размер, 0.03 * размер);
            assert!(!согнут(з, костяшка, прямой), "размер {размер}");
            assert!(согнут(з, костяшка, сжатый), "размер {размер}");
        }
    }

    /// Кнопка ☰ и кулак ведут в одно действие — пульт «Пуск»; клавиатура своя,
    /// и ни один жест по умолчанию ничего не закрывает и не убивает.
    #[test]
    fn у_каждого_жеста_есть_имя_и_действие() {
        use crate::config::Action;
        let mut имена = std::collections::HashSet::new();
        for ж in Жест::все() {
            assert!(имена.insert(ж.имя()), "имя {} встречается дважды", ж.имя());
            // Разрушающих действий в раскладке по умолчанию быть не должно:
            // жест ошибается чаще клавиши.
            assert!(
                !matches!(ж.по_умолчанию(), Action::Kill | Action::Quit),
                "{} по умолчанию делает нечто необратимое",
                ж.имя()
            );
        }
        assert!(matches!(Жест::Кулак.по_умолчанию(), Action::VrLauncher));
        assert!(matches!(Жест::КнопкаМеню.по_умолчанию(), Action::VrLauncher));
        assert!(matches!(Жест::КнопкаА.по_умолчанию(), Action::VrKeyboard));
    }
}
