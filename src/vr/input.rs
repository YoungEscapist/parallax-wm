//! Ввод в шлеме: контроллеры-указки, щипок рукой и всё, что от них требуется.
//!
//! **Три способа управлять окнами, и все три равноправны.**
//!
//! 1. **Клавиатура и мышь.** Ничего нового: parallax отдаёт события клиентам как
//!    обычно, а мышь ездит по той панели, на которую смотрит человек (см.
//!    `mod.rs`). Все существующие бинды работают в шлеме без изменений — это
//!    осознанно главный способ: печатать в VR всё равно приходится на железной
//!    клавиатуре.
//! 2. **Контроллеры Touch как указки.** Из контроллера выходит луч; курок
//!    (`select`) — это левая кнопка мыши, хват (`squeeze`) — перетаскивание
//!    панели, стик — размер и расстояние.
//! 3. **Руки.** `XR_EXT_hand_tracking`: целится указательный палец, щипок
//!    большого и указательного — клик (он же выбор окна). Работает там, где
//!    рантайм отдаёт суставы; на Quest 3 через WiVRn отдаёт.
//!
//! **Жесты — это действия parallax, а не «функции VR».** Кулак, взмах ладонью,
//! щелчок стиком и лицевые кнопки дают один и тот же результат: имя жеста
//! (`fist`, `swipe_left`, …) превращается в обычное действие `bind{}` — через
//! `vr{ gestures = … }` в `config.lua`, а без него через
//! [`Жест::по_умолчанию`]. Поэтому «добавить жесту функцию parallax» — это строчка
//! в конфиге, а не правка здесь. Полная раскладка видна командой
//! `plxctl vr gestures`.
//!
//! **Почему действия (`XrAction`), а не «прочитать кнопку».** В OpenXR нет
//! чтения кнопок: приложение объявляет действия («выбрать», «схватить»), даёт
//! предлагаемые привязки для известных ему контроллеров, а рантайм сам решает,
//! какая физическая кнопка их даст. Благодаря этому тот же код работает и на
//! Touch, и на Index, и на симуляторе.
//!
//! **Грабля, стоившая бы вечера.** Привязки предлагаются ДО
//! `xrAttachSessionActionSets`, а тот делается ОДИН раз за жизнь сессии. Забыть
//! порядок — значит получить действия, которые молча всегда возвращают ноль:
//! ни ошибки, ни предупреждения.

