//! Жесты шлема как ЗНАЧЕНИЯ — без единой строчки OpenXR.
//!
//! Вынесено из `vr/input.rs` ради сборки `plx-standard`: `config.lua` разбирает
//! таблицу `vr{ gestures = … }` ВСЕГДА, в обеих сборках, и список жестов с их
//! именами обязан быть один и тот же — иначе один и тот же конфиг ругался бы на
//! неизвестный ключ в минимальной сборке и молчал в полной. Всё, что умеет
//! РАСПОЗНАВАТЬ эти жесты (руки, контроллеры, рантайм), осталось в `input.rs`
//! и собирается только с фичей `vr`.

/// Куда взмахнули рукой или отклонили стик. Стороны считаются в системе
/// ЧЕЛОВЕКА, а не мира: «влево» — это влево от того направления, куда смотрит
/// сцена (`Сцена::перед`). Иначе один и тот же взмах означал бы разное в
/// зависимости от того, куда человек развернул кресло.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Сторона {
    Влево,
    Вправо,
    Вверх,
    Вниз,
}

/// Жест или кнопка, сработавшая в этом кадре.
///
/// Что жест ДЕЛАЕТ, здесь не решается: имя (`имя()`) уходит в `config.lua`
/// (`vr{ gestures = … }`), а если человек его не переопределил — берётся
/// [`Жест::по_умолчанию`]. Так любой жест в шлеме — это обычное действие parallax,
/// ровно то же самое, что вешается на клавиши в `bind{}`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Жест {
    // ── Контроллер ──────────────────────────────────────────────────────────
    /// Кнопка ☰ (Touch: левый контроллер) и нажатие на стик.
    КнопкаМеню,
    /// A / X.
    КнопкаА,
    /// B / Y.
    КнопкаБ,
    /// Стик отклонили до упора.
    Стик(Сторона),
    // ── Рука ────────────────────────────────────────────────────────────────
    /// Кулак — все четыре пальца сжаты.
    Кулак,
    /// Кулаки на ОБЕИХ руках сразу.
    ДваКулака,
    /// Большой палец вверх.
    БольшойВверх,
    /// Раскрытая ладонь повёрнута к лицу и держится.
    ЛадоньВверх,
    /// Щипок большим и средним / безымянным / мизинцем. Щипок УКАЗАТЕЛЬНЫМ
    /// сюда не входит: он — левая кнопка мыши, и на действие его вешать нельзя.
    ЩипокСредним,
    ЩипокБезымянным,
    ЩипокМизинцем,
    /// Взмах раскрытой ладонью.
    Свайп(Сторона),
}

impl Жест {
    /// Имя для `config.lua`. Латиницей и через подчёркивание, как остальные
    /// ключи конфига.
    pub fn имя(self) -> &'static str {
        use Сторона::*;
        match self {
            Жест::КнопкаМеню => "menu_button",
            Жест::КнопкаА => "button_a",
            Жест::КнопкаБ => "button_b",
            Жест::Стик(Влево) => "stick_left",
            Жест::Стик(Вправо) => "stick_right",
            Жест::Стик(Вверх) => "stick_up",
            Жест::Стик(Вниз) => "stick_down",
            Жест::Кулак => "fist",
            Жест::ДваКулака => "two_fists",
            Жест::БольшойВверх => "thumb_up",
            Жест::ЛадоньВверх => "palm_up",
            Жест::ЩипокСредним => "pinch_middle",
            Жест::ЩипокБезымянным => "pinch_ring",
            Жест::ЩипокМизинцем => "pinch_little",
            Жест::Свайп(Влево) => "swipe_left",
            Жест::Свайп(Вправо) => "swipe_right",
            Жест::Свайп(Вверх) => "swipe_up",
            Жест::Свайп(Вниз) => "swipe_down",
        }
    }

    /// Все жесты по порядку — для `vr input` и для проверки, что у каждого есть
    /// и имя, и действие по умолчанию.
    pub fn все() -> [Жест; 18] {
        use Сторона::*;
        [
            Жест::КнопкаМеню,
            Жест::КнопкаА,
            Жест::КнопкаБ,
            Жест::Стик(Влево),
            Жест::Стик(Вправо),
            Жест::Стик(Вверх),
            Жест::Стик(Вниз),
            Жест::Кулак,
            Жест::ДваКулака,
            Жест::БольшойВверх,
            Жест::ЛадоньВверх,
            Жест::ЩипокСредним,
            Жест::ЩипокБезымянным,
            Жест::ЩипокМизинцем,
            Жест::Свайп(Влево),
            Жест::Свайп(Вправо),
            Жест::Свайп(Вверх),
            Жест::Свайп(Вниз),
        ]
    }

    /// Что жест делает, пока его не переназначили в `config.lua`.
    ///
    /// **Правило раскладки.** Легко попадающие жесты (кулак, кнопка меню) —
    /// самые частые действия: пульт и клавиатура. Труднодоступные (мизинец,
    /// два кулака) — то, что случайно вызывать нельзя: passthrough и пересбор
    /// сцены. Ничего разрушающего (`kill`, `quit`) по умолчанию нет вовсе:
    /// жест ошибается чаще клавиши, и цена ошибки должна быть нулевой.
    pub fn по_умолчанию(self) -> crate::config::Action {
        use crate::config::Action as Д;
        use Сторона::*;
        match self {
            // Пульт «Пуск» — кулаком и кнопкой ☰: два самых простых движения.
            Жест::Кулак | Жест::КнопкаМеню | Жест::ЛадоньВверх => Д::VrLauncher,
            // Клавиатура — A/X и щипок безымянным (как было и раньше).
            Жест::КнопкаА | Жест::ЩипокБезымянным => Д::VrKeyboard,
            // Терминал — B/Y.
            Жест::КнопкаБ => Д::Spawn("foot".into()),
            // Рабочие столы — вбок: и стиком, и взмахом ладони.
            Жест::Стик(Влево) | Жест::Свайп(Влево) => Д::WorkspaceStep(-1),
            Жест::Стик(Вправо) | Жест::Свайп(Вправо) => Д::WorkspaceStep(1),
            // Вверх — обзор столов, вниз — свести камеру на окно в фокусе.
            Жест::Стик(Вверх) | Жест::Свайп(Вверх) | Жест::ЩипокСредним => Д::ToggleOverview,
            Жест::Стик(Вниз) | Жест::Свайп(Вниз) => Д::CenterWindow,
            // Окно на весь экран — «палец вверх».
            Жест::БольшойВверх => Д::ToggleFullscreen,
            // Комната вместо пустоты — мизинцем.
            Жест::ЩипокМизинцем => Д::VrAr,
            // Собрать панели заново вокруг взгляда — двумя кулаками.
            Жест::ДваКулака => Д::VrRecenter,
        }
    }
}
