//! Сцена: где в комнате висят окна.
//!
//! **Что такое «выделенная шлему зона».** У Quest 3 (и любого шлема с
//! охраняемой границей) рантайм отдаёт прямоугольник пола — `xrGetReference
//! SpaceBoundsRect` для `STAGE`. Это и есть зона, в которой человек может
//! ходить, и именно её dawn берёт за рабочее пространство: панели расставляются
//! по её краю, а таскать их за границу нельзя — окно, уехавшее сквозь стену,
//! человек уже не достанет.
//!
//! Зоны может не быть (шлем не настроен, симулятор, сидячий режим). Тогда
//! берётся круг радиуса [`Зона::РАДИУС_ПО_УМОЛЧАНИЮ`] вокруг человека — то же
//! самое, только без прямых углов.
//!
//! **Модель.** Одно окно — одна панель. Панель это прямоугольник в метрах с
//! позой (место + поворот) и текстурой содержимого. Раскладка (`Раскладка`)
//! решает, где стоят НЕЗАКРЕПЛЁННЫЕ панели; закреплённые (те, что человек
//! перетащил руками) не трогает никто — иначе следующий же кадр возвращал бы
//! окно на место, и перетаскивания не существовало бы.
//!
//! **Почему сцена ничего не знает ни про `Window`, ни про smithay.** Ключ
//! окна — просто `u64` (см. `mod.rs::ключ_окна`), размер — пиксели. Благодаря
//! этому весь расчёт мест проверяется обычными тестами, без композитора, шлема
//! и GL: ровно тот приём, которым в dawn уже проверялся тайлинг (см.
//! `dwindle.rs`).

use super::math::{Век3, Кватернион, Луч, Поза};

/// Ключ окна в сцене — стабильный номер, выданный ему при первой встрече.
pub type Ключ = u64;

/// Размер зоны, в которой живут панели.
#[derive(Debug, Clone, Copy)]
pub struct Зона {
    /// Половина ширины (X) и половина глубины (Z) прямоугольника зоны, метры.
    /// У круглой зоны оба равны радиусу.
    pub пол_ширина: f32,
    pub пол_глубина: f32,
    /// Прямоугольная зона пришла от рантайма; круглая — наша выдумка.
    pub от_шлема: bool,
}

impl Зона {
    /// Радиус зоны, когда рантайм её не знает. Полтора метра — вытянутая рука
    /// плюс запас: дальше панель не достать контроллером, ближе она давит.
    pub const РАДИУС_ПО_УМОЛЧАНИЮ: f32 = 1.6;

    pub fn круглая(радиус: f32) -> Зона {
        Зона { пол_ширина: радиус, пол_глубина: радиус, от_шлема: false }
    }

    pub fn прямоугольная(ширина: f32, глубина: f32) -> Зона {
        Зона {
            пол_ширина: (ширина * 0.5).max(0.5),
            пол_глубина: (глубина * 0.5).max(0.5),
            от_шлема: true,
        }
    }

    /// Радиус, на котором стоят панели: чуть внутри зоны, чтобы окно не
    /// оказалось в стене, но не ближе полуметра — вплотную к лицу читать нельзя.
    pub fn рабочий_радиус(&self) -> f32 {
        let наименьший = self.пол_ширина.min(self.пол_глубина);
        (наименьший * 0.8).clamp(0.6, 3.0)
    }

    /// Зажать точку внутри зоны (с запасом на половину панели).
    pub fn зажать(&self, p: Век3, запас: f32) -> Век3 {
        let ш = (self.пол_ширина - запас).max(0.2);
        let г = (self.пол_глубина - запас).max(0.2);
        Век3::new(p.x.clamp(-ш, ш), p.y.clamp(0.2, 3.0), p.z.clamp(-г, г))
    }
}

impl Default for Зона {
    fn default() -> Self {
        Зона::круглая(Зона::РАДИУС_ПО_УМОЛЧАНИЮ)
    }
}

/// Как расставлять незакреплённые панели.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Раскладка {
    /// Дуга вокруг человека на уровне глаз — рабочий стол «полукругом».
    /// Это и есть поведение по умолчанию: так окна видно, не поворачиваясь
    /// всем телом.
    Дуга,
    /// Плоская стена перед человеком. Ближе к привычному монитору: удобно,
    /// когда окна — текст, и кривизна дуги мешает читать край.
    Стена,
    /// Два-три яруса дуги: когда окон больше, чем влезает в один ряд.
    Купол,
    /// Ничего не расставлять: все панели там, где их поставили руками.
    Свободно,
}

impl Раскладка {
    pub fn имя(self) -> &'static str {
        match self {
            Раскладка::Дуга => "дуга",
            Раскладка::Стена => "стена",
            Раскладка::Купол => "купол",
            Раскладка::Свободно => "свободно",
        }
    }

    pub fn следующая(self) -> Раскладка {
        match self {
            Раскладка::Дуга => Раскладка::Стена,
            Раскладка::Стена => Раскладка::Купол,
            Раскладка::Купол => Раскладка::Свободно,
            Раскладка::Свободно => Раскладка::Дуга,
        }
    }
}

/// Окно, каким его видит сцена.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ОкноВСцене {
    pub ключ: Ключ,
    /// Размер содержимого в пикселях — из него берётся пропорция панели.
    pub ширина_пкс: i32,
    pub высота_пкс: i32,
}

/// Панель — окно, повешенное в комнате.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Панель {
    pub ключ: Ключ,
    pub поза: Поза,
    /// Полуразмеры в метрах: так удобнее и рисовать (quad от −1 до 1), и
    /// пересекать лучом.
    pub пол_ширина: f32,
    pub пол_высота: f32,
    pub ширина_пкс: i32,
    pub высота_пкс: i32,
    /// Поставлена руками — раскладка её не двигает.
    pub закреплена: bool,
}

impl Панель {
    /// Точка попадания луча в пикселях окна: (0,0) — левый верхний угол, как
    /// во всём остальном dawn.
    ///
    /// Панель в своих координатах идёт от −пол_ширина до +пол_ширина слева
    /// направо и от −пол_высота до +пол_высота СНИЗУ ВВЕРХ (мир — правая
    /// тройка, Y вверх), а пиксели окна растут вниз. Отсюда переворот по Y,
    /// и это ровно то место, где его легко забыть: клик тогда попадает
    /// зеркально по вертикали.
    pub fn в_пиксели(&self, местная_x: f32, местная_y: f32) -> (f64, f64) {
        let u = (местная_x / self.пол_ширина + 1.0) * 0.5;
        let v = 1.0 - (местная_y / self.пол_высота + 1.0) * 0.5;
        (
            (u as f64) * self.ширина_пкс as f64,
            (v as f64) * self.высота_пкс as f64,
        )
    }
}

/// Вся расстановка целиком.
#[derive(Debug, Clone)]
pub struct Сцена {
    pub панели: Vec<Панель>,
    pub раскладка: Раскладка,
    pub зона: Зона,
    /// Сколько метров в одном пикселе окна при обычном размере панели.
    ///
    /// 0.0008 м/пкс — это окно 1920 пикселей шириной в полтора метра, стоящее
    /// в метре с небольшим: примерно то же угловое разрешение, что у монитора
    /// на столе. Дальше человек масштабирует панели сам.
    pub метров_на_пиксель: f32,
    /// Высота центра дуги над полом. Полтора метра — глаза стоящего человека;
    /// у сидящего рантайм всё равно отдаёт свою высоту головы, а панели
    /// подстраиваются вокруг неё (см. `разложить`).
    pub высота_глаз: f32,
    /// Куда смотрит человек «по умолчанию» — рыскание в радианах. Дуга
    /// строится вокруг этого направления, чтобы окна оказались перед лицом, а
    /// не за спиной, куда бы человек ни повернулся при входе в VR.
    pub перед: f32,
    /// Просьба взять `перед` и `высота_глаз` из позы головы на ближайшем кадре.
    ///
    /// Якорь снимается ровно в двух случаях — вход в VR и явный пересбор
    /// (`vr_recenter`, смена раскладки). Обновлять его каждым кадром нельзя:
    /// панели поехали бы за головой (приседаешь — приседают и они), а именно
    /// неподвижность и делает их «окнами в комнате», а не забралом.
    pub нужен_якорь: bool,
}

impl Default for Сцена {
    fn default() -> Self {
        Сцена {
            панели: Vec::new(),
            раскладка: Раскладка::Дуга,
            зона: Зона::default(),
            метров_на_пиксель: 0.0008,
            высота_глаз: 1.5,
            перед: 0.0,
            нужен_якорь: true,
        }
    }
}

impl Сцена {
    /// Свести список окон композитора со списком панелей.
    ///
    /// Панели исчезнувших окон убираются, новым заводятся, у оставшихся
    /// сохраняется поза (в том числе закреплённая). Порядок панелей — порядок
    /// окон: он задаёт и порядок в раскладке, и то, какая панель «первая».
    pub fn свести(&mut self, окна: &[ОкноВСцене]) {
        let старые = std::mem::take(&mut self.панели);
        // Считаем в локальный список, а не прямо в `self.панели`: расчёт
        // читает саму сцену (масштаб, метры на пиксель), и запись в поле по
        // ходу чтения — это ровно то, что borrow checker и не пропускает.
        let новые: Vec<Панель> = окна
            .iter()
            .map(|о| {
                let (пол_ш, пол_в) = self.полуразмеры(о.ширина_пкс, о.высота_пкс);
                match старые.iter().find(|п| п.ключ == о.ключ) {
                    Some(п) => Панель {
                        ключ: о.ключ,
                        поза: п.поза,
                        // Размер пересчитываем всегда: окно могло изменить
                        // размер (ресайз, полный экран), и панель обязана
                        // остаться той же формы, что и содержимое, — иначе
                        // картинка растянется, а клики поедут.
                        пол_ширина: пол_ш * п.масштаб_к(self),
                        пол_высота: пол_в * п.масштаб_к(self),
                        ширина_пкс: о.ширина_пкс,
                        высота_пкс: о.высота_пкс,
                        закреплена: п.закреплена,
                    },
                    None => Панель {
                        ключ: о.ключ,
                        поза: Поза::default(),
                        пол_ширина: пол_ш,
                        пол_высота: пол_в,
                        ширина_пкс: о.ширина_пкс,
                        высота_пкс: о.высота_пкс,
                        закреплена: false,
                    },
                }
            })
            .collect();
        self.панели = новые;
    }

    fn полуразмеры(&self, ш: i32, в: i32) -> (f32, f32) {
        let ш = (ш.max(1) as f32) * self.метров_на_пиксель * 0.5;
        let в = (в.max(1) as f32) * self.метров_на_пиксель * 0.5;
        (ш.max(0.05), в.max(0.05))
    }

    /// Расставить незакреплённые панели по текущей раскладке.
    ///
    /// `голова` — поза головы: из неё берётся высота глаз и направление
    /// «перед». Дуга строится вокруг ТЕКУЩЕГО направления взгляда только при
    /// явном пересборе (`перед` обновляет вызывающий), иначе окна ездили бы за
    /// каждым поворотом головы — самая частая ошибка в самодельных VR-оболочках.
    pub fn разложить(&mut self) {
        let свободные: Vec<usize> = self
            .панели
            .iter()
            .enumerate()
            .filter(|(_, п)| !п.закреплена)
            .map(|(i, _)| i)
            .collect();
        if свободные.is_empty() {
            return;
        }
        match self.раскладка {
            Раскладка::Свободно => {
                // Даже здесь новорождённой панели надо где-то появиться:
                // ставим её перед человеком, иначе окно откроется в точке
                // (0,0,0) — то есть у него в животе.
                let радиус = self.зона.рабочий_радиус();
                for &i in &свободные {
                    if self.панели[i].поза == Поза::default() {
                        let п = &mut self.панели[i];
                        п.поза = поза_на_дуге(self.перед, радиус, self.высота_глаз);
                        п.закреплена = true;
                    }
                }
            }
            Раскладка::Дуга => self.разложить_дугой(&свободные, 0),
            Раскладка::Стена => self.разложить_стеной(&свободные),
            Раскладка::Купол => {
                // Ярусы по три панели: выше — дальше от центра по вертикали.
                let на_ярус = 3;
                for (ярус, кусок) in свободные.chunks(на_ярус).enumerate() {
                    self.разложить_дугой(кусок_как_вектор(кусок).as_slice(), ярус as i32);
                }
            }
        }
    }

    /// Дуга: панели стоят на одном радиусе, вплотную друг к другу по угловому
    /// размеру, и каждая развёрнута лицом в центр.
    ///
    /// `ярус` сдвигает дугу по высоте (0 — на уровне глаз, 1 — выше, −1 — ниже).
    fn разложить_дугой(&mut self, кто: &[usize], ярус: i32) {
        let радиус = self.зона.рабочий_радиус();
        // Угловая ширина каждой панели плюс зазор в 2°.
        let зазор = 2.0f32.to_radians();
        let углы: Vec<f32> = кто
            .iter()
            .map(|&i| {
                let п = &self.панели[i];
                2.0 * (п.пол_ширина / радиус).atan() + зазор
            })
            .collect();
        let всего: f32 = углы.iter().sum();
        let mut текущий = self.перед + всего * 0.5;
        // Высота яруса: панели верхнего ряда чуть наклонены вниз, нижнего —
        // вверх, чтобы смотреть на них не выворачивая шею.
        let высота = self.высота_глаз + ярус as f32 * 0.55;
        let наклон = -(ярус as f32) * 18.0f32.to_radians();
        for (k, &i) in кто.iter().enumerate() {
            let ширина_угла = углы[k];
            let центр = текущий - ширина_угла * 0.5;
            текущий -= ширина_угла;
            let mut поза = поза_на_дуге(центр, радиус, высота);
            поза.поворот = поза.поворот.умножить(Кватернион::вокруг_x(наклон));
            self.панели[i].поза = поза;
        }
    }

    /// Стена: сетка перед человеком, все панели в одной плоскости.
    fn разложить_стеной(&mut self, кто: &[usize]) {
        let радиус = self.зона.рабочий_радиус();
        // Направление «перед» и «вправо» на плоскости пола.
        let вперёд = Век3::new(-self.перед.sin(), 0.0, -self.перед.cos());
        let вправо = Век3::new(self.перед.cos(), 0.0, -self.перед.sin());
        let в_ряд = (кто.len() as f32).sqrt().ceil().max(1.0) as usize;
        let зазор = 0.06;
        // Считаем ширину каждого ряда, чтобы центрировать его.
        for (номер_ряда, ряд) in кто.chunks(в_ряд).enumerate() {
            let ширина: f32 = ряд
                .iter()
                .map(|&i| self.панели[i].пол_ширина * 2.0 + зазор)
                .sum();
            let высота_ряда = ряд
                .iter()
                .map(|&i| self.панели[i].пол_высота * 2.0)
                .fold(0.0f32, f32::max);
            let mut x = -ширина * 0.5;
            let y = self.высота_глаз - номер_ряда as f32 * (высота_ряда + зазор);
            for &i in ряд {
                let п = &self.панели[i];
                let сдвиг = x + п.пол_ширина;
                x += п.пол_ширина * 2.0 + зазор;
                let место = (вправо * сдвиг)
                    .плюс(вперёд * радиус)
                    .плюс(Век3::new(0.0, y, 0.0));
                self.панели[i].поза = Поза {
                    место,
                    поворот: Кватернион::вокруг_y(self.перед),
                };
            }
        }
    }

    /// Во что целится луч. Возвращает индекс панели и точку в пикселях окна.
    ///
    /// Ближайшая по лучу — та, что перекрывает остальные; именно она и должна
    /// получать клик, ровно как окно сверху в обычном композиторе.
    pub fn навести(&self, луч: Луч) -> Option<(usize, f64, f64)> {
        let mut лучшая: Option<(usize, f32, f64, f64)> = None;
        for (i, п) in self.панели.iter().enumerate() {
            let Some((t, x, y)) = луч.попал(п.поза, п.пол_ширина, п.пол_высота) else {
                continue;
            };
            let (пкс_x, пкс_y) = п.в_пиксели(x, y);
            match лучшая {
                Some((_, лучше, _, _)) if лучше <= t => {}
                _ => лучшая = Some((i, t, пкс_x, пкс_y)),
            }
        }
        лучшая.map(|(i, _, x, y)| (i, x, y))
    }

    /// Поставить панель туда, куда показывает луч, на заданном расстоянии, и
    /// развернуть лицом к человеку. Так работает перетаскивание контроллером.
    pub fn перенести(&mut self, индекс: usize, луч: Луч, расстояние: f32, глаз: Век3) {
        // Зону копируем ДО того, как возьмём панель изменяемо: иначе чтение
        // `self.зона` спорит с уже занятым `self.панели`.
        let зона = self.зона;
        let Some(п) = self.панели.get_mut(индекс) else { return };
        let точка = луч.начало.плюс(луч.направление * расстояние);
        let запас = п.пол_ширина.max(п.пол_высота);
        let точка = зона.зажать(точка, запас * 0.5);
        п.поза = Поза {
            место: точка,
            поворот: лицом_к(точка, глаз),
        };
        // Тронутая руками панель больше не подчиняется раскладке — иначе
        // следующий кадр вернул бы её в строй, и перетащить было бы нельзя.
        п.закреплена = true;
    }

    /// Изменить размер панели (колесо мыши, стики контроллера).
    pub fn масштабировать(&mut self, индекс: usize, во_сколько: f32) {
        let Some(п) = self.панели.get_mut(индекс) else { return };
        let к = во_сколько.clamp(0.5, 2.0);
        // Пределы: меньше 10 см панель не читается, больше 4 м не помещается
        // ни в какую зону.
        п.пол_ширина = (п.пол_ширина * к).clamp(0.05, 2.0);
        п.пол_высота = (п.пол_высота * к).clamp(0.05, 2.0);
        п.закреплена = true;
    }

    /// Отпустить все панели обратно под раскладку.
    pub fn расстановку_сбросить(&mut self) {
        for п in &mut self.панели {
            п.закреплена = false;
        }
    }

    /// Попросить взять направление «перед» и высоту глаз из позы головы на
    /// ближайшем кадре: позы здесь нет, она приходит только с кадром шлема.
    pub fn якорь_сбросить(&mut self) {
        self.нужен_якорь = true;
    }

    /// Поставить якорь по позе головы. `перед` — рыскание взгляда: панели
    /// строятся вокруг того направления, куда человек смотрел в этот момент.
    pub fn якорь_по_голове(&mut self, голова: Поза, высота: f32) {
        let d = голова.поворот.повернуть(Век3::new(0.0, 0.0, -1.0));
        // Обратное к `поза_на_дуге`: направление угла θ это (−sinθ, 0, −cosθ).
        // Взгляд строго вверх/вниз рыскания не задаёт — тогда оставляем прежнее.
        let гориз = (d.x * d.x + d.z * d.z).sqrt();
        if гориз > 1e-3 {
            self.перед = (-d.x).atan2(-d.z);
        }
        self.высота_глаз = высота;
        self.нужен_якорь = false;
    }
}

impl Панель {
    /// Во сколько раз панель отличается от «штатного» размера своего окна.
    /// Нужно, чтобы пересчёт размера при ресайзе окна не отменял ручной
    /// масштаб: человек растянул панель — она обязана остаться растянутой.
    fn масштаб_к(&self, сцена: &Сцена) -> f32 {
        let штатная = (self.ширина_пкс.max(1) as f32) * сцена.метров_на_пиксель * 0.5;
        if штатная <= 1e-4 {
            1.0
        } else {
            (self.пол_ширина / штатная).clamp(0.2, 8.0)
        }
    }
}

/// Точка на дуге радиуса `радиус` под углом рыскания `угол`, повёрнутая лицом
/// в центр дуги.
fn поза_на_дуге(угол: f32, радиус: f32, высота: f32) -> Поза {
    Поза {
        место: Век3::new(-угол.sin() * радиус, высота, -угол.cos() * радиус),
        поворот: Кватернион::вокруг_y(угол),
    }
}

/// Поворот, при котором панель в точке `место` смотрит на `глаз`.
///
/// Только рыскание: кренить панель вслед за наклоном головы — верный способ
/// сделать человеку плохо. Наклон по вертикали добавляется отдельно и
/// умеренно.
fn лицом_к(место: Век3, глаз: Век3) -> Кватернион {
    let d = глаз.минус(место);
    let рыскание = d.x.atan2(d.z);
    let гориз = (d.x * d.x + d.z * d.z).sqrt();
    let тангаж = (d.y / гориз.max(1e-3)).atan().clamp(-0.6, 0.6);
    Кватернион::вокруг_y(рыскание).умножить(Кватернион::вокруг_x(тангаж))
}

/// Мелкая обёртка ради читаемости `разложить`: `chunks` даёт срез, а
/// `разложить_дугой` просит владение независимым списком индексов.
fn кусок_как_вектор(к: &[usize]) -> Vec<usize> {
    к.to_vec()
}

