//! Заглушка VR-режима: то, что видит остальной код, когда фича `vr` выключена.
//!
//! Подставляется вместо `src/vr/` целиком (см. `#[path]` в lib.rs), поэтому
//! снаружи модуль по-прежнему зовётся `crate::vr` и все места вызова остаются
//! нетронутыми — в `plx-standard` они просто ничего не делают.
//!
//! **Что здесь настоящее, а что пустое.** Типы, которые разбирает `config.lua`
//! (`scene::Раскладка`, `input::Жест`) и чистая математика подключаются теми же
//! файлами, что и в полной сборке: конфиг обязан вести себя одинаково в обеих
//! сборках, иначе `vr{ layout = "ring" }` в одной был бы верным ключом, а в
//! другой — ошибкой разбора. Пустые — только те функции, за которыми стоит
//! реальный шлем.

// Настоящие файлы из vr/: ни один из них не знает про OpenXR.
//
// `allow(dead_code)` — не заметание мусора под ковёр: конфигу из этих файлов
// нужны РОВНО `scene::Раскладка`, `scene::Ключ`, `ui::Вид` и `math::Кватернион`,
// а вся геометрия комнаты и раскладка панелей рядом с ними в минимальной
// сборке действительно не зовётся. Без этого разрешения сборка выдавала бы
// два десятка «never constructed» на код, который заведомо и намеренно спит,
// и настоящие предупреждения утонули бы в них.
#[path = "../vr/жест.rs"]
#[allow(dead_code)]
pub mod жест;
#[path = "../vr/math.rs"]
#[allow(dead_code)]
pub mod math;
#[path = "../vr/scene.rs"]
#[allow(dead_code)]
pub mod scene;
#[path = "../vr/ui.rs"]
#[allow(dead_code)]
pub mod ui;

/// `crate::vr::input::Жест` — путь, по которому жесты зовёт `config.rs`.
/// Распознавание жестов (руки, контроллеры) осталось в полной сборке, а сам
/// перечень — вот он, тот же самый.
pub mod input {
    // `Сторона` конфигу не нужна, но реэкспорт держим полным: путь
    // `vr::input::{Жест, Сторона}` обязан значить в обеих сборках одно и то же.
    #[allow(unused_imports)]
    pub use super::жест::{Жест, Сторона};
}

/// `vr_поиск` в состоянии держит `Result<xr::Заготовка, ОшибкаВхода>`. Шлема
/// здесь нет и заготовке взяться неоткуда, поэтому тип пустой: значение такого
/// типа создать нельзя, и компилятор сам следит, что канал никогда не сработает.
pub mod xr {
    pub enum Заготовка {}
}

use crate::state::Parallax;
use smithay::backend::renderer::gles::GlesRenderer;

/// Живой шлем. В минимальной сборке значения этого типа не существует —
/// `state.vr` всегда `None`.
pub enum ВР {}

/// Ожидание, пока человек наденет шлем. Тоже недостижимо.
pub enum Ожидание {}

/// Причина, по которой вход в VR не удался.
pub enum ОшибкаВхода {}

/// Состояние дополненной реальности. Здесь достижим только `НеУмеет`, но
/// перечень полный: он уходит в `match` в `config.rs` и `ctl.rs`, общий на обе
/// сборки.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(dead_code)]
pub enum АР {
    Включена,
    Выключена,
    НеУмеет,
}

/// Единственный текст, который минимальная сборка говорит про шлем. Отдельной
/// константой, чтобы сообщение было ОДНО на все точки входа: человек, нажавший
/// Super+Alt+V, должен узнать не «не сработало», а что именно ставить.
pub fn нет_фичи() -> &'static str {
    crate::т!(
        "VR в этой сборке не собран — нужен plx-extra",
        "VR is not built into this binary — use plx-extra",
    )
}

pub fn включить(_state: &mut Parallax) -> Result<(), String> {
    Err(нет_фичи().into())
}

pub fn выключить(_state: &mut Parallax) {}

pub fn режим(state: &mut Parallax) {
    state.уведомить(нет_фичи());
}

/// Зовётся каждой итерацией главного цикла — здесь это пустое тело, которое
/// оптимизатор выкидывает целиком.
pub fn тик(_state: &mut Parallax) {}

pub fn тик_с(_state: &mut Parallax, _renderer: &mut GlesRenderer) {}

pub fn сменить_раскладку(state: &mut Parallax) -> scene::Раскладка {
    state.vr_раскладка
}

pub fn переключить_ар(_state: &mut Parallax) -> АР {
    АР::НеУмеет
}

pub fn пересобрать(_state: &mut Parallax) {}

pub fn пульт(_state: &mut Parallax, _вид: ui::Вид) -> Result<bool, String> {
    Err(нет_фичи().into())
}

pub fn нажать(_state: &mut Parallax, _вид: ui::Вид, _номер: usize) -> Result<String, String> {
    Err(нет_фичи().into())
}

pub fn снимок(_state: &mut Parallax, _путь: std::path::PathBuf) -> Result<(), String> {
    Err(нет_фичи().into())
}

pub fn пульты_строкой(_state: &Parallax) -> String {
    нет_фичи().into()
}

pub fn панели_строкой(_state: &Parallax) -> String {
    нет_фичи().into()
}

pub fn ввод_строкой(_state: &Parallax) -> String {
    нет_фичи().into()
}

pub fn жесты_строкой(_state: &Parallax) -> String {
    нет_фичи().into()
}

/// Как рантайм смешивает картинку с комнатой. Рантайма нет — строка пустая,
/// и текст «шлем не показывает комнату (…)» остаётся без скобочной части.
pub fn смешивание_строкой(_state: &Parallax) -> String {
    String::new()
}

pub fn состояние(_state: &Parallax) -> String {
    нет_фичи().into()
}
