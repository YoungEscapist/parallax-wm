//! Звуки зажатия и уведомления: восходящая пробежка нот, пока держат «сон»,
//! «перезагрузку» или «выключение», короткая фраза на подтверждение, спад на
//! отмену и двухнотный тон уведомления (его играет notify.rs).
//!
//! **Файлов в репозитории нет** — волны считаются здесь же и один раз за
//! запуск выкладываются WAV-ами в XDG_RUNTIME_DIR. Ноты зажатия расставлены
//! по долям [`crate::зажим::ДЕРЖАТЬ`]: заливка кнопки и пробежка доходят до
//! верха вместе, и записанный заранее файл с этим разъехался бы при первой
//! же правке длительности.
//!
//! **Каждая нота — удар молоточка**, а не тянущийся тон: атака в несколько
//! миллисекунд и затухание по экспоненте. Прежние звуки были ровными
//! синусами — тон зажатия ехал вверх с дрожанием, как сирена, тон
//! уведомления стоял на 780 Гц почти секунду, как писк, — и оба резали
//! слух. Все ноты из одной пентатоники (ре мажор), поэтому наложения —
//! пробежка ещё звенит, а уже пошло «готово» — звучат аккордом, а не спором.
//!
//! **Проигрывает** тот же `pw-play`/`paplay`, что и тон уведомления (см.
//! notify.rs): своего микшера у композитора нет. Пробежка — отдельный
//! процесс, и отпущенную раньше времени кнопку слышно сразу: процесс
//! убивается, вместо него звучит спад.

use std::io::Write;
use std::path::PathBuf;
use std::process::Child;

use crate::notify::Проигрыватель;
use crate::tray::PowerAction;

const ЧАСТОТА: u32 = 48_000;
/// Громкость проигрывателя. Чуть громче тона уведомления (0.35): пробежку
/// слышат, держа кнопку, и тише она терялась бы под музыкой.
const ГРОМКОСТЬ: f32 = 0.45;

// Ре-мажорная пентатоника.
const РЕ4: f64 = 293.66;
const ЛЯ4: f64 = 440.0;
const РЕ5: f64 = 587.33;
const МИ5: f64 = 659.26;
const ФА5_ДИЕЗ: f64 = 739.99;
const ЛЯ5: f64 = 880.0;
const СИ5: f64 = 987.77;
const РЕ6: f64 = 1174.66;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Звук {
    /// Восходящая пробежка, пока кнопку держат.
    Зажим,
    /// Додержали: у каждого действия своя короткая фраза — сон уходит вниз
    /// мягко, перезагрузка вверх, выключение спускается на три ноты.
    Готово(PowerAction),
    /// Отпустили раньше времени.
    Отмена,
}

impl Звук {
    fn имя(self) -> &'static str {
        match self {
            Звук::Зажим => "plx-hold.wav",
            Звук::Готово(PowerAction::Sleep) => "plx-hold-sleep.wav",
            Звук::Готово(PowerAction::Reboot) => "plx-hold-reboot.wav",
            Звук::Готово(PowerAction::Off) => "plx-hold-off.wav",
            Звук::Отмена => "plx-hold-cancel.wav",
        }
    }

    const ВСЕ: [Звук; 5] = [
        Звук::Зажим,
        Звук::Готово(PowerAction::Sleep),
        Звук::Готово(PowerAction::Reboot),
        Звук::Готово(PowerAction::Off),
        Звук::Отмена,
    ];
}

// ── Волны ────────────────────────────────────────────────────────────────────

/// Пробежка зажатия: пять нот пентатоники вверх (ре–ми–фа♯–ля–си), по одной
/// на каждую пятую часть `сек` и чуть громче с каждой ступенью. Последняя
/// падает на 0.8 `сек`, следующий удар — уже «готово» ровно на `сек`, так что
/// пульс не сбивается. Хвост звенит после `сек`: на подтверждении его не
/// обрывают, он ложится под первую ноту фразы.
pub fn волна_зажима(сек: f64) -> Vec<f32> {
    let ноты = [РЕ5, МИ5, ФА5_ДИЕЗ, ЛЯ5, СИ5];
    let шаг = сек / ноты.len() as f64;
    let мелодия: Vec<_> =
        ноты.iter().enumerate().map(|(k, &f)| (k as f64 * шаг, f, 0.26 + 0.04 * k as f64)).collect();
    фраза(&мелодия, 0.30, 0.16, 0.16)
}

/// Додержали: у каждого действия своя фраза — сон спускается на квинту и
/// тише прочих, перезагрузка поднимается к октаве, выключение сходит на три
/// ноты к тонике и гаснет.
pub fn волна_готово(действие: PowerAction) -> Vec<f32> {
    let мелодия: &[(f64, f64, f64)] = match действие {
        PowerAction::Sleep => &[(0.0, ЛЯ5, 0.30), (0.14, РЕ5, 0.28)],
        PowerAction::Reboot => &[(0.0, ЛЯ5, 0.32), (0.09, РЕ6, 0.34)],
        PowerAction::Off => &[(0.0, ЛЯ5, 0.34), (0.11, ФА5_ДИЕЗ, 0.32), (0.22, РЕ5, 0.30)],
    };
    // Последняя нота звучит дольше: на ней фраза и кончается.
    фраза(мелодия, 0.60, 0.26, 0.14)
}

/// Отмена: две тихие низкие ноты вниз, чтобы отпущенная кнопка не обрывалась
/// тишиной.
pub fn волна_отмены() -> Vec<f32> {
    фраза(&[(0.0, ЛЯ4, 0.30), (0.07, РЕ4, 0.26)], 0.30, 0.12, 0.08)
}

/// Тон уведомления: ре → ля, две ноты вразбивку, полсекунды с хвостом.
/// Встроенный в notify.rs; `set{ notify_sound = … }` заменяет его файлом.
pub fn волна_уведомления() -> Vec<f32> {
    фраза(&[(0.0, РЕ5, 0.52), (0.085, ЛЯ5, 0.45)], 0.55, 0.20, 0.12)
}

/// Ноты `(начало, частота, громкость)` одна за другой; длина — до последней
/// ноты плюс `хвост`. Последняя затухает с `тау_посл`, прочие — с `тау`.
fn фраза(мелодия: &[(f64, f64, f64)], хвост: f64, тау_посл: f64, тау: f64) -> Vec<f32> {
    let длина = мелодия.last().map_or(0.0, |н| н.0) + хвост;
    let mut out = vec![0.0_f32; (длина * ЧАСТОТА as f64) as usize];
    for (k, &(с, f, громкость)) in мелодия.iter().enumerate() {
        нота(&mut out, с, f, громкость, if k + 1 == мелодия.len() { тау_посл } else { тау });
    }
    for (i, s) in out.iter_mut().enumerate() {
        *s *= огибающая(i as f64 / ЧАСТОТА as f64, длина, 0.0, 0.03) as f32;
    }
    out
}

/// Молоточек по деревянному бруску: основной тон затухает за `тау`, вторая
/// гармоника — вдвое с лишним быстрее (тепло в начале удара), а короткий
/// призвук на ~4f, как у маримбы, — стук, который гаснет за пару десятков
/// миллисекунд. Атака 5 мс: без неё удар щёлкает, длиннее — «дует».
fn нота(out: &mut [f32], с: f64, f: f64, громкость: f64, тау: f64) {
    use std::f64::consts::TAU;
    let начало = (с * ЧАСТОТА as f64) as usize;
    for (i, s) in out.iter_mut().enumerate().skip(начало) {
        let t = (i - начало) as f64 / ЧАСТОТА as f64;
        let атака = (t / 0.005).min(1.0);
        let тело = (TAU * f * t).sin() * (-t / тау).exp()
            + 0.18 * (TAU * 2.0 * f * t).sin() * (-t / (тау * 0.4)).exp()
            + 0.10 * (TAU * 3.94 * f * t).sin() * (-t / 0.018).exp();
        *s += (тело / 1.28 * громкость * атака) as f32;
    }
}

/// Линейные подъём и спад по краям — без них начало и конец щёлкают.
fn огибающая(t: f64, сек: f64, подъём: f64, спад: f64) -> f64 {
    let a = if подъём > 0.0 { (t / подъём).min(1.0) } else { 1.0 };
    let b = if спад > 0.0 { ((сек - t) / спад).clamp(0.0, 1.0) } else { 1.0 };
    a * b
}

/// 16-битный моно WAV.
pub fn wav(волна: &[f32]) -> Vec<u8> {
    let данных = (волна.len() * 2) as u32;
    let mut b = Vec::with_capacity(44 + данных as usize);
    b.extend_from_slice(b"RIFF");
    b.extend_from_slice(&(36 + данных).to_le_bytes());
    b.extend_from_slice(b"WAVEfmt ");
    b.extend_from_slice(&16u32.to_le_bytes());
    b.extend_from_slice(&1u16.to_le_bytes()); // PCM
    b.extend_from_slice(&1u16.to_le_bytes()); // моно
    b.extend_from_slice(&ЧАСТОТА.to_le_bytes());
    b.extend_from_slice(&(ЧАСТОТА * 2).to_le_bytes());
    b.extend_from_slice(&2u16.to_le_bytes());
    b.extend_from_slice(&16u16.to_le_bytes());
    b.extend_from_slice(b"data");
    b.extend_from_slice(&данных.to_le_bytes());
    for s in волна {
        b.extend_from_slice(&((s.clamp(-1.0, 1.0) * 32767.0).round() as i16).to_le_bytes());
    }
    b
}

// ── Проигрывание ─────────────────────────────────────────────────────────────

/// Проигрыватель и выложенные файлы. Готовится при первом звуке, а не на
/// старте: зажатие случается раз в день, и считать волны каждому запуску
/// незачем.
#[derive(Default)]
pub struct Звуки {
    /// None — ещё не пробовали; Some(None) — пробовали, звука не будет.
    готово: Option<Option<(Проигрыватель, PathBuf)>>,
    /// Пробежка зажатия — её обрывают, если кнопку отпустили.
    зажим: Option<Child>,
    /// Остальные: ждём их только затем, чтобы не копить зомби.
    прочие: Vec<Child>,
}

impl Звуки {
    fn приготовить(&mut self) -> Option<(Проигрыватель, PathBuf)> {
        if let Some(г) = &self.готово {
            return г.clone();
        }
        let г = (|| {
            let п = Проигрыватель::найти()?;
            let каталог = std::env::var("XDG_RUNTIME_DIR")
                .map(PathBuf::from)
                .unwrap_or_else(|_| std::env::temp_dir());
            for з in Звук::ВСЕ {
                let волна = match з {
                    Звук::Зажим => волна_зажима(crate::зажим::ДЕРЖАТЬ.as_secs_f64()),
                    Звук::Готово(д) => волна_готово(д),
                    Звук::Отмена => волна_отмены(),
                };
                let путь = каталог.join(з.имя());
                if let Err(e) = std::fs::File::create(&путь).and_then(|mut f| f.write_all(&wav(&волна))) {
                    tracing::warn!("plx/sounds: could not write {:?}: {}", путь, e);
                    return None;
                }
            }
            Some((п, каталог))
        })();
        if г.is_none() {
            tracing::warn!("plx/sounds: no pw-play/paplay or no place for the files — hold is silent");
        }
        self.готово = Some(г.clone());
        г
    }

    pub fn играть(&mut self, з: Звук) {
        if !crate::bar::вид().sounds {
            return;
        }
        let Some((п, каталог)) = self.приготовить() else { return };
        if з == Звук::Зажим {
            self.оборвать();
        }
        match п.команда(&каталог.join(з.имя()), ГРОМКОСТЬ).spawn() {
            Ok(c) if з == Звук::Зажим => self.зажим = Some(c),
            Ok(c) => self.прочие.push(c),
            Err(e) => tracing::warn!("plx/sounds: {}: {}", п.имя(), e),
        }
    }

    /// Оборвать пробежку зажатия (кнопку отпустили).
    pub fn оборвать(&mut self) {
        if let Some(mut c) = self.зажим.take() {
            let _ = c.kill();
            let _ = c.wait();
        }
    }

    /// Прибрать доигравшие процессы. Зовётся из тика зажима.
    pub fn прибрать(&mut self) {
        self.прочие.retain_mut(|c| matches!(c.try_wait(), Ok(None)));
        if self.зажим.as_mut().is_some_and(|c| !matches!(c.try_wait(), Ok(None))) {
            self.зажим = None;
        }
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    /// Частота по числу переходов через ноль на отрезке.
    fn частота(в: &[f32], с: f64, по: f64) -> f64 {
        let (a, b) = ((с * ЧАСТОТА as f64) as usize, (по * ЧАСТОТА as f64) as usize);
        let нулей = в[a..b].windows(2).filter(|w| w[0] < 0.0 && w[1] >= 0.0).count();
        нулей as f64 / (по - с)
    }

    /// Громкость на отрезке (среднеквадратичное).
    fn громкость(в: &[f32], с: f64, по: f64) -> f64 {
        let (a, b) = ((с * ЧАСТОТА as f64) as usize, (по * ЧАСТОТА as f64) as usize);
        (в[a..b].iter().map(|s| (*s as f64).powi(2)).sum::<f64>() / (b - a) as f64).sqrt()
    }

    #[test]
    fn пробежка_зажатия_растёт_и_укладывается_в_удержание() {
        let в = волна_зажима(1.0);
        let низ = частота(&в, 0.05, 0.15);
        let верх = частота(&в, 0.85, 0.95);
        assert!(низ < 650.0 && верх > 900.0, "пробежка не растёт: {низ:.0} → {верх:.0} Гц");
        // Последняя нота — до конца удержания, после него только хвост.
        assert!(громкость(&в, 1.0, 1.05) < громкость(&в, 0.8, 0.85) / 2.0);
        // Края без щелчка: первые и последние отсчёты у нуля.
        assert!(в[0].abs() < 1e-3 && в[в.len() - 1].abs() < 1e-2);
        assert!(в.iter().all(|s| s.abs() <= 1.0), "перегруз");
    }

    /// Звук — удары, а не тянущийся тон: через треть секунды после последней
    /// ноты от неё остаётся меньше четверти. Ровный синус (каким был тон
    /// уведомления) этого не проходит.
    #[test]
    fn ноты_затухают() {
        let в = волна_уведомления();
        let удар = громкость(&в, 0.09, 0.14);
        let хвост = громкость(&в, 0.42, 0.47);
        assert!(хвост < удар / 4.0, "не затухает: {удар:.3} → {хвост:.3}");
    }

    #[test]
    fn звоны_не_перегружают() {
        for д in [PowerAction::Sleep, PowerAction::Reboot, PowerAction::Off] {
            let в = волна_готово(д);
            let пик = в.iter().fold(0.0_f32, |м, s| м.max(s.abs()));
            assert!(пик > 0.1 && пик < 0.9, "{д:?}: пик {пик}");
        }
        for в in [волна_отмены(), волна_уведомления()] {
            let пик = в.iter().fold(0.0_f32, |м, s| м.max(s.abs()));
            assert!(пик > 0.05 && пик < 0.9, "пик {пик}");
            assert!(в[0].abs() < 1e-3 && в[в.len() - 1].abs() < 1e-2);
        }
    }

    #[test]
    fn заголовок_wav() {
        let b = wav(&[0.0, 0.5, -0.5]);
        assert_eq!(&b[0..4], b"RIFF");
        assert_eq!(&b[8..16], b"WAVEfmt ");
        assert_eq!(b.len(), 44 + 6);
        assert_eq!(u32::from_le_bytes(b[40..44].try_into().unwrap()), 6);
    }
}
