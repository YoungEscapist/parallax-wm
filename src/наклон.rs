//! Наклон и вращение окон.
//!
//! Окно можно повернуть тремя способами, и все три живут на одной плоскости
//! в пространстве: КРЕН — вращение в плоскости экрана (окно лежит на столе
//! повёрнутым, как брошенная фотография), РЫСКАНИЕ и ТАНГАЖ — наклон к
//! зрителю вокруг вертикальной и горизонтальной осей.
//!
//! **Рисуется тем же шейдером, что куб и `flip3d`.** Наклонённое окно — это
//! грань куба с нулевым радиусом (`Куб::плоскость`), только базис плоскости
//! повёрнут ещё и креном/тангажем (`Куб::плоскость_окна`). Скругление окна на
//! этот путь не ложится (две программы на одно место кадра), поэтому углы режет
//! сам шейдер плоскости (`cube_round`), а тени и заплаты размытия у
//! наклонённого окна нет — плоские прямоугольники под повёрнутым окном выдали
//! бы обман.
//!
//! **Ввод.** Клиент про наклон не знает: для него окно стоит ровно. Точку
//! экрана переводим в точку окна ОБРАТНОЙ проекцией (`Куб::обратно_на` — та же
//! строка, что в шейдере), и `surface_under` отдаёт «виртуальное начало»,
//! подобранное так, чтобы `pos − начало` было этой точкой. Контракт тот же, что
//! у порталов и слоёв. Начало пересчитывается на каждом движении: отображение
//! не аффинное, одним сдвигом его не выразить.
//!
//! Управление (input.rs): Super+Ctrl+колесо — вращение, Super+Shift+колесо —
//! наклон влево-вправо, Super+Ctrl+Shift+колесо — вперёд-назад; Super+ЛКМ+ПКМ
//! по окну — вращение вслед за курсором (grabs/tilt_grab.rs); действия
//! `window_tilt { yaw, pitch, roll }` (в градусах, приращения) и
//! `window_tilt_reset`.
//!
//! **Анимация.** Все способы двигают только ЦЕЛЬ (`ЖивойНаклон::цель`), а
//! рисуется и ловит клики ПОКАЗ — его `наклон_тик` экспоненциально подводит к
//! цели. Так шаг колеса в 5° и сброс доворачиваются плавно, а не скачком.
//! Ввод считается по показу: клик попадает туда, где окно нарисовано сейчас.

use smithay::desktop::{space::SpaceElement, Window, WindowSurfaceType};
use smithay::reexports::wayland_server::protocol::wl_surface::WlSurface;
use smithay::utils::{IsAlive, Logical, Point};

use crate::state::Parallax;

/// Наклон окна, радианы.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Наклон {
    /// Вокруг вертикальной оси: `> 0` — правый край уходит от зрителя.
    pub рыскание: f32,
    /// Вокруг горизонтальной: `> 0` — верх уходит от зрителя.
    pub тангаж: f32,
    /// В плоскости экрана: `> 0` — по часовой стрелке.
    pub крен: f32,
}

/// Предел двух наклонов к зрителю. Дальше окно встаёт почти ребром: от него
/// остаётся полоска, а ближний край большого окна подходит к камере вплотную.
pub const ПРЕДЕЛ: f32 = 75.0 * std::f32::consts::PI / 180.0;

/// Шаг колеса, градусы.
pub const ШАГ_ГРАДУСОВ: f32 = 5.0;

/// Наклон окна в движении: куда едет и где стоит в этом кадре.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct ЖивойНаклон {
    pub цель: Наклон,
    pub показ: Наклон,
}

/// Постоянная времени доводки, секунды: за неё показ проходит ~63% пути.
/// Шаг колеса доезжает за ~0.2 с, а поворот мышью отстаёт от курсора едва
/// заметно — ровно настолько, чтобы рывки руки сгладились.
const ТАУ: f32 = 0.06;

/// Ближе этого (радианы, ~0.05°) показ считается доехавшим.
const ДОЕХАЛ: f32 = 0.001;

impl Наклон {
    pub fn нулевой(&self) -> bool {
        self.рыскание.abs() < 1e-4 && self.тангаж.abs() < 1e-4 && self.крен.abs() < 1e-4
    }
}

/// Привести угол к (−π, π]: крен крутится вечно, но хранить 37 оборотов незачем.
pub fn в_круг(a: f32) -> f32 {
    use std::f32::consts::{PI, TAU};
    let a = a.rem_euclid(TAU);
    if a > PI { a - TAU } else { a }
}

impl Parallax {
    /// Наклон окна на этот кадр. `None` — окно стоит ровно и рисуется
    /// обычным путём.
    ///
    /// Без шейдера плоскости (минимальная сборка, не скомпилировалась
    /// программа) наклона нет вовсе — и в рендере, и во вводе: иначе клики
    /// считались бы по повёрнутому окну, нарисованному ровно. Полноэкранное
    /// окно тоже стоит ровно, наклон к нему вернётся после выхода.
    pub fn наклон_окна(&self, window: &Window) -> Option<Наклон> {
        if self.куб_шейдер.is_none() || self.наклоны_окон.is_empty() || self.is_fullscreen(window) {
            return None;
        }
        self.наклоны_окон
            .iter()
            .find(|(w, _)| crate::dwindle::same_window(w, window))
            .map(|(_, н)| н.показ)
            .filter(|н| !н.нулевой())
    }

    /// Куда окно доворачивается (нулевой наклон, если окна в списке нет).
    pub fn цель_наклона(&self, window: &Window) -> Наклон {
        self.наклоны_окон
            .iter()
            .find(|(w, _)| crate::dwindle::same_window(w, window))
            .map(|(_, н)| н.цель)
            .unwrap_or_default()
    }

    fn живой_наклон(&mut self, window: &Window) -> &mut ЖивойНаклон {
        self.наклоны_окон.retain(|(w, _)| w.alive());
        let i = match self.наклоны_окон.iter().position(|(w, _)| crate::dwindle::same_window(w, window)) {
            Some(i) => i,
            None => {
                self.наклоны_окон.push((window.clone(), ЖивойНаклон::default()));
                self.наклоны_окон.len() - 1
            }
        };
        &mut self.наклоны_окон[i].1
    }

    /// Поставить крен (абсолютный, радианы) — поворот мышью.
    pub fn задать_крен(&mut self, window: &Window, крен: f32) {
        let н = self.живой_наклон(window);
        н.цель.крен = в_круг(крен);
        if н.цель.крен.abs() < 0.2f32.to_radians() {
            н.цель.крен = 0.0;
        }
        self.request_redraw();
    }

    /// Подвести показ каждого наклона к цели. `true` — кто-то ещё едет.
    /// Доехавшие до нуля окна уходят из списка и возвращаются на обычный путь
    /// рендера (с тенью и блюром).
    pub fn наклон_тик(&mut self, dt: f64) -> bool {
        if self.наклоны_окон.is_empty() {
            return false;
        }
        let k = 1.0 - (-(dt as f32) / ТАУ).exp();
        let ехал = self.наклон_едет();
        let mut едет = false;
        for (_, н) in self.наклоны_окон.iter_mut() {
            if н.показ == н.цель {
                continue;
            }
            let (ц, п) = (н.цель, &mut н.показ);
            п.рыскание += (ц.рыскание - п.рыскание) * k;
            п.тангаж += (ц.тангаж - п.тангаж) * k;
            // Крен — по короткой дуге: из 170° в −170° через 180°, а не через ноль.
            п.крен = в_круг(п.крен + в_круг(ц.крен - п.крен) * k);
            if (ц.рыскание - п.рыскание).abs() < ДОЕХАЛ
                && (ц.тангаж - п.тангаж).abs() < ДОЕХАЛ
                && в_круг(ц.крен - п.крен).abs() < ДОЕХАЛ
            {
                *п = ц;
            } else {
                едет = true;
            }
        }
        let было = self.наклоны_окон.len();
        self.наклоны_окон.retain(|(w, н)| w.alive() && !(н.цель.нулевой() && н.показ.нулевой()));
        // Кадр — только пока что-то едет или окно сошло со списка: стоячий
        // наклон не должен держать композитор на частом такте.
        if едет || было != self.наклоны_окон.len() || ехал {
            self.request_redraw();
        }
        едет
    }

    /// Хоть один наклон ещё доворачивается — тику нужен частый такт.
    pub fn наклон_едет(&self) -> bool {
        self.наклоны_окон.iter().any(|(_, н)| н.показ != н.цель)
    }

    /// Добавить к наклону окна приращения (радианы).
    pub fn наклонить_окно(&mut self, window: &Window, рыскание: f32, тангаж: f32, крен: f32) {
        let н = &mut self.живой_наклон(window).цель;
        н.рыскание = (н.рыскание + рыскание).clamp(-ПРЕДЕЛ, ПРЕДЕЛ);
        н.тангаж = (н.тангаж + тангаж).clamp(-ПРЕДЕЛ, ПРЕДЕЛ);
        н.крен = в_круг(н.крен + крен);
        // Набежавшие из шагов колеса доли градуса не дают «ровно ноль» —
        // докручиваем до него, иначе окно, возвращённое на место колесом,
        // так и осталось бы на шейдерном пути без тени.
        for a in [&mut н.рыскание, &mut н.тангаж, &mut н.крен] {
            if a.abs() < 0.2f32.to_radians() {
                *a = 0.0;
            }
        }
        let н = *н;
        tracing::debug!(
            "plx/tilt: yaw={:.1}° pitch={:.1}° roll={:.1}°",
            н.рыскание.to_degrees(), н.тангаж.to_degrees(), н.крен.to_degrees(),
        );
        self.request_redraw();
    }

    /// Вернуть окно ровно — тоже доворотом, а не скачком.
    pub fn сбросить_наклон(&mut self, window: &Window) {
        self.живой_наклон(window).цель = Наклон::default();
        self.request_redraw();
    }

    /// Окно под курсором, а без него — окно в фокусе: кому достаётся
    /// действие наклона с клавиатуры.
    fn окно_для_наклона(&self) -> Option<Window> {
        let pos = self.pointer_location;
        self.окно_под(pos).map(|(w, _)| w).or_else(|| self.focused_window())
    }

    /// Действие `window_tilt` (градусы).
    pub fn наклонить_по_действию(&mut self, рыскание: f32, тангаж: f32, крен: f32) {
        if let Some(w) = self.окно_для_наклона() {
            self.наклонить_окно(&w, рыскание.to_radians(), тангаж.to_radians(), крен.to_radians());
        }
    }

    /// Действие `window_tilt_reset`.
    pub fn сбросить_наклон_по_действию(&mut self) {
        if let Some(w) = self.окно_для_наклона() {
            self.сбросить_наклон(&w);
        }
    }

    /// Наклонённое окно под точкой холста и «виртуальное начало» его дерева
    /// поверхностей: `pos − начало` — точка окна, которую человек видит под
    /// курсором (см. шапку).
    ///
    /// Окна обходятся сверху вниз: обычное окно, лежащее выше и накрывающее
    /// точку, закрывает наклонённые под ним — ответ `None`, и дальше работает
    /// обычный путь.
    pub fn наклонённое_под(&self, pos: Point<f64, Logical>) -> Option<(Window, Point<f64, Logical>)> {
        if self.наклоны_окон.is_empty() || self.куб_шейдер.is_none() {
            return None;
        }
        let zoom = self.viewport.zoom.max(0.01);
        let cam = (self.viewport.cam_x, self.viewport.cam_y);
        let экран = (((pos.x - cam.0) * zoom) as f32, ((pos.y - cam.1) * zoom) as f32);
        let ширина = self.screen_size().w as f32;
        for w in self.space.elements().rev() {
            if self.закреплено(w) {
                continue;
            }
            let Some(g) = self.space.element_geometry(w) else { continue };
            // Начало дерева поверхностей, а не видимой части (см. цикл окон в udev.rs).
            let loc = (g.loc - w.geometry().loc).to_f64();
            if let Some(н) = self.наклон_окна(w) {
                let geo = w.geometry();
                let центр = (
                    loc.x + geo.loc.x as f64 + geo.size.w as f64 * 0.5,
                    loc.y + geo.loc.y as f64 + geo.size.h as f64 * 0.5,
                );
                let ось = (((центр.0 - cam.0) * zoom) as f32, ((центр.1 - cam.1) * zoom) as f32);
                let камера = crate::куб::Куб::плоскость(ширина, self.lua_config.cube_focal, ось);
                let пл = crate::куб::Куб::плоскость_окна(н.рыскание, н.тангаж, н.крен);
                let Some((u, v)) = камера.обратно_на(&пл, экран) else { continue };
                let точка = Point::<f64, Logical>::from((
                    центр.0 + u as f64 / zoom,
                    центр.1 + v as f64 / zoom,
                ));
                if self.в_видимой_рамке(w, точка) && w.is_in_input_region(&(точка - loc)) {
                    return Some((w.clone(), pos - (точка - loc)));
                }
                continue;
            }
            if self.в_видимой_рамке(w, pos) && w.is_in_input_region(&(pos - loc)) {
                return None;
            }
        }
        None
    }

    /// Поверхность наклонённого окна под точкой — ветка `surface_under`.
    pub fn наклонённая_поверхность_под(
        &self,
        pos: Point<f64, Logical>,
    ) -> Option<(WlSurface, Point<f64, Logical>)> {
        let (window, начало) = self.наклонённое_под(pos)?;
        window
            .surface_under(pos - начало, WindowSurfaceType::ALL)
            .map(|(s, p)| (s, p.to_f64() + начало))
    }

    /// Строка для `ctl tilt`: наклон окна под курсором и точка окна под ним.
    pub fn наклон_отчёт(&self) -> String {
        let pos = self.pointer_location;
        let окно = self.окно_для_наклона();
        let н = окно.as_ref().and_then(|w| self.наклон_окна(w)).unwrap_or_default();
        let под = self.наклонённое_под(pos).map(|(w, начало)| {
            let локаль = pos - начало;
            format!("{} ({:.1},{:.1})", crate::xwin::app_id(&w).unwrap_or_default(), локаль.x, локаль.y)
        });
        format!(
            "window={} yaw={:.1} pitch={:.1} roll={:.1} tilted={} hit={}",
            окно.as_ref().and_then(crate::xwin::app_id).unwrap_or_else(|| "-".into()),
            н.рыскание.to_degrees(), н.тангаж.to_degrees(), н.крен.to_degrees(),
            self.наклоны_окон.len(),
            под.unwrap_or_else(|| "-".into()),
        )
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn крен_в_круг() {
        let a = в_круг(370f32.to_radians()).to_degrees();
        assert!((a - 10.0).abs() < 1e-3);
        let b = в_круг(-190f32.to_radians()).to_degrees();
        assert!((b - 170.0).abs() < 1e-3);
    }
}
