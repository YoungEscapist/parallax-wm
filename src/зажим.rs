//! Зажатие для сна, перезагрузки и выключения.
//!
//! Раньше кнопки питания в полке «взводились»: первый щелчок подсвечивал,
//! второй в течение четырёх секунд выполнял. Двойной щелчок защищает от
//! промаха, но не от привычки щёлкать дважды, и ничего не говорит о том,
//! сколько осталось. Зажатие честнее: кнопка заливается, пока её держат, тон
//! растёт вместе с заливкой (см. звуки.rs), отпустил раньше — заливка стекает
//! обратно, и ничего не случилось.
//!
//! Одно состояние на композитор, а не по копии у каждого органа: держат
//! кнопку и во всплывающем окошке панели (всплывашки.rs), и в полке
//! (tray.rs), а отпускают её где угодно — курсор мог уехать за край
//! карточки. Поэтому отпускание разбирается в input.rs ПЕРВЫМ, до всех
//! органов (см. `зажим_отпустить`).

use std::time::{Duration, Instant};

use smithay::utils::{Physical, Point};

use crate::tray::PowerAction;
use crate::звуки::Звук;

/// Сколько держать кнопку. Ровно столько же длится тон (звуки.rs).
pub const ДЕРЖАТЬ: Duration = Duration::from_millis(1000);
/// За сколько секунд полная заливка стекает обратно, если отпустили.
const ОТКАТ: f64 = 0.30;
/// Пауза между «додержали» и самой командой: звон успевает прозвучать, а
/// человек — увидеть, что сработало. Без неё сон гасил экран раньше, чем
/// заливка доходила до края.
const ДО_КОМАНДЫ: Duration = Duration::from_millis(450);
/// Отпустили быстрее — это был щелчок, а не «передумал»: вместо спада тона
/// загорается подсказка держать.
const ЩЕЛЧОК: Duration = Duration::from_millis(220);
/// Сколько горит подсказка «удерживайте».
pub const ПОДСКАЗКА: Duration = Duration::from_millis(1800);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Откуда {
    /// Всплывающее окошко панели (значок питания справа).
    Окошко,
    /// Полка состояния.
    Полка,
}

#[derive(Clone, Copy, Debug)]
pub struct Удержание {
    pub действие: PowerAction,
    pub откуда: Откуда,
    /// Заливка 0…1.
    pub доля: f64,
    /// Кнопку всё ещё держат.
    pub жмут: bool,
    нажали: Instant,
    /// Когда додержали: дальше ждём `ДО_КОМАНДЫ` и выполняем.
    pub сделано: Option<Instant>,
}

#[derive(Default)]
pub struct Зажим {
    pub тек: Option<Удержание>,
    /// Щёлкнули вместо того, чтобы держать: какую кнопку и когда.
    pub щёлкнули: Option<(PowerAction, Instant)>,
    звуки: crate::звуки::Звуки,
}

impl Зажим {
    /// Заливка кнопки `д` в органе `откуда` (None — эту кнопку не держат).
    pub fn доля(&self, д: PowerAction, откуда: Откуда) -> Option<f64> {
        self.тек.filter(|у| у.действие == д && у.откуда == откуда).map(|у| у.доля)
    }

    /// Додержали и ждём команды.
    pub fn сделано(&self) -> Option<PowerAction> {
        self.тек.filter(|у| у.сделано.is_some()).map(|у| у.действие)
    }

    /// Держат прямо сейчас (или уже додержали) — окошко не должно гаснуть.
    pub fn держит(&self) -> bool {
        self.тек.is_some_and(|у| у.жмут || у.сделано.is_some())
    }

    /// Щёлкнули по этой кнопке, а не зажали, — и подсказка ещё горит.
    pub fn щёлкнули(&self) -> Option<PowerAction> {
        self.щёлкнули.filter(|(_, t)| t.elapsed() < ПОДСКАЗКА).map(|(д, _)| д)
    }
}

impl crate::state::Parallax {
    /// Нажали кнопку питания.
    pub fn зажим_начать(&mut self, действие: PowerAction, откуда: Откуда) {
        // Додержанное уже не отменить — второй палец его не перебивает.
        if self.зажим.сделано().is_some() {
            return;
        }
        // Стекающую заливку той же кнопки подхватываем с места: «отпустил и
        // тут же нажал снова» не должно начинать с нуля на глазах.
        let было = self.зажим.доля(действие, откуда).unwrap_or(0.0);
        let нажали = Instant::now() - ДЕРЖАТЬ.mul_f64(было.clamp(0.0, 1.0));
        self.зажим.тек = Some(Удержание { действие, откуда, доля: было, жмут: true, нажали, сделано: None });
        self.зажим.щёлкнули = None;
        self.зажим.звуки.играть(Звук::Зажим);
        tracing::info!("plx/hold: {} — holding", действие.human());
        self.request_redraw();
    }

    /// Отпустили кнопку мыши (где угодно). true — отпускание наше.
    pub fn зажим_отпустить(&mut self) -> bool {
        let Some(у) = self.зажим.тек.as_mut() else { return false };
        if !у.жмут {
            return false;
        }
        у.жмут = false;
        if у.сделано.is_some() {
            return true;
        }
        // Додержал, а тик этого ещё не заметил (тики раз в кадр, отпустить
        // можно между ними) — это подтверждение, а не отмена: человек честно
        // продержал секунду. Поймано в харнессе: отпустил через 1.009 с.
        if у.нажали.elapsed() >= ДЕРЖАТЬ {
            у.доля = 1.0;
            у.сделано = Some(Instant::now());
            let д = у.действие;
            tracing::info!("plx/hold: {} — confirmed", д.human());
            self.зажим.звуки.играть(Звук::Готово(д));
            self.request_redraw();
            return true;
        }
        let (д, щелчок) = (у.действие, у.нажали.elapsed() < ЩЕЛЧОК);
        self.зажим.звуки.оборвать();
        if щелчок {
            self.зажим.щёлкнули = Some((д, Instant::now()));
        } else {
            self.зажим.звуки.играть(Звук::Отмена);
        }
        tracing::info!("plx/hold: {} — released early", д.human());
        self.request_redraw();
        true
    }

    /// Курсор двинулся: съехал с зажатой кнопки — это то же, что отпустить.
    pub fn зажим_движение(&mut self, pos: Point<f64, Physical>) {
        let Some(у) = self.зажим.тек.filter(|у| у.жмут && у.сделано.is_none()) else { return };
        let на_месте = match у.откуда {
            Откуда::Окошко => self.всплывашка_питание_под(pos) == Some(у.действие),
            Откуда::Полка => self.tray_power_at(pos) == Some(у.действие),
        };
        if !на_месте {
            self.зажим_отпустить();
        }
    }

    /// Шаг (зовёт `anim::tick`). true — кадр нужно перерисовать.
    pub fn зажим_тик(&mut self, dt: Duration) -> bool {
        self.зажим.звуки.прибрать();
        let mut dirty = false;
        let mut выполнить = None;
        if let Some(у) = self.зажим.тек.as_mut() {
            dirty = true;
            if let Some(когда) = у.сделано {
                if когда.elapsed() >= ДО_КОМАНДЫ {
                    выполнить = Some((у.действие, у.откуда));
                }
            } else if у.жмут {
                // По часам, а не по сумме dt: заливка обязана дойти до края
                // ровно тогда, когда кончится тон, а тики приходят неровно.
                у.доля = (у.нажали.elapsed().as_secs_f64() / ДЕРЖАТЬ.as_secs_f64()).min(1.0);
                if у.доля >= 1.0 {
                    у.сделано = Some(Instant::now());
                    let д = у.действие;
                    tracing::info!("plx/hold: {} — confirmed", д.human());
                    self.зажим.звуки.играть(Звук::Готово(д));
                }
            } else {
                у.доля -= dt.as_secs_f64() / (ОТКАТ * crate::anim::tempo()).max(1e-3);
                if у.доля <= 0.0 {
                    self.зажим.тек = None;
                }
            }
        }
        if let Some((д, откуда)) = выполнить {
            self.зажим.тек = None;
            match откуда {
                Откуда::Окошко => self.всплывашка_закрыть(),
                Откуда::Полка => self.tray_set_open(false),
            }
            self.tray_power(д);
        }
        if self.зажим.щёлкнули.is_some_and(|(_, t)| t.elapsed() >= ПОДСКАЗКА) {
            self.зажим.щёлкнули = None;
            dirty = true;
        } else if self.зажим.щёлкнули.is_some() {
            // Подсказка мигает (см. всплывашки.rs) — кадры нужны всё время.
            dirty = true;
        }
        dirty
    }

    /// Движется ли что-нибудь у зажатия — для `anim_busy`.
    pub fn зажим_занят(&self) -> bool {
        self.зажим.тек.is_some() || self.зажим.щёлкнули.is_some()
    }
}
