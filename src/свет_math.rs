//! Свет на холсте — чистая арифметика без единого вызова GL.
//!
//! Отдельным файлом, потому что нужна ОБЕИМ сборкам: полная светит по ней и на
//! сцену, и на окна (см. `свет.rs`, `rounded.rs`), стандартная берёт из неё то
//! же место источника, чтобы вызывающий код в `udev.rs` не считал его
//! по-разному в двух сборках (тот же приём, что у `куб_math.rs`).

/// Где сейчас источник и как далеко он достаёт.
#[derive(Clone, Copy, Debug)]
pub struct Источник {
    /// Точка на экране в физических пикселях. Может лежать и за краем экрана —
    /// свет от этого не пропадает, он просто приходит сбоку.
    pub точка: (f64, f64),
    /// Радиус спада в тех же пикселях: на этом расстоянии свет сходит в ноль.
    pub охват: f64,
}

/// Место источника и его охват на экране.
///
/// `точка` — где источник стоит, в физических пикселях от дома монитора,
/// `радиус` — охват в тех же пикселях, `камера` — смещение камеры ОТНОСИТЕЛЬНО
/// ДОМА, `даль` — насколько источник далеко: 0 — приклеен к экрану и не
/// реагирует ни на камеру, ни на зум, 1 — лежит на холсте наравне с окнами.
///
/// **Почему не просто точка холста.** Так оно и было сделано сначала — и первый
/// же прогон показал, чего это стоит: холст бесконечен, камера уезжает на
/// тысячи пикселей, и источник пропадает из кадра навсегда, а вместе с ним и
/// весь свет. Настоящее солнце далеко: оно смещается при ходьбе, но не остаётся
/// позади. Отсюда параллакс — тот же приём, что у сетки точек фона
/// (`PARALLAX_FACTOR` в udev.rs), только ещё сильнее: и сдвиг, и масштаб
/// берутся с долей.
///
/// Масштаб — `зум^даль`, а не `зум·даль`: при `даль = 0` он обязан быть РОВНО
/// единицей на любом зуме (приклеено к экрану — значит размер не меняется), а
/// линейная доля дала бы ноль.
///
/// **Смещение с насыщением.** Простой доли от камеры мало: она лишь замедляет
/// уход, а холст бесконечен — после перелёта на 20 000 пикселей четверть от
/// него это всё те же 5 000, и источника в кадре нет. Поэтому сдвиг проходит
/// через `tanh` с размахом в экран: на малых перемещениях он неотличим от
/// честного холста (`tanh x ≈ x`), а на больших упирается в предел.
pub fn источник(
    точка: (f64, f64),
    радиус: f64,
    камера: (f64, f64),
    зум: f64,
    даль: f64,
    размах: f64,
) -> Источник {
    let даль = даль.clamp(0.0, 1.0);
    let масштаб = зум.max(1e-6).powf(даль);
    let размах = размах.max(1.0);
    let сдвиг = |c: f64| размах * даль * (c / размах).tanh();
    Источник {
        точка: (
            (точка.0 - сдвиг(камера.0)) * масштаб,
            (точка.1 - сдвиг(камера.1)) * масштаб,
        ),
        охват: (радиус * масштаб).max(1.0),
    }
}

/// Как свет падает на прямоугольник с центром `центр`.
///
/// Возвращает единичное направление НА источник в экранных координатах и долю
/// силы 0…1 — сколько света сюда доходит. `None` — не доходит ничего, и окну
/// незачем нести лишние uniform'ы.
///
/// Спад квадратичный: линейный на краю охвата даёт заметную границу («здесь
/// светит, а на пиксель дальше нет»), обратный квадрат — бесконечный хвост,
/// который на холсте виден как ровная подсветка вообще всего. Квадрат от
/// остатка сходится в ноль плавно и ровно на `охват`.
pub fn на_прямоугольник(центр: (f64, f64), и: Источник) -> Option<([f32; 2], f32)> {
    let dx = и.точка.0 - центр.0;
    let dy = и.точка.1 - центр.1;
    let d = (dx * dx + dy * dy).sqrt();
    if d >= и.охват {
        return None;
    }
    // Ровно в источнике направления нет; светим сверху — это ближе всего к
    // «свет прямо над окном» и не даёт делить на ноль.
    let напр = if d < 1e-3 {
        [0.0, -1.0]
    } else {
        [(dx / d) as f32, (dy / d) as f32]
    };
    let остаток = 1.0 - d / и.охват;
    Some((напр, (остаток * остаток) as f32))
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn на_малых_перемещениях_едет_как_холст() {
        // Зум 1, камера в нуле — источник стоит там, где стоит.
        let и = источник((1000.0, 500.0), 400.0, (0.0, 0.0), 1.0, 1.0, 5000.0);
        assert!((и.точка.0 - 1000.0).abs() < 1e-9 && (и.точка.1 - 500.0).abs() < 1e-9);
        assert!((и.охват - 400.0).abs() < 1e-9);
        // Камера уехала на 300 при размахе 5000 — tanh здесь ещё неотличим от
        // прямой, и источник ушёл влево ровно на столько же. Полпикселя
        // допуска: tanh отстаёт от прямой в третьем порядке.
        let и2 = источник((1000.0, 500.0), 400.0, (300.0, 0.0), 1.0, 1.0, 5000.0);
        assert!((и2.точка.0 - 700.0).abs() < 0.5, "x = {}", и2.точка.0);
        // Отдалились вдвое — и охват вдвое меньше.
        let и3 = источник((1000.0, 500.0), 400.0, (0.0, 0.0), 0.5, 1.0, 5000.0);
        assert!((и3.охват - 200.0).abs() < 1e-9);
    }

    #[test]
    fn даль_0_приклеивает_к_экрану() {
        // Ни камера, ни зум ничего не меняют: свет как из лампы над монитором.
        let а = источник((1000.0, 500.0), 400.0, (0.0, 0.0), 1.0, 0.0, 5000.0);
        let б = источник((1000.0, 500.0), 400.0, (9999.0, -8888.0), 0.2, 0.0, 5000.0);
        assert!((а.точка.0 - б.точка.0).abs() < 1e-9 && (а.точка.1 - б.точка.1).abs() < 1e-9);
        assert!((а.охват - б.охват).abs() < 1e-9);
    }

    #[test]
    fn далёкий_источник_не_теряется_после_дальнего_перелёта() {
        // Ровно та беда, ради которой заведено насыщение: камера ушла на
        // 20 000 пикселей — источник, честно стоящий на холсте, давно за краем
        // света, а далёкий упёрся в свой размах и остался при экране.
        let экран = 2560.0;
        let и = источник((2000.0, 200.0), 4000.0, (20_000.0, 0.0), 1.0, 0.25, экран);
        assert!(
            и.точка.0 + и.охват > 0.0 && и.точка.0 - и.охват < экран,
            "свет обязан доставать до экрана: x={} охват={}",
            и.точка.0,
            и.охват,
        );
    }

    #[test]
    fn направление_смотрит_на_источник() {
        let и = Источник { точка: (2000.0, 100.0), охват: 3000.0 };
        // Окно слева и ниже: свет приходит справа сверху.
        let (напр, сила) = на_прямоугольник((500.0, 800.0), и).expect("свет доходит");
        assert!(напр[0] > 0.0, "источник справа: {напр:?}");
        assert!(напр[1] < 0.0, "и выше: {напр:?}");
        assert!((напр[0] * напр[0] + напр[1] * напр[1] - 1.0).abs() < 1e-5, "не единичный");
        assert!(сила > 0.0 && сила < 1.0);
    }

    #[test]
    fn сила_падает_с_расстоянием_и_кончается_на_охвате() {
        let и = Источник { точка: (0.0, 0.0), охват: 1000.0 };
        let (_, ближе) = на_прямоугольник((100.0, 0.0), и).unwrap();
        let (_, дальше) = на_прямоугольник((700.0, 0.0), и).unwrap();
        assert!(ближе > дальше, "{ближе} против {дальше}");
        assert!(на_прямоугольник((1000.0, 0.0), и).is_none(), "на охвате света нет");
        assert!(на_прямоугольник((5000.0, 0.0), и).is_none(), "и дальше тоже");
        // У самого края спад обязан быть плавным, а не обрывом: иначе окно,
        // проезжающее границу охвата, мигнёт.
        let (_, у_края) = на_прямоугольник((990.0, 0.0), и).unwrap();
        assert!(у_края < 0.001, "у края почти ноль: {у_края}");
    }

    #[test]
    fn в_самом_источнике_направления_не_делим_на_ноль() {
        let и = Источник { точка: (10.0, 10.0), охват: 500.0 };
        let (напр, сила) = на_прямоугольник((10.0, 10.0), и).unwrap();
        assert!(напр[0].is_finite() && напр[1].is_finite());
        assert!((сила - 1.0).abs() < 1e-6, "в источнике свет в полную силу");
    }
}
