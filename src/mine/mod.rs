/// Шаг режима из главного цикла. Как и у VR, рендерер берём из устройства udev;
/// в headless он передаётся явно (см. [`тик_с`]).
pub fn тик(state: &mut Parallax) {
    if state.mine.is_none() {
        return;
    }
    let mut устройства = std::mem::take(&mut state.udev_devices);
    if let Some(устройство) = устройства.values_mut().next() {
        let гles = &mut устройство.gles as *mut GlesRenderer;
        // Безопасно по той же причине, что и в `udev::render_all`: `state`
        // больше не владеет устройствами, второго пути к рендереру нет.
        unsafe { тик_с(state, &mut *гles) };
    }
    state.udev_devices = устройства;
}

/// Тот же шаг с явно переданным рендерером — так режим работает и в headless,
/// где `GlesRenderer` живёт внутри замыкания таймера. Благодаря этому вся
/// parallax-сторона plx-mine проверяется харнессом без Minecraft вообще.
pub fn тик_с(state: &mut Parallax, renderer: &mut GlesRenderer) {
    net::убрать_мёртвого(state);
    let Some(шахта) = state.mine.as_ref() else { return };
    // Мода нет или он ещё не поздоровался — рисовать некому. Сокет при этом
    // продолжает слушать: человек как раз запускает игру.
    if !шахта.мод_на_связи() {
        return;
    }

    // ── Сцена ───────────────────────────────────────────────────────────────
    let окна = окна_сцены(state);
    {
        let Some(шахта) = state.mine.as_mut() else { return };
        шахта.сцена.свести(&окна.iter().map(|(_, окно)| *окно).collect::<Vec<_>>());
        шахта.сцена.разложить();
    }

    // Игра — всегда самая верхняя на мониторе. Проверка стоит на каждом кадре
    // нарочно: поднять окно поверх неё умеет не только клик мода и появление
    // нового окна (они чинятся по месту), но и любой бинд, метящий в фокус, —
    // Alt+Tab, обзор, «поднять в мастер-слот». Из игры это выглядит одинаково:
    // мир на мгновение сменился рабочим столом.
    игру_наверх(state);

    // ── Список панелей ──────────────────────────────────────────────────────
    //
    // СТРОГО ДО пикселей. Пиксели адресованы панели по ключу, а завести под
    // них текстуру мод может, только зная её размер: кусок, пришедший раньше
    // списка, ему просто некуда положить. Замер 31.08.2026 (проба на
    // харнессе): при обратном порядке первый — и единственный, пока окно
    // неподвижно, — кадр уходил в никуда, и панель оставалась чёрной.
    послать_панели(state);

    // ── Полотна и пиксели ───────────────────────────────────────────────────
    for (окно, в_сцене) in &окна {
        отдать_окно(state, renderer, окно, *в_сцене);
    }
    {
        // Полотна закрытых окон освобождаем: текстура окна 2560×1080 — это
        // 11 МиБ, десяток забытых съедает больше, чем весь остальной parallax.
        let живые: std::collections::HashSet<Ключ> = окна.iter().map(|(_, в_сцене)| в_сцене.ключ).collect();
        if let Some(шахта) = state.mine.as_mut() {
            шахта.полотна.retain(|к, _| живые.contains(к));
            шахта.посланные.retain(|к, _| живые.contains(к));
        }
    }

    // ── Указка → курсор parallax ────────────────────────────────────────────────
    применить_ввод(state);

    if let Some(шахта) = state.mine.as_mut() {
        шахта.кадров += 1;
    }
}

/// Окна для сцены — те же, что в шлеме, но БЕЗ окна самой игры.
///
/// Без этой строки Minecraft висит панелью внутри себя: человек видит в мире
/// собственный экран «монитором» и ничего больше — окно игры развёрнуто, и
/// кроме него в сцене чаще всего нет никого (замер 01.09.2026, живой сеанс).
fn окна_сцены(state: &mut Parallax) -> Vec<(Window, crate::vr::scene::ОкноВСцене)> {
    найти_окно_игры(state);
    let игра = state.mine.as_ref().and_then(|ш| ш.окно_игры.clone());
    crate::vr::окна_для_сцены(state)
        .into_iter()
        .filter(|(окно, _)| игра.as_ref() != Some(окно))
        .collect()
}

/// Найти окно игры по pid на том конце сокета. Ищем один раз и запоминаем;
/// закрытое окно (или ещё не появившееся) отпускаем и ищем снова.
///
/// **Почему pid, а не заголовок.** Заголовок у Minecraft меняется («Minecraft*
/// 26.2», в одиночной игре — с именем мира), а мод сидит в ЕЁ ЖЕ процессе:
/// `SO_PEERCRED` даёт тот самый pid без единой догадки.
fn найти_окно_игры(state: &mut Parallax) {
    let живо = state
        .mine
        .as_ref()
        .and_then(|ш| ш.окно_игры.as_ref())
        .is_some_and(|окно| state.space.elements().any(|w| w == окно));
    if живо {
        return;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.окно_игры = None;
    }
    let Some(pid) = state.mine.as_ref().and_then(|ш| ш.мод.as_ref()).and_then(|м| м.pid) else {
        return;
    };
    let найдено = state
        .space
        .elements()
        .find(|окно| pid_окна(state, окно) == Some(pid))
        .cloned();
    if let Some(окно) = найдено {
        tracing::info!("plx/mine: game window found by pid {pid} — kept out of the scene");
        if let Some(шахта) = state.mine.as_mut() {
            шахта.окно_игры = Some(окно);
        }
    }
}

/// Процесс, которому принадлежит окно.
///
/// У Wayland-клиента — из `wl_client`; у X11 (а Minecraft приходит именно
/// через Xwayland) этот путь бесполезен: все X11-окна принадлежат одному
/// процессу, самому Xwayland. Поэтому для них спрашиваем `_NET_WM_PID` у
/// самого окна.
fn pid_окна(state: &Parallax, окно: &Window) -> Option<u32> {
    match окно.underlying_surface() {
        // У X11-окна pid знает сам XWM — он читает `_NET_WM_PID` при
        // отображении окна. Прямое чтение свойства оставлено запасным путём:
        // клиент вправе выставить его и позже, а у XWM оно к тому моменту уже
        // прочитано и закэшировано.
        smithay::desktop::WindowSurface::X11(s) => {
            s.pid().or_else(|| crate::icons::pid_окна_x11(s.window_id()))
        }
        smithay::desktop::WindowSurface::Wayland(t) => {
            use smithay::reexports::wayland_server::Resource as _;
            let клиент = t.wl_surface().client()?;
            клиент
                .get_credentials(&state.display_handle)
                .ok()
                .and_then(|c| u32::try_from(c.pid).ok())
        }
    }
}

/// Нарисовать окно в полотно и отдать моду то, что изменилось.
fn отдать_окно(
    state: &mut Parallax,
    renderer: &mut GlesRenderer,
    окно: &Window,
    в_сцене: crate::vr::scene::ОкноВСцене,
) {
    let (ш, в) = (в_сцене.ширина_пкс.max(1), в_сцене.высота_пкс.max(1));
    let повреждения = {
        let Some(шахта) = state.mine.as_mut() else { return };
        crate::vr::нарисовать_в_полотно(&mut шахта.полотна, renderer, окно, в_сцене)
    };
    // Размер поменялся — мод обязан завести текстуру заново, и до этого любые
    // куски старого размера легли бы у него не туда. Полный кадр.
    let размер_сменился = state
        .mine
        .as_ref()
        .and_then(|ш| ш.посланные.get(&в_сцене.ключ).copied())
        != Some((ш as u16, в as u16));

    let куски: Vec<Rectangle<i32, Physical>> = match повреждения {
        Повреждения::Мимо => return,
        Повреждения::Всё => vec![Rectangle::from_size((ш, в).into())],
        Повреждения::Куски(к) => {
            if размер_сменился {
                vec![Rectangle::from_size((ш, в).into())]
            } else if к.is_empty() {
                // Самый частый кадр: окно неподвижно, слать нечего. Именно
                // отсюда берётся дешевизна режима на неподвижном экране.
                return;
            } else {
                к
            }
        }
    };

    let текстура = {
        let Some(шахта) = state.mine.as_ref() else { return };
        match шахта.полотна.get(&в_сцене.ключ) {
            Some(п) => п.текстура.clone(),
            None => return,
        }
    };
    let mut цель = текстура;
    let mut ушло_байт = 0u64;
    for кусок in куски {
        // Зажимаем в полотно: трекер повреждений отдаёт прямоугольники в
        // координатах вывода, и кусок, вылезший за край (окно уменьшилось в
        // этом же кадре), заставил бы GL читать за пределами буфера.
        let Some(кусок) = кусок.intersection(Rectangle::from_size((ш, в).into())) else {
            continue;
        };
        if кусок.size.w <= 0 || кусок.size.h <= 0 {
            continue;
        }
        // Полосами: сообщение не упирается в предел протокола, и мод заливает
        // в текстуру уже пришедшее, не дожидаясь всего куска.
        let высота_полосы = proto::ПОЛОСА as i32;
        let mut y = кусок.loc.y;
        while y < кусок.loc.y + кусок.size.h {
            let h = высота_полосы.min(кусок.loc.y + кусок.size.h - y);
            let полоса = Rectangle::<i32, Physical>::new(
                (кусок.loc.x, y).into(),
                (кусок.size.w, h).into(),
            );
            if let Some(данные) = вычитать(renderer, &mut цель, полоса) {
                ушло_байт += данные.len() as u64;
                net::послать(
                    state,
                    &proto::ОтДавна::Пиксели {
                        ключ: в_сцене.ключ,
                        x: полоса.loc.x as u16,
                        y: полоса.loc.y as u16,
                        ш: полоса.size.w as u16,
                        в: полоса.size.h as u16,
                        данные,
                    },
                    // Пиксели ронять МОЖНО: если мод не успевает, свежая
                    // картинка важнее полной. Потерянный кусок вернётся, как
                    // только клиент нарисует что-нибудь ещё... а если не
                    // нарисует — его вернёт `посланные`, см. ниже.
                    true,
                );
            }
            y += h;
        }
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.посланные.insert(в_сцене.ключ, (ш as u16, в as u16));
        шахта.байт += ушло_байт;
    }
}

/// Прочитать кусок полотна в RGBA8.
///
/// `Abgr8888` — это байты R,G,B,A подряд, то есть ровно то, что JVM зальёт в
/// текстуру как `GL_RGBA` без единой перестановки. `Argb8888` был бы на одно
/// расширение драйвера рискованнее и потребовал бы свопа на чьей-то стороне
/// (см. `screencopy.rs`, где ради совместимости приходится уметь оба).
fn вычитать(
    renderer: &mut GlesRenderer,
    цель: &mut smithay::backend::renderer::gles::GlesTexture,
    кусок: Rectangle<i32, Physical>,
) -> Option<Vec<u8>> {
    use smithay::backend::allocator::Fourcc;
    let fb = match renderer.bind(цель) {
        Ok(fb) => fb,
        Err(e) => {
            tracing::warn!("plx/mine: canvas bind: {e:?}");
            return None;
        }
    };
    let в_буфере = Rectangle::<i32, smithay::utils::Buffer>::new(
        (кусок.loc.x, кусок.loc.y).into(),
        (кусок.size.w, кусок.size.h).into(),
    );
    let слепок = match renderer.copy_framebuffer(&fb, в_буфере, Fourcc::Abgr8888) {
        Ok(с) => с,
        Err(e) => {
            tracing::warn!("plx/mine: copy_framebuffer: {e:?}");
            return None;
        }
    };
    // fb держит &mut цель, а map_texture хочет &mut renderer — отпускаем.
    drop(fb);
    match renderer.map_texture(&слепок) {
        Ok(данные) => Some(данные.to_vec()),
        Err(e) => {
            tracing::warn!("plx/mine: map_texture: {e:?}");
            None
        }
    }
}

/// Отдать моду список панелей, если он изменился.
fn послать_панели(state: &mut Parallax) {
    let новый: Vec<proto::Панель> = {
        let Some(шахта) = state.mine.as_ref() else { return };
        шахта
            .сцена
            .панели
            .iter()
            .map(|п| в_протокол(п, заголовок(state, п.ключ)))
            .collect()
    };
    let изменилось = state
        .mine
        .as_ref()
        .is_some_and(|ш| ш.слепок != новый);
    if !изменилось {
        return;
    }
    // Печатаем только на изменении списка — на неподвижном экране это ноль
    // строк. Без неё «окон в игре не видно» неразличимо с «сцена пуста»:
    // окно игры вычитается, и если других окон нет, мод честно рисует ничто.
    tracing::info!(
        "plx/mine: {} panels — [{}]",
        новый.len(),
        новый.iter().map(|п| п.заголовок.as_str()).collect::<Vec<_>>().join(", ")
    );
    net::послать(state, &proto::ОтДавна::Панели(новый.clone()), false);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.слепок = новый;
    }
}

fn в_протокол(п: &Панель, заголовок: String) -> proto::Панель {
    let м = п.поза.место;
    let к = п.поза.поворот;
    proto::Панель {
        ключ: п.ключ,
        место: [м.x, м.y, м.z],
        поворот: [к.x, к.y, к.z, к.w],
        пол_ширина: п.пол_ширина,
        пол_высота: п.пол_высота,
        ш_пкс: п.ширина_пкс.clamp(1, u16::MAX as i32) as u16,
        в_пкс: п.высота_пкс.clamp(1, u16::MAX as i32) as u16,
        заголовок,
    }
}

/// Заголовок окна для таблички над панелью.
fn заголовок(state: &Parallax, ключ: Ключ) -> String {
    crate::vr::окно_по_ключу(state, ключ)
        .and_then(|о| crate::xwin::title(&о).or_else(|| crate::xwin::app_id(&о)))
        .unwrap_or_default()
}

// ── Ввод ────────────────────────────────────────────────────────────────────

/// Луч игрока → курсор parallax. Ровно та же логика, что у указки в шлеме, и по
/// той же причине: дальше работает весь существующий код — `surface_under`,
/// фокус по наведению, клики, перетаскивание, меню.
fn применить_ввод(state: &mut Parallax) {
    // ── Закреплённое окно (ЛКМ по панели) ───────────────────────────────────
    //
    // Управление отдано ОДНОМУ окну: стрелку по нему ведёт мышь, взгляд не
    // участвует. Ветка стоит первой и до луча не доходит вовсе — в этом весь
    // смысл режима: игрок вправе смотреть куда угодно, пока печатает.
    //
    // Закрепление за закрытым окном отпускаем молча: панель исчезла, держаться
    // не за что, и указка возвращается взгляду.
    if let Some((ключ, x, y)) = state.mine.as_ref().and_then(|ш| ш.закреплено) {
        match crate::vr::окно_по_ключу(state, ключ) {
            Some(окно) => {
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.наведено = Some((ключ, x, y));
                }
                let брать_фокус = взять_фокус(state, ключ);
                seat::навести(state, &окно, x, y, брать_фокус);
                послать_курсор(state, ключ, x as f32, y as f32, true);
                return;
            }
            None => {
                отпустить_кнопку(state);
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.закреплено = None;
                }
            }
        }
    }

    let Some(луч) = state.mine.as_ref().and_then(|ш| ш.луч) else { return };

    // ── Изменение размера окна (Super+ПКМ) ──────────────────────────────────
    //
    // Стоит ДО перетаскивания: обе ветки висят на одной кнопке, и занята
    // одновременно может быть только одна.
    if let Some(изм) = state.mine.as_ref().and_then(|ш| ш.меняем_размер) {
        вести_изменение_размера(state, изм, луч);
        return;
    }

    // ── Перетаскивание панели ───────────────────────────────────────────────
    if let Some((индекс, расстояние)) = state.mine.as_ref().and_then(|ш| ш.тащим) {
        // Глаз игрока — начало его же луча: другого положения головы у нас нет,
        // и оно тут единственно верное (панель разворачивается к тому, кто её
        // тащит).
        let глаз = луч.начало;
        if let Some(шахта) = state.mine.as_mut() {
            if индекс < шахта.сцена.панели.len() {
                шахта.сцена.перенести(индекс, луч, расстояние, глаз);
            } else {
                // Окно закрылось, пока его тащили: хват отпускаем, иначе
                // индекс указывал бы в чужую панель.
                шахта.тащим = None;
            }
        }
        // Пока тащим — курсор в окно не гоняем: окно получало бы «мышь ездит»
        // на каждый кадр переноса.
        return;
    }

    let попал = state.mine.as_ref().and_then(|ш| ш.сцена.навести(луч));
    let наведено = попал.and_then(|(i, x, y)| {
        state
            .mine
            .as_ref()
            .map(|ш| (ш.сцена.панели[i].ключ, x, y))
    });
    if let Some(шахта) = state.mine.as_mut() {
        шахта.наведено = наведено;
    }

    // ── Указка → своё место ─────────────────────────────────────────────────
    //
    // Ни курсор хозяина, ни его фокус здесь больше не трогаются: у мода своё
    // место (`seat.rs`). Именно поэтому исчезло правило «пока трогают мышь,
    // указка молчит», которое живёт в шлеме: спорить не с кем — хозяйская мышь
    // осталась у Minecraft и крутит игроку голову.
    let Some((ключ, пкс_x, пкс_y)) = наведено else {
        // Взгляд в пустоту: зажатую кнопку отпускаем, иначе окно осталось бы с
        // нажатой мышью навсегда.
        отпустить_кнопку(state);
        seat::увести(state);
        // Взгляд ушёл в мир: следующий заход на панель снова отдаст ей
        // клавиатуру. Сам фокус при этом не снимается (см. `seat::увести`) —
        // забывается только «этой панели уже отдавали».
        if let Some(шахта) = state.mine.as_mut() {
            шахта.фокус_взгляда = None;
        }
        послать_курсор(state, 0, 0.0, 0.0, false);
        return;
    };

    if let Some(окно) = crate::vr::окно_по_ключу(state, ключ) {
        let брать_фокус = взять_фокус(state, ключ);
        seat::навести(state, &окно, пкс_x, пкс_y, брать_фокус);
    }
    послать_курсор(state, ключ, пкс_x as f32, пкс_y as f32, true);
}

/// Пора ли отдавать клавиатуру панели под взглядом.
///
/// Правило: фокус едет за взглядом на ВХОДЕ на панель — ровно так же, как
/// sloppy focus на столе едет за ДВИЖЕНИЕМ мыши, а не за тем, где она лежит.
/// Разница не косметическая: пока панель под лучом та же, фокусом распоряжается
/// человек — Alt+Tab, Super+J, «фокус влево», выбор в обзоре и новое окно,
/// открытое прямо из игры, сохраняют клавиатуру за собой. Переустановка на
/// каждом кадре откатывала их за один кадр, и снаружи это выглядело как «бинды
/// не работают».
fn взять_фокус(state: &mut Parallax, ключ: Ключ) -> bool {
    let Some(шахта) = state.mine.as_mut() else { return false };
    if шахта.фокус_взгляда == Some(ключ) {
        return false;
    }
    шахта.фокус_взгляда = Some(ключ);
    true
}

/// Где рисовать стрелку. Курсор parallax живёт поверх кадра монитора и в полотно
/// панели не попадает вовсе, поэтому в игре его рисует мод — иначе не видно,
/// куда нажмёшь.
///
/// Шлём только НА ИЗМЕНЕНИЕ: сообщение короткое, но идёт оно каждый кадр, а на
/// той стороне это разбор в игровом такте и лишний повод перерисовать стрелку.
/// Сравниваем в пикселях панели — то есть в тех же числах, что уедут по
/// проводу: сравнивать луч бессмысленно, дрожь взгляда в четверть пикселя мод
/// всё равно не увидит.
fn послать_курсор(state: &mut Parallax, ключ: Ключ, x: f32, y: f32, видим: bool) {
    // Невидимый курсор — это «стрелки нет»; панель и точку в нём не сравниваем,
    // иначе взгляд, ушедший с панели на другую, слал бы «не видно» дважды.
    let сейчас = if видим { (ключ, x, y, true) } else { (0, 0.0, 0.0, false) };
    if state.mine.as_ref().is_some_and(|ш| ш.посланный_курсор == Some(сейчас)) {
        return;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.посланный_курсор = Some(сейчас);
    }
    net::послать(state, &proto::ОтДавна::Курсор { ключ, x, y, видим }, true);
}

/// Держит ли игрок Super — на СВОЁМ месте или на хозяйском.
///
/// Мест два, и оба настоящие. При полном перехвате (F7) клавиши уезжают моду и
/// попадают на место `plx-mine`; в обычной игре мод в клавиатуру не лезет вовсе —
/// её слышит окно Minecraft, то есть хозяйское место. ПКМ при этом мод шлёт в
/// обоих случаях (`Control.кнопка`), так что Super+ПКМ обязан работать и там, и
/// там — иначе ресайз был бы доступен только внутри перехвата.
fn супер_зажат(state: &Parallax) -> bool {
    let своё = state
        .mine
        .as_ref()
        .and_then(|ш| ш.место.as_ref())
        .and_then(|м| м.get_keyboard())
        .is_some_and(|к| к.modifier_state().logo);
    своё
        || state
            .seat
            .get_keyboard()
            .is_some_and(|к| к.modifier_state().logo)
}

/// Сделать окно плавающим на время ресайза — и навсегда после него.
///
/// **Без этого ресайза не было вовсе.** Раскладка пересчитывает размеры тайловых
/// окон из своего дерева на КАЖДОЙ перекладке (новое окно, смена стола, обзор,
/// закрытие соседа), так что натянутый `set_size` стирался ближайшим же поводом.
/// Замер на харнессе 01.09.2026: панель дотянули до 3133×1153, обзор столов
/// вернул 2508×1028 — это и есть жалоба «нажимаю Win+ПКМ, ничего не
/// происходит».
///
/// **Почему не деления дерева, как у мыши на столе** (`resize_grab.rs` тянет
/// `dwindle_resize_focused`). Две причины, и обе решающие. Первая: соседом по
/// дереву в игре сплошь и рядом оказывается САМО окно Minecraft — тянуть
/// деление значило бы менять размер игры из-под игрока. Вторая: единственному
/// тайловому окну дерево двигать нечего, и ресайз молча не делал бы ничего
/// (проверено на харнессе: одно окно, `ресайз` — 2508×1028 до и после).
///
/// В мире тайлинга нет: панель уже таскают взглядом свободно (`Хват`), и размер
/// обязан вести себя так же. `float_pinned` — «выбор человека», сборка в
/// тайлинг его не отменяет (см. `tiling::toggle_floating`).
fn выпустить_из_тайлинга(state: &mut Parallax, окно: &Window) {
    let было = state
        .tagged_windows
        .iter_mut()
        .find(|tw| &tw.window == окно)
        .map(|tw| {
            let было = tw.floating;
            tw.floating = true;
            tw.float_pinned = true;
            было
        });
    if было == Some(false) {
        // Соседи занимают освободившееся место — как при `toggle_floating`.
        state.arrange();
    }
}

/// Взять окно под взглядом на ресайз: запомнить линейку и размер на старте.
fn начать_изменение_размера(state: &mut Parallax) {
    let Some(луч) = state.mine.as_ref().and_then(|ш| ш.луч) else { return };
    let Some(шахта) = state.mine.as_ref() else { return };
    let Some((i, _, _)) = шахта.сцена.навести(луч) else { return };
    let опора = шахта.сцена.панели[i];
    // Точку захвата берём в МЕТРАХ панели, а не в её пикселях: пиксели —
    // производная от размера окна, который мы как раз собираемся менять.
    let Some((_, местная_x, местная_y)) = луч.попал(опора.поза, опора.пол_ширина, опора.пол_высота)
    else {
        return;
    };
    let Some(окно) = crate::vr::окно_по_ключу(state, опора.ключ) else { return };
    выпустить_из_тайлинга(state, &окно);
    let размер0 = crate::xwin::current_size(&окно);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.тащим = None;
        шахта.меняем_размер = Some(ИзменениеРазмера {
            ключ: опора.ключ,
            опора,
            местная_x,
            местная_y,
            размер0,
        });
    }
    tracing::info!(
        "plx/mine: panel {} resized from {}×{}",
        опора.ключ, размер0.w, размер0.h
    );
}

/// Вести размер за взглядом, пока держат Super+ПКМ.
///
/// Правило простое: сколько взгляд прошёл по ЗАМОРОЖЕННОЙ плоскости панели,
/// на столько и меняется окно — как будто тянешь его правый нижний угол.
fn вести_изменение_размера(state: &mut Parallax, изм: ИзменениеРазмера, луч: Луч) {
    let Some(окно) = crate::vr::окно_по_ключу(state, изм.ключ) else {
        // Окно закрылось под рукой — держаться не за что.
        if let Some(шахта) = state.mine.as_mut() {
            шахта.меняем_размер = None;
        }
        return;
    };
    // Плоскость опоры БЕЗ границ: тянуть окно больше исходной панели — обычное
    // дело, а `попал` за её краем вернул бы None и ресайз замирал бы ровно там,
    // где начинается интересное.
    const БЕЗ_ГРАНИЦ: f32 = 1.0e4;
    let Some((_, x, y)) = луч.попал(изм.опора.поза, БЕЗ_ГРАНИЦ, БЕЗ_ГРАНИЦ) else { return };
    let пкс_на_метр_x = изм.опора.ширина_пкс as f32 / (2.0 * изм.опора.пол_ширина.max(1e-4));
    let пкс_на_метр_y = изм.опора.высота_пкс as f32 / (2.0 * изм.опора.пол_высота.max(1e-4));
    let (dw, dh) = размер_по_взгляду(&изм, x, y, пкс_на_метр_x, пкс_на_метр_y);

    let новый = smithay::utils::Size::<i32, smithay::utils::Logical>::from((
        (изм.размер0.w + dw).clamp(МЕНЬШЕ_НЕЛЬЗЯ, БОЛЬШЕ_НЕЛЬЗЯ),
        (изм.размер0.h + dh).clamp(МЕНЬШЕ_НЕЛЬЗЯ, БОЛЬШЕ_НЕЛЬЗЯ),
    ));
    if crate::xwin::current_size(&окно) == новый {
        return;
    }
    crate::xwin::set_size(&окно, Some(новый), crate::xwin::Tiled::Keep);
    crate::xwin::configure(&окно);
    state.request_redraw();
}

/// Пределы размера окна при ресайзе взглядом, логические пиксели.
///
/// Раньше пола не было вовсе (`.max(1)`), а потолка нет и сейчас нигде больше —
/// но здесь они обязательны, и вот почему. Линейка ресайза — плоскость
/// схваченной панели, а взгляд по ней ходит через тангенс: у самого края поля
/// зрения крошечное движение мыши уводит точку пересечения на десятки метров.
/// В пикселях это окно шириной в сотню тысяч — клиент на такой `configure`
/// отвечает либо мусором, либо смертью. Снизу то же самое с другой стороны:
/// окно в один пиксель нельзя ни увидеть, ни схватить обратно.
const МЕНЬШЕ_НЕЛЬЗЯ: i32 = 120;
const БОЛЬШЕ_НЕЛЬЗЯ: i32 = 8192;

/// Насколько далеко от точки захвата считается взгляд, в полуразмерах панели.
///
/// Тот же тангенс: дальше этого движение уже не «тяну окно», а «мазнул мышью
/// мимо», и честно пересчитывать его в пиксели незачем.
const ДАЛЬШЕ_НЕ_ТЯНЕМ: f32 = 3.0;

/// Насколько изменить окно, когда взгляд пришёл в точку `(x, y)` плоскости
/// опоры (метры её местных координат).
///
/// **Правило: ведёшь взгляд ОТ СЕРЕДИНЫ панели — окно растёт, к середине —
/// жмётся.** Панель висит в мире серединой на своём месте и растёт во все
/// стороны сразу (`Сцена::свести` считает полуразмеры из размера окна), поэтому
/// «тяну за край» здесь значит именно «удаляю взгляд от середины» — с какой бы
/// стороны ни взялся. Отсюда и двойка: половина уходит в одну сторону, половина
/// в другую, а взгляд провожает ровно одну из них.
///
/// **Что было и почему это читалось как перевёрнутый ресайз.** Считалась
/// разность со знаком: вправо — растёт, влево — жмётся, независимо от того,
/// за какую половину панели взялись. Взял левую половину, повёл взгляд влево
/// (то есть НАРУЖУ, «тяну левый край левее») — окно ужималось. Ровно половина
/// движений работала наоборот, что снаружи и выглядит как «ресайз инвертирован».
///
/// Знак `y` тут больше не нужен: сравниваются РАССТОЯНИЯ от середины, а они
/// одинаковы что вверх, что вниз.
fn размер_по_взгляду(
    изм: &ИзменениеРазмера,
    x: f32,
    y: f32,
    пкс_на_метр_x: f32,
    пкс_на_метр_y: f32,
) -> (i32, i32) {
    let предел_x = изм.опора.пол_ширина.max(1e-4) * ДАЛЬШЕ_НЕ_ТЯНЕМ;
    let предел_y = изм.опора.пол_высота.max(1e-4) * ДАЛЬШЕ_НЕ_ТЯНЕМ;
    let было_x = изм.местная_x.abs().min(предел_x);
    let было_y = изм.местная_y.abs().min(предел_y);
    let стало_x = x.abs().min(предел_x);
    let стало_y = y.abs().min(предел_y);
    (
        (2.0 * (стало_x - было_x) * пкс_на_метр_x).round() as i32,
        (2.0 * (стало_y - было_y) * пкс_на_метр_y).round() as i32,
    )
}

/// Ближе и дальше этого схваченную панель не утянуть, метры (они же блоки).
///
/// Ближняя граница — из шлема: вплотную к лицу панель не читается. Дальняя своя
/// и щедрая: в мире некуда упереться, но панель, улетевшая за прорисовку чанков,
/// перестала бы рисоваться вовсе — а человек считал бы, что окно потерялось.
const БЛИЖЕ_НЕЛЬЗЯ: f32 = 0.35;
const ДАЛЬШЕ_НЕЛЬЗЯ: f32 = 64.0;

/// Один зубец колеса меняет расстояние в этой пропорции.
///
/// Множитель, а не слагаемое, как у стика в шлеме (`vr/mod.rs`: `+ стик.1 *
/// 0.04`). Разница не в прихоти, а в том, что там непрерывное отклонение при
/// диапазоне в комнату, а здесь — дискретный щелчок при диапазоне в 64 блока:
/// постоянный шаг был бы на вытянутой руке грубым рывком, а в тридцати блоках
/// — незаметным. У доли же шаг всегда «на столько же, на сколько прошлый»:
/// вдвое дальше — за шесть зубцов на любом расстоянии.
const ЗУБЕЦ: f32 = 1.12;

/// Колесо, пока панель тащат: притянуть или оттолкнуть её.
///
/// `true` — колесо съедено тягой и в окно не уходит. Прокручивать содержимое
/// панели, которую в этот момент несут перед собой, всё равно некому: указка
/// занята переносом, и курсор в окно на это время не гоняется вовсе (см.
/// [`применить_ввод`]).
fn тяга_колесом(state: &mut Parallax, dy: f32) -> bool {
    let Some(шахта) = state.mine.as_mut() else { return false };
    let Some((индекс, расстояние)) = шахта.тащим else { return false };
    // Колесо ВВЕРХ (у мода это плюс — договор GLFW) толкает панель от себя:
    // то же направление, что у стика вверх в шлеме.
    let новое = (расстояние * ЗУБЕЦ.powf(dy)).clamp(БЛИЖЕ_НЕЛЬЗЯ, ДАЛЬШЕ_НЕЛЬЗЯ);
    шахта.тащим = Some((индекс, новое));
    // Сам перенос делает `применить_ввод` ближайшим кадром — по тому же лучу,
    // что и всегда. Своей копии `перенести` здесь нет нарочно: она разъехалась
    // бы с той по развороту панели лицом к игроку.
    state.request_redraw();
    true
}

fn отпустить_кнопку(state: &mut Parallax) {
    let держим = state.mine.as_ref().is_some_and(|ш| ш.кнопка_нажата);
    if !держим {
        return;
    }
    seat::кнопка(state, None, crate::synth::КНОПКА_ЛКМ, false);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.кнопка_нажата = false;
    }
}

/// Запомнить луч указки. Отдельной функцией, потому что этим путём ходят двое:
/// живой мод (через [`принять_сообщение`]) и харнесс (через [`луч_снаружи`]).
/// Проверка вырожденного направления обязана быть общей: NaN, пропущенный на
/// одном из путей, потом тихо разъезжается по всей сцене.
fn запомнить_луч(state: &mut Parallax, начало: [f32; 3], направление: [f32; 3]) -> bool {
    let л = Луч::new(
        Век3::new(начало[0], начало[1], начало[2]),
        Век3::new(направление[0], направление[1], направление[2]),
    );
    if !л.направление.длина().is_finite() || л.направление.длина() < 0.5 {
        tracing::warn!("plx/mine: degenerate ray {направление:?} — skipping");
        return false;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.луч = Some(л);
    }
    state.request_redraw();
    true
}

/// Сообщение от мода. `false` — соединение рвём.
pub fn принять_сообщение(state: &mut Parallax, сообщение: proto::ОтМода) -> bool {
    let впущен = state
        .mine
        .as_ref()
        .and_then(|ш| ш.мод.as_ref())
        .is_some_and(|м| м.впущен);

    // До «привета» не принимаем ничего: мод чужой версии обязан получить
    // отказ, а не начать двигать курсор по чужой раскладке полей.
    if !впущен {
        let proto::ОтМода::Привет { версия, имя } = сообщение else {
            tracing::warn!("plx/mine: mod spoke before the greeting — dropping");
            return false;
        };
        if версия != proto::ВЕРСИЯ {
            tracing::warn!(
                "plx/mine: mod speaks version {версия}, protocol is {} — dropping",
                proto::ВЕРСИЯ
            );
            return false;
        }
        let (зона_ширина, зона_глубина) = match state.mine.as_ref() {
            Some(ш) => (ш.сцена.зона.пол_ширина * 2.0, ш.сцена.зона.пол_глубина * 2.0),
            None => return false,
        };
        if let Some(м) = state.mine.as_mut().and_then(|ш| ш.мод.as_mut()) {
            м.впущен = true;
            м.имя = имя.clone();
        }
        tracing::info!("plx/mine: mod '{имя}' connected");
        net::послать(
            state,
            &proto::ОтДавна::Здравствуй { версия: proto::ВЕРСИЯ, зона_ширина, зона_глубина },
            false,
        );
        // Всё, что мод знал раньше, недействительно: пусть текстуры зальются
        // заново на ближайшем кадре.
        if let Some(шахта) = state.mine.as_mut() {
            шахта.посланные.clear();
            шахта.слепок.clear();
            // И про стрелку мод тоже ничего не знает: без сброса она появилась
            // бы у него только после следующего поворота головы.
            шахта.посланный_курсор = None;
        }
        state.request_redraw();
        return true;
    }

    // Мышь мода отменяет ожидающий тап Super — ровно как хозяйский клик
    // (`input.rs`: «Любой клик отменяет ожидающий тап Super»). Клики игрока до
    // parallax не доходят вовсе: мышь в этот момент у Minecraft, а к композитору
    // они приезжают по сокету. Без этой строки Super+ПКМ кончался обзором
    // столов на ОТПУСКАНИИ Super — и обзор перекладывал тайлинг, стирая только
    // что натянутый размер. Снаружи это и есть жалоба 01.09.2026: «нажимаю
    // Win+ПКМ, ничего не происходит, а потом камера дёргается в другую
    // сторону» (замер на харнессе: панель дотянули до 3133×1153, обзор вернул
    // 2508×1028).
    if matches!(
        сообщение,
        proto::ОтМода::Кнопка { .. } | proto::ОтМода::Хват { .. } | proto::ОтМода::Колесо { .. }
    ) {
        state.super_tap = false;
    }

    match сообщение {
        proto::ОтМода::Привет { .. } => {
            tracing::warn!("plx/mine: greeting sent twice — dropping");
            return false;
        }
        proto::ОтМода::Луч { начало, направление } => {
            запомнить_луч(state, начало, направление);
        }
        proto::ОтМода::Кнопка { код, нажата } => {
            // Кнопку жмём ТОЛЬКО когда указка на панели: клик в пустоту мира
            // Minecraft не должен уходить в окно, на которое человек не смотрит.
            let на_панели = state.mine.as_ref().is_some_and(|ш| ш.наведено.is_some());
            if нажата && !на_панели {
                return true;
            }
            let окно = state
                .mine
                .as_ref()
                .and_then(|ш| ш.наведено)
                .and_then(|(ключ, _, _)| crate::vr::окно_по_ключу(state, ключ));
            seat::кнопка(state, окно, код, нажата);
            if код == crate::synth::КНОПКА_ЛКМ {
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.кнопка_нажата = нажата;
                }
            }
        }
        proto::ОтМода::Колесо { dx, dy } => {
            // Пока панель тащат, колесо занято тягой: притянуть и оттолкнуть —
            // ровно как стик в шлеме, где хват тоже забирает стик себе.
            if тяга_колесом(state, dy) {
                return true;
            }
            // Обе оси: Minecraft отдаёт моду и горизонталь (тачпад, наклон
            // колеса), а браузер на панели без неё не прокручивался бы вбок.
            //
            // ВЕРТИКАЛЬ ПЕРЕВОРАЧИВАЕМ, и это не косметика. Мод шлёт колесо по
            // договору GLFW (и Minecraft за ним): вверх — ПЛЮС. Wayland
            // считает наоборот, у него положительная вертикаль это прокрутка
            // ВНИЗ. Без минуса всякая панель — терминал, браузер, редактор —
            // прокручивалась бы колесом задом наперёд.
            //
            // Горизонталь при этом НЕ трогаем: там оба договора совпадают,
            // плюс — вправо.
            seat::колесо(state, dx as f64, -dy as f64);
        }
        proto::ОтМода::Клавиша { код, нажата } => {
            // Через СВОЁ место, а не через `process_input_event`: хозяйская
            // клавиатура в этот момент у Minecraft, и отдать её панели значило
            // бы лишить игру даже той клавиши, которой ввод возвращают назад.
            // Бинды parallax при этом работают — их разбирает `seat::клавиша`.
            seat::клавиша(state, код, нажата);
        }
        proto::ОтМода::Указка { ключ, x, y } => {
            // Закрепление за окном, которого нет, молча пропускаем: мод мог
            // взять управление ровно тогда, когда окно закрылось.
            let есть = ключ != 0 && crate::vr::окно_по_ключу(state, ключ).is_some();
            // Кнопку, зажатую на ПРЕДЫДУЩЕЙ цели, отпускаем при смене окна —
            // иначе она осталась бы нажатой в нём навсегда.
            let прежний = state.mine.as_ref().and_then(|ш| ш.закреплено).map(|(к, _, _)| к);
            if прежний.is_some() && прежний != Some(ключ) {
                отпустить_кнопку(state);
            }
            if let Some(шахта) = state.mine.as_mut() {
                шахта.закреплено = есть.then_some((ключ, x as f64, y as f64));
            }
            применить_ввод(state);
            state.request_redraw();
        }
        proto::ОтМода::Хват { нажат } => {
            let луч = state.mine.as_ref().and_then(|ш| ш.луч);
            // Хват с Super — это не «таскать», а «менять размер». Отдельного
            // сообщения для него нет нарочно: протокол не знает про
            // модификаторы, и знать не должен — какая клавиша что значит,
            // решает parallax, ровно как с биндами (см. `seat::клавиша`).
            if нажат && супер_зажат(state) {
                начать_изменение_размера(state);
                return true;
            }
            if let Some(шахта) = state.mine.as_mut() {
                шахта.меняем_размер = None;
            }
            if let (Some(шахта), Some(луч)) = (state.mine.as_mut(), луч) {
                шахта.тащим = if нажат {
                    шахта.сцена.навести(луч).map(|(i, _, _)| {
                        let d = шахта.сцена.панели[i]
                            .поза
                            .место
                            .минус(луч.начало)
                            .длина();
                        (i, d)
                    })
                } else {
                    None
                };
            }
        }
        proto::ОтМода::Действие { имя } => match crate::config::action_from_str(&имя, "") {
            Some(действие) => {
                tracing::info!("plx/mine: action '{имя}'");
                // Выключать режим изнутри игры — верный способ остаться без
                // панелей и без способа вернуть их: клавиатура в этот момент у
                // Minecraft.
                if matches!(действие, crate::config::Action::MineMode) {
                    tracing::warn!("plx/mine: the mode can only be left from the keyboard");
                } else {
                    state.dispatch_action(действие);
                }
            }
            None => tracing::warn!("plx/mine: unknown action '{имя}'"),
        },
        proto::ОтМода::Пока => {
            tracing::info!("plx/mine: mod said goodbye");
            return false;
        }
    }
    true
}

