/// Действие `mine_mode` (по умолчанию Super+Alt+M): войти в режим или выйти.
pub fn режим(state: &mut Dawn) {
    if state.mine.is_some() {
        выключить(state);
        state.уведомить("Minecraft: режим выключен");
        return;
    }
    match включить(state) {
        Ok(()) => state.уведомить(&format!(
            "Minecraft: жду мод на {}",
            net::путь_сокета().display()
        )),
        Err(e) => state.уведомить(&format!("Minecraft: {e}")),
    }
}

/// Поднять сокет и завести сцену.
pub fn включить(state: &mut Dawn) -> Result<(), String> {
    if state.mine.is_some() {
        return Ok(());
    }
    let слушатель = net::слушать(state).map_err(|e| format!("сокет: {e}"))?;
    let зона = Зона::прямоугольная(
        state.lua_config.mine.зона_ширина,
        state.lua_config.mine.зона_глубина,
    );
    let mut сцена = Сцена {
        зона,
        раскладка: state.vr_раскладка,
        метров_на_пиксель: state.lua_config.mine.метров_на_пиксель,
        // Высота глаз игрока Minecraft — 1.62 блока; блок это метр, поэтому
        // панели, расставленные на этой высоте, окажутся ровно на уровне
        // взгляда, а не под ногами.
        высота_глаз: 1.62,
        перед: 0.0,
        // Якорь берётся не из позы головы (её здесь нет — есть только луч), а
        // задан игрой: мод сам ставит начало координат туда, где стоял игрок.
        нужен_якорь: false,
        ..Сцена::default()
    };
    сцена.разложить();
    state.mine = Some(Box::new(Шахта {
        слушатель,
        мод: None,
        сцена,
        полотна: HashMap::new(),
        посланные: HashMap::new(),
        слепок: Vec::new(),
        наведено: None,
        закреплено: None,
        луч: None,
        кнопка_нажата: false,
        тащим: None,
        место: None,
        окно_игры: None,
        посланный_курсор: None,
        кадров: 0,
        байт: 0,
    }));
    // Место заводим сразу вместе с режимом, а не по приходу мода: `wl_seat` —
    // это глобал, и клиенты разбирают его при подключении. Появись он позже,
    // уже открытые окна о нём бы не узнали (см. оговорку про ghostty в
    // `share/seat.rs`), а открыты к этому моменту ровно те окна, ради которых
    // режим и включают.
    let место = seat::завести(state);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.место = место;
    }
    tracing::info!("dawn/mine: режим включён");
    state.request_redraw();
    Ok(())
}

/// Выйти: попрощаться с модом, снять сокет, освободить полотна.
pub fn выключить(state: &mut Dawn) {
    if state.mine.is_none() {
        return;
    }
    // Кнопку, если держали, отпускаем ДО прощания: иначе окно осталось бы с
    // зажатой мышью навсегда — та же беда, что ловится в `применить_ввод`.
    let держим = state.mine.as_ref().is_some_and(|ш| ш.кнопка_нажата);
    if держим {
        seat::кнопка(state, None, crate::synth::КНОПКА_ЛКМ, false);
    }
    net::послать(state, &proto::ОтДавна::Прощай, false);
    net::отключить(state);
    let место = state.mine.as_mut().and_then(|ш| ш.место.take());
    if let Some(место) = место {
        seat::убрать(state, место);
    }
    let Some(шахта) = state.mine.take() else { return };
    state.петля.remove(шахта.слушатель);
    // Файл сокета за собой убираем: следующий вход в режим иначе увидит
    // «занято» и полезет проверять, живой ли там хозяин.
    let _ = std::fs::remove_file(net::путь_сокета());
    tracing::info!("dawn/mine: режим выключен, панелей было {}", шахта.панелей());
    state.request_redraw();
}

// ── Кадр ────────────────────────────────────────────────────────────────────

/// Шаг режима из главного цикла. Как и у VR, рендерер берём из устройства udev;
/// в headless он передаётся явно (см. [`тик_с`]).
pub fn тик(state: &mut Dawn) {
    if state.mine.is_none() {
        return;
    }
    let mut устройства = std::mem::take(&mut state.udev_devices);
    if let Some(устройство) = устройства.values_mut().next() {
        let гles = &mut устройство.gles as *mut GlesRenderer;
        // Безопасно по той же причине, что и в `udev::render_all`: `state`
        // больше не владеет устройствами, второго пути к рендереру нет.
        unsafe { тик_с(state, &mut *гles) };
    }
    state.udev_devices = устройства;
}

/// Тот же шаг с явно переданным рендерером — так режим работает и в headless,
/// где `GlesRenderer` живёт внутри замыкания таймера. Благодаря этому вся
/// dawn-сторона dmine проверяется харнессом без Minecraft вообще.
pub fn тик_с(state: &mut Dawn, renderer: &mut GlesRenderer) {
    net::убрать_мёртвого(state);
    let Some(шахта) = state.mine.as_ref() else { return };
    // Мода нет или он ещё не поздоровался — рисовать некому. Сокет при этом
    // продолжает слушать: человек как раз запускает игру.
    if !шахта.мод_на_связи() {
        return;
    }

    // ── Сцена ───────────────────────────────────────────────────────────────
    let окна = окна_сцены(state);
    {
        let Some(шахта) = state.mine.as_mut() else { return };
        шахта.сцена.свести(&окна.iter().map(|(_, о)| *о).collect::<Vec<_>>());
        шахта.сцена.разложить();
    }

    // ── Список панелей ──────────────────────────────────────────────────────
    //
    // СТРОГО ДО пикселей. Пиксели адресованы панели по ключу, а завести под
    // них текстуру мод может, только зная её размер: кусок, пришедший раньше
    // списка, ему просто некуда положить. Замер 31.08.2026 (проба на
    // харнессе): при обратном порядке первый — и единственный, пока окно
    // неподвижно, — кадр уходил в никуда, и панель оставалась чёрной.
    послать_панели(state);

    // ── Полотна и пиксели ───────────────────────────────────────────────────
    for (окно, о) in &окна {
        отдать_окно(state, renderer, окно, *о);
    }
    {
        // Полотна закрытых окон освобождаем: текстура окна 2560×1080 — это
        // 11 МиБ, десяток забытых съедает больше, чем весь остальной dawn.
        let живые: std::collections::HashSet<Ключ> = окна.iter().map(|(_, о)| о.ключ).collect();
        if let Some(шахта) = state.mine.as_mut() {
            шахта.полотна.retain(|к, _| живые.contains(к));
            шахта.посланные.retain(|к, _| живые.contains(к));
        }
    }

    // ── Указка → курсор dawn ────────────────────────────────────────────────
    применить_ввод(state);

    if let Some(шахта) = state.mine.as_mut() {
        шахта.кадров += 1;
    }
}

/// Окна для сцены — те же, что в шлеме, но БЕЗ окна самой игры.
///
/// Без этой строки Minecraft висит панелью внутри себя: человек видит в мире
/// собственный экран «монитором» и ничего больше — окно игры развёрнуто, и
/// кроме него в сцене чаще всего нет никого (замер 01.09.2026, живой сеанс).
fn окна_сцены(state: &mut Dawn) -> Vec<(Window, crate::vr::scene::ОкноВСцене)> {
    найти_окно_игры(state);
    let игра = state.mine.as_ref().and_then(|ш| ш.окно_игры.clone());
    crate::vr::окна_для_сцены(state)
        .into_iter()
        .filter(|(окно, _)| игра.as_ref() != Some(окно))
        .collect()
}

/// Найти окно игры по pid на том конце сокета. Ищем один раз и запоминаем;
/// закрытое окно (или ещё не появившееся) отпускаем и ищем снова.
///
/// **Почему pid, а не заголовок.** Заголовок у Minecraft меняется («Minecraft*
/// 26.2», в одиночной игре — с именем мира), а мод сидит в ЕЁ ЖЕ процессе:
/// `SO_PEERCRED` даёт тот самый pid без единой догадки.
fn найти_окно_игры(state: &mut Dawn) {
    let живо = state
        .mine
        .as_ref()
        .and_then(|ш| ш.окно_игры.as_ref())
        .is_some_and(|окно| state.space.elements().any(|w| w == окно));
    if живо {
        return;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.окно_игры = None;
    }
    let Some(pid) = state.mine.as_ref().and_then(|ш| ш.мод.as_ref()).and_then(|м| м.pid) else {
        return;
    };
    let найдено = state
        .space
        .elements()
        .find(|окно| pid_окна(state, окно) == Some(pid))
        .cloned();
    if let Some(окно) = найдено {
        tracing::info!("dawn/mine: окно игры найдено по pid {pid} — в сцену не берём");
        if let Some(шахта) = state.mine.as_mut() {
            шахта.окно_игры = Some(окно);
        }
    }
}

/// Процесс, которому принадлежит окно.
///
/// У Wayland-клиента — из `wl_client`; у X11 (а Minecraft приходит именно
/// через Xwayland) этот путь бесполезен: все X11-окна принадлежат одному
/// процессу, самому Xwayland. Поэтому для них спрашиваем `_NET_WM_PID` у
/// самого окна.
fn pid_окна(state: &Dawn, окно: &Window) -> Option<u32> {
    match окно.underlying_surface() {
        // У X11-окна pid знает сам XWM — он читает `_NET_WM_PID` при
        // отображении окна. Прямое чтение свойства оставлено запасным путём:
        // клиент вправе выставить его и позже, а у XWM оно к тому моменту уже
        // прочитано и закэшировано.
        smithay::desktop::WindowSurface::X11(s) => {
            s.pid().or_else(|| crate::icons::pid_окна_x11(s.window_id()))
        }
        smithay::desktop::WindowSurface::Wayland(t) => {
            use smithay::reexports::wayland_server::Resource as _;
            let клиент = t.wl_surface().client()?;
            клиент
                .get_credentials(&state.display_handle)
                .ok()
                .and_then(|c| u32::try_from(c.pid).ok())
        }
    }
}

/// Нарисовать окно в полотно и отдать моду то, что изменилось.
fn отдать_окно(
    state: &mut Dawn,
    renderer: &mut GlesRenderer,
    окно: &Window,
    о: crate::vr::scene::ОкноВСцене,
) {
    let (ш, в) = (о.ширина_пкс.max(1), о.высота_пкс.max(1));
    let повреждения = {
        let Some(шахта) = state.mine.as_mut() else { return };
        crate::vr::нарисовать_в_полотно(&mut шахта.полотна, renderer, окно, о)
    };
    // Размер поменялся — мод обязан завести текстуру заново, и до этого любые
    // куски старого размера легли бы у него не туда. Полный кадр.
    let размер_сменился = state
        .mine
        .as_ref()
        .and_then(|ш| ш.посланные.get(&о.ключ).copied())
        != Some((ш as u16, в as u16));

    let куски: Vec<Rectangle<i32, Physical>> = match повреждения {
        Повреждения::Мимо => return,
        Повреждения::Всё => vec![Rectangle::from_size((ш, в).into())],
        Повреждения::Куски(к) => {
            if размер_сменился {
                vec![Rectangle::from_size((ш, в).into())]
            } else if к.is_empty() {
                // Самый частый кадр: окно неподвижно, слать нечего. Именно
                // отсюда берётся дешевизна режима на неподвижном экране.
                return;
            } else {
                к
            }
        }
    };

    let текстура = {
        let Some(шахта) = state.mine.as_ref() else { return };
        match шахта.полотна.get(&о.ключ) {
            Some(п) => п.текстура.clone(),
            None => return,
        }
    };
    let mut цель = текстура;
    let mut ушло_байт = 0u64;
    for кусок in куски {
        // Зажимаем в полотно: трекер повреждений отдаёт прямоугольники в
        // координатах вывода, и кусок, вылезший за край (окно уменьшилось в
        // этом же кадре), заставил бы GL читать за пределами буфера.
        let Some(кусок) = кусок.intersection(Rectangle::from_size((ш, в).into())) else {
            continue;
        };
        if кусок.size.w <= 0 || кусок.size.h <= 0 {
            continue;
        }
        // Полосами: сообщение не упирается в предел протокола, и мод заливает
        // в текстуру уже пришедшее, не дожидаясь всего куска.
        let высота_полосы = proto::ПОЛОСА as i32;
        let mut y = кусок.loc.y;
        while y < кусок.loc.y + кусок.size.h {
            let h = высота_полосы.min(кусок.loc.y + кусок.size.h - y);
            let полоса = Rectangle::<i32, Physical>::new(
                (кусок.loc.x, y).into(),
                (кусок.size.w, h).into(),
            );
            if let Some(данные) = вычитать(renderer, &mut цель, полоса) {
                ушло_байт += данные.len() as u64;
                net::послать(
                    state,
                    &proto::ОтДавна::Пиксели {
                        ключ: о.ключ,
                        x: полоса.loc.x as u16,
                        y: полоса.loc.y as u16,
                        ш: полоса.size.w as u16,
                        в: полоса.size.h as u16,
                        данные,
                    },
                    // Пиксели ронять МОЖНО: если мод не успевает, свежая
                    // картинка важнее полной. Потерянный кусок вернётся, как
                    // только клиент нарисует что-нибудь ещё... а если не
                    // нарисует — его вернёт `посланные`, см. ниже.
                    true,
                );
            }
            y += h;
        }
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.посланные.insert(о.ключ, (ш as u16, в as u16));
        шахта.байт += ушло_байт;
    }
}

/// Прочитать кусок полотна в RGBA8.
///
/// `Abgr8888` — это байты R,G,B,A подряд, то есть ровно то, что JVM зальёт в
/// текстуру как `GL_RGBA` без единой перестановки. `Argb8888` был бы на одно
/// расширение драйвера рискованнее и потребовал бы свопа на чьей-то стороне
/// (см. `screencopy.rs`, где ради совместимости приходится уметь оба).
fn вычитать(
    renderer: &mut GlesRenderer,
    цель: &mut smithay::backend::renderer::gles::GlesTexture,
    кусок: Rectangle<i32, Physical>,
) -> Option<Vec<u8>> {
    use smithay::backend::allocator::Fourcc;
    let fb = match renderer.bind(цель) {
        Ok(fb) => fb,
        Err(e) => {
            tracing::warn!("dawn/mine: bind полотна: {e:?}");
            return None;
        }
    };
    let в_буфере = Rectangle::<i32, smithay::utils::Buffer>::new(
        (кусок.loc.x, кусок.loc.y).into(),
        (кусок.size.w, кусок.size.h).into(),
    );
    let слепок = match renderer.copy_framebuffer(&fb, в_буфере, Fourcc::Abgr8888) {
        Ok(с) => с,
        Err(e) => {
            tracing::warn!("dawn/mine: copy_framebuffer: {e:?}");
            return None;
        }
    };
    // fb держит &mut цель, а map_texture хочет &mut renderer — отпускаем.
    drop(fb);
    match renderer.map_texture(&слепок) {
        Ok(данные) => Some(данные.to_vec()),
        Err(e) => {
            tracing::warn!("dawn/mine: map_texture: {e:?}");
            None
        }
    }
}

/// Отдать моду список панелей, если он изменился.
fn послать_панели(state: &mut Dawn) {
    let новый: Vec<proto::Панель> = {
        let Some(шахта) = state.mine.as_ref() else { return };
        шахта
            .сцена
            .панели
            .iter()
            .map(|п| в_протокол(п, заголовок(state, п.ключ)))
            .collect()
    };
    let изменилось = state
        .mine
        .as_ref()
        .is_some_and(|ш| ш.слепок != новый);
    if !изменилось {
        return;
    }
    // Печатаем только на изменении списка — на неподвижном экране это ноль
    // строк. Без неё «окон в игре не видно» неразличимо с «сцена пуста»:
    // окно игры вычитается, и если других окон нет, мод честно рисует ничто.
    tracing::info!(
        "dawn/mine: панелей {} — [{}]",
        новый.len(),
        новый.iter().map(|п| п.заголовок.as_str()).collect::<Vec<_>>().join(", ")
    );
    net::послать(state, &proto::ОтДавна::Панели(новый.clone()), false);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.слепок = новый;
    }
}

fn в_протокол(п: &Панель, заголовок: String) -> proto::Панель {
    let м = п.поза.место;
    let к = п.поза.поворот;
    proto::Панель {
        ключ: п.ключ,
        место: [м.x, м.y, м.z],
        поворот: [к.x, к.y, к.z, к.w],
        пол_ширина: п.пол_ширина,
        пол_высота: п.пол_высота,
        ш_пкс: п.ширина_пкс.clamp(1, u16::MAX as i32) as u16,
        в_пкс: п.высота_пкс.clamp(1, u16::MAX as i32) as u16,
        заголовок,
    }
}

/// Заголовок окна для таблички над панелью.
fn заголовок(state: &Dawn, ключ: Ключ) -> String {
    crate::vr::окно_по_ключу(state, ключ)
        .and_then(|о| crate::xwin::title(&о).or_else(|| crate::xwin::app_id(&о)))
        .unwrap_or_default()
}

