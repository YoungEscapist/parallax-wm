/// Живой режим Minecraft.
pub struct Шахта {
    /// Источник слушающего сокета — снимаем при выходе из режима.
    слушатель: RegistrationToken,
    /// Подключённый мод, если он есть. Режим включается и БЕЗ мода: сокет
    /// стоит и ждёт, пока человек запустит игру, — иначе порядок действий был
    /// бы жёстким («сначала игра, потом бинд»), а он никому не очевиден.
    pub мод: Option<net::Мод>,
    /// Расстановка панелей — та же, что в шлеме.
    pub сцена: Сцена,
    /// Полотна окон: текстура с содержимым и история повреждений.
    полотна: HashMap<Ключ, Полотно>,
    /// Что мод уже знает про панель: её размер в пикселях. По расхождению
    /// понимаем, что текстуру у него надо залить целиком.
    pub посланные: HashMap<Ключ, (u16, u16)>,
    /// Последний посланный список панелей. Сравниваем с новым, чтобы не гнать
    /// одно и то же 60 раз в секунду: панели стоят неподвижно, пока их не
    /// двигают.
    слепок: Vec<proto::Панель>,
    /// Панель под лучом и точка в её пикселях.
    pub наведено: Option<(Ключ, f64, f64)>,
    /// Закреплённое окно и точка в его пикселях: мод взял управление одним
    /// окном (ЛКМ по панели) и ведёт стрелку мышью, а не взглядом. Пока это
    /// поле занято, луч на наведение НЕ влияет — иначе стрелка убегала бы от
    /// руки на каждый поворот головы, а голова в этом режиме свободна.
    pub закреплено: Option<(Ключ, f64, f64)>,
    /// Последний луч от мода. Держим между кадрами: игрок стоит и смотрит в
    /// одну точку, а кадры идут — луч должен продолжать действовать.
    луч: Option<Луч>,
    /// Левая кнопка сейчас зажата нами.
    кнопка_нажата: bool,
    /// Тащим панель хватом: её индекс и расстояние до игрока.
    тащим: Option<(usize, f32)>,
    /// Своё место мода: курсор, клавиатура и фокус панелей (см. `seat.rs`).
    /// Игра при этом остаётся за местом хозяина целиком.
    pub место: Option<smithay::input::Seat<Dawn>>,
    /// Окно самой игры. Его вычитаем из сцены и никогда не трогаем вводом:
    /// иначе Minecraft висит панелью внутри себя, а клики уходят в него, потому
    /// что оно развёрнуто поверх всех.
    pub окно_игры: Option<Window>,
    /// Что про курсор мод уже знает. Стрелка стоит на месте, пока игрок не
    /// шевельнул головой, а кадры идут своим чередом: без этой памяти dawn
    /// слала бы одно и то же сообщение шестьдесят раз в секунду (замер
    /// 31.08.2026 на харнессе: 186 одинаковых «курсоров» за три секунды).
    посланный_курсор: Option<(Ключ, f32, f32, bool)>,
    /// Сколько кадров отдали моду — для `mine state`.
    pub кадров: u64,
    /// Сколько байт пикселей ушло — там же.
    pub байт: u64,
}

impl Шахта {
    pub fn панелей(&self) -> usize {
        self.сцена.панели.len()
    }
    pub fn мод_на_связи(&self) -> bool {
        self.мод.as_ref().is_some_and(|м| м.впущен)
    }
}

/// Прятать ли хозяйскую стрелку в этом кадре.
///
/// Пока мод на связи, а указатель стоит над окном игры, никакой стрелки dawn на
/// экране быть не должно: указка в этом режиме — ВЗГЛЯД игрока, и рисует её мод
/// у себя в мире (`ОтДавна::Курсор`). Хозяйская стрелка поверх Minecraft — это
/// ровно та «вторая, которая летает»: она живёт своей жизнью, показывает не
/// туда, куда смотрит игрок, и ни на что не влияет.
///
/// Условие «над окном игры», а не «режим включён»: человек вправе свернуть
/// игру, уйти на второй монитор или в соседнее окно, не выходя из режима, — и
/// там курсор обязан быть на месте. Уходит указатель с окна игры — стрелка
/// возвращается сама.
pub fn прячем_курсор(state: &Dawn) -> bool {
    let Some(шахта) = state.mine.as_ref() else { return false };
    if !шахта.мод_на_связи() {
        return false;
    }
    let Some(игра) = шахта.окно_игры.as_ref() else { return false };
    state
        .space
        .element_under(state.pointer_location)
        .is_some_and(|(окно, _)| окно == игра)
}

/// Окно — это панель в мире игры, а не сама игра?
///
/// Вопрос ровно один и задают его отовсюду, где dawn собиралась поднять окно
/// наверх или отдать ему хозяйскую клавиатуру. Пока мод на связи, и то и другое
/// принадлежит ИГРЕ: всё остальное человек видит внутри неё, а не на мониторе.
pub fn панель_а_не_игра(state: &Dawn, окно: &Window) -> bool {
    let Some(шахта) = state.mine.as_ref() else { return false };
    if !шахта.мод_на_связи() {
        return false;
    }
    шахта.окно_игры.as_ref().is_some_and(|игра| игра != окно)
}

/// Вернуть окно игры на самый верх стопки.
///
/// Зовётся после каждого подъёма панели (клик мода) и после появления нового
/// окна. Без этого новое окно — и любая панель, по которой щёлкнули, — ложится
/// ПОВЕРХ развёрнутой на весь экран игры, и человек на полсекунды оказывается
/// на рабочем столе: «окно сначала появляется поверх игры, потом уже рисуется в
/// майнкрафте» (жалоба 01.09.2026).
pub fn игру_наверх(state: &mut Dawn) {
    let Some(игра) = state.mine.as_ref().filter(|ш| ш.мод_на_связи()).and_then(|ш| ш.окно_игры.clone())
    else {
        return;
    };
    // Уже наверху — не трогаем: лишний `raise_element` дёргает порядок
    // override-redirect окон (меню X11-клиентов) на ровном месте.
    if state.space.elements().last() == Some(&игра) {
        return;
    }
    state.space.raise_element(&игра, false);
    state.raise_x11(&игра);
    state.request_redraw();
}

/// Отдать окно КЛАВИАТУРЕ МОДА, не трогая хозяйскую.
///
/// Открылось новое окно: на рабочем столе оно получило бы фокус, и все бинды
/// («закрыть», «ресайз», «на другой стол») метили бы в него. В игре ровно тот же
/// смысл имеет фокус МЕСТА мода — а хозяйский обязан остаться у Minecraft,
/// иначе игра перестаёт слышать клавиатуру ровно в тот момент, когда из неё же
/// что-то запустили.
pub fn фокус_панели(state: &mut Dawn, окно: &Window) {
    let Some(место) = state.mine.as_ref().and_then(|ш| ш.место.clone()) else { return };
    let Some(клавиатура) = место.get_keyboard() else { return };
    let Some(цель) = crate::focus::KeyboardFocusTarget::for_window(окно) else { return };
    let serial = smithay::utils::SERIAL_COUNTER.next_serial();
    клавиатура.set_focus(state, Some(цель), serial);
}

