/// `mine state` — одной строкой всё, что нужно, чтобы понять, что происходит.
pub fn состояние(state: &Parallax) -> String {
    let Some(шахта) = state.mine.as_ref() else {
        return т!("mine: выключен", "mine: off").into();
    };
    let мод = match шахта.мод.as_ref() {
        None => т!("мода нет", "no mod").to_string(),
        Some(м) if !м.впущен => т!("мод стучится", "a mod is knocking").to_string(),
        Some(м) => тф!("мод «{}»", "mod '{}'", м.имя),
    };
    // Окно игры — первое, что спрашивают, когда «в мире висит мой же экран»:
    // не нашли его по pid, значит оно попало в сцену панелью.
    // Назначенное руками (`mine game N`) окно живёт БЕЗ мода на связи — на
    // харнессе это обычное дело, и «окна игры нет» тогда было прямой ложью:
    // строка врала ровно в том разборе, ради которого она и заведена.
    let игра = match (шахта.окно_игры.as_ref(), шахта.мод.as_ref().and_then(|м| м.pid)) {
        (Some(_), Some(pid)) => тф!("окно игры pid {pid}", "game window pid {pid}"),
        (Some(_), None) => т!("окно игры назначено вручную", "the game window was set by hand").to_string(),
        (None, Some(pid)) => тф!("окно игры по pid {pid} НЕ НАЙДЕНО", "game window for pid {pid} NOT FOUND"),
        (None, None) => т!("окна игры нет", "no game window").to_string(),
    };
    тф!(
        "mine: включён, {мод}, {игра}, сокет {}, панелей {}, раскладка {}, кадров {}, \
         отдано {:.1} МиБ, наведено {}{}",
        "mine: on, {мод}, {игра}, socket {}, panels {}, layout {}, frames {}, \
         sent {:.1} MiB, aimed {}{}",
        net::путь_сокета().display(),
        шахта.панелей(),
        шахта.сцена.раскладка.имя(),
        шахта.кадров,
        шахта.байт as f64 / (1024.0 * 1024.0),
        match шахта.наведено {
            Some((к, x, y)) => тф!("окно {к} в ({x:.0}, {y:.0})", "window {к} at ({x:.0}, {y:.0})"),
            None => т!("мимо", "missed").into(),
        },
        match шахта.закреплено {
            Some((к, _, _)) => тф!(", управление закреплено за окном {к}", ", control is pinned to window {к}"),
            None => String::new(),
        }
    )
}

/// `mine panels` — где стоят панели. Тот же формат, что у `vr panels`: человек,
/// сверяющий шлем с игрой, читает два вывода рядом.
pub fn панели_строкой(state: &Parallax) -> String {
    let Some(шахта) = state.mine.as_ref() else {
        return т!("mine: выключен", "mine: off").into();
    };
    if шахта.сцена.панели.is_empty() {
        return т!("панелей нет", "no panels").into();
    }
    шахта
        .сцена
        .панели
        .iter()
        .map(|п| {
            тф!(
                "{}: место ({:.2}, {:.2}, {:.2}) м, размер {:.2}×{:.2} м, {}×{} пкс{}", "{}: at ({:.2}, {:.2}, {:.2}) m, size {:.2}×{:.2} m, {}×{} px{}",
                п.ключ,
                п.поза.место.x,
                п.поза.место.y,
                п.поза.место.z,
                п.пол_ширина * 2.0,
                п.пол_высота * 2.0,
                п.ширина_пкс,
                п.высота_пкс,
                if п.закреплена { т!(", закреплена", ", pinned") } else { "" }
            )
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// `mine ray x y z dx dy dz` — послать луч, как это делает мод. Ровно то, чем
/// проверяется попадание указки на харнессе, без Minecraft.
pub fn луч_снаружи(state: &mut Parallax, начало: [f32; 3], направление: [f32; 3]) -> String {
    if state.mine.is_none() {
        return т!("ошибка: режим выключен", "error: the mode is off").into();
    }
    // Мимо `принять_сообщение` НАМЕРЕННО. Тот путь до «привета» не принимает
    // ничего (и правильно: мод чужой версии не должен двигать курсор), а у
    // харнесса мода нет вовсе — и до 31.08.2026 `mine ray` из-за этого ВСЕГДА
    // отвечал «мимо всех панелей», сколько бы панелей ни висело. Проверка
    // указки без Minecraft ради этого и заведена, так что она ходит прямо.
    if !запомнить_луч(state, начало, направление) {
        return т!("ошибка: вырожденное направление", "error: degenerate direction").into();
    }
    применить_ввод(state);
    match state.mine.as_ref().and_then(|ш| ш.наведено) {
        Some((к, x, y)) => тф!("панель {к}, пиксель ({x:.1}, {y:.1})", "panel {к}, pixel ({x:.1}, {y:.1})"),
        None => т!("мимо всех панелей", "missed every panel").into(),
    }
}

/// `mine pin ключ x y` — закрепить управление за окном, как это делает ЛКМ по
/// панели в игре (`ключ = 0` — отпустить). Мимо `принять_сообщение` по той же
/// причине, что и `луч_снаружи`: у харнесса мода нет, а тот путь до «привета»
/// не принимает ничего.
pub fn закрепить_снаружи(state: &mut Parallax, ключ: Ключ, x: f32, y: f32) -> String {
    if state.mine.is_none() {
        return т!("ошибка: режим выключен", "error: the mode is off").into();
    }
    if ключ != 0 && crate::vr::окно_по_ключу(state, ключ).is_none() {
        return тф!("ошибка: окна {ключ} нет — сверься с `mine panels`", "error: there is no window {ключ} — check `mine panels`");
    }
    let прежний = state.mine.as_ref().and_then(|ш| ш.закреплено).map(|(к, _, _)| к);
    if прежний.is_some() && прежний != Some(ключ) {
        отпустить_кнопку(state);
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.закреплено = (ключ != 0).then_some((ключ, x as f64, y as f64));
    }
    применить_ввод(state);
    state.request_redraw();
    match state.mine.as_ref().and_then(|ш| ш.закреплено) {
        Some((к, x, y)) => тф!("управление у окна {к}, пиксель ({x:.1}, {y:.1})", "control is on window {к}, pixel ({x:.1}, {y:.1})"),
        None => т!("закрепление отпущено — указка снова за взглядом", "unpinned — the pointer follows the gaze again").into(),
    }
}

/// `mine game <номер из windows>` — объявить окно окном игры (`-` снимает).
///
/// Только для харнесса. Живьём окно игры находится по pid на том конце сокета,
/// а у харнесса мод — отдельный процесс (`minesim.py`), окна у него нет вовсе, и
/// без этой команды всё, что живёт правилом «игра — самая верхняя, и клавиатура
/// её» (новое окно, клик по панели, Alt+Tab), проверялось бы только запуском
/// Minecraft.
pub fn назначить_игру(state: &mut Parallax, номер: Option<usize>) -> String {
    if state.mine.is_none() {
        return т!("ошибка: режим выключен", "error: the mode is off").into();
    }
    let Some(номер) = номер else {
        if let Some(шахта) = state.mine.as_mut() {
            шахта.окно_игры = None;
        }
        return т!("ok: окна игры больше нет", "ok: the game window is gone").into();
    };
    let Some(окно) = state.space.elements().nth(номер).cloned() else {
        return тф!("ошибка: окна {номер} нет — сверься с `windows`", "error: there is no window {номер} — check `windows`");
    };
    let имя = crate::xwin::title(&окно)
        .or_else(|| crate::xwin::app_id(&окно))
        .unwrap_or_default();
    if let Some(шахта) = state.mine.as_mut() {
        шахта.окно_игры = Some(окно);
    }
    игру_наверх(state);
    тф!("ok: окно игры — {номер} «{имя}»", "ok: the game window is {номер} '{имя}'")
}

/// Сменить раскладку панелей по кругу (`mine layout`).
/// Взять панель под взглядом или отпустить её (действие `mine_grab`).
///
/// Тумблер, а не «пока зажато»: у мода хват висит на боковой кнопке мыши
/// (`GLFW_MOUSE_BUTTON_4`), которой у обычной мыши попросту нет. Взял — панель
/// едет за взглядом, отпустил — осталась висеть; расстояние до неё сохраняется
/// тем же, каким было в момент хвата.
///
/// Панель, переставленную руками, сцена закрепляет — но только в раскладке
/// «свободно»: в дуге и стене её на следующем же перерасчёте вернуло бы на
/// место. Поэтому первый хват сам переводит сцену в «свободно» — иначе
/// «перетащил, а оно отскочило» выглядело бы поломкой.
pub fn хват_тумблер(state: &mut Parallax) {
    let держим = state.mine.as_ref().is_some_and(|ш| ш.тащим.is_some());
    if держим {
        if let Some(шахта) = state.mine.as_mut() {
            шахта.тащим = None;
        }
        state.уведомить(т!("Minecraft: панель отпущена", "Minecraft: panel released"));
        return;
    }
    if state.vr_раскладка != Раскладка::Свободно {
        state.vr_раскладка = Раскладка::Свободно;
        if let Some(шахта) = state.mine.as_mut() {
            шахта.сцена.раскладка = Раскладка::Свободно;
        }
    }
    let луч = state.mine.as_ref().and_then(|ш| ш.луч);
    let Some(луч) = луч else {
        state.уведомить(т!("Minecraft: указки нет — мод молчит", "Minecraft: no pointer — the mod is silent"));
        return;
    };
    let взято = state.mine.as_mut().and_then(|шахта| {
        шахта.сцена.навести(луч).map(|(i, _, _)| {
            let d = шахта.сцена.панели[i].поза.место.минус(луч.начало).длина();
            шахта.тащим = Some((i, d));
            i
        })
    });
    match взято {
        Some(_) => state.уведомить(т!("Minecraft: панель взята — веди взглядом", "Minecraft: panel grabbed — steer with your gaze")),
        None => state.уведомить(т!("Minecraft: под взглядом нет панели", "Minecraft: no panel under the gaze")),
    }
}

pub fn сменить_раскладку(state: &mut Parallax) -> Раскладка {
    let новая = state.vr_раскладка.следующая();
    state.vr_раскладка = новая;
    if let Some(шахта) = state.mine.as_mut() {
        шахта.сцена.раскладка = новая;
        if новая != Раскладка::Свободно {
            шахта.сцена.расстановку_сбросить();
        }
        шахта.сцена.разложить();
    }
    новая
}

/// Проверки арифметики ресайза взглядом. Сам режим без игры (или без
/// `minesim.py`) не проверить, а вот правило «наружу — растёт, внутрь —
/// жмётся» живёт в обычной функции, и ошибка в нём стоит ровно той жалобы, с
/// которой всё началось: «ресайз инвертирован».
#[cfg(test)]
mod тесты_ресайза {
    use super::*;
    use crate::vr::scene::Панель;
    use crate::vr::math::{Век3, Кватернион, Поза};

    fn опора() -> Панель {
        Панель {
            ключ: 1,
            поза: Поза { место: Век3::new(0.0, 0.0, -2.0), поворот: Кватернион::ЕДИНИЦА },
            // Метр на полтора и 1000×600 пикселей: метр по горизонтали — это
            // 1000 пикселей, по вертикали — 600 на 0.75 м.
            пол_ширина: 0.5,
            пол_высота: 0.375,
            ширина_пкс: 1000,
            высота_пкс: 600,
            закреплена: false,
        }
    }

    fn изменение(захват_x: f32, захват_y: f32) -> ИзменениеРазмера {
        ИзменениеРазмера {
            ключ: 1,
            опора: опора(),
            местная_x: захват_x,
            местная_y: захват_y,
            размер0: smithay::utils::Size::from((1000, 600)),
        }
    }

    fn шаг(изм: &ИзменениеРазмера, x: f32, y: f32) -> (i32, i32) {
        let о = изм.опора;
        размер_по_взгляду(
            изм,
            x,
            y,
            о.ширина_пкс as f32 / (2.0 * о.пол_ширина),
            о.высота_пкс as f32 / (2.0 * о.пол_высота),
        )
    }

    /// Главное правило: от середины — растёт, к середине — жмётся. И это
    /// НЕ ЗАВИСИТ от того, за какую половину панели взялись, — вот из-за чего
    /// половина движений раньше работала наоборот.
    #[test]
    fn наружу_растёт_внутрь_жмётся_с_любой_стороны() {
        // Взяли правую половину, повели вправо — наружу.
        let правая = изменение(0.25, 0.0);
        let (dw, _) = шаг(&правая, 0.35, 0.0);
        assert!(dw > 0, "справа наружу окно обязано расти: {dw}");
        // Она же, но взгляд пошёл к середине.
        let (dw, _) = шаг(&правая, 0.15, 0.0);
        assert!(dw < 0, "справа внутрь окно обязано жаться: {dw}");

        // ЛЕВАЯ половина: наружу — это ВЛЕВО. Ровно этот случай и работал
        // раньше наоборот.
        let левая = изменение(-0.25, 0.0);
        let (dw, _) = шаг(&левая, -0.35, 0.0);
        assert!(dw > 0, "слева наружу окно обязано расти: {dw}");
        let (dw, _) = шаг(&левая, -0.15, 0.0);
        assert!(dw < 0, "слева внутрь окно обязано жаться: {dw}");
    }

    /// То же по вертикали, и снизу тоже: раньше знак был жёстко «вниз растит».
    #[test]
    fn по_вертикали_так_же() {
        let верх = изменение(0.0, 0.2);
        assert!(шаг(&верх, 0.0, 0.3).1 > 0, "вверх от верхней половины — рост");
        assert!(шаг(&верх, 0.0, 0.1).1 < 0, "вниз к середине — сжатие");
        let низ = изменение(0.0, -0.2);
        assert!(шаг(&низ, 0.0, -0.3).1 > 0, "вниз от нижней половины — рост");
        assert!(шаг(&низ, 0.0, -0.1).1 < 0, "вверх к середине — сжатие");
    }

    /// Двойка не украшение: панель растёт в обе стороны от середины, и взгляд
    /// провожает ровно одну из них. Ведём на 0.1 м при 1000 px на метр — окно
    /// обязано вырасти на 200 px, а не на 100.
    #[test]
    fn пиксели_считаются_от_обеих_половин() {
        let изм = изменение(0.25, 0.0);
        let (dw, _) = шаг(&изм, 0.35, 0.0);
        assert_eq!(dw, 200, "0.1 м наружу при 1000 px/м — это 200 px");
    }

    /// Взгляд у края поля зрения уходит по плоскости в бесконечность (тангенс),
    /// и без предела окно раздувалось бы до сотен тысяч пикселей. Проверяем,
    /// что дальше `ДАЛЬШЕ_НЕ_ТЯНЕМ` полуразмеров ничего не считается.
    #[test]
    fn взгляд_в_бесконечность_не_раздувает_окно() {
        let изм = изменение(0.0, 0.0);
        let (у_предела, _) = шаг(&изм, 0.5 * ДАЛЬШЕ_НЕ_ТЯНЕМ, 0.0);
        let (за_пределом, _) = шаг(&изм, 1.0e4, 0.0);
        assert_eq!(у_предела, за_пределом, "за пределом ничего не прибавляется");
        assert!(за_пределом < 4000, "и сам предел разумный: {за_пределом}");
    }
}
