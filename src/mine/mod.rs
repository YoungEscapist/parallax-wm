/// Super+ПКМ: тянем размер окна за ближний к прицелу край — как у Hypr3D.
///
/// **Правило Hypr3D, а не наше прежнее.** Край выбирается по той половине
/// панели, за которую взялись (левая половина — левый край, верхняя — верхний),
/// и едет ровно на столько, на сколько прицел прошёл по плоскости окна от
/// точки захвата. Противоположный край при этом стоит в мире на месте: центр
/// панели сдвигается на половину прироста (`держать_край`). Раньше панель росла
/// во все стороны от середины, и «потянул за угол» превращалось в «раздул
/// всё окно» — снаружи это читалось как кривой ресайз.
///
/// **Опора заморожена нарочно.** Панель растёт вместе с окном, и мерить взгляд
/// по ЖИВОЙ панели значило бы менять линейку прямо под рукой. Поэтому
/// плоскость и метры-на-пиксель берутся со снимка на момент захвата.
#[derive(Debug, Clone, Copy)]
struct ИзменениеРазмера {
    /// Окно, которое тянем.
    ключ: Ключ,
    /// Снимок панели на момент захвата — та самая линейка.
    опора: Панель,
    /// Точка захвата в местных координатах опоры (метры, Y вверх).
    местная_x: f32,
    местная_y: f32,
    /// Какой край едет: −1 левый / +1 правый; +1 верхний / −1 нижний.
    край_x: i8,
    край_y: i8,
    /// Размер окна на момент захвата.
    размер0: smithay::utils::Size<i32, smithay::utils::Logical>,
}

/// Super+ЛКМ: несём панель за прицелом (`CWorld::startDrag`/`updateDrag` у
/// Hypr3D).
///
/// Держится не центр, а ТОЧКА, за которую взяли: панель не прыгает серединой
/// под прицел в момент хвата. Расстояние до этой точки сохраняется, колесо
/// меняет его ЦЕЛЬ, а само расстояние доезжает до цели плавно — прокрутка не
/// телепортирует окно рывками по зубцам.
#[derive(Debug, Clone, Copy)]
struct Перенос {
    ключ: Ключ,
    /// Текущее расстояние от глаза до точки хвата, метры.
    расстояние: f32,
    /// Куда его ведёт колесо.
    цель: f32,
    /// Точка хвата в местных координатах панели (метры от центра).
    местная_x: f32,
    местная_y: f32,
}

/// Super+СКМ: крутим панель вокруг её нормали на угол, который прицел
/// заметает вокруг её центра (`s_wheelRot` у Hypr3D).
#[derive(Debug, Clone, Copy)]
struct Вращение {
    ключ: Ключ,
    центр: Век3,
    нормаль: Век3,
    /// От центра к точке захвата — от него меряется угол.
    опорный: Век3,
    поворот0: crate::vr::math::Кватернион,
}

/// Super+колесо без хвата: панель под прицелом едет ближе/дальше вдоль луча
/// «глаз → её центр» и доезжает плавно (`s_zoom*` у Hypr3D). Луч привязан к
/// месту глаза в момент последнего щелчка: окно остаётся неподвижным в мире,
/// а не едет за игроком.
#[derive(Debug, Clone, Copy)]
struct Приближение {
    ключ: Ключ,
    якорь: Век3,
    направление: Век3,
    сейчас: f32,
    цель: f32,
}

/// Что было у окна в 2D до того, как оно ушло в мир игры.
///
/// Тот же приём, что `ghostWindows` у Hypr3D: пока окно висит панелью, им НЕ
/// правит раскладка рабочего стола. Без этого любая перекладка — смена
/// tiling/niri/floating, новое окно, обзор — меняла окнам размер, а размер
/// окна это размер панели: панели в мире прыгали и ломались. Мир — это вид, а
/// не правка: при выходе всё возвращается как было.
#[derive(Debug, Clone)]
struct Призрак {
    окно: Window,
    floating: bool,
    float_pinned: bool,
    размер: smithay::utils::Size<i32, smithay::utils::Logical>,
}

/// Живой режим Minecraft.
pub struct Шахта {
    /// Источник слушающего сокета — снимаем при выходе из режима.
    слушатель: RegistrationToken,
    /// Подключённый мод, если он есть. Режим включается и БЕЗ мода: сокет
    /// стоит и ждёт, пока человек запустит игру, — иначе порядок действий был
    /// бы жёстким («сначала игра, потом бинд»), а он никому не очевиден.
    pub мод: Option<net::Мод>,
    /// Расстановка панелей — та же, что в шлеме.
    pub сцена: Сцена,
    /// Полотна окон: текстура с содержимым и история повреждений.
    полотна: HashMap<Ключ, Полотно>,
    /// Что мод уже знает про панель: её размер в пикселях. По расхождению
    /// понимаем, что текстуру у него надо залить целиком.
    pub посланные: HashMap<Ключ, (u16, u16)>,
    /// Последний посланный список панелей. Сравниваем с новым, чтобы не гнать
    /// одно и то же 60 раз в секунду: панели стоят неподвижно, пока их не
    /// двигают.
    слепок: Vec<proto::Панель>,
    /// Панель под лучом и точка в её пикселях.
    pub наведено: Option<(Ключ, f64, f64)>,
    /// Панель, которой взгляд УЖЕ отдал клавиатуру. Нужна ровно затем, чтобы
    /// фокус ехал за взглядом на ВХОДЕ на панель, а не переустанавливался на
    /// каждом кадре: пока поле совпадает с панелью под лучом, `навести` фокус
    /// не трогает. Без этого любой бинд, метящий в фокус (Alt+Tab, Super+J,
    /// «фокус влево», выбор в обзоре) откатывался за один кадр — и новое окно,
    /// открытое из игры, теряло клавиатуру раньше, чем в нём успевали набрать
    /// первый символ (жалоба 01.09.2026 «бинды и фокус»; замер на харнессе:
    /// четыре Super+J подряд не сдвинули фокус вовсе).
    фокус_взгляда: Option<Ключ>,
    /// Закреплённое окно и точка в его пикселях: мод взял управление одним
    /// окном (ЛКМ по панели) и ведёт стрелку мышью, а не взглядом. Пока это
    /// поле занято, луч на наведение НЕ влияет — иначе стрелка убегала бы от
    /// руки на каждый поворот головы, а голова в этом режиме свободна.
    pub закреплено: Option<(Ключ, f64, f64)>,
    /// Последний луч от мода. Держим между кадрами: игрок стоит и смотрит в
    /// одну точку, а кадры идут — луч должен продолжать действовать.
    луч: Option<Луч>,
    /// Левая кнопка сейчас зажата нами.
    кнопка_нажата: bool,
    /// Неявный захват (как у Hypr3D и у любого композитора на столе): окно,
    /// в котором НАЖАЛИ кнопку, и сколько кнопок в нём держат. Пока захват
    /// есть, указка ведётся по плоскости ЭТОЙ панели без её границ и зажимается
    /// в окно: выделение текста, перетаскивание ползунка, рисование не рвутся
    /// оттого, что взгляд на миг соскочил за край панели. Без него `применить_ввод`
    /// на первом же промахе отпускал кнопку («взгляд в пустоту»).
    захват: Option<(Ключ, u8)>,
    /// Тащим панель хватом (Super+ЛКМ, см. [`Перенос`]).
    тащим: Option<Перенос>,
    /// Меняем размер окна: Super+ПКМ вместо хвата (см. [`ИзменениеРазмера`]).
    меняем_размер: Option<ИзменениеРазмера>,
    /// Только что отпущенный ресайз: край держим ещё [`ДОВОДКА`], пока клиент
    /// не пришлёт кадр последнего размера.
    доводка: Option<(ИзменениеРазмера, std::time::Instant)>,
    /// Крутим панель (Super+СКМ, см. [`Вращение`]).
    крутим: Option<Вращение>,
    /// Доезд Super+колеса (см. [`Приближение`]).
    приближаем: Option<Приближение>,
    /// Окна, снятые с раскладки на время жизни в мире (см. [`Призрак`]).
    призраки: HashMap<Ключ, Призрак>,
    /// Первая партия окон уже снята с раскладки — всё, что появится дальше,
    /// это НОВЫЕ окна (им — размер появления и место перед игроком).
    призраки_заведены: bool,
    /// Панели уже расставлены первый раз. Дальше раскладка «свободно», и новые
    /// окна появляются перед игроком, а не встают в дугу (см. `родить_панели`).
    разложено: bool,
    /// Когда прицел ушёл со всех панелей: через [`ГРАЦИЯ_ПРИЦЕЛА`] фокус
    /// снимается (`AimFocus` у Hypr3D).
    мимо_с: Option<std::time::Instant>,
    /// Время прошлого шага — для плавных доездов.
    прошлый_шаг: Option<std::time::Instant>,
    /// Своё место мода: курсор, клавиатура и фокус панелей (см. `seat.rs`).
    /// Игра при этом остаётся за местом хозяина целиком.
    pub место: Option<smithay::input::Seat<Parallax>>,
    /// Окно самой игры. Его вычитаем из сцены и никогда не трогаем вводом:
    /// иначе Minecraft висит панелью внутри себя, а клики уходят в него, потому
    /// что оно развёрнуто поверх всех.
    pub окно_игры: Option<Window>,
    /// Что про курсор мод уже знает. Стрелка стоит на месте, пока игрок не
    /// шевельнул головой, а кадры идут своим чередом: без этой памяти parallax
    /// слала бы одно и то же сообщение шестьдесят раз в секунду (замер
    /// 31.08.2026 на харнессе: 186 одинаковых «курсоров» за три секунды).
    посланный_курсор: Option<(Ключ, f32, f32, bool)>,
    /// Полотна-dmabuf (путь без вычитки, см. `dma.rs`). `None` — ещё не
    /// заводили или мод их не умеет.
    pub дма: Option<dma::Дма>,
    /// Завести dmabuf-полотна не вышло — больше не пробуем, едем пикселями.
    дма_отказ: bool,
    /// Сколько кадров отдали моду — для `mine state`.
    pub кадров: u64,
    /// Сколько байт пикселей ушло — там же.
    pub байт: u64,
}

impl Шахта {
    pub fn панелей(&self) -> usize {
        self.сцена.панели.len()
    }
    pub fn мод_на_связи(&self) -> bool {
        self.мод.as_ref().is_some_and(|м| м.впущен)
    }
}

/// Прятать ли хозяйскую стрелку в этом кадре.
///
/// Пока мод на связи, а указатель стоит над окном игры, никакой стрелки parallax на
/// экране быть не должно: указка в этом режиме — ВЗГЛЯД игрока, и рисует её мод
/// у себя в мире (`ОтДавна::Курсор`). Хозяйская стрелка поверх Minecraft — это
/// ровно та «вторая, которая летает»: она живёт своей жизнью, показывает не
/// туда, куда смотрит игрок, и ни на что не влияет.
///
/// Условие «над окном игры», а не «режим включён»: человек вправе свернуть
/// игру, уйти на второй монитор или в соседнее окно, не выходя из режима, — и
/// там курсор обязан быть на месте. Уходит указатель с окна игры — стрелка
/// возвращается сама.
/// Фокус клавиатуры на панели мода, если он там. `None` — панелей нет, мод не
/// на связи или взгляд ещё ни разу не заходил на панель.
///
/// Отдельной функцией, чтобы `focus.rs` не разбирал внутренности `Шахта`:
/// в сборке `plx-standard` этого типа не существует вовсе (см. mine_stub/).
pub fn фокус_панели_мода(state: &Parallax) -> Option<WlSurface> {
    state
        .mine
        .as_ref()
        .filter(|ш| ш.мод_на_связи())
        .and_then(|ш| ш.место.as_ref())
        .and_then(|место| место.get_keyboard())
        .and_then(|kb| kb.current_focus())
        .and_then(|f| f.surface())
}

/// Это поверхность самого окна Minecraft (а не панели)? Бинды, метящие в
/// «сфокусированное окно», обязаны в этом случае не делать НИЧЕГО.
pub fn это_окно_игры(state: &Parallax, s: &WlSurface) -> bool {
    state
        .mine
        .as_ref()
        .filter(|ш| ш.мод_на_связи())
        .and_then(|ш| ш.окно_игры.as_ref())
        .is_some_and(|и| crate::xwin::is_surface(и, s))
}

///
/// **И только пока игра держит мышь захваченной** (pointer lock — так GLFW
/// делает `GLFW_CURSOR_DISABLED` под Wayland). До 07.10.2026 условия не было:
/// стрелка пряталась над окном игры ВСЕГДА, и в меню паузы, инвентаре, чате —
/// везде, где Minecraft сам показывает свою стрелку через этот же курсор
/// хозяина, — её не было видно вовсе («пропадает курсор после включения
/// мода»). Пока игра мышь держит, она и сама ставит пустую стрелку; прятать
/// приходится только то, что могла бы нарисовать parallax поверх.
pub fn прячем_курсор(state: &Parallax) -> bool {
    let Some(шахта) = state.mine.as_ref() else { return false };
    if !шахта.мод_на_связи() {
        return false;
    }
    let Some(игра) = шахта.окно_игры.as_ref() else { return false };
    let над_игрой = state
        .space
        .element_under(state.pointer_location)
        .is_some_and(|(окно, _)| окно == игра);
    if !над_игрой {
        return false;
    }
    let под = state.surface_under(state.pointer_location);
    state.pointer_constraint_at(под.as_ref()).locked
}

/// Окно — это панель в мире игры, а не сама игра?
///
/// Вопрос ровно один и задают его отовсюду, где parallax собиралась поднять окно
/// наверх или отдать ему хозяйскую клавиатуру. Пока мод на связи, и то и другое
/// принадлежит ИГРЕ: всё остальное человек видит внутри неё, а не на мониторе.
pub fn панель_а_не_игра(state: &Parallax, окно: &Window) -> bool {
    let Some(шахта) = state.mine.as_ref() else { return false };
    if !шахта.мод_на_связи() {
        return false;
    }
    шахта.окно_игры.as_ref().is_some_and(|игра| игра != окно)
}

/// Кнопки мыши над этим окном принадлежат ИГРЕ целиком — parallax своих хватов по
/// нему не начинает.
///
/// **Из-за этого не работал Super+ПКМ (ресайз панели) живьём, а на харнессе
/// работал.** Мышь в обычной игре держит Minecraft, но композитор-то parallax:
/// физическая ПКМ сперва приезжает на ХОЗЯЙСКОЕ место, и там `input.rs` видит
/// свою же пару «Super+ПКМ → ресайз окна под курсором». Курсор в этот момент
/// стоит над развёрнутой игрой, поэтому parallax забирала кнопку в
/// `ResizeSurfaceGrab` по САМОЙ ИГРЕ — и до Minecraft она уже не доходила. А мод
/// узнаёт о кнопке единственным способом: опросом `glfwGetMouseButton`
/// (`Dmine.мышьВИгре`). Не дошла кнопка — не было и `Хват`, то есть parallax не
/// получала повода начать ресайз вовсе: снаружи «нажимаю Win+ПКМ, ничего не
/// происходит». Сим этой развилки не проходил никогда — он шлёт `Хват` прямо в
/// сокет, минуя и Minecraft, и хозяйское место, оттого замер на харнессе
/// 01.09.2026 показывал исправный ресайз.
///
/// Ровно та же беда была у Super+ЛКМ: он уводил кнопку в `MoveSurfaceGrab` по
/// игре, а мод по ней берёт управление одним окном.
///
/// Симметрично [`панель_а_не_игра`]: там вопрос «это НЕ игра?», здесь — «это
/// игра?». Разными их делает случай, когда окно игры ещё не найдено: поднимать
/// наверх тогда нечего (`false`), но и отбирать кнопки не у кого (тоже `false`).
pub fn кнопки_игре(state: &Parallax, окно: &Window) -> bool {
    let Some(шахта) = state.mine.as_ref() else { return false };
    if !шахта.мод_на_связи() {
        return false;
    }
    шахта.окно_игры.as_ref() == Some(окно)
}

/// Участвует ли окно в переборе фокуса (Alt+Tab, Super+J, «фокус влево», поиск
/// окон). Окно игры — НЕТ, пока мод на связи.
///
/// **Почему без этого перебор замирал насмерть.** Игра для parallax — обычное окно,
/// и в кольце перебора она стояла наравне с панелями. Стоило перебору попасть
/// на неё, как `xwin::focus` уходил обычной дорогой (это же не панель) и отдавал
/// её ХОЗЯЙСКОМУ месту, а «окно, с которым работают» (`focused_surface`) читает
/// место МОДА — там оставалась прежняя панель. Следующее нажатие считало
/// «текущим» ту же панель и снова выбирало игру: перебор навсегда упирался в
/// неё, а снаружи это выглядело как «Super+J и Alt+Tab не работают вовсе»
/// (замер на харнессе 01.09.2026: четыре Super+J подряд не сдвинули фокус ни
/// разу; стоило снять окно игры — фокус поехал).
pub fn в_переборе(state: &Parallax, окно: &Window) -> bool {
    let Some(шахта) = state.mine.as_ref() else { return true };
    if !шахта.мод_на_связи() {
        return true;
    }
    шахта.окно_игры.as_ref() != Some(окно)
}

/// Вернуть окно игры на самый верх стопки.
///
/// Зовётся после каждого подъёма панели (клик мода) и после появления нового
/// окна. Без этого новое окно — и любая панель, по которой щёлкнули, — ложится
/// ПОВЕРХ развёрнутой на весь экран игры, и человек на полсекунды оказывается
/// на рабочем столе: «окно сначала появляется поверх игры, потом уже рисуется в
/// майнкрафте» (жалоба 01.09.2026).
pub fn игру_наверх(state: &mut Parallax) {
    let Some(игра) = state.mine.as_ref().filter(|ш| ш.мод_на_связи()).and_then(|ш| ш.окно_игры.clone())
    else {
        return;
    };
    // Уже наверху — не трогаем: лишний `raise_element` дёргает порядок
    // override-redirect окон (меню X11-клиентов) на ровном месте.
    if state.space.elements().last() == Some(&игра) {
        return;
    }
    state.space.raise_element(&игра, false);
    state.raise_x11(&игра);
    state.request_redraw();
}

/// Отдать окно КЛАВИАТУРЕ МОДА, не трогая хозяйскую.
///
/// Открылось новое окно: на рабочем столе оно получило бы фокус, и все бинды
/// («закрыть», «ресайз», «на другой стол») метили бы в него. В игре ровно тот же
/// смысл имеет фокус МЕСТА мода — а хозяйский обязан остаться у Minecraft,
/// иначе игра перестаёт слышать клавиатуру ровно в тот момент, когда из неё же
/// что-то запустили.
/// Нельзя отдавать клавиатуру места мода этому окну: и оно, и игра сидят в
/// Xwayland.
///
/// **У X-сервера фокус ОДИН на всех X11-окна.** Клавиатура места мода,
/// войдя в X11-окно, делает в Xwayland `SetInputFocus` на него — и окно игры,
/// тоже X11, теряет фокус: Minecraft встаёт на паузу, а хозяйские клавиши
/// уезжают мимо игры. Замер на харнессе 06.10.2026: появление xterm при
/// живом моде — игра тут же открыла меню паузы, а набранный Enter нажал в
/// нём «выйти в главное меню». Фокус же едет за ВЗГЛЯДОМ, то есть хватало
/// просто посмотреть на такую панель.
///
/// Поэтому таким панелям клавиатура места мода не достаётся (указка и клики
/// — достаются). Игра под Wayland (мод dmine с 06.10 снимает принудительный
/// X11 у GLFW) этой беды не знает вовсе: её фокус — свой, а не иксовый.
pub fn икс_фокус_отнимет_игру(state: &Parallax, окно: &Window) -> bool {
    let Some(игра) = state.mine.as_ref().and_then(|ш| ш.окно_игры.as_ref()) else { return false };
    игра.x11_surface().is_some() && окно.x11_surface().is_some() && игра != окно
}

pub fn фокус_панели(state: &mut Parallax, окно: &Window) {
    if икс_фокус_отнимет_игру(state, окно) {
        return;
    }
    let Some(место) = state.mine.as_ref().and_then(|ш| ш.место.clone()) else { return };
    let Some(клавиатура) = место.get_keyboard() else { return };
    let Some(цель) = crate::focus::KeyboardFocusTarget::for_window(окно) else { return };
    let serial = smithay::utils::SERIAL_COUNTER.next_serial();
    клавиатура.set_focus(state, Some(цель), serial);
}

