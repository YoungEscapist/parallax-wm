/// Действие `mine_mode` (по умолчанию Super+Alt+M): войти в режим или выйти.
pub fn режим(state: &mut Parallax) {
    if state.mine.is_some() {
        выключить(state);
        state.уведомить(т!("Minecraft: режим выключен", "Minecraft: mode off"));
        return;
    }
    match включить(state) {
        Ok(()) => state.уведомить(&тф!(
            "Minecraft: жду мод на {}", "Minecraft: waiting for the mod on {}",
            net::путь_сокета().display()
        )),
        Err(e) => state.уведомить(&format!("Minecraft: {e}")),
    }
}

/// Поднять сокет и завести сцену.
pub fn включить(state: &mut Parallax) -> Result<(), String> {
    if state.mine.is_some() {
        return Ok(());
    }
    let слушатель = net::слушать(state).map_err(|e| тф!("сокет: {e}", "socket: {e}"))?;
    let зона = Зона::прямоугольная(
        state.lua_config.mine.зона_ширина,
        state.lua_config.mine.зона_глубина,
    );
    let mut сцена = Сцена {
        зона,
        // Зона в игре — только про то, ГДЕ РАСКЛАДКА СТАВИТ панели по
        // умолчанию. Стен вокруг игрока нет, тащить панель за её край —
        // обычное дело (см. `Сцена::держать_в_зоне`).
        держать_в_зоне: false,
        раскладка: state.vr_раскладка,
        метров_на_пиксель: state.lua_config.mine.метров_на_пиксель,
        // Высота глаз игрока Minecraft — 1.62 блока; блок это метр, поэтому
        // панели, расставленные на этой высоте, окажутся ровно на уровне
        // взгляда, а не под ногами.
        высота_глаз: 1.62,
        перед: 0.0,
        // Якорь берётся не из позы головы (её здесь нет — есть только луч), а
        // задан игрой: мод сам ставит начало координат туда, где стоял игрок.
        нужен_якорь: false,
        ..Сцена::default()
    };
    сцена.разложить();
    state.mine = Some(Box::new(Шахта {
        слушатель,
        мод: None,
        сцена,
        полотна: HashMap::new(),
        посланные: HashMap::new(),
        слепок: Vec::new(),
        наведено: None,
        фокус_взгляда: None,
        закреплено: None,
        луч: None,
        кнопка_нажата: false,
        захват: None,
        тащим: None,
        меняем_размер: None,
        доводка: None,
        крутим: None,
        приближаем: None,
        призраки: HashMap::new(),
        призраки_заведены: false,
        разложено: false,
        мимо_с: None,
        прошлый_шаг: None,
        место: None,
        окно_игры: None,
        посланный_курсор: None,
        дма: None,
        дма_отказ: false,
        кадров: 0,
        байт: 0,
    }));
    // Место мода заведено ещё при старте parallax (`seat::завести`): появись
    // `wl_seat` только сейчас, уже открытые окна — ровно те, ради которых режим
    // и включают, — о нём бы не узнали.
    let место = state.mine_место.clone();
    if место.is_none() {
        tracing::warn!("plx/mine: no seat for the mod — panels will get no input");
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.место = место;
    }
    tracing::info!("plx/mine: mode on");
    state.request_redraw();
    Ok(())
}

/// Выйти: попрощаться с модом, снять сокет, освободить полотна.
pub fn выключить(state: &mut Parallax) {
    if state.mine.is_none() {
        return;
    }
    // Кнопку, если держали, отпускаем ДО прощания: иначе окно осталось бы с
    // зажатой мышью навсегда — та же беда, что ловится в `применить_ввод`.
    let держим = state.mine.as_ref().is_some_and(|ш| ш.кнопка_нажата);
    if держим {
        seat::кнопка(state, None, crate::synth::КНОПКА_ЛКМ, false);
    }
    net::послать(state, &proto::ОтДавна::Прощай, false);
    net::отключить(state);
    вернуть_призраков(state);
    let место = state.mine.as_mut().and_then(|ш| ш.место.take());
    if let Some(место) = место {
        seat::убрать(state, место);
    }
    let Some(шахта) = state.mine.take() else { return };
    state.петля.remove(шахта.слушатель);
    // Файл сокета за собой убираем: следующий вход в режим иначе увидит
    // «занято» и полезет проверять, живой ли там хозяин.
    let _ = std::fs::remove_file(net::путь_сокета());
    tracing::info!("plx/mine: mode off, {} panels were up", шахта.панелей());
    state.request_redraw();
}

// ── Кадр ────────────────────────────────────────────────────────────────────

/// Шаг режима из главного цикла. Как и у VR, рендерер берём из устройства udev;
/// в headless он передаётся явно (см. [`тик_с`]).
pub fn тик(state: &mut Parallax) {
    if state.mine.is_none() {
        return;
    }
    let mut устройства = std::mem::take(&mut state.udev_devices);
    if let Some(устройство) = устройства.values_mut().next() {
        let гles = &mut устройство.gles as *mut GlesRenderer;
        // Безопасно по той же причине, что и в `udev::render_all`: `state`
        // больше не владеет устройствами, второго пути к рендереру нет.
        unsafe { тик_с(state, &mut *гles) };
    }
    state.udev_devices = устройства;
}

/// Тот же шаг с явно переданным рендерером — так режим работает и в headless,
/// где `GlesRenderer` живёт внутри замыкания таймера. Благодаря этому вся
/// parallax-сторона plx-mine проверяется харнессом без Minecraft вообще.
pub fn тик_с(state: &mut Parallax, renderer: &mut GlesRenderer) {
    net::убрать_мёртвого(state);
    let Some(шахта) = state.mine.as_ref() else { return };
    // Мода нет или он ещё не поздоровался — рисовать некому. Сокет при этом
    // продолжает слушать: человек как раз запускает игру. Окна, снятые с
    // раскладки, пока мод был на связи, возвращаем на стол.
    if !шахта.мод_на_связи() {
        вернуть_призраков(state);
        return;
    }

    // ── Сцена ───────────────────────────────────────────────────────────────
    let окна = окна_сцены(state);
    завести_призраков(state, &окна);
    let живые = crate::vr::ключи_живых_окон(state);
    {
        let Some(шахта) = state.mine.as_mut() else { return };
        шахта.сцена.свести(&окна.iter().map(|(_, окно)| *окно).collect::<Vec<_>>());
        шахта.сцена.забыть_кроме(&живые);
        родить_панели(шахта);
        шахта.сцена.разложить();
        держать_край(шахта);
    }

    // Игра — всегда самая верхняя на мониторе. Проверка стоит на каждом кадре
    // нарочно: поднять окно поверх неё умеет не только клик мода и появление
    // нового окна (они чинятся по месту), но и любой бинд, метящий в фокус, —
    // Alt+Tab, обзор, «поднять в мастер-слот». Из игры это выглядит одинаково:
    // мир на мгновение сменился рабочим столом.
    игру_наверх(state);

    // ── Список панелей ──────────────────────────────────────────────────────
    //
    // СТРОГО ДО пикселей. Пиксели адресованы панели по ключу, а завести под
    // них текстуру мод может, только зная её размер: кусок, пришедший раньше
    // списка, ему просто некуда положить. Замер 31.08.2026 (проба на
    // харнессе): при обратном порядке первый — и единственный, пока окно
    // неподвижно, — кадр уходил в никуда, и панель оставалась чёрной.
    послать_панели(state);

    // ── Полотна и пиксели ───────────────────────────────────────────────────
    //
    // Мод умеет dmabuf — окно едет без вычитки (`dma.rs`). Не вышло завести
    // буфер под конкретное окно — оно одно уезжает старым путём, пикселями.
    let по_дма = готовить_дма(state, renderer);
    for (окно, в_сцене) in &окна {
        if по_дма && отдать_окно_дма(state, renderer, окно, *в_сцене) {
            continue;
        }
        отдать_окно(state, renderer, окно, *в_сцене);
    }
    {
        // Полотна закрытых окон освобождаем: текстура окна 2560×1080 — это
        // 11 МиБ, десяток забытых съедает больше, чем весь остальной parallax.
        let живые: std::collections::HashSet<Ключ> = окна.iter().map(|(_, в_сцене)| в_сцене.ключ).collect();
        if let Some(шахта) = state.mine.as_mut() {
            шахта.полотна.retain(|к, _| живые.contains(к));
            шахта.посланные.retain(|к, _| живые.contains(к));
            if let Some(дма) = шахта.дма.as_mut() {
                дма.полотна.retain(|к, _| живые.contains(к));
            }
        }
    }

    // ── Отложенное удаление GL-объектов ─────────────────────────────────────
    //
    // Каждый `bind` полотна заводит FBO, каждое `вычитать` — буфер под
    // пиксели, и удаляет их smithay НЕ сразу: кладёт в очередь, которую
    // разбирает только конец GL-кадра (`GlesFrame::finish`) или `unbind`.
    // Здесь кадра нет вовсе, когда полотно не повреждено, а главный экран
    // в это время может не рисоваться через GL совсем — игра во весь экран
    // уходит в прямой вывод. Тогда очередь не разбирается никогда: замер
    // 06.10.2026 — 8.7 ГиБ кучи за полчаса Minecraft во весь экран, на
    // харнессе +250 КиБ/с при трёх неподвижных панелях (malloc внутри Mesa
    // из `GlesRenderer::bind`). Разбираем сами, раз в тик.
    {
        use smithay::backend::renderer::Renderer as _;
        if let Err(e) = renderer.cleanup_texture_cache() {
            tracing::debug!("plx/mine: GL cleanup: {e:?}");
        }
    }

    // ── Указка → курсор parallax ────────────────────────────────────────────────
    применить_ввод(state);

    if let Some(шахта) = state.mine.as_mut() {
        шахта.кадров += 1;
    }
}

/// Размер, с которым НОВОЕ окно появляется в мире (`kSpawnWidth/Height` у
/// Hypr3D). Окну, открытому из игры, раскладка стола выдала бы слот — часто
/// во весь монитор, — и панель вылезала бы стеной перед лицом.
const РАЗМЕР_ПОЯВЛЕНИЯ: (i32, i32) = (960, 540);

/// На каком расстоянии перед игроком появляется новое окно, метры (блоки).
///
/// У Hypr3D `spawn_distance` = 5 при 100 px на метр × 0.5; у нас метр — это
/// блок, а панель меряется `mine{ метров_на_пиксель }`. Полтора блока дают окну
/// 960 px примерно ту же угловую ширину, что у Hypr3D, и оно не утыкается в
/// игрока.
const РАССТОЯНИЕ_ПОЯВЛЕНИЯ: f32 = 1.5;

/// Снять окна сцены с раскладки рабочего стола (см. [`Призрак`]).
///
/// Сперва запоминаем ВСЕ, потом трогаем: снятие одного окна перекладывает
/// оставшиеся, и снятый после размер был бы уже чужим (тот же порядок у
/// Hypr3D, `ghostWindows`).
fn завести_призраков(state: &mut Parallax, окна: &[(Window, crate::vr::scene::ОкноВСцене)]) {
    let Some(шахта) = state.mine.as_ref() else { return };
    let первые = !шахта.призраки_заведены;
    let новые: Vec<(Window, Ключ)> = окна
        .iter()
        .filter(|(_, о)| !шахта.призраки.contains_key(&о.ключ))
        .map(|(окно, о)| (окно.clone(), о.ключ))
        .collect();
    if новые.is_empty() {
        if let Some(шахта) = state.mine.as_mut() {
            шахта.призраки_заведены = true;
        }
        return;
    }
    // Закрытые окна из памяти убираем; ушедшие на другой стол — НЕТ: они
    // по-прежнему плавающие нашими руками, и вернуть их обязаны при выходе.
    if let Some(шахта) = state.mine.as_mut() {
        let живые: Vec<Window> = state.tagged_windows.iter().map(|tw| tw.window.clone()).collect();
        шахта.призраки.retain(|_, п| живые.contains(&п.окно));
    }
    let mut записи = Vec::new();
    for (окно, ключ) in &новые {
        let Some(tw) = state.tagged_windows.iter().find(|tw| &tw.window == окно) else { continue };
        записи.push((
            *ключ,
            Призрак {
                окно: окно.clone(),
                floating: tw.floating,
                float_pinned: tw.float_pinned,
                размер: crate::xwin::current_size(окно),
            },
        ));
    }
    let mut переложить = false;
    for (_, п) in &записи {
        let Some(tw) = state.tagged_windows.iter_mut().find(|tw| tw.window == п.окно) else { continue };
        if !tw.floating {
            переложить = true;
        }
        tw.floating = true;
        tw.float_pinned = true;
        // Окно, появившееся уже при живом моде, получает размер появления —
        // но только если раскладка держала его плиткой: плавающему человек
        // выбрал размер сам. Первую партию не трогаем: её размеры человек
        // видел на столе.
        if !первые && !п.floating && !state.is_fullscreen(&п.окно) {
            let (w, h) = РАЗМЕР_ПОЯВЛЕНИЯ;
            crate::xwin::set_size(&п.окно, Some((w, h).into()), crate::xwin::Tiled::Keep);
            crate::xwin::configure(&п.окно);
        }
    }
    if let Some(шахта) = state.mine.as_mut() {
        for (ключ, п) in записи {
            шахта.призраки.insert(ключ, п);
        }
        шахта.призраки_заведены = true;
    }
    if переложить {
        state.arrange();
    }
    tracing::info!("plx/mine: {} windows taken off the desk layout", новые.len());
}

/// Вернуть окна на стол такими, какими они были до мира игры.
fn вернуть_призраков(state: &mut Parallax) {
    let Some(шахта) = state.mine.as_mut() else { return };
    шахта.призраки_заведены = false;
    if шахта.призраки.is_empty() {
        return;
    }
    let призраки: Vec<Призрак> = шахта.призраки.drain().map(|(_, п)| п).collect();
    for п in &призраки {
        let Some(tw) = state.tagged_windows.iter_mut().find(|tw| tw.window == п.окно) else { continue };
        tw.floating = п.floating;
        tw.float_pinned = п.float_pinned;
        // Плавающему — его прежний размер; плиточному размер вернёт раскладка.
        if п.floating && crate::xwin::current_size(&п.окно) != п.размер {
            crate::xwin::set_size(&п.окно, Some(п.размер), crate::xwin::Tiled::Keep);
            crate::xwin::configure(&п.окно);
        }
    }
    state.arrange();
    tracing::info!("plx/mine: {} windows returned to the desk layout", призраки.len());
}

/// Поставить новорождённые панели (см. `Сцена::свести`: поза по умолчанию).
///
/// Первый раз — по раскладке (дуга вокруг игрока), и все панели тут же
/// закрепляются: дальше их двигает только человек. Всё, что появится потом,
/// встаёт прямо перед игроком лицом к нему, как у Hypr3D (`syncWorld`: «NEW
/// windows spawn straight in front of the camera»).
fn родить_панели(шахта: &mut Шахта) {
    use crate::vr::math::Поза;
    if !шахта.разложено {
        if шахта.сцена.панели.is_empty() {
            return;
        }
        шахта.сцена.разложить();
        for п in &mut шахта.сцена.панели {
            п.закреплена = true;
        }
        шахта.сцена.раскладка = Раскладка::Свободно;
        шахта.разложено = true;
        return;
    }
    let Some(луч) = шахта.луч else { return };
    // Новорождённых бывает и несколько разом — первый заход на стол, где уже
    // лежат окна. Ставить каждую в одну точку значило бы свалить их в кучу
    // (жалоба 07.10.2026), поэтому пачка встаёт в ряд поперёк взгляда,
    // серединой ряда в прицел.
    let новые: Vec<usize> = шахта
        .сцена
        .панели
        .iter()
        .enumerate()
        .filter(|(_, п)| !п.закреплена && п.поза == Поза::default())
        .map(|(i, _)| i)
        .collect();
    if новые.is_empty() {
        return;
    }
    let поворот = лицом_к_взгляду(луч.направление);
    let вправо = поворот.повернуть(Век3::new(1.0, 0.0, 0.0));
    let центр = луч.начало.плюс(луч.направление * РАССТОЯНИЕ_ПОЯВЛЕНИЯ);
    let ширина: f32 = новые.iter().map(|&i| шахта.сцена.панели[i].пол_ширина * 2.0).sum::<f32>()
        + ЗАЗОР_ПОЯВЛЕНИЯ * (новые.len() - 1) as f32;
    let mut x = -ширина * 0.5;
    for i in новые {
        x += шахта.сцена.панели[i].пол_ширина;
        // Окна, открытые по одному при неподвижном взгляде, приходят в разные
        // тики и метят в ту же точку — место занято, сдвигаемся вправо, за
        // соседа.
        let mut место = центр.плюс(вправо * x);
        for _ in 0..32 {
            let Some(сосед) = шахта.сцена.панели.iter().enumerate().find(|(j, о)| {
                *j != i && о.закреплена && (о.поза.место.минус(место)).длина() < СОСЕД_ВПЛОТНУЮ
            }) else {
                break;
            };
            let шаг = сосед.1.пол_ширина + шахта.сцена.панели[i].пол_ширина + ЗАЗОР_ПОЯВЛЕНИЯ;
            место = место.плюс(вправо * шаг);
        }
        let п = &mut шахта.сцена.панели[i];
        п.поза = Поза { место, поворот };
        п.закреплена = true;
        x += п.пол_ширина + ЗАЗОР_ПОЯВЛЕНИЯ;
    }
}

/// Ближе этого (блоки) середина чужой панели — место появления занято.
const СОСЕД_ВПЛОТНУЮ: f32 = 0.3;

/// Зазор между панелями, появившимися разом (см. `родить_панели`), блоки.
const ЗАЗОР_ПОЯВЛЕНИЯ: f32 = 0.1;

/// Поворот панели, при котором её лицо смотрит ПРОТИВ взгляда — прямо на
/// игрока, с полным наклоном по вертикали (Hypr3D `updateDrag`: target pitch =
/// camera pitch, предел ±1.5 рад).
///
/// Нормаль панели — её +Z, а `вокруг_y(р)·вокруг_x(т)` уводит +Z в
/// (cos т·sin р, −sin т, cos т·cos р). Приравниваем это к −взгляд.
fn лицом_к_взгляду(взгляд: Век3) -> crate::vr::math::Кватернион {
    use crate::vr::math::Кватернион;
    let н = (взгляд * -1.0).нормаль();
    let рыскание = н.x.atan2(н.z);
    let тангаж = (-н.y).clamp(-1.0, 1.0).asin().clamp(-1.5, 1.5);
    Кватернион::вокруг_y(рыскание).умножить(Кватернион::вокруг_x(тангаж))
}

/// Пока тянут размер, противоположный край панели стоит в мире на месте.
///
/// Панель растёт из размера окна (`свести`), а растёт она от СЕРЕДИНЫ — значит
/// середину надо сдвинуть на половину прироста в сторону тянущего края
/// (Hypr3D `syncWorld`, ветка `g_resize.active`).
///
/// И ещё [`ДОВОДКА`] после отпускания: клиент отвечает на последний `configure`
/// кадром позже, и без доводки этот последний прирост ложился на обе стороны —
/// противоположный край уезжал на сантиметр (замер на харнессе 07.10.2026).
fn держать_край(шахта: &mut Шахта) {
    if шахта.доводка.is_some_and(|(_, с)| с.elapsed() > ДОВОДКА) {
        шахта.доводка = None;
    }
    let Some(изм) = шахта.меняем_размер.or(шахта.доводка.map(|(и, _)| и)) else { return };
    let Some(п) = шахта.сцена.панели.iter_mut().find(|п| п.ключ == изм.ключ) else { return };
    let поворот = изм.опора.поза.поворот;
    let вправо = поворот.повернуть(Век3::new(1.0, 0.0, 0.0));
    let вверх = поворот.повернуть(Век3::new(0.0, 1.0, 0.0));
    let dx = (п.пол_ширина - изм.опора.пол_ширина) * изм.край_x as f32;
    let dy = (п.пол_высота - изм.опора.пол_высота) * изм.край_y as f32;
    п.поза.место = изм.опора.поза.место.плюс(вправо * dx).плюс(вверх * dy);
    п.поза.поворот = поворот;
    п.закреплена = true;
}

/// Сколько держать край после отпускания ресайза (см. `держать_край`).
const ДОВОДКА: std::time::Duration = std::time::Duration::from_millis(500);

/// Окна для сцены — те же, что в шлеме, но БЕЗ окна самой игры.
///
/// Без этой строки Minecraft висит панелью внутри себя: человек видит в мире
/// собственный экран «монитором» и ничего больше — окно игры развёрнуто, и
/// кроме него в сцене чаще всего нет никого (замер 01.09.2026, живой сеанс).
fn окна_сцены(state: &mut Parallax) -> Vec<(Window, crate::vr::scene::ОкноВСцене)> {
    найти_окно_игры(state);
    let игра = state.mine.as_ref().and_then(|ш| ш.окно_игры.clone());
    crate::vr::окна_для_сцены(state)
        .into_iter()
        .filter(|(окно, _)| игра.as_ref() != Some(окно))
        .collect()
}

/// Найти окно игры по pid на том конце сокета. Ищем один раз и запоминаем;
/// закрытое окно (или ещё не появившееся) отпускаем и ищем снова.
///
/// **Почему pid, а не заголовок.** Заголовок у Minecraft меняется («Minecraft*
/// 26.2», в одиночной игре — с именем мира), а мод сидит в ЕЁ ЖЕ процессе:
/// `SO_PEERCRED` даёт тот самый pid без единой догадки.
fn найти_окно_игры(state: &mut Parallax) {
    let живо = state
        .mine
        .as_ref()
        .and_then(|ш| ш.окно_игры.as_ref())
        .is_some_and(|окно| state.space.elements().any(|w| w == окно));
    if живо {
        return;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.окно_игры = None;
    }
    let Some(pid) = state.mine.as_ref().and_then(|ш| ш.мод.as_ref()).and_then(|м| м.pid) else {
        return;
    };
    let найдено = state
        .space
        .elements()
        .find(|окно| state.pid_окна(окно) == Some(pid))
        .cloned();
    if let Some(окно) = найдено {
        tracing::info!("plx/mine: game window found by pid {pid} — kept out of the scene");
        if let Some(шахта) = state.mine.as_mut() {
            шахта.окно_игры = Some(окно);
        }
    }
}


/// Нарисовать окно в полотно и отдать моду то, что изменилось.
fn отдать_окно(
    state: &mut Parallax,
    renderer: &mut GlesRenderer,
    окно: &Window,
    в_сцене: crate::vr::scene::ОкноВСцене,
) {
    let (ш, в) = (в_сцене.ширина_пкс.max(1), в_сцене.высота_пкс.max(1));
    let повреждения = {
        let Some(шахта) = state.mine.as_mut() else { return };
        crate::vr::нарисовать_в_полотно(&mut шахта.полотна, renderer, окно, в_сцене)
    };
    // Размер поменялся — мод обязан завести текстуру заново, и до этого любые
    // куски старого размера легли бы у него не туда. Полный кадр.
    let размер_сменился = state
        .mine
        .as_ref()
        .and_then(|ш| ш.посланные.get(&в_сцене.ключ).copied())
        != Some((ш as u16, в as u16));

    let куски: Vec<Rectangle<i32, Physical>> = match повреждения {
        Повреждения::Мимо => return,
        Повреждения::Всё => vec![Rectangle::from_size((ш, в).into())],
        Повреждения::Куски(к) => {
            if размер_сменился {
                vec![Rectangle::from_size((ш, в).into())]
            } else if к.is_empty() {
                // Самый частый кадр: окно неподвижно, слать нечего. Именно
                // отсюда берётся дешевизна режима на неподвижном экране.
                return;
            } else {
                к
            }
        }
    };

    let текстура = {
        let Some(шахта) = state.mine.as_ref() else { return };
        match шахта.полотна.get(&в_сцене.ключ) {
            Some(п) => п.текстура.clone(),
            None => return,
        }
    };
    let mut цель = текстура;
    let mut ушло_байт = 0u64;
    for кусок in куски {
        // Зажимаем в полотно: трекер повреждений отдаёт прямоугольники в
        // координатах вывода, и кусок, вылезший за край (окно уменьшилось в
        // этом же кадре), заставил бы GL читать за пределами буфера.
        let Some(кусок) = кусок.intersection(Rectangle::from_size((ш, в).into())) else {
            continue;
        };
        if кусок.size.w <= 0 || кусок.size.h <= 0 {
            continue;
        }
        // Полосами: сообщение не упирается в предел протокола, и мод заливает
        // в текстуру уже пришедшее, не дожидаясь всего куска.
        let высота_полосы = proto::ПОЛОСА as i32;
        let mut y = кусок.loc.y;
        while y < кусок.loc.y + кусок.size.h {
            let h = высота_полосы.min(кусок.loc.y + кусок.size.h - y);
            let полоса = Rectangle::<i32, Physical>::new(
                (кусок.loc.x, y).into(),
                (кусок.size.w, h).into(),
            );
            if let Some(данные) = вычитать(renderer, &mut цель, полоса) {
                ушло_байт += данные.len() as u64;
                net::послать(
                    state,
                    &proto::ОтДавна::Пиксели {
                        ключ: в_сцене.ключ,
                        x: полоса.loc.x as u16,
                        y: полоса.loc.y as u16,
                        ш: полоса.size.w as u16,
                        в: полоса.size.h as u16,
                        данные,
                    },
                    // Пиксели ронять МОЖНО: если мод не успевает, свежая
                    // картинка важнее полной. Потерянный кусок вернётся, как
                    // только клиент нарисует что-нибудь ещё... а если не
                    // нарисует — его вернёт `посланные`, см. ниже.
                    true,
                );
            }
            y += h;
        }
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.посланные.insert(в_сцене.ключ, (ш as u16, в as u16));
        шахта.байт += ушло_байт;
    }
}

/// Готов ли путь dmabuf на этот кадр: мод его умеет, полотна заведены.
fn готовить_дма(state: &mut Parallax, renderer: &GlesRenderer) -> bool {
    let Some(шахта) = state.mine.as_mut() else { return false };
    let умеет = шахта.мод.as_ref().is_some_and(|м| м.dmabuf);
    if !умеет || шахта.дма_отказ {
        return false;
    }
    if шахта.дма.is_none() {
        match dma::Дма::завести(renderer) {
            Ok(д) => шахта.дма = Some(д),
            Err(e) => {
                tracing::warn!("plx/mine: no dmabuf canvases ({e}) — windows go as pixels");
                шахта.дма_отказ = true;
                return false;
            }
        }
    }
    true
}

/// Окно → его dmabuf-полотно → мод. `false` — не вышло, пусть едет пикселями.
fn отдать_окно_дма(
    state: &mut Parallax,
    renderer: &mut GlesRenderer,
    окно: &Window,
    в_сцене: crate::vr::scene::ОкноВСцене,
) -> bool {
    let итог = {
        let Some(дма) = state.mine.as_mut().and_then(|ш| ш.дма.as_mut()) else { return false };
        дма.нарисовать(renderer, окно, в_сцене)
    };
    match итог {
        dma::Итог::Мимо => false,
        dma::Итог::Тишина => true,
        dma::Итог::Кадр => {
            net::послать(state, &proto::ОтДавна::Кадр { ключ: в_сцене.ключ }, true);
            true
        }
        dma::Итог::Новое => {
            let отдать = state
                .mine
                .as_ref()
                .and_then(|ш| ш.дма.as_ref())
                .and_then(|д| д.отдать(в_сцене.ключ));
            let Some((сообщение, fd)) = отдать else {
                tracing::warn!("plx/mine: could not export the dmabuf of panel {}", в_сцене.ключ);
                return false;
            };
            tracing::info!(
                "plx/mine: panel {} — dmabuf {}×{}",
                в_сцене.ключ, в_сцене.ширина_пкс, в_сцене.высота_пкс
            );
            net::послать_буфер(state, &сообщение, fd);
            true
        }
    }
}

/// Прочитать кусок полотна в RGBA8.
///
/// `Abgr8888` — это байты R,G,B,A подряд, то есть ровно то, что JVM зальёт в
/// текстуру как `GL_RGBA` без единой перестановки. `Argb8888` был бы на одно
/// расширение драйвера рискованнее и потребовал бы свопа на чьей-то стороне
/// (см. `screencopy.rs`, где ради совместимости приходится уметь оба).
fn вычитать(
    renderer: &mut GlesRenderer,
    цель: &mut smithay::backend::renderer::gles::GlesTexture,
    кусок: Rectangle<i32, Physical>,
) -> Option<Vec<u8>> {
    use smithay::backend::allocator::Fourcc;
    let fb = match renderer.bind(цель) {
        Ok(fb) => fb,
        Err(e) => {
            tracing::warn!("plx/mine: canvas bind: {e:?}");
            return None;
        }
    };
    let в_буфере = Rectangle::<i32, smithay::utils::Buffer>::new(
        (кусок.loc.x, кусок.loc.y).into(),
        (кусок.size.w, кусок.size.h).into(),
    );
    let слепок = match renderer.copy_framebuffer(&fb, в_буфере, Fourcc::Abgr8888) {
        Ok(с) => с,
        Err(e) => {
            tracing::warn!("plx/mine: copy_framebuffer: {e:?}");
            return None;
        }
    };
    // fb держит &mut цель, а map_texture хочет &mut renderer — отпускаем.
    drop(fb);
    match renderer.map_texture(&слепок) {
        Ok(данные) => Some(данные.to_vec()),
        Err(e) => {
            tracing::warn!("plx/mine: map_texture: {e:?}");
            None
        }
    }
}

/// Отдать моду список панелей, если он изменился.
fn послать_панели(state: &mut Parallax) {
    let новый: Vec<proto::Панель> = {
        let Some(шахта) = state.mine.as_ref() else { return };
        шахта
            .сцена
            .панели
            .iter()
            .map(|п| в_протокол(п, заголовок(state, п.ключ)))
            .collect()
    };
    let изменилось = state
        .mine
        .as_ref()
        .is_some_and(|ш| ш.слепок != новый);
    if !изменилось {
        return;
    }
    // Печатаем только на изменении списка — на неподвижном экране это ноль
    // строк. Без неё «окон в игре не видно» неразличимо с «сцена пуста»:
    // окно игры вычитается, и если других окон нет, мод честно рисует ничто.
    tracing::info!(
        "plx/mine: {} panels — [{}]",
        новый.len(),
        новый.iter().map(|п| п.заголовок.as_str()).collect::<Vec<_>>().join(", ")
    );
    net::послать(state, &proto::ОтДавна::Панели(новый.clone()), false);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.слепок = новый;
    }
}

fn в_протокол(п: &Панель, заголовок: String) -> proto::Панель {
    let м = п.поза.место;
    let к = п.поза.поворот;
    proto::Панель {
        ключ: п.ключ,
        место: [м.x, м.y, м.z],
        поворот: [к.x, к.y, к.z, к.w],
        пол_ширина: п.пол_ширина,
        пол_высота: п.пол_высота,
        ш_пкс: п.ширина_пкс.clamp(1, u16::MAX as i32) as u16,
        в_пкс: п.высота_пкс.clamp(1, u16::MAX as i32) as u16,
        заголовок,
    }
}

/// Заголовок окна для таблички над панелью.
fn заголовок(state: &Parallax, ключ: Ключ) -> String {
    crate::vr::окно_по_ключу(state, ключ)
        .and_then(|о| crate::xwin::title(&о).or_else(|| crate::xwin::app_id(&о)))
        .unwrap_or_default()
}

// ── Ввод ────────────────────────────────────────────────────────────────────

/// Луч игрока → курсор parallax. Ровно та же логика, что у указки в шлеме, и по
/// той же причине: дальше работает весь существующий код — `surface_under`,
/// фокус по наведению, клики, перетаскивание, меню.
fn применить_ввод(state: &mut Parallax) {
    // ── Закреплённое окно (ЛКМ по панели) ───────────────────────────────────
    //
    // Управление отдано ОДНОМУ окну: стрелку по нему ведёт мышь, взгляд не
    // участвует. Ветка стоит первой и до луча не доходит вовсе — в этом весь
    // смысл режима: игрок вправе смотреть куда угодно, пока печатает.
    //
    // Закрепление за закрытым окном отпускаем молча: панель исчезла, держаться
    // не за что, и указка возвращается взгляду.
    if let Some((ключ, x, y)) = state.mine.as_ref().and_then(|ш| ш.закреплено) {
        match crate::vr::окно_по_ключу(state, ключ) {
            Some(окно) => {
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.наведено = Some((ключ, x, y));
                }
                let брать_фокус = взять_фокус(state, ключ);
                seat::навести(state, &окно, x, y, брать_фокус);
                послать_курсор(state, ключ, x as f32, y as f32, true);
                return;
            }
            None => {
                отпустить_кнопку(state);
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.закреплено = None;
                }
            }
        }
    }

    let Some(луч) = state.mine.as_ref().and_then(|ш| ш.луч) else { return };

    // Время шага для плавных доездов. Предел в десятую секунды: после паузы
    // (игра свёрнута, мир грузится) доезд не должен перескакивать за один кадр.
    let dt = {
        let Some(шахта) = state.mine.as_mut() else { return };
        let сейчас = std::time::Instant::now();
        let dt = шахта
            .прошлый_шаг
            .map_or(0.0, |т| сейчас.duration_since(т).as_secs_f32())
            .min(0.1);
        шахта.прошлый_шаг = Some(сейчас);
        dt
    };

    // Super+колесо доезжает и без хвата — шаг до всех веток ниже.
    if let Some(шахта) = state.mine.as_mut() {
        вести_приближение(шахта, dt);
    }

    // ── Изменение размера окна (Super+ПКМ) ──────────────────────────────────
    //
    // Стоит ДО перетаскивания: обе ветки висят на одной кнопке, и занята
    // одновременно может быть только одна.
    if let Some(изм) = state.mine.as_ref().and_then(|ш| ш.меняем_размер) {
        вести_изменение_размера(state, изм, луч);
        return;
    }

    // ── Вращение (Super+СКМ) ────────────────────────────────────────────────
    if let Some(вр) = state.mine.as_ref().and_then(|ш| ш.крутим) {
        if let Some(шахта) = state.mine.as_mut() {
            вести_вращение(шахта, вр, луч);
        }
        return;
    }

    // ── Перенос панели (Super+ЛКМ) ──────────────────────────────────────────
    if state.mine.as_ref().is_some_and(|ш| ш.тащим.is_some()) {
        if let Some(шахта) = state.mine.as_mut() {
            вести_перенос(шахта, луч, dt);
        }
        // Пока тащим — курсор в окно не гоняем: окно получало бы «мышь ездит»
        // на каждый кадр переноса.
        return;
    }

    // ── Неявный захват: кнопка зажата в окне ────────────────────────────────
    if let Some((ключ, _)) = state.mine.as_ref().and_then(|ш| ш.захват) {
        if вести_захват(state, ключ, луч) {
            return;
        }
        // Окно закрылось под рукой — захвата больше нет.
        if let Some(шахта) = state.mine.as_mut() {
            шахта.захват = None;
        }
    }

    let попал = state.mine.as_ref().and_then(|ш| ш.сцена.навести(луч));
    let наведено = попал.and_then(|(i, x, y)| {
        state
            .mine
            .as_ref()
            .map(|ш| (ш.сцена.панели[i].ключ, x, y))
    });
    if let Some(шахта) = state.mine.as_mut() {
        шахта.наведено = наведено;
    }

    // ── Указка → своё место ─────────────────────────────────────────────────
    //
    // Ни курсор хозяина, ни его фокус здесь больше не трогаются: у мода своё
    // место (`seat.rs`). Именно поэтому исчезло правило «пока трогают мышь,
    // указка молчит», которое живёт в шлеме: спорить не с кем — хозяйская мышь
    // осталась у Minecraft и крутит игроку голову.
    let Some((ключ, пкс_x, пкс_y)) = наведено else {
        // Взгляд в пустоту: зажатую кнопку отпускаем, иначе окно осталось бы с
        // нажатой мышью навсегда.
        отпустить_кнопку(state);
        seat::увести(state);
        // Прицел ушёл в мир. Как у Hypr3D (`AimFocus`): короткая отсрочка, и
        // фокус снимается совсем — «фокус есть только там, куда смотрят».
        // Отсрочка нужна, чтобы прицел, проскочивший щель между панелями или
        // край окна, не дёргал фокус туда-обратно.
        let снять = {
            let Some(шахта) = state.mine.as_mut() else { return };
            let с = *шахта.мимо_с.get_or_insert_with(std::time::Instant::now);
            шахта.фокус_взгляда.is_some() && с.elapsed() >= ГРАЦИЯ_ПРИЦЕЛА
        };
        if снять {
            if let Some(шахта) = state.mine.as_mut() {
                шахта.фокус_взгляда = None;
            }
            seat::снять_фокус(state);
        }
        послать_курсор(state, 0, 0.0, 0.0, false);
        return;
    };
    if let Some(шахта) = state.mine.as_mut() {
        шахта.мимо_с = None;
    }

    if let Some(окно) = crate::vr::окно_по_ключу(state, ключ) {
        let брать_фокус = взять_фокус(state, ключ);
        seat::навести(state, &окно, пкс_x, пкс_y, брать_фокус);
    }
    послать_курсор(state, ключ, пкс_x as f32, пкс_y as f32, true);
}

/// Сколько прицел может провести мимо панелей, прежде чем фокус снимется.
/// Те же 80 мс, что у Hypr3D (`AimFocus::lostGraceSeconds`). Мод держит ту же
/// отсрочку у себя, решая, кому отдать клавишу.
const ГРАЦИЯ_ПРИЦЕЛА: std::time::Duration = std::time::Duration::from_millis(80);

/// Скорости доездов, 1/с: расстояние (колесо) и разворот лицом к игроку.
/// Числа Hypr3D: `exp(-8·dt)` у колеса, `smoothAngle(…, 9)` у разворота.
const СКОРОСТЬ_ДОЕЗДА: f32 = 8.0;
const СКОРОСТЬ_РАЗВОРОТА: f32 = 9.0;

/// Ближайшая панель под лучом: индекс, расстояние по лучу и точка в её местных
/// метрах. То же, что `Сцена::навести`, но с метрами — их просят хваты.
fn попадание(сцена: &Сцена, луч: Луч) -> Option<(usize, f32, f32, f32)> {
    let mut лучшее: Option<(usize, f32, f32, f32)> = None;
    for (i, п) in сцена.панели.iter().enumerate() {
        let Some((t, x, y)) = луч.попал(п.поза, п.пол_ширина, п.пол_высота) else { continue };
        if лучшее.is_none_or(|(_, лучше, _, _)| t < лучше) {
            лучшее = Some((i, t, x, y));
        }
    }
    лучшее
}

/// Взять панель под прицелом в перенос (Super+ЛКМ).
fn начать_перенос(шахта: &mut Шахта, луч: Луч) {
    let Some((i, t, x, y)) = попадание(&шахта.сцена, луч) else { return };
    let ключ = шахта.сцена.панели[i].ключ;
    шахта.приближаем = None; // расстоянием теперь правит перенос
    шахта.тащим = Some(Перенос { ключ, расстояние: t, цель: t, местная_x: x, местная_y: y });
}

/// Шаг переноса: точка хвата едет по лучу прицела, расстояние доезжает до цели
/// колеса, панель плавно разворачивается лицом к игроку (и вращение Super+СКМ
/// при этом сходит на нет — у Hypr3D так же: «a dragged window with a leftover
/// roll would face the player tilted»).
fn вести_перенос(шахта: &mut Шахта, луч: Луч, dt: f32) {
    let Some(мы) = шахта.тащим else { return };
    let Some(п) = шахта.сцена.панели.iter_mut().find(|п| п.ключ == мы.ключ) else {
        // Окно закрылось, пока его несли.
        шахта.тащим = None;
        return;
    };
    let расстояние = мы.расстояние + (мы.цель - мы.расстояние) * (1.0 - (-СКОРОСТЬ_ДОЕЗДА * dt).exp());
    let точка = луч.начало.плюс(луч.направление * расстояние);
    let поворот = п
        .поза
        .поворот
        .сблизить(лицом_к_взгляду(луч.направление), 1.0 - (-СКОРОСТЬ_РАЗВОРОТА * dt).exp());
    let хват = поворот.повернуть(Век3::new(мы.местная_x, мы.местная_y, 0.0));
    п.поза.место = точка.минус(хват);
    п.поза.поворот = поворот;
    п.закреплена = true;
    шахта.тащим = Some(Перенос { расстояние, ..мы });
}

/// Взять панель под прицелом во вращение (Super+СКМ). Прицел ровно в центре
/// панели угла не задаёт — там хват не берётся (у Hypr3D так же).
fn начать_вращение(шахта: &mut Шахта, луч: Луч) {
    let Some((i, t, _, _)) = попадание(&шахта.сцена, луч) else { return };
    let п = шахта.сцена.панели[i];
    let точка = луч.начало.плюс(луч.направление * t);
    let опорный = точка.минус(п.поза.место);
    if опорный.скалярно(опорный) <= 0.0004 {
        return;
    }
    шахта.крутим = Some(Вращение {
        ключ: п.ключ,
        центр: п.поза.место,
        нормаль: п.поза.поворот.повернуть(Век3::new(0.0, 0.0, 1.0)),
        опорный,
        поворот0: п.поза.поворот,
    });
}

/// Шаг вращения: угол, который прицел замёл вокруг центра панели, — это и есть
/// поворот вокруг её нормали.
fn вести_вращение(шахта: &mut Шахта, вр: Вращение, луч: Луч) {
    use crate::vr::math::{Кватернион, Поза};
    // Плоскость панели без границ: прицел вправе уйти за край, крутя дальше.
    let плоскость = Поза { место: вр.центр, поворот: вр.поворот0 };
    let Some((_, x, y)) = луч.попал(плоскость, 1.0e4, 1.0e4) else { return };
    let v = вр.поворот0.повернуть(Век3::new(x, y, 0.0));
    let угол = вр.опорный.векторно(v).скалярно(вр.нормаль).atan2(вр.опорный.скалярно(v));
    let Some(п) = шахта.сцена.панели.iter_mut().find(|п| п.ключ == вр.ключ) else {
        шахта.крутим = None;
        return;
    };
    п.поза.поворот = Кватернион::вокруг_оси(вр.нормаль, угол).умножить(вр.поворот0).нормаль();
    п.закреплена = true;
}

/// Super+колесо без хвата: толкнуть панель под прицелом дальше (колесо от
/// себя) или притянуть (на себя). Множитель за зубец — как у переноса.
fn приблизить(шахта: &mut Шахта, луч: Луч, шаги: f32) {
    let Some((i, _, _, _)) = попадание(&шахта.сцена, луч) else { return };
    let п = шахта.сцена.панели[i];
    let до = п.поза.место.минус(луч.начало);
    let расстояние = до.длина();
    if !расстояние.is_finite() || расстояние < 0.05 {
        return;
    }
    // Тот же ключ — цель копится (крутят несколько зубцов подряд), но
    // нынешнее расстояние и луч берём живые: игрок мог сдвинуться между
    // щелчками, и старый якорь дёрнул бы панель.
    let цель = match шахта.приближаем {
        Some(пр) if пр.ключ == п.ключ => пр.цель / пр.сейчас.max(1e-3) * расстояние,
        _ => расстояние,
    };
    шахта.приближаем = Some(Приближение {
        ключ: п.ключ,
        якорь: луч.начало,
        направление: до * (1.0 / расстояние),
        сейчас: расстояние,
        цель: (цель * ЗУБЕЦ.powf(шаги)).clamp(БЛИЖЕ_НЕЛЬЗЯ, ДАЛЬШЕ_НЕЛЬЗЯ),
    });
}

/// Шаг доезда Super+колеса. Доехал — состояние сбрасывается, и окно снова
/// просто висит в мире (у Hypr3D: «a live zoom state would keep the window
/// glued to a moving camera»).
fn вести_приближение(шахта: &mut Шахта, dt: f32) {
    let Some(пр) = шахта.приближаем else { return };
    let Some(п) = шахта.сцена.панели.iter_mut().find(|п| п.ключ == пр.ключ) else {
        шахта.приближаем = None;
        return;
    };
    let сейчас = пр.сейчас + (пр.цель - пр.сейчас) * (1.0 - (-СКОРОСТЬ_ДОЕЗДА * dt).exp());
    п.поза.место = пр.якорь.плюс(пр.направление * сейчас);
    п.закреплена = true;
    шахта.приближаем = if (пр.цель - сейчас).abs() < 0.02 { None } else { Some(Приближение { сейчас, ..пр }) };
}

/// Указка по плоскости схваченной панели. `false` — панели (окна) больше нет.
fn вести_захват(state: &mut Parallax, ключ: Ключ, луч: Луч) -> bool {
    let Some(панель) = state
        .mine
        .as_ref()
        .and_then(|ш| ш.сцена.панели.iter().find(|п| п.ключ == ключ).copied())
    else {
        return false;
    };
    let Some(окно) = crate::vr::окно_по_ключу(state, ключ) else { return false };
    // Плоскость без границ (как у ресайза): за краем панели `попал` с честными
    // полуразмерами вернул бы None. Точку потом зажимаем в окно — клиент
    // получает координату на своём краю, как на столе при уходе мыши за окно.
    const БЕЗ_ГРАНИЦ: f32 = 1.0e4;
    let Some((_, x, y)) = луч.попал(панель.поза, БЕЗ_ГРАНИЦ, БЕЗ_ГРАНИЦ) else {
        // Взгляд ушёл за спину панели: стрелка стоит где была, захват держится.
        return true;
    };
    let x = x.clamp(-панель.пол_ширина, панель.пол_ширина);
    let y = y.clamp(-панель.пол_высота, панель.пол_высота);
    let (пкс_x, пкс_y) = панель.в_пиксели(x, y);
    let пкс_x = пкс_x.clamp(0.0, (панель.ширина_пкс - 1).max(0) as f64);
    let пкс_y = пкс_y.clamp(0.0, (панель.высота_пкс - 1).max(0) as f64);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.наведено = Some((ключ, пкс_x, пкс_y));
    }
    seat::навести(state, &окно, пкс_x, пкс_y, false);
    послать_курсор(state, ключ, пкс_x as f32, пкс_y as f32, true);
    true
}

/// Пора ли отдавать клавиатуру панели под взглядом.
///
/// Правило: фокус едет за взглядом на ВХОДЕ на панель — ровно так же, как
/// sloppy focus на столе едет за ДВИЖЕНИЕМ мыши, а не за тем, где она лежит.
/// Разница не косметическая: пока панель под лучом та же, фокусом распоряжается
/// человек — Alt+Tab, Super+J, «фокус влево», выбор в обзоре и новое окно,
/// открытое прямо из игры, сохраняют клавиатуру за собой. Переустановка на
/// каждом кадре откатывала их за один кадр, и снаружи это выглядело как «бинды
/// не работают».
fn взять_фокус(state: &mut Parallax, ключ: Ключ) -> bool {
    let Some(шахта) = state.mine.as_mut() else { return false };
    if шахта.фокус_взгляда == Some(ключ) {
        return false;
    }
    шахта.фокус_взгляда = Some(ключ);
    true
}

/// Где рисовать стрелку. Курсор parallax живёт поверх кадра монитора и в полотно
/// панели не попадает вовсе, поэтому в игре его рисует мод — иначе не видно,
/// куда нажмёшь.
///
/// Шлём только НА ИЗМЕНЕНИЕ: сообщение короткое, но идёт оно каждый кадр, а на
/// той стороне это разбор в игровом такте и лишний повод перерисовать стрелку.
/// Сравниваем в пикселях панели — то есть в тех же числах, что уедут по
/// проводу: сравнивать луч бессмысленно, дрожь взгляда в четверть пикселя мод
/// всё равно не увидит.
fn послать_курсор(state: &mut Parallax, ключ: Ключ, x: f32, y: f32, видим: bool) {
    // Невидимый курсор — это «стрелки нет»; панель и точку в нём не сравниваем,
    // иначе взгляд, ушедший с панели на другую, слал бы «не видно» дважды.
    let сейчас = if видим { (ключ, x, y, true) } else { (0, 0.0, 0.0, false) };
    if state.mine.as_ref().is_some_and(|ш| ш.посланный_курсор == Some(сейчас)) {
        return;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.посланный_курсор = Some(сейчас);
    }
    net::послать(state, &proto::ОтДавна::Курсор { ключ, x, y, видим }, true);
}

/// Сделать окно плавающим на время ресайза — и навсегда после него.
///
/// **Без этого ресайза не было вовсе.** Раскладка пересчитывает размеры тайловых
/// окон из своего дерева на КАЖДОЙ перекладке (новое окно, смена стола, обзор,
/// закрытие соседа), так что натянутый `set_size` стирался ближайшим же поводом.
/// Замер на харнессе 01.09.2026: панель дотянули до 3133×1153, обзор столов
/// вернул 2508×1028 — это и есть жалоба «нажимаю Win+ПКМ, ничего не
/// происходит».
///
/// **Почему не деления дерева, как у мыши на столе** (`resize_grab.rs` тянет
/// `dwindle_resize_focused`). Две причины, и обе решающие. Первая: соседом по
/// дереву в игре сплошь и рядом оказывается САМО окно Minecraft — тянуть
/// деление значило бы менять размер игры из-под игрока. Вторая: единственному
/// тайловому окну дерево двигать нечего, и ресайз молча не делал бы ничего
/// (проверено на харнессе: одно окно, `ресайз` — 2508×1028 до и после).
///
/// В мире тайлинга нет: панель уже таскают взглядом свободно (`Хват`), и размер
/// обязан вести себя так же. `float_pinned` — «выбор человека», сборка в
/// тайлинг его не отменяет (см. `tiling::toggle_floating`).
fn выпустить_из_тайлинга(state: &mut Parallax, окно: &Window) {
    let было = state
        .tagged_windows
        .iter_mut()
        .find(|tw| &tw.window == окно)
        .map(|tw| {
            let было = tw.floating;
            tw.floating = true;
            tw.float_pinned = true;
            было
        });
    if было == Some(false) {
        // Соседи занимают освободившееся место — как при `toggle_floating`.
        state.arrange();
    }
}

/// Взять окно под прицелом на ресайз: запомнить линейку, край и размер на
/// старте.
fn начать_изменение_размера(state: &mut Parallax) {
    let Some(луч) = state.mine.as_ref().and_then(|ш| ш.луч) else { return };
    let Some(шахта) = state.mine.as_ref() else { return };
    let Some((i, _, местная_x, местная_y)) = попадание(&шахта.сцена, луч) else { return };
    let опора = шахта.сцена.панели[i];
    let Some(окно) = crate::vr::окно_по_ключу(state, опора.ключ) else { return };
    выпустить_из_тайлинга(state, &окно);
    let размер0 = crate::xwin::current_size(&окно);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.тащим = None;
        шахта.крутим = None;
        шахта.приближаем = None;
        шахта.меняем_размер = Some(ИзменениеРазмера {
            ключ: опора.ключ,
            опора,
            местная_x,
            местная_y,
            // Половина, за которую взялись, и есть край (Hypr3D: `HIT.u < 0.5`
            // — левый, `HIT.v < 0.5` — верхний; у нас Y вверх).
            край_x: if местная_x < 0.0 { -1 } else { 1 },
            край_y: if местная_y > 0.0 { 1 } else { -1 },
            размер0,
        });
    }
    tracing::info!(
        "plx/mine: panel {} resized from {}×{}",
        опора.ключ, размер0.w, размер0.h
    );
}

/// Вести размер за прицелом, пока держат Super+ПКМ.
fn вести_изменение_размера(state: &mut Parallax, изм: ИзменениеРазмера, луч: Луч) {
    let Some(окно) = crate::vr::окно_по_ключу(state, изм.ключ) else {
        // Окно закрылось под рукой — держаться не за что.
        if let Some(шахта) = state.mine.as_mut() {
            шахта.меняем_размер = None;
        }
        return;
    };
    // Плоскость опоры БЕЗ границ: тянуть окно больше исходной панели — обычное
    // дело, а `попал` за её краем вернул бы None и ресайз замирал бы ровно там,
    // где начинается интересное.
    const БЕЗ_ГРАНИЦ: f32 = 1.0e4;
    let Some((_, x, y)) = луч.попал(изм.опора.поза, БЕЗ_ГРАНИЦ, БЕЗ_ГРАНИЦ) else { return };
    let (w, h) = размер_по_прицелу(&изм, x, y);
    let новый = smithay::utils::Size::<i32, smithay::utils::Logical>::from((w, h));
    if crate::xwin::current_size(&окно) == новый {
        return;
    }
    crate::xwin::set_size(&окно, Some(новый), crate::xwin::Tiled::Keep);
    crate::xwin::configure(&окно);
    state.request_redraw();
}

/// Пределы размера окна при ресайзе взглядом, логические пиксели.
///
/// Снизу — окно, которое ещё можно увидеть и схватить обратно. Сверху — потому
/// что взгляд по плоскости ходит через тангенс: у края поля зрения крошечное
/// движение мыши уводит точку на десятки метров, и без потолка клиент получил
/// бы `configure` на сотню тысяч пикселей.
const МЕНЬШЕ_НЕЛЬЗЯ: i32 = 120;
const БОЛЬШЕ_НЕЛЬЗЯ: i32 = 8192;

/// Насколько далеко от точки захвата считается взгляд, в полуразмерах опоры —
/// та же защита от тангенса, но на входе, а не на выходе.
const ДАЛЬШЕ_НЕ_ТЯНЕМ: f32 = 3.0;

/// Размер окна, когда прицел пришёл в точку `(x, y)` плоскости опоры (метры
/// её местных координат, Y вверх) — `resizeBoxFromAim` у Hypr3D.
///
/// Тянущий край едет на столько пикселей, на сколько прицел прошёл от точки
/// захвата: правый край вправо — шире, левый край влево — шире, верхний вверх
/// — выше, нижний вниз — выше. Старт ничего не дёргает: в точке захвата размер
/// ровно исходный.
fn размер_по_прицелу(изм: &ИзменениеРазмера, x: f32, y: f32) -> (i32, i32) {
    let о = изм.опора;
    let пкс_на_метр_x = о.ширина_пкс as f32 / (2.0 * о.пол_ширина.max(1e-4));
    let пкс_на_метр_y = о.высота_пкс as f32 / (2.0 * о.пол_высота.max(1e-4));
    let предел_x = о.пол_ширина.max(1e-4) * ДАЛЬШЕ_НЕ_ТЯНЕМ;
    let предел_y = о.пол_высота.max(1e-4) * ДАЛЬШЕ_НЕ_ТЯНЕМ;
    let x = x.clamp(изм.местная_x - предел_x, изм.местная_x + предел_x);
    let y = y.clamp(изм.местная_y - предел_y, изм.местная_y + предел_y);
    let dx = (x - изм.местная_x) * пкс_на_метр_x * изм.край_x as f32;
    let dy = (y - изм.местная_y) * пкс_на_метр_y * изм.край_y as f32;
    (
        (изм.размер0.w as f32 + dx).round().clamp(МЕНЬШЕ_НЕЛЬЗЯ as f32, БОЛЬШЕ_НЕЛЬЗЯ as f32) as i32,
        (изм.размер0.h as f32 + dy).round().clamp(МЕНЬШЕ_НЕЛЬЗЯ as f32, БОЛЬШЕ_НЕЛЬЗЯ as f32) as i32,
    )
}

/// Ближе и дальше этого панель колесом не утянуть, метры (они же блоки).
///
/// У Hypr3D пределов нет вовсе. Здесь они есть по одной причине на каждый:
/// вплотную панель уходит за ближнюю плоскость отсечения игры и пропадает, а
/// дальше прорисовки чанков её не видно — человек считал бы, что окно
/// потерялось.
const БЛИЖЕ_НЕЛЬЗЯ: f32 = 0.3;
const ДАЛЬШЕ_НЕЛЬЗЯ: f32 = 256.0;

/// Один зубец колеса меняет расстояние в этой пропорции — число Hypr3D
/// (`ZOOM_FACTOR = 1.06`): множитель, а не слагаемое, поэтому шаг ощущается
/// одинаково и у самого лица, и в двадцати блоках.
const ЗУБЕЦ: f32 = 1.06;

/// Больше двух зубцов за событие не берём: у колёс высокого разрешения одно
/// физическое движение приходит пачкой, и без предела «чуть крутнул» швыряло бы
/// окно через весь мир (у Hypr3D тот же `clamp(-2, 2)`).
const ЗУБЦОВ_ЗА_РАЗ: f32 = 2.0;

/// Колесо, пока панель несут: притянуть или оттолкнуть её. Меняется ЦЕЛЬ,
/// само расстояние доезжает в `вести_перенос`.
///
/// `true` — колесо съедено переносом и в окно не уходит.
fn тяга_колесом(state: &mut Parallax, шаги: f32) -> bool {
    let Some(шахта) = state.mine.as_mut() else { return false };
    let Some(мы) = шахта.тащим.as_mut() else { return false };
    // Колесо ОТ СЕБЯ (у мода плюс — договор GLFW) толкает панель дальше, как у
    // Hypr3D: «wheel forward (+) pushes the window away».
    мы.цель = (мы.цель * ЗУБЕЦ.powf(шаги)).clamp(БЛИЖЕ_НЕЛЬЗЯ, ДАЛЬШЕ_НЕЛЬЗЯ);
    state.request_redraw();
    true
}

fn отпустить_кнопку(state: &mut Parallax) {
    let держим = state.mine.as_ref().is_some_and(|ш| ш.кнопка_нажата);
    if !держим {
        return;
    }
    seat::кнопка(state, None, crate::synth::КНОПКА_ЛКМ, false);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.кнопка_нажата = false;
        шахта.захват = None;
    }
}

/// Запомнить луч указки. Отдельной функцией, потому что этим путём ходят двое:
/// живой мод (через [`принять_сообщение`]) и харнесс (через [`луч_снаружи`]).
/// Проверка вырожденного направления обязана быть общей: NaN, пропущенный на
/// одном из путей, потом тихо разъезжается по всей сцене.
fn запомнить_луч(state: &mut Parallax, начало: [f32; 3], направление: [f32; 3]) -> bool {
    let л = Луч::new(
        Век3::new(начало[0], начало[1], начало[2]),
        Век3::new(направление[0], направление[1], направление[2]),
    );
    if !л.направление.длина().is_finite() || л.направление.длина() < 0.5 {
        tracing::warn!("plx/mine: degenerate ray {направление:?} — skipping");
        return false;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.луч = Some(л);
    }
    state.request_redraw();
    true
}

/// Сообщение от мода. `false` — соединение рвём.
pub fn принять_сообщение(state: &mut Parallax, сообщение: proto::ОтМода) -> bool {
    let впущен = state
        .mine
        .as_ref()
        .and_then(|ш| ш.мод.as_ref())
        .is_some_and(|м| м.впущен);

    // До «привета» не принимаем ничего: мод чужой версии обязан получить
    // отказ, а не начать двигать курсор по чужой раскладке полей.
    if !впущен {
        let proto::ОтМода::Привет { версия, имя, умения } = сообщение else {
            tracing::warn!("plx/mine: mod spoke before the greeting — dropping");
            return false;
        };
        if версия != proto::ВЕРСИЯ {
            tracing::warn!(
                "plx/mine: mod speaks version {версия}, protocol is {} — dropping",
                proto::ВЕРСИЯ
            );
            return false;
        }
        let (зона_ширина, зона_глубина) = match state.mine.as_ref() {
            Some(ш) => (ш.сцена.зона.пол_ширина * 2.0, ш.сцена.зона.пол_глубина * 2.0),
            None => return false,
        };
        let dmabuf = умения & proto::умею::DMABUF != 0;
        if let Some(м) = state.mine.as_mut().and_then(|ш| ш.мод.as_mut()) {
            м.впущен = true;
            м.имя = имя.clone();
            м.dmabuf = dmabuf;
        }
        tracing::info!("plx/mine: mod '{имя}' connected (dmabuf: {dmabuf})");
        net::послать(
            state,
            &proto::ОтДавна::Здравствуй { версия: proto::ВЕРСИЯ, зона_ширина, зона_глубина },
            false,
        );
        // Всё, что мод знал раньше, недействительно: пусть текстуры зальются
        // заново на ближайшем кадре.
        if let Some(шахта) = state.mine.as_mut() {
            шахта.посланные.clear();
            шахта.слепок.clear();
            // Буферов прошлого мода у этого нет: полотна заводятся заново и
            // уйдут ему на ближайшем кадре вместе с дескрипторами.
            if let Some(дма) = шахта.дма.as_mut() {
                дма.полотна.clear();
            }
            // И про стрелку мод тоже ничего не знает: без сброса она появилась
            // бы у него только после следующего поворота головы.
            шахта.посланный_курсор = None;
        }
        state.request_redraw();
        return true;
    }

    // Мышь мода отменяет ожидающий тап Super — ровно как хозяйский клик
    // (`input.rs`: «Любой клик отменяет ожидающий тап Super»). Клики игрока до
    // parallax не доходят вовсе: мышь в этот момент у Minecraft, а к композитору
    // они приезжают по сокету. Без этой строки Super+ПКМ кончался обзором
    // столов на ОТПУСКАНИИ Super — и обзор перекладывал тайлинг, стирая только
    // что натянутый размер. Снаружи это и есть жалоба 01.09.2026: «нажимаю
    // Win+ПКМ, ничего не происходит, а потом камера дёргается в другую
    // сторону» (замер на харнессе: панель дотянули до 3133×1153, обзор вернул
    // 2508×1028).
    if matches!(
        сообщение,
        proto::ОтМода::Кнопка { .. } | proto::ОтМода::Хват { .. } | proto::ОтМода::Колесо { .. }
    ) {
        state.super_tap = false;
    }

    match сообщение {
        proto::ОтМода::Привет { .. } => {
            tracing::warn!("plx/mine: greeting sent twice — dropping");
            return false;
        }
        proto::ОтМода::Луч { начало, направление } => {
            запомнить_луч(state, начало, направление);
        }
        proto::ОтМода::Кнопка { код, нажата } => {
            // Кнопку жмём ТОЛЬКО когда указка на панели: клик в пустоту мира
            // Minecraft не должен уходить в окно, на которое человек не смотрит.
            let наведено = state.mine.as_ref().and_then(|ш| ш.наведено);
            let захват = state.mine.as_ref().and_then(|ш| ш.захват);
            if нажата && наведено.is_none() && захват.is_none() {
                return true;
            }
            // Кнопка уходит окну захвата, если он есть: отпускание обязано
            // попасть туда же, где было нажатие, куда бы ни смотрел игрок.
            let ключ = захват.map(|(к, _)| к).or(наведено.map(|(к, _, _)| к));
            if let (Some(к), Some(шахта)) = (ключ, state.mine.as_mut()) {
                let держат = шахта.захват.map_or(0, |(_, n)| n);
                let держат = if нажата { держат.saturating_add(1) } else { держат.saturating_sub(1) };
                шахта.захват = (держат > 0).then_some((к, держат));
            }
            let окно = ключ.and_then(|к| crate::vr::окно_по_ключу(state, к));
            seat::кнопка(state, окно, код, нажата);
            if код == crate::synth::КНОПКА_ЛКМ {
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.кнопка_нажата = нажата;
                }
            }
        }
        proto::ОтМода::Колесо { dx, dy, супер } => {
            let шаги = dy.clamp(-ЗУБЦОВ_ЗА_РАЗ, ЗУБЦОВ_ЗА_РАЗ);
            // Пока тянут размер или крутят, колесу делать нечего: оно двигало
            // бы панель из-под той же руки, что держит край.
            if state.mine.as_ref().is_some_and(|ш| ш.меняем_размер.is_some() || ш.крутим.is_some()) {
                return true;
            }
            // Пока панель несут, колесо — её расстояние (Hypr3D: «during an
            // LMB drag the wheel zooms the dragged window»), с Super или без.
            if тяга_колесом(state, шаги) {
                return true;
            }
            // Super+колесо над панелью — ближе/дальше без хвата. В окно такое
            // колесо не уходит никогда, даже мимо панелей.
            if супер {
                let луч = state.mine.as_ref().and_then(|ш| ш.луч);
                if let (Some(шахта), Some(луч)) = (state.mine.as_mut(), луч) {
                    приблизить(шахта, луч, шаги);
                }
                state.request_redraw();
                return true;
            }
            // Обе оси: Minecraft отдаёт моду и горизонталь (тачпад, наклон
            // колеса), а браузер на панели без неё не прокручивался бы вбок.
            //
            // ВЕРТИКАЛЬ ПЕРЕВОРАЧИВАЕМ, и это не косметика. Мод шлёт колесо по
            // договору GLFW (и Minecraft за ним): вверх — ПЛЮС. Wayland
            // считает наоборот, у него положительная вертикаль это прокрутка
            // ВНИЗ. Без минуса всякая панель — терминал, браузер, редактор —
            // прокручивалась бы колесом задом наперёд.
            //
            // Горизонталь при этом НЕ трогаем: там оба договора совпадают,
            // плюс — вправо.
            seat::колесо(state, dx as f64, -dy as f64);
        }
        proto::ОтМода::Клавиша { код, нажата } => {
            // Через СВОЁ место, а не через `process_input_event`: хозяйская
            // клавиатура в этот момент у Minecraft, и отдать её панели значило
            // бы лишить игру даже той клавиши, которой ввод возвращают назад.
            // Бинды parallax при этом работают — их разбирает `seat::клавиша`.
            seat::клавиша(state, код, нажата);
        }
        proto::ОтМода::Указка { ключ, x, y } => {
            // Закрепление за окном, которого нет, молча пропускаем: мод мог
            // взять управление ровно тогда, когда окно закрылось.
            let есть = ключ != 0 && crate::vr::окно_по_ключу(state, ключ).is_some();
            // Кнопку, зажатую на ПРЕДЫДУЩЕЙ цели, отпускаем при смене окна —
            // иначе она осталась бы нажатой в нём навсегда.
            let прежний = state.mine.as_ref().and_then(|ш| ш.закреплено).map(|(к, _, _)| к);
            if прежний.is_some() && прежний != Some(ключ) {
                отпустить_кнопку(state);
            }
            if let Some(шахта) = state.mine.as_mut() {
                шахта.закреплено = есть.then_some((ключ, x as f64, y as f64));
            }
            применить_ввод(state);
            state.request_redraw();
        }
        proto::ОтМода::Хват { нажат, вид } => {
            // Вид хвата называет мод: Super+ЛКМ — нести, Super+ПКМ — размер,
            // Super+СКМ — крутить, как у Hypr3D. Отпускание любого снимает все
            // три: у одной руки один жест.
            if let Some(шахта) = state.mine.as_mut() {
                шахта.тащим = None;
                шахта.доводка = шахта.меняем_размер.take().map(|и| (и, std::time::Instant::now()));
                шахта.крутим = None;
            }
            if !нажат {
                state.request_redraw();
                return true;
            }
            let луч = state.mine.as_ref().and_then(|ш| ш.луч);
            let Some(луч) = луч else { return true };
            match вид {
                proto::хват::РАЗМЕР => начать_изменение_размера(state),
                proto::хват::КРУТИТЬ => {
                    if let Some(шахта) = state.mine.as_mut() {
                        шахта.приближаем = None;
                        начать_вращение(шахта, луч);
                    }
                }
                _ => {
                    if let Some(шахта) = state.mine.as_mut() {
                        начать_перенос(шахта, луч);
                    }
                }
            }
            state.request_redraw();
        }
        proto::ОтМода::Действие { имя } => match crate::config::action_from_str(&имя, "") {
            Some(действие) => {
                tracing::info!("plx/mine: action '{имя}'");
                // Выключать режим изнутри игры — верный способ остаться без
                // панелей и без способа вернуть их: клавиатура в этот момент у
                // Minecraft.
                if matches!(действие, crate::config::Action::MineMode) {
                    tracing::warn!("plx/mine: the mode can only be left from the keyboard");
                } else {
                    state.dispatch_action(действие);
                }
            }
            None => tracing::warn!("plx/mine: unknown action '{имя}'"),
        },
        proto::ОтМода::Пока => {
            tracing::info!("plx/mine: mod said goodbye");
            return false;
        }
    }
    true
}

