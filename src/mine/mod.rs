//! plx-mine: parallax внутри Minecraft.
//!
//! **Что это.** Тот же приём, что в шлеме (см. `vr/`), только «шлем» —
//! Minecraft с модом `plx-mine`. Окна parallax становятся панелями, висящими в мире
//! игры; взгляд игрока — указкой; клик — обычным кликом parallax. Композитор при
//! этом остаётся собой целиком: столы, тайлинг, зум, бинды, буфер обмена — всё
//! работает, потому что меняется только то, КУДА уходит картинка и ОТКУДА
//! приходит указка.
//!
//! ```text
//!   окно parallax ──► полотно (vr::нарисовать_в_полотно, damage-трекер)
//!                     │  только изменившиеся куски
//!                     ▼
//!   пиксели RGBA ──► unix-сокет ──► мод (Java) ──► квад в мире Minecraft
//!                     ▲                               │
//!                     │                               ▼ взгляд игрока
//!   курсор parallax ◄── луч (scene::навести) ◄───────── ЛУЧ в метрах сцены
//! ```
//!
//! **Что здесь СВОЁ, а что взято у VR.** Расстановка панелей, пересечение луча
//! с панелью и отрисовка окна в полотно — общие с VR: это ровно те три вещи,
//! которые дорого писать и очень дорого иметь в двух расходящихся копиях
//! (панель на экране в одном месте, клик — в другом). Своё здесь: сокет,
//! протокол и вычитка пикселей — у шлема их нет, он получает текстуру напрямую
//! в своём GL-контексте.
//!
//! **Почему пиксели, а не dmabuf.** Мод живёт в JVM со своим GL-контекстом, и
//! отдать ему текстуру parallax без EGL-моста нельзя, а мост потребовал бы правок
//! в самом Minecraft. Полотна вычитываются `copy_framebuffer` и едут по
//! unix-сокету сырыми — но только повреждёнными кусками (см. `Повреждения`):
//! неподвижное окно не стоит ничего, набор текста в терминале — десятки
//! килобайт на кадр.
//!
//! **Ввод.** Мод не решает, куда попал взгляд, — он шлёт ЛУЧ, а попадание
//! считает parallax тем же `scene::навести`, что и для шлема. Клавиши разбирает та
//! же `input::разобрать_клавишу`, что и клавиши с железной клавиатуры, поэтому
//! из игры работают ВСЕ бинды parallax и всё, чего в таблице биндов нет: обзор
//! тапом по Super, лупа и её пан стрелками, Alt+Tab, меню. Ещё мод умеет
//! попросить любое действие parallax по имени (`ОтМода::Действие`) — тем же именем,
//! что стоит в `bind{}`.
//!
//! **Управление — логика Hypr3D** (плагин Hyprland, github.com/samine825/Hypr3D;
//! перенесена 07.10.2026 по просьбе Ярика «сделай как в Hypr3D»):
//!
//! * прицел — указка; окно под прицелом получает фокус сразу, ушёл прицел в
//!   мир — через [`ГРАЦИЯ_ПРИЦЕЛА`] фокуса нет ни у кого;
//! * клавиши без переключателя: движение игре, остальное окну под прицелом
//!   (решает мод, `Dmine.клавиша`); Super+Левый Alt — «всё окну»;
//! * Super+ЛКМ — нести панель ([`Перенос`]), колесо в это время — ближе/дальше;
//!   Super+ПКМ — тянуть размер за ближний край ([`ИзменениеРазмера`]);
//!   Super+СКМ — крутить ([`Вращение`]); Super+колесо — ближе/дальше без хвата
//!   ([`Приближение`]);
//! * окна в мире сняты с раскладки стола ([`Призрак`]): tiling/niri/floating
//!   их больше не трогает, новые окна появляются перед игроком.
//!
//! **Окно, с которым работают** — это панель под взглядом (или закреплённая), а
//! не то, что держит фокус у хозяина: там всегда сама игра. Развилка живёт в
//! `Parallax::focused_surface` — без неё `Super+Q` из игры закрывал бы Minecraft.
//! Панели под взглядом ещё не было — бинд, метящий в окно, не делает НИЧЕГО:
//! хозяйский фокус в этот момент и есть игра, и «ресайз» тихо менял бы её
//! размер под полным экраном (жалоба 01.09.2026 «не работает ресайз и часть
//! биндов»; замер на харнессе: окно игры 2560×1050 → 2560×1020).
//!
//! **Игра — всегда верхняя, и хозяйская клавиатура её.** Всё остальное человек
//! видит панелями ВНУТРИ неё, поэтому окно, поднятое поверх Minecraft, — это
//! мир, на мгновение сменившийся рабочим столом. Поднять его умеют трое: новое
//! окно (`xwin::insert_new_window` — оно же отбирало у игры клавиатуру, и
//! запущенный из игры терминал выкидывал игрока на стол), клик мода по панели
//! (`seat::кнопка` поднимает её ради попапов) и любой бинд, метящий в фокус
//! (Alt+Tab, обзор). Первые два чинятся по месту, на всех прочих стоит
//! [`игру_наверх`] — и зовётся он ПЕРЕД сборкой кадра, из `udev::render_surface`.
//! Такт режима для этого не годится: он идёт в конце итерации главного цикла,
//! то есть уже ПОСЛЕ `render_all`, и окно успевало показаться поверх игры ровно
//! на один кадр — «между открытием окон просвечивают окна поверх игры» (жалоба
//! 01.09.2026).

