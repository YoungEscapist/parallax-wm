/// Луч игрока → курсор dawn. Ровно та же логика, что у указки в шлеме, и по
/// той же причине: дальше работает весь существующий код — `surface_under`,
/// фокус по наведению, клики, перетаскивание, меню.
fn применить_ввод(state: &mut Dawn) {
    // ── Закреплённое окно (ЛКМ по панели) ───────────────────────────────────
    //
    // Управление отдано ОДНОМУ окну: стрелку по нему ведёт мышь, взгляд не
    // участвует. Ветка стоит первой и до луча не доходит вовсе — в этом весь
    // смысл режима: игрок вправе смотреть куда угодно, пока печатает.
    //
    // Закрепление за закрытым окном отпускаем молча: панель исчезла, держаться
    // не за что, и указка возвращается взгляду.
    if let Some((ключ, x, y)) = state.mine.as_ref().and_then(|ш| ш.закреплено) {
        match crate::vr::окно_по_ключу(state, ключ) {
            Some(окно) => {
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.наведено = Some((ключ, x, y));
                }
                seat::навести(state, &окно, x, y);
                послать_курсор(state, ключ, x as f32, y as f32, true);
                return;
            }
            None => {
                отпустить_кнопку(state);
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.закреплено = None;
                }
            }
        }
    }

    let Some(луч) = state.mine.as_ref().and_then(|ш| ш.луч) else { return };

    // ── Перетаскивание панели ───────────────────────────────────────────────
    if let Some((индекс, расстояние)) = state.mine.as_ref().and_then(|ш| ш.тащим) {
        // Глаз игрока — начало его же луча: другого положения головы у нас нет,
        // и оно тут единственно верное (панель разворачивается к тому, кто её
        // тащит).
        let глаз = луч.начало;
        if let Some(шахта) = state.mine.as_mut() {
            if индекс < шахта.сцена.панели.len() {
                шахта.сцена.перенести(индекс, луч, расстояние, глаз);
            } else {
                // Окно закрылось, пока его тащили: хват отпускаем, иначе
                // индекс указывал бы в чужую панель.
                шахта.тащим = None;
            }
        }
        // Пока тащим — курсор в окно не гоняем: окно получало бы «мышь ездит»
        // на каждый кадр переноса.
        return;
    }

    let попал = state.mine.as_ref().and_then(|ш| ш.сцена.навести(луч));
    let наведено = попал.and_then(|(i, x, y)| {
        state
            .mine
            .as_ref()
            .map(|ш| (ш.сцена.панели[i].ключ, x, y))
    });
    if let Some(шахта) = state.mine.as_mut() {
        шахта.наведено = наведено;
    }

    // ── Указка → своё место ─────────────────────────────────────────────────
    //
    // Ни курсор хозяина, ни его фокус здесь больше не трогаются: у мода своё
    // место (`seat.rs`). Именно поэтому исчезло правило «пока трогают мышь,
    // указка молчит», которое живёт в шлеме: спорить не с кем — хозяйская мышь
    // осталась у Minecraft и крутит игроку голову.
    let Some((ключ, пкс_x, пкс_y)) = наведено else {
        // Взгляд в пустоту: зажатую кнопку отпускаем, иначе окно осталось бы с
        // нажатой мышью навсегда.
        отпустить_кнопку(state);
        seat::увести(state);
        послать_курсор(state, 0, 0.0, 0.0, false);
        return;
    };

    if let Some(окно) = crate::vr::окно_по_ключу(state, ключ) {
        seat::навести(state, &окно, пкс_x, пкс_y);
    }
    послать_курсор(state, ключ, пкс_x as f32, пкс_y as f32, true);
}

/// Где рисовать стрелку. Курсор dawn живёт поверх кадра монитора и в полотно
/// панели не попадает вовсе, поэтому в игре его рисует мод — иначе не видно,
/// куда нажмёшь.
///
/// Шлём только НА ИЗМЕНЕНИЕ: сообщение короткое, но идёт оно каждый кадр, а на
/// той стороне это разбор в игровом такте и лишний повод перерисовать стрелку.
/// Сравниваем в пикселях панели — то есть в тех же числах, что уедут по
/// проводу: сравнивать луч бессмысленно, дрожь взгляда в четверть пикселя мод
/// всё равно не увидит.
fn послать_курсор(state: &mut Dawn, ключ: Ключ, x: f32, y: f32, видим: bool) {
    // Невидимый курсор — это «стрелки нет»; панель и точку в нём не сравниваем,
    // иначе взгляд, ушедший с панели на другую, слал бы «не видно» дважды.
    let сейчас = if видим { (ключ, x, y, true) } else { (0, 0.0, 0.0, false) };
    if state.mine.as_ref().is_some_and(|ш| ш.посланный_курсор == Some(сейчас)) {
        return;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.посланный_курсор = Some(сейчас);
    }
    net::послать(state, &proto::ОтДавна::Курсор { ключ, x, y, видим }, true);
}

fn отпустить_кнопку(state: &mut Dawn) {
    let держим = state.mine.as_ref().is_some_and(|ш| ш.кнопка_нажата);
    if !держим {
        return;
    }
    seat::кнопка(state, None, crate::synth::КНОПКА_ЛКМ, false);
    if let Some(шахта) = state.mine.as_mut() {
        шахта.кнопка_нажата = false;
    }
}

/// Запомнить луч указки. Отдельной функцией, потому что этим путём ходят двое:
/// живой мод (через [`принять_сообщение`]) и харнесс (через [`луч_снаружи`]).
/// Проверка вырожденного направления обязана быть общей: NaN, пропущенный на
/// одном из путей, потом тихо разъезжается по всей сцене.
fn запомнить_луч(state: &mut Dawn, начало: [f32; 3], направление: [f32; 3]) -> bool {
    let л = Луч::new(
        Век3::new(начало[0], начало[1], начало[2]),
        Век3::new(направление[0], направление[1], направление[2]),
    );
    if !л.направление.длина().is_finite() || л.направление.длина() < 0.5 {
        tracing::warn!("dawn/mine: вырожденный луч {направление:?} — пропускаю");
        return false;
    }
    if let Some(шахта) = state.mine.as_mut() {
        шахта.луч = Some(л);
    }
    state.request_redraw();
    true
}

/// Сообщение от мода. `false` — соединение рвём.
pub fn принять_сообщение(state: &mut Dawn, сообщение: proto::ОтМода) -> bool {
    let впущен = state
        .mine
        .as_ref()
        .and_then(|ш| ш.мод.as_ref())
        .is_some_and(|м| м.впущен);

    // До «привета» не принимаем ничего: мод чужой версии обязан получить
    // отказ, а не начать двигать курсор по чужой раскладке полей.
    if !впущен {
        let proto::ОтМода::Привет { версия, имя } = сообщение else {
            tracing::warn!("dawn/mine: мод заговорил до приветствия — рвём");
            return false;
        };
        if версия != proto::ВЕРСИЯ {
            tracing::warn!(
                "dawn/mine: мод версии {версия}, а протокол {} — рвём",
                proto::ВЕРСИЯ
            );
            return false;
        }
        let (зона_ширина, зона_глубина) = match state.mine.as_ref() {
            Some(ш) => (ш.сцена.зона.пол_ширина * 2.0, ш.сцена.зона.пол_глубина * 2.0),
            None => return false,
        };
        if let Some(м) = state.mine.as_mut().and_then(|ш| ш.мод.as_mut()) {
            м.впущен = true;
            м.имя = имя.clone();
        }
        tracing::info!("dawn/mine: мод «{имя}» на связи");
        net::послать(
            state,
            &proto::ОтДавна::Здравствуй { версия: proto::ВЕРСИЯ, зона_ширина, зона_глубина },
            false,
        );
        // Всё, что мод знал раньше, недействительно: пусть текстуры зальются
        // заново на ближайшем кадре.
        if let Some(шахта) = state.mine.as_mut() {
            шахта.посланные.clear();
            шахта.слепок.clear();
            // И про стрелку мод тоже ничего не знает: без сброса она появилась
            // бы у него только после следующего поворота головы.
            шахта.посланный_курсор = None;
        }
        state.request_redraw();
        return true;
    }

    match сообщение {
        proto::ОтМода::Привет { .. } => {
            tracing::warn!("dawn/mine: повторное приветствие — рвём");
            return false;
        }
        proto::ОтМода::Луч { начало, направление } => {
            запомнить_луч(state, начало, направление);
        }
        proto::ОтМода::Кнопка { код, нажата } => {
            // Кнопку жмём ТОЛЬКО когда указка на панели: клик в пустоту мира
            // Minecraft не должен уходить в окно, на которое человек не смотрит.
            let на_панели = state.mine.as_ref().is_some_and(|ш| ш.наведено.is_some());
            if нажата && !на_панели {
                return true;
            }
            let окно = state
                .mine
                .as_ref()
                .and_then(|ш| ш.наведено)
                .and_then(|(ключ, _, _)| crate::vr::окно_по_ключу(state, ключ));
            seat::кнопка(state, окно, код, нажата);
            if код == crate::synth::КНОПКА_ЛКМ {
                if let Some(шахта) = state.mine.as_mut() {
                    шахта.кнопка_нажата = нажата;
                }
            }
        }
        proto::ОтМода::Колесо { dx, dy } => {
            // Обе оси: Minecraft отдаёт моду и горизонталь (тачпад, наклон
            // колеса), а браузер на панели без неё не прокручивался бы вбок.
            seat::колесо(state, dx as f64, dy as f64);
        }
        proto::ОтМода::Клавиша { код, нажата } => {
            // Через СВОЁ место, а не через `process_input_event`: хозяйская
            // клавиатура в этот момент у Minecraft, и отдать её панели значило
            // бы лишить игру даже той клавиши, которой ввод возвращают назад.
            // Бинды dawn при этом работают — их разбирает `seat::клавиша`.
            seat::клавиша(state, код, нажата);
        }
        proto::ОтМода::Указка { ключ, x, y } => {
            // Закрепление за окном, которого нет, молча пропускаем: мод мог
            // взять управление ровно тогда, когда окно закрылось.
            let есть = ключ != 0 && crate::vr::окно_по_ключу(state, ключ).is_some();
            // Кнопку, зажатую на ПРЕДЫДУЩЕЙ цели, отпускаем при смене окна —
            // иначе она осталась бы нажатой в нём навсегда.
            let прежний = state.mine.as_ref().and_then(|ш| ш.закреплено).map(|(к, _, _)| к);
            if прежний.is_some() && прежний != Some(ключ) {
                отпустить_кнопку(state);
            }
            if let Some(шахта) = state.mine.as_mut() {
                шахта.закреплено = есть.then_some((ключ, x as f64, y as f64));
            }
            применить_ввод(state);
            state.request_redraw();
        }
        proto::ОтМода::Хват { нажат } => {
            let луч = state.mine.as_ref().and_then(|ш| ш.луч);
            if let (Some(шахта), Some(луч)) = (state.mine.as_mut(), луч) {
                шахта.тащим = if нажат {
                    шахта.сцена.навести(луч).map(|(i, _, _)| {
                        let d = шахта.сцена.панели[i]
                            .поза
                            .место
                            .минус(луч.начало)
                            .длина();
                        (i, d)
                    })
                } else {
                    None
                };
            }
        }
        proto::ОтМода::Действие { имя } => match crate::config::action_from_str(&имя, "") {
            Some(действие) => {
                tracing::info!("dawn/mine: действие «{имя}»");
                // Выключать режим изнутри игры — верный способ остаться без
                // панелей и без способа вернуть их: клавиатура в этот момент у
                // Minecraft.
                if matches!(действие, crate::config::Action::MineMode) {
                    tracing::warn!("dawn/mine: выйти из режима можно только с клавиатуры");
                } else {
                    state.dispatch_action(действие);
                }
            }
            None => tracing::warn!("dawn/mine: неизвестное действие «{имя}»"),
        },
        proto::ОтМода::Пока => {
            tracing::info!("dawn/mine: мод попрощался");
            return false;
        }
    }
    true
}

