    /// Заголовок окна у Ярика русский, а обрезка по 255 БАЙТАМ приходится на
    /// середину буквы. Битый utf-8 в моде — это не «кракозябры в подписи», а
    /// исключение в разборе на стороне Java и пропавшая панель.
    #[test]
    fn длинный_кириллический_заголовок_не_рвёт_букву() {
        let длинный = "я".repeat(200); // 400 байт
        let о = ОтДавна::Панели(vec![Панель {
            ключ: 1,
            место: [0.0; 3],
            поворот: [0.0, 0.0, 0.0, 1.0],
            пол_ширина: 0.5,
            пол_высота: 0.5,
            ш_пкс: 10,
            в_пкс: 10,
            заголовок: длинный,
        }]);
        let байты = о.в_байты();
        let ОтДавна::Панели(назад) = ОтДавна::из_байт(&байты[4..]).expect("не разобралось") else {
            panic!("разобралось не в панели");
        };
        assert!(
            назад[0].заголовок.chars().all(|c| c == 'я'),
            "в заголовке появился мусор: {:?}",
            назад[0].заголовок
        );
    }

    #[test]
    fn поток_собирает_разрезанное_сообщение() {
        let целое = ОтМода::Луч { начало: [1.0; 3], направление: [0.0, 0.0, -1.0] }.в_байты();
        let mut п = Поток::new();
        for i in 0..целое.len() - 1 {
            п.дописать(&целое[i..i + 1]);
            assert_eq!(п.следующее(), Ok(None), "сообщение выдано недособранным");
        }
        п.дописать(&целое[целое.len() - 1..]);
        let тело = п.следующее().unwrap().expect("сообщение не собралось");
        assert!(matches!(ОтМода::из_байт(&тело), Some(ОтМода::Луч { .. })));
    }

    #[test]
    fn запредельная_длина_рвёт_соединение() {
        let mut п = Поток::new();
        п.дописать(&u32::MAX.to_le_bytes());
        assert_eq!(п.следующее(), Err(()));
    }

