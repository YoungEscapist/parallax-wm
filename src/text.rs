//! Текст в оверлеях dawn: Nunito, растеризованный fontdue, и текстуры строк.
//!
//! **Что здесь было раньше.** Свой битмап-шрифт 7×13: 161 глиф таблицей по
//! `u8` на строку, старший бит — левый столбец, ASCII 32..126 плюс кириллица
//! и Ё/ё. Он честно отработал своё (без него меню блютуза было бы без имён
//! устройств), но у моноширинной единички на 13 строк потолок один: буквы
//! ступенчатые, кегль меняется только целым множителем, а всё, чего в таблице
//! нет, рисуется как «?» — многоточие «…» в том числе.
//!
//! Теперь глифы берутся из настоящего шрифта — **Nunito** (SIL OFL, лежит в
//! `assets/`, вшивается в бинарь через `include_bytes!`): скруглённый и
//! спокойный, ровно то, чем dawn хочет выглядеть. Растеризует `fontdue` —
//! чистый Rust, без C-зависимостей и без системных шрифтовых библиотек,
//! которых в dawn не было и заводить их ради подписей не хотелось.
//!
//! Покрытие проверено по cmap обоих начертаний: ASCII 0x20..0x7E целиком,
//! кириллица 0x400..0x45F целиком, «…» (0x2026), «№» (0x2116), «°» (0x00B0).
//! Это строгий надмножество старой таблицы — потерять символ переход не мог.
//!
//! **Как считается кегль.** Вызывающие живут в единицах `scale` (целый
//! множитель, `bar::TEXT = 2`), и высота строки как была `GLYPH_H * scale`,
//! так и осталась: вся вёрстка панелей и меню считает от неё. Кегль под эту
//! высоту подбирается не по метрикам из `hhea` (они с запасом под диакритику
//! и дали бы заметно мельче прежнего), а по ФАКТИЧЕСКОЙ краске: один раз при
//! первом обращении опрашиваются метрики всех символов покрытия и берётся
//! настоящий разброс ymin..ymax. Поэтому строка гарантированно не обрезается
//! (буфер ровно такой высоты, какая нужна самому высокому глифу — им, к слову,
//! оказался не «Ё», а «Ѐ» с ударением),
//! и при этом занимает всю отведённую высоту, а не её половину.
//!
//! Ширина теперь НАСТОЯЩАЯ: шрифт пропорциональный, `width()` складывает
//! адвансы (с кернингом), а не умножает число символов на ширину ячейки.
//! Считать её арифметикой снаружи больше НЕЛЬЗЯ, и константы `GLYPH_W`,
//! которой это делали, здесь намеренно нет: у пропорционального шрифта нет
//! ширины ячейки, и любое её значение было бы враньём в среднем. Где нужен
//! порог «влезает ли столько-то» — меряется ОБРАЗЕЦ строки (`bar::layout`),
//! где нужна обрезка — [`fits`].
//!
//! Почему текстурой, а не прямоугольниками. Строка из 20 символов — это ~600
//! закрашенных «пикселей» глифов; отдельными `SolidColorRenderElement` кадр
//! распух бы вчетверо (сейчас в кадре ~400 элементов на всё). Поэтому строка
//! растеризуется в RGBA-буфер и уходит одним элементом, как плитки декораций.
//!
//! Пиксели premultiplied — так их ждёт GL-блендинг smithay. Про пул буферов
//! (по буферу на каждый нарисованный экземпляр) см. заметку об Id в decor.rs:
//! damage tracker индексируется по Id буфера, и один буфер в двух элементах
//! кадра ломает подсчёт повреждений.

use std::collections::HashMap;
use std::sync::OnceLock;

use fontdue::{Font, FontSettings};
use smithay::{
    backend::{allocator::Fourcc, renderer::element::memory::MemoryRenderBuffer},
    utils::Transform,
};

/// Высота строки в «пикселях шрифта» на единицу `scale`.
pub const GLYPH_H: i32 = 13;

/// Начертание. Regular — для текста, который читают (заголовки окон, имена
/// устройств); SemiBold — для коротких подписей поверх полупрозрачных плашек
/// (часы, буквы столов, горячие клавиши в меню), где тонкий штрих size 13
/// просто размывается о фон.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Weight {
    Regular,
    Semi,
}

static REGULAR_TTF: &[u8] = include_bytes!("../assets/Nunito-Regular.ttf");
static SEMI_TTF: &[u8] = include_bytes!("../assets/Nunito-SemiBold.ttf");

/// Шрифт вместе с нормировкой, снятой с него самого (см. [`Норма`]).
struct Начертание {
    font: Font,
    норма: Норма,
}

/// Во что укладывается краска шрифта на единицу кегля.
///
/// `высота` — полный разброс ymin..ymax по всему покрытию, `база` — сколько от
/// верха этого разброса до базовой линии. Обе доли от кегля, поэтому кегль под
/// заданную высоту строки = `высота_строки / норма.высота`, а базовая линия
/// внутри буфера = `кегль * норма.база`.
struct Норма {
    высота: f32,
    база: f32,
}

/// Символы, по которым снимается нормировка: всё, что шрифт вообще может
/// нарисовать в dawn. Крайние по высоте здесь заведомо есть — «Ё» и «й» сверху
/// (диакритика), «р», «у», «щ», «g», «j» снизу (выносные элементы).
fn покрытие() -> impl Iterator<Item = char> {
    (0x20u32..=0x7E)
        .chain(0x400..=0x45F)
        .chain([0xB0, 0x2026, 0x2116])
        .filter_map(char::from_u32)
}

impl Начертание {
    fn new(ttf: &[u8]) -> Self {
        // collection_index 0, scale — подсказка кэшу растеризатора, на метрики
        // не влияет. Шрифт вшит в бинарь, так что развалиться разбор может
        // только при порче самого бинаря — тогда падать честнее, чем молча
        // остаться без подписей.
        let font = Font::from_bytes(ttf, FontSettings::default())
            .expect("dawn: не разобрался вшитый Nunito");
        // Референсный кегль берём крупным: метрики fontdue целочисленные, и на
        // мелком кегле округление до пикселя заметно перекосило бы доли.
        const REF: f32 = 256.0;
        let (mut верх, mut низ) = (0.0f32, 0.0f32);
        for ch in покрытие() {
            let m = font.metrics(ch, REF);
            if m.width == 0 || m.height == 0 {
                continue; // пробел и прочее без краски
            }
            верх = верх.max((m.ymin + m.height as i32) as f32);
            низ = низ.min(m.ymin as f32);
        }
        let разброс = (верх - низ).max(1.0);
        Self {
            font,
            норма: Норма { высота: разброс / REF, база: верх / REF },
        }
    }
}

fn начертание(w: Weight) -> &'static Начертание {
    static REGULAR: OnceLock<Начертание> = OnceLock::new();
    static SEMI: OnceLock<Начертание> = OnceLock::new();
    match w {
        Weight::Regular => REGULAR.get_or_init(|| Начертание::new(REGULAR_TTF)),
        Weight::Semi => SEMI.get_or_init(|| Начертание::new(SEMI_TTF)),
    }
}

/// Кегль (px), при котором краска шрифта ровно заполняет высоту строки.
fn кегль(w: Weight, scale: i32) -> f32 {
    height(scale) as f32 / начертание(w).норма.высота
}

/// Разложить строку по горизонтали: для каждого символа — его пиксельные
/// метрики и позиция пера. Возвращает ещё и общую ширину буфера.
///
/// Ширина — это не просто сумма адвансов: у крайнего правого глифа краска
/// может выступать за адванс (курсивные хвосты, «Ж», кавычки), и обрезать её
/// нельзя. Поэтому берём максимум из «сумма адвансов» и «правый край краски».
fn раскладка(text: &str, w: Weight, scale: i32) -> (Vec<(char, f32)>, i32) {
    let н = начертание(w);
    let px = кегль(w, scale);
    let mut плоды = Vec::with_capacity(text.chars().count());
    let mut перо = 0.0f32;
    let mut край = 0.0f32;
    let mut прошлый: Option<char> = None;
    for ch in text.chars() {
        if let Some(p) = прошлый {
            перо += н.font.horizontal_kern(p, ch, px).unwrap_or(0.0);
        }
        let m = н.font.metrics(ch, px);
        плоды.push((ch, перо));
        край = край.max(перо + m.xmin as f32 + m.width as f32);
        перо += m.advance_width;
        прошлый = Some(ch);
    }
    (плоды, перо.max(край).ceil().max(0.0) as i32)
}

/// Ширина строки в пикселях при масштабе `scale` (начертание Regular).
pub fn width(text: &str, scale: i32) -> i32 {
    width_of(text, Weight::Regular, scale)
}

/// То же для заданного начертания: у SemiBold адвансы шире, и мерить её
/// метриками Regular значит промахнуться мимо своей же плашки.
pub fn width_of(text: &str, w: Weight, scale: i32) -> i32 {
    if text.is_empty() {
        return 0;
    }
    раскладка(text, w, scale.max(1)).1
}

/// Сколько символов строки влезает в `max_w` пикселей (начертание `w`).
/// Нужна там, где строку обрезают: посчитать это делением на ширину символа
/// нельзя — символы разной ширины.
pub fn fits(text: &str, w: Weight, scale: i32, max_w: i32) -> usize {
    let (плоды, _) = раскладка(text, w, scale.max(1));
    let н = начертание(w);
    let px = кегль(w, scale.max(1));
    let mut n = 0;
    for (i, (ch, перо)) in плоды.iter().enumerate() {
        let m = н.font.metrics(*ch, px);
        if (перо + m.advance_width).ceil() as i32 > max_w {
            break;
        }
        n = i + 1;
    }
    n
}

/// Высота строки при масштабе `scale`.
pub fn height(scale: i32) -> i32 {
    GLYPH_H * scale.max(1)
}

/// Растеризовать строку в premultiplied RGBA.
///
/// Сначала копится ОДНОБАЙТНАЯ маска покрытия, и только потом разворачивается
/// в цвет. Так соседние глифы, задевающие друг друга (кернинг сводит их
/// вплотную), не темнят перекрытие вдвое: в маске берётся максимум, а не сумма.
/// Публична ради VR: пульты в шлеме (`vr/ui.rs`) рисуют свой холст целиком
/// сами и кладут строки прямо в него — `MemoryRenderBuffer` из `TextCache` им
/// не подходит, потому что в шлеме нет ни элементов кадра, ни damage tracker'а,
/// а есть одна текстура на всю панель.
pub fn pixels(text: &str, w: Weight, scale: i32, color: [f32; 4]) -> (Vec<u8>, i32, i32) {
    let scale = scale.max(1);
    let н = начертание(w);
    let px = кегль(w, scale);
    let (плоды, ширина) = раскладка(text, w, scale);
    let ширина = ширина.max(1);
    let высота = height(scale);
    let база = (px * н.норма.база).round() as i32;

    let mut маска = vec![0u8; (ширина * высота) as usize];
    for (ch, перо) in плоды {
        let (m, покрытие) = н.font.rasterize(ch, px);
        if m.width == 0 || m.height == 0 {
            continue;
        }
        let ox = (перо + m.xmin as f32).round() as i32;
        // ymin отсчитывается ВВЕРХ от базовой линии, а строки буфера идут вниз.
        let oy = база - m.ymin - m.height as i32;
        for row in 0..m.height as i32 {
            let y = oy + row;
            if y < 0 || y >= высота {
                continue;
            }
            for col in 0..m.width as i32 {
                let x = ox + col;
                if x < 0 || x >= ширина {
                    continue;
                }
                let c = покрытие[(row * m.width as i32 + col) as usize];
                let o = (y * ширина + x) as usize;
                маска[o] = маска[o].max(c);
            }
        }
    }

    let a = color[3].clamp(0.0, 1.0);
    let mut buf = vec![0u8; (ширина * высота * 4) as usize];
    for (i, &c) in маска.iter().enumerate() {
        if c == 0 {
            continue;
        }
        let alpha = a * (c as f32 / 255.0);
        buf[i * 4] = (color[0] * alpha * 255.0).round() as u8;
        buf[i * 4 + 1] = (color[1] * alpha * 255.0).round() as u8;
        buf[i * 4 + 2] = (color[2] * alpha * 255.0).round() as u8;
        buf[i * 4 + 3] = (alpha * 255.0).round() as u8;
    }
    (buf, ширина, высота)
}

/// Ключ кэша: одинаковые строки одного размера, цвета и НАЧЕРТАНИЯ делят
/// пиксели. Начертание в ключе обязательно: «12:30» полужирным и обычным — две
/// разные картинки разной ширины, а с общим ключом вторая молча получила бы
/// растр первой.
type Key = (String, i32, [u32; 4], u8);

fn key(text: &str, scale: i32, color: [f32; 4]) -> Key {
    (text.to_string(), scale, color.map(|c| c.to_bits()), 0)
}

fn key_w(text: &str, scale: i32, color: [f32; 4], w: Weight) -> Key {
    let (t, s, c, _) = key(text, scale, color);
    (t, s, c, match w { Weight::Regular => 1, Weight::Semi => 2 })
}

/// Сколько разных картинок держим в кэше.
///
/// Предел появился вместе с панелью (bar.rs): раньше кэш жил только на время
/// открытого меню и обнулялся при закрытии, а панель рисует часы и ЗАГОЛОВОК
/// АКТИВНОГО ОКНА — то есть строки, которые меняются сами по себе. Часы дают
/// 1440 разных строк в сутки, заголовки вкладок браузера — сколько угодно, и
/// каждая тянет за собой растр (строка в 50 символов при масштабе 2 — это
/// 73 КБ) плюс пул буферов. За день такой кэш съедал бы сотни мегабайт.
const CACHE_LIMIT: usize = 256;

/// Кэш растеризованных картинок (строки, маски значков, углы плиток) + пул
/// буферов на каждую.
///
/// Вытесняется по давности использования, а не сбрасывается целиком. Разница
/// принципиальная: часы добавляют новую строку каждую минуту, и полный сброс
/// раз в CACHE_LIMIT минут выбрасывал бы заодно углы островов и значки — то
/// есть всё то, что рисуется КАЖДЫЙ кадр и не меняется никогда. Один кадр
/// после сброса пришлось бы растрировать заново целиком.
pub struct TextCache {
    protos: HashMap<Key, (Vec<u8>, i32, i32)>,
    pools: HashMap<Key, Vec<MemoryRenderBuffer>>,
    /// Когда ключом пользовались в последний раз (номер обращения).
    used: HashMap<Key, u64>,
    tick: u64,
}

impl TextCache {
    pub fn new() -> Self {
        Self {
            protos: HashMap::new(),
            pools: HashMap::new(),
            used: HashMap::new(),
            tick: 0,
        }
    }

    /// Общая часть всех трёх видов картинок: отметить обращение, вытеснить
    /// давнее, растрировать при первом появлении и выдать буфер под номером.
    ///
    /// `build` зовётся ТОЛЬКО когда картинки в кэше ещё нет.
    fn ensure<F>(&mut self, k: Key, slot: usize, build: F) -> (&MemoryRenderBuffer, i32, i32)
    where
        F: FnOnce() -> (Vec<u8>, i32, i32),
    {
        self.tick += 1;
        self.used.insert(k.clone(), self.tick);

        if !self.protos.contains_key(&k) && self.protos.len() >= CACHE_LIMIT {
            // Выбрасываем САМОЕ ДАВНЕЕ — им заведомо окажется устаревшая
            // строка часов или ушедший заголовок окна, а не углы и значки.
            if let Some(старьё) = self
                .used
                .iter()
                .filter(|(key, _)| self.protos.contains_key(*key))
                .min_by_key(|(_, t)| **t)
                .map(|(key, _)| key.clone())
            {
                self.protos.remove(&старьё);
                self.pools.remove(&старьё);
                self.used.remove(&старьё);
            }
        }

        let proto = self.protos.entry(k.clone()).or_insert_with(build);
        let (px, w, h) = (&proto.0, proto.1, proto.2);
        let pool = self.pools.entry(k).or_default();
        while pool.len() <= slot {
            pool.push(MemoryRenderBuffer::from_slice(
                px, Fourcc::Abgr8888, (w, h), 1, Transform::Normal, None,
            ));
        }
        (&pool[slot], w, h)
    }

    /// Буфер строки для слота `slot` начертанием Regular.
    pub fn buffer(
        &mut self,
        text: &str,
        scale: i32,
        color: [f32; 4],
        slot: usize,
    ) -> (&MemoryRenderBuffer, i32, i32) {
        self.buffer_w(text, Weight::Regular, scale, color, slot)
    }

    /// Буфер строки заданным начертанием. Растеризация происходит один раз на
    /// (строка, начертание, масштаб, цвет); буферы в пуле создаются по мере
    /// надобности.
    pub fn buffer_w(
        &mut self,
        text: &str,
        w: Weight,
        scale: i32,
        color: [f32; 4],
        slot: usize,
    ) -> (&MemoryRenderBuffer, i32, i32) {
        let k = key_w(text, scale, color, w);
        let text = text.to_string();
        self.ensure(k, slot, move || pixels(&text, w, scale, color))
    }

    /// Буфер 1-битной маски (значки полки и блютуза) РАЗМЕРОМ В ПИКСЕЛЯХ, а не
    /// кратным масштабом: `rows` — по строке на пиксель маски, старший бит из
    /// `w` — левый столбец. Маска растеризуется с запасом (SS×SS выборок на
    /// итоговый пиксель) и усредняется — по краям выходит полупрозрачная
    /// кромка вместо лесенки. Ключ кэша делается из `name`, поэтому он должен
    /// быть уникален.
    ///
    /// Зачем: значок блютуза считается долей от высоты бара и на кратный
    /// масштаб не ложится. Отдать крупный буфер и попросить рендер сжать его
    /// было нельзя — он берёт ближайший пиксель, и тонкие диагонали руны
    /// просто выпадали: на экране от значка оставались палка и пара ступенек.
    pub fn bitmap_fit(
        &mut self,
        name: &str,
        rows: &[u32],
        w: i32,
        tw: i32,
        th: i32,
        color: [f32; 4],
        slot: usize,
    ) -> (&MemoryRenderBuffer, i32, i32) {
        const SS: i32 = 4; // выборок на пиксель по каждой оси
        let k = key(&format!("{name}@{tw}x{th}"), th, color);
        let rows = rows.to_vec();
        self.ensure(k, slot, move || {
            let (tw, th) = (tw.max(1), th.max(1));
            let (mw, mh) = (w.max(1), rows.len().max(1) as i32);
            let mut buf = vec![0u8; (tw * th * 4) as usize];
            let a = color[3].clamp(0.0, 1.0);
            for y in 0..th {
                for x in 0..tw {
                    let mut hits = 0i32;
                    for sy in 0..SS {
                        // Центр подвыборки → координата в маске.
                        let my = ((y * SS + sy) as i64 * mh as i64
                            / (th * SS) as i64) as i32;
                        let Some(bits) = rows.get(my as usize) else { continue };
                        for sx in 0..SS {
                            let mx = ((x * SS + sx) as i64 * mw as i64
                                / (tw * SS) as i64) as i32;
                            if bits & (1 << (mw - 1 - mx)) != 0 {
                                hits += 1;
                            }
                        }
                    }
                    if hits == 0 {
                        continue;
                    }
                    // Покрытие идёт в альфу, цвет домножен на неё (premultiplied).
                    let cov = a * hits as f32 / (SS * SS) as f32;
                    let o = ((y * tw + x) * 4) as usize;
                    buf[o..o + 4].copy_from_slice(&[
                        (color[0] * cov * 255.0).round() as u8,
                        (color[1] * cov * 255.0).round() as u8,
                        (color[2] * cov * 255.0).round() as u8,
                        (cov * 255.0).round() as u8,
                    ]);
                }
            }
            (buf, tw, th)
        })
    }

    /// Плитка скруглённого угла: квадрат со стороной `radius`, залитый цветом
    /// внутри четверти круга и прозрачный снаружи. `corner` — 0=ЛВ, 1=ПВ,
    /// 2=ЛН, 3=ПН.
    ///
    /// Зачем плитка вместо построчной заливки. `udev::rounded_solid` режет углы
    /// ПО СТРОКЕ: скруглённый прямоугольник радиуса 12 — это 25 элементов
    /// кадра, а панель сверху из них и состоит (одних значков столов девять).
    /// В живом логе это давало «элементов до 252, из них интерфейс 215» на
    /// пустом экране. С плитками тот же прямоугольник — четыре текстуры плюс
    /// три сплошных куска, семь элементов вместо двадцати пяти, а края ещё и
    /// сглажены (у построчной версии они лесенкой).
    pub fn corner(
        &mut self,
        radius: i32,
        corner: usize,
        color: [f32; 4],
        slot: usize,
    ) -> (&MemoryRenderBuffer, i32) {
        const SS: i32 = 4; // подвыборок на пиксель по каждой оси
        let r = radius.max(1);
        let k = key(&format!("corner{r}#{corner}"), r, color);
        let (buf, side, _) = self.ensure(k, slot, move || {
            // Центр окружности — в том углу плитки, который смотрит ВНУТРЬ
            // прямоугольника: у левого-верхнего угла это правый-нижний край.
            let cx = if corner % 2 == 1 { 0.0 } else { r as f64 };
            let cy = if corner >= 2 { 0.0 } else { r as f64 };
            let a = color[3].clamp(0.0, 1.0);
            let mut buf = vec![0u8; (r * r * 4) as usize];
            for y in 0..r {
                for x in 0..r {
                    let mut внутри = 0i32;
                    for sy in 0..SS {
                        for sx in 0..SS {
                            let px = x as f64 + (sx as f64 + 0.5) / SS as f64;
                            let py = y as f64 + (sy as f64 + 0.5) / SS as f64;
                            if (px - cx).hypot(py - cy) <= r as f64 {
                                внутри += 1;
                            }
                        }
                    }
                    if внутри == 0 {
                        continue;
                    }
                    let cov = a * внутри as f32 / (SS * SS) as f32;
                    let o = ((y * r + x) * 4) as usize;
                    buf[o..o + 4].copy_from_slice(&[
                        (color[0] * cov * 255.0).round() as u8,
                        (color[1] * cov * 255.0).round() as u8,
                        (color[2] * cov * 255.0).round() as u8,
                        (cov * 255.0).round() as u8,
                    ]);
                }
            }
            (buf, r, r)
        });
        (buf, side)
    }

    /// Выбросить всё, что накопилось. Зовётся, когда меню закрывается: имена
    /// устройств и проценты заряда меняются, и держать их вечно незачем.
    pub fn clear(&mut self) {
        self.protos.clear();
        self.pools.clear();
        self.used.clear();
    }
}

#[cfg(test)]
