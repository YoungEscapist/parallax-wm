/// Индекс глифа в таблице. Неизвестный символ рисуется как «?».
fn glyph(ch: char) -> &'static [u8; GLYPH_H as usize] {
    let idx = match ch {
        ' '..='~' => ch as usize - 32,
        'А'..='я' => 95 + (ch as usize - 0x410),
        'Ё' => 159,
        'ё' => 160,
        _ => '?' as usize - 32,
    };
    &GLYPHS[idx.min(GLYPHS.len() - 1)]
}

/// Ширина строки в «пикселях шрифта» при масштабе `scale`.
pub fn width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * GLYPH_W * scale
}

/// Высота строки при масштабе `scale`.
pub fn height(scale: i32) -> i32 {
    GLYPH_H * scale
}

/// Растеризовать строку в premultiplied RGBA.
fn pixels(text: &str, scale: i32, color: [f32; 4]) -> (Vec<u8>, i32, i32) {
    let scale = scale.max(1);
    let w = width(text, scale).max(1);
    let h = height(scale);
    let mut buf = vec![0u8; (w * h * 4) as usize];
    let a = color[3].clamp(0.0, 1.0);
    let rgba = [
        (color[0] * a * 255.0).round() as u8,
        (color[1] * a * 255.0).round() as u8,
        (color[2] * a * 255.0).round() as u8,
        (a * 255.0).round() as u8,
    ];
    for (i, ch) in text.chars().enumerate() {
        let g = glyph(ch);
        let ox = i as i32 * GLYPH_W * scale;
        for (row, bits) in g.iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (1 << (GLYPH_W - 1 - col)) == 0 {
                    continue;
                }
                // один «пиксель шрифта» — квадрат scale×scale
                for dy in 0..scale {
                    for dx in 0..scale {
                        let x = ox + col * scale + dx;
                        let y = row as i32 * scale + dy;
                        let o = ((y * w + x) * 4) as usize;
                        buf[o..o + 4].copy_from_slice(&rgba);
                    }
                }
            }
        }
    }
    (buf, w, h)
}

/// Ключ кэша: одинаковые строки одного размера и цвета делят пиксели.
type Key = (String, i32, [u32; 4]);

fn key(text: &str, scale: i32, color: [f32; 4]) -> Key {
    (text.to_string(), scale, color.map(|c| c.to_bits()))
}

/// Кэш растеризованных строк + пул буферов на каждую.
pub struct TextCache {
    protos: HashMap<Key, (Vec<u8>, i32, i32)>,
    pools: HashMap<Key, Vec<MemoryRenderBuffer>>,
}

impl TextCache {
    pub fn new() -> Self {
        Self { protos: HashMap::new(), pools: HashMap::new() }
    }

    /// Буфер строки для слота `slot`. Растеризация происходит один раз на
    /// (строка, масштаб, цвет); буферы в пуле создаются по мере надобности.
    pub fn buffer(
        &mut self,
        text: &str,
        scale: i32,
        color: [f32; 4],
        slot: usize,
    ) -> (&MemoryRenderBuffer, i32, i32) {
        let k = key(text, scale, color);
        let proto = self.protos.entry(k.clone())
            .or_insert_with(|| pixels(text, scale, color));
        let (px, w, h) = (&proto.0, proto.1, proto.2);
        let pool = self.pools.entry(k).or_default();
        while pool.len() <= slot {
            pool.push(MemoryRenderBuffer::from_slice(
                px, Fourcc::Abgr8888, (w, h), 1, Transform::Normal, None,
            ));
        }
        (&pool[slot], w, h)
    }

    /// Буфер 1-битной маски (значки полки и блютуза) РАЗМЕРОМ В ПИКСЕЛЯХ, а не
    /// кратным масштабом: `rows` — по строке на пиксель маски, старший бит из
    /// `w` — левый столбец. Маска растеризуется с запасом (SS×SS выборок на
    /// итоговый пиксель) и усредняется — по краям выходит полупрозрачная
    /// кромка вместо лесенки. Ключ кэша делается из `name`, поэтому он должен
    /// быть уникален.
    ///
    /// Зачем: значок блютуза считается долей от высоты бара и на кратный
    /// масштаб не ложится. Отдать крупный буфер и попросить рендер сжать его
    /// было нельзя — он берёт ближайший пиксель, и тонкие диагонали руны
    /// просто выпадали: на экране от значка оставались палка и пара ступенек.
    pub fn bitmap_fit(
        &mut self,
        name: &str,
        rows: &[u32],
        w: i32,
        tw: i32,
        th: i32,
        color: [f32; 4],
        slot: usize,
    ) -> (&MemoryRenderBuffer, i32, i32) {
        const SS: i32 = 4; // выборок на пиксель по каждой оси
        let k = key(&format!("{name}@{tw}x{th}"), th, color);
        let proto = self.protos.entry(k.clone()).or_insert_with(|| {
            let (tw, th) = (tw.max(1), th.max(1));
            let (mw, mh) = (w.max(1), rows.len().max(1) as i32);
            let mut buf = vec![0u8; (tw * th * 4) as usize];
            let a = color[3].clamp(0.0, 1.0);
            for y in 0..th {
                for x in 0..tw {
                    let mut hits = 0i32;
                    for sy in 0..SS {
                        // Центр подвыборки → координата в маске.
                        let my = ((y * SS + sy) as i64 * mh as i64
                            / (th * SS) as i64) as i32;
                        let Some(bits) = rows.get(my as usize) else { continue };
                        for sx in 0..SS {
                            let mx = ((x * SS + sx) as i64 * mw as i64
                                / (tw * SS) as i64) as i32;
                            if bits & (1 << (mw - 1 - mx)) != 0 {
                                hits += 1;
                            }
                        }
                    }
                    if hits == 0 {
                        continue;
                    }
                    // Покрытие идёт в альфу, цвет домножен на неё (premultiplied).
                    let cov = a * hits as f32 / (SS * SS) as f32;
                    let o = ((y * tw + x) * 4) as usize;
                    buf[o..o + 4].copy_from_slice(&[
                        (color[0] * cov * 255.0).round() as u8,
                        (color[1] * cov * 255.0).round() as u8,
                        (color[2] * cov * 255.0).round() as u8,
                        (cov * 255.0).round() as u8,
                    ]);
                }
            }
            (buf, tw, th)
        });
        let (px, pw, ph) = (&proto.0, proto.1, proto.2);
        let pool = self.pools.entry(k).or_default();
        while pool.len() <= slot {
            pool.push(MemoryRenderBuffer::from_slice(
                px, Fourcc::Abgr8888, (pw, ph), 1, Transform::Normal, None,
            ));
        }
        (&pool[slot], pw, ph)
    }

    /// Выбросить всё, что накопилось. Зовётся, когда меню закрывается: имена
    /// устройств и проценты заряда меняются, и держать их вечно незачем.
    pub fn clear(&mut self) {
        self.protos.clear();
        self.pools.clear();
    }
}
