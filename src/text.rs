    /// Печатает строку «пикселями» — глазами посмотреть, что глиф не поехал.
    /// Живёт под `--nocapture`, автоматических утверждений не делает.
    fn показать(text: &str, w: Weight, scale: i32) {
        let (buf, ширина, высота) = pixels(text, w, scale, [1.0, 1.0, 1.0, 1.0]);
        println!("── {text:?} {w:?} scale={scale} → {ширина}×{высота}");
        for y in 0..высота {
            let строка: String = (0..ширина)
                .map(|x| match buf[((y * ширина + x) * 4 + 3) as usize] {
                    0..=31 => ' ',
                    32..=95 => '·',
                    96..=159 => '+',
                    160..=207 => '#',
                    _ => '█',
                })
                .collect();
            println!("│{строка}│");
        }
    }

    /// Замер: во что обходится измерение строки. `bar::layout` зовётся на
    /// КАЖДЫЙ кадр (до 190/с), и если ширина считается дорого, это видно.
    #[test]
    #[ignore = "замер, не проверка"]
    fn почём_измерение() {
        let образцы = ["12:30", "Пн 23.08", "RU", "100%",
                       "Waterfox — Rust: примитивы синхронизации и когда их применять"];
        // прогрев (разбор шрифта + нормировка)
        for s in образцы { width(s, 2); }
        let t = std::time::Instant::now();
        const N: u32 = 10_000;
        let mut сумма = 0i64;
        for _ in 0..N {
            for s in образцы { сумма += width(s, 2) as i64; }
        }
        let на_кадр = t.elapsed().as_secs_f64() / N as f64 * 1e6;
        println!("измерение всех подписей панели: {на_кадр:.2} мкс на кадр (сумма {сумма})");
        let t = std::time::Instant::now();
        for _ in 0..200 { pixels("Waterfox — примитивы синхронизации", Weight::Regular, 2, [1.0;4]); }
        println!("растеризация строки: {:.1} мкс", t.elapsed().as_secs_f64()/200.0*1e6);
    }

    #[test]
    fn посмотреть_глазами() {
        показать("Ёй 12:30 Wq", Weight::Semi, 2);
        показать("Пн 23.08", Weight::Regular, 1);
    }

    /// Кегль подобран так, чтобы САМАЯ высокая и САМАЯ низкая краска шрифта
    /// ровно вписывались в отведённую высоту строки. Проверяем обе границы: в
    /// буфере не должно оставаться пустых полей сверху/снизу (иначе текст
    /// мельче, чем мог быть), и ничего не должно обрезаться.
    #[test]
    fn краска_занимает_всю_высоту_и_не_обрезается() {
        for w in [Weight::Regular, Weight::Semi] {
            for scale in [1, 2, 3] {
                // Крайние глифы покрытия, снятые замером (см. `покрытие`):
                // «Ѐ» с ударением — выше всех, «Q» — глубже всех. Брать сюда
                // «Ё» было бы естественно и НЕВЕРНО: её диакритика ниже.
                let (buf, ширина, высота) = pixels("ЀQ", w, scale, [1.0, 1.0, 1.0, 1.0]);
                assert_eq!(высота, height(scale));
                let занята = |y: i32| {
                    (0..ширина).any(|x| buf[((y * ширина + x) * 4 + 3) as usize] > 0)
                };
                assert!(занята(0), "{w:?} scale={scale}: сверху пустая строка — кегль занижен");
                assert!(
                    занята(высота - 1),
                    "{w:?} scale={scale}: снизу пустая строка — кегль занижен",
                );
            }
        }
    }

    /// Ширина строки — сумма настоящих адвансов, а не число символов на
    /// ширину ячейки. Проверка ровно про то, обо что спотыкались вызывающие:
    /// узкие и широкие символы должны давать РАЗНУЮ ширину.
    #[test]
    fn ширина_пропорциональная() {
        let узко = width("iiii", 2);
        let широко = width("ШШШШ", 2);
        assert!(узко > 0 && широко > узко, "iiii={узко}, ШШШШ={широко}");
        assert_eq!(width("", 2), 0);
        // fits не даёт вылезти за отведённое место и не врёт в большую сторону.
        let s = "Waterfox — примитивы синхронизации";
        for предел in [10, 50, 120, 400] {
            let n = fits(s, Weight::Regular, 2, предел);
            let кусок: String = s.chars().take(n).collect();
            assert!(
                width(&кусок, 2) <= предел,
                "«{кусок}» = {} > {предел}", width(&кусок, 2),
            );
        }
    }

    /// Кэш обязан выбрасывать ДАВНЕЕ, а не всё подряд. Проверка ровно про
    /// панель: часы добавляют новую строку каждую минуту, и полный сброс
    /// уносил бы вместе с ними углы островов — то, что рисуется каждый кадр.
    #[test]
    fn кэш_вытесняет_давнее_а_не_горячее() {
        let mut c = TextCache::new();
        let цвет = [1.0f32, 1.0, 1.0, 1.0];
        let горячий = key("corner12#0", 12, цвет);

        for i in 0..CACHE_LIMIT * 2 {
            // Каждый «час» — новая строка и обращение к тому же углу.
            c.buffer(&format!("{:02}:{:02}", i / 60, i % 60), 2, цвет, 0);
            c.corner(12, 0, цвет, 0);
        }

        assert!(
            c.protos.len() <= CACHE_LIMIT,
            "кэш разросся: {} записей при пределе {}", c.protos.len(), CACHE_LIMIT,
        );
        assert!(c.protos.contains_key(&горячий), "угол острова вытеснили");
        assert!(
            !c.protos.contains_key(&key("00:00", 2, цвет)),
            "самая давняя строка осталась в кэше",
        );
    }

    /// Плитка угла: внутри четверти круга — цвет, снаружи — прозрачно. Ошибка
    /// в центре окружности дала бы «обкусанные» с другой стороны острова.
    #[test]
    fn плитка_угла_закруглена_в_нужную_сторону() {
        let mut c = TextCache::new();
        let цвет = [1.0f32, 1.0, 1.0, 1.0];
        const R: i32 = 8;

        // Левый-верхний угол: центр окружности в правом-нижнем углу плитки.
        let альфа = |c: &mut TextCache, corner: usize, x: i32, y: i32| -> u8 {
            let k = key(&format!("corner{R}#{corner}"), R, цвет);
            c.corner(R, corner, цвет, 0);
            let (px, w, _) = c.protos.get(&k).expect("плитка построена");
            px[((y * w + x) * 4 + 3) as usize]
        };

        assert_eq!(альфа(&mut c, 0, 0, 0), 0, "ЛВ: внешний угол должен быть пуст");
        assert_eq!(альфа(&mut c, 0, R - 1, R - 1), 255, "ЛВ: внутренний угол должен быть залит");
        assert_eq!(альфа(&mut c, 1, R - 1, 0), 0, "ПВ: внешний угол должен быть пуст");
        assert_eq!(альфа(&mut c, 1, 0, R - 1), 255, "ПВ: внутренний угол должен быть залит");
        assert_eq!(альфа(&mut c, 2, 0, R - 1), 0, "ЛН: внешний угол должен быть пуст");
        assert_eq!(альфа(&mut c, 3, R - 1, R - 1), 0, "ПН: внешний угол должен быть пуст");
    }
