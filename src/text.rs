//! Текст в оверлеях dawn: 1-битный шрифт 7×13 и текстуры строк.
//!
//! Зачем свой шрифт. dawn рисует интерфейс сплошными прямоугольниками и
//! текстурами (см. decor.rs), внешних библиотек шрифтов в нём нет, а меню
//! блютуза без имён устройств бессмысленно. Глифы растрированы один раз из
//! JetBrains Mono NF (скрипт лежит в истории задачи) и вшиты таблицей: по
//! `u8` на строку глифа, старший бит — левый столбец. ASCII 32..126 и
//! кириллица А..я, Ё/ё — имена наушников часто русские.
//!
//! Почему текстурой, а не прямоугольниками. Строка из 20 символов — это ~600
//! закрашенных «пикселей» глифов; отдельными `SolidColorRenderElement` кадр
//! распух бы вчетверо (сейчас в кадре ~400 элементов на всё). Поэтому строка
//! растеризуется в RGBA-буфер и уходит одним элементом, как плитки декораций.
//!
//! Пиксели premultiplied — так их ждёт GL-блендинг smithay. Про пул буферов
//! (по буферу на каждый нарисованный экземпляр) см. заметку об Id в decor.rs:
//! damage tracker индексируется по Id буфера, и один буфер в двух элементах
//! кадра ломает подсчёт повреждений.

