const ОРЕОЛ_СДВИГ: &str = "";

/// Цветной ореол наружу — тот же акцент обоев и та же ручка `glow`, что у каймы
/// изнутри. Именно он и связывает обводку со свечением: одно значение, один
/// цвет, один источник света, разные стороны границы окна.
#[cfg(feature = "shaders")]
const ОРЕОЛ_СВЕЧЕНИЕ: &str = r#"
        if (glow_strength > 0.0 && hd > 0.0) {
            // Наружу ореол тянется вдвое дальше, чем кайма внутрь: снаружи ему
            // не мешает содержимое окна, и короткий ореол читался бы обводкой в
            // один пиксель, а не свечением.
            float hrim = 1.0 - smoothstep(0.0, max(glow_width * 2.0, 1.0), hd);
            // Квадрат — тот же спад, что у света на холсте (свет.rs::профиль):
            // линейный даёт видимую границу «здесь светит, а дальше нет».
            hrim = hrim * hrim;
            float hside = 0.5;
            if (light_amount > 0.0) {
                vec2 hlp = (hp - hcenter) / max(hhalf, vec2(1.0));
                hside = clamp(dot(hlp, light_dir) * 0.5 + 0.5, 0.0, 1.0);
            }
            // 0.6 — ореол тише каймы: он крупнее по площади, и в полную силу
            // окно оказывалось бы в цветном тумане.
            hrgb += glow_color * (hrim * glow_strength * (0.5 + hside) * 0.6);
        }
"#;
#[cfg(not(feature = "shaders"))]
const ОРЕОЛ_СВЕЧЕНИЕ: &str = "";

/// Исходник шейдера под текущую сборку: те же строки, что выше, с
/// подставленным (или пустым) свечением.
fn исходник() -> String {
    ФРАГМЕНТ
        .replace("//_GLOW_UNIFORMS_", ГЛОУ_UNIFORMS)
        .replace("//_GLOW_BODY_", ГЛОУ_ТЕЛО)
        .replace("//_HALO_SHIFT_", ОРЕОЛ_СДВИГ)
        .replace("//_HALO_GLOW_", ОРЕОЛ_СВЕЧЕНИЕ)
}

/// Скомпилированная программа. Компилируется один раз на рендерер.
#[derive(Debug, Clone)]
pub struct Шейдер(GlesTexProgram);

impl Шейдер {
    pub fn new(renderer: &mut GlesRenderer) -> Option<Self> {
        // Uniform'ы свечения регистрируются только там, где они в шейдере
        // есть: имени, которого нет в коде, GLSL не оставляет location, и
        // регистрация такого uniform'а — заявка на несуществующее.
        let mut uniforms = vec![
            UniformName::new("win_rect", UniformType::_4f),
            UniformName::new("win_radius", UniformType::_1f),
            UniformName::new("hard_clip", UniformType::_1f),
            // Ореол есть в ОБЕИХ сборках: тень вокруг окна — не украшение, а
            // единственное, что отделяет окно от обоев. Цветной он только там,
            // где есть свечение (см. ОРЕОЛ_СВЕЧЕНИЕ).
            UniformName::new("halo", UniformType::_1f),
            UniformName::new("halo_spread", UniformType::_1f),
            UniformName::new("halo_drop", UniformType::_1f),
            UniformName::new("halo_dark", UniformType::_1f),
        ];
        if cfg!(feature = "shaders") {
            uniforms.push(UniformName::new("glow_color", UniformType::_3f));
            uniforms.push(UniformName::new("glow_width", UniformType::_1f));
            uniforms.push(UniformName::new("glow_strength", UniformType::_1f));
            uniforms.push(UniformName::new("light_dir", UniformType::_2f));
            uniforms.push(UniformName::new("light_amount", UniformType::_1f));
        }
        match renderer.compile_custom_texture_shader(исходник().as_str(), &uniforms) {
            Ok(program) => Some(Self(program)),
            Err(e) => {
                // Не фатально: без шейдера окна просто останутся с прямыми
                // углами. Молчать нельзя — иначе «скругление пропало» пришлось
                // бы искать снаружи.
                tracing::warn!("plx/rounded: corner shader failed to compile: {:?}", e);
                None
            }
        }
    }
}

/// Тень ореола: насколько далеко наружу и куда она уходит.
///
/// Цвет и свет сюда не входят — они общие со свечением окна и приезжают
/// [`Свечение`]м. В этом и смысл: у обводки нет ни своего цвета, ни своего
/// источника света, только геометрия.
#[derive(Clone, Copy, Debug)]
pub struct Ореол {
    /// Ширина тени наружу, физические пиксели.
    pub ширина: f32,
    /// Сдвиг тени прочь от света, физические пиксели.
    pub сдвиг: f32,
    /// Сила тени, 0…1.
    pub тень: f32,
}

/// Uniform'ы одного элемента. Один список на оба случая (окно и ореол за ним):
/// в шейдере это одна программа, и разойтись значениям негде.
fn набор(
    rect: [f32; 4],
    radius: f32,
    hard_clip: bool,
    ореол: Option<Ореол>,
    свечение: Свечение,
) -> Vec<Uniform<'static>> {
    let о = ореол.unwrap_or(Ореол { ширина: 0.0, сдвиг: 0.0, тень: 0.0 });
    let mut u = vec![
        Uniform::new("win_rect", rect),
        Uniform::new("win_radius", radius),
        Uniform::new("hard_clip", if hard_clip { 1.0f32 } else { 0.0f32 }),
        Uniform::new("halo", if ореол.is_some() { 1.0f32 } else { 0.0f32 }),
        Uniform::new("halo_spread", о.ширина.max(1.0)),
        Uniform::new("halo_drop", о.сдвиг),
        Uniform::new("halo_dark", о.тень.clamp(0.0, 1.0)),
    ];
    // Те же значения, что и при компиляции: в сборке без свечения их в
    // программе нет, и передавать их некуда.
    if cfg!(feature = "shaders") {
        u.push(Uniform::new("glow_color", свечение.цвет));
        u.push(Uniform::new("glow_width", свечение.ширина));
        u.push(Uniform::new("glow_strength", свечение.сила));
        u.push(Uniform::new("light_dir", свечение.направление));
        u.push(Uniform::new("light_amount", свечение.свет));
    }
    u
}

/// Обёртка над элементом окна: та же картинка, но нарисованная шейдером
/// скругления.
#[derive(Debug)]
pub struct Rounded<E> {
    inner: E,
    program: GlesTexProgram,
    uniforms: Vec<Uniform<'static>>,
}

impl<E> Rounded<E> {
    /// `rect` — прямоугольник окна на экране в физических пикселях,
    /// `radius` — радиус там же.
    ///
    /// Рамка приходит ДРОБНОЙ, и это не придирка. Округлив её до целого, мы
    /// получаем маску, которая на дробной камере (а камера почти всегда
    /// дробная — пружина, инерция, зум) прыгает то на пиксель влево, то
    /// вправо — на каждый кадр. Снаружи ровно это и читается как «маска
    /// скругления мигает»: дуга дрожит по краю, пока холст едет.
    /// `hard_clip` — резать ли ещё и снаружи `rect` целиком, не только дугу
    /// по углам (см. uniform `hard_clip` в шейдере выше). Нужно true только
    /// для основного дерева поверхностей окна, которое рисует БОЛЬШЕ, чем у
    /// него запросили (см. udev.rs, "нужен_кроп"); во всех остальных случаях
    /// — false, ровно старое поведение (дуга по углам, снаружи не трогаем).
    pub fn new(
        inner: E,
        шейдер: &Шейдер,
        rect: [f32; 4],
        radius: f32,
        hard_clip: bool,
        свечение: Свечение,
    ) -> Self {
        Self {
            inner,
            program: шейдер.0.clone(),
            uniforms: набор(rect, radius, hard_clip, None, свечение),
        }
    }

    /// Ореол ПОЗАДИ окна: тень плюс свечение наружу, всё одним элементом.
    ///
    /// `rect` — прямоугольник САМОГО ОКНА (тот же, что уходит в его собственный
    /// [`Rounded::new`]), а не плитки: плитка крупнее на ширину тени, но форму
    /// шейдер считает по окну. Одна рамка на обе стороны границы — именно
    /// поэтому обводка и кайма не могут разъехаться.
    ///
    /// `ширина` — насколько тень уходит наружу, `сдвиг` — на сколько она
    /// смещена от света, `тень` — её сила (0…1). Всё в ФИЗИЧЕСКИХ пикселях:
    /// вызывающий уже умножил логические на зум.
    pub fn ореол(
        inner: E,
        шейдер: &Шейдер,
        rect: [f32; 4],
        radius: f32,
        форма: Ореол,
        свечение: Свечение,
    ) -> Self {
        Self {
            inner,
            program: шейдер.0.clone(),
            uniforms: набор(rect, radius, false, Some(форма), свечение),
        }
    }

    /// То же от целочисленного прямоугольника — для плашек интерфейса, которые
    /// и так стоят на целых пикселях экрана и никуда не едут. `hard_clip`
    /// всегда false — плашки не имеют дела с чужим неподатливым содержимым.
    pub fn from_rect(
        inner: E,
        шейдер: &Шейдер,
        rect: Rectangle<i32, Physical>,
        radius: f32,
    ) -> Self {
        Self::new(
            inner,
            шейдер,
            [
                rect.loc.x as f32,
                rect.loc.y as f32,
                rect.size.w as f32,
                rect.size.h as f32,
            ],
            radius,
            false,
            // Плашки интерфейса не светятся: свечение — признак ОКНА, и на
            // панели или меню оно бы только сбивало с толку.
            Свечение::нет(),
        )
    }
}

/// Свет на окне: и ровная кайма по краю, и направленный свет от источника на
/// холсте. Считается по палитре обоев и настройкам — см.
/// [`Свечение::для_окна`] и [`Свечение::со_светом`].
#[derive(Clone, Copy, Debug)]
pub struct Свечение {
    pub цвет: [f32; 3],
    /// Ширина полосы в ФИЗИЧЕСКИХ пикселях: её задают в логических и умножают
    /// на зум — иначе на отдалённой камере кайма расплывалась бы во всё окно.
    pub ширина: f32,
    /// 0 — выключено. Отдельным полем, а не `Option`: в шейдер уходит число,
    /// и лишняя ветка по дороге ничего не даёт.
    pub сила: f32,
    /// Единичное направление НА источник света в экранных координатах (см.
    /// свет.rs). При нулевом `свет` не значит ничего.
    pub направление: [f32; 2],
    /// Сколько света от источника доходит до этого окна, 0…1. 0 — свет
    /// выключен, не настроен или окно за его охватом.
    pub свет: f32,
}

impl Свечение {
    pub fn нет() -> Self {
        Self {
            цвет: [0.0, 0.0, 0.0],
            ширина: 0.0,
            сила: 0.0,
            направление: [0.0, -1.0],
            свет: 0.0,
        }
    }

    /// Свечение окна по палитре обоев.
    ///
    /// Три множителя, и каждый со своей причиной:
    ///
    /// * `сила` из настроек — общий предел, чтобы эффект можно было приглушить
    ///   или выключить, не пересобирая;
    /// * светлота обоев — на светлой картинке цветная кайма читается грязью,
    ///   поэтому к белым обоям свечение сходит на нет само;
    /// * фокус — окно, в котором работают, светится вдвое ярче остальных. Это
    ///   не украшение: на холсте с десятком окон именно так видно, где ввод.
    pub fn для_окна(
        палитра: Option<crate::обои::Палитра>,
        сила: f32,
        ширина_лог: f32,
        зум: f64,
        в_фокусе: bool,
    ) -> Self {
        let Some(п) = палитра else { return Self::нет() };
        if сила <= 0.0 {
            return Self::нет();
        }
        let по_обоям = (1.0 - п.светлота()).clamp(0.0, 1.0);
        let по_фокусу = if в_фокусе { 1.0 } else { 0.45 };
        Self {
            цвет: п.акцент,
            ширина: (ширина_лог as f64 * зум).max(0.5) as f32,
            сила: сила * по_обоям * по_фокусу,
            ..Self::нет()
        }
    }

    /// Добавить свет от источника на холсте.
    ///
    /// Цвет берётся из палитры даже тогда, когда кайма выключена: свет и кайма
    /// — разные ручки (`sun` и `glow`), и светить окнами при `glow = 0` мы
    /// обязаны уметь. Гасится светлотой обоев по тому же правилу, что и сама
    /// заливка сцены (`свет::гашение`), иначе окна на светлых обоях светились
    /// бы ярче холста под ними.
    ///
    /// `окно` — центр окна на экране в физических пикселях.
    pub fn со_светом(
        mut self,
        палитра: Option<crate::обои::Палитра>,
        сила: f32,
        источник: Option<crate::свет::Источник>,
        окно: (f64, f64),
    ) -> Self {
        let (Some(п), Some(и)) = (палитра, источник) else { return self };
        if сила <= 0.0 {
            return self;
        }
        let Some((напр, доля)) = crate::свет::на_прямоугольник(окно, и) else { return self };
        self.цвет = п.акцент;
        self.направление = напр;
        self.свет = (сила * доля * crate::свет::гашение(&п)).clamp(0.0, 1.0);
        self
    }
}

impl<E: Element> Element for Rounded<E> {
    /// Id берём У ВЛОЖЕННОГО элемента, а не свежий на каждый кадр: damage
    /// tracker ведёт историю повреждений по Id, и новый Id каждый кадр означал
    /// бы полную перерисовку экрана всегда (ровно эта грабля уже стоила parallax
    /// производительности на плитках декораций, см. decor.rs).
    fn id(&self) -> &Id {
        self.inner.id()
    }

    fn current_commit(&self) -> CommitCounter {
        self.inner.current_commit()
    }

    fn geometry(&self, scale: Scale<f64>) -> Rectangle<i32, Physical> {
        self.inner.geometry(scale)
    }

    fn location(&self, scale: Scale<f64>) -> Point<i32, Physical> {
        self.inner.location(scale)
    }

    fn transform(&self) -> Transform {
        self.inner.transform()
    }

    fn src(&self) -> Rectangle<f64, BufferCoords> {
        self.inner.src()
    }

    fn damage_since(&self, scale: Scale<f64>, commit: Option<CommitCounter>) -> DamageSet<i32, Physical> {
        self.inner.damage_since(scale, commit)
    }

    /// Пусто — см. шапку модуля: под вырезанным углом рисовать ЕСТЬ что.
    fn opaque_regions(&self, _scale: Scale<f64>) -> OpaqueRegions<i32, Physical> {
        OpaqueRegions::default()
    }

    fn alpha(&self) -> f32 {
        self.inner.alpha()
    }

    fn kind(&self) -> Kind {
        self.inner.kind()
    }
}

impl<E: RenderElement<GlesRenderer>> RenderElement<GlesRenderer> for Rounded<E> {
    fn draw(
        &self,
        frame: &mut GlesFrame<'_, '_>,
        src: Rectangle<f64, BufferCoords>,
        dst: Rectangle<i32, Physical>,
        damage: &[Rectangle<i32, Physical>],
        opaque_regions: &[Rectangle<i32, Physical>],
        cache: Option<&UserDataMap>,
    ) -> Result<(), GlesError> {
        frame.override_default_tex_program(self.program.clone(), self.uniforms.clone());
        // Снять override обязаны в ЛЮБОМ случае, включая ошибку отрисовки:
        // он живёт до конца кадра, и забытый здесь скруглил бы всё, что
        // рисуется после этого окна.
        let итог = self.inner.draw(frame, src, dst, damage, opaque_regions, cache);
        frame.clear_tex_program_override();
        итог
    }

    /// `None` — окну запрещено уезжать на плоскость DRM мимо шейдера
    /// (см. шапку модуля).
    fn underlying_storage(&self, _renderer: &mut GlesRenderer) -> Option<UnderlyingStorage<'_>> {
        None
    }
}

/// Проверки арифметики свечения. Сам шейдер тестом не поймать (нужен GL), но
/// решение «светить или нет и насколько» живёт здесь, в обычном коде, — и
/// ошибка в нём стоит либо грязной каймы на светлых обоях, либо одинаково
/// светящихся окон, по которым не видно, где ввод.
#[cfg(test)]
mod тесты {
    use super::*;
    use crate::обои::Палитра;

    fn палитра(фон: [f32; 3]) -> Палитра {
        Палитра { акцент: [0.6, 0.8, 0.4], фон }
    }

    #[test]
    fn без_палитры_не_светимся() {
        let с = Свечение::для_окна(None, 1.0, 12.0, 1.0, true);
        assert_eq!(с.сила, 0.0, "без палитры светить нечем");
    }

    #[test]
    fn нулевая_настройка_выключает() {
        let с = Свечение::для_окна(Some(палитра([0.0, 0.0, 0.0])), 0.0, 12.0, 1.0, true);
        assert_eq!(с.сила, 0.0);
    }

    #[test]
    fn на_светлых_обоях_гаснет_само() {
        let тёмные = Свечение::для_окна(Some(палитра([0.05, 0.06, 0.05])), 1.0, 12.0, 1.0, true);
        let светлые = Свечение::для_окна(Some(палитра([0.95, 0.96, 0.95])), 1.0, 12.0, 1.0, true);
        assert!(тёмные.сила > 0.9, "на тёмных обоях светим в полную силу: {}", тёмные.сила);
        assert!(светлые.сила < 0.1, "на светлых почти гаснем: {}", светлые.сила);
    }

    #[test]
    fn окно_в_фокусе_ярче_соседа() {
        let п = Some(палитра([0.0, 0.0, 0.0]));
        let в_фокусе = Свечение::для_окна(п, 1.0, 12.0, 1.0, true);
        let мимо = Свечение::для_окна(п, 1.0, 12.0, 1.0, false);
        assert!(в_фокусе.сила > мимо.сила * 1.5, "{} против {}", в_фокусе.сила, мимо.сила);
        assert!(мимо.сила > 0.0, "окно не в фокусе всё же светится, только тише");
    }

    /// Ширина задаётся в ЛОГИЧЕСКИХ пикселях и обязана ехать за зумом: иначе
    /// на отдалённой камере кайма расплылась бы во всё окно, а на приближённой
    /// стала бы ниткой.
    #[test]
    fn ширина_едет_за_зумом() {
        let п = Some(палитра([0.0, 0.0, 0.0]));
        assert!((Свечение::для_окна(п, 1.0, 10.0, 2.0, true).ширина - 20.0).abs() < 0.01);
        assert!((Свечение::для_окна(п, 1.0, 10.0, 0.5, true).ширина - 5.0).abs() < 0.01);
        // Ниже половины пикселя не опускаемся: шейдер делит на ширину.
        assert!(Свечение::для_окна(п, 1.0, 0.0, 0.01, true).ширина >= 0.5);
    }
}
