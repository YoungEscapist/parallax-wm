/// Объявления uniform'ов свечения и сам его расчёт — отдельными кусками,
/// потому что в сборке без фичи `shaders` их в шейдере нет ВООБЩЕ.
///
/// Это не экономия на строчках: шейдер скругления считается для каждого
/// фрагмента каждого окна каждый кадр, и «выключенное» свечение всё равно
/// стоило бы видеокарте ветки и двух `smoothstep` на пиксель. В plx-standard
/// пиксель обязан идти самым коротким путём — там этого кода просто нет.
#[cfg(feature = "shaders")]
const ГЛОУ_UNIFORMS: &str = r#"
// Свечение по краю окна ИЗНУТРИ: цвет, ширина полосы в физических пикселях
// и сила (0 — выключено). Цвет приходит из палитры ОБОЕВ (см. src/обои.rs),
// поэтому кайма всегда одного тона с картинкой на экране.
//
// Почему изнутри, а не ореолом наружу: снаружи окна фрагментов попросту нет —
// шейдер работает по его прямоугольнику, и рисовать за ним нечем. Ореол
// потребовал бы отдельного элемента под окном; кайма даёт то же ощущение
// подсвеченного стекла и не стоит ни одного лишнего пикселя.
uniform vec3 glow_color;
uniform float glow_width;
uniform float glow_strength;

// Свет от источника на холсте (см. свет.rs): единичное направление НА него в
// экранных координатах и сила, уже посчитанная по расстоянию. 0 — света нет.
// Цвет берётся тот же, что у каймы (акцент обоев): источник и кайма — один и
// тот же свет, и разные их тона читались бы как два источника.
uniform vec2 light_dir;
uniform float light_amount;
"#;
#[cfg(not(feature = "shaders"))]
const ГЛОУ_UNIFORMS: &str = "";

#[cfg(feature = "shaders")]
const ГЛОУ_ТЕЛО: &str = r#"
    // ── Свечение краёв ──────────────────────────────────────────────────────
    // Считается ПОСЛЕ вырезания угла и множится на альфу: там, где окна нет
    // (вырезанный угол, прозрачная часть буфера), прибавлять свет не к чему —
    // иначе по дуге пошла бы яркая скобка в пустоте.
    //
    // Кадр смешивается с ПРЕДумноженной альфой, поэтому свет именно
    // ПРИБАВЛЯЕТСЯ к цвету, а не подмешивается: полоса выглядит светящейся, а
    // не покрашенной.
    if ((glow_strength > 0.0 || light_amount > 0.0) && win_rect.z > 0.0 && win_rect.w > 0.0) {
        vec2 gp = gl_FragCoord.xy;
        vec2 ghalf = win_rect.zw * 0.5;
        vec2 gcenter = win_rect.xy + ghalf;
        float gd = rounded_box(gp - gcenter, ghalf, win_radius);
        // Наружу (gd > 0) не светим вовсе: там уже не окно.
        float inside = step(gd, 0.0);

        // ── Сторона, обращённая к свету ─────────────────────────────────────
        // Доля вдоль направления на источник: −1 у дальнего края окна, +1 у
        // ближнего к свету. Нормируем на половину размера окна, иначе широкое
        // окно освещалось бы иначе, чем узкое, при том же положении источника.
        //
        // Именно это и делает свет светом: у окна появляется освещённая
        // сторона и затенённая, и по ним видно, откуда светит. Ровная кайма
        // такого не давала — она горела одинаково со всех четырёх сторон.
        float side = 0.5;
        if (light_amount > 0.0) {
            vec2 lp = (gp - gcenter) / max(ghalf, vec2(1.0));
            side = clamp(dot(lp, light_dir) * 0.5 + 0.5, 0.0, 1.0);
            // Освещённая сторона прибавляет света, затенённая — приглушается.
            // Оба множителя мягкие (квадрат и половина силы): окно обязано
            // остаться читаемым, это подсветка, а не студийный свет.
            color.rgb += glow_color * (light_amount * side * side * 0.55) * color.a * inside;
            color.rgb *= 1.0 - light_amount * 0.35 * (1.0 - side) * inside;
        }

        if (glow_strength > 0.0) {
            // gd < 0 внутри. Полоса шириной glow_width вдоль края: у самого
            // края единица, глубже внутрь плавно в ноль.
            float rim = (1.0 - smoothstep(0.0, max(glow_width, 0.5), -gd)) * inside;
            // Кайма тоже слушается света: край, на который он падает, горит
            // ярче противоположного. Без света (light_amount = 0) side = 0.5 и
            // множитель ровно единица — старое поведение до пикселя.
            float rim_side = 0.5 + side;
            color.rgb += glow_color * (rim * glow_strength * rim_side) * color.a;
        }
    }

"#;
#[cfg(not(feature = "shaders"))]
const ГЛОУ_ТЕЛО: &str = "";

