// ── Что за окошко ────────────────────────────────────────────────────────────

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Окошко {
    Календарь,
    Звук,
    Питание,
    Раскладка,
    /// Подпись значка трея (номер в списке `sni::Item`).
    Трей(usize),
}

impl Окошко {
    /// Окошко ячейки панели. Столы и окна — не сюда: у них своя карточка
    /// предпросмотра (`anim::предпросмотр_возможен`).
    pub fn для(cell: Cell) -> Option<Self> {
        match cell {
            Cell::Clock | Cell::Date => Some(Self::Календарь),
            Cell::Volume => Some(Self::Звук),
            Cell::Battery => Some(Self::Питание),
            Cell::Kb => Some(Self::Раскладка),
            Cell::Tray(i) => Some(Self::Трей(i)),
            _ => None,
        }
    }

    /// Закрепляется ли щелчком по ячейке. Раскладка и трей щелчком делают
    /// своё (следующая раскладка, Activate) — у них окошко только по наведению.
    fn закрепляется(self) -> bool {
        matches!(self, Self::Календарь | Self::Звук | Self::Питание)
    }
}

