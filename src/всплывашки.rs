//! Всплывающие окошки панели — как popout'ы у Caelestia и прочих шеллов на
//! Quickshell. Навёл на часы — под островом выезжает календарь, на звук —
//! громкость и выходы, на заряд — питание и подсветка, на раскладку — список
//! раскладок, на значок трея — его подпись. Ведёшь мышь вдоль панели — окошко
//! не гаснет и не рождается заново, а ПЕРЕТЕКАЕТ: карточка едет к следующей
//! ячейке и меняет размер, а содержимое проявляется уже на новом месте.
//!
//! Щелчок по часам, звуку или заряду ЗАКРЕПЛЯЕТ окошко: оно остаётся, когда
//! мышь ушла (и на сенсорном экране, где наведения нет вовсе). Закреплённое
//! закрывают Esc, щелчок мимо и повторный щелчок по той же ячейке.
//!
//! Устроено как карточка предпросмотра (`canvas::preview_geom`): ОДНА раскладка
//! на отрисовку и на ввод. [`собрать`] выдаёт штрихи (что рисовать) и цели (что
//! нажимается) в координатах карточки, `udev::build_bar_popout` рисует первые,
//! разбор щелчков здесь же ищет по вторым. Разъехаться им негде — а на
//! разъехавшихся копиях геометрии parallax уже однажды промахивался кликами.
//!
//! 24.10.2026, вторая волна: окошки и у вайфая, блютуза и питания — по
//! значку-квадратику в том же правом острове (тумблер, список сетей или
//! устройств, поиск), а сон, перезагрузка и выключение делаются ЗАЖАТИЕМ
//! кнопки со звуком (зажим.rs). Окошко открывается не сразу, а когда мышь
//! задержалась на значке хоть на `ВЗГЛЯД`: значков в острове стало много, и
//! мышь, едущая к краю экрана, иначе будила бы их по очереди.
//!
//! Чем это отличается от меню (wifi.rs, audio.rs, питание.rs): меню — это
//! клавиатура и список посреди экрана, оно остаётся для биндов (`audio_menu`,
//! `power_menu`). Окошко — мышь и место прямо под тем, на что навели.
//! Выключается `bar{ popups = false }`: тогда щелчки по панели ведут себя
//! по-старому (звук и заряд открывают меню).

