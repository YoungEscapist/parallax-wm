/// Что нарисовать. Координаты — от левого верхнего угла карточки, пока
/// окошко собирается, и экранные, когда оно поставлено на место.
#[derive(Clone, Debug, PartialEq)]
pub enum Штрих {
    Плашка { r: Rect, радиус: i32, цвет: [f32; 4] },
    Текст { x: i32, y: i32, w: i32, текст: String, масштаб: i32, вес: Weight, цвет: [f32; 4] },
    /// Маска значка высотой `h`, по центру ячейки `r`.
    Значок { r: Rect, h: i32, какой: Значок, цвет: [f32; 4] },
}

impl Штрих {
    pub fn рамка(&self) -> Rect {
        match self {
            Штрих::Плашка { r, .. } | Штрих::Значок { r, .. } => *r,
            Штрих::Текст { x, y, w, масштаб, .. } => Rect { x: *x, y: *y, w: *w, h: text::height(*масштаб) },
        }
    }

    fn сдвинуть(&mut self, dx: i32, dy: i32) {
        match self {
            Штрих::Плашка { r, .. } | Штрих::Значок { r, .. } => {
                r.x += dx;
                r.y += dy;
            }
            Штрих::Текст { x, y, .. } => {
                *x += dx;
                *y += dy;
            }
        }
    }
}

/// Что нажимается.
#[derive(Clone, Debug, PartialEq)]
pub enum Цель {
    МесяцНазад,
    МесяцВперёд,
    МесяцСейчас,
    /// Ползунок: где начинается дорожка и какой она ширины (экранные пиксели).
    Громкость { x0: i32, w: i32 },
    Немота,
    Выход(String),
    Вход(String),
    Профиль(String),
    Яркость { x0: i32, w: i32 },
    /// Подсветка клавиатуры: следующий уровень по кругу.
    Подсветка,
    Раскладка(usize),
    ВайфайРадио,
    /// Строка сети (по SSID: путь точки берётся из снимка в момент щелчка —
    /// список пересортировывается на каждом опросе).
    Сеть(String),
    ВайфайПоиск,
    /// «Все сети»: полное меню посреди экрана.
    ВайфайВсе,
    БлютузАдаптер,
    /// Строка устройства (путь BlueZ).
    Bt(String),
    БлютузПоиск,
    БлютузВсе,
    /// Сон, перезагрузка или выключение — нажатие начинает зажатие.
    Сеанс(crate::tray::PowerAction),
}

impl Цель {
    /// Та же цель, без оглядки на геометрию: дорожка ползунка едет вместе с
    /// карточкой, а «под курсором ползунок громкости» от этого не меняется.
    pub fn тот_же(&self, о: &Цель) -> bool {
        match (self, о) {
            (Цель::Громкость { .. }, Цель::Громкость { .. }) | (Цель::Яркость { .. }, Цель::Яркость { .. }) => true,
            (a, b) => a == b,
        }
    }

    fn сдвинуть(&mut self, dx: i32) {
        if let Цель::Громкость { x0, .. } | Цель::Яркость { x0, .. } = self {
            *x0 += dx;
        }
    }
}

/// Собранное окошко в координатах карточки: её естественный размер, штрихи
/// от заднего плана к переднему и цели.
#[derive(Clone, Debug, Default)]
pub struct Содержимое {
    pub w: i32,
    pub h: i32,
    pub штрихи: Vec<Штрих>,
    pub цели: Vec<(Rect, Цель)>,
}

fn ширина(s: &str, масштаб: i32, вес: Weight) -> i32 {
    text::width_of(s, вес, масштаб)
}

fn с_альфой(c: [f32; 4], a: f32) -> [f32; 4] {
    [c[0], c[1], c[2], c[3] * a]
}

fn смесь(a: [f32; 4], b: [f32; 4], t: f32) -> [f32; 4] {
    let м = |x: f32, y: f32| x + (y - x) * t;
    [м(a[0], b[0]), м(a[1], b[1]), м(a[2], b[2]), м(a[3], b[3])]
}

fn наведено(д: &Данные, ц: &Цель) -> bool {
    д.наведено.as_ref().is_some_and(|н| н.тот_же(ц))
}

/// Альфа ступеньками: каждая новая альфа — новый растр углов в кэше (цвет
/// входит в ключ), и плавное проявление без ступенек растрировало бы их на
/// каждом кадре.
fn ступень(t: f32, ступеней: f32) -> f32 {
    (t.clamp(0.0, 1.0) * ступеней).round() / ступеней
}

/// Подложка под курсором: не вспыхивает, а проявляется за `ПОДСВЕТКА_DUR`.
fn под_курсором(д: &Данные, c: [f32; 4]) -> [f32; 4] {
    с_альфой(c, ступень(д.подсветка, 6.0))
}

#[derive(Default)]
struct Холст {
    шт: Vec<Штрих>,
    цели: Vec<(Rect, Цель)>,
}

impl Холст {
    fn плашка(&mut self, x: i32, y: i32, w: i32, h: i32, радиус: i32, цвет: [f32; 4]) {
        if w > 0 && h > 0 {
            self.шт.push(Штрих::Плашка { r: Rect { x, y, w, h }, радиус, цвет });
        }
    }

    fn текст(&mut self, x: i32, y: i32, s: &str, масштаб: i32, вес: Weight, цвет: [f32; 4]) -> i32 {
        if s.is_empty() {
            return 0;
        }
        let w = ширина(s, масштаб, вес);
        self.шт.push(Штрих::Текст { x, y, w, текст: s.to_string(), масштаб, вес, цвет });
        w
    }

    /// Текст, прижатый правым краем к `правый_x`.
    fn текст_справа(&mut self, правый_x: i32, y: i32, s: &str, масштаб: i32, вес: Weight, цвет: [f32; 4]) {
        let w = ширина(s, масштаб, вес);
        self.текст(правый_x - w, y, s, масштаб, вес, цвет);
    }

    /// Текст по центру прямоугольника.
    fn текст_в(&mut self, r: Rect, s: &str, масштаб: i32, вес: Weight, цвет: [f32; 4]) {
        let w = ширина(s, масштаб, вес);
        self.текст(r.x + (r.w - w) / 2, r.y + (r.h - text::height(масштаб)) / 2, s, масштаб, вес, цвет);
    }

    fn значок(&mut self, r: Rect, h: i32, какой: Значок, цвет: [f32; 4]) {
        self.шт.push(Штрих::Значок { r, h, какой, цвет });
    }

    fn цель(&mut self, r: Rect, ц: Цель) {
        self.цели.push((r, ц));
    }

    /// Ползунок: дорожка, заполнение акцентом и ручка. Ручка под курсором
    /// (или пока её тянут) крупнее — так видно, что за неё можно взяться.
    fn ползунок(&mut self, x0: i32, cy: i32, w: i32, доля: f32, горит: bool, ц: &Цвета) {
        let доля = доля.clamp(0.0, 1.0);
        self.плашка(x0, cy - 3, w, 6, 3, ц.дорожка);
        let з = (w as f32 * доля).round() as i32;
        if з > 0 {
            self.плашка(x0, cy - 3, з.max(6), 6, 3, ц.акцент);
        }
        let d = if горит { 20 } else { 16 };
        self.плашка(x0 + з - d / 2, cy - d / 2, d, d, d / 2, ц.ручка);
    }

    /// Строка списка: точка (акцент — выбранное), подпись, справа — пояснение.
    #[allow(clippy::too_many_arguments)]
    fn строка(
        &mut self,
        д: &Данные,
        y: i32,
        w: i32,
        подпись: &str,
        справа: Option<&str>,
        активна: bool,
        цель: Цель,
    ) {
        let ц = &д.цвета;
        let r = Rect { x: ПОЛЕ - 6, y, w: w - ПОЛЕ * 2 + 12, h: СТРОКА - 2 };
        if наведено(д, &цель) {
            self.плашка(r.x, r.y, r.w, r.h, 9, под_курсором(д, ц.наведение));
        }
        let d = 8;
        self.плашка(ПОЛЕ + 2, y + (r.h - d) / 2, d, d, d / 2, if активна { ц.акцент } else { ц.точка });
        let под_справа = справа.map(|s| ширина(s, 2, Weight::Regular) + 10).unwrap_or(0);
        let текст = bar::fit_text(подпись, 2, w - ПОЛЕ * 2 - 20 - под_справа);
        let ty = y + (r.h - text::height(2)) / 2;
        self.текст(ПОЛЕ + 20, ty, &текст, 2, Weight::Regular, if активна { ц.текст } else { ц.тусклый });
        if let Some(s) = справа {
            self.текст_справа(w - ПОЛЕ, ty, s, 2, Weight::Regular, ц.тусклый);
        }
        self.цель(r, цель);
    }

    /// Подпись раздела («ВЫВОД», «РЕЖИМ») — мелко и тускло, как в Caelestia.
    fn раздел(&mut self, y: i32, s: &str, ц: &Цвета) -> i32 {
        self.текст(ПОЛЕ, y, s, 1, Weight::Semi, ц.тусклый);
        y + text::height(1) + 6
    }

    fn в(self, w: i32, h: i32) -> Содержимое {
        Содержимое { w, h, штрихи: self.шт, цели: self.цели }
    }

    /// Тумблер: дорожка заливается акцентом, ручка едет. `t` — положение
    /// ручки 0…1 (его ведёт тик, см. `Состояние::тумблеры`); цвет дорожки —
    /// ступеньками, как всякая плавная альфа здесь.
    fn тумблер(&mut self, д: &Данные, x: i32, y: i32, t: f32, цель: Цель) {
        let ц = &д.цвета;
        let t = t.clamp(0.0, 1.0);
        self.плашка(x, y, ТУМБЛЕР_W, ТУМБЛЕР_H, ТУМБЛЕР_H / 2, смесь(ц.дорожка, ц.акцент, ступень(t, 8.0)));
        let d = if наведено(д, &цель) { 18 } else { 16 };
        let ход = (ТУМБЛЕР_W - ТУМБЛЕР_H) as f32;
        let cx = x + ТУМБЛЕР_H / 2 + (ход * t).round() as i32;
        self.плашка(cx - d / 2, y + (ТУМБЛЕР_H - d) / 2, d, d, d / 2, ц.ручка);
        self.цель(Rect { x: x - 6, y: y - 6, w: ТУМБЛЕР_W + 12, h: ТУМБЛЕР_H + 12 }, цель);
    }

    /// Три точки «ищу…»: вспыхивают по очереди. Возвращает занятую ширину.
    fn точки(&mut self, x: i32, cy: i32, фаза: f32, цвет: [f32; 4]) -> i32 {
        let (d, шаг) = (5, 9);
        for i in 0..3 {
            let t = (фаза * 1.6 - i as f32 * 0.2).rem_euclid(1.0);
            let пульс = 1.0 - (t * 2.0 - 1.0).abs();
            self.плашка(x + i * шаг, cy - d / 2, d, d, d / 2, с_альфой(цвет, 0.25 + 0.75 * ступень(пульс, 4.0)));
        }
        шаг * 2 + d
    }

    /// Уровень сигнала сети: четыре столбика, горят по силе.
    fn сигнал(&mut self, x: i32, низ: i32, сила: u8, вкл: [f32; 4], выкл: [f32; 4]) {
        let горит = match сила {
            0 => 0,
            1..=24 => 1,
            25..=49 => 2,
            50..=74 => 3,
            _ => 4,
        };
        for i in 0..4 {
            let h = 5 + i * 3;
            self.плашка(x + i * 5, низ - h, 3, h, 1, if i < горит { вкл } else { выкл });
        }
    }

    /// Значок вайфая: точка и три дуги, горят первые `дуг`.
    fn вайфай_значок(&mut self, r: Rect, h: i32, дуг: i32, вкл: [f32; 4], выкл: [f32; 4]) {
        self.значок(r, h, Значок::ВайфайТочка, if дуг > 0 { вкл } else { выкл });
        for n in 1..=3u8 {
            self.значок(r, h, Значок::ВайфайДуга(n), if n as i32 <= дуг { вкл } else { выкл });
        }
    }

    /// Шапка окошка вайфая и блютуза: значок в кружке (акцентном, когда
    /// включено), заголовок, под ним состояние, справа тумблер.
    #[allow(clippy::too_many_arguments)]
    fn шапка(
        &mut self,
        д: &Данные,
        w: i32,
        вкл: bool,
        значок: impl FnOnce(&mut Self, Rect, [f32; 4]),
        заголовок: &str,
        состояние: &str,
        тумблер: f32,
        цель: Цель,
    ) -> i32 {
        let ц = &д.цвета;
        const D: i32 = 40;
        self.плашка(ПОЛЕ, ПОЛЕ, D, D, D / 2, if вкл { ц.акцент } else { ц.наведение_сильнее });
        значок(self, Rect { x: ПОЛЕ, y: ПОЛЕ, w: D, h: D }, if вкл { ц.на_акценте } else { ц.тусклый });
        let tx = ПОЛЕ + D + 12;
        let под_тумблер = ТУМБЛЕР_W + 16;
        self.текст(tx, ПОЛЕ - 2, заголовок, 2, Weight::Semi, ц.текст);
        let с = bar::fit_text(состояние, 1, w - tx - ПОЛЕ - под_тумблер);
        self.текст(tx, ПОЛЕ + text::height(2) - 1, &с, 1, Weight::Regular, ц.тусклый);
        self.тумблер(д, w - ПОЛЕ - ТУМБЛЕР_W, ПОЛЕ + (D - ТУМБЛЕР_H) / 2, тумблер, цель);
        let y = ПОЛЕ + D + 14;
        self.плашка(ПОЛЕ, y, w - ПОЛЕ * 2, 1, 0, ц.черта);
        y + 1 + 12
    }

    /// Кнопка-таблетка подвала: подложка, по желанию значок слева, подпись.
    /// `от_правого` — `x` это правый край. Возвращает ширину.
    #[allow(clippy::too_many_arguments)]
    fn кнопка(
        &mut self,
        д: &Данные,
        x: i32,
        y: i32,
        подпись: &str,
        значок: Option<Значок>,
        точки: bool,
        цель: Цель,
        от_правого: bool,
    ) -> i32 {
        let ц = &д.цвета;
        let tw = ширина(подпись, 2, Weight::Regular);
        let слева = if значок.is_some() { 22 } else { 0 };
        let справа = if точки { 30 } else { 0 };
        let w = 14 + слева + tw + справа + 14;
        let x = if от_правого { x - w } else { x };
        let r = Rect { x, y, w, h: КНОПКА };
        self.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, ц.наведение);
        if наведено(д, &цель) {
            self.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, под_курсором(д, ц.наведение));
        }
        if let Some(з) = значок {
            self.значок(Rect { x: x + 12, y, w: 16, h: КНОПКА }, 15, з, ц.текст);
        }
        self.текст(x + 14 + слева, y + (КНОПКА - text::height(2)) / 2, подпись, 2, Weight::Regular, ц.текст);
        if точки {
            self.точки(x + 14 + слева + tw + 8, y + КНОПКА / 2, д.фаза, ц.акцент);
        }
        self.цель(r, цель);
        w
    }
}

/// Собрать окошко. `None` — показывать нечего (одна раскладка, у значка трея
/// нет подписи, у машины нет батареи).
pub fn собрать(что: Окошко, д: &Данные) -> Option<Содержимое> {
    match что {
        Окошко::Календарь => календарь(д),
        Окошко::Звук => Some(звук(д)),
        Окошко::Питание => питание(д),
        Окошко::Раскладка => раскладки(д),
        Окошко::Трей(i) => подпись(д, i),
        Окошко::Вайфай => вайфай(д),
        Окошко::Блютуз => блютуз(д),
        Окошко::Сеанс => Some(сеанс(д)),
    }
}

/// Окошко с одной строкой: «звука нет» и подобное.
fn сообщение(s: &str, ц: &Цвета) -> Содержимое {
    let mut х = Холст::default();
    let w = (ширина(s, 2, Weight::Regular) + ПОЛЕ * 2).max(240);
    х.текст_в(Rect { x: 0, y: ПОЛЕ, w, h: text::height(2) }, s, 2, Weight::Regular, ц.тусклый);
    х.в(w, text::height(2) + ПОЛЕ * 2)
}

// ── Календарь ────────────────────────────────────────────────────────────────

const МЕСЯЦЫ_RU: [&str; 12] = [
    "Январь", "Февраль", "Март", "Апрель", "Май", "Июнь",
    "Июль", "Август", "Сентябрь", "Октябрь", "Ноябрь", "Декабрь",
];
const МЕСЯЦЫ_EN: [&str; 12] = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
];
/// «24 октября» — по-русски число требует родительного падежа.
const МЕСЯЦЫ_РОД_RU: [&str; 12] = [
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
];
/// С понедельника.
const ДНИ_RU: [&str; 7] = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"];
const ДНИ_EN: [&str; 7] = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
const ДНИ_КОРОТКО_RU: [&str; 7] = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"];
const ДНИ_КОРОТКО_EN: [&str; 7] = ["Mo", "Tu", "We", "Th", "Fr", "Sa", "Su"];

/// Дней от 1970-01-01 по григорианскому календарю (days_from_civil Хиннанта).
fn дни_от_эпохи(год: i32, месяц: i32, день: i32) -> i64 {
    let y = (if месяц <= 2 { год - 1 } else { год }) as i64;
    let эра = if y >= 0 { y } else { y - 399 } / 400;
    let гэ = y - эра * 400;
    let м = месяц as i64;
    let дг = (153 * (if м > 2 { м - 3 } else { м + 9 }) + 2) / 5 + день as i64 - 1;
    let дэ = гэ * 365 + гэ / 4 - гэ / 100 + дг;
    эра * 146_097 + дэ - 719_468
}

/// День недели, 0 — понедельник. 1970-01-01 был четвергом.
pub fn день_недели(год: i32, месяц: i32, день: i32) -> i32 {
    (дни_от_эпохи(год, месяц, день) + 3).rem_euclid(7) as i32
}

pub fn дней_в_месяце(год: i32, месяц: i32) -> i32 {
    match месяц {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        _ if (год % 4 == 0 && год % 100 != 0) || год % 400 == 0 => 29,
        _ => 28,
    }
}

/// Месяц на `на` вперёд (или назад) от данного: (год, 1…12).
pub fn сдвинуть_месяц(год: i32, месяц: i32, на: i32) -> (i32, i32) {
    let i = год * 12 + (месяц - 1) + на;
    (i.div_euclid(12), i.rem_euclid(12) + 1)
}

fn календарь(д: &Данные) -> Option<Содержимое> {
    let в = д.время?;
    let ц = &д.цвета;
    const КЛ_W: i32 = 40;
    const КЛ_H: i32 = 34;
    let w = КЛ_W * 7 + ПОЛЕ * 2;
    let mut х = Холст::default();

    // ── Шапка: время крупно, справа день недели и число ──────────────────────
    х.текст(ПОЛЕ, ПОЛЕ, &format!("{:02}:{:02}", в.час, в.мин), 3, Weight::Semi, ц.текст);
    let м = (в.месяц - 1).clamp(0, 11) as usize;
    let день = т!(ДНИ_RU, ДНИ_EN)[в.день_недели.clamp(0, 6) as usize];
    let число = if crate::lang::русский() {
        format!("{} {}", в.день, МЕСЯЦЫ_РОД_RU[м])
    } else {
        format!("{} {}", МЕСЯЦЫ_EN[м], в.день)
    };
    х.текст_справа(w - ПОЛЕ, ПОЛЕ + 1, день, 1, Weight::Regular, ц.тусклый);
    х.текст_справа(w - ПОЛЕ, ПОЛЕ + text::height(1) + 2, &число, 2, Weight::Semi, ц.текст);
    let mut y = ПОЛЕ + text::height(3) + 12;
    х.плашка(ПОЛЕ, y, w - ПОЛЕ * 2, 1, 0, ц.черта);
    y += 1 + 10;

    // ── Месяц: ‹ Октябрь 2026 › ───────────────────────────────────────────────
    let (год, месяц) = сдвинуть_месяц(в.год, в.месяц, д.месяц);
    let сейчас = д.месяц == 0;
    let заголовок = format!("{} {}", т!(МЕСЯЦЫ_RU, МЕСЯЦЫ_EN)[(месяц - 1) as usize], год);
    for (x, цель, знак) in [
        (ПОЛЕ, Цель::МесяцНазад, "‹"),
        (w - ПОЛЕ - КНОПКА, Цель::МесяцВперёд, "›"),
    ] {
        let r = Rect { x, y, w: КНОПКА, h: КНОПКА };
        if наведено(д, &цель) {
            х.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, под_курсором(д, ц.наведение_сильнее));
        }
        х.текст_в(r, знак, 2, Weight::Semi, ц.текст);
        х.цель(r, цель);
    }
    let tw = ширина(&заголовок, 2, Weight::Semi);
    let tx = (w - tw) / 2;
    // Листнули — название месяца становится кнопкой «вернуться к сегодня».
    if !сейчас {
        let r = Rect { x: tx - 10, y, w: tw + 20, h: КНОПКА };
        if наведено(д, &Цель::МесяцСейчас) {
            х.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, под_курсором(д, ц.наведение));
        }
        х.цель(r, Цель::МесяцСейчас);
    }
    х.текст(
        tx, y + (КНОПКА - text::height(2)) / 2, &заголовок, 2, Weight::Semi,
        if сейчас { ц.текст } else { ц.акцент },
    );
    y += КНОПКА + 8;

    // ── Дни недели ───────────────────────────────────────────────────────────
    let выходной = смесь(ц.текст, ц.акцент, 0.55);
    for (i, имя) in т!(ДНИ_КОРОТКО_RU, ДНИ_КОРОТКО_EN).iter().enumerate() {
        let r = Rect { x: ПОЛЕ + i as i32 * КЛ_W, y, w: КЛ_W, h: text::height(1) };
        let цвет = if i >= 5 { с_альфой(выходной, 0.85) } else { ц.тусклый };
        х.текст_в(r, имя, 1, Weight::Semi, цвет);
    }
    y += text::height(1) + 8;

    // ── Сетка: всегда шесть недель, чтобы окошко не прыгало от месяца к месяцу ─
    let первый = день_недели(год, месяц, 1);
    let дней = дней_в_месяце(год, месяц);
    let (пг, пм) = сдвинуть_месяц(год, месяц, -1);
    let дней_раньше = дней_в_месяце(пг, пм);
    for клетка in 0..42i32 {
        let (столбец, ряд) = (клетка % 7, клетка / 7);
        let n = клетка - первый + 1;
        let (число, свой) = if n < 1 {
            (дней_раньше + n, false)
        } else if n > дней {
            (n - дней, false)
        } else {
            (n, true)
        };
        let r = Rect { x: ПОЛЕ + столбец * КЛ_W, y: y + ряд * КЛ_H, w: КЛ_W, h: КЛ_H };
        let сегодня = свой && сейчас && n == в.день;
        let (цвет, вес) = if сегодня {
            let d = 30;
            х.плашка(r.x + (r.w - d) / 2, r.y + (r.h - d) / 2, d, d, d / 2, ц.акцент);
            (ц.на_акценте, Weight::Semi)
        } else if !свой {
            (с_альфой(ц.текст, 0.26), Weight::Regular)
        } else if столбец >= 5 {
            (выходной, Weight::Regular)
        } else {
            (ц.текст, Weight::Regular)
        };
        х.текст_в(r, &число.to_string(), 2, вес, цвет);
    }
    Some(х.в(w, y + 6 * КЛ_H + ПОЛЕ - 6))
}

// ── Звук ─────────────────────────────────────────────────────────────────────

fn звук(д: &Данные) -> Содержимое {
    let ц = &д.цвета;
    let w = 344;
    let Some(з) = д.звук.as_ref().filter(|з| !з.выходы.is_empty()) else {
        return сообщение(т!("Звука нет: pactl молчит", "No audio: pactl is silent"), ц);
    };
    let mut х = Холст::default();
    let какой = if з.немо { Значок::ЗвукВыкл } else { Значок::Звук };

    // ── Шапка: значок, «Звук», проценты ──────────────────────────────────────
    х.значок(Rect { x: ПОЛЕ, y: ПОЛЕ, w: 24, h: text::height(2) }, 18, какой, if з.немо { ц.тревога } else { ц.текст });
    х.текст(ПОЛЕ + 34, ПОЛЕ, т!("Звук", "Sound"), 2, Weight::Semi, ц.текст);
    let проценты = format!("{}%", (з.громкость.max(0.0) * 100.0).round() as i32);
    х.текст_справа(w - ПОЛЕ, ПОЛЕ, &проценты, 2, Weight::Semi, if з.немо { ц.тревога } else { ц.тусклый });
    let mut y = ПОЛЕ + text::height(2) + 14;

    // ── Ползунок и кнопка немоты ─────────────────────────────────────────────
    let дорожка = w - ПОЛЕ * 2 - КНОПКА - 14;
    let цель = Цель::Громкость { x0: ПОЛЕ, w: дорожка };
    let горит = наведено(д, &цель) || д.тащим_громкость;
    х.ползунок(ПОЛЕ, y + КНОПКА / 2, дорожка, з.громкость, горит, ц);
    х.цель(Rect { x: ПОЛЕ - 8, y, w: дорожка + 16, h: КНОПКА }, цель);
    let r = Rect { x: w - ПОЛЕ - КНОПКА, y, w: КНОПКА, h: КНОПКА };
    let фон = if з.немо {
        ц.тревога
    } else if наведено(д, &Цель::Немота) {
        ц.наведение_сильнее
    } else {
        ц.наведение
    };
    х.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, фон);
    х.значок(r, 15, какой, if з.немо { ц.на_акценте } else { ц.текст });
    х.цель(r, Цель::Немота);
    y += КНОПКА + 16;

    // ── Устройства ───────────────────────────────────────────────────────────
    for (заголовок, список, вход) in [
        (т!("ВЫВОД", "OUTPUT"), &з.выходы, false),
        (т!("ВВОД", "INPUT"), &з.входы, true),
    ] {
        if список.is_empty() {
            continue;
        }
        y = х.раздел(y, заголовок, ц);
        for у in список.iter().take(5) {
            let цель = if вход { Цель::Вход(у.имя.clone()) } else { Цель::Выход(у.имя.clone()) };
            х.строка(д, y, w, &у.подпись, None, у.основное, цель);
            y += СТРОКА;
        }
        y += 8;
    }
    х.в(w, y + ПОЛЕ - 8)
}

// ── Питание ──────────────────────────────────────────────────────────────────

fn питание(д: &Данные) -> Option<Содержимое> {
    let ц = &д.цвета;
    let (процент, заряжается) = д.заряд?;
    let w = 344;
    let mut х = Холст::default();
    let тревога = процент <= 20 && !заряжается;

    // ── Шапка: проценты крупно, справа — что с зарядом ───────────────────────
    х.текст(ПОЛЕ, ПОЛЕ, &format!("{процент}%"), 3, Weight::Semi, if тревога { ц.тревога } else { ц.текст });
    let состояние = match (заряжается, процент >= 100) {
        (true, true) => т!("Заряжена", "Charged"),
        (true, false) => т!("Заряжается", "Charging"),
        (false, _) => т!("От батареи", "On battery"),
    };
    х.текст_справа(
        w - ПОЛЕ, ПОЛЕ + (text::height(3) - text::height(2)) / 2,
        состояние, 2, Weight::Regular, ц.тусклый,
    );
    let mut y = ПОЛЕ + text::height(3) + 10;
    let полоса = w - ПОЛЕ * 2;
    х.плашка(ПОЛЕ, y, полоса, 8, 4, ц.дорожка);
    let з = полоса * процент.min(100) as i32 / 100;
    if з > 0 {
        let цвет = if заряжается { ц.хорошо } else if тревога { ц.тревога } else { ц.акцент };
        х.плашка(ПОЛЕ, y, з.max(8), 8, 4, цвет);
    }
    y += 8 + 10;

    let п = д.питание.as_ref();
    let mut подробно = Vec::new();
    if let Some(м) = п.and_then(|п| п.минут) {
        let т = crate::питание::время(м);
        подробно.push(if заряжается {
            тф!("до полного {}", "{} to full", т)
        } else {
            тф!("осталось {}", "{} left", т)
        });
    }
    if let Some(вт) = п.and_then(|п| п.ватт) {
        подробно.push(тф!("{:.1} Вт", "{:.1} W", вт));
    }
    if подробно.is_empty() {
        y += 6;
    } else {
        х.текст(ПОЛЕ, y, &подробно.join(" · "), 1, Weight::Regular, ц.тусклый);
        y += text::height(1) + 14;
    }

    let Some(п) = п else { return Some(х.в(w, y + ПОЛЕ - 14)) };

    // ── Режимы power-profiles-daemon ─────────────────────────────────────────
    if п.служба && !п.профили.is_empty() {
        y = х.раздел(y, т!("РЕЖИМ", "MODE"), ц);
        for имя in crate::питание::ПРОФИЛИ.iter().filter(|и| п.профили.iter().any(|x| x == *и)) {
            х.строка(
                д, y, w, crate::питание::имя_профиля(имя), None,
                п.активный == *имя, Цель::Профиль(имя.to_string()),
            );
            y += СТРОКА;
        }
        y += 8;
    }

    // ── Подсветка экрана ─────────────────────────────────────────────────────
    if let Some(экран) = п.экран.as_ref() {
        y = х.раздел(y, т!("ЯРКОСТЬ", "BRIGHTNESS"), ц);
        let доля = д.яркость.unwrap_or_else(|| crate::питание::доля_на_глаз(экран));
        let подпись = format!("{}%", (доля * 100.0).round() as i32);
        let дорожка = w - ПОЛЕ * 2 - ширина("100%", 2, Weight::Semi) - 16;
        let цель = Цель::Яркость { x0: ПОЛЕ, w: дорожка };
        let горит = наведено(д, &цель) || д.тащим_яркость;
        х.ползунок(ПОЛЕ, y + КНОПКА / 2, дорожка, доля, горит, ц);
        х.текст_справа(w - ПОЛЕ, y + (КНОПКА - text::height(2)) / 2, &подпись, 2, Weight::Semi, ц.тусклый);
        if экран.пишется {
            х.цель(Rect { x: ПОЛЕ - 8, y, w: дорожка + 16, h: КНОПКА }, цель);
        }
        y += КНОПКА + 4;
        if !экран.пишется {
            х.текст(ПОЛЕ, y, т!("нет прав менять подсветку", "no permission to change backlight"), 1, Weight::Regular, ц.тревога);
            y += text::height(1) + 6;
        }
        y += 6;
    }

    // ── Подсветка клавиатуры ─────────────────────────────────────────────────
    if let Some(кл) = п.клавиатура.as_ref() {
        let уровень = format!("{}/{}", кл.сейчас, кл.макс);
        х.строка(
            д, y, w, т!("Подсветка клавиатуры", "Keyboard backlight"), Some(&уровень),
            кл.сейчас > 0, Цель::Подсветка,
        );
        y += СТРОКА + 8;
    }
    Some(х.в(w, y + ПОЛЕ - 8))
}

