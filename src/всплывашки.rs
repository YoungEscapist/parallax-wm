fn раскладки(д: &Данные) -> Option<Содержимое> {
    if д.раскладки.len() < 2 {
        return None;
    }
    let ц = &д.цвета;
    let код_w = д.раскладки.iter().map(|к| ширина(к, 2, Weight::Semi)).max().unwrap_or(0);
    let имя_w = д.раскладки.iter().map(|к| ширина(имя_раскладки(к), 2, Weight::Regular)).max().unwrap_or(0);
    let w = (ПОЛЕ * 2 + 20 + код_w + 14 + имя_w + 8).clamp(220, 420);
    let mut х = Холст::default();
    let mut y = х.раздел(ПОЛЕ, т!("РАСКЛАДКА", "KEYBOARD LAYOUT"), ц);
    for (i, код) in д.раскладки.iter().enumerate() {
        let цель = Цель::Раскладка(i);
        let активна = i == д.раскладка;
        let r = Rect { x: ПОЛЕ - 6, y, w: w - ПОЛЕ * 2 + 12, h: СТРОКА - 2 };
        if наведено(д, &цель) {
            х.плашка(r.x, r.y, r.w, r.h, 9, под_курсором(д, ц.наведение));
        }
        let d = 8;
        х.плашка(ПОЛЕ + 2, y + (r.h - d) / 2, d, d, d / 2, if активна { ц.акцент } else { ц.точка });
        let ty = y + (r.h - text::height(2)) / 2;
        х.текст(ПОЛЕ + 20, ty, код, 2, Weight::Semi, if активна { ц.текст } else { ц.тусклый });
        let имя_x = ПОЛЕ + 20 + код_w + 14;
        let имя = bar::fit_text(имя_раскладки(код), 2, w - ПОЛЕ - имя_x);
        х.текст(имя_x, ty, &имя, 2, Weight::Regular, ц.тусклый);
        х.цель(r, цель);
        y += СТРОКА;
    }
    Some(х.в(w, y + ПОЛЕ - 8))
}

// ── Подпись значка трея ──────────────────────────────────────────────────────

fn подпись(д: &Данные, i: usize) -> Option<Содержимое> {
    let текст = д.трей.get(i)?.trim();
    if текст.is_empty() {
        return None;
    }
    let s = bar::fit_text(текст, 2, 440);
    let (поле_x, поле_y) = (14, 9);
    let w = ширина(&s, 2, Weight::Regular) + поле_x * 2;
    let mut х = Холст::default();
    х.текст(поле_x, поле_y, &s, 2, Weight::Regular, д.цвета.текст);
    Some(х.в(w, text::height(2) + поле_y * 2))
}


// ── Вайфай ───────────────────────────────────────────────────────────────────

/// Сколько дуг гореть у значка вайфая (та же арифметика, что на панели).
fn дуги(в: &crate::wifi::Snapshot, фаза: f32) -> i32 {
    bar::wifi_arcs(
        &bar::WifiCell { enabled: в.enabled, connected: в.ssid.is_some(), connecting: в.connecting, strength: в.strength },
        фаза as f64,
    )
}

fn вайфай(д: &Данные) -> Option<Содержимое> {
    let ц = &д.цвета;
    let в = д.вайфай.as_ref().filter(|в| в.present)?;
    let w = 344;
    let mut х = Холст::default();
    let дуг = дуги(в, д.фаза);
    let состояние = if !в.enabled {
        т!("Выключен", "Off").to_string()
    } else if в.connecting {
        match д.сеть_ждём.as_deref() {
            Some(s) => тф!("Подключаюсь к {}…", "Connecting to {}…", s),
            None => т!("Подключаюсь…", "Connecting…").to_string(),
        }
    } else if let Some(ssid) = в.ssid.as_deref() {
        format!("{ssid} · {}%", в.strength)
    } else {
        т!("Не подключено", "Not connected").to_string()
    };
    let mut y = х.шапка(
        д, w, в.enabled,
        |х, r, цвет| х.вайфай_значок(r, 16, if в.enabled { дуг.max(1) } else { 3 }, цвет, с_альфой(цвет, 0.35)),
        "Wi-Fi", &состояние, д.тумблер_вайфай, Цель::ВайфайРадио,
    );

    if !в.enabled {
        х.текст(ПОЛЕ, y, т!("Включите, чтобы увидеть сети", "Turn it on to see networks"), 1, Weight::Regular, ц.тусклый);
        y += text::height(1) + 14;
        х.кнопка(д, w - ПОЛЕ, y, т!("Все сети ›", "All networks ›"), None, false, Цель::ВайфайВсе, true);
        return Some(х.в(w, y + КНОПКА + ПОЛЕ));
    }

    // ── Сети ─────────────────────────────────────────────────────────────────
    // Сохранённые, которых нет в эфире (путь "/"), — только в полном меню:
    // окошко отвечает на «к чему можно подключиться прямо сейчас».
    let сети: Vec<&crate::wifi::Ap> = в.aps.iter().filter(|a| a.path != "/").take(СЕТЕЙ).collect();
    let ищем = д.ищем_сети || сети.is_empty();
    let заголовок_y = y;
    y = х.раздел(y, т!("СЕТИ", "NETWORKS"), ц);
    if ищем {
        х.точки(ПОЛЕ + ширина(т!("СЕТИ", "NETWORKS"), 1, Weight::Semi) + 10, заголовок_y + text::height(1) / 2, д.фаза, ц.акцент);
    }
    if сети.is_empty() {
        х.текст(ПОЛЕ, y + 6, т!("Ищу сети", "Looking for networks"), 2, Weight::Regular, ц.тусклый);
        y += СТРОКА + 4;
    }
    for ap in сети {
        let цель = Цель::Сеть(ap.ssid.clone());
        let r = Rect { x: ПОЛЕ - 6, y, w: w - ПОЛЕ * 2 + 12, h: СТРОКА - 2 };
        if ap.active {
            х.плашка(r.x, r.y, r.w, r.h, 9, с_альфой(ц.акцент, 0.16));
        }
        if наведено(д, &цель) {
            х.плашка(r.x, r.y, r.w, r.h, 9, под_курсором(д, ц.наведение));
        }
        let вкл = if ap.active { ц.акцент } else { ц.текст };
        х.сигнал(ПОЛЕ + 1, y + r.h / 2 + 7, ap.strength, вкл, ц.точка);
        let ждём = в.connecting && д.сеть_ждём.as_deref() == Some(ap.ssid.as_str());
        let ty = y + (r.h - text::height(2)) / 2;
        let справа_w = if ждём {
            х.точки(w - ПОЛЕ - 23, y + r.h / 2, д.фаза, ц.акцент) + 8
        } else if ap.active {
            let s = т!("подключено", "connected");
            х.текст_справа(w - ПОЛЕ, y + (r.h - text::height(1)) / 2, s, 1, Weight::Semi, ц.акцент);
            ширина(s, 1, Weight::Semi) + 10
        } else if ap.secure {
            х.значок(Rect { x: w - ПОЛЕ - 12, y, w: 12, h: r.h }, 13, Значок::Замок, ц.тусклый);
            22
        } else {
            0
        };
        let имя = bar::fit_text(&ap.ssid, 2, w - ПОЛЕ * 2 - 28 - справа_w);
        х.текст(ПОЛЕ + 28, ty, &имя, 2, if ap.active { Weight::Semi } else { Weight::Regular }, ц.текст);
        х.цель(r, цель);
        y += СТРОКА;
    }
    y += 8;

    // ── Подвал ───────────────────────────────────────────────────────────────
    х.кнопка(д, ПОЛЕ, y, т!("Обновить", "Rescan"), Some(Значок::Перезагрузка), false, Цель::ВайфайПоиск, false);
    х.кнопка(д, w - ПОЛЕ, y, т!("Все сети ›", "All networks ›"), None, false, Цель::ВайфайВсе, true);
    Some(х.в(w, y + КНОПКА + ПОЛЕ))
}

// ── Блютуз ───────────────────────────────────────────────────────────────────

/// Что за устройство — по иконке BlueZ (см. `bluetooth::Device::kind`).
fn вид_устройства(d: &crate::bluetooth::Device) -> &'static str {
    match d.kind() {
        "audio" => т!("наушники", "audio"),
        "mouse" => т!("мышь", "mouse"),
        "kbd" => т!("клавиатура", "keyboard"),
        "pad" => т!("геймпад", "gamepad"),
        "phone" => т!("телефон", "phone"),
        "pc" => т!("компьютер", "computer"),
        _ => "",
    }
}

fn блютуз(д: &Данные) -> Option<Содержимое> {
    let ц = &д.цвета;
    let б = д.блютуз.as_ref().filter(|б| б.adapter.is_some())?;
    let w = 344;
    let mut х = Холст::default();
    let подключены: Vec<&crate::bluetooth::Device> = б.devices.iter().filter(|d| d.connected).collect();
    let состояние = if !б.powered {
        т!("Выключен", "Off").to_string()
    } else if подключены.len() == 1 {
        подключены[0].name.clone()
    } else if подключены.len() > 1 {
        тф!("Подключено устройств: {}", "{} devices connected", подключены.len())
    } else if б.discovering {
        т!("Ищу устройства…", "Looking for devices…").to_string()
    } else {
        т!("Нет подключений", "Nothing connected").to_string()
    };
    let mut y = х.шапка(
        д, w, б.powered,
        |х, r, цвет| х.значок(r, 18, Значок::Блютуз, цвет),
        "Bluetooth", &состояние, д.тумблер_блютуз, Цель::БлютузАдаптер,
    );

    if !б.powered {
        х.текст(ПОЛЕ, y, т!("Включите, чтобы подключить устройства", "Turn it on to connect devices"), 1, Weight::Regular, ц.тусклый);
        y += text::height(1) + 14;
        х.кнопка(д, w - ПОЛЕ, y, т!("Все устройства ›", "All devices ›"), None, false, Цель::БлютузВсе, true);
        return Some(х.в(w, y + КНОПКА + ПОЛЕ));
    }

    let строка = |х: &mut Холст, y: i32, dev: &crate::bluetooth::Device| {
        let цель = Цель::Bt(dev.path.clone());
        let r = Rect { x: ПОЛЕ - 6, y, w: w - ПОЛЕ * 2 + 12, h: СТРОКА - 2 };
        if dev.connected {
            х.плашка(r.x, r.y, r.w, r.h, 9, с_альфой(ц.акцент, 0.16));
        }
        if наведено(д, &цель) {
            х.плашка(r.x, r.y, r.w, r.h, 9, под_курсором(д, ц.наведение));
        }
        let d = 8;
        х.плашка(ПОЛЕ + 2, y + (r.h - d) / 2, d, d, d / 2, if dev.connected { ц.акцент } else { ц.точка });
        let ждём = д.устройство_ждём.as_deref() == Some(dev.path.as_str());
        let ty1 = y + (r.h - text::height(1)) / 2;
        let справа_w = if ждём {
            х.точки(w - ПОЛЕ - 23, y + r.h / 2, д.фаза, ц.акцент) + 8
        } else {
            let (s, цвет) = match (dev.connected, dev.battery, dev.paired) {
                (true, Some(з), _) => (format!("{з}%"), if з <= 20 { ц.тревога } else { ц.акцент }),
                (true, None, _) => (т!("подключено", "connected").to_string(), ц.акцент),
                (false, _, false) => (т!("сопрячь", "pair").to_string(), ц.тусклый),
                (false, _, true) => (вид_устройства(dev).to_string(), ц.тусклый),
            };
            if s.is_empty() {
                0
            } else {
                х.текст_справа(w - ПОЛЕ, ty1, &s, 1, Weight::Semi, цвет);
                ширина(&s, 1, Weight::Semi) + 10
            }
        };
        let имя = bar::fit_text(&dev.name, 2, w - ПОЛЕ * 2 - 20 - справа_w);
        let вес = if dev.connected { Weight::Semi } else { Weight::Regular };
        х.текст(ПОЛЕ + 20, y + (r.h - text::height(2)) / 2, &имя, 2, вес, ц.текст);
        х.цель(r, цель);
    };

    let сопряжённые: Vec<&crate::bluetooth::Device> = б.devices.iter().filter(|d| d.paired).take(УСТРОЙСТВ).collect();
    let найденные: Vec<&crate::bluetooth::Device> = б.devices.iter()
        .filter(|d| !d.paired && d.name != d.address)
        .take(4)
        .collect();
    if сопряжённые.is_empty() && !б.discovering {
        х.текст(ПОЛЕ, y, т!("Сопряжённых нет — нажмите «Поиск»", "No paired devices — press Scan"), 1, Weight::Regular, ц.тусклый);
        y += text::height(1) + 14;
    }
    if !сопряжённые.is_empty() {
        y = х.раздел(y, т!("УСТРОЙСТВА", "DEVICES"), ц);
        for dev in сопряжённые {
            строка(&mut х, y, dev);
            y += СТРОКА;
        }
        y += 8;
    }
    if б.discovering || !найденные.is_empty() {
        let заголовок_y = y;
        y = х.раздел(y, т!("РЯДОМ", "NEARBY"), ц);
        if б.discovering {
            х.точки(ПОЛЕ + ширина(т!("РЯДОМ", "NEARBY"), 1, Weight::Semi) + 10, заголовок_y + text::height(1) / 2, д.фаза, ц.акцент);
        }
        if найденные.is_empty() {
            х.текст(ПОЛЕ, y + 4, т!("Пока никого", "Nobody yet"), 1, Weight::Regular, ц.тусклый);
            y += text::height(1) + 12;
        }
        for dev in найденные {
            строка(&mut х, y, dev);
            y += СТРОКА;
        }
        y += 8;
    }

    // ── Подвал ───────────────────────────────────────────────────────────────
    let поиск = if б.discovering { т!("Стоп", "Stop") } else { т!("Поиск", "Scan") };
    let слева = х.кнопка(д, ПОЛЕ, y, поиск, None, б.discovering, Цель::БлютузПоиск, false);
    // Пока идёт поиск, левая кнопка шире (бегут точки) — правой тогда
    // хватает короткой подписи, иначе они слипались бы.
    let полная = т!("Все устройства ›", "All devices ›");
    let влезает = ПОЛЕ + слева + 10 + ширина(полная, 2, Weight::Regular) + 28 <= w - ПОЛЕ;
    let все = if влезает { полная } else { т!("Все ›", "All ›") };
    х.кнопка(д, w - ПОЛЕ, y, все, None, false, Цель::БлютузВсе, true);
    Some(х.в(w, y + КНОПКА + ПОЛЕ))
}

