// ── Раскладка окошка: штрихи и цели ──────────────────────────────────────────

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Значок {
    Звук,
    ЗвукВыкл,
}

/// Что нарисовать. Координаты — от левого верхнего угла карточки, пока
/// окошко собирается, и экранные, когда оно поставлено на место.
#[derive(Clone, Debug, PartialEq)]
pub enum Штрих {
    Плашка { r: Rect, радиус: i32, цвет: [f32; 4] },
    Текст { x: i32, y: i32, w: i32, текст: String, масштаб: i32, вес: Weight, цвет: [f32; 4] },
    /// Маска значка высотой `h`, по центру ячейки `r`.
    Значок { r: Rect, h: i32, какой: Значок, цвет: [f32; 4] },
}

impl Штрих {
    pub fn рамка(&self) -> Rect {
        match self {
            Штрих::Плашка { r, .. } | Штрих::Значок { r, .. } => *r,
            Штрих::Текст { x, y, w, масштаб, .. } => Rect { x: *x, y: *y, w: *w, h: text::height(*масштаб) },
        }
    }

    fn сдвинуть(&mut self, dx: i32, dy: i32) {
        match self {
            Штрих::Плашка { r, .. } | Штрих::Значок { r, .. } => {
                r.x += dx;
                r.y += dy;
            }
            Штрих::Текст { x, y, .. } => {
                *x += dx;
                *y += dy;
            }
        }
    }
}

/// Что нажимается.
#[derive(Clone, Debug, PartialEq)]
pub enum Цель {
    МесяцНазад,
    МесяцВперёд,
    МесяцСейчас,
    /// Ползунок: где начинается дорожка и какой она ширины (экранные пиксели).
    Громкость { x0: i32, w: i32 },
    Немота,
    Выход(String),
    Вход(String),
    Профиль(String),
    Яркость { x0: i32, w: i32 },
    /// Подсветка клавиатуры: следующий уровень по кругу.
    Подсветка,
    Раскладка(usize),
}

impl Цель {
    /// Та же цель, без оглядки на геометрию: дорожка ползунка едет вместе с
    /// карточкой, а «под курсором ползунок громкости» от этого не меняется.
    pub fn тот_же(&self, о: &Цель) -> bool {
        match (self, о) {
            (Цель::Громкость { .. }, Цель::Громкость { .. }) | (Цель::Яркость { .. }, Цель::Яркость { .. }) => true,
            (a, b) => a == b,
        }
    }

    fn сдвинуть(&mut self, dx: i32) {
        if let Цель::Громкость { x0, .. } | Цель::Яркость { x0, .. } = self {
            *x0 += dx;
        }
    }
}

/// Собранное окошко в координатах карточки: её естественный размер, штрихи
/// от заднего плана к переднему и цели.
#[derive(Clone, Debug, Default)]
pub struct Содержимое {
    pub w: i32,
    pub h: i32,
    pub штрихи: Vec<Штрих>,
    pub цели: Vec<(Rect, Цель)>,
}

fn ширина(s: &str, масштаб: i32, вес: Weight) -> i32 {
    text::width_of(s, вес, масштаб)
}

fn с_альфой(c: [f32; 4], a: f32) -> [f32; 4] {
    [c[0], c[1], c[2], c[3] * a]
}

fn смесь(a: [f32; 4], b: [f32; 4], t: f32) -> [f32; 4] {
    let м = |x: f32, y: f32| x + (y - x) * t;
    [м(a[0], b[0]), м(a[1], b[1]), м(a[2], b[2]), м(a[3], b[3])]
}

fn наведено(д: &Данные, ц: &Цель) -> bool {
    д.наведено.as_ref().is_some_and(|н| н.тот_же(ц))
}

#[derive(Default)]
struct Холст {
    шт: Vec<Штрих>,
    цели: Vec<(Rect, Цель)>,
}

impl Холст {
    fn плашка(&mut self, x: i32, y: i32, w: i32, h: i32, радиус: i32, цвет: [f32; 4]) {
        if w > 0 && h > 0 {
            self.шт.push(Штрих::Плашка { r: Rect { x, y, w, h }, радиус, цвет });
        }
    }

    fn текст(&mut self, x: i32, y: i32, s: &str, масштаб: i32, вес: Weight, цвет: [f32; 4]) -> i32 {
        if s.is_empty() {
            return 0;
        }
        let w = ширина(s, масштаб, вес);
        self.шт.push(Штрих::Текст { x, y, w, текст: s.to_string(), масштаб, вес, цвет });
        w
    }

    /// Текст, прижатый правым краем к `правый_x`.
    fn текст_справа(&mut self, правый_x: i32, y: i32, s: &str, масштаб: i32, вес: Weight, цвет: [f32; 4]) {
        let w = ширина(s, масштаб, вес);
        self.текст(правый_x - w, y, s, масштаб, вес, цвет);
    }

    /// Текст по центру прямоугольника.
    fn текст_в(&mut self, r: Rect, s: &str, масштаб: i32, вес: Weight, цвет: [f32; 4]) {
        let w = ширина(s, масштаб, вес);
        self.текст(r.x + (r.w - w) / 2, r.y + (r.h - text::height(масштаб)) / 2, s, масштаб, вес, цвет);
    }

    fn значок(&mut self, r: Rect, h: i32, какой: Значок, цвет: [f32; 4]) {
        self.шт.push(Штрих::Значок { r, h, какой, цвет });
    }

    fn цель(&mut self, r: Rect, ц: Цель) {
        self.цели.push((r, ц));
    }

    /// Ползунок: дорожка, заполнение акцентом и ручка. Ручка под курсором
    /// (или пока её тянут) крупнее — так видно, что за неё можно взяться.
    fn ползунок(&mut self, x0: i32, cy: i32, w: i32, доля: f32, горит: bool, ц: &Цвета) {
        let доля = доля.clamp(0.0, 1.0);
        self.плашка(x0, cy - 3, w, 6, 3, ц.дорожка);
        let з = (w as f32 * доля).round() as i32;
        if з > 0 {
            self.плашка(x0, cy - 3, з.max(6), 6, 3, ц.акцент);
        }
        let d = if горит { 20 } else { 16 };
        self.плашка(x0 + з - d / 2, cy - d / 2, d, d, d / 2, ц.ручка);
    }

    /// Строка списка: точка (акцент — выбранное), подпись, справа — пояснение.
    #[allow(clippy::too_many_arguments)]
    fn строка(
        &mut self,
        д: &Данные,
        y: i32,
        w: i32,
        подпись: &str,
        справа: Option<&str>,
        активна: bool,
        цель: Цель,
    ) {
        let ц = &д.цвета;
        let r = Rect { x: ПОЛЕ - 6, y, w: w - ПОЛЕ * 2 + 12, h: СТРОКА - 2 };
        if наведено(д, &цель) {
            self.плашка(r.x, r.y, r.w, r.h, 9, ц.наведение);
        }
        let d = 8;
        self.плашка(ПОЛЕ + 2, y + (r.h - d) / 2, d, d, d / 2, if активна { ц.акцент } else { ц.точка });
        let под_справа = справа.map(|s| ширина(s, 2, Weight::Regular) + 10).unwrap_or(0);
        let текст = bar::fit_text(подпись, 2, w - ПОЛЕ * 2 - 20 - под_справа);
        let ty = y + (r.h - text::height(2)) / 2;
        self.текст(ПОЛЕ + 20, ty, &текст, 2, Weight::Regular, if активна { ц.текст } else { ц.тусклый });
        if let Some(s) = справа {
            self.текст_справа(w - ПОЛЕ, ty, s, 2, Weight::Regular, ц.тусклый);
        }
        self.цель(r, цель);
    }

    /// Подпись раздела («ВЫВОД», «РЕЖИМ») — мелко и тускло, как в Caelestia.
    fn раздел(&mut self, y: i32, s: &str, ц: &Цвета) -> i32 {
        self.текст(ПОЛЕ, y, s, 1, Weight::Semi, ц.тусклый);
        y + text::height(1) + 6
    }

    fn в(self, w: i32, h: i32) -> Содержимое {
        Содержимое { w, h, штрихи: self.шт, цели: self.цели }
    }
}

/// Собрать окошко. `None` — показывать нечего (одна раскладка, у значка трея
/// нет подписи, у машины нет батареи).
pub fn собрать(что: Окошко, д: &Данные) -> Option<Содержимое> {
    match что {
        Окошко::Календарь => календарь(д),
        Окошко::Звук => Some(звук(д)),
        Окошко::Питание => питание(д),
        Окошко::Раскладка => раскладки(д),
        Окошко::Трей(i) => подпись(д, i),
    }
}

/// Окошко с одной строкой: «звука нет» и подобное.
fn сообщение(s: &str, ц: &Цвета) -> Содержимое {
    let mut х = Холст::default();
    let w = (ширина(s, 2, Weight::Regular) + ПОЛЕ * 2).max(240);
    х.текст_в(Rect { x: 0, y: ПОЛЕ, w, h: text::height(2) }, s, 2, Weight::Regular, ц.тусклый);
    х.в(w, text::height(2) + ПОЛЕ * 2)
}

