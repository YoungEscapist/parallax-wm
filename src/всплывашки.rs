#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Тащим {
    Громкость { x0: i32, w: i32 },
    Яркость { x0: i32, w: i32 },
}

#[derive(Debug, Default)]
pub struct Состояние {
    /// Что показываем (держится, пока карточка не свернётся до конца).
    pub что: Option<Окошко>,
    /// Цель раскрытия: открыто или сворачивается.
    pub открыто: bool,
    /// Доля раскрытия 0…1.
    pub доля: f64,
    /// Проявление содержимого после смены окошка 0…1.
    pub смена: f64,
    /// Карточка на этом кадре (x, y, w, h) — едет к цели.
    pub рамка: Option<[f64; 4]>,
    рамка_едет: bool,
    pub закреплено: bool,
    /// Курсор на самой карточке или в зазоре над ней.
    pub на_окошке: bool,
    ушли: Option<Instant>,
    pub наведено: Option<Цель>,
    pub месяц: i32,
    pub тащим: Option<Тащим>,
    /// Своё значение и до какого момента его держать.
    pub громкость: Option<(f32, Instant)>,
    pub яркость: Option<(f32, Instant)>,
    отправлено: Option<Instant>,
    ждёт: Option<Тащим>,
    колесо: f64,
    /// Закрыли щелчком или Esc, а курсор всё ещё на ячейке: не открывать
    /// снова, пока он с неё не уйдёт.
    подавить: Option<Окошко>,
    /// Что сказали потокам звука, питания, вайфая и блютуза.
    следим: Следим,
    /// На какую ячейку и когда легла мышь (см. `ВЗГЛЯД`).
    навели: Option<(Окошко, Instant)>,
    /// Ручки тумблеров 0…1: вайфай, блютуз.
    тумблеры: [f64; 2],
    /// Проявление подложки под курсором 0…1.
    подсветка: f64,
    /// Когда окошко открылось — от этого бегут точки «ищу…».
    открыли: Option<Instant>,
    /// Сеть, к которой только что начали подключаться.
    сеть_ждём: Option<(String, Instant)>,
    /// Когда попросили пересканировать эфир.
    поиск_сетей: Option<Instant>,
    /// Устройство, которому послали команду: путь, было ли оно подключено и
    /// сопряжено в тот момент и когда. Ответ — смена любого из двух.
    устройство_ждём: Option<(String, bool, bool, Instant)>,
    /// Шапка окошка питания и когда её читали (аптайм дописывается часами).
    сеанс: Option<(Сеанс, Instant)>,
}

/// Каким потокам сказано, что на их окошко смотрят.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct Следим {
    звук: bool,
    питание: bool,
    вайфай: bool,
    блютуз: bool,
}

impl Состояние {
    pub fn следит_звук(&self) -> bool {
        self.следим.звук
    }

    pub fn следит_питание(&self) -> bool {
        self.следим.питание
    }

    pub fn следит_вайфай(&self) -> bool {
        self.следим.вайфай
    }

    pub fn следит_блютуз(&self) -> bool {
        self.следим.блютуз
    }

    /// Открыть `что` или перевести на него открытое окошко.
    fn навести(&mut self, что: Окошко) {
        if self.что == Some(что) {
            self.открыто = true;
            return;
        }
        if self.что.is_some() && self.доля > 0.0 {
            // Перетекание: карточка едет с места на место, содержимое
            // проявляется заново.
            self.смена = 0.0;
        } else {
            self.доля = 0.0;
            self.рамка = None;
            self.смена = 1.0;
            self.открыли = Some(Instant::now());
        }
        if что == Окошко::Календарь {
            self.месяц = 0;
        }
        self.что = Some(что);
        self.наведено = None;
        self.открыто = true;
        self.ушли = None;
    }
}

