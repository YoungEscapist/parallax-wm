/// «3 ч 12 мин», «2 д 4 ч», «5 мин».
pub fn сколько_работает(сек: u64) -> String {
    let мин = сек / 60;
    let (д, ч, м) = (мин / 1440, мин / 60 % 24, мин % 60);
    if д > 0 {
        тф!("{} д {} ч", "{}d {}h", д, ч)
    } else if ч > 0 {
        тф!("{} ч {} мин", "{}h {}m", ч, м)
    } else {
        тф!("{} мин", "{}m", м)
    }
}

fn сеанс(д: &Данные) -> Содержимое {
    use crate::tray::PowerAction as Д;
    let ц = &д.цвета;
    let w = 344;
    let mut х = Холст::default();

    // ── Шапка: буква в кружке, кто и где, сколько работает ───────────────────
    const D: i32 = 40;
    let кто = if д.сеанс.кто.is_empty() { "parallax" } else { д.сеанс.кто.as_str() };
    let буква: String = кто.chars().next().map(|c| c.to_uppercase().collect()).unwrap_or_default();
    х.плашка(ПОЛЕ, ПОЛЕ, D, D, D / 2, ц.акцент);
    х.текст_в(Rect { x: ПОЛЕ, y: ПОЛЕ, w: D, h: D }, &буква, 2, Weight::Semi, ц.на_акценте);
    let tx = ПОЛЕ + D + 12;
    let работает = д.сеанс.работает.map(|с| тф!("работает {}", "up {}", сколько_работает(с))).unwrap_or_default();
    let справа = ширина(&работает, 1, Weight::Regular);
    х.текст(tx, ПОЛЕ - 2, &bar::fit_text(кто, 2, w - tx - ПОЛЕ - справа - 10), 2, Weight::Semi, ц.текст);
    if !д.сеанс.машина.is_empty() {
        х.текст(tx, ПОЛЕ + text::height(2) - 1, &bar::fit_text(&д.сеанс.машина, 1, w - tx - ПОЛЕ), 1, Weight::Regular, ц.тусклый);
    }
    х.текст_справа(w - ПОЛЕ, ПОЛЕ + (D - text::height(1)) / 2, &работает, 1, Weight::Regular, ц.тусклый);
    let mut y = ПОЛЕ + D + 14;
    х.плашка(ПОЛЕ, y, w - ПОЛЕ * 2, 1, 0, ц.черта);
    y += 1 + 12;

    // ── Кнопки ───────────────────────────────────────────────────────────────
    for (действие, значок, подпись) in [
        (Д::Sleep, Значок::Сон, т!("Сон", "Sleep")),
        (Д::Reboot, Значок::Перезагрузка, т!("Перезагрузка", "Reboot")),
        (Д::Off, Значок::Выключение, т!("Выключение", "Power off")),
    ] {
        let цель = Цель::Сеанс(действие);
        let r = Rect { x: ПОЛЕ, y, w: w - ПОЛЕ * 2, h: КНОПКА_СЕАНСА };
        let радиус = 12;
        х.плашка(r.x, r.y, r.w, r.h, радиус, ц.наведение);
        let держат = д.зажим.filter(|з| з.действие == действие);
        if наведено(д, &цель) && держат.is_none() {
            х.плашка(r.x, r.y, r.w, r.h, радиус, под_курсором(д, ц.наведение));
        }
        // Заливка растёт слева направо, пока держат, и стекает, если
        // отпустили. Выключение заливается цветом тревоги: оно необратимее.
        let готово = держат.is_some_and(|з| з.готово);
        if let Some(Зажата { доля, .. }) = держат {
            let цвет = if действие == Д::Off { ц.тревога } else { ц.акцент };
            let fw = (r.w as f32 * доля.clamp(0.0, 1.0)).round() as i32;
            if fw > 0 {
                х.плашка(r.x, r.y, fw, r.h, радиус, с_альфой(цвет, if готово { 0.95 } else { 0.55 }));
            }
        }
        let передний = if готово { ц.на_акценте } else { ц.текст };
        х.значок(Rect { x: r.x + 14, y: r.y, w: 22, h: r.h }, 18, значок, передний);
        х.текст(r.x + 48, r.y + (r.h - text::height(2)) / 2, подпись, 2, Weight::Semi, передний);
        // Справа: пока держат — сколько осталось, под курсором — подсказка.
        let ty1 = r.y + (r.h - text::height(1)) / 2;
        match держат {
            Some(Зажата { доля, жмут: true, готово: false, .. }) => {
                let осталось = (1.0 - доля).max(0.0) * crate::зажим::ДЕРЖАТЬ.as_secs_f32();
                х.текст_справа(r.x + r.w - 14, ty1, &тф!("{:.1} с", "{:.1}s", осталось), 1, Weight::Semi, ц.текст);
            }
            Some(_) => {}
            None if наведено(д, &цель) => {
                х.текст_справа(r.x + r.w - 14, ty1, т!("удерживать", "hold"), 1, Weight::Regular, ц.тусклый);
            }
            None => {}
        }
        х.цель(r, цель);
        y += КНОПКА_СЕАНСА + 8;
    }

    // ── Подсказка ────────────────────────────────────────────────────────────
    y += 2;
    let (s, цвет) = match (д.зажим, д.щёлкнули) {
        (Some(Зажата { действие: Д::Sleep, готово: true, .. }), _) => (т!("Засыпаю…", "Going to sleep…"), ц.акцент),
        (Some(Зажата { действие: Д::Reboot, готово: true, .. }), _) => (т!("Перезагружаю…", "Rebooting…"), ц.акцент),
        (Some(Зажата { действие: Д::Off, готово: true, .. }), _) => (т!("Выключаю…", "Powering off…"), ц.тревога),
        (Some(Зажата { жмут: true, .. }), _) => (т!("Держите…", "Keep holding…"), ц.текст),
        // Отпустили раньше — заливка стекает, а подсказка уже прежняя.
        (Some(_), None) | (None, None) => (т!("Удерживайте кнопку секунду", "Hold a button for a second"), ц.тусклый),
        (Some(_), Some(_)) | (None, Some(_)) => {
            // Мигает: щелчок вместо зажатия — частая ошибка, и тихая серая
            // строка её бы не объяснила.
            let мигание = 0.55 + 0.45 * ступень((д.фаза * std::f32::consts::TAU * 1.5).cos() * 0.5 + 0.5, 4.0);
            (т!("Не щелчок — удерживайте секунду", "Don't click — hold for a second"), с_альфой(ц.тревога, мигание))
        }
    };
    х.текст_в(Rect { x: 0, y, w, h: text::height(1) }, s, 1, Weight::Regular, цвет);
    y += text::height(1);
    х.в(w, y + ПОЛЕ)
}

