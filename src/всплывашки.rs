const ДНИ_КОРОТКО_RU: [&str; 7] = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"];
const ДНИ_КОРОТКО_EN: [&str; 7] = ["Mo", "Tu", "We", "Th", "Fr", "Sa", "Su"];

/// Дней от 1970-01-01 по григорианскому календарю (days_from_civil Хиннанта).
fn дни_от_эпохи(год: i32, месяц: i32, день: i32) -> i64 {
    let y = (if месяц <= 2 { год - 1 } else { год }) as i64;
    let эра = if y >= 0 { y } else { y - 399 } / 400;
    let гэ = y - эра * 400;
    let м = месяц as i64;
    let дг = (153 * (if м > 2 { м - 3 } else { м + 9 }) + 2) / 5 + день as i64 - 1;
    let дэ = гэ * 365 + гэ / 4 - гэ / 100 + дг;
    эра * 146_097 + дэ - 719_468
}

/// День недели, 0 — понедельник. 1970-01-01 был четвергом.
pub fn день_недели(год: i32, месяц: i32, день: i32) -> i32 {
    (дни_от_эпохи(год, месяц, день) + 3).rem_euclid(7) as i32
}

pub fn дней_в_месяце(год: i32, месяц: i32) -> i32 {
    match месяц {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        _ if (год % 4 == 0 && год % 100 != 0) || год % 400 == 0 => 29,
        _ => 28,
    }
}

/// Месяц на `на` вперёд (или назад) от данного: (год, 1…12).
pub fn сдвинуть_месяц(год: i32, месяц: i32, на: i32) -> (i32, i32) {
    let i = год * 12 + (месяц - 1) + на;
    (i.div_euclid(12), i.rem_euclid(12) + 1)
}

fn календарь(д: &Данные) -> Option<Содержимое> {
    let в = д.время?;
    let ц = &д.цвета;
    const КЛ_W: i32 = 40;
    const КЛ_H: i32 = 34;
    let w = КЛ_W * 7 + ПОЛЕ * 2;
    let mut х = Холст::default();

    // ── Шапка: время крупно, справа день недели и число ──────────────────────
    х.текст(ПОЛЕ, ПОЛЕ, &format!("{:02}:{:02}", в.час, в.мин), 3, Weight::Semi, ц.текст);
    let м = (в.месяц - 1).clamp(0, 11) as usize;
    let день = т!(ДНИ_RU, ДНИ_EN)[в.день_недели.clamp(0, 6) as usize];
    let число = if crate::lang::русский() {
        format!("{} {}", в.день, МЕСЯЦЫ_РОД_RU[м])
    } else {
        format!("{} {}", МЕСЯЦЫ_EN[м], в.день)
    };
    х.текст_справа(w - ПОЛЕ, ПОЛЕ + 1, день, 1, Weight::Regular, ц.тусклый);
    х.текст_справа(w - ПОЛЕ, ПОЛЕ + text::height(1) + 2, &число, 2, Weight::Semi, ц.текст);
    let mut y = ПОЛЕ + text::height(3) + 12;
    х.плашка(ПОЛЕ, y, w - ПОЛЕ * 2, 1, 0, ц.черта);
    y += 1 + 10;

    // ── Месяц: ‹ Октябрь 2026 › ───────────────────────────────────────────────
    let (год, месяц) = сдвинуть_месяц(в.год, в.месяц, д.месяц);
    let сейчас = д.месяц == 0;
    let заголовок = format!("{} {}", т!(МЕСЯЦЫ_RU, МЕСЯЦЫ_EN)[(месяц - 1) as usize], год);
    for (x, цель, знак) in [
        (ПОЛЕ, Цель::МесяцНазад, "‹"),
        (w - ПОЛЕ - КНОПКА, Цель::МесяцВперёд, "›"),
    ] {
        let r = Rect { x, y, w: КНОПКА, h: КНОПКА };
        if наведено(д, &цель) {
            х.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, ц.наведение_сильнее);
        }
        х.текст_в(r, знак, 2, Weight::Semi, ц.текст);
        х.цель(r, цель);
    }
    let tw = ширина(&заголовок, 2, Weight::Semi);
    let tx = (w - tw) / 2;
    // Листнули — название месяца становится кнопкой «вернуться к сегодня».
    if !сейчас {
        let r = Rect { x: tx - 10, y, w: tw + 20, h: КНОПКА };
        if наведено(д, &Цель::МесяцСейчас) {
            х.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, ц.наведение);
        }
        х.цель(r, Цель::МесяцСейчас);
    }
    х.текст(
        tx, y + (КНОПКА - text::height(2)) / 2, &заголовок, 2, Weight::Semi,
        if сейчас { ц.текст } else { ц.акцент },
    );
    y += КНОПКА + 8;

    // ── Дни недели ───────────────────────────────────────────────────────────
    let выходной = смесь(ц.текст, ц.акцент, 0.55);
    for (i, имя) in т!(ДНИ_КОРОТКО_RU, ДНИ_КОРОТКО_EN).iter().enumerate() {
        let r = Rect { x: ПОЛЕ + i as i32 * КЛ_W, y, w: КЛ_W, h: text::height(1) };
        let цвет = if i >= 5 { с_альфой(выходной, 0.85) } else { ц.тусклый };
        х.текст_в(r, имя, 1, Weight::Semi, цвет);
    }
    y += text::height(1) + 8;

    // ── Сетка: всегда шесть недель, чтобы окошко не прыгало от месяца к месяцу ─
    let первый = день_недели(год, месяц, 1);
    let дней = дней_в_месяце(год, месяц);
    let (пг, пм) = сдвинуть_месяц(год, месяц, -1);
    let дней_раньше = дней_в_месяце(пг, пм);
    for клетка in 0..42i32 {
        let (столбец, ряд) = (клетка % 7, клетка / 7);
        let n = клетка - первый + 1;
        let (число, свой) = if n < 1 {
            (дней_раньше + n, false)
        } else if n > дней {
            (n - дней, false)
        } else {
            (n, true)
        };
        let r = Rect { x: ПОЛЕ + столбец * КЛ_W, y: y + ряд * КЛ_H, w: КЛ_W, h: КЛ_H };
        let сегодня = свой && сейчас && n == в.день;
        let (цвет, вес) = if сегодня {
            let d = 30;
            х.плашка(r.x + (r.w - d) / 2, r.y + (r.h - d) / 2, d, d, d / 2, ц.акцент);
            (ц.на_акценте, Weight::Semi)
        } else if !свой {
            (с_альфой(ц.текст, 0.26), Weight::Regular)
        } else if столбец >= 5 {
            (выходной, Weight::Regular)
        } else {
            (ц.текст, Weight::Regular)
        };
        х.текст_в(r, &число.to_string(), 2, вес, цвет);
    }
    Some(х.в(w, y + 6 * КЛ_H + ПОЛЕ - 6))
}

// ── Звук ─────────────────────────────────────────────────────────────────────

fn звук(д: &Данные) -> Содержимое {
    let ц = &д.цвета;
    let w = 344;
    let Some(з) = д.звук.as_ref().filter(|з| !з.выходы.is_empty()) else {
        return сообщение(т!("Звука нет: pactl молчит", "No audio: pactl is silent"), ц);
    };
    let mut х = Холст::default();
    let какой = if з.немо { Значок::ЗвукВыкл } else { Значок::Звук };

    // ── Шапка: значок, «Звук», проценты ──────────────────────────────────────
    х.значок(Rect { x: ПОЛЕ, y: ПОЛЕ, w: 24, h: text::height(2) }, 18, какой, if з.немо { ц.тревога } else { ц.текст });
    х.текст(ПОЛЕ + 34, ПОЛЕ, т!("Звук", "Sound"), 2, Weight::Semi, ц.текст);
    let проценты = format!("{}%", (з.громкость.max(0.0) * 100.0).round() as i32);
    х.текст_справа(w - ПОЛЕ, ПОЛЕ, &проценты, 2, Weight::Semi, if з.немо { ц.тревога } else { ц.тусклый });
    let mut y = ПОЛЕ + text::height(2) + 14;

    // ── Ползунок и кнопка немоты ─────────────────────────────────────────────
    let дорожка = w - ПОЛЕ * 2 - КНОПКА - 14;
    let цель = Цель::Громкость { x0: ПОЛЕ, w: дорожка };
    let горит = наведено(д, &цель) || д.тащим_громкость;
    х.ползунок(ПОЛЕ, y + КНОПКА / 2, дорожка, з.громкость, горит, ц);
    х.цель(Rect { x: ПОЛЕ - 8, y, w: дорожка + 16, h: КНОПКА }, цель);
    let r = Rect { x: w - ПОЛЕ - КНОПКА, y, w: КНОПКА, h: КНОПКА };
    let фон = if з.немо {
        ц.тревога
    } else if наведено(д, &Цель::Немота) {
        ц.наведение_сильнее
    } else {
        ц.наведение
    };
    х.плашка(r.x, r.y, r.w, r.h, КНОПКА / 2, фон);
    х.значок(r, 15, какой, if з.немо { ц.на_акценте } else { ц.текст });
    х.цель(r, Цель::Немота);
    y += КНОПКА + 16;

    // ── Устройства ───────────────────────────────────────────────────────────
    for (заголовок, список, вход) in [
        (т!("ВЫВОД", "OUTPUT"), &з.выходы, false),
        (т!("ВВОД", "INPUT"), &з.входы, true),
    ] {
        if список.is_empty() {
            continue;
        }
        y = х.раздел(y, заголовок, ц);
        for у in список.iter().take(5) {
            let цель = if вход { Цель::Вход(у.имя.clone()) } else { Цель::Выход(у.имя.clone()) };
            х.строка(д, y, w, &у.подпись, None, у.основное, цель);
            y += СТРОКА;
        }
        y += 8;
    }
    х.в(w, y + ПОЛЕ - 8)
}

// ── Питание ──────────────────────────────────────────────────────────────────

fn питание(д: &Данные) -> Option<Содержимое> {
    let ц = &д.цвета;
    let (процент, заряжается) = д.заряд?;
    let w = 344;
    let mut х = Холст::default();
    let тревога = процент <= 20 && !заряжается;

    // ── Шапка: проценты крупно, справа — что с зарядом ───────────────────────
    х.текст(ПОЛЕ, ПОЛЕ, &format!("{процент}%"), 3, Weight::Semi, if тревога { ц.тревога } else { ц.текст });
    let состояние = match (заряжается, процент >= 100) {
        (true, true) => т!("Заряжена", "Charged"),
        (true, false) => т!("Заряжается", "Charging"),
        (false, _) => т!("От батареи", "On battery"),
    };
    х.текст_справа(
        w - ПОЛЕ, ПОЛЕ + (text::height(3) - text::height(2)) / 2,
        состояние, 2, Weight::Regular, ц.тусклый,
    );
    let mut y = ПОЛЕ + text::height(3) + 10;
    let полоса = w - ПОЛЕ * 2;
    х.плашка(ПОЛЕ, y, полоса, 8, 4, ц.дорожка);
    let з = полоса * процент.min(100) as i32 / 100;
    if з > 0 {
        let цвет = if заряжается { ц.хорошо } else if тревога { ц.тревога } else { ц.акцент };
        х.плашка(ПОЛЕ, y, з.max(8), 8, 4, цвет);
    }
    y += 8 + 10;

    let п = д.питание.as_ref();
    let mut подробно = Vec::new();
    if let Some(м) = п.and_then(|п| п.минут) {
        let т = crate::питание::время(м);
        подробно.push(if заряжается {
            тф!("до полного {}", "{} to full", т)
        } else {
            тф!("осталось {}", "{} left", т)
        });
    }
    if let Some(вт) = п.and_then(|п| п.ватт) {
        подробно.push(тф!("{:.1} Вт", "{:.1} W", вт));
    }
    if подробно.is_empty() {
        y += 6;
    } else {
        х.текст(ПОЛЕ, y, &подробно.join(" · "), 1, Weight::Regular, ц.тусклый);
        y += text::height(1) + 14;
    }

    let Some(п) = п else { return Some(х.в(w, y + ПОЛЕ - 14)) };

    // ── Режимы power-profiles-daemon ─────────────────────────────────────────
    if п.служба && !п.профили.is_empty() {
        y = х.раздел(y, т!("РЕЖИМ", "MODE"), ц);
        for имя in crate::питание::ПРОФИЛИ.iter().filter(|и| п.профили.iter().any(|x| x == *и)) {
            х.строка(
                д, y, w, crate::питание::имя_профиля(имя), None,
                п.активный == *имя, Цель::Профиль(имя.to_string()),
            );
            y += СТРОКА;
        }
        y += 8;
    }

    // ── Подсветка экрана ─────────────────────────────────────────────────────
    if let Some(экран) = п.экран.as_ref() {
        y = х.раздел(y, т!("ЯРКОСТЬ", "BRIGHTNESS"), ц);
        let доля = д.яркость.unwrap_or_else(|| crate::питание::доля_на_глаз(экран));
        let подпись = format!("{}%", (доля * 100.0).round() as i32);
        let дорожка = w - ПОЛЕ * 2 - ширина("100%", 2, Weight::Semi) - 16;
        let цель = Цель::Яркость { x0: ПОЛЕ, w: дорожка };
        let горит = наведено(д, &цель) || д.тащим_яркость;
        х.ползунок(ПОЛЕ, y + КНОПКА / 2, дорожка, доля, горит, ц);
        х.текст_справа(w - ПОЛЕ, y + (КНОПКА - text::height(2)) / 2, &подпись, 2, Weight::Semi, ц.тусклый);
        if экран.пишется {
            х.цель(Rect { x: ПОЛЕ - 8, y, w: дорожка + 16, h: КНОПКА }, цель);
        }
        y += КНОПКА + 4;
        if !экран.пишется {
            х.текст(ПОЛЕ, y, т!("нет прав менять подсветку", "no permission to change backlight"), 1, Weight::Regular, ц.тревога);
            y += text::height(1) + 6;
        }
        y += 6;
    }

    // ── Подсветка клавиатуры ─────────────────────────────────────────────────
    if let Some(кл) = п.клавиатура.as_ref() {
        let уровень = format!("{}/{}", кл.сейчас, кл.макс);
        х.строка(
            д, y, w, т!("Подсветка клавиатуры", "Keyboard backlight"), Some(&уровень),
            кл.сейчас > 0, Цель::Подсветка,
        );
        y += СТРОКА + 8;
    }
    Some(х.в(w, y + ПОЛЕ - 8))
}

