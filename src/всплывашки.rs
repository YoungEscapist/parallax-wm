fn раскладки(д: &Данные) -> Option<Содержимое> {
    if д.раскладки.len() < 2 {
        return None;
    }
    let ц = &д.цвета;
    let код_w = д.раскладки.iter().map(|к| ширина(к, 2, Weight::Semi)).max().unwrap_or(0);
    let имя_w = д.раскладки.iter().map(|к| ширина(имя_раскладки(к), 2, Weight::Regular)).max().unwrap_or(0);
    let w = (ПОЛЕ * 2 + 20 + код_w + 14 + имя_w + 8).clamp(220, 420);
    let mut х = Холст::default();
    let mut y = х.раздел(ПОЛЕ, т!("РАСКЛАДКА", "KEYBOARD LAYOUT"), ц);
    for (i, код) in д.раскладки.iter().enumerate() {
        let цель = Цель::Раскладка(i);
        let активна = i == д.раскладка;
        let r = Rect { x: ПОЛЕ - 6, y, w: w - ПОЛЕ * 2 + 12, h: СТРОКА - 2 };
        if наведено(д, &цель) {
            х.плашка(r.x, r.y, r.w, r.h, 9, ц.наведение);
        }
        let d = 8;
        х.плашка(ПОЛЕ + 2, y + (r.h - d) / 2, d, d, d / 2, if активна { ц.акцент } else { ц.точка });
        let ty = y + (r.h - text::height(2)) / 2;
        х.текст(ПОЛЕ + 20, ty, код, 2, Weight::Semi, if активна { ц.текст } else { ц.тусклый });
        let имя_x = ПОЛЕ + 20 + код_w + 14;
        let имя = bar::fit_text(имя_раскладки(код), 2, w - ПОЛЕ - имя_x);
        х.текст(имя_x, ty, &имя, 2, Weight::Regular, ц.тусклый);
        х.цель(r, цель);
        y += СТРОКА;
    }
    Some(х.в(w, y + ПОЛЕ - 8))
}

