/// Куда встаёт карточка: под серединой якоря, не вылезая за края экрана.
pub fn цель_рамки(якорь: Rect, (w, h): (i32, i32), верх: i32, экран_w: i32) -> Rect {
    let край = bar::edge();
    let x = (якорь.x + якорь.w / 2 - w / 2).clamp(край, (экран_w - край - w).max(край));
    Rect { x, y: верх, w, h }
}

/// Карточка на этом кадре раскрытия: пока раскрывается, она чуть меньше и
/// чуть выше — выезжает из-под панели с лёгким перелётом, как предпросмотр.
pub fn рамка_на_доле(р: [f64; 4], доля: f64) -> Rect {
    let t = доля.clamp(0.0, 1.0);
    let k = МИН_K + (1.0 - МИН_K) * crate::anim::ease_out_back(t);
    let w = (р[2] * k).round().max(1.0);
    let h = (р[3] * k).round().max(1.0);
    let cx = р[0] + р[2] / 2.0;
    let подъём = (1.0 - crate::anim::ease_out_cubic(t)) * ПОДЪЁМ;
    Rect {
        x: (cx - w / 2.0).round() as i32,
        y: (р[1] - подъём).round() as i32,
        w: w as i32,
        h: h as i32,
    }
}

/// Насколько видна карточка при этой доле раскрытия (как `preview_fade`).
pub fn видимость(доля: f64) -> f32 {
    crate::anim::ease_out_cubic(доля.clamp(0.0, 1.0).powf(0.6)) as f32
}

fn внутри(r: Rect, в: Rect) -> bool {
    r.x >= в.x && r.y >= в.y && r.x + r.w <= в.x + в.w && r.y + r.h <= в.y + в.h
}

/// Окошко, поставленное на экран: карточка, её штрихи и цели в экранных
/// координатах. То, что в карточку на этом кадре не влезло (она ещё
/// раскрывается или едет к новому размеру), не рисуется и не нажимается.
#[derive(Clone, Debug)]
pub struct Кадр {
    pub карточка: Rect,
    pub штрихи: Vec<Штрих>,
    pub цели: Vec<(Rect, Цель)>,
    pub видимость: f32,
    /// Доля проявления содержимого после смены окошка (0…1).
    pub проявление: f32,
}

impl Кадр {
    pub fn содержит(&self, x: f64, y: f64) -> bool {
        self.карточка.hit(x, y)
    }

    pub fn цель_в(&self, x: f64, y: f64) -> Option<&Цель> {
        self.цели.iter().find(|(r, _)| r.hit(x, y)).map(|(_, ц)| ц)
    }
}

/// Поставить собранное окошко в карточку.
pub fn поставить(с: Содержимое, карточка: Rect) -> (Vec<Штрих>, Vec<(Rect, Цель)>) {
    let (dx, dy) = (карточка.x, карточка.y);
    let штрихи = с.штрихи.into_iter().filter_map(|mut ш| {
        ш.сдвинуть(dx, dy);
        внутри(ш.рамка(), карточка).then_some(ш)
    }).collect();
    let цели = с.цели.into_iter().filter_map(|(mut r, mut ц)| {
        r.x += dx;
        r.y += dy;
        ц.сдвинуть(dx);
        // Цель может быть чуть шире карточки (поле ползунка) — обрезаем, а не
        // выбрасываем: иначе ползунок не нажимался бы вовсе.
        let x0 = r.x.max(карточка.x);
        let x1 = (r.x + r.w).min(карточка.x + карточка.w);
        (r.y + r.h <= карточка.y + карточка.h && x1 > x0).then(|| (Rect { x: x0, y: r.y, w: x1 - x0, h: r.h }, ц))
    }).collect();
    (штрихи, цели)
}

fn шаг(тек: f64, цель: f64, dt: Duration, dur: f64) -> f64 {
    let s = dt.as_secs_f64() / (dur * crate::anim::tempo()).max(1e-3);
    if цель > тек { (тек + s).min(цель) } else { (тек - s).max(цель) }
}

// ── Состояние ────────────────────────────────────────────────────────────────

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Тащим {
    Громкость { x0: i32, w: i32 },
    Яркость { x0: i32, w: i32 },
}

#[derive(Debug, Default)]
pub struct Состояние {
    /// Что показываем (держится, пока карточка не свернётся до конца).
    pub что: Option<Окошко>,
    /// Цель раскрытия: открыто или сворачивается.
    pub открыто: bool,
    /// Доля раскрытия 0…1.
    pub доля: f64,
    /// Проявление содержимого после смены окошка 0…1.
    pub смена: f64,
    /// Карточка на этом кадре (x, y, w, h) — едет к цели.
    pub рамка: Option<[f64; 4]>,
    рамка_едет: bool,
    pub закреплено: bool,
    /// Курсор на самой карточке или в зазоре над ней.
    pub на_окошке: bool,
    ушли: Option<Instant>,
    pub наведено: Option<Цель>,
    pub месяц: i32,
    pub тащим: Option<Тащим>,
    /// Своё значение и до какого момента его держать.
    pub громкость: Option<(f32, Instant)>,
    pub яркость: Option<(f32, Instant)>,
    отправлено: Option<Instant>,
    ждёт: Option<Тащим>,
    колесо: f64,
    /// Закрыли щелчком или Esc, а курсор всё ещё на ячейке: не открывать
    /// снова, пока он с неё не уйдёт.
    подавить: Option<Окошко>,
    /// Что сказали потокам звука и питания: (звук, питание).
    следим: (bool, bool),
}

impl Состояние {
    pub fn следит_звук(&self) -> bool {
        self.следим.0
    }

    pub fn следит_питание(&self) -> bool {
        self.следим.1
    }

    /// Открыть `что` или перевести на него открытое окошко.
    fn навести(&mut self, что: Окошко) {
        if self.что == Some(что) {
            self.открыто = true;
            return;
        }
        if self.что.is_some() && self.доля > 0.0 {
            // Перетекание: карточка едет с места на место, содержимое
            // проявляется заново.
            self.смена = 0.0;
        } else {
            self.доля = 0.0;
            self.рамка = None;
            self.смена = 1.0;
        }
        if что == Окошко::Календарь {
            self.месяц = 0;
        }
        self.что = Some(что);
        self.наведено = None;
        self.открыто = true;
        self.ушли = None;
    }
}

// ── Сторона композитора ──────────────────────────────────────────────────────

impl crate::state::Parallax {
    pub fn всплывашки_вкл(&self) -> bool {
        bar::вид().popups
    }

    /// Можно ли сейчас показывать окошки: панель на месте, не обзор и не
    /// полный экран — ровно те условия, при которых видна сама панель.
    fn всплывашка_можно(&self) -> bool {
        self.всплывашки_вкл() && !self.overview_active && !self.fullscreen_here() && self.bar_hide < 0.5
    }

    fn всплывашка_цвета(&self) -> Цвета {
        let вид = bar::вид();
        // Акцент — оттенок обоев с каплей белого, той же формулой, что у
        // виджетов стола: сырой акцент палитры бывает темнее самих обоев и на
        // стекле пропадает.
        let акцент = match self.палитра_обоев.as_ref() {
            Some(п) => {
                let м = п.акцент[0].max(п.акцент[1]).max(п.акцент[2]).max(1e-3);
                let к = |c: f32| (c / м) * 0.8 + 0.2;
                [к(п.акцент[0]), к(п.акцент[1]), к(п.акцент[2]), 0.95]
            }
            None => Цвета::default().акцент,
        };
        Цвета { текст: вид.fg, тусклый: вид.dim, акцент, ..Цвета::default() }
    }

    fn всплывашка_раскладки(&self) -> Vec<String> {
        self.lua_config
            .xkb
            .layout
            .split(',')
            .map(|s| s.trim().to_uppercase())
            .filter(|s| !s.is_empty())
            .collect()
    }

    pub fn всплывашка_данные(&self) -> Данные {
        let с = &self.всплывашка;
        let время = bar::local_time().map(|tm| Время {
            год: tm.tm_year + 1900,
            месяц: tm.tm_mon + 1,
            день: tm.tm_mday,
            день_недели: (tm.tm_wday + 6) % 7,
            час: tm.tm_hour,
            мин: tm.tm_min,
        });
        let звук = self.audio_snapshot().map(|s| {
            let (громкость, немо) = s.volume().unwrap_or((0.0, false));
            let устройства = |список: &[crate::audio::Device]| {
                список
                    .iter()
                    .map(|d| Устройство { имя: d.name.clone(), подпись: d.description.clone(), основное: d.default })
                    .collect()
            };
            Звук {
                громкость: с.громкость.map(|(v, _)| v).unwrap_or(громкость),
                немо,
                выходы: устройства(&s.sinks),
                входы: устройства(&s.sources),
            }
        });
        let раскладки = self.всплывашка_раскладки();
        let раскладка = раскладки.iter().position(|к| *к == self.bar_kb).unwrap_or(0);
        Данные {
            время,
            месяц: с.месяц,
            звук,
            заряд: self
                .tray
                .as_ref()
                .and_then(|t| t.snap.battery.as_ref())
                .map(|b| (b.percent, b.charging)),
            питание: self.питание.as_ref().map(|п| п.снимок.clone()),
            раскладки,
            раскладка,
            трей: self
                .sni_items()
                .iter()
                .map(|i| if i.title.trim().is_empty() { i.id.clone() } else { i.title.clone() })
                .collect(),
            наведено: с.наведено.clone(),
            тащим_громкость: matches!(с.тащим, Some(Тащим::Громкость { .. })),
            тащим_яркость: matches!(с.тащим, Some(Тащим::Яркость { .. })),
            яркость: с.яркость.map(|(v, _)| v),
            цвета: self.всплывашка_цвета(),
        }
    }

    /// Есть ли у окошка содержимое — по тем же данным, по которым оно строится.
    fn всплывашка_есть(&self, что: Окошко) -> bool {
        match что {
            Окошко::Трей(i) => self
                .sni_items()
                .get(i)
                .is_some_and(|it| !it.title.trim().is_empty() || !it.id.trim().is_empty()),
            Окошко::Раскладка => self.всплывашка_раскладки().len() >= 2,
            _ => true,
        }
    }

    /// Ячейка (или остров), под которой встаёт окошко.
    fn всплывашка_якорь(&self, что: Окошко, lay: &bar::Layout) -> Option<Rect> {
        let ячейка = |c: Cell| lay.cells.iter().find(|i| i.cell == c).map(|i| i.rect);
        match что {
            // Под серединой центрального острова: у календаря две ячейки
            // (часы и дата), и встать под одну из них значило бы перекоситься.
            Окошко::Календарь => lay.center,
            Окошко::Звук => ячейка(Cell::Volume),
            Окошко::Питание => ячейка(Cell::Battery),
            Окошко::Раскладка => ячейка(Cell::Kb),
            Окошко::Трей(i) => ячейка(Cell::Tray(i)),
        }
    }

    /// Куда едет карточка этого окошка и что в ней.
    fn всплывашка_цель(&self, что: Окошко, д: &Данные) -> Option<(Rect, Содержимое)> {
        let lay = bar::layout(&self.bar_data());
        let якорь = self.всплывашка_якорь(что, &lay)?;
        let с = собрать(что, д)?;
        let верх = bar::island_y(self.bar_hide) + bar::h() + ЗАЗОР;
        Some((цель_рамки(якорь, (с.w, с.h), верх, self.screen_size().w), с))
    }

    /// Окошко на этом кадре. Одна точка правды на отрисовку и на ввод.
    pub fn всплывашка_кадр(&self) -> Option<Кадр> {
        let с = &self.всплывашка;
        let что = с.что?;
        if с.доля <= 0.0 {
            return None;
        }
        let д = self.всплывашка_данные();
        let (цель, содержимое) = self.всплывашка_цель(что, &д)?;
        let рамка = с.рамка.unwrap_or([цель.x as f64, цель.y as f64, цель.w as f64, цель.h as f64]);
        let карточка = рамка_на_доле(рамка, с.доля);
        let (штрихи, цели) = поставить(содержимое, карточка);
        let проявление = if с.смена >= 1.0 {
            1.0
        } else {
            // Содержимое начинает проявляться почти сразу: дольше пустая
            // карточка на ходу читается как «не успело нарисоваться».
            crate::anim::smoothstep(((с.смена - 0.15) / 0.85).clamp(0.0, 1.0)) as f32
        };
        Some(Кадр { карточка, штрихи, цели, видимость: видимость(с.доля), проявление })
    }

    /// Лежит ли точка на карточке (то, что нарисовано, то и ловит мышь).
    pub fn всплывашка_над(&self, pos: Point<f64, Physical>) -> bool {
        self.всплывашка_кадр().is_some_and(|к| к.содержит(pos.x, pos.y))
    }

    /// Курсор поехал (зовёт `bar_hover_update`): на карточке ли он — с
    /// зазором над ней, иначе окошко гасло бы ровно посреди пути к нему, — и
    /// что в ней под ним.
    pub fn всплывашка_наведение(&mut self, pos: Point<f64, Physical>) {
        let (держит, цель) = match self.всплывашка_кадр() {
            Some(к) => {
                let r = к.карточка;
                let верх = (r.y - ЗАЗОР - 2) as f64;
                let держит = pos.x >= r.x as f64
                    && pos.x <= (r.x + r.w) as f64
                    && pos.y >= верх
                    && pos.y <= (r.y + r.h) as f64;
                (держит, к.цель_в(pos.x, pos.y).cloned())
            }
            None => (false, None),
        };
        let с = &mut self.всплывашка;
        let та_же = match (&с.наведено, &цель) {
            (Some(a), Some(b)) => a.тот_же(b),
            (None, None) => true,
            _ => false,
        };
        if с.на_окошке != держит || !та_же {
            с.на_окошке = держит;
            с.наведено = цель;
            self.request_redraw();
        }
    }

    /// Лежит ли точка на ячейке панели, под которой стоит открытое окошко.
    fn всплывашка_над_якорем(&self, pos: Point<f64, Physical>) -> bool {
        let Some(что) = self.всплывашка.что else { return false };
        let lay = bar::layout(&self.bar_data());
        lay.hit(pos.x, pos.y).and_then(Окошко::для) == Some(что)
    }

    pub fn всплывашка_закрыть(&mut self) {
        let с = &mut self.всплывашка;
        с.открыто = false;
        с.закреплено = false;
        с.тащим = None;
        с.подавить = с.что;
        self.request_redraw();
    }

    /// Щелчок по ячейке панели (зовёт `bar_click`). true — щелчок наш:
    /// часы, звук и заряд закрепляют своё окошко, повторный щелчок закрывает.
    pub fn всплывашка_щелчок_по_ячейке(&mut self, cell: Cell, правая: bool, средняя: bool) -> bool {
        if правая || средняя || !self.всплывашка_можно() {
            return false;
        }
        let Some(что) = Окошко::для(cell).filter(|ч| ч.закрепляется()) else { return false };
        if !self.всплывашка_есть(что) {
            return false;
        }
        let с = &self.всплывашка;
        if с.что == Some(что) && с.открыто && с.закреплено {
            self.всплывашка_закрыть();
            return true;
        }
        let с = &mut self.всплывашка;
        с.подавить = None;
        с.навести(что);
        с.закреплено = true;
        self.всплывашка_следить();
        self.request_redraw();
        true
    }

    /// Кнопка мыши. true — событие наше.
    pub fn всплывашка_кнопка(&mut self, pos: Point<f64, Physical>, левая: bool, нажата: bool) -> bool {
        if !нажата {
            // Отпустили ползунок — последнее значение уходит сразу, без
            // ожидания шага отправки.
            if let Some(т) = self.всплывашка.тащим.take() {
                self.всплывашка.ждёт = None;
                self.всплывашка_послать(т);
                self.request_redraw();
                return true;
            }
            return false;
        }
        let Some(к) = self.всплывашка_кадр() else { return false };
        if !к.содержит(pos.x, pos.y) {
            // Мимо: закреплённое закрывается, но щелчок не съедаем — его
            // получит то, во что попали. Щелчок по самой ячейке разбирает
            // `всплывашка_щелчок_по_ячейке` (там он закрывает окошко).
            if self.всплывашка.закреплено && !self.всплывашка_над_якорем(pos) {
                self.всплывашка_закрыть();
            }
            return false;
        }
        if левая {
            if let Some(ц) = к.цель_в(pos.x, pos.y).cloned() {
                self.всплывашка_нажать(ц, pos.x);
            }
        }
        self.request_redraw();
        true
    }

    fn всплывашка_нажать(&mut self, ц: Цель, x: f64) {
        use crate::audio::Cmd as Ак;
        use crate::питание::Cmd as Пк;
        match ц {
            Цель::МесяцНазад => self.всплывашка.месяц -= 1,
            Цель::МесяцВперёд => self.всплывашка.месяц += 1,
            Цель::МесяцСейчас => self.всплывашка.месяц = 0,
            Цель::Громкость { x0, w } => {
                self.всплывашка.тащим = Some(Тащим::Громкость { x0, w });
                self.всплывашка_тянуть(x);
            }
            Цель::Яркость { x0, w } => {
                self.всплывашка.тащим = Some(Тащим::Яркость { x0, w });
                self.всплывашка_тянуть(x);
            }
            Цель::Немота => self.audio_send(Ак::MuteToggle),
            Цель::Выход(name) => self.audio_send(Ак::SetDefault { sink: true, name }),
            Цель::Вход(name) => self.audio_send(Ак::SetDefault { sink: false, name }),
            Цель::Профиль(имя) => self.питание_послать(Пк::Профиль(имя)),
            Цель::Подсветка => self.питание_послать(Пк::КлавиатураКруг),
            Цель::Раскладка(i) => self.всплывашка_раскладка_на(i),
        }
    }

    /// Поставить раскладку с номером `i` — тем же действием, что Alt+Shift:
    /// у xkb нет «поставь третью», есть «следующая».
    fn всплывашка_раскладка_на(&mut self, i: usize) {
        let раскладки = self.всплывашка_раскладки();
        for _ in 0..раскладки.len() {
            if раскладки.iter().position(|к| *к == self.bar_kb) == Some(i) {
                break;
            }
            self.dispatch_action(crate::config::Action::LayoutNext);
        }
    }

    /// Курсор двинулся (зовёт input.rs): ведём ползунок, если его держат.
    pub fn всплывашка_движение(&mut self, pos: Point<f64, Physical>) {
        if self.всплывашка.тащим.is_some() {
            self.всплывашка_тянуть(pos.x);
        }
    }

    fn всплывашка_тянуть(&mut self, x: f64) {
        let Some(т) = self.всплывашка.тащим else { return };
        let (x0, w) = match т {
            Тащим::Громкость { x0, w } | Тащим::Яркость { x0, w } => (x0, w),
        };
        let доля = ((x - x0 as f64) / w.max(1) as f64).clamp(0.0, 1.0) as f32;
        let до = Instant::now() + ДЕРЖИМ_ПОКАЗ;
        match т {
            Тащим::Громкость { .. } => self.всплывашка.громкость = Some((доля, до)),
            Тащим::Яркость { .. } => self.всплывашка.яркость = Some((доля, до)),
        }
        let пора = self.всплывашка.отправлено.is_none_or(|t| t.elapsed() >= ШАГ_ОТПРАВКИ);
        if пора {
            self.всплывашка_послать(т);
        } else {
            self.всплывашка.ждёт = Some(т);
        }
        self.request_redraw();
    }

    fn всплывашка_послать(&mut self, т: Тащим) {
        self.всплывашка.отправлено = Some(Instant::now());
        match т {
            Тащим::Громкость { .. } => {
                if let Some((v, _)) = self.всплывашка.громкость {
                    self.audio_send(crate::audio::Cmd::SetVolume(v));
                }
            }
            Тащим::Яркость { .. } => {
                if let Some((v, _)) = self.всплывашка.яркость {
                    self.питание_послать(crate::питание::Cmd::Экран(v));
                }
            }
        }
    }

    /// Колесо над окошком или над его ячейкой панели: месяц, громкость,
    /// яркость, раскладка. true — колесо наше.
    pub fn всплывашка_колесо(&mut self, pos: Point<f64, Physical>, v: f64) -> bool {
        if v == 0.0 || !self.всплывашка_можно() {
            return false;
        }
        let что = if self.всплывашка_над(pos) {
            self.всплывашка.что
        } else {
            self.bar_hover.and_then(Окошко::для)
        };
        let Some(что) = что else { return false };
        if matches!(что, Окошко::Трей(_)) {
            return false;
        }
        // Тачпад шлёт прокрутку мелкими порциями — копим до щелчка колеса.
        let с = &mut self.всплывашка;
        с.колесо += v;
        let шагов = (с.колесо / КОЛЕСО).trunc() as i32;
        if шагов == 0 {
            return true;
        }
        с.колесо -= шагов as f64 * КОЛЕСО;
        // v > 0 — колесо к себе: месяц вперёд, громкость и яркость тише.
        let до = Instant::now() + ДЕРЖИМ_ПОКАЗ;
        match что {
            Окошко::Календарь => self.всплывашка.месяц += шагов,
            Окошко::Звук => {
                let было = self
                    .всплывашка
                    .громкость
                    .map(|(v, _)| v)
                    .or_else(|| self.audio_snapshot().and_then(|s| s.volume()).map(|(v, _)| v))
                    .unwrap_or(0.0);
                let стало = (было - ШАГ * шагов as f32).clamp(0.0, 1.0);
                self.всплывашка.громкость = Some((стало, до));
                self.audio_send(crate::audio::Cmd::SetVolume(стало));
            }
            Окошко::Питание => {
                let экран = self.питание.as_ref().and_then(|п| п.снимок.экран.clone());
                let Some(экран) = экран.filter(|э| э.пишется) else { return true };
                let было = self
                    .всплывашка
                    .яркость
                    .map(|(v, _)| v)
                    .unwrap_or_else(|| crate::питание::доля_на_глаз(&экран));
                let стало = (было - ШАГ * шагов as f32).clamp(0.0, 1.0);
                self.всплывашка.яркость = Some((стало, до));
                self.питание_послать(crate::питание::Cmd::Экран(стало));
            }
            Окошко::Раскладка => {
                let действие = if шагов > 0 {
                    crate::config::Action::LayoutNext
                } else {
                    crate::config::Action::LayoutPrev
                };
                for _ in 0..шагов.unsigned_abs() {
                    self.dispatch_action(действие.clone());
                }
            }
            Окошко::Трей(_) => {}
        }
        self.request_redraw();
        true
    }

    /// Esc: закрыть закреплённое окошко. Незакреплённое (просто наведено) Esc
    /// не трогает — клавиша принадлежит окну, мышь лишь проходила мимо.
    pub fn всплывашка_esc(&mut self) -> bool {
        if self.всплывашка.закреплено && self.всплывашка.открыто {
            self.всплывашка_закрыть();
            return true;
        }
        false
    }

    /// Сказать потокам звука и питания, что их окошко открыто: открытое
    /// опрашивается чаще (звук — раз в 0.8 с вместо 5, питание — вообще только
    /// пока на него смотрят).
    fn всплывашка_следить(&mut self) {
        let что = if self.всплывашка.открыто { self.всплывашка.что } else { None };
        let нужно = (что == Some(Окошко::Звук), что == Some(Окошко::Питание));
        if self.всплывашка.следим == нужно {
            return;
        }
        self.всплывашка.следим = нужно;
        self.audio_sync_watch();
        let меню = self.питание_открыто();
        self.питание_послать(crate::питание::Cmd::Смотреть(меню || нужно.1));
    }

    /// Движется ли что-нибудь у окошек — для `anim_busy`.
    pub fn всплывашка_занята(&self) -> bool {
        let с = &self.всплывашка;
        let цель = if с.открыто && с.что.is_some() { 1.0 } else { 0.0 };
        с.доля != цель
            || с.смена < 1.0
            || с.рамка_едет
            || с.ушли.is_some()
            || с.ждёт.is_some()
            || с.громкость.is_some()
            || с.яркость.is_some()
    }

    /// Шаг анимации (зовёт `anim::tick`). true — кадр нужно перерисовать.
    pub fn всплывашка_тик(&mut self, dt: Duration) -> bool {
        let можно = self.всплывашка_можно();
        let наведено = if можно {
            self.bar_hover.and_then(Окошко::для).filter(|к| self.всплывашка_есть(*к))
        } else {
            None
        };
        let now = Instant::now();
        let mut dirty = false;
        {
            let с = &mut self.всплывашка;
            if с.подавить.is_some() && наведено != с.подавить {
                с.подавить = None;
            }
            let наведено = наведено.filter(|к| с.подавить != Some(*к));
            let держит = с.на_окошке || с.тащим.is_some();
            if !можно {
                if с.открыто {
                    с.открыто = false;
                    с.закреплено = false;
                    dirty = true;
                }
            } else if let Some(к) = наведено {
                if с.что != Some(к) || !с.открыто {
                    с.навести(к);
                    dirty = true;
                }
                с.ушли = None;
            } else if держит || с.закреплено {
                с.ушли = None;
            } else if с.открыто {
                match с.ушли {
                    None => с.ушли = Some(now),
                    Some(t) if now.duration_since(t) >= ЖДЁМ_УХОДА => {
                        с.открыто = false;
                        с.ушли = None;
                        dirty = true;
                    }
                    Some(_) => {}
                }
            } else {
                с.ушли = None;
            }

            let цель = if с.открыто && с.что.is_some() { 1.0 } else { 0.0 };
            if с.доля != цель {
                с.доля = шаг(с.доля, цель, dt, ДОЛЯ_DUR);
                dirty = true;
            }
            if с.доля <= 0.0 && !с.открыто && с.что.is_some() {
                // Свернулось до конца — забываем всё, кроме того, что живёт
                // дольше одного показа.
                *с = Состояние { следим: с.следим, подавить: с.подавить, ..Default::default() };
                dirty = true;
            }
            if с.смена < 1.0 {
                с.смена = (с.смена + dt.as_secs_f64() / (СМЕНА_DUR * crate::anim::tempo()).max(1e-3)).min(1.0);
                dirty = true;
            }
            if с.громкость.is_some_and(|(_, до)| now >= до) && !matches!(с.тащим, Some(Тащим::Громкость { .. })) {
                с.громкость = None;
                dirty = true;
            }
            if с.яркость.is_some_and(|(_, до)| now >= до) && !matches!(с.тащим, Some(Тащим::Яркость { .. })) {
                с.яркость = None;
                dirty = true;
            }
        }

        // Ползунок тянули чаще шага отправки — досылаем последнее значение.
        if let Some(т) = self.всплывашка.ждёт {
            if self.всплывашка.отправлено.is_none_or(|t| t.elapsed() >= ШАГ_ОТПРАВКИ) {
                self.всплывашка.ждёт = None;
                self.всплывашка_послать(т);
            }
        }

        // Карточка едет к цели. Цель меняется не только сменой окошка: пришёл
        // снимок звука с другим числом устройств — карточка плавно меняет рост.
        if let Some(что) = self.всплывашка.что {
            let д = self.всплывашка_данные();
            if let Some((цель, _)) = self.всплывашка_цель(что, &д) {
                let ц = [цель.x as f64, цель.y as f64, цель.w as f64, цель.h as f64];
                let с = &mut self.всплывашка;
                match с.рамка {
                    None => {
                        с.рамка = Some(ц);
                        dirty = true;
                    }
                    Some(р) => {
                        let t = 1.0 - (-dt.as_secs_f64() / (РАМКА_TAU * crate::anim::tempo()).max(1e-3)).exp();
                        let mut н = р;
                        let mut едет = false;
                        for i in 0..4 {
                            let d = ц[i] - р[i];
                            if d.abs() > 0.4 {
                                н[i] = р[i] + d * t;
                                едет = true;
                            } else {
                                н[i] = ц[i];
                            }
                        }
                        if н != р {
                            с.рамка = Some(н);
                            dirty = true;
                        }
                        с.рамка_едет = едет;
                    }
                }
            }
        } else {
            self.всплывашка.рамка_едет = false;
        }

        self.всплывашка_следить();
        dirty
    }
}

