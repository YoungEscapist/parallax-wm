    /// Ручка тумблера стоит по `тумблер_*`: выключенный — у левого края
    /// дорожки, включённый — у правого.
    #[test]
    fn ручка_тумблера_едет() {
        let ручка_x = |t: f32| {
            let д = Данные { тумблер_вайфай: t, ..данные() };
            let с = собрать(Окошко::Вайфай, &д).unwrap();
            let (r, _) = с.цели.iter().find(|(_, ц)| *ц == Цель::ВайфайРадио).cloned().unwrap();
            с.штрихи.iter().filter_map(|ш| match ш {
                Штрих::Плашка { r: п, цвет, .. } if *цвет == д.цвета.ручка && п.y >= r.y && п.y + п.h <= r.y + r.h => Some(п.x),
                _ => None,
            }).next().expect("ручка")
        };
        let (выкл, середина, вкл) = (ручка_x(0.0), ручка_x(0.5), ручка_x(1.0));
        assert!(выкл < середина && середина < вкл, "{выкл} {середина} {вкл}");
        assert_eq!(вкл - выкл, ТУМБЛЕР_W - ТУМБЛЕР_H);
    }

