//! Мышь и камера с клавиатуры: указатель, кнопки, колесо, пан и зум холста.
//!
//! **Зачем.** Клавиатурой в parallax делалось почти всё, кроме одного — самого
//! указателя. Любое действие, которое живёт под курсором (полка панели, чипы
//! бара, миникарта, карточка предпросмотра, контекстное меню приложения,
//! выделение области для снимка, драг окна), требовало руки на мыши. Отдельного
//! «режима мыши», как в vimium, здесь нарочно нет: это обычные действия
//! `bind{}`, их можно повесить куда угодно и раздать жестам и шлему — см.
//! [`crate::config::Action`].
//!
//! **Почему через синтетику.** Ставить `pointer_location` руками нельзя: до
//! smithay в parallax живёт половина поведения указателя — пан у края экрана,
//! зажим в видимую область, драг миникарты, наведение на чипы панели, sloppy
//! focus. Поэтому клавиши входят в ту же дверь, что и настоящая мышь, —
//! `process_input_event` с событиями из [`crate::synth`]; ровно так же устроен
//! харнесс (`mouse to|click|scroll` в ctl.rs) и сенсорный экран.
//!
//! **Почему удержание считается здесь, а не автоповтором клавиатуры.**
//! Автоповтора у композитора НЕТ: libinput отдаёт ровно два события на клавишу
//! — нажатие и отпускание, а повтор рисует уже клиент, получив от нас
//! `repeat_info`. То есть «зажать Alt+L и ехать» через бинды не выражается
//! вовсе: бинд сработал бы один раз, и курсор сдвинулся бы на один шаг.
//! Поэтому нажатие ВЗВОДИТ ход ([`Ход`]), а двигает его тик анимаций
//! (`anim::tick`, 60 Гц) — тот же, что ведёт автодовод курсора у края накладки
//! тачпада, и по той же причине: на неподвижном экране другого повода
//! пошевелить курсор в композиторе нет.
//!
//! **Разгон.** Первое нажатие двигает ровно на свой шаг — тычок обязан быть
//! точным до пикселя. Дальше, если клавишу держат дольше [`ЗАДЕРЖКА`],
//! начинается ход: скорость растёт от [`ШАГОВ_В_СЕК`] шагов в секунду до
//! [`ПОТОЛОК`]-кратной за [`РАЗГОН`] и дальше держится. С шагом 12 px это от
//! 360 до 3240 px/с — 4K-экран пересекается примерно за полторы секунды, а
//! короткое касание остаётся ювелирным.

use std::time::{Duration, Instant};

use smithay::backend::input::InputEvent;

use crate::state::Parallax;
use crate::synth::{Движение, Кнопка, Колесо, Синтетика};
use crate::т;

/// Сколько держать клавишу, прежде чем ход тронется. Примерно как задержка
/// автоповтора в терминале: короче — и одиночный тычок уезжал бы дальше, чем
/// просили.
pub const ЗАДЕРЖКА: Duration = Duration::from_millis(220);
/// Шагов в секунду на старте хода.
const ШАГОВ_В_СЕК: f64 = 30.0;
/// Во сколько раз скорость вырастает к концу разгона.
const ПОТОЛОК: f64 = 9.0;
/// За сколько скорость доходит до потолка.
const РАЗГОН: Duration = Duration::from_millis(800);
/// Как часто повторяется ход КАМЕРЫ. Камера едет своей анимацией с накоплением
/// цели (`zoom_nav_pan`), и подталкивать её каждый кадр незачем — от этого
/// цель убегала бы вперёд быстрее, чем камера успевает доехать.
const ШАГ_КАМЕРЫ: Duration = Duration::from_millis(110);
/// Как часто крутится зажатое колесо на старте хода. С разгоном период
/// ужимается до трети: быстрее колесо не нужно — страница листается быстрее,
/// чем её успевают читать.
const ШАГ_КОЛЕСА: Duration = Duration::from_millis(70);
/// Во сколько раз зажатое колесо ускоряется к концу разгона.
const ПОТОЛОК_КОЛЕСА: f64 = 3.0;

/// Множитель скорости хода, прошедшего `прошло` от своего начала (не считая
/// [`ЗАДЕРЖКА`]). Отдельной функцией — чтобы разгон проверялся тестом, а не
/// глазами по экрану.
fn множитель(прошло: Duration) -> f64 {
    let t = (прошло.as_secs_f64() / РАЗГОН.as_secs_f64()).clamp(0.0, 1.0);
    1.0 + (ПОТОЛОК - 1.0) * t
}

/// Что делает зажатая клавиша.
#[derive(Clone, Copy, Debug)]
enum Что {
    /// Курсор: направление и шаг в экранных пикселях.
    Курсор { dx: f64, dy: f64, шаг: f64 },
    /// Камера по холсту: направление.
    Камера { dx: f64, dy: f64 },
    /// Колесо: зубцы за один толчок.
    Колесо { гор: f64, верт: f64 },
    /// Зум у курсора: множитель одного щелчка.
    Зум { множитель: f64 },
}

/// Взведённый ход: какая клавиша его держит, что он двигает и с каких пор.
#[derive(Clone, Copy, Debug)]
struct Ход {
    /// Keysym (латинский), по отпусканию которого ход кончается.
    клавиша: u32,
    что: Что,
    /// Когда клавишу нажали — от этого считается [`ЗАДЕРЖКА`].
    нажата: Instant,
    /// Когда ход двигали в последний раз.
    тронут: Instant,
    /// Тронулся ли ход вообще (задержка вышла). Нужен, чтобы отсчитывать
    /// разгон от НАЧАЛА ХОДА, а не от нажатия.
    пошёл: Option<Instant>,
}

/// Куда поставить курсор по `pointer_warp`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Цель {
    /// Центр окна в фокусе.
    Окно,
    /// Центр экрана.
    Экран,
    /// Правый остров панели — оттуда открывается полка состояния.
    Панель,
}

impl Цель {
    pub fn разобрать(s: &str) -> Option<Цель> {
        match s.trim().to_ascii_lowercase().as_str() {
            "window" | "окно" | "focus" => Some(Цель::Окно),
            "screen" | "экран" | "center" | "центр" => Some(Цель::Экран),
            "bar" | "панель" | "tray" | "полка" => Some(Цель::Панель),
            _ => None,
        }
    }
}

/// Состояние клавиатурной мыши: идущий ход и кнопки, зажатые `pointer_drag`.
#[derive(Debug, Default)]
pub struct КлавиМышь {
    /// Клавиша, которую разбирают ПРЯМО СЕЙЧАС. Ставится в input.rs перед
    /// вызовом действия: сам `Action` клавиши не знает (и знать не должен —
    /// его же зовут жесты, шлем и сокет), а ход обязан кончиться ровно с её
    /// отпусканием.
    текущая: Option<u32>,
    ход: Option<Ход>,
    /// Кнопки, которые держит `pointer_drag` (evdev-коды). Их надо помнить:
    /// отпускает их повторное нажатие того же бинда, а не отпускание клавиши.
    зажаты: Vec<u32>,
    /// Кнопка, которую держит КЛАВИША `pointer_click`: (keysym, evdev-код).
    /// Нажатие клавиши прижимает кнопку, отпускание — отпускает. Живёт отдельно
    /// от хода: пока держат Alt+Enter, Alt+HJKL обязаны возить курсор, не
    /// отпуская кнопку, — это и есть драг одной рукой без тумблера.
    кнопка: Option<(u32, u32)>,
    /// Идёт ли сейчас СВОЁ синтетическое событие. Все бинды клавимыши висят
    /// на Alt, и он зажат в ту самую минуту, когда событие входит в
    /// `process_input_event`. А там Alt+ЛКМ во Float — пан холста, Alt+колесо —
    /// зум: клик Alt+Enter молча становился паном, прокрутка Alt+E — зумом, и до
    /// окна не доходило ни то, ни другое. Пока флаг стоит, input.rs считает Alt
    /// отпущенным (см. [`Parallax::alt_для_мыши`]).
    шлёт: bool,
}

impl Parallax {
    /// Какую клавишу разбираем сейчас (см. [`КлавиМышь::текущая`]). Зовётся из
    /// `input.rs` перед `dispatch_action`.
    /// Отдана ли клавиатурная мышь окну в фокусе
    /// (`set{ keymouse_block_apps = {...} }`).
    ///
    /// **Зачем.** В Dota 2 на Alt висит половина игры — пинг Alt+кликом,
    /// сообщения о способностях, обзор Alt+стрелками, — а клавиатурная мышь
    /// забирает эти сочетания себе целиком. Внутри матча это выглядит как
    /// «vim-режим включён и не выключается»: игра не получает ни одного Alt.
    ///
    /// Отнимаются ровно семь действий клавиатурной мыши, и только пока окно
    /// игры в фокусе; все остальные бинды (столы, обзор, поиск окон) работают
    /// как работали. Сравнение без учёта регистра — по тем же соображениям, что
    /// и у `keyboard_grab_apps`: класс окна пишут кто во что горазд.
    pub(crate) fn клавимышь_отдана_окну(&self, действие: &crate::config::Action) -> bool {
        use crate::config::Action::*;
        if !matches!(
            действие,
            PointerMove(..)
                | PointerClick(..)
                | PointerDrag(..)
                | PointerScroll(..)
                | PointerWarp(..)
                | CameraPan(..)
                | CameraZoom(..)
        ) {
            return false;
        }
        if self.lua_config.keymouse_block_apps.is_empty() {
            return false;
        }
        let Some(окно) = self.focused_window() else { return false };
        let Some(класс) = crate::xwin::app_id(&окно) else { return false };
        self.lua_config
            .keymouse_block_apps
            .iter()
            .any(|имя| имя.eq_ignore_ascii_case(&класс))
    }

    /// `None` — действие разобрано, клавиши больше нет. Без сброса ход
    /// взвёлся бы и от сокета/жеста — на давно отпущенной клавише, и ехал бы
    /// до первого нажатия чего угодно.
    pub(crate) fn клавимышь_клавиша(&mut self, keysym: Option<u32>) {
        self.клавимышь.текущая = keysym;
    }

    /// Отпустили клавишу. `true` — она держала ход или кнопку, и они кончились
    /// (тогда отпускание клиенту не отдаётся: нажатие он тоже не видел).
    pub(crate) fn клавимышь_отпущена(&mut self, keysym: u32) -> bool {
        let mut своя = false;
        if self.клавимышь.ход.is_some_and(|х| х.клавиша == keysym) {
            self.клавимышь.ход = None;
            своя = true;
        }
        if let Some((клавиша, код)) = self.клавимышь.кнопка {
            if клавиша == keysym {
                self.клавимышь.кнопка = None;
                self.курсор_кнопка(код, false);
                своя = true;
            }
        }
        своя
    }

    /// Заперта ли камера для клавиатурной мыши: пан и зум в tiling и в ленте
    /// колонок (niri) отняты — по тому же правилу, что у тачпада
    /// ([`Parallax::touchpad_camera_allowed`]): в Tile окна разложены под экран
    /// и возить холст под ними незачем, а в Columns вид ходит по полосе своими
    /// клавишами, и свободный пан уводил его в пустоту мимо колонок. Обзор и
    /// лупа — исключение, там вид оторван от раскладки.
    ///
    /// Сброс к 1:1 (`zoom_camera { reset }`) не заперт: это выход из зума, а
    /// не зум.
    pub(crate) fn клавимышь_камера_заперта(&self, действие: &crate::config::Action) -> bool {
        use crate::config::Action::*;
        match действие {
            CameraPan(..) => !self.touchpad_camera_allowed(),
            CameraZoom(м) if *м > 0.0 => !self.touchpad_camera_allowed(),
            _ => false,
        }
    }

    /// Любое другое нажатие или отпускание обрывает ход: отпустили Alt —
    /// поехали дальше без модификатора, нажали соседнюю клавишу — поехали в
    /// другую сторону. Иначе курсор продолжал бы ехать сам по себе.
    pub(crate) fn клавимышь_чужая_клавиша(&mut self, keysym: u32) {
        if self.клавимышь.ход.is_some_and(|х| х.клавиша != keysym) {
            self.клавимышь.ход = None;
        }
    }

    /// Alt с точки зрения мыши: зажат на клавиатуре и событие — не своё
    /// синтетическое (см. [`КлавиМышь::шлёт`]).
    pub(crate) fn alt_для_мыши(&self, alt: bool) -> bool {
        alt && !self.клавимышь.шлёт
    }

    /// Идёт ли ход. Тик анимаций обязан оставаться частым, пока идёт (см.
    /// `anim::anim_busy`).
    pub fn клавимышь_идёт(&self) -> bool {
        self.клавимышь.ход.is_some()
    }

    /// Кадр хода: двигает курсор или камеру, пока клавишу держат. Зовётся из
    /// `anim::tick` (60 Гц).
    pub fn клавимышь_тик(&mut self) {
        let Some(mut ход) = self.клавимышь.ход else { return };
        let сейчас = Instant::now();
        if сейчас.duration_since(ход.нажата) < ЗАДЕРЖКА {
            return;
        }
        // Первый кадр после задержки только отмечает начало хода: считать от
        // него дельту времени нельзя — за задержку набежало 220 мс, и курсор
        // прыгнул бы сразу на четверть экрана.
        if ход.пошёл.is_none() {
            ход.пошёл = Some(сейчас);
            ход.тронут = сейчас;
            self.клавимышь.ход = Some(ход);
            return;
        }
        let пошёл = ход.пошёл.unwrap_or(сейчас);
        let с_толчка = сейчас.duration_since(ход.тронут);

        match ход.что {
            Что::Курсор { dx, dy, шаг } => {
                ход.тронут = сейчас;
                self.клавимышь.ход = Some(ход);
                let скорость = шаг * ШАГОВ_В_СЕК * множитель(сейчас.duration_since(пошёл));
                let к = скорость * с_толчка.as_secs_f64();
                self.двинуть_курсор(dx * к, dy * к);
            }
            // Камеру толкаем реже кадра: `zoom_nav_pan` копит цель, и толчок
            // каждый кадр уносил бы её быстрее, чем камера успевает доехать.
            Что::Камера { dx, dy } => {
                if с_толчка < ШАГ_КАМЕРЫ {
                    return;
                }
                ход.тронут = сейчас;
                self.клавимышь.ход = Some(ход);
                // Раскладку могли сменить посреди хода жестом или с сокета —
                // клавишу при этом никто не трогал, и ход сам бы не кончился.
                if !self.touchpad_camera_allowed() {
                    self.клавимышь.ход = None;
                    return;
                }
                self.zoom_nav_pan(dx, dy);
            }
            Что::Колесо { гор, верт } => {
                let ускорение = множитель(сейчас.duration_since(пошёл)).min(ПОТОЛОК_КОЛЕСА);
                if с_толчка.as_secs_f64() < ШАГ_КОЛЕСА.as_secs_f64() / ускорение {
                    return;
                }
                ход.тронут = сейчас;
                self.клавимышь.ход = Some(ход);
                self.крутнуть_колесо(гор, верт);
            }
            Что::Зум { множитель } => {
                if с_толчка < ШАГ_КАМЕРЫ {
                    return;
                }
                ход.тронут = сейчас;
                self.клавимышь.ход = Some(ход);
                if !self.touchpad_camera_allowed() {
                    self.клавимышь.ход = None;
                    return;
                }
                self.zoom_step_at_cursor(множитель);
            }
        }
    }

    /// Шаг указателя. `dx`,`dy` — направление (обычно ±1), `шаг` — сколько
    /// экранных пикселей за одно нажатие. Нажатие двигает ровно на шаг и
    /// взводит ход: держат клавишу — курсор едет дальше и с разгоном.
    pub fn курсор_шаг(&mut self, dx: f64, dy: f64, шаг: f64) {
        self.двинуть_курсор(dx * шаг, dy * шаг);
        self.взвести(Что::Курсор { dx, dy, шаг });
    }

    /// Клик. С клавиатуры кнопка держится, пока держат клавишу, и отпускается
    /// вместе с ней ([`Parallax::клавимышь_отпущена`]): тычок — обычный клик,
    /// удержание — зажатая кнопка, под которой можно возить курсор теми же
    /// Alt+HJKL (выделение текста, драг окна, долгое нажатие). От жеста, шлема
    /// и сокета клавиши нет — там нажать и сразу отпустить.
    pub fn курсор_клик(&mut self, код: u32) {
        // Прошлое отпускание потерялось (сменили VT посреди удержания) —
        // не копим прижатую кнопку, а отпускаем её перед новым нажатием.
        if let Some((_, старый)) = self.клавимышь.кнопка.take() {
            self.курсор_кнопка(старый, false);
        }
        self.курсор_кнопка(код, true);
        match self.клавимышь.текущая {
            Some(клавиша) => self.клавимышь.кнопка = Some((клавиша, код)),
            None => self.курсор_кнопка(код, false),
        }
    }

    /// Тумблер удержания кнопки: первое нажатие бинда прижимает её, второе
    /// отпускает. Именно тумблером, а не «пока держат клавишу»: драг окна —
    /// это зажатая кнопка ПЛЮС движение, а движение здесь идёт другими
    /// клавишами, и удерживать их все разом было бы нечем.
    pub fn курсор_держать(&mut self, код: u32) {
        if let Some(i) = self.клавимышь.зажаты.iter().position(|&к| к == код) {
            self.клавимышь.зажаты.remove(i);
            self.курсор_кнопка(код, false);
            self.уведомить(т!("Мышь: кнопка отпущена", "Mouse: button released"));
        } else {
            self.клавимышь.зажаты.push(код);
            self.курсор_кнопка(код, true);
            self.уведомить(т!("Мышь: кнопка зажата", "Mouse: button held"));
        }
    }

    /// Колесо: `гор`/`верт` — зубцы (вниз и вправо положительны).
    /// Держат клавишу — колесо крутится дальше, с разгоном до
    /// [`ПОТОЛОК_КОЛЕСА`].
    pub fn курсор_колесо(&mut self, гор: f64, верт: f64) {
        self.крутнуть_колесо(гор, верт);
        self.взвести(Что::Колесо { гор, верт });
    }

    fn крутнуть_колесо(&mut self, гор: f64, верт: f64) {
        self.клавимышь.шлёт = true;
        self.process_input_event(InputEvent::PointerAxis::<Синтетика> {
            event: Колесо::по_осям(гор, верт),
        });
        self.клавимышь.шлёт = false;
        self.request_redraw();
    }

    /// Поставить курсор в заданную точку интерфейса.
    pub fn курсор_к(&mut self, цель: Цель) {
        let экран = self.screen_size();
        let точка = match цель {
            Цель::Экран => Some((экран.w as f64 / 2.0, экран.h as f64 / 2.0)),
            // Целимся в полосочку полки, а не в середину острова: середина —
            // это промежуток между чипами, и клик там ничего не открывает
            // (замерено на харнессе: `bar=None`). С полки же дотягиваются
            // вайфай, звук, заряд и питание — а внутри них уже ходят J/K.
            Цель::Панель => {
                let вид = crate::bar::layout(&self.bar_data());
                let чип = вид
                    .cells
                    .iter()
                    .find(|i| i.cell == crate::bar::Cell::Handle)
                    .map(|i| i.rect)
                    .unwrap_or(вид.right);
                Some((чип.x as f64 + чип.w as f64 / 2.0, чип.y as f64 + чип.h as f64 / 2.0))
            }
            Цель::Окно => self.focused_window().and_then(|окно| {
                let geo = self.space.element_geometry(&окно)?;
                let zoom = self.viewport.zoom.max(0.01);
                // Центр окна на ХОЛСТЕ → в пиксели экрана: камера и зум те же,
                // что у pointer_screen_physical, иначе стрелка уехала бы мимо.
                let x = (geo.loc.x as f64 + geo.size.w as f64 / 2.0 - self.viewport.cam_x) * zoom;
                let y = (geo.loc.y as f64 + geo.size.h as f64 / 2.0 - self.viewport.cam_y) * zoom;
                Some((x, y))
            }),
        };
        let Some((x, y)) = точка else { return };
        // За край экрана не ставим: окно в фокусе может лежать вне кадра
        // (камеру увели), а курсор — устройство экрана. Промахнувшийся курсор
        // упёрся бы в зажим `pointer_location` и выглядел бы как «стрелка
        // пропала».
        let x = x.clamp(1.0, (экран.w as f64 - 2.0).max(1.0));
        let y = y.clamp(1.0, (экран.h as f64 - 2.0).max(1.0));
        let сейчас = self.pointer_screen_physical();
        self.двинуть_курсор(x - сейчас.x, y - сейчас.y);
    }

    /// Шаг камеры по холсту (vim-пан): `dx`,`dy` — направление. Держат
    /// клавишу — камера продолжает ехать, толчками раз в [`ШАГ_КАМЕРЫ`].
    pub fn камера_шаг(&mut self, dx: f64, dy: f64) {
        // Заперто и здесь, а не только в input.rs: то же действие зовут жест,
        // шлем и сокет (см. `клавимышь_камера_заперта`).
        if !self.touchpad_camera_allowed() {
            return;
        }
        self.zoom_nav_pan(dx, dy);
        self.взвести(Что::Камера { dx, dy });
    }

    /// Зум холста с клавиатуры. `множитель` > 0 — щелчок зума у курсора, как
    /// у колеса, держат клавишу — зумит дальше; `множитель` <= 0 — вернуть 1:1.
    pub fn камера_зум(&mut self, множитель: f64) {
        if множитель > 0.0 {
            if !self.touchpad_camera_allowed() {
                return;
            }
            self.zoom_step_at_cursor(множитель);
            self.взвести(Что::Зум { множитель });
            return;
        }
        // Возврат к 1:1. Режим лупы держит свой зум сам — там это делает
        // повторный Super+Space, а не отдельный бинд. Запрет зума в
        // tiling сброс к 1:1 НЕ запирает: это выход из зума, а не зум.
        if self.zoom_nav_mode && !self.overview_active {
            return;
        }
        if let Some((якорь, центр)) = self.screen_center_and_anchor() {
            self.zoom_glide = None;
            self.zoom_anim = Some(crate::anim::ZoomAnim::new(
                якорь,
                центр,
                self.viewport.zoom,
                1.0,
                crate::anim::дуг::смена_зума(),
            ));
            self.request_redraw();
        }
    }

    /// Взвести ход на клавише, которую разбирают сейчас. Без неё (действие
    /// пришло от жеста, шлема или сокета) ход не взводится вовсе: отпускать
    /// его было бы нечем.
    fn взвести(&mut self, что: Что) {
        let Some(клавиша) = self.клавимышь.текущая else { return };
        let сейчас = Instant::now();
        self.клавимышь.ход = Some(Ход {
            клавиша,
            что,
            нажата: сейчас,
            тронут: сейчас,
            пошёл: None,
        });
        self.request_redraw();
    }

    /// Сдвинуть стрелку на экранную дельту синтетическим движением мыши.
    fn двинуть_курсор(&mut self, dx: f64, dy: f64) {
        self.process_input_event(InputEvent::PointerMotion::<Синтетика> {
            event: Движение::new(dx, dy),
        });
        self.request_redraw();
    }

    /// Нажать или отпустить кнопку мыши.
    fn курсор_кнопка(&mut self, код: u32, нажата: bool) {
        self.клавимышь.шлёт = true;
        self.process_input_event(InputEvent::PointerButton::<Синтетика> {
            event: Кнопка::new(код, нажата),
        });
        self.клавимышь.шлёт = false;
        self.request_redraw();
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    /// Разгон: старт со своей скорости, потолок ровно [`ПОТОЛОК`], между ними
    /// монотонно. Проверяется формулой, а не экраном: на глаз «курсор едет
    /// как-то не так» неотличимо от сбитого шага в конфиге.
    #[test]
    fn разгон_растёт_и_упирается_в_потолок() {
        assert_eq!(множитель(Duration::ZERO), 1.0);
        assert_eq!(множитель(РАЗГОН), ПОТОЛОК);
        // Дальше потолка не растёт — иначе зажатая клавиша уносила бы курсор
        // тем быстрее, чем дольше её держат, без всякого предела.
        assert_eq!(множитель(РАЗГОН * 10), ПОТОЛОК);
        let середина = множитель(РАЗГОН / 2);
        assert!(
            середина > 1.0 && середина < ПОТОЛОК,
            "середина разгона вне (1, {ПОТОЛОК}): {середина}"
        );
    }
}
