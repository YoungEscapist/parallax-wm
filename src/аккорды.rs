//! Мышиные аккорды — команда задаётся ПАРОЙ кнопок, нажатых подряд.
//!
//! Перенесено из [hevel](https://git.sr.ht/~dlm/hevel), плавающего
//! скроллящегося WM, где мышью делается вообще всё: «1 → 3 → протяжка» открывает
//! терминал в обведённой рамке, «3 → 1 → навести → отпустить» закрывает окно,
//! «2 → 1» ведёт окно, «2 → 3» меняет ему размер. Кнопки называются как в
//! hevel: 1 — левая, 2 — колесо, 3 — правая.
//!
//! ## Чем это отличается от обычного бинда
//!
//! Аккорд опознаётся по ВТОРОЙ кнопке, а первая к этому моменту уже нажата.
//! Значит первую нельзя сразу отдавать клиенту: отдали — и «3 → 1» успело бы
//! открыть контекстное меню, прежде чем мы поняли, что это аккорд. Поэтому
//! первая кнопка ЗАДЕРЖИВАЕТСЯ (см. [`ОтложеннаяКнопка`]), и дальше одно из
//! трёх:
//!
//! * пришла вторая кнопка известного аккорда — аккорд начался, задержанное
//!   нажатие выбрасывается: клиент его не видел и не увидит;
//! * ту же кнопку отпустили — это был обычный клик, и клиент получает
//!   нажатие и отпускание подряд, как если бы задержки не было;
//! * вышло время (`chord_click_timeout_ms` из hevel, у нас
//!   `mouse_chord_timeout`) — это удержание, а не аккорд: нажатие уходит
//!   клиенту, и дальше всё идёт как обычно.
//!
//! **Задержка не бесплатна, и потому она ИЗБИРАТЕЛЬНА.** Задерживается только
//! кнопка, с которой хоть один аккорд НАЧИНАЕТСЯ. Не настроено ни одного
//! аккорда с левой — левая работает ровно как раньше, без единой лишней
//! миллисекунды. Это то же обещание, что даёт таблица жестов: пустая таблица не
//! может перехватить ничего, и поведение до этого файла воспроизводится
//! отсутствием строк в конфиге, а не флагом.
//!
//! ## Отпускание одной из двух кнопок
//!
//! Протяжка (пан, ведение, размер) идёт, пока нажата ХОТЬ ОДНА кнопка аккорда,
//! и кончается, когда отпущены обе, — как в hevel, где жест ведут одной рукой:
//! нажал 2, нажал 3, снял лишний палец с колеса и тянешь размер правой.
//! Мгновенные аккорды (`3 → 1` закрыть, `1 → 3` рамка) наоборот решают по
//! ПЕРВОМУ отпусканию: у них отпускание — это и есть выбор жертвы или второго
//! угла рамки.
//!
//! ## Модификатор старше аккорда
//!
//! Пока зажат Super (или Alt), аккорды не начинаются вовсе: мышиные бинды с
//! модификатором — Super+ЛКМ вести окно, Super+ПКМ менять размер — стоят в
//! `input.rs` ПОСЛЕ этого модуля, и без явной уступки аккорд с правой кнопки
//! отнимал у Super+ПКМ саму кнопку.

use smithay::utils::{Logical, Point};

/// Кнопка мыши в нумерации hevel.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Кнопка {
    /// 1 — левая.
    Левая,
    /// 2 — колесо.
    Средняя,
    /// 3 — правая.
    Правая,
}

// Коды те же, что в input.rs (linux/input-event-codes.h). Дублируются намеренно:
// тащить сюда приватные константы input.rs ради трёх чисел — лишний шов, а
// разъехаться им негде, это ABI ядра.
const BTN_LEFT: u32 = 0x110;
const BTN_RIGHT: u32 = 0x111;
const BTN_MIDDLE: u32 = 0x112;

impl Кнопка {
    pub fn из_кода(код: u32) -> Option<Кнопка> {
        match код {
            BTN_LEFT => Some(Кнопка::Левая),
            BTN_MIDDLE => Some(Кнопка::Средняя),
            BTN_RIGHT => Some(Кнопка::Правая),
            _ => None,
        }
    }

    pub fn код(self) -> u32 {
        match self {
            Кнопка::Левая => BTN_LEFT,
            Кнопка::Средняя => BTN_MIDDLE,
            Кнопка::Правая => BTN_RIGHT,
        }
    }

    /// Имя из конфига: цифра как в hevel или слово.
    pub fn разобрать(s: &str) -> Option<Кнопка> {
        match s.trim().to_ascii_lowercase().as_str() {
            "1" | "left" | "лкм" | "левая" => Some(Кнопка::Левая),
            "2" | "middle" | "wheel" | "скм" | "средняя" | "колесо" => Some(Кнопка::Средняя),
            "3" | "right" | "пкм" | "правая" => Some(Кнопка::Правая),
            _ => None,
        }
    }
}

/// Вторая половина аккорда: кнопка — или ПРОКРУТКА.
///
/// Колесо крутят, а не нажимают, и это не придирка к словам: у прокрутки нет
/// ни удержания, ни отпускания, поэтому «1 → колесо» устроено иначе, чем
/// «1 → 3». Первая кнопка НЕ задерживается вовсе (задержка нужна только чтобы
/// не отдать клиенту нажатие, которое окажется началом аккорда, а прокрутка
/// приходит сама и никому ничего не ломает), и весь аккорд — это «пока зажата
/// ЛКМ, колесо делает то-то». Ровно так, как Alt+колесо зумит холст, только
/// вместо Alt рука держит кнопку мыши.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Вторая {
    Кнопка(Кнопка),
    Прокрутка,
    /// ВТОРОЙ ЩЕЛЧОК ТОЙ ЖЕ КНОПКИ — двойной клик (`chord = "3-3"`).
    ///
    /// Раньше «одна и та же кнопка дважды» отвергалось конфигом со словами
    /// «второе нажатие без отпускания физически не придёт». Верно — но между
    /// ними приходит ОТПУСКАНИЕ, и пара «щелчок, щелчок» распознаётся не хуже
    /// пары кнопок. Цена другая и она своя: чтобы двойной клик не успел стать
    /// обычным, задержать приходится не только нажатие, но и отпускание, —
    /// то есть весь первый щелчок целиком (см. `mouse_double_click`).
    Двойной,
}

impl Вторая {
    pub fn разобрать(s: &str) -> Option<Вторая> {
        match s.trim().to_ascii_lowercase().as_str() {
            "scroll" | "скролл" | "прокрутка" | "колёсико" | "колесико" => Some(Вторая::Прокрутка),
            "double" | "dbl" | "двойной" | "два" => Some(Вторая::Двойной),
            иначе => Кнопка::разобрать(иначе).map(Вторая::Кнопка),
        }
    }
}

/// Что делает аккорд.
#[derive(Clone, Debug)]
pub enum ДействиеАккорда {
    /// Обвести рамку и запустить в ней команду (hevel: 1 → 3).
    Прямоугольник(String),
    /// Закрыть окно, НАД КОТОРЫМ ОТПУСТИЛИ, а не над которым начали
    /// (hevel: 3 → 1 — «навести на жертву и отпустить»).
    ЗакрытьПод,
    /// Панорамировать вид протяжкой (hevel: 3 → 2).
    Пан,
    /// Вести окно (hevel: 2 → 1).
    ВестиОкно,
    /// Менять размер окна (hevel: 2 → 3).
    РазмерОкна,
    /// Зум холста протяжкой (у hevel на этой паре `custom_chord`).
    Зум,
    /// Любое обычное действие из таблицы, сразу на второй кнопке
    /// (hevel: 1 → 2, у него настраиваемый `custom_chord`).
    Обычное(Box<crate::config::Action>),
}

/// Одна строка таблицы аккордов.
#[derive(Clone, Debug)]
pub struct БиндАккорда {
    pub первая: Кнопка,
    pub вторая: Вторая,
    pub действие: ДействиеАккорда,
}

/// Нажатие, задержанное до выяснения — аккорд это или обычный клик.
#[derive(Clone, Copy, Debug)]
pub struct ОтложеннаяКнопка {
    pub кнопка: Кнопка,
    pub когда: std::time::Instant,
    /// Время события libinput: с ним нажатие и уйдёт клиенту, если окажется,
    /// что аккорда нет. Своё время подставлять нельзя — клиенты (и сам
    /// smithay) считают по нему двойной клик.
    pub время: u32,
    /// Кнопку уже отпустили, и мы ждём ВТОРОЙ щелчок (только когда на эту
    /// кнопку настроен двойной клик). `Some` — время того отпускания: клиенту
    /// оно уйдёт следом за нажатием, если второго щелчка так и не будет.
    pub отпущена: Option<u32>,
}

/// Идущий аккорд.
#[derive(Clone, Debug)]
pub struct ИдётАккорд {
    pub действие: ДействиеАккорда,
    pub первая: Кнопка,
    pub вторая: Кнопка,
    /// Где нажали вторую кнопку — начало рамки и точка отсчёта протяжки.
    pub начало: Point<f64, Logical>,
    /// Сколько кнопок аккорда ещё физически нажато. Протяжка живёт, пока это
    /// не ноль (см. «отпускание одной из двух» ниже).
    pub держат: u8,
    /// Аккорд от ДВОЙНОГО КЛИКА и кончается он не отпусканием, а СЛЕДУЮЩИМ
    /// ЩЕЛЧКОМ: «взял окно — оно едет за курсором — щёлкнул, положил».
    ///
    /// Иначе двойной клик был бы бесполезен: отпускание второго щелчка
    /// приходит через миг после него, и протяжка кончалась бы, не начавшись.
    /// Ход руки при этом не теряется — если человек ПОТЯНУЛ, не отпуская
    /// (обычный драг с двойного клика), отпускание аккорд закрывает.
    pub по_щелчку: bool,
}

/// Есть ли аккорд, начинающийся с этой кнопки ВТОРОЙ КНОПКОЙ. По этому ответу
/// решается, задерживать ли нажатие вообще.
///
/// Аккорды с прокруткой сюда не считаются нарочно: им задержка не нужна (см.
/// [`Вторая`]), а считались бы — и `1-scroll` отнимал бы у левой кнопки
/// мгновенность на ровном месте. Именно это и случилось у Ярика: с
/// `chord = "1-2"` нажатие ЛКМ уходило в отложенные, мимо ветки, которая
/// начинает рамку выделения, и выделение «просто не рисовалось».
pub fn начинает(таблица: &[БиндАккорда], к: Кнопка) -> bool {
    таблица
        .iter()
        .any(|б| б.первая == к && matches!(б.вторая, Вторая::Кнопка(_) | Вторая::Двойной))
}

/// Настроен ли на эту кнопку ДВОЙНОЙ КЛИК. По этому ответу решается, держать
/// ли ещё и отпускание — то есть весь первый щелчок целиком.
pub fn двойной(таблица: &[БиндАккорда], к: Кнопка) -> Option<&БиндАккорда> {
    таблица
        .iter()
        .find(|б| б.первая == к && б.вторая == Вторая::Двойной)
}

/// Найти аккорд по паре кнопок.
pub fn найти(таблица: &[БиндАккорда], первая: Кнопка, вторая: Кнопка) -> Option<&БиндАккорда> {
    таблица
        .iter()
        .find(|б| б.первая == первая && б.вторая == Вторая::Кнопка(вторая))
}

/// Найти аккорд «кнопка + прокрутка».
pub fn найти_прокрутку(таблица: &[БиндАккорда], первая: Кнопка) -> Option<&БиндАккорда> {
    таблица
        .iter()
        .find(|б| б.первая == первая && б.вторая == Вторая::Прокрутка)
}

