//! Мышиные аккорды — команда задаётся ПАРОЙ кнопок, нажатых подряд.
//!
//! Перенесено из [hevel](https://git.sr.ht/~dlm/hevel), плавающего
//! скроллящегося WM, где мышью делается вообще всё: «1 → 3 → протяжка» открывает
//! терминал в обведённой рамке, «3 → 1 → навести → отпустить» закрывает окно,
//! «2 → 1» ведёт окно, «2 → 3» меняет ему размер. Кнопки называются как в
//! hevel: 1 — левая, 2 — колесо, 3 — правая.
//!
//! ## Чем это отличается от обычного бинда
//!
//! Аккорд опознаётся по ВТОРОЙ кнопке, а первая к этому моменту уже нажата.
//! Значит первую нельзя сразу отдавать клиенту: отдали — и «3 → 1» успело бы
//! открыть контекстное меню, прежде чем мы поняли, что это аккорд. Поэтому
//! первая кнопка ЗАДЕРЖИВАЕТСЯ (см. [`ОтложеннаяКнопка`]), и дальше одно из
//! трёх:
//!
//! * пришла вторая кнопка известного аккорда — аккорд начался, задержанное
//!   нажатие выбрасывается: клиент его не видел и не увидит;
//! * ту же кнопку отпустили — это был обычный клик, и клиент получает
//!   нажатие и отпускание подряд, как если бы задержки не было;
//! * вышло время (`chord_click_timeout_ms` из hevel, у нас
//!   `mouse_chord_timeout`) — это удержание, а не аккорд: нажатие уходит
//!   клиенту, и дальше всё идёт как обычно.
//!
//! **Задержка не бесплатна, и потому она ИЗБИРАТЕЛЬНА.** Задерживается только
//! кнопка, с которой хоть один аккорд НАЧИНАЕТСЯ. Не настроено ни одного
//! аккорда с левой — левая работает ровно как раньше, без единой лишней
//! миллисекунды. Это то же обещание, что даёт таблица жестов: пустая таблица не
//! может перехватить ничего, и поведение до этого файла воспроизводится
//! отсутствием строк в конфиге, а не флагом.
//!
//! ## Чего здесь нет
//!
//! Режима hevel «3 → 2, отпустить 2 и продолжать держать колесо». Отпускание
//! ОДНОЙ из двух кнопок как продолжение аккорда — это третье состояние сверх
//! «идёт» и «кончился», и оно нужно ровно одному аккорду из шести. У нас
//! протяжка идёт, пока нажата любая из двух кнопок аккорда, и кончается на
//! первом отпускании: для пана, ведения и размера разница только в том, можно
//! ли отпустить лишний палец посреди жеста.

use smithay::utils::{Logical, Point};

/// Кнопка мыши в нумерации hevel.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Кнопка {
    /// 1 — левая.
    Левая,
    /// 2 — колесо.
    Средняя,
    /// 3 — правая.
    Правая,
}

// Коды те же, что в input.rs (linux/input-event-codes.h). Дублируются намеренно:
// тащить сюда приватные константы input.rs ради трёх чисел — лишний шов, а
// разъехаться им негде, это ABI ядра.
const BTN_LEFT: u32 = 0x110;
const BTN_RIGHT: u32 = 0x111;
const BTN_MIDDLE: u32 = 0x112;

impl Кнопка {
    pub fn из_кода(код: u32) -> Option<Кнопка> {
        match код {
            BTN_LEFT => Some(Кнопка::Левая),
            BTN_MIDDLE => Some(Кнопка::Средняя),
            BTN_RIGHT => Some(Кнопка::Правая),
            _ => None,
        }
    }

    pub fn код(self) -> u32 {
        match self {
            Кнопка::Левая => BTN_LEFT,
            Кнопка::Средняя => BTN_MIDDLE,
            Кнопка::Правая => BTN_RIGHT,
        }
    }

    /// Имя из конфига: цифра как в hevel или слово.
    pub fn разобрать(s: &str) -> Option<Кнопка> {
        match s.trim().to_ascii_lowercase().as_str() {
            "1" | "left" | "лкм" | "левая" => Some(Кнопка::Левая),
            "2" | "middle" | "wheel" | "скм" | "средняя" | "колесо" => Some(Кнопка::Средняя),
            "3" | "right" | "пкм" | "правая" => Some(Кнопка::Правая),
            _ => None,
        }
    }
}

/// Что делает аккорд.
#[derive(Clone, Debug)]
pub enum ДействиеАккорда {
    /// Обвести рамку и запустить в ней команду (hevel: 1 → 3).
    Прямоугольник(String),
    /// Закрыть окно, НАД КОТОРЫМ ОТПУСТИЛИ, а не над которым начали
    /// (hevel: 3 → 1 — «навести на жертву и отпустить»).
    ЗакрытьПод,
    /// Панорамировать вид протяжкой (hevel: 3 → 2).
    Пан,
    /// Вести окно (hevel: 2 → 1).
    ВестиОкно,
    /// Менять размер окна (hevel: 2 → 3).
    РазмерОкна,
    /// Любое обычное действие из таблицы, сразу на второй кнопке
    /// (hevel: 1 → 2, у него настраиваемый `custom_chord`).
    Обычное(Box<crate::config::Action>),
}

/// Одна строка таблицы аккордов.
#[derive(Clone, Debug)]
pub struct БиндАккорда {
    pub первая: Кнопка,
    pub вторая: Кнопка,
    pub действие: ДействиеАккорда,
}

/// Нажатие, задержанное до выяснения — аккорд это или обычный клик.
#[derive(Clone, Copy, Debug)]
pub struct ОтложеннаяКнопка {
    pub кнопка: Кнопка,
    pub когда: std::time::Instant,
    /// Время события libinput: с ним нажатие и уйдёт клиенту, если окажется,
    /// что аккорда нет. Своё время подставлять нельзя — клиенты (и сам
    /// smithay) считают по нему двойной клик.
    pub время: u32,
}

/// Идущий аккорд.
#[derive(Clone, Debug)]
pub struct ИдётАккорд {
    pub действие: ДействиеАккорда,
    pub первая: Кнопка,
    pub вторая: Кнопка,
    /// Где нажали вторую кнопку — начало рамки и точка отсчёта протяжки.
    pub начало: Point<f64, Logical>,
}

/// Есть ли аккорд, начинающийся с этой кнопки. По этому ответу решается,
/// задерживать ли нажатие вообще.
pub fn начинает(таблица: &[БиндАккорда], к: Кнопка) -> bool {
    таблица.iter().any(|б| б.первая == к)
}

/// Найти аккорд по паре кнопок.
pub fn найти(таблица: &[БиндАккорда], первая: Кнопка, вторая: Кнопка) -> Option<&БиндАккорда> {
    таблица.iter().find(|б| б.первая == первая && б.вторая == вторая)
}

// ── Диспетчер ────────────────────────────────────────────────────────────────

use crate::Parallax;

impl Parallax {
    /// Кнопка мыши глазами аккордов.
    ///
    /// `true` — событие СЪЕДЕНО: ни прежним веткам `input.rs`, ни клиенту его
    /// отдавать не надо. `false` — аккорды тут ни при чём, всё идёт как раньше.
    pub fn аккорд_кнопка(&mut self, код: u32, нажата: bool, время: u32) -> bool {
        if self.lua_config.mouse_chords.is_empty() {
            return false;
        }
        let Some(к) = Кнопка::из_кода(код) else { return false };

        // ── Аккорд уже идёт ──────────────────────────────────────────────────
        if let Some(идёт) = self.аккорд.clone() {
            if нажата {
                // Третья кнопка посреди аккорда: глотаем, но состояние не
                // трогаем — иначе случайный лишний палец рвал бы протяжку.
                return true;
            }
            if к == идёт.первая || к == идёт.вторая {
                self.аккорд_кончить(&идёт);
                self.аккорд = None;
            }
            return true;
        }

        // ── Ждём вторую кнопку ───────────────────────────────────────────────
        if let Some(ждём) = self.аккорд_ждёт {
            if нажата {
                if let Some(бинд) = найти(&self.lua_config.mouse_chords, ждём.кнопка, к) {
                    let действие = бинд.действие.clone();
                    self.аккорд_ждёт = None;
                    self.аккорд_начать(ждём.кнопка, к, действие);
                    return true;
                }
                // Пара не сложилась: задержанное нажатие больше держать не за
                // чем — отдаём его клиенту и пропускаем текущее событие дальше
                // ОБЫЧНЫМ путём. Порядок важен: клиент обязан увидеть кнопки в
                // том же порядке, в каком их нажимал человек.
                self.аккорд_отпустить_отложенное();
                return false;
            }
            if к == ждём.кнопка {
                // Обычный клик, только опознанный задним числом: отдаём клиенту
                // нажатие, а отпускание пойдёт дальше своим ходом.
                self.аккорд_отпустить_отложенное();
                return false;
            }
            return false;
        }

        // ── Ничего не идёт ───────────────────────────────────────────────────
        if нажата && начинает(&self.lua_config.mouse_chords, к) {
            self.аккорд_ждёт = Some(ОтложеннаяКнопка {
                кнопка: к,
                когда: std::time::Instant::now(),
                время,
            });
            return true;
        }
        false
    }

    /// Отдать задержанное нажатие клиенту — аккорда не вышло.
    fn аккорд_отпустить_отложенное(&mut self) {
        let Some(ждём) = self.аккорд_ждёт.take() else { return };
        self.аккорд_отдать_клиенту(ждём.кнопка.код(), true, ждём.время);
    }

    /// Дозреть задержанное нажатие по времени.
    ///
    /// Зовётся из `anim::tick`. Без этого удержание кнопки (нажал и держу, не
    /// нажимая вторую) висело бы у нас вечно: второй кнопки нет, отпускания
    /// нет, а клиент нажатия так и не увидел.
    pub fn аккорд_сторож(&mut self) {
        let Some(ждём) = self.аккорд_ждёт else { return };
        let срок = std::time::Duration::from_millis(self.lua_config.mouse_chord_timeout as u64);
        if ждём.когда.elapsed() >= срок {
            self.аккорд_отпустить_отложенное();
        }
    }

    /// Начать аккорд: подготовить то, что будет тянуться за мышью.
    fn аккорд_начать(&mut self, первая: Кнопка, вторая: Кнопка, действие: ДействиеАккорда) {
        tracing::debug!("plx/chords: chord {первая:?}→{вторая:?} → {действие:?}");
        let начало = self.pointer_location;

        // Мгновенное действие аккордом и кончается: держать нечего, а
        // оставленный `self.аккорд` съел бы отпускание обеих кнопок.
        if let ДействиеАккорда::Обычное(a) = &действие {
            self.dispatch_action((**a).clone());
            return;
        }

        // Протяжные действия берут окно и готовят состояние ТЕМ ЖЕ путём, что
        // жесты тачпада (`жест_подготовить`): одно окно не может ехать по двум
        // путям сразу, и общее состояние гарантирует, что приберёт за собой
        // один и тот же код.
        match действие {
            ДействиеАккорда::ВестиОкно => {
                self.жест_подготовить(crate::gestures::Непрерывное::ВестиОкно)
            }
            ДействиеАккорда::РазмерОкна => {
                self.жест_подготовить(crate::gestures::Непрерывное::РазмерОкна)
            }
            ДействиеАккорда::Прямоугольник(_) => {
                self.аккорд_рамка = Some(начало);
                self.request_redraw();
            }
            _ => {}
        }
        self.аккорд = Some(ИдётАккорд { действие, первая, вторая, начало });
    }

    /// Движение мыши во время аккорда.
    ///
    /// `true` — курсор двигать НЕ надо, движение целиком ушло в действие. Так
    /// отвечает только пан: он ведёт камеру так, чтобы точка холста под
    /// стрелкой осталась той же, и сдвинуть стрелку сверху значило бы проехать
    /// вдвое. Остальные аккорды — обычная мышиная протяжка: окно едет за рукой,
    /// и стрелка обязана ехать вместе с ним, иначе она отстаёт от схваченного
    /// окна на весь путь жеста.
    pub fn аккорд_движение(&mut self, dx: f64, dy: f64, время: u32) -> bool {
        let Some(идёт) = self.аккорд.clone() else { return false };
        match идёт.действие {
            ДействиеАккорда::Пан => {
                self.применить_непрерывное(crate::gestures::Непрерывное::ПанВида, dx, dy, время);
                return true;
            }
            ДействиеАккорда::ВестиОкно => {
                self.применить_непрерывное(crate::gestures::Непрерывное::ВестиОкно, dx, dy, время)
            }
            ДействиеАккорда::РазмерОкна => {
                self.применить_непрерывное(crate::gestures::Непрерывное::РазмерОкна, dx, dy, время)
            }
            // Рамке довольно перерисовки: второй её угол — сам курсор,
            // и он уже там, куда его привело это движение.
            ДействиеАккорда::Прямоугольник(_) => self.request_redraw(),
            // Закрытие смотрит, где ОТПУСТИЛИ: по дороге делать нечего, курсор
            // ходит как обычно — им и выбирают жертву.
            ДействиеАккорда::ЗакрытьПод => {}
            ДействиеАккорда::Обычное(_) => {}
        }
        false
    }

    /// Конец аккорда: то, что делается на отпускании.
    fn аккорд_кончить(&mut self, идёт: &ИдётАккорд) {
        match &идёт.действие {
            ДействиеАккорда::ЗакрытьПод => {
                // Именно под КУРСОРОМ СЕЙЧАС: в hevel это «3 → 1, навести на
                // жертву, отпустить», то есть окно выбирается по дороге, а не
                // в начале.
                if let Some((w, _)) = self.space.element_under(self.pointer_location) {
                    let w = w.clone();
                    tracing::info!("plx/chords: closing the window under the cursor");
                    crate::xwin::close(&w);
                }
            }
            ДействиеАккорда::Прямоугольник(cmd) => {
                let начало = self.аккорд_рамка.take();
                self.request_redraw();
                let Some(a) = начало else { return };
                let b = self.pointer_location;
                // Рамка меньше пары пикселей — это промах, а не «окно нулевого
                // размера»: запускать по ней значит открывать терминал в точке.
                let (w, h) = ((b.x - a.x).abs(), (b.y - a.y).abs());
                if w < 8.0 || h < 8.0 {
                    tracing::debug!("plx/chords: the frame is too small ({w:.0}x{h:.0}), not spawning");
                    return;
                }
                let угол = Point::<f64, Logical>::from((a.x.min(b.x), a.y.min(b.y)));
                self.аккорд_запуск_в_рамке = Some((угол, (w, h), std::time::Instant::now()));
                self.dispatch_action(crate::config::Action::Spawn(cmd.clone()));
            }
            ДействиеАккорда::Пан => self.momentum.launch(),
            ДействиеАккорда::ВестиОкно => self.gesture_move_window = None,
            ДействиеАккорда::РазмерОкна => {
                let группа = std::mem::take(&mut self.gesture_resize_group);
                self.gesture_resize_window = None;
                for (w, _) in группа {
                    let size = crate::xwin::current_size(&w);
                    if let Some(tw) = self.tagged_windows.iter_mut().find(|tw| tw.window == w) {
                        tw.float_size = Some(size);
                    }
                }
            }
            ДействиеАккорда::Обычное(_) => {}
        }
    }
}
