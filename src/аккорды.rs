use crate::Parallax;

impl Parallax {
    /// Кнопка мыши глазами аккордов.
    ///
    /// `true` — событие СЪЕДЕНО: ни прежним веткам `input.rs`, ни клиенту его
    /// отдавать не надо. `false` — аккорды тут ни при чём, всё идёт как раньше.
    pub fn аккорд_кнопка(&mut self, код: u32, нажата: bool, время: u32) -> bool {
        if self.lua_config.mouse_chords.is_empty() {
            return false;
        }
        let Some(к) = Кнопка::из_кода(код) else { return false };

        // Кто сейчас физически зажат — единственное, что нужно аккорду с
        // прокруткой. Пишется ДО всех ветвлений и возвратов: кнопка нажата
        // независимо от того, чем это нажатие кончится, и разъехавшийся здесь
        // счёт означал бы «колесо зумит, хотя ЛКМ давно отпустили».
        self.аккорд_зажаты[к as usize] = нажата;

        // ── Модификатор старше аккорда ───────────────────────────────────────
        //
        // Super+ПКМ (размер) и Super+ЛКМ (перемещение) старше аккордов, и
        // проверка обязана стоять ЗДЕСЬ, а не в ветках `input.rs`: до них дело
        // не доходит вовсе — аккорды съедают нажатие первыми. Без этих строк
        // включённый аккорд «3-…» отнимал у Super+ПКМ саму кнопку, и ресайз
        // мышью переставал работать целиком (в логе сеанса с аккордами
        // `resize grab start` не встречается ни разу, а нажатий правой до
        // `input.rs` доходит ноль).
        //
        // Начало аккорда — единственное, что здесь запрещено. Уже идущий
        // аккорд ведётся до конца: человек мог нажать Super посреди протяжки,
        // и бросать её на полпути — хуже, чем доводить.
        let модификатор = self.logo_held
            || self
                .seat
                .get_keyboard()
                .map(|kb| {
                    let м = kb.modifier_state();
                    м.logo || м.alt
                })
                .unwrap_or(false);
        if модификатор && self.аккорд.is_none() {
            // Задержанное нажатие отдаём сейчас: Super нажали уже после первой
            // кнопки, аккорда из неё не выйдет, а клиент её всё ещё не видел.
            self.аккорд_отпустить_отложенное();
            return false;
        }

        // ── Аккорд уже идёт ──────────────────────────────────────────────────
        if let Some(идёт) = self.аккорд.clone() {
            if нажата {
                // Третья кнопка посреди аккорда: глотаем, но состояние не
                // трогаем — иначе случайный лишний палец рвал бы протяжку.
                return true;
            }
            if к == идёт.первая || к == идёт.вторая {
                // ОТПУСКАНИЕ ОДНОЙ ИЗ ДВУХ — ещё не конец. В hevel протяжку
                // ведут одной кнопкой: нажал 2, нажал 3, отпустил колесо и
                // тянешь размер правой. Пока мы кончали аккорд на ПЕРВОМ
                // отпускании, `2-3` и `2-1` умирали в тот же миг, когда рука
                // снимала лишний палец, — снаружи ровно «аккорд не работает»
                // (в логе сеанса `РазмерОкна` начинался четыре раза и ни разу
                // не успел ничего изменить).
                //
                // Мгновенные аккорды считают моментом решения именно первое
                // отпускание: `3-1` закрывает окно, НАД КОТОРЫМ отпустили, а
                // `1-3` запускает по обведённой рамке. Им ждать второй кнопки
                // нечего — они и так кончились.
                let протяжка = matches!(
                    идёт.действие,
                    ДействиеАккорда::Пан
                        | ДействиеАккорда::ВестиОкно
                        | ДействиеАккорда::РазмерОкна
                        | ДействиеАккорда::Зум
                );
                if протяжка {
                    if let Some(и) = self.аккорд.as_mut() {
                        и.держат = и.держат.saturating_sub(1);
                    }
                    let все_отпустили =
                        self.аккорд.as_ref().map(|и| и.держат == 0).unwrap_or(true);
                    if !все_отпустили {
                        return true;
                    }
                }
                self.аккорд_кончить(&идёт);
                self.аккорд = None;
            }
            return true;
        }

        // ── Ждём вторую кнопку ───────────────────────────────────────────────
        if let Some(ждём) = self.аккорд_ждёт {
            if нажата {
                if let Some(бинд) = найти(&self.lua_config.mouse_chords, ждём.кнопка, к) {
                    let действие = бинд.действие.clone();
                    self.аккорд_ждёт = None;
                    self.аккорд_начать(ждём.кнопка, к, действие);
                    return true;
                }
                // Пара не сложилась: задержанное нажатие больше держать не за
                // чем — отдаём его клиенту и пропускаем текущее событие дальше
                // ОБЫЧНЫМ путём. Порядок важен: клиент обязан увидеть кнопки в
                // том же порядке, в каком их нажимал человек.
                self.аккорд_отпустить_отложенное();
                return false;
            }
            if к == ждём.кнопка {
                // Обычный клик, только опознанный задним числом: отдаём клиенту
                // нажатие, а отпускание пойдёт дальше своим ходом.
                self.аккорд_отпустить_отложенное();
                return false;
            }
            return false;
        }

        // ── Ничего не идёт ───────────────────────────────────────────────────
        if нажата && начинает(&self.lua_config.mouse_chords, к) {
            self.аккорд_ждёт = Some(ОтложеннаяКнопка {
                кнопка: к,
                когда: std::time::Instant::now(),
                время,
            });
            return true;
        }
        false
    }

    /// Прокрутка глазами аккордов: `mouse{ chord = "1-scroll", action = "zoom" }`.
    ///
    /// `true` — колесо съедено аккордом и до клиента не идёт.
    ///
    /// Кнопку берём из СВОЕГО списка зажатых, а не из состояния указателя:
    /// пока идёт grab (та же рамка выделения на ЛКМ), фокус указателя очищен,
    /// и спрашивать у него, что нажато, — значит получать ответ про клиента, а
    /// не про руку.
    pub fn аккорд_прокрутка(&mut self, v: f64, палец: bool) -> bool {
        // Тачпад сюда не ходит: два пальца — это прокрутка, а не колесо, и
        // отнимать её у окна под курсором из-за зажатой кнопки нельзя. У
        // тачпада для того же есть щипок и своя таблица жестов.
        if палец || v == 0.0 || self.lua_config.mouse_chords.is_empty() {
            return false;
        }
        let зажаты = [Кнопка::Левая, Кнопка::Средняя, Кнопка::Правая];
        let Some(действие) = зажаты
            .into_iter()
            .filter(|к| self.аккорд_зажаты[*к as usize])
            .find_map(|к| найти_прокрутку(&self.lua_config.mouse_chords, к))
            .map(|б| б.действие.clone())
        else {
            return false;
        };
        match действие {
            ДействиеАккорда::Зум => {
                // Тот же шаг и тот же доезд, что у Alt+колеса (см. input.rs):
                // аккорд обещан как «ЛКМ вместо Alt», и отличаться на ощупь он
                // не имеет права. Колесо вниз (v > 0) — отдалить.
                self.zoom_step_at_cursor(if v < 0.0 { 1.1 } else { 0.9 });
                true
            }
            ДействиеАккорда::Обычное(a) => {
                self.dispatch_action(*a);
                true
            }
            // Протяжные действия прокруткой не ведутся: у колеса нет хода руки,
            // за которым им следовать. Такие пары отсеиваются ещё в config.rs —
            // здесь остаётся честный отказ, а не молча съеденное колесо.
            _ => false,
        }
    }

    /// Отдать задержанное нажатие клиенту — аккорда не вышло.
    fn аккорд_отпустить_отложенное(&mut self) {
        let Some(ждём) = self.аккорд_ждёт.take() else { return };
        self.аккорд_отдать_клиенту(ждём.кнопка.код(), true, ждём.время);
    }

    /// Дозреть задержанное нажатие по времени.
    ///
    /// Зовётся из `anim::tick` И из обработчика движения мыши. Без этого
    /// удержание кнопки (нажал и держу, не нажимая вторую) висело бы у нас
    /// вечно: второй кнопки нет, отпускания нет, а клиент нажатия так и не
    /// увидел. Движение добавлено к тику потому, что тик идёт по кадрам, а на
    /// неподвижном экране кадров нет: там нажатие дозревало только вместе с
    /// чужой анимацией.
    pub fn аккорд_сторож(&mut self) {
        let Some(ждём) = self.аккорд_ждёт else { return };
        let срок = std::time::Duration::from_millis(self.lua_config.mouse_chord_timeout as u64);
        if ждём.когда.elapsed() >= срок {
            self.аккорд_отпустить_отложенное();
        }
    }

    /// Начать аккорд: подготовить то, что будет тянуться за мышью.
    fn аккорд_начать(&mut self, первая: Кнопка, вторая: Кнопка, действие: ДействиеАккорда) {
        tracing::debug!("plx/chords: chord {первая:?}→{вторая:?} → {действие:?}");
        let начало = self.pointer_location;

        // Мгновенное действие аккордом и кончается: держать нечего, а
        // оставленный `self.аккорд` съел бы отпускание обеих кнопок.
        if let ДействиеАккорда::Обычное(a) = &действие {
            self.dispatch_action((**a).clone());
            return;
        }

        // Протяжные действия берут окно и готовят состояние ТЕМ ЖЕ путём, что
        // жесты тачпада (`жест_подготовить`): одно окно не может ехать по двум
        // путям сразу, и общее состояние гарантирует, что приберёт за собой
        // один и тот же код.
        match действие {
            ДействиеАккорда::ВестиОкно => {
                self.жест_подготовить(crate::gestures::Непрерывное::ВестиОкно)
            }
            ДействиеАккорда::РазмерОкна => {
                self.жест_подготовить(crate::gestures::Непрерывное::РазмерОкна)
            }
            ДействиеАккорда::Прямоугольник(_) => {
                self.аккорд_рамка = Some(начало);
                self.request_redraw();
            }
            _ => {}
        }
        self.аккорд = Some(ИдётАккорд { действие, первая, вторая, начало, держат: 2 });
    }

    /// Движение мыши во время аккорда.
    ///
    /// `true` — курсор двигать НЕ надо, движение целиком ушло в действие. Так
    /// отвечает только пан: он ведёт камеру так, чтобы точка холста под
    /// стрелкой осталась той же, и сдвинуть стрелку сверху значило бы проехать
    /// вдвое. Остальные аккорды — обычная мышиная протяжка: окно едет за рукой,
    /// и стрелка обязана ехать вместе с ним, иначе она отстаёт от схваченного
    /// окна на весь путь жеста.
    pub fn аккорд_движение(&mut self, dx: f64, dy: f64, время: u32) -> bool {
        let Some(идёт) = self.аккорд.clone() else { return false };
        match идёт.действие {
            ДействиеАккорда::Пан => {
                self.применить_непрерывное(crate::gestures::Непрерывное::ПанВида, dx, dy, время);
                return true;
            }
            ДействиеАккорда::ВестиОкно => {
                // Делим на зум по той же причине, что и размер: курсор ходит в
                // пикселях экрана, окно живёт в единицах холста. Без деления
                // окно на отдалённой камере отставало от стрелки, за которую
                // его вроде бы и ведут.
                let зум = self.viewport.zoom.max(0.05);
                self.применить_непрерывное(
                    crate::gestures::Непрерывное::ВестиОкно,
                    dx / зум,
                    dy / зум,
                    время,
                )
            }
            // Мышиный путь ресайза: своё усиление и деление на зум, см.
            // `размер_мышью`. Через `применить_непрерывное` не идёт нарочно —
            // там усиление тачпада, и одна цифра на два устройства означала бы,
            // что настройка под мышь каждый раз ломает жест пальцами.
            ДействиеАккорда::РазмерОкна => self.размер_мышью(dx, dy),
            ДействиеАккорда::Зум => {
                // Зум ведётся ВЕРТИКАЛЬЮ: рука тянет «ближе — дальше», и это
                // вверх-вниз, а не вбок. Вверх (dy < 0) = приблизить. Шаг вдвое
                // круче щипкового: у щипка ход руки ограничен накладкой, у мыши
                // — нет, и на её ходу мелкий шаг читается как «не работает».
                // Экспонента, а не `1 - dy*k`: линейная формула на большом шаге
                // даёт ОТРИЦАТЕЛЬНЫЙ множитель (на харнессе `mouse move 0 300`
                // — вся протяжка одним событием — так и уходила в мусор, зум
                // молча стоял), да и обратный ход у неё не симметричен прямому.
                // У экспоненты множитель положителен всегда, а два одинаковых
                // хода вверх-вниз возвращают ровно исходный масштаб.
                self.зум_мышью((-dy * 0.004).exp());
                // Курсор не двигаем — как у пана: зум идёт вокруг стрелки, и
                // уезжающая стрелка уводила бы за собой точку отсчёта.
                return true;
            }
            // Рамке довольно перерисовки: второй её угол — сам курсор,
            // и он уже там, куда его привело это движение.
            ДействиеАккорда::Прямоугольник(_) => self.request_redraw(),
            // Закрытие смотрит, где ОТПУСТИЛИ: по дороге делать нечего, курсор
            // ходит как обычно — им и выбирают жертву.
            ДействиеАккорда::ЗакрытьПод => {}
            ДействиеАккорда::Обычное(_) => {}
        }
        false
    }

    /// Конец аккорда: то, что делается на отпускании.
    fn аккорд_кончить(&mut self, идёт: &ИдётАккорд) {
        match &идёт.действие {
            ДействиеАккорда::ЗакрытьПод => {
                // Именно под КУРСОРОМ СЕЙЧАС: в hevel это «3 → 1, навести на
                // жертву, отпустить», то есть окно выбирается по дороге, а не
                // в начале.
                if let Some((w, _)) = self.space.element_under(self.pointer_location) {
                    let w = w.clone();
                    tracing::info!("plx/chords: closing the window under the cursor");
                    crate::xwin::close(&w);
                }
            }
            ДействиеАккорда::Прямоугольник(cmd) => {
                let начало = self.аккорд_рамка.take();
                self.request_redraw();
                let Some(a) = начало else { return };
                let b = self.pointer_location;
                // Рамка меньше пары пикселей — это промах, а не «окно нулевого
                // размера»: запускать по ней значит открывать терминал в точке.
                let (w, h) = ((b.x - a.x).abs(), (b.y - a.y).abs());
                if w < 8.0 || h < 8.0 {
                    tracing::debug!("plx/chords: the frame is too small ({w:.0}x{h:.0}), not spawning");
                    return;
                }
                let угол = Point::<f64, Logical>::from((a.x.min(b.x), a.y.min(b.y)));
                self.аккорд_запуск_в_рамке = Some((угол, (w, h), std::time::Instant::now()));
                self.dispatch_action(crate::config::Action::Spawn(cmd.clone()));
            }
            ДействиеАккорда::Пан => self.momentum.launch(),
            // Зуму на отпускании делать нечего: масштаб уже там, куда его
            // привела рука, и инерции у него нет.
            ДействиеАккорда::Зум => {}
            ДействиеАккорда::ВестиОкно => self.gesture_move_window = None,
            ДействиеАккорда::РазмерОкна => {
                let группа = std::mem::take(&mut self.gesture_resize_group);
                self.gesture_resize_window = None;
                for (w, _) in группа {
                    let size = crate::xwin::current_size(&w);
                    if let Some(tw) = self.tagged_windows.iter_mut().find(|tw| tw.window == w) {
                        tw.float_size = Some(size);
                    }
                }
            }
            ДействиеАккорда::Обычное(_) => {}
        }
    }
}
