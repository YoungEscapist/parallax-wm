//! Заглушка мультиюзера: то, что видит остальной код, когда фича `share`
//! выключена.
//!
//! Подставляется вместо `src/share/` целиком (см. `#[path]` в lib.rs), поэтому
//! снаружи модуль по-прежнему зовётся `crate::share`.
//!
//! Палитра участников подключается НАСТОЯЩАЯ, тем же файлом: цвет хозяина
//! (`цвет(0)`) рисует обычный рендер независимо от того, раздаём мы экран или
//! нет, — см. `share/палитра.rs`.

#[path = "../share/палитра.rs"]
mod палитра;
// `ЦВЕТА` снаружи зовут только из share/, но реэкспорт держим полным — путь
// `share::{цвет, ЦВЕТА}` должен значить в обеих сборках одно и то же.
#[allow(unused_imports)]
pub use палитра::{цвет, ЦВЕТА};

use crate::state::Parallax;

/// Идущая раздача. В минимальной сборке значения не существует —
/// `state.раздача` всегда `None`.
pub enum Раздача {}

/// Единственный текст про мультиюзер в минимальной сборке.
pub fn нет_фичи() -> &'static str {
    crate::т!(
        "Мультиюзер в этой сборке не собран — нужен plx-extra",
        "Multi-user sharing is not built into this binary — use plx-extra",
    )
}

/// Рассылка кадров гостям. Зовётся из `udev.rs` и `headless.rs` под проверкой
/// `раздача_идёт()`, которая здесь всегда `false`, — но сигнатура обязана
/// существовать, чтобы места вызова не пришлось обкладывать `#[cfg]`.
pub mod render {
    use crate::state::Parallax;
    use smithay::backend::renderer::gles::GlesRenderer;
    use smithay::output::Output;

    pub fn кадры_гостям(
        _state: &mut Parallax,
        _renderer: &mut GlesRenderer,
        _output: &Output,
        _скругление: Option<&crate::rounded::Шейдер>,
    ) {
    }
}

impl Parallax {
    pub fn раздача_идёт(&self) -> bool {
        false
    }

    pub fn раздача_начать(&mut self, _порт: u16) -> Result<String, String> {
        Err(нет_фичи().into())
    }

    pub fn раздача_по_команде(&mut self, _порт: u16) {
        self.уведомить(нет_фичи());
    }

    pub fn раздача_переключить(&mut self, _порт: u16) {
        self.уведомить(нет_фичи());
    }

    pub fn раздача_закончить(&mut self) {}

    pub fn раздача_панель_открыта(&self) -> bool {
        false
    }

    /// Клавиша, съеденная панелью раздачи. `false` — «не съедена», то есть
    /// ввод идёт обычным путём: панели нет и перехватывать нечего.
    pub fn раздача_клавиша(&mut self, _sym: u32) -> bool {
        false
    }

    pub fn раздача_тик(&mut self) {}

    // ── Аксессоры для панели и анимации ──────────────────────────────────
    // Панель (`bar.rs`) и тик (`anim.rs`) раньше лазали прямо в поля
    // `Раздача`. Теперь — через эти два метода: снаружи они одинаковы в обеих
    // сборках, а подделывать форму структуры не приходится.

    pub fn раздача_код_и_гостей(&self) -> Option<(String, usize)> {
        None
    }

    pub fn раздача_есть_впущенные(&self) -> bool {
        false
    }
}
