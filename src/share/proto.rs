//! Протокол мультиюзера: что летает между dawn (хост) и `dshare` (гость).
//!
//! **形 кадра.** `u32 LE длина` + `u8 тип` + тело. Длина считает ТЕЛО вместе с
//! байтом типа, потолок — [`ПРЕДЕЛ_КАДРА`]. Ни одного разделителя внутри: по
//! TCP приходит поток, а не сообщения, и любой «читать до \n» рано или поздно
//! разорвал бы кадр видео пополам.
//!
//! **Почему руками, а не serde/bincode.** Тело кадра видео — это десятки
//! килобайт, которые нельзя копировать лишний раз; вся структура протокола —
//! полтора десятка полей фиксированного размера. Сериализатор общего
//! назначения тут добавил бы зависимость, версионный риск и копию буфера, не
//! дав ничего взамен.
//!
//! **Версия — первое поле в `Привет`.** Гость может оказаться старее хоста
//! (обновился только один из двух); хост обязан ответить понятной ошибкой, а
//! не разобрать чужую раскладку как свою.
//!
//! Координаты: гость шлёт позицию курсора В СВОИХ экранных пикселях (кадр,
//! который ему рисуют), а не в холсте. Пересчёт делает хост по камере ЭТОГО
//! гостя — только у него есть достоверная камера на момент кадра, и только он
//! знает про зум. Иначе рассинхрон камеры превращался бы в промах курсора.

use std::io::{self, Read, Write};

/// Версия протокола. Меняется при ЛЮБОЙ правке раскладки — старый гость
/// должен получить отказ, а не мусор.
///
/// 2 (30.08.2026): кадр рисуется в размере ОКНА ГОСТЯ, а не хозяйского выхода
/// — добавлено сообщение [`ОтХоста::Размер`], которым хост объявляет смену
/// разрешения посреди потока.
pub const ВЕРСИЯ: u16 = 2;

/// Потолок кадра, 8 МиБ. Ключевой кадр 2560×1080 в h264 столько не занимает
/// даже близко; число нужно, чтобы битый/злой отправитель не заставил хост
/// выделить гигабайт по одному полю длины.
pub const ПРЕДЕЛ_КАДРА: usize = 8 * 1024 * 1024;

/// Сколько гостей пускаем. Ярик просил до пяти.
pub const МАКС_ГОСТЕЙ: usize = 5;

/// Порт по умолчанию.
pub const ПОРТ: u16 = 7373;

// ── Типы сообщений ───────────────────────────────────────────────────────────

pub mod тип {
    // Хост → гость
    pub const ВЫЗОВ: u8 = 1;
    pub const ДОБРО: u8 = 2;
    pub const КАДР: u8 = 3;
    pub const УЧАСТНИКИ: u8 = 4;
    pub const КАМЕРА_ХОСТА: u8 = 5;
    pub const ОТКАЗ: u8 = 6;
    pub const ПРОЩАЙ: u8 = 7;
    pub const РАЗМЕР: u8 = 8;

    // Гость → хост
    pub const ПРИВЕТ: u8 = 20;
    pub const КУРСОР: u8 = 21;
    pub const КНОПКА: u8 = 22;
    pub const КОЛЕСО: u8 = 23;
    pub const КЛАВИША: u8 = 24;
    pub const ВИД: u8 = 25;
    pub const ЗА_ХОСТОМ: u8 = 26;
    pub const ПОКА: u8 = 27;
}

/// Сообщение гостя. Всё, что хост принимает по сети.
#[derive(Debug, Clone, PartialEq)]
pub enum ОтГостя {
    /// Ответ на вызов: версия, имя и доказательство знания кода.
    Привет { версия: u16, имя: String, доказательство: [u8; 32] },
    /// Курсор в экранных пикселях КАДРА ГОСТЯ.
    Курсор { x: f32, y: f32 },
    /// Кнопка мыши: код evdev (0x110 — левая) и нажата ли.
    Кнопка { код: u32, нажата: bool },
    /// Колесо в «зубцах»: положительное — вниз.
    Колесо { dx: f32, dy: f32 },
    /// Клавиша: скан-код evdev (как с железной клавиатуры) и нажата ли.
    Клавиша { код: u32, нажата: bool },
    /// Куда смотрит гость и какого размера у него окно. Хост рисует ему
    /// кадр именно по этим числам.
    Вид { cam_x: f32, cam_y: f32, zoom: f32, w: u16, h: u16 },
    /// Прилипнуть к камере хоста (кнопка «за хостом») или отлипнуть.
    ЗаХостом { включено: bool },
    Пока,
}

/// Сообщение хоста.
#[derive(Debug, Clone, PartialEq)]
pub enum ОтХоста {
    /// Случайная соль. Гость считает `sha256(соль ‖ код)` и шлёт обратно —
    /// сам код по проводу не идёт НИКОГДА, даже в открытой сети.
    Вызов { соль: [u8; 16] },
    /// Пустили: номер участника, его цвет (курсор и рамка), размер кадра,
    /// который хост готов рисовать, и кодек.
    Добро { id: u8, цвет: u32, w: u16, h: u16, кодек: Кодек },
    /// Кусок видеопотока (Annex-B h264 или сырой кадр — см. [`Кодек`]).
    Кадр { номер: u32, ключевой: bool, данные: Vec<u8> },
    /// Кто ещё в сессии: чтобы рисовать чужие курсоры и список.
    Участники(Vec<Участник>),
    /// Где камера хоста — для кнопки «за хостом».
    КамераХоста { x: f32, y: f32, zoom: f32 },
    Отказ { причина: String },
    Прощай,
    /// Кадр теперь такого размера. Приходит ПЕРЕД первым кадром нового
    /// разрешения: гость по нему пересобирает декодер и свои буферы.
    ///
    /// Отдельным сообщением, а не полем в `Кадр`: разрешение меняется редко
    /// (потянули окно), а `Кадр` летит 30 раз в секунду на каждого — четыре
    /// лишних байта в каждом кадре ради события, которого почти не бывает.
    Размер { w: u16, h: u16 },
}

/// Кто в сессии. Хост тоже участник — у него `id = 0`.
#[derive(Debug, Clone, PartialEq)]
pub struct Участник {
    pub id: u8,
    pub цвет: u32,
    pub имя: String,
    /// Где его курсор НА ХОЛСТЕ — чужие стрелки рисуются всем.
    pub курсор: (f32, f32),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Кодек {
    /// h264 Annex-B, поток от ffmpeg.
    H264 = 0,
    /// Сырой BGRA целым кадром. Только для отладки в локалке — 10 МиБ на кадр.
    Сырой = 1,
}

impl Кодек {
    pub fn из_числа(n: u8) -> Option<Self> {
        match n {
            0 => Some(Кодек::H264),
            1 => Some(Кодек::Сырой),
            _ => None,
        }
    }
}

// ── Сборка ───────────────────────────────────────────────────────────────────

/// Буфер под одно сообщение: сперва пишем тело, потом ставим длину в начало.
/// Отдельный тип, чтобы нельзя было забыть длину — самая дорогая ошибка в
/// потоковом протоколе (разъезжается ВСЁ последующее, а не одно сообщение).
struct Сборщик(Vec<u8>);

impl Сборщик {
    fn new(тип: u8) -> Self {
        let mut v = Vec::with_capacity(64);
        v.extend_from_slice(&[0, 0, 0, 0]); // место под длину
        v.push(тип);
        Self(v)
    }
    fn u8(&mut self, x: u8) -> &mut Self { self.0.push(x); self }
    fn u16(&mut self, x: u16) -> &mut Self { self.0.extend_from_slice(&x.to_le_bytes()); self }
    fn u32(&mut self, x: u32) -> &mut Self { self.0.extend_from_slice(&x.to_le_bytes()); self }
    fn f32(&mut self, x: f32) -> &mut Self { self.0.extend_from_slice(&x.to_le_bytes()); self }
    fn байты(&mut self, b: &[u8]) -> &mut Self { self.0.extend_from_slice(b); self }
    /// Строка: длина одним байтом + utf-8. Имена длиннее 255 байт не бывают,
    /// а короткая длина экономит место в «Участниках», которые шлются часто.
    fn строка(&mut self, s: &str) -> &mut Self {
        let b = s.as_bytes();
        let n = b.len().min(255);
        self.0.push(n as u8);
        self.0.extend_from_slice(&b[..n]);
        self
    }
    fn готово(mut self) -> Vec<u8> {
        let длина = (self.0.len() - 4) as u32;
        self.0[..4].copy_from_slice(&длина.to_le_bytes());
        self.0
    }
}

impl ОтХоста {
    pub fn в_байты(&self) -> Vec<u8> {
        match self {
            ОтХоста::Вызов { соль } => {
                let mut с = Сборщик::new(тип::ВЫЗОВ);
                с.байты(соль);
                с.готово()
            }
            ОтХоста::Добро { id, цвет, w, h, кодек } => {
                let mut с = Сборщик::new(тип::ДОБРО);
                с.u16(ВЕРСИЯ).u8(*id).u32(*цвет).u16(*w).u16(*h).u8(*кодек as u8);
                с.готово()
            }
            ОтХоста::Кадр { номер, ключевой, данные } => {
                let mut с = Сборщик::new(тип::КАДР);
                с.u32(*номер).u8(u8::from(*ключевой)).u32(данные.len() as u32).байты(данные);
                с.готово()
            }
            ОтХоста::Участники(список) => {
                let mut с = Сборщик::new(тип::УЧАСТНИКИ);
                с.u8(список.len().min(255) as u8);
                for у in список.iter().take(255) {
                    с.u8(у.id).u32(у.цвет).f32(у.курсор.0).f32(у.курсор.1).строка(&у.имя);
                }
                с.готово()
            }
            ОтХоста::КамераХоста { x, y, zoom } => {
                let mut с = Сборщик::new(тип::КАМЕРА_ХОСТА);
                с.f32(*x).f32(*y).f32(*zoom);
                с.готово()
            }
            ОтХоста::Отказ { причина } => {
                let mut с = Сборщик::new(тип::ОТКАЗ);
                с.строка(причина);
                с.готово()
            }
            ОтХоста::Прощай => Сборщик::new(тип::ПРОЩАЙ).готово(),
            ОтХоста::Размер { w, h } => {
                let mut с = Сборщик::new(тип::РАЗМЕР);
                с.u16(*w).u16(*h);
                с.готово()
            }
        }
    }
}

impl ОтГостя {
    pub fn в_байты(&self) -> Vec<u8> {
        match self {
            ОтГостя::Привет { версия, имя, доказательство } => {
                let mut с = Сборщик::new(тип::ПРИВЕТ);
                с.u16(*версия).строка(имя).байты(доказательство);
                с.готово()
            }
            ОтГостя::Курсор { x, y } => {
                let mut с = Сборщик::new(тип::КУРСОР);
                с.f32(*x).f32(*y);
                с.готово()
            }
            ОтГостя::Кнопка { код, нажата } => {
                let mut с = Сборщик::new(тип::КНОПКА);
                с.u32(*код).u8(u8::from(*нажата));
                с.готово()
            }
            ОтГостя::Колесо { dx, dy } => {
                let mut с = Сборщик::new(тип::КОЛЕСО);
                с.f32(*dx).f32(*dy);
                с.готово()
            }
            ОтГостя::Клавиша { код, нажата } => {
                let mut с = Сборщик::new(тип::КЛАВИША);
                с.u32(*код).u8(u8::from(*нажата));
                с.готово()
            }
            ОтГостя::Вид { cam_x, cam_y, zoom, w, h } => {
                let mut с = Сборщик::new(тип::ВИД);
                с.f32(*cam_x).f32(*cam_y).f32(*zoom).u16(*w).u16(*h);
                с.готово()
            }
            ОтГостя::ЗаХостом { включено } => {
                let mut с = Сборщик::new(тип::ЗА_ХОСТОМ);
                с.u8(u8::from(*включено));
                с.готово()
            }
            ОтГостя::Пока => Сборщик::new(тип::ПОКА).готово(),
        }
    }
}

// ── Разбор ───────────────────────────────────────────────────────────────────

/// Читалка по срезу: каждое взятие проверяет остаток. Ни одного `unwrap` на
/// длине — сообщение приходит из сети, и обрезанное поле обязано давать
/// ошибку разбора, а не панику композитора.
struct Чтец<'a> {
    b: &'a [u8],
    i: usize,
}

impl<'a> Чтец<'a> {
    fn new(b: &'a [u8]) -> Self { Self { b, i: 0 } }
    fn взять(&mut self, n: usize) -> Option<&'a [u8]> {
        let кусок = self.b.get(self.i..self.i + n)?;
        self.i += n;
        Some(кусок)
    }
    fn u8(&mut self) -> Option<u8> { Some(self.взять(1)?[0]) }
    fn bool(&mut self) -> Option<bool> { Some(self.u8()? != 0) }
    fn u16(&mut self) -> Option<u16> { Some(u16::from_le_bytes(self.взять(2)?.try_into().ok()?)) }
    fn u32(&mut self) -> Option<u32> { Some(u32::from_le_bytes(self.взять(4)?.try_into().ok()?)) }
    fn f32(&mut self) -> Option<f32> { Some(f32::from_le_bytes(self.взять(4)?.try_into().ok()?)) }
    fn массив32(&mut self) -> Option<[u8; 32]> { self.взять(32)?.try_into().ok() }
    fn массив16(&mut self) -> Option<[u8; 16]> { self.взять(16)?.try_into().ok() }
    fn строка(&mut self) -> Option<String> {
        let n = self.u8()? as usize;
        Some(String::from_utf8_lossy(self.взять(n)?).into_owned())
    }
}

impl ОтГостя {
    /// `None` — сообщение не разобралось (чужая версия, обрезано, неизвестный
    /// тип). Вызывающий обязан на этом РВАТЬ соединение: продолжать читать
    /// поток, в котором не понял одно сообщение, нельзя — границы уже потеряны.
    pub fn из_байт(тело: &[u8]) -> Option<Self> {
        let mut ч = Чтец::new(тело);
        let т = ч.u8()?;
        Some(match т {
            тип::ПРИВЕТ => ОтГостя::Привет {
                версия: ч.u16()?,
                имя: ч.строка()?,
                доказательство: ч.массив32()?,
            },
            тип::КУРСОР => ОтГостя::Курсор { x: ч.f32()?, y: ч.f32()? },
            тип::КНОПКА => ОтГостя::Кнопка { код: ч.u32()?, нажата: ч.bool()? },
            тип::КОЛЕСО => ОтГостя::Колесо { dx: ч.f32()?, dy: ч.f32()? },
            тип::КЛАВИША => ОтГостя::Клавиша { код: ч.u32()?, нажата: ч.bool()? },
            тип::ВИД => ОтГостя::Вид {
                cam_x: ч.f32()?, cam_y: ч.f32()?, zoom: ч.f32()?,
                w: ч.u16()?, h: ч.u16()?,
            },
            тип::ЗА_ХОСТОМ => ОтГостя::ЗаХостом { включено: ч.bool()? },
            тип::ПОКА => ОтГостя::Пока,
            _ => return None,
        })
    }
}

impl ОтХоста {
    pub fn из_байт(тело: &[u8]) -> Option<Self> {
        let mut ч = Чтец::new(тело);
        let т = ч.u8()?;
        Some(match т {
            тип::ВЫЗОВ => ОтХоста::Вызов { соль: ч.массив16()? },
            тип::ДОБРО => {
                let версия = ч.u16()?;
                if версия != ВЕРСИЯ {
                    return None;
                }
                ОтХоста::Добро {
                    id: ч.u8()?,
                    цвет: ч.u32()?,
                    w: ч.u16()?,
                    h: ч.u16()?,
                    кодек: Кодек::из_числа(ч.u8()?)?,
                }
            }
            тип::КАДР => {
                let номер = ч.u32()?;
                let ключевой = ч.bool()?;
                let n = ч.u32()? as usize;
                ОтХоста::Кадр { номер, ключевой, данные: ч.взять(n)?.to_vec() }
            }
            тип::УЧАСТНИКИ => {
                let n = ч.u8()? as usize;
                let mut список = Vec::with_capacity(n);
                for _ in 0..n {
                    список.push(Участник {
                        id: ч.u8()?,
                        цвет: ч.u32()?,
                        курсор: (ч.f32()?, ч.f32()?),
                        имя: ч.строка()?,
                    });
                }
                ОтХоста::Участники(список)
            }
            тип::КАМЕРА_ХОСТА => ОтХоста::КамераХоста { x: ч.f32()?, y: ч.f32()?, zoom: ч.f32()? },
            тип::ОТКАЗ => ОтХоста::Отказ { причина: ч.строка()? },
            тип::ПРОЩАЙ => ОтХоста::Прощай,
            тип::РАЗМЕР => ОтХоста::Размер { w: ч.u16()?, h: ч.u16()? },
            _ => return None,
        })
    }
}

// ── Поток ────────────────────────────────────────────────────────────────────

/// Накопитель входящего потока: TCP отдаёт куски произвольного размера, а
/// сообщения из них надо собирать целиком.
#[derive(Default)]
pub struct Поток {
    буфер: Vec<u8>,
}

impl Поток {
    pub fn new() -> Self { Self::default() }

    /// Дописать сырые байты из сокета.
    pub fn дописать(&mut self, кусок: &[u8]) {
        self.буфер.extend_from_slice(кусок);
    }

    /// Достать следующее ЦЕЛОЕ сообщение, если оно уже пришло.
    /// `Err(())` — длина за пределом: соединение рвём.
    pub fn следующее(&mut self) -> Result<Option<Vec<u8>>, ()> {
        if self.буфер.len() < 4 {
            return Ok(None);
        }
        let длина = u32::from_le_bytes(self.буфер[..4].try_into().unwrap()) as usize;
        if длина == 0 || длина > ПРЕДЕЛ_КАДРА {
            return Err(());
        }
        if self.буфер.len() < 4 + длина {
            return Ok(None);
        }
        let тело = self.буфер[4..4 + длина].to_vec();
        self.буфер.drain(..4 + длина);
        Ok(Some(тело))
    }

    /// Сколько байт лежит непрожёванным — для замера «клиент не успевает».
    pub fn остаток(&self) -> usize { self.буфер.len() }
}

/// Записать сообщение в сокет целиком (блокирующе). Используется на коротких
/// служебных сообщениях; видеокадры идут через неблокирующую очередь, см.
/// `net.rs`.
pub fn послать<W: Write>(w: &mut W, сообщение: &[u8]) -> io::Result<()> {
    w.write_all(сообщение)
}

/// Прочитать ровно одно сообщение блокирующе — нужно клиенту на рукопожатии,
/// где иначе пришлось бы городить состояние ради двух пакетов.
pub fn принять<R: Read>(r: &mut R) -> io::Result<Vec<u8>> {
    let mut заголовок = [0u8; 4];
    r.read_exact(&mut заголовок)?;
    let длина = u32::from_le_bytes(заголовок) as usize;
    if длина == 0 || длина > ПРЕДЕЛ_КАДРА {
        return Err(io::Error::new(io::ErrorKind::InvalidData, "длина кадра вне предела"));
    }
    let mut тело = vec![0u8; длина];
    r.read_exact(&mut тело)?;
    Ok(тело)
}

// ── Код доступа ──────────────────────────────────────────────────────────────

/// Доказательство знания кода: `sha256(соль ‖ код)`.
///
/// Сам код по проводу не идёт, а соль у каждого соединения своя — поэтому
/// подслушанное доказательство нельзя переиграть на следующем подключении.
/// Это не замена шифрованию канала (его тут нет): цель скромнее — чтобы
/// сосед по локалке не подключился к чужому столу, зная только адрес.
pub fn доказательство(соль: &[u8; 16], код: &str) -> [u8; 32] {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(соль);
    h.update(код.as_bytes());
    h.finalize().into()
}

/// Код из шести цифр — его человек диктует голосом, поэтому не буквы
/// («эс» против «эф» по телефону) и не длиннее.
pub fn новый_код() -> String {
    let n = случайные_байты::<3>();
    let число = u32::from(n[0]) << 16 | u32::from(n[1]) << 8 | u32::from(n[2]);
    format!("{:06}", число % 1_000_000)
}

/// Случайные байты из `/dev/urandom`. Своего генератора не заводим: соль и код
/// — единственное место, где случайность нужна, а тянуть `rand` ради этого
/// незачем. Отказ файла — не молчаливый ноль: лучше упасть в предсказуемое
/// «не смогли», чем раздать предсказуемую соль.
pub fn случайные_байты<const N: usize>() -> [u8; N] {
    let mut b = [0u8; N];
    match std::fs::File::open("/dev/urandom").and_then(|mut f| f.read_exact(&mut b)) {
        Ok(()) => b,
        Err(e) => {
            tracing::error!("dawn/share: /dev/urandom недоступен ({e}) — соль вырождена");
            b
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn сообщения_гостя_ходят_туда_и_обратно() {
        let образцы = [
            ОтГостя::Привет { версия: ВЕРСИЯ, имя: "Ярик".into(), доказательство: [7u8; 32] },
            ОтГостя::Курсор { x: 12.5, y: -3.25 },
            ОтГостя::Кнопка { код: 0x110, нажата: true },
            ОтГостя::Колесо { dx: 0.0, dy: -1.0 },
            ОтГостя::Клавиша { код: 30, нажата: false },
            ОтГостя::Вид { cam_x: -100.0, cam_y: 50.0, zoom: 0.75, w: 1920, h: 1080 },
            ОтГостя::ЗаХостом { включено: true },
            ОтГостя::Пока,
        ];
        for о in образцы {
            let байты = о.в_байты();
            // Длина в заголовке обязана совпадать с фактом — иначе поток
            // разъедется на следующем же сообщении.
            let длина = u32::from_le_bytes(байты[..4].try_into().unwrap()) as usize;
            assert_eq!(длина, байты.len() - 4, "длина не совпала у {о:?}");
            assert_eq!(ОтГостя::из_байт(&байты[4..]), Some(о));
        }
    }

    #[test]
    fn сообщения_хоста_ходят_туда_и_обратно() {
        let образцы = [
            ОтХоста::Вызов { соль: [3u8; 16] },
            ОтХоста::Добро { id: 2, цвет: 0xff8800, w: 1920, h: 1080, кодек: Кодек::H264 },
            ОтХоста::Кадр { номер: 42, ключевой: true, данные: vec![1, 2, 3, 4] },
            ОтХоста::Участники(vec![
                Участник { id: 0, цвет: 1, имя: "хост".into(), курсор: (1.0, 2.0) },
                Участник { id: 1, цвет: 2, имя: "гость".into(), курсор: (-5.0, 0.0) },
            ]),
            ОтХоста::КамераХоста { x: 10.0, y: 20.0, zoom: 1.5 },
            ОтХоста::Отказ { причина: "неверный код".into() },
            ОтХоста::Прощай,
            ОтХоста::Размер { w: 1280, h: 800 },
        ];
        for о in образцы {
            let байты = о.в_байты();
            assert_eq!(ОтХоста::из_байт(&байты[4..]), Some(о));
        }
    }

    #[test]
    fn поток_собирает_разрезанное_сообщение() {
        let целое = ОтГостя::Курсор { x: 1.0, y: 2.0 }.в_байты();
        let mut п = Поток::new();
        // По одному байту — худший случай TCP.
        for i in 0..целое.len() - 1 {
            п.дописать(&целое[i..i + 1]);
            assert_eq!(п.следующее(), Ok(None), "сообщение выдано недособранным");
        }
        п.дописать(&целое[целое.len() - 1..]);
        let тело = п.следующее().unwrap().expect("сообщение не собралось");
        assert_eq!(ОтГостя::из_байт(&тело), Some(ОтГостя::Курсор { x: 1.0, y: 2.0 }));
    }

    #[test]
    fn поток_отдаёт_два_сообщения_из_одного_куска() {
        let mut п = Поток::new();
        let mut склейка = ОтГостя::Пока.в_байты();
        склейка.extend_from_slice(&ОтГостя::Курсор { x: 5.0, y: 6.0 }.в_байты());
        п.дописать(&склейка);
        assert!(matches!(
            ОтГостя::из_байт(&п.следующее().unwrap().unwrap()),
            Some(ОтГостя::Пока)
        ));
        assert!(matches!(
            ОтГостя::из_байт(&п.следующее().unwrap().unwrap()),
            Some(ОтГостя::Курсор { .. })
        ));
        assert_eq!(п.следующее(), Ok(None));
    }

    #[test]
    fn запредельная_длина_рвёт_соединение() {
        let mut п = Поток::new();
        п.дописать(&u32::MAX.to_le_bytes());
        assert_eq!(п.следующее(), Err(()));
    }

    #[test]
    fn обрезанное_поле_не_паникует() {
        let целое = ОтГостя::Привет {
            версия: ВЕРСИЯ, имя: "гость".into(), доказательство: [0u8; 32],
        }.в_байты();
        // Отрезаем хвост доказательства: разбор обязан вернуть None.
        assert_eq!(ОтГостя::из_байт(&целое[4..целое.len() - 5]), None);
    }

    #[test]
    fn чужая_версия_хоста_не_принимается() {
        let mut байты = ОтХоста::Добро {
            id: 1, цвет: 0, w: 100, h: 100, кодек: Кодек::H264,
        }.в_байты();
        // Поле версии — сразу после длины и типа.
        байты[5..7].copy_from_slice(&(ВЕРСИЯ + 1).to_le_bytes());
        assert_eq!(ОтХоста::из_байт(&байты[4..]), None);
    }

    #[test]
    fn доказательство_зависит_и_от_соли_и_от_кода() {
        let a = доказательство(&[1u8; 16], "123456");
        let b = доказательство(&[2u8; 16], "123456");
        let c = доказательство(&[1u8; 16], "654321");
        assert_ne!(a, b, "соль не участвует — подслушанное можно переиграть");
        assert_ne!(a, c, "код не участвует — пустит кого угодно");
    }

    /// У гостя (`dshare`) лежит КОПИЯ этого файла: клиент собирается на чужой
    /// машине, где dawn нет, поэтому общего крейта быть не может.
    ///
    /// Разошедшийся протокол — самая дорогая ошибка в этой затее: обе стороны
    /// собираются, обе работают, а по проводу едет мусор, и виноватым выглядит
    /// что угодно, кроме настоящей причины. Тест сравнивает файлы дословно.
    /// Копии рядом нет (dshare не выложен на этой машине) — тест молчит: он
    /// сторожит расхождение, а не наличие клиента.
    #[test]
    fn копия_протокола_не_разошлась() {
        let свой = include_str!("proto.rs");
        for путь in ["../dshare/src/proto.rs", "../../dshare/src/proto.rs"] {
            let Ok(копия) = std::fs::read_to_string(путь) else { continue };
            assert_eq!(
                копия, свой,
                "{путь} разошёлся с dawn/src/share/proto.rs — хост и гость \
                 будут понимать друг друга по-разному",
            );
            return;
        }
    }

    #[test]
    fn код_всегда_шесть_цифр() {
        for _ in 0..64 {
            let к = новый_код();
            assert_eq!(к.len(), 6, "код не шестизначный: {к}");
            assert!(к.chars().all(|c| c.is_ascii_digit()), "в коде не только цифры: {к}");
        }
    }
}
