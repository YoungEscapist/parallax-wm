//! Мультиюзер: до пяти человек за одним бесконечным холстом.
//!
//! **Что это.** Хост раздаёт СВОЙ рабочий стол; гости подключаются
//! приложением `dshare` по адресу и шестизначному коду. У каждого гостя своя
//! камера по общему холсту (можно прилипнуть к камере хоста кнопкой), свой
//! курсор своего цвета и — по решению Ярика 25.08.2026 — полный доступ:
//! двигать окна, тянуть за края, кликать и печатать.
//!
//! **Почему только floating и только холст.** Пока раздача идёт, тайлинг и
//! рабочие столы ВЫКЛЮЧАЮТСЯ (это тоже требование, не упрощение). Причина
//! внятная: тайловая раскладка — это одно дерево на один экран, а тут пять
//! человек в разных местах бесконечного холста; «перетасовать всем окна,
//! потому что кто-то открыл терминал» — ровно то, чего не должно быть.
//! Столы выключены по той же причине: тег — это «что показывать на экране»,
//! а экранов теперь пять, и переключение тега одним человеком выдернуло бы
//! картинку у остальных. Бесконечный холст даёт то же самое без конфликта:
//! разошлись по разным местам — и не мешаете друг другу.
//!
//! **Как оно устроено.** Три слоя, каждый в своём файле:
//! * `proto.rs` — что летает по проводу (и только это);
//! * `net.rs` — сокеты, приём, очередь на отправку, calloop;
//! * этот файл — состояние сессии: кто подключён, чья камера, чей курсор,
//!   и что происходит с самим dawn, пока раздача идёт.
//!
//! Видео (кадр на каждого гостя со своей камеры) живёт в `video.rs`.

pub mod net;
pub mod proto;
pub mod render;
pub mod seat;
pub mod video;

use std::net::TcpStream;
use std::time::Instant;

use smithay::reexports::calloop::RegistrationToken;

use crate::Dawn;

/// Цвета участников по номеру. Первый — хозяин машины.
///
/// Подобраны так, чтобы различаться и на светлых, и на тёмных обоях, и не
/// сливаться с синей рамкой выделения самого dawn.
pub const ЦВЕТА: [u32; 6] = [
    0xff_e8_c0_50, // хост — тёплый жёлтый
    0xff_5b_c8_ff, // голубой
    0xff_7d_e0_8d, // зелёный
    0xff_ff_8a_5b, // оранжевый
    0xff_c8_8a_ff, // сиреневый
    0xff_ff_6b_9d, // розовый
];

pub fn цвет(id: u8) -> u32 {
    ЦВЕТА[(id as usize) % ЦВЕТА.len()]
}

/// Размер к чётным сторонам. h264 кодирует макроблоками, и с `yuv420p` ffmpeg
/// на нечётной стороне просто откажется стартовать — а отказ кодировщика
/// выглядит снаружи как «у гостя чёрный экран», без единого намёка на причину.
fn чётный((w, h): (u16, u16)) -> (u16, u16) {
    (w & !1, h & !1)
}

/// Один подключившийся.
pub struct Гость {
    pub id: u8,
    pub имя: String,
    pub цвет: u32,
    /// Сокет для ЗАПИСИ. Чтение идёт через дубликат внутри источника calloop
    /// (`try_clone`): источник владеет своим дескриптором, а очередь на
    /// отправку живёт здесь, в состоянии, и наполняется из рендера.
    pub сокет: TcpStream,
    pub токен: Option<RegistrationToken>,
    /// Откуда подключился — для показа в панели и для бана.
    pub адрес: std::net::IpAddr,
    /// Соль этого соединения — под неё считается доказательство кода.
    pub соль: [u8; 16],
    /// До «Привета» с верным доказательством гость не получает НИЧЕГО:
    /// ни кадров, ни списка участников, ни права шевелить окна.
    pub впущен: bool,
    /// Куда смотрит гость: своя камера по общему холсту.
    pub камера: (f64, f64, f64),
    /// Какого размера ему рисовать кадр — размер ОКНА гостя, как он его
    /// прислал в `Вид`.
    pub кадр: (u16, u16),
    /// Размер, в котором СЕЙЧАС работает кодировщик и который гость ждёт от
    /// декодера. Отстаёт от `кадр`, пока гость тянет окно: смена размера — это
    /// перезапуск ffmpeg и пересборка декодера на той стороне, и делать это на
    /// каждый пиксель тяги за угол нельзя.
    pub кадр_кодировщика: (u16, u16),
    /// Когда кодировщик последний раз пересобирали под новый размер.
    pub размер_сменён: Instant,
    /// Прилипнуть к камере хоста.
    pub за_хостом: bool,
    /// Где его курсор НА ХОЛСТЕ (не на экране): курсор рисуется всем
    /// остальным, а холст у всех общий.
    pub курсор: (f64, f64),
    /// Исходящая очередь: главный цикл кладёт, пишущий поток гостя забирает
    /// (см. net.rs — почему запись вынесена из цикла композитора).
    pub исходящие: std::sync::Arc<net::Очередь>,
    pub номер_кадра: u32,
    pub последний_кадр: Instant,
    pub кодировщик: Option<video::Кодировщик>,
    /// Своё место (wl_seat): свой курсор, свой фокус, своя клавиатура.
    /// Заводится при впуске — до проверки кода гостю не положено ничего.
    pub место: Option<smithay::input::Seat<Dawn>>,
    /// Живой ли ещё: рвём соединение отложенно, из главного цикла, а не из
    /// середины разбора сообщения.
    pub жив: bool,
}

impl Гость {
    /// Сколько сообщений ждёт отправки — по этому числу видно, что гость не
    /// успевает (кадры для него начинают роняться).
    pub fn долг(&self) -> usize {
        self.исходящие.длина()
    }
}

/// Состояние раздачи. `None` в [`Dawn`] — мультиюзера нет вовсе, и ни одна
/// проверка ниже ничего не стоит.
pub struct Раздача {
    pub порт: u16,
    pub код: String,
    pub гости: Vec<Гость>,
    pub следующий_id: u8,
    /// Забаненные адреса: соединение с них закрывается сразу после accept,
    /// до соли и до кода.
    ///
    /// Живёт ровно столько, сколько идёт эта раздача, и на диск не пишется:
    /// бан — это «выгнать вот этого прямо сейчас», а не список врагов на годы.
    /// Пересоздавать его при каждом включении честнее, чем однажды забыть, кого
    /// забанил месяц назад, и полдня искать, почему друг не подключается.
    pub бан: Vec<std::net::IpAddr>,
    /// Открыта ли панель управления (повторное Super+Shift+S) и что в ней
    /// выбрано.
    pub панель: bool,
    pub выбран: usize,
    pub токен_слушателя: Option<RegistrationToken>,
    /// Размер выхода хоста на момент включения раздачи — справочно, для
    /// `dawn-share` и логов.
    ///
    /// **Кадром гостя это быть перестало 30.08.2026.** Раньше в этом размере
    /// рисовали всем, а вписывал картинку в своё окно сам гость. Мешало
    /// ровно одно: `capture` строил damage tracker по геометрии ВЫХОДА, и
    /// буфер другого размера не ужимал сцену, а обрезал её углом. Починено в
    /// `screencopy::capture` (трекер строится по запрошенному размеру), и
    /// теперь у каждого гостя своё разрешение — размер его окна, см.
    /// `Гость::кадр_кодировщика` и `раздача_подогнать_размеры`.
    pub кадр: (u32, u32),
    /// Имя выхода, с геометрии которого считается кадр гостям.
    ///
    /// Нужно именно имя, а не сам `Output`: у Ярика два монитора, а
    /// `render_surface` зовётся на КАЖДЫЙ CRTC — без этой отсечки гость получал
    /// бы вперемешку два потока разного размера с двух экранов.
    pub выход: String,
    /// Сколько элементов было в прошлом кадре гостю — резерв под вектор,
    /// ровно как `Surface::last_elements` у монитора.
    pub последних_элементов: usize,
    /// Что было до раздачи — вернём при остановке.
    pub прежняя_раскладка: crate::tiling::Layout,
    pub прежний_холст: bool,
    /// Когда в последний раз рассылали список участников: он меняется на
    /// каждое движение чужого курсора, а слать это 200 раз в секунду незачем.
    pub список_разослан: Instant,
}

impl Раздача {
    pub fn гость(&mut self, id: u8) -> Option<&mut Гость> {
        self.гости.iter_mut().find(|г| г.id == id)
    }

    /// Список для рассылки: хост нулевым, затем впущенные гости.
    pub fn участники(&self, курсор_хоста: (f64, f64), имя_хоста: &str) -> Vec<proto::Участник> {
        let mut список = vec![proto::Участник {
            id: 0,
            цвет: цвет(0),
            имя: имя_хоста.to_string(),
            курсор: (курсор_хоста.0 as f32, курсор_хоста.1 as f32),
        }];
        for г in self.гости.iter().filter(|г| г.впущен) {
            список.push(proto::Участник {
                id: г.id,
                цвет: г.цвет,
                имя: г.имя.clone(),
                курсор: (г.курсор.0 as f32, г.курсор.1 as f32),
            });
        }
        список
    }
}

impl Dawn {
    pub fn раздача_идёт(&self) -> bool {
        self.раздача.is_some()
    }

    /// Включить раздачу. Возвращает код, который человек говорит гостям.
    ///
    /// Порт 0 означает «как в протоколе» ([`proto::ПОРТ`]).
    pub fn раздача_начать(&mut self, порт: u16) -> Result<String, String> {
        if self.раздача.is_some() {
            return Err("раздача уже идёт".into());
        }
        let порт = if порт == 0 { proto::ПОРТ } else { порт };
        let код = proto::новый_код();

        // Режим переключаем ДО того, как кого-то пустили: гость не должен
        // увидеть переезд окон из тайлинга во float как первое, что произошло
        // на его экране.
        let прежняя_раскладка = self.tile_config.layout;
        let прежний_холст = self.viewport.canvas_mode;
        self.включить_режим_холста();

        // Размер кадра — чётный: h264 кодирует макроблоками 16×16, и на
        // нечётной стороне ffmpeg с yuv420p просто откажется стартовать.
        let экран = self.screen_size();
        let кадр = (
            (экран.w.max(160) as u32) & !1,
            (экран.h.max(120) as u32) & !1,
        );
        // Тот же выход, из которого взят размер: `screen_size` смотрит на
        // первый в `space`, и кадр гостям обязан считаться с него же.
        let выход = self.space.outputs().next().map(|o| o.name()).unwrap_or_default();

        match net::слушать(self, порт) {
            Ok(токен) => {
                self.раздача = Some(Раздача {
                    порт,
                    код: код.clone(),
                    гости: Vec::new(),
                    следующий_id: 1,
                    бан: Vec::new(),
                    панель: false,
                    выбран: 0,
                    токен_слушателя: Some(токен),
                    кадр,
                    выход,
                    последних_элементов: 0,
                    прежняя_раскладка,
                    прежний_холст,
                    список_разослан: Instant::now(),
                });
                tracing::info!(
                    "dawn/share: раздача включена, порт {}, код {}, кадр {}×{} (до {} гостей)",
                    порт, код, кадр.0, кадр.1, proto::МАКС_ГОСТЕЙ,
                );
                self.request_redraw();
                Ok(код)
            }
            Err(e) => {
                // Режим возвращаем: раздачи не случилось, а холст молча
                // остался бы включённым.
                self.tile_config.layout = прежняя_раскладка;
                self.viewport.canvas_mode = прежний_холст;
                Err(format!("не занять порт {порт}: {e}"))
            }
        }
    }

    /// Включить раздачу по бинду или по `ctl`: отказ не роняет ничего, но и
    /// молчать о нём нельзя — человек нажал и ждёт код.
    pub fn раздача_по_команде(&mut self, порт: u16) {
        match self.раздача_начать(порт) {
            Ok(код) => tracing::info!("dawn/share: код доступа {код}"),
            Err(причина) => tracing::warn!("dawn/share: раздача не включилась: {причина}"),
        }
    }

    /// Выключить раздачу: попрощаться со всеми, снять источники, вернуть режим.
    pub fn раздача_закончить(&mut self) {
        let Some(mut раздача) = self.раздача.take() else { return };
        // «Прощай» кладём ВСЕМ, потом ждём один раз и только потом закрываем
        // очереди. Раньше пауза стояла внутри цикла — то есть каждый гость
        // получал свои 5 мс, а последний ждал пятикратно дольше первого; на
        // прощание с пятью гостями это 25 мс застывшего экрана у хозяина.
        // Пауза нужна, потому что пишет отдельный поток: закрой очередь сразу,
        // и он выйдет, не успев отдать прощание, — гость увидит просто обрыв.
        for гость in &mut раздача.гости {
            гость.исходящие.положить(proto::ОтХоста::Прощай.в_байты(), false);
        }
        if !раздача.гости.is_empty() {
            std::thread::sleep(std::time::Duration::from_millis(20));
        }
        for гость in &mut раздача.гости {
            гость.исходящие.закрыть();
        }
        let токены: Vec<RegistrationToken> = раздача
            .гости
            .iter()
            .filter_map(|г| г.токен)
            .chain(раздача.токен_слушателя)
            .collect();
        for т in токены {
            self.петля.remove(т);
        }
        // Места убираем ПОСЛЕ источников: пока источник жив, из него может
        // прийти ещё одно сообщение, и оно пошло бы в место, которого уже нет.
        // Кодировщики умирают сами со сбросом `Гость` (см. video::Drop).
        for место in раздача.гости.iter_mut().filter_map(|г| г.место.take()) {
            seat::убрать(self, место);
        }
        self.tile_config.layout = раздача.прежняя_раскладка;
        self.viewport.canvas_mode = раздача.прежний_холст;
        self.arrange();
        tracing::info!("dawn/share: раздача выключена");
        self.request_redraw();
    }

    /// Режим, в котором работает мультиюзер: только float, только холст.
    fn включить_режим_холста(&mut self) {
        self.tile_config.layout = crate::tiling::Layout::Float;
        self.viewport.canvas_mode = true;
        // Обзор столов и полный экран выключаем: и то, и другое — «весь экран
        // одному», а экранов теперь несколько.
        if self.overview_active {
            self.exit_overview_immediate(None);
        }
        self.arrange();
    }

    /// Пришло сообщение от гостя. Возвращает `false`, если соединение надо
    /// закрыть (протокол нарушен, гость попрощался, код не тот).
    pub fn раздача_сообщение(&mut self, id: u8, сообщение: proto::ОтГостя) -> bool {
        use proto::ОтГостя as М;
        // Всё, кроме «Привета», требует впуска. Это не паранойя: до проверки
        // кода собеседник — просто кто-то, открывший порт.
        let впущен = self
            .раздача
            .as_ref()
            .and_then(|р| р.гости.iter().find(|г| г.id == id))
            .map(|г| г.впущен)
            .unwrap_or(false);
        if !впущен && !matches!(сообщение, М::Привет { .. }) {
            tracing::warn!("dawn/share: гость {id} шлёт {сообщение:?} до впуска — рвём");
            return false;
        }

        match сообщение {
            М::Привет { версия, имя, доказательство } => self.раздача_впустить(id, версия, имя, доказательство),
            М::Вид { cam_x, cam_y, zoom, w, h } => {
                let за_хостом = self
                    .раздача
                    .as_ref()
                    .and_then(|р| р.гости.iter().find(|г| г.id == id))
                    .map(|г| г.за_хостом)
                    .unwrap_or(false);
                let (hx, hy, hz) = (self.viewport.cam_x, self.viewport.cam_y, self.viewport.zoom);
                if let Some(г) = self.раздача.as_mut().and_then(|р| р.гость(id)) {
                    // Кадр гостя ограничиваем сверху: он приходит из сети, и
                    // «дай мне 30000×30000» — это гигабайты в рендере.
                    г.кадр = (w.clamp(160, 4096), h.clamp(120, 2304));
                    г.камера = if за_хостом {
                        (hx, hy, hz)
                    } else {
                        (cam_x as f64, cam_y as f64, (zoom as f64).clamp(0.05, 8.0))
                    };
                }
                true
            }
            М::ЗаХостом { включено } => {
                let (hx, hy, hz) = (self.viewport.cam_x, self.viewport.cam_y, self.viewport.zoom);
                if let Some(г) = self.раздача.as_mut().and_then(|р| р.гость(id)) {
                    г.за_хостом = включено;
                    if включено {
                        г.камера = (hx, hy, hz);
                    }
                }
                true
            }
            М::Курсор { x, y } => {
                self.раздача_курсор(id, x as f64, y as f64);
                true
            }
            М::Кнопка { код, нажата } => {
                self.гостевая_кнопка(id, код, нажата);
                true
            }
            М::Колесо { dx, dy } => {
                self.гостевое_колесо(id, dx as f64, dy as f64);
                true
            }
            М::Клавиша { код, нажата } => {
                self.гостевая_клавиша(id, код, нажата);
                true
            }
            М::Пока => false,
        }
    }

    /// Проверка кода и впуск.
    fn раздача_впустить(&mut self, id: u8, версия: u16, имя: String, доказательство: [u8; 32]) -> bool {
        let Some(раздача) = self.раздача.as_mut() else { return false };
        let код = раздача.код.clone();
        let Some(гость) = раздача.гость(id) else { return false };
        if гость.впущен {
            tracing::warn!("dawn/share: гость {id} здоровается дважды — рвём");
            return false;
        }
        if версия != proto::ВЕРСИЯ {
            let отказ = proto::ОтХоста::Отказ {
                причина: format!("версия протокола {} против {}", версия, proto::ВЕРСИЯ),
            };
            гость.исходящие.положить(отказ.в_байты(), false);
            tracing::warn!("dawn/share: гость {id} с версией {версия} — отказ");
            return false;
        }
        let ожидаемое = proto::доказательство(&гость.соль, &код);
        // Сравнение за постоянное время: побайтовое `==` с ранним выходом
        // подсказывает подбирающему, сколько байт он уже угадал.
        let сходится = ожидаемое
            .iter()
            .zip(доказательство.iter())
            .fold(0u8, |acc, (a, b)| acc | (a ^ b))
            == 0;
        if !сходится {
            гость.исходящие.положить(
                proto::ОтХоста::Отказ { причина: "неверный код".into() }.в_байты(),
                false,
            );
            tracing::warn!("dawn/share: гость {id} назвал неверный код — отказ");
            return false;
        }

        гость.впущен = true;
        гость.имя = if имя.trim().is_empty() { format!("гость {id}") } else { имя };
        // Стартовый размер — тот, что записан у гостя (пока это значение по
        // умолчанию: настоящий размер окна приедет первым же `Вид`, и через
        // полсекунды `раздача_подогнать_размеры` пересоберёт поток под него).
        //
        // Числа в `Добро` обязаны совпадать с тем, в чём НА САМОМ ДЕЛЕ
        // запускается кодировщик двумя десятками строк ниже: по ним гость
        // заводит декодер, и разойдись они — он развернул бы поток не тем
        // размером и показал бы кашу.
        let (w, h) = чётный(гость.кадр);
        гость.кадр_кодировщика = (w, h);
        гость.размер_сменён = Instant::now();
        let гость = раздача.гость(id).expect("гость только что был");
        let добро = proto::ОтХоста::Добро {
            id,
            цвет: гость.цвет,
            w,
            h,
            кодек: video::КОДЕК,
        };
        let имя_гостя = гость.имя.clone();
        let исходящие = гость.исходящие.clone();
        исходящие.положить(добро.в_байты(), false);

        // Кодировщик и место заводим ТОЛЬКО здесь, после проверки кода: до неё
        // собеседник — просто кто-то, открывший порт, и поднимать ради него
        // процесс ffmpeg и глобал wl_seat нельзя (это и ресурсы, и видимый
        // клиентам объект).
        let кодировщик = video::Кодировщик::запустить(id, w as u32, h as u32, исходящие);
        if кодировщик.is_none() {
            tracing::warn!("dawn/share: гость {id} без кодировщика — картинки не будет");
        }
        let место = seat::завести(self, id, &имя_гостя);
        if let Some(г) = self.раздача.as_mut().and_then(|р| р.гость(id)) {
            г.кодировщик = кодировщик;
            г.место = место;
        }

        tracing::info!("dawn/share: гость {id} «{имя_гостя}» впущен");
        self.раздача_разослать_участников();
        self.request_redraw();
        true
    }

    /// Курсор гостя приехал в экранных координатах ЕГО кадра — переводим в
    /// холст по камере этого же гостя. Единственное место перевода: если
    /// считать где-то ещё, стрелка и клик разъедутся (см.
    /// [[dawn-cursor-offset-measurement]] — та же болезнь была у X11).
    pub fn раздача_курсор(&mut self, id: u8, x: f64, y: f64) {
        let Some(гость) = self.раздача.as_mut().and_then(|р| р.гость(id)) else { return };
        let (cx, cy, zoom) = гость.камера;
        let zoom = if zoom.abs() < 1e-6 { 1.0 } else { zoom };
        гость.курсор = (cx + x / zoom, cy + y / zoom);
        self.гостевое_движение(id);
        self.request_redraw();
    }

    /// Разослать всем впущенным, кто где. Чужие курсоры рисуются у каждого,
    /// поэтому список — это не «интерфейс», а часть картинки.
    pub fn раздача_разослать_участников(&mut self) {
        let курсор_хоста = (self.pointer_location.x, self.pointer_location.y);
        let Some(раздача) = self.раздача.as_ref() else { return };
        let список = раздача.участники(курсор_хоста, "хост");
        let байты = proto::ОтХоста::Участники(список).в_байты();
        let камера = proto::ОтХоста::КамераХоста {
            x: self.viewport.cam_x as f32,
            y: self.viewport.cam_y as f32,
            zoom: self.viewport.zoom as f32,
        }
        .в_байты();
        let Some(раздача) = self.раздача.as_mut() else { return };
        раздача.список_разослан = Instant::now();
        let ids: Vec<u8> = раздача.гости.iter().filter(|г| г.впущен).map(|г| г.id).collect();
        for id in ids {
            net::поставить_в_очередь(self, id, &байты, false);
            net::поставить_в_очередь(self, id, &камера, false);
        }
    }

    // ── Панель управления раздачей ──────────────────────────────────────────
    //
    // Повторное Super+Shift+S у хозяина машины не выключает раздачу, а
    // открывает панель: кто подключён, кого выгнать, кого забанить, и отдельной
    // кнопкой — закончить совсем. Так задумано Яриком 30.08.2026, и разница
    // важная: раньше единственным способом убрать ОДНОГО назойливого гостя было
    // выключить раздачу ВСЕМ.
    //
    // У гостя то же сочетание значит своё — выйти самому (перехватывается в
    // dshare и хосту не доходит вовсе, см. dshare/src/main.rs).

    pub fn раздача_панель_открыта(&self) -> bool {
        self.раздача.as_ref().is_some_and(|р| р.панель)
    }

    /// Super+Shift+S: нет раздачи — включить, идёт — показать панель,
    /// панель открыта — закрыть её.
    pub fn раздача_переключить(&mut self, порт: u16) {
        match self.раздача.as_mut() {
            None => self.раздача_по_команде(порт),
            Some(раздача) => {
                раздача.панель = !раздача.панель;
                раздача.выбран = 0;
                self.request_redraw();
            }
        }
    }

    /// Клавиша в открытой панели. `true` — забрали себе.
    pub fn раздача_клавиша(&mut self, sym: u32) -> bool {
        use smithay::input::keyboard::keysyms as ks;
        if !self.раздача_панель_открыта() {
            return false;
        }
        let сколько = self.раздача.as_ref().map(|р| р.гости.len()).unwrap_or(0);
        match sym {
            ks::KEY_Escape | ks::KEY_q | ks::KEY_Q => {
                if let Some(р) = self.раздача.as_mut() {
                    р.панель = false;
                }
                self.request_redraw();
            }
            ks::KEY_Up | ks::KEY_k | ks::KEY_K => {
                if let Some(р) = self.раздача.as_mut() {
                    р.выбран = р.выбран.saturating_sub(1);
                }
                self.request_redraw();
            }
            ks::KEY_Down | ks::KEY_j | ks::KEY_J => {
                if let Some(р) = self.раздача.as_mut() {
                    р.выбран = (р.выбран + 1).min(сколько.saturating_sub(1));
                }
                self.request_redraw();
            }
            // Выгнать выбранного. Тем же клавишам, что и в остальных меню
            // dawn, здесь взяться неоткуда — берём мнемонику: kick, ban.
            ks::KEY_x | ks::KEY_X | ks::KEY_Delete => self.раздача_выгнать_выбранного(false),
            ks::KEY_b | ks::KEY_B => self.раздача_выгнать_выбранного(true),
            // Закончить раздачу совсем.
            ks::KEY_s | ks::KEY_S => self.раздача_закончить(),
            _ => return false,
        }
        true
    }

    fn раздача_выгнать_выбранного(&mut self, забанить: bool) {
        let Some(раздача) = self.раздача.as_mut() else { return };
        let Some(гость) = раздача.гости.get(раздача.выбран) else { return };
        let (id, имя, адрес) = (гость.id, гость.имя.clone(), гость.адрес);
        if забанить && !раздача.бан.contains(&адрес) {
            раздача.бан.push(адрес);
        }
        // Выбор сдвигаем ДО удаления: гость уедет из списка, и индекс,
        // указывающий за конец, показал бы пустоту вместо соседа.
        раздача.выбран = раздача.выбран.min(раздача.гости.len().saturating_sub(2));
        self.раздача_выгнать(id);
        tracing::info!(
            "dawn/share: гость {id} («{имя}», {адрес}) {}",
            if забанить { "забанен" } else { "выгнан" },
        );
    }

    /// Выгнать гостя: попрощаться и пометить мёртвым. Всё остальное —
    /// источник, очередь, место, кодировщик — приберёт `убрать_мёртвых` на
    /// ближайшем тике, тем же путём, что и при обычном обрыве связи.
    pub fn раздача_выгнать(&mut self, id: u8) {
        let Some(гость) = self.раздача.as_mut().and_then(|р| р.гость(id)) else { return };
        гость.исходящие.положить(proto::ОтХоста::Прощай.в_байты(), false);
        гость.жив = false;
        self.request_redraw();
    }

    /// Подогнать разрешение потока под окно каждого гостя.
    ///
    /// **Зачем вообще.** До 30.08.2026 кадр всем рисовался в разрешении
    /// хозяйского выхода, а вписывал его в своё окно сам гость. Замер показал,
    /// где это больно: не канал (78 Мбит/с между машинами при потоке в 12) и
    /// не кодирование, а КЛИЕНТ — он декодирует 2560×1080 и выводит через
    /// `softbuffer`, то есть масштабирует и рисует на процессоре. Ноут с окном
    /// 1280×720 гонял вчетверо больше пикселей, чем показывал.
    ///
    /// **Почему с задержкой и порогом, а не сразу по `Вид`.** Смена размера —
    /// это перезапуск ffmpeg у хоста и пересборка декодера у гостя, то есть
    /// разрыв потока и ожидание ключевого кадра. Гость, тянущий окно за угол,
    /// шлёт новый размер на каждый пиксель; без порога и выдержки картинка у
    /// него разваливалась бы всё время, пока он тянет.
    fn раздача_подогнать_размеры(&mut self) {
        /// Насколько окно должно разойтись с потоком, чтобы стоило дёргать
        /// кодек. Меньше — глазу не видно, а перезапуск виден всегда.
        const ПОРОГ: i32 = 64;
        /// Сколько ждать после прошлой смены (и после начала тяги).
        const ВЫДЕРЖКА: std::time::Duration = std::time::Duration::from_millis(500);

        let Some(раздача) = self.раздача.as_ref() else { return };
        let кандидаты: Vec<(u8, (u16, u16))> = раздача
            .гости
            .iter()
            .filter(|г| г.впущен && г.жив)
            .filter_map(|г| {
                let нужно = чётный(г.кадр);
                let (сейчас_w, сейчас_h) = г.кадр_кодировщика;
                let далеко = (нужно.0 as i32 - сейчас_w as i32).abs() > ПОРОГ
                    || (нужно.1 as i32 - сейчас_h as i32).abs() > ПОРОГ;
                let отстоялось = г.размер_сменён.elapsed() >= ВЫДЕРЖКА;
                (далеко && отстоялось).then_some((г.id, нужно))
            })
            .collect();
        for (id, размер) in кандидаты {
            self.раздача_пересобрать_кодировщик(id, размер);
        }
    }

    /// Перезапустить кодировщик гостя в новом разрешении.
    fn раздача_пересобрать_кодировщик(&mut self, id: u8, размер: (u16, u16)) {
        let Some(гость) = self.раздача.as_mut().and_then(|р| р.гость(id)) else { return };
        let исходящие = гость.исходящие.clone();
        let прежний = гость.кадр_кодировщика;

        // «Размер» кладём в очередь ДО первого кадра нового разрешения.
        // Очередь одна и упорядочена — значит гость гарантированно пересоберёт
        // декодер раньше, чем получит несовместимые с ним байты. Пошли мы это
        // сообщение мимо очереди, оно обогнало бы хвост старых кадров.
        исходящие.положить(
            proto::ОтХоста::Размер { w: размер.0, h: размер.1 }.в_байты(),
            false,
        );

        // Старый ffmpeg гасим ДО запуска нового: держать разом два процесса,
        // каждый со своим состоянием потока и буферами, незачем — а на пяти
        // гостях это была бы десятка процессов вместо пяти.
        гость.кодировщик = None;
        гость.кадр_кодировщика = размер;
        гость.размер_сменён = Instant::now();

        let новый = video::Кодировщик::запустить(id, размер.0 as u32, размер.1 as u32, исходящие);
        if новый.is_none() {
            tracing::warn!("dawn/share: гостю {id} не поднялся кодировщик {}×{} — картинки не будет",
                размер.0, размер.1);
        }
        if let Some(гость) = self.раздача.as_mut().and_then(|р| р.гость(id)) {
            гость.кодировщик = новый;
        }
        tracing::info!(
            "dawn/share: гость {id}: поток {}×{} → {}×{}",
            прежний.0, прежний.1, размер.0, размер.1,
        );
    }

    /// Периодическая работа раздачи: рассылка списка участников (не чаще
    /// 10 раз в секунду) и добивание недописанных очередей.
    ///
    /// Зовётся из `anim::tick` — единственного места, которое тикает и на
    /// статичном экране.
    pub fn раздача_тик(&mut self) {
        if self.раздача.is_none() {
            return;
        }
        // «За хостом» ведём ЗДЕСЬ, а не по приходящему от гостя `Вид`.
        // Гость шлёт свой вид, только когда сам его меняет (плюс раз в
        // полсекунды на всякий случай), — а прилипший к хозяину камеры не
        // меняет вовсе. Обновляй мы её по его сообщениям, гость «за хостом»
        // видел бы чужой перелёт рывками по полсекунды вместо плавного хода.
        let камера_хоста = (self.viewport.cam_x, self.viewport.cam_y, self.viewport.zoom);
        if let Some(раздача) = self.раздача.as_mut() {
            for гость in раздача.гости.iter_mut().filter(|гость| гость.за_хостом) {
                гость.камера = камера_хоста;
            }
        }

        let пора = self
            .раздача
            .as_ref()
            .map(|р| р.список_разослан.elapsed().as_millis() >= 100)
            .unwrap_or(false);
        if пора {
            self.раздача_разослать_участников();
        }
        self.раздача_подогнать_размеры();
        net::убрать_мёртвых(self);
        // Выбор в панели держим внутри списка: гость мог отключиться сам, пока
        // панель открыта, и указатель остался бы за концом — подсветка пропала
        // бы, а «выгнать» перестало работать без единого объяснения.
        if let Some(раздача) = self.раздача.as_mut() {
            раздача.выбран = раздача.выбран.min(раздача.гости.len().saturating_sub(1));
        }

        // Кадр гостю рисуется в конце кадра МОНИТОРА, а монитор на неподвижном
        // экране не перерисовывается вовсе. Значит, пока кому-то из гостей пора
        // отдавать картинку, кадр надо просить самим — иначе гость, ведущий
        // свою камеру по холсту, видел бы застывший экран до первого движения
        // хозяйской мыши.
        let кому_то_пора = self
            .раздача
            .as_ref()
            .is_some_and(|р| {
                р.гости.iter().any(|г| {
                    г.впущен && г.кодировщик.as_ref().is_some_and(|к| к.жив() && к.пора())
                })
            });
        if кому_то_пора {
            self.request_redraw();
        }
    }
}
