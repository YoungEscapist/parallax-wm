//! Кадр каждому гостю: та же сцена, что на мониторе, но с ЕГО камерой.
//!
//! **Как это вообще возможно так дёшево.** Камера у dawn не живёт в масштабе
//! выхода и не размазана по коду: весь кадр собирается одной функцией
//! `udev::собрать_элементы`, которая читает `state.viewport` и привязку выхода
//! в `space`. Значит «нарисуй то же самое, но с другой точки» — это подменить
//! две вещи, собрать список и вернуть их назад. Никакой второй сцены, никакого
//! отдельного пути отрисовки: гость видит ровно то же, что увидел бы хозяин,
//! отведи он камеру туда же (включая скругления, обрезку и блюр).
//!
//! **Курсоры в кадр не идут.** Список приходит с числом «сколько первых
//! элементов рисуют курсоры» (свой курсор хоста и стрелки гостей), и мы
//! отрезаем ровно их — тем же приёмом, что и запись экрана без курсора
//! (см. `screencopy::serve_pending`). Стрелки всех участников гость рисует у
//! себя сам, по списку из `Участники`: он приходит 10 раз в секунду короткими
//! сообщениями и не роняется, тогда как видео роняется и отстаёт. Курсор,
//! вмороженный в видеокадр, дёргался бы вместе с потоком.
//!
//! **Одна камера — один снимок.** Гости, прилипшие к хосту («за хостом»),
//! смотрят в одну точку; рисовать им один и тот же кадр по разу на каждого
//! незачем. Снимок делится между всеми, у кого камера совпала, а кодируется
//! всё равно каждому свой (у ffmpeg на гостя своё состояние потока и свой
//! канал).
//!
//! **Чего здесь осознанно нет.** Блюр под плашками пересчитывается для камеры
//! ХОЗЯИНА (`пересчитать_блюр` зовётся один раз за кадр монитора) — у гостя
//! обои под панелью размыты «не со своего места». Это заметно только если
//! искать, а честный пересчёт стоил бы двух проходов свёртки на гостя на кадр.

use smithay::backend::renderer::gles::GlesRenderer;
use smithay::output::Output;

use crate::Dawn;

/// Насколько две камеры считаются одной и той же (логические пиксели холста и
/// доли зума). Полпикселя: ближе — картинки не отличить, а пружина камеры
/// хоста всё время дрожит в последнем знаке, и без допуска «за хостом»
/// никогда бы не совпало само с собой.
const ДОПУСК_КАМЕРЫ: f64 = 0.5;
const ДОПУСК_ЗУМА: f64 = 0.001;

/// Нарисовать и отдать кадры всем гостям, которым пора.
///
/// Зовётся из `udev::render_surface` (после того, как кадр ушёл на монитор) и
/// из `headless::такт` — то есть и на живом железе, и в харнессе.
pub fn кадры_гостям(
    state: &mut Dawn,
    renderer: &mut GlesRenderer,
    output: &Output,
    скругление: Option<&crate::rounded::Шейдер>,
) {
    let Some(раздача) = state.раздача.as_ref() else { return };
    // Кадр считается с одного выхода — того, чей размер записан в раздаче.
    if раздача.выход != output.name() {
        if пора_сказать(ЧУЖОЙ_ВЫХОД) {
            tracing::debug!(
                "dawn/share: кадра гостям нет: выход {:?} не тот, кадр считается с {:?}",
                output.name(), раздача.выход,
            );
        }
        return;
    }
    // Кому пора: впущенный, кодировщик жив и с прошлого кадра прошло 1/30 с.
    // Размер берём У КАЖДОГО свой — тот, в котором работает его кодировщик
    // (см. `раздача_подогнать_размеры`): гость с окном 1280×720 и гость на
    // втором мониторе во весь экран получают разные кадры.
    let ждут: Vec<(u8, (f64, f64, f64), (u32, u32))> = раздача
        .гости
        .iter()
        .filter(|г| г.жив && г.впущен)
        .filter(|г| г.кодировщик.as_ref().is_some_and(|к| к.жив() && к.пора()))
        .map(|г| (г.id, г.камера, (г.кадр_кодировщика.0 as u32, г.кадр_кодировщика.1 as u32)))
        .collect();
    if ждут.is_empty() {
        if !раздача.гости.is_empty() && пора_сказать(НИКОМУ_НЕ_ПОРА) {
            tracing::debug!(
                "dawn/share: кадра гостям нет: никому не пора: {}",
                раздача.гости.iter()
                    .map(|г| format!(
                        "{}: впущен={} кодировщик={} жив={} пора={} отдано={} уронено={}",
                        г.id, г.впущен, г.кодировщик.is_some(),
                        г.кодировщик.as_ref().is_some_and(|к| к.жив()),
                        г.кодировщик.as_ref().is_some_and(|к| к.пора()),
                        г.кодировщик.as_ref().map(|к| к.отдано).unwrap_or(0),
                        г.кодировщик.as_ref().map(|к| к.уронено).unwrap_or(0),
                    ))
                    .collect::<Vec<_>>().join("; "),
            );
        }
        return;
    }

    // Группируем по камере И РАЗМЕРУ: одна отрисовка на всех, кто смотрит в
    // одну точку одинаковым окном. Размер обязан входить в ключ — иначе двое
    // «за хостом» с разными окнами получили бы один буфер на двоих, и тому,
    // чей размер не совпал с выбранным, кодировщик скормил бы кадр чужой
    // длины: для rawvideo это не обрезка картинки, а сдвиг всего потока.
    let mut группы: Vec<((f64, f64, f64), (u32, u32), Vec<u8>)> = Vec::new();
    for (id, камера, размер) in ждут {
        match группы.iter_mut().find(|(к, р, _)| одна_камера(*к, камера) && *р == размер) {
            Some((_, _, кому)) => кому.push(id),
            None => группы.push((камера, размер, vec![id])),
        }
    }

    for (камера, размер, кому) in группы {
        let Some(пиксели) = снимок(state, renderer, output, скругление, камера, размер) else {
            continue;
        };
        // Один снимок на всю группу: `Arc` уезжает потокам записи без копии.
        let пиксели = std::sync::Arc::new(пиксели);
        for id in кому {
            let Some(гость) = state.раздача.as_mut().and_then(|р| р.гость(id)) else { continue };
            let Some(кодировщик) = гость.кодировщик.as_mut() else { continue };
            if кодировщик.кадр(&пиксели) {
                гость.номер_кадра = гость.номер_кадра.wrapping_add(1);
                гость.последний_кадр = std::time::Instant::now();
            }
        }
    }
}

/// Пора ли снова сказать в лог, почему гостю не досталось кадра: не чаще раза
/// в две секунды НА КАЖДЫЙ ВИД причины. Тем же приёмом и по той же причине,
/// что `udev::почему_нет_блюра`: снаружи «картинки нет» выглядит одинаково при
/// чужом выходе, мёртвом ffmpeg и невпущенном госте, а чинить каждый раз надо
/// разное.
///
/// **Ключ — только ВИД причины, без подробностей, и это не мелочь.** Первая
/// версия сравнивала строку целиком, а в строке стоял счётчик `отдано=9531`,
/// который меняется каждый кадр: совпадения не случалось никогда, и защита не
/// срабатывала ни разу за всё время. Замер 30.08.2026 на живой раздаче — 29
/// МиБ логов в час, и 4.9 ГБ, накопленных в `logs/`.
///
/// **Слот на каждый вид, а не один общий, — по той же причине.** У Ярика два
/// монитора, `render_surface` зовётся на каждый: причины «чужой выход» и
/// «никому не пора» чередуются такт через такт. Один слот они выбивали бы друг
/// у друга, и throttle снова не работал бы, уже по второму кругу.
///
/// Возвращает `bool`, а не печатает сам: подробности стоят `format!` по всем
/// гостям, и складывать их, чтобы тут же выбросить, — ровно тот расход, ради
/// устранения которого всё это и написано.
fn пора_сказать(вид: &str) -> bool {
    use std::sync::Mutex;
    static КОГДА: Mutex<Vec<(&'static str, std::time::Instant)>> = Mutex::new(Vec::new());
    // Видов ровно два, поиск перебором дешевле хеша и не тянет HashMap.
    let виды: [&'static str; 2] = [ЧУЖОЙ_ВЫХОД, НИКОМУ_НЕ_ПОРА];
    let Some(&вид) = виды.iter().find(|в| **в == вид) else { return true };
    let Ok(mut когда) = КОГДА.lock() else { return false };
    match когда.iter_mut().find(|(в, _)| *в == вид) {
        Some((_, t)) if t.elapsed().as_secs() < 2 => false,
        Some((_, t)) => {
            *t = std::time::Instant::now();
            true
        }
        None => {
            когда.push((вид, std::time::Instant::now()));
            true
        }
    }
}

const ЧУЖОЙ_ВЫХОД: &str = "чужой выход";
const НИКОМУ_НЕ_ПОРА: &str = "никому не пора";

fn одна_камера(a: (f64, f64, f64), b: (f64, f64, f64)) -> bool {
    (a.0 - b.0).abs() < ДОПУСК_КАМЕРЫ
        && (a.1 - b.1).abs() < ДОПУСК_КАМЕРЫ
        && (a.2 - b.2).abs() < ДОПУСК_ЗУМА
}

/// Собрать сцену с чужой камеры и снять её в плотный BGRA.
///
/// Вид подменяется на время ровно одного вызова и возвращается ОБЯЗАТЕЛЬНО —
/// в том числе привязка выхода в `space`, от которой smithay отсчитывает
/// положение всех окон. Забыть её значило бы оставить монитор хозяина стоящим
/// в чужой точке холста до ближайшего `apply_camera`, то есть моргание кадра
/// на каждого гостя.
///
/// `сохранить_вид` здесь звать НЕЛЬЗЯ (в отличие от `войти_в_монитор`): она
/// записывает текущий `viewport` в активный монитор, и чужая камера уехала бы
/// в память монитора хозяина насовсем.
fn снимок(
    state: &mut Dawn,
    renderer: &mut GlesRenderer,
    output: &Output,
    скругление: Option<&crate::rounded::Шейдер>,
    камера: (f64, f64, f64),
    размер: (u32, u32),
) -> Option<Vec<u8>> {
    let прежний_вид = state.viewport;
    let прежний_дом = state.space.output_geometry(output).map(|g| g.loc);

    state.viewport.cam_x = камера.0;
    state.viewport.cam_y = камера.1;
    state.viewport.zoom = камера.2.clamp(0.05, 8.0);
    let дом = smithay::utils::Point::from((
        state.viewport.cam_x.round() as i32,
        state.viewport.cam_y.round() as i32,
    ));
    state.space.map_output(output, дом);

    let ёмкость = state.раздача.as_ref().map(|р| р.последних_элементов).unwrap_or(0);
    let (elements, курсорных) =
        crate::udev::собрать_элементы(state, renderer, output, скругление, ёмкость);
    if let Some(раздача) = state.раздача.as_mut() {
        раздача.последних_элементов = elements.len();
    }
    let размер_буфера = (размер.0 as i32, размер.1 as i32).into();
    // Курсоры отрезаем: их рисует сам гость по списку участников.
    let пиксели =
        crate::screencopy::capture(renderer, output, &elements[курсорных..], размер_буфера);
    drop(elements);

    state.viewport = прежний_вид;
    if let Some(дом) = прежний_дом {
        state.space.map_output(output, дом);
    }
    пиксели
}
