//! Видео гостям: кадр на каждого, со СВОЕЙ камерой, через ffmpeg.
//!
//! **Почему ffmpeg отдельным процессом, а не libavcodec в себе.** Внутрь
//! композитора кодек тащить нельзя без веской причины: любой его сбой — это
//! падение всего рабочего стола, а нам нужно ровно одно — «дай h264 из
//! потока BGRA». Процесс отделён границей ОС: он может умереть, зависнуть,
//! быть убитым — хост это переживёт и просто перезапустит кодировщик. Цена —
//! копия кадра через трубу; на 1080p это единицы миллисекунд.
//! (В plx-wall кодек как раз в процессе — там обратная задача: декодировать
//! обои, и падение декодера означает лишь чёрный фон.)
//!
//! **Почему кадр рисуется на каждого отдельно.** У гостя своя камера по
//! общему холсту — это прямое требование Ярика. Значит и картинка у каждого
//! своя: общий поток можно было бы гнать один на всех только при
//! «зеркале экрана хоста». Дороже, зато это и есть смысл бесконечного холста:
//! пятеро работают в разных его местах и не мешают друг другу.
//!
//! **Разрешение — у каждого своё, по размеру его окна.** Первая версия рисовала
//! всем в разрешении хозяйского выхода, отдавая масштабирование клиенту. Замер
//! 30.08.2026 показал, чего это стоило: канал не при чём (78 Мбит/с между
//! машинами при потоке в 12), кодирование тоже — платил КЛИЕНТ, декодируя
//! 2560×1080 и выводя через `softbuffer`, то есть масштабируя и рисуя на
//! процессоре. Ноут с окном 1280×720 гонял вчетверо больше пикселей, чем
//! показывал. Теперь размер потока идёт за окном гостя (с порогом и выдержкой,
//! см. `раздача_подогнать_размеры`), а смена объявляется сообщением
//! `ОтХоста::Размер` перед первым кадром нового разрешения.
//!
//! **Кадр в ffmpeg отдаёт отдельный поток, и это не украшательство.** Сырой
//! BGRA 2560×1080 — это 11 МиБ на кадр, а труба ОС держит 64 КиБ. Первая
//! версия писала прямо из композитора в неблокирующую трубу и досылала остаток
//! на следующем кадре: замер 26.08.2026 в харнессе — `отдано=1 уронено=115`,
//! то есть за шесть секунд в кодировщик уехал ОДИН кадр, и тот не целиком.
//! Арифметика простая: одна попытка записи за такт кадра даёт 64 КиБ × 30 =
//! 2 МиБ/с при нужных 330 МиБ/с. Теперь труба обычная (блокирующая), пишет в
//! неё свой поток, а композитор только КЛАДЁТ готовый кадр в ячейку на одного
//! (`Ячейка`) — ровно тем же приёмом, что и очередь сообщений в net.rs.
//! Не успел забрать — кадр роняется целиком, а не наполовину: rawvideo это
//! поток кадров фиксированного размера, и половина кадра портит всё дальнейшее.

use std::io::Write;
use std::process::{Child, ChildStdin, ChildStdout, Command, Stdio};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Condvar, Mutex};
use std::time::{Duration, Instant};

use super::net::Очередь;
use super::proto;

/// Кодек, о котором договариваемся с гостем.
pub const КОДЕК: proto::Кодек = proto::Кодек::H264;

/// Сколько кадров в секунду рисуем каждому гостю. 30 — заметно дешевле 60 по
/// GPU и по каналу, а для совместной работы (не игры) разницы на глаз нет.
pub const КАДРОВ: u32 = 30;

/// Ключевой кадр раз в две секунды: с него гость начинает показывать
/// картинку, подключившись посреди потока.
pub const КЛЮЧЕВОЙ_ЧЕРЕЗ: u32 = КАДРОВ * 2;

/// Есть ли в системе аппаратный кодировщик NVIDIA. Спрашиваем ОДИН раз:
/// запуск `ffmpeg -encoders` стоит десятки миллисекунд, а ответ не меняется.
fn есть_nvenc() -> bool {
    static ОТВЕТ: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ОТВЕТ.get_or_init(|| {
        let вывод = Command::new("ffmpeg")
            .args(["-hide_banner", "-loglevel", "error", "-encoders"])
            .output();
        match вывод {
            Ok(в) => {
                let текст = String::from_utf8_lossy(&в.stdout);
                let есть = текст.contains("h264_nvenc");
                tracing::info!("plx/share: h264_nvenc {}", if есть { "yes" } else { "no, falling back to libx264" });
                есть
            }
            Err(e) => {
                tracing::warn!("plx/share: ffmpeg will not start ({e}) — guests will get no video");
                false
            }
        }
    })
}

/// Ячейка на один кадр между композитором и потоком, пишущим в ffmpeg.
///
/// Глубина ровно один: копить сырые кадры по 11 МиБ бессмысленно — гостю нужен
/// СВЕЖИЙ кадр, а не полная история. Не успел кодировщик забрать прошлый —
/// новый просто не кладётся.
struct Ячейка {
    кадр: Mutex<Option<Arc<Vec<u8>>>>,
    есть: Condvar,
    закрыта: AtomicBool,
}

impl Ячейка {
    fn new() -> Self {
        Self {
            кадр: Mutex::new(None),
            есть: Condvar::new(),
            закрыта: AtomicBool::new(false),
        }
    }

    /// `false` — прошлый кадр ещё не забрали (роняем) либо ячейка закрыта.
    fn положить(&self, кадр: Arc<Vec<u8>>) -> bool {
        if self.закрыта.load(Ordering::Relaxed) {
            return false;
        }
        let mut слот = match self.кадр.lock() {
            Ok(с) => с,
            Err(отравлен) => отравлен.into_inner(),
        };
        if слот.is_some() {
            return false;
        }
        *слот = Some(кадр);
        self.есть.notify_one();
        true
    }

    /// Забрать кадр, ожидая появления. `None` — ячейка закрыта.
    fn взять(&self) -> Option<Arc<Vec<u8>>> {
        let mut слот = match self.кадр.lock() {
            Ok(с) => с,
            Err(отравлен) => отравлен.into_inner(),
        };
        loop {
            if let Some(к) = слот.take() {
                return Some(к);
            }
            if self.закрыта.load(Ordering::Relaxed) {
                return None;
            }
            слот = match self.есть.wait(слот) {
                Ok(с) => с,
                Err(отравлен) => отравлен.into_inner(),
            };
        }
    }

    fn закрыть(&self) {
        self.закрыта.store(true, Ordering::Relaxed);
        self.есть.notify_all();
    }
}

/// Кодировщик одного гостя: процесс ffmpeg плюс два потока — один пишет в него
/// сырые кадры, другой читает готовый h264.
pub struct Кодировщик {
    процесс: Child,
    /// Куда композитор кладёт очередной кадр. Сам `ChildStdin` отдан потоку
    /// записи целиком.
    ячейка: Arc<Ячейка>,
    pub ширина: u32,
    pub высота: u32,
    живой: Arc<AtomicBool>,
    pub отдано: u64,
    pub уронено: u64,
    последний: Instant,
}

impl Кодировщик {
    /// Запустить ffmpeg и поток-читатель. `исходящие` — очередь гостя: туда
    /// поток кладёт готовые куски h264 уже завёрнутыми в сообщение протокола.
    pub fn запустить(id: u8, ширина: u32, высота: u32, исходящие: Arc<Очередь>) -> Option<Self> {
        let аппаратный = есть_nvenc();
        let размер = format!("{ширина}x{высота}");
        let частота = КАДРОВ.to_string();
        let ключ = КЛЮЧЕВОЙ_ЧЕРЕЗ.to_string();

        let mut команда = Command::new("ffmpeg");
        команда.args([
            "-hide_banner", "-loglevel", "error",
            "-f", "rawvideo", "-pix_fmt", "bgra",
            "-s", &размер, "-r", &частота,
            "-i", "pipe:0",
            "-an",
        ]);
        if аппаратный {
            команда.args([
                "-c:v", "h264_nvenc",
                // p1 — самый быстрый пресет, ll — low latency: очередь кадров
                // внутри кодировщика для интерактива вреднее, чем лишний
                // мегабит.
                "-preset", "p1", "-tune", "ll",
                "-rc", "cbr", "-b:v", "12M",
                "-g", &ключ, "-bf", "0",
                "-delay", "0",
            ]);
        } else {
            команда.args([
                "-c:v", "libx264",
                "-preset", "ultrafast", "-tune", "zerolatency",
                "-b:v", "8M",
                "-g", &ключ, "-bf", "0",
            ]);
        }
        // Annex-B без контейнера: гость скармливает поток декодеру как есть,
        // никакой демуксер не нужен.
        команда.args(["-pix_fmt", "yuv420p", "-f", "h264", "pipe:1"]);
        команда.stdin(Stdio::piped()).stdout(Stdio::piped()).stderr(Stdio::inherit());

        let mut процесс = match команда.spawn() {
            Ok(п) => п,
            Err(e) => {
                tracing::warn!("plx/share: ffmpeg failed to start for guest {id}: {e}");
                return None;
            }
        };
        let вход = процесс.stdin.take();
        let выход = процесс.stdout.take();
        let живой = Arc::new(AtomicBool::new(true));
        let ячейка = Arc::new(Ячейка::new());

        if let Some(выход) = выход {
            запустить_читателя(id, выход, исходящие, живой.clone());
        }
        match вход {
            Some(вход) => {
                // Трубу расширяем до предела, разрешённого системой: чем
                // крупнее буфер, тем реже поток записи упирается в ffmpeg на
                // кадре в 11 МиБ. Отказ не страшен — просто чаще будет ждать.
                расширить_трубу(&вход);
                запустить_писателя(id, вход, ячейка.clone(), живой.clone());
            }
            None => {
                tracing::warn!("plx/share: ffmpeg for guest {id} has no stdin — no frames");
                живой.store(false, Ordering::Relaxed);
            }
        }

        tracing::info!(
            "plx/share: encoder for guest {id}: {ширина}x{высота}@{КАДРОВ}, {}",
            if аппаратный { "h264_nvenc" } else { "libx264" },
        );
        Some(Self {
            процесс,
            ячейка,
            ширина,
            высота,
            живой,
            отдано: 0,
            уронено: 0,
            последний: Instant::now() - Duration::from_secs(1),
        })
    }

    /// Пора ли рисовать следующий кадр этому гостю.
    pub fn пора(&self) -> bool {
        self.последний.elapsed() >= Duration::from_micros(1_000_000 / КАДРОВ as u64)
    }

    pub fn жив(&self) -> bool {
        self.живой.load(Ordering::Relaxed)
    }

    /// Скормить кадр. `пиксели` — плотный BGRA размером ширина×высота×4.
    /// `false` — кадр уронен (кодировщик не успел забрать прошлый или умер).
    ///
    /// `Arc`, а не срез: один и тот же снимок уходит всем гостям с одинаковой
    /// камерой, и копировать 11 МиБ на каждого незачем — поток записи держит
    /// ссылку ровно до конца записи.
    pub fn кадр(&mut self, пиксели: &Arc<Vec<u8>>) -> bool {
        if !self.жив() {
            return false;
        }
        let ждём = (self.ширина * self.высота * 4) as usize;
        if пиксели.len() != ждём {
            tracing::warn!(
                "plx/share: frame is {} bytes instead of {} — skipped",
                пиксели.len(), ждём,
            );
            return false;
        }
        // Время отметки — здесь, а не после успеха: `пора()` задаёт ЧАСТОТУ
        // ПОПЫТОК. Отмечай мы только удачные, при отставании кодировщика
        // композитор пересобирал бы сцену гостю на каждом кадре монитора
        // (то есть до 200 раз в секунду) и выбрасывал результат.
        self.последний = Instant::now();
        if self.ячейка.положить(пиксели.clone()) {
            self.отдано += 1;
            true
        } else {
            self.уронено += 1;
            false
        }
    }
}

impl Drop for Кодировщик {
    fn drop(&mut self) {
        self.живой.store(false, Ordering::Relaxed);
        // Закрываем ячейку: поток записи выйдет из ожидания, отпустит
        // `ChildStdin`, и ffmpeg увидит конец входа. Без этого поток остался бы
        // висеть на условной переменной, держа трубу открытой, — а ffmpeg
        // ждал бы данных вечно.
        self.ячейка.закрыть();
        let _ = self.процесс.kill();
        let _ = self.процесс.wait();
    }
}

/// Поток, отдающий сырые кадры в ffmpeg. Труба здесь обычная, блокирующая, и
/// это ровно то, что нужно: ждёт не композитор, а этот поток.
fn запустить_писателя(id: u8, mut вход: ChildStdin, ячейка: Arc<Ячейка>, живой: Arc<AtomicBool>) {
    std::thread::Builder::new()
        .name(format!("plx-share-raw-{id}"))
        .spawn(move || {
            while let Some(кадр) = ячейка.взять() {
                if let Err(e) = вход.write_all(&кадр) {
                    // Обрыв трубы бывает двух сортов, и путать их нельзя.
                    //
                    // ffmpeg умер сам — это настоящая беда, картинки у гостя
                    // больше не будет. А вот `Drop` гасит его НАМЕРЕННО, и
                    // первым делом ставит `живой = false` (см. выше): так
                    // происходит на каждой смене разрешения, то есть на каждой
                    // тяге окна гостя за угол. Замер 30.08.2026: один
                    // ресайз — один `WARN … Broken pipe` на ровном месте.
                    if живой.load(Ordering::Relaxed) {
                        tracing::warn!("plx/share: writing a frame for guest {id}: {e}");
                    } else {
                        tracing::debug!("plx/share: encoder for guest {id} closed by us: {e}");
                    }
                    живой.store(false, Ordering::Relaxed);
                    return;
                }
            }
            // Явно роняем вход: ffmpeg по концу трубы штатно доигрывает и
            // выходит сам.
            drop(вход);
        })
        .map_err(|e| tracing::warn!("plx/share: frame writer thread failed to start: {e}"))
        .ok();
}

/// Поток, читающий выход ffmpeg и складывающий куски в очередь гостя.
///
/// Куски отдаются КАК ЕСТЬ, без разбора на кадры: h264 Annex-B склеивается
/// декодером сам, а искать границы кадров в композиторе — лишняя работа с
/// нулевой пользой. Флаг «ключевой» проставляется по стартовому коду IDR
/// (0x65 в первом байте после 00 00 01) — гость по нему понимает, что с этого
/// места картинку можно показывать.
fn запустить_читателя(id: u8, mut выход: ChildStdout, исходящие: Arc<Очередь>, живой: Arc<AtomicBool>) {
    std::thread::Builder::new()
        .name(format!("plx-share-enc-{id}"))
        .spawn(move || {
            use std::io::Read;
            let mut буфер = vec![0u8; 256 * 1024];
            let mut номер: u32 = 0;
            while живой.load(Ordering::Relaxed) {
                match выход.read(&mut буфер) {
                    Ok(0) => break,
                    Ok(n) => {
                        let кусок = &буфер[..n];
                        let ключевой = есть_idr(кусок);
                        номер = номер.wrapping_add(1);
                        let сообщение = proto::ОтХоста::Кадр {
                            номер,
                            ключевой,
                            данные: кусок.to_vec(),
                        }
                        .в_байты();
                        // Ключевые не роняем: без них гость не восстановится.
                        if !исходящие.положить(сообщение, !ключевой) {
                            continue;
                        }
                    }
                    Err(e) if e.kind() == std::io::ErrorKind::Interrupted => continue,
                    Err(e) => {
                        tracing::warn!("plx/share: reading from ffmpeg (guest {id}): {e}");
                        break;
                    }
                }
            }
            живой.store(false, Ordering::Relaxed);
            tracing::info!("plx/share: encoder for guest {id} finished");
        })
        .map_err(|e| tracing::warn!("plx/share: encoder thread failed to start: {e}"))
        .ok();
}

/// Есть ли в куске NAL типа 5 (IDR) — по нему гость понимает «отсюда можно
/// начинать показ».
///
/// Стартовый код бывает трёх- и четырёхбайтовым (00 00 01 и 00 00 00 01);
/// тип лежит в младших пяти битах следующего байта. Ищем оба варианта: ffmpeg
/// ставит четырёхбайтовый перед SPS/PPS/IDR и трёхбайтовый внутри кадра.
fn есть_idr(кусок: &[u8]) -> bool {
    let mut i = 0usize;
    while i + 3 < кусок.len() {
        if кусок[i] == 0 && кусок[i + 1] == 0 {
            if кусок[i + 2] == 1 {
                if (кусок[i + 3] & 0x1f) == 5 {
                    return true;
                }
                i += 3;
                continue;
            }
            if кусок[i + 2] == 0 && i + 4 < кусок.len() && кусок[i + 3] == 1 {
                if (кусок[i + 4] & 0x1f) == 5 {
                    return true;
                }
                i += 4;
                continue;
            }
        }
        i += 1;
    }
    false
}

/// Раздвинуть трубу в ffmpeg до потолка, разрешённого системой
/// (`/proc/sys/fs/pipe-max-size`, обычно 1 МиБ против 64 КиБ по умолчанию).
///
/// Не обязательная оптимизация, а заметная: кадр 2560×1080 BGRA — 11 МиБ, и на
/// 64-килобайтной трубе поток записи просыпается на каждый кадр 170 раз.
fn расширить_трубу(файл: &ChildStdin) {
    use std::os::fd::AsRawFd;
    const F_SETPIPE_SZ: i32 = 1031;
    let предел = std::fs::read_to_string("/proc/sys/fs/pipe-max-size")
        .ok()
        .and_then(|s| s.trim().parse::<i32>().ok())
        .unwrap_or(1024 * 1024)
        .clamp(64 * 1024, 8 * 1024 * 1024);
    let fd = файл.as_raw_fd();
    // SAFETY: fd принадлежит живому ChildStdin, F_SETPIPE_SZ берёт int.
    let вышло = unsafe { libc::fcntl(fd, F_SETPIPE_SZ, предел) };
    if вышло < 0 {
        tracing::debug!(
            "plx/share: the ffmpeg pipe kept its previous size: {}",
            std::io::Error::last_os_error(),
        );
    }
}

/// Ради удобства вызывающего: сообщение «кадр» для сырого режима отладки.
#[allow(dead_code)]
pub fn сырой_кадр(номер: u32, пиксели: &[u8]) -> Vec<u8> {
    proto::ОтХоста::Кадр { номер, ключевой: true, данные: пиксели.to_vec() }.в_байты()
}
