//! Сенсорный экран ноутбука — палец как полноправное устройство ввода.
//!
//! До этого файла parallax не заводил `wl_touch` вовсе: место объявляло только
//! клавиатуру и указатель, а события `TouchDown`/`TouchMotion`/`TouchUp`
//! доходили до `process_input_event` и молча падали в `_ => {}`. На машине с
//! мышью это незаметно, на ноутбуке с сенсорным экраном — это «экран не
//! работает».
//!
//! ## Три судьбы одного касания
//!
//! Палец кладут в одно из трёх мест, и у каждого свой хозяин:
//!
//! 1. **По окну — касание уходит КЛИЕНТУ**, настоящим `wl_touch`, со слотами и
//!    мультитачем. Браузер получает свою инерционную прокрутку, читалка —
//!    щипок по странице, рисовалка — нажим двух пальцев. Ничего из этого не
//!    даёт эмуляция мыши, поэтому она здесь и не годится по умолчанию.
//!
//! 2. **По органам самого компоновщика** (панель, полка, карта окон, карточка
//!    предпросмотра, обзор, куб, выбор источника для демонстрации) — палец
//!    работает УКАЗАТЕЛЕМ: курсор переносится под палец, и дальше событие
//!    разбирает обычная цепочка `PointerButton`. Иначе пришлось бы завести
//!    второй хит-тест для каждого органа и держать его в согласии с первым —
//!    а их полтора десятка, и расходиться они начали бы с первой же правки.
//!
//! 3. **По пустому холсту — палец ведёт КАМЕРУ.** Это главное, ради чего всё
//!    и написано: холст parallax бесконечен, и на планшетном экране его больше
//!    нечем двигать — мыши нет, тачпад под клавиатурой в планшетном режиме
//!    недоступен. Один палец панит (с той же инерцией, что и жест тачпада),
//!    два щипком зумят, три и больше идут в общую таблицу `gesture{}`.
//!
//! ## Почему курсор ходит за пальцем всегда
//!
//! Даже когда касание уходит клиенту, стрелка переносится под палец. Так надо
//! не для красоты: половина parallax считает «где человек» по
//! `pointer_location` — хит-тест карты и карточки, якорь зума, выбор окна для
//! непрерывных жестов. Оставь мы курсор на месте — щипок зумил бы вокруг
//! точки, где палец был десять минут назад.
//!
//! ## Долгое нажатие = правая кнопка
//!
//! Правой кнопки у пальца нет, а контекстные меню есть у всех. Палец, который
//! пролежал `touch_long_press` мс не сдвинувшись, отдаётся окну как ПКМ
//! (нажатие и отпускание подряд), а само касание при этом отменяется —
//! `wl_touch.cancel`, чтобы клиент не посчитал его вдобавок за тап. Сторож
//! этого срока зовётся и из `anim::tick`, и из движения пальца: тик идёт по
//! кадрам, а на неподвижном экране кадров нет — тем же самым однажды уже
//! болел сторож мышиных аккордов (см. `аккорды.rs`).
//!
//! ## Договор с настройками
//!
//! `set{ touch = false }` возвращает поведение до этого файла слово в слово:
//! `wl_touch` местом не объявляется, события отбрасываются. Отдельными
//! ключами гасятся пан (`touch_pan`), щипок (`touch_zoom`), жесты
//! (`touch_gestures`) и долгое нажатие (`touch_long_press = 0`), а
//! `touch_emulate_pointer = true` уводит В УКАЗАТЕЛЬ вообще всё — это для
//! приложений, которые `wl_touch` не поддерживают (старые игры под Xwayland,
//! java-клиенты) и на палец не отзываются вовсе.

use smithay::{
    input::touch::{DownEvent, MotionEvent, UpEvent},
    utils::{Logical, Point, SERIAL_COUNTER},
};
use std::time::Instant;

use crate::state::Parallax;

/// Один палец на стекле.
#[derive(Debug, Clone)]
pub struct Палец {
    /// Слот libinput. Пальцев на экране несколько, и события каждого имеют
    /// смысл только в ряду событий ТОГО ЖЕ слота.
    pub слот: i32,
    /// Где палец сейчас, в пикселях ЭКРАНА (не холста).
    ///
    /// Экранные координаты здесь ведущие нарочно. Палец лежит на стекле, а не
    /// на холсте: пока он неподвижен, камера под ним может уехать (пан, зум,
    /// инерция), и точка холста под пальцем меняется каждый кадр. Считай мы
    /// дельту пана по холсту — она включала бы в себя то самое движение,
    /// которое сама и вызвала, и пан разгонялся бы сам от себя.
    pub экран: Point<f64, Logical>,
    /// Где палец лёг. По расстоянию до этой точки отличается тап от протяжки.
    pub начало: Point<f64, Logical>,
    /// Когда лёг — для долгого нажатия и для того же отличия тапа.
    pub положен: Instant,
    /// Ушёл ли `down` клиенту. `up` обязан уйти ровно тем же путём: клиент,
    /// увидевший нажатие и не увидевший отпускания, считает палец лежащим
    /// вечно.
    pub у_клиента: bool,
    /// Палец уже отработал долгим нажатием — его отпускание больше ничего не
    /// значит.
    pub истрачен: bool,
}

impl Палец {
    /// Насколько палец уехал от точки, где лёг, в пикселях экрана.
    pub fn сдвиг(&self) -> f64 {
        let (dx, dy) = (self.экран.x - self.начало.x, self.экран.y - self.начало.y);
        (dx * dx + dy * dy).sqrt()
    }
}

/// Чем занят сенсор прямо сейчас.
///
/// Роль выбирается ОДИН раз, по первому пальцу, и держится до тех пор, пока с
/// экрана не уйдут все. Иначе касание меняло бы хозяина на середине: увёл
/// палец с окна на пустое место — и протяжка внутри приложения превратилась бы
/// в пан холста.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Роль {
    /// Экрана никто не касается.
    #[default]
    Нет,
    /// Пальцы принадлежат клиенту, идут настоящим `wl_touch`.
    Клиенту,
    /// Палец изображает мышь: курсор + левая кнопка.
    Указатель,
    /// Пан камеры одним пальцем.
    Пан,
    /// Щипок двумя: зум и пан заодно.
    Щипок,
    /// Три пальца и больше уже на стекле, но ЧТО ими делают — ещё не ясно.
    ///
    /// Таблица `gesture{}` держит свайпы и щипки раздельно, и основу жеста
    /// libinput сообщает событием, а тачскрин — нет: с него приходят одни
    /// координаты пальцев. Поэтому основу выбираем сами, по первому же
    /// заметному движению: разъехались пальцы — щипок, поехал их общий центр —
    /// свайп. Пока не решили, не начат и жест: начатый не той основой молча
    /// съел бы всё движение (`порог_отработал` встал бы у чужого триггера).
    ЖестЖдёт,
    /// Три пальца и больше — таблица `gesture{}`, общая с тачпадом.
    Жест,
}

/// Всё состояние сенсорного ввода.
#[derive(Debug, Default)]
pub struct Сенсор {
    /// Пальцы на стекле, в порядке появления.
    pub пальцы: Vec<Палец>,
    pub роль: Роль,
    /// Расстояние между пальцами щипка на прошлом кадре, пиксели экрана.
    pub щипок_база: f64,
    /// Середина между пальцами (и центр всех пальцев жеста) на прошлом кадре.
    /// Ею ведётся пан во время щипка и свайп в жесте.
    pub центр: Point<f64, Logical>,
    /// Центр и разброс пальцев в тот миг, когда их стало трое. От этих двух
    /// чисел и считается выбор основы жеста (см. `Роль::ЖестЖдёт`).
    pub жест_центр0: Point<f64, Logical>,
    pub жест_разброс0: f64,
    /// Выбранная основа: `true` — щипок, `false` — свайп.
    pub жест_щипком: bool,
}

impl Сенсор {
    fn палец(&mut self, слот: i32) -> Option<&mut Палец> {
        self.пальцы.iter_mut().find(|п| п.слот == слот)
    }

    /// Середина между всеми пальцами, пиксели экрана.
    fn центр_пальцев(&self) -> Point<f64, Logical> {
        if self.пальцы.is_empty() {
            return Point::from((0.0, 0.0));
        }
        let n = self.пальцы.len() as f64;
        let (sx, sy) = self
            .пальцы
            .iter()
            .fold((0.0, 0.0), |(x, y), п| (x + п.экран.x, y + п.экран.y));
        Point::from((sx / n, sy / n))
    }

    /// Расстояние между первыми двумя пальцами, пиксели экрана.
    fn разброс(&self) -> f64 {
        let (Some(a), Some(b)) = (self.пальцы.first(), self.пальцы.get(1)) else {
            return 0.0;
        };
        let (dx, dy) = (a.экран.x - b.экран.x, a.экран.y - b.экран.y);
        (dx * dx + dy * dy).sqrt()
    }
}

impl Parallax {
    /// Точка холста под точкой экрана. Та же формула, что у абсолютного
    /// указателя в `input.rs`: делим на зум и прибавляем камеру.
    pub(crate) fn сенсор_холст(&self, экран: Point<f64, Logical>) -> Point<f64, Logical> {
        let z = self.viewport.zoom.max(0.01);
        Point::from((
            экран.x / z + self.viewport.cam_x,
            экран.y / z + self.viewport.cam_y,
        ))
    }

    /// Занял ли точку под пальцем сам компоновщик.
    ///
    /// Список — те же ветки, что стоят в начале `PointerButton`, и в том же
    /// порядке. Второго хит-теста для каждого органа заводить не стали: он
    /// разошёлся бы с первым, а цена ошибки здесь маленькая — палец просто
    /// уйдёт указателем туда, где мышь и так работает.
    pub(crate) fn сенсор_на_органе(&self) -> bool {
        let экран = self.pointer_screen_physical();
        self.overview_active
            || self.portal_picking()
            || self.bar_inside(экран)
            || self.tray_inside(экран)
            || self.preview_hit().is_some()
            || self.minimap_hit().is_some()
            || self.курсор_над_слоем(self.pointer_location)
    }

    /// Палец лёг на стекло. `экран` — точка в пикселях экрана.
    pub fn сенсор_вниз(&mut self, слот: i32, экран: Point<f64, Logical>, время: u32) {
        if !self.lua_config.touch {
            return;
        }
        // Курсор идёт за пальцем ВСЕГДА и ДО выбора роли: по нему считают и
        // хит-тесты органов ниже, и якорь зума, и выбор окна для жеста.
        let холст = self.сенсор_холст(экран);
        self.warp_pointer(холст);

        let первый = self.сенсор.пальцы.is_empty();
        self.сенсор.пальцы.push(Палец {
            слот,
            экран,
            начало: экран,
            положен: Instant::now(),
            у_клиента: false,
            истрачен: false,
        });

        if первый {
            self.роль_по_первому_пальцу(слот, холст, время);
        } else {
            self.роль_по_добавленному_пальцу(слот, холст, время);
        }
        self.request_redraw();
    }

    /// Выбор роли по первому пальцу — та самая развилка из трёх судеб.
    fn роль_по_первому_пальцу(&mut self, слот: i32, холст: Point<f64, Logical>, время: u32) {
        let под = self.surface_under(холст);

        // 2. Орган компоновщика — палец работает мышью.
        if self.сенсор_на_органе() {
            self.сенсор.роль = Роль::Указатель;
            self.сенсор_кнопка(true, время);
            return;
        }

        // 1. Окно. Фокус переводим сразу, как это делает клик: касание по
        // окну обязано поднять его, а не только доехать до клиента.
        if let Some((поверхность, точка)) = под {
            if let Some((окно, _)) = self.space.element_under(холст).map(|(w, l)| (w.clone(), l)) {
                crate::xwin::focus(self, &окно);
            }
            if self.lua_config.touch_emulate_pointer {
                self.сенсор.роль = Роль::Указатель;
                self.сенсор_кнопка(true, время);
                return;
            }
            self.сенсор.роль = Роль::Клиенту;
            self.сенсор_клиенту_вниз(слот, поверхность, точка, холст, время);
            return;
        }

        // 3. Пустой холст. Пан выключили — остаётся указатель: там рамка
        // выделения во Float и снятие фокуса, то есть ровно то, что делает по
        // пустому месту мышь.
        if self.lua_config.touch_pan {
            self.сенсор.роль = Роль::Пан;
            self.momentum.stop();
        } else {
            self.сенсор.роль = Роль::Указатель;
            self.сенсор_кнопка(true, время);
        }
    }

    /// Второй и следующие пальцы: щипок из пана, жест из щипка.
    fn роль_по_добавленному_пальцу(&mut self, слот: i32, холст: Point<f64, Logical>, время: u32) {
        let пальцев = self.сенсор.пальцы.len() as u32;

        // Клиенту отдаём мультитач как есть: сколько пальцев положили, столько
        // он и увидит. Жест тремя пальцами ПОВЕРХ ОКНА мы у него не отнимаем —
        // приложения с трёхпальцевыми жестами существуют, а вот отнятый на
        // середине мультитач выглядит как поломка приложения, а не как жест.
        if self.сенсор.роль == Роль::Клиенту {
            let под = self.surface_under(холст);
            if let Some((поверхность, точка)) = под {
                self.сенсор_клиенту_вниз(слот, поверхность, точка, холст, время);
            }
            return;
        }

        // Три пальца и больше — общая таблица жестов, та же, что у тачпада.
        // Основу (свайп или щипок) выберет первое движение, см. `ЖестЖдёт`.
        if пальцев >= 3 && self.lua_config.touch_gestures {
            self.сенсор.роль = Роль::ЖестЖдёт;
            self.сенсор.центр = self.сенсор.центр_пальцев();
            self.сенсор.жест_центр0 = self.сенсор.центр;
            self.сенсор.жест_разброс0 = self.сенсор.разброс();
            self.сенсор.жест_щипком = false;
            return;
        }

        if пальцев == 2 && self.lua_config.touch_zoom
            && matches!(self.сенсор.роль, Роль::Пан | Роль::Указатель)
        {
            // Указатель, ставший щипком: нажатую левую кнопку надо отпустить,
            // иначе рамка выделения останется висеть на камере до конца сеанса.
            if self.сенсор.роль == Роль::Указатель {
                self.сенсор_кнопка(false, время);
            }
            self.сенсор.роль = Роль::Щипок;
            self.сенсор.щипок_база = self.сенсор.разброс();
            self.сенсор.центр = self.сенсор.центр_пальцев();
        }
    }

    /// Палец поехал.
    pub fn сенсор_движение(&mut self, слот: i32, экран: Point<f64, Logical>, время: u32) {
        if !self.lua_config.touch {
            return;
        }
        let Some(палец) = self.сенсор.палец(слот) else { return };
        let прошлый = палец.экран;
        палец.экран = экран;
        let шаг = Point::<f64, Logical>::from((экран.x - прошлый.x, экран.y - прошлый.y));
        let холст = self.сенсор_холст(экран);

        match self.сенсор.роль {
            Роль::Клиенту => {
                let под = self.surface_under(холст);
                if let Some(touch) = self.seat.get_touch() {
                    touch.motion(self, под, &MotionEvent { slot: Some(слот as u32).into(), location: холст, time: время });
                    touch.frame(self);
                }
                self.warp_pointer(холст);
            }
            Роль::Указатель => {
                self.warp_pointer(холст);
            }
            Роль::Пан => {
                // Ведёт только тот палец, который лежит первым: второй в этой
                // роли взяться неоткуда, но слот-другой от ладони на краю
                // экрана иначе тянул бы камеру в свою сторону.
                if self.сенсор.пальцы.first().is_some_and(|п| п.слот == слот) {
                    self.сенсор_пан(шаг, экран, время);
                }
            }
            Роль::Щипок => self.сенсор_щипок(время),
            Роль::ЖестЖдёт => self.сенсор_основа_жеста(время),
            Роль::Жест if self.сенсор.жест_щипком => {
                let разброс = self.сенсор.разброс();
                let база = self.сенсор.жест_разброс0;
                if база > 1.0 {
                    self.жест_щипок_шаг(разброс / база);
                }
            }
            Роль::Жест => {
                let центр = self.сенсор.центр_пальцев();
                let d = Point::<f64, Logical>::from((
                    центр.x - self.сенсор.центр.x,
                    центр.y - self.сенсор.центр.y,
                ));
                self.сенсор.центр = центр;
                self.жест_свайп_шаг(d.x, d.y, время);
            }
            Роль::Нет => {}
        }

        // Долгое нажатие мерится от точки, где палец ЛЁГ: сторож ниже сам
        // проверит, что тот не уехал. Звать его отсюда обязательно — на
        // неподвижном экране кадров нет, а с ними нет и `anim::tick`.
        self.сенсор_сторож();
        self.request_redraw();
    }

    /// Выбор основы жеста тремя пальцами: щипок или свайп.
    ///
    /// Пороги разные и обе величины считаются ОТ НАЧАЛА, а не по кадрам: рука
    /// с тремя пальцами на стекле всегда немного и разъезжается, и едет разом,
    /// а решение должно быть принято по тому, чего человек сделал БОЛЬШЕ.
    fn сенсор_основа_жеста(&mut self, _время: u32) {
        /// Насколько должен уехать общий центр пальцев, чтобы это был свайп.
        const ПОРОГ_СВАЙПА: f64 = 20.0;
        /// Насколько должны разъехаться пальцы, чтобы это был щипок. Больше
        /// порога свайпа: рука, ведущая свайп, разъезжается сама собой.
        const ПОРОГ_ЩИПКА: f64 = 30.0;

        let центр = self.сенсор.центр_пальцев();
        let (dx, dy) = (центр.x - self.сенсор.жест_центр0.x, центр.y - self.сенсор.жест_центр0.y);
        let путь = (dx * dx + dy * dy).sqrt();
        let разброс = (self.сенсор.разброс() - self.сенсор.жест_разброс0).abs();
        let пальцев = self.сенсор.пальцы.len() as u32;

        if разброс > ПОРОГ_ЩИПКА && разброс > путь {
            self.сенсор.жест_щипком = true;
            self.сенсор.роль = Роль::Жест;
            self.жест_начало(crate::gestures::ОсноваЖеста::Щипок, пальцев);
        } else if путь > ПОРОГ_СВАЙПА {
            self.сенсор.жест_щипком = false;
            self.сенсор.роль = Роль::Жест;
            self.сенсор.центр = self.сенсор.жест_центр0;
            self.жест_начало(crate::gestures::ОсноваЖеста::Свайп, пальцев);
            // Путь, пройденный ДО решения, жест обязан увидеть: пороги свайпа в
            // таблице считаются от начала, и потерянные двадцать пикселей — это
            // ровно те двадцать, за которые человек ждал ответа.
            self.жест_свайп_шаг(dx, dy, _время);
            self.сенсор.центр = центр;
        }
    }

    /// Пан камеры одним пальцем: холст едет ЗА пальцем, один в один.
    fn сенсор_пан(&mut self, шаг: Point<f64, Logical>, экран: Point<f64, Logical>, время: u32) {
        let зум = self.viewport.zoom.max(0.01);
        let (dcam_x, dcam_y) = (шаг.x / зум, шаг.y / зум);
        self.pan_camera_by(dcam_x, dcam_y);
        // Инерция — та же, что у пана жестом тачпада: палец, брошенный на
        // ходу, оставляет холст в движении. Знак обратный дельте камеры, как в
        // `применить_непрерывное`.
        self.momentum
            .accumulate(Point::from((-dcam_x, -dcam_y)), время);
        // Курсор обязан остаться ПОД ПАЛЬЦЕМ, а `pan_camera_by` вернул его в
        // прежнюю точку холста, то есть увёл вместе с содержимым.
        let холст = self.сенсор_холст(экран);
        self.warp_pointer(холст);
    }

    /// Щипок: зум вокруг середины между пальцами, и она же ведёт камеру.
    fn сенсор_щипок(&mut self, время: u32) {
        let разброс = self.сенсор.разброс();
        let центр = self.сенсор.центр_пальцев();
        let прошлый_центр = self.сенсор.центр;
        self.сенсор.центр = центр;

        // Сперва пан серединой: якорь зума считается уже по новой камере.
        let шаг = Point::<f64, Logical>::from((центр.x - прошлый_центр.x, центр.y - прошлый_центр.y));
        if шаг.x != 0.0 || шаг.y != 0.0 {
            self.сенсор_пан(шаг, центр, время);
        } else {
            self.warp_pointer(self.сенсор_холст(центр));
        }

        // Порог в пиксель — против дрожи: пальцы на стекле никогда не стоят
        // ровно, и без него зум полз бы сам по себе всё время касания.
        let база = self.сенсор.щипок_база;
        if база > 1.0 && разброс > 1.0 && (разброс - база).abs() > 1.0 {
            self.сенсор.щипок_база = разброс;
            // Через `зум_мышью`, а не `зум_щипком`: тачпадный гейт запрещает
            // камере ездить от пальцев в тайлинге, и здесь он означал бы, что
            // на планшетном экране зума нет вовсе — другого способа приблизить
            // холст пальцем не существует.
            self.зум_мышью(разброс / база);
        }
    }

    /// Палец подняли.
    pub fn сенсор_вверх(&mut self, слот: i32, время: u32) {
        if !self.lua_config.touch {
            return;
        }
        let Some(i) = self.сенсор.пальцы.iter().position(|п| п.слот == слот) else { return };
        let палец = self.сенсор.пальцы.remove(i);

        if палец.у_клиента {
            if let Some(touch) = self.seat.get_touch() {
                let serial = SERIAL_COUNTER.next_serial();
                touch.up(self, &UpEvent { slot: Some(слот as u32).into(), serial, time: время });
                touch.frame(self);
            }
        }

        if !self.сенсор.пальцы.is_empty() {
            // Пальцы ещё есть. Щипок, потерявший один, доживает паном
            // оставшегося — так же ведёт себя мышиный аккорд, у которого сняли
            // лишнюю кнопку (см. `аккорды.rs`).
            if self.сенсор.роль == Роль::Щипок && self.сенсор.пальцы.len() == 1 {
                self.сенсор.роль = Роль::Пан;
            }
            self.сенсор.щипок_база = self.сенсор.разброс();
            self.сенсор.центр = self.сенсор.центр_пальцев();
            return;
        }

        // Экран отпустили целиком — прибираем за ролью.
        let роль = self.сенсор.роль;
        self.сенсор.роль = Роль::Нет;
        match роль {
            Роль::Указатель if !палец.истрачен => self.сенсор_кнопка(false, время),
            Роль::Пан => {
                // Инерция летит только после протяжки. Тап по пустому холсту —
                // это не пан длиной ноль, а «сними фокус», ровно как щелчок
                // мышью по пустому месту.
                if палец.сдвиг() > self.lua_config.touch_tap_slop {
                    self.momentum.launch();
                } else {
                    self.сенсор_тап_по_пустому(время);
                }
            }
            Роль::Жест => {
                self.жест_конец(false);
            }
            _ => {}
        }
        self.request_redraw();
    }

    /// Касание отменил сам драйвер (ладонь, переключение режима, уход
    /// устройства). Всё, что начали, закрываем — иначе висит вечно.
    pub fn сенсор_отмена(&mut self) {
        if self.сенсор.пальцы.is_empty() && self.сенсор.роль == Роль::Нет {
            return;
        }
        if self.сенсор.пальцы.iter().any(|п| п.у_клиента) {
            if let Some(touch) = self.seat.get_touch() {
                touch.cancel(self);
            }
        }
        match self.сенсор.роль {
            Роль::Указатель => self.сенсор_кнопка(false, 0),
            Роль::Жест => {
                self.жест_конец(true);
            }
            _ => {}
        }
        self.сенсор.пальцы.clear();
        self.сенсор.роль = Роль::Нет;
        self.request_redraw();
    }

    /// Конец пачки событий одного кадра. Клиенту он нужен как есть: по нему
    /// приложение понимает, что все пальцы этого кадра уже пришли.
    pub fn сенсор_кадр(&mut self) {
        if self.сенсор.роль != Роль::Клиенту {
            return;
        }
        if let Some(touch) = self.seat.get_touch() {
            touch.frame(self);
        }
    }

    /// Сторож долгого нажатия: палец лежит дольше срока и не сдвинулся —
    /// это правая кнопка.
    ///
    /// Зовётся из `anim::tick` И из движения пальца. Только из тика нельзя:
    /// тик идёт по кадрам, а неподвижный палец на неподвижном экране кадров не
    /// вызывает — той же болезнью болел сторож мышиных аккордов.
    pub fn сенсор_сторож(&mut self) {
        let срок = self.lua_config.touch_long_press;
        if срок == 0 || !matches!(self.сенсор.роль, Роль::Клиенту | Роль::Указатель) {
            return;
        }
        if self.сенсор.пальцы.len() != 1 {
            return;
        }
        let порог = self.lua_config.touch_tap_slop;
        let Some(палец) = self.сенсор.пальцы.first() else { return };
        if палец.истрачен
            || палец.сдвиг() > порог
            || палец.положен.elapsed().as_millis() < срок as u128
        {
            return;
        }
        let время = палец.положен.elapsed().as_millis() as u32;
        tracing::debug!("plx/touch: long press → right button");

        // Клиент видел нажатие пальцем — отменяем его, иначе к контекстному
        // меню он добавит ещё и тап.
        if палец.у_клиента {
            if let Some(touch) = self.seat.get_touch() {
                touch.cancel(self);
            }
        }
        if let Some(палец) = self.сенсор.пальцы.first_mut() {
            палец.истрачен = true;
            палец.у_клиента = false;
        }
        // Роль меняем на указатель: отпускание такого пальца больше ничего не
        // должно делать, а нажатую левую кнопку он и не нажимал.
        self.сенсор.роль = Роль::Указатель;
        self.сенсор_кнопка_кодом(crate::synth::КНОПКА_ПКМ, true, время);
        self.сенсор_кнопка_кодом(crate::synth::КНОПКА_ПКМ, false, время);
    }

    /// Тап по пустому холсту = щелчок левой по пустому месту: снять фокус (и
    /// начать рамку выделения во Float, которую тут же и закончит отпускание).
    fn сенсор_тап_по_пустому(&mut self, время: u32) {
        self.сенсор_кнопка(true, время);
        self.сенсор_кнопка(false, время);
    }

    /// Левая кнопка от пальца.
    fn сенсор_кнопка(&mut self, нажата: bool, время: u32) {
        self.сенсор_кнопка_кодом(crate::synth::КНОПКА_ЛКМ, нажата, время);
    }

    /// Кнопка мыши от пальца — ЧЕРЕЗ ОБЩУЮ ЦЕПОЧКУ `PointerButton`.
    ///
    /// Не `pointer.button` напрямую: в той цепочке живут панель, полка, карта,
    /// карточка, обзор, куб, рамка выделения и смена фокуса. Пойди палец мимо
    /// неё — и «нажатие работает, но ничего не делает», ровно как когда-то
    /// задержанная аккордом кнопка не начинала выделение.
    fn сенсор_кнопка_кодом(&mut self, код: u32, нажата: bool, время: u32) {
        let _ = время;
        // Мимо аккордов: пара кнопок у пальца невозможна, а задержка первой
        // кнопки стоила бы 250 мс КАЖДОМУ тычку по экрану (см. `аккорд_мимо`).
        self.аккорд_мимо = true;
        self.process_input_event(smithay::backend::input::InputEvent::PointerButton::<
            crate::synth::Синтетика,
        > {
            event: crate::synth::Кнопка::new(код, нажата),
        });
        self.аккорд_мимо = false;
    }

    /// Отдать касание клиенту настоящим `wl_touch`.
    fn сенсор_клиенту_вниз(
        &mut self,
        слот: i32,
        поверхность: smithay::reexports::wayland_server::protocol::wl_surface::WlSurface,
        точка: Point<f64, Logical>,
        холст: Point<f64, Logical>,
        время: u32,
    ) {
        let Some(touch) = self.seat.get_touch() else { return };
        let serial = SERIAL_COUNTER.next_serial();
        touch.down(
            self,
            Some((поверхность, точка)),
            &DownEvent { slot: Some(слот as u32).into(), location: холст, serial, time: время },
        );
        touch.frame(self);
        if let Some(палец) = self.сенсор.палец(слот) {
            палец.у_клиента = true;
        }
    }
}

/// Сколько пальцев на экране — для строки состояния и замеров харнесса.
impl Parallax {
    pub fn сенсор_состояние(&self) -> String {
        format!(
            "touch: {:?}, {} finger(s){}",
            self.сенсор.роль,
            self.сенсор.пальцы.len(),
            self.сенсор
                .пальцы
                .iter()
                .map(|п| format!(" [{} {:.0},{:.0}]", п.слот, п.экран.x, п.экран.y))
                .collect::<String>()
        )
    }
}

// Кнопка от пальца уходит через синтетическое событие, а не мимо цепочки, —
// см. `сенсор_кнопка_кодом`. Событие собирается в `synth.rs`, там же, где его
// собирает харнесс: два способа сделать одно и то же разошлись бы.
#[cfg(test)]
mod тесты {
    use super::*;

    fn палец(x: f64, y: f64) -> Палец {
        Палец {
            слот: 0,
            экран: Point::from((x, y)),
            начало: Point::from((x, y)),
            положен: Instant::now(),
            у_клиента: false,
            истрачен: false,
        }
    }

    #[test]
    fn центр_и_разброс_двух_пальцев() {
        let mut с = Сенсор::default();
        с.пальцы.push(палец(0.0, 0.0));
        с.пальцы.push(палец(100.0, 0.0));
        assert_eq!(с.центр_пальцев(), Point::from((50.0, 0.0)));
        assert_eq!(с.разброс(), 100.0);
    }

    #[test]
    fn сдвиг_меряется_от_точки_касания() {
        let mut п = палец(10.0, 10.0);
        assert_eq!(п.сдвиг(), 0.0);
        п.экран = Point::from((13.0, 14.0));
        assert_eq!(п.сдвиг(), 5.0);
    }

    #[test]
    fn разброс_одного_пальца_ноль() {
        let mut с = Сенсор::default();
        с.пальцы.push(палец(5.0, 5.0));
        assert_eq!(с.разброс(), 0.0);
    }
}
