//! Свет на холсте в цвет обоев — источник, а не нарисованное солнце.
//!
//! Диска на экране нет. Есть точка, из которой светит, и от неё берут своё два
//! потребителя:
//!
//! * **сцена** — мягкая заливка поверх обоев и под окнами (этот файл): то,
//!   как освещён сам холст;
//! * **окна** — сторона, обращённая к свету, ярче, обратная уходит в тень,
//!   кайма горит сильнее там, куда падает (см. `rounded.rs`, uniform'ы
//!   `light_*`). Считает это `свет_math::на_прямоугольник`.
//!
//! Так свет ведёт себя как свет, а не как картинка: у окон появляется сторона,
//! и по ней сразу видно, откуда светит, — а раньше на холсте висело жёлтое
//! пятно, до которого ничему не было дела.
//!
//! **Почему заливка сцены — картинка, а не шейдер.** Градиент считается один
//! раз на смену обоев и растягивается билинейно: он мягкий, резких переходов в
//! нём нет, и 256×256 хватает на любой экран (на 4K один тексель растягивается
//! в ~15 пикселей — при плавном градиенте это незаметно, а полосы гасит дизер,
//! см. ниже). Шейдер считал бы то же самое заново в каждом пикселе каждого
//! кадра.
//!
//! **Профиль.** Квадрат остатка `(1−r)²` и потолок альфы: ни выбеленного ядра,
//! ни чёткого края. Ядро и было тем, из-за чего пятно читалось солнцем —
//! середина выбеливалась, и глаз видел объект. Свет объекта иметь не должен.
//!
//! **Дизер.** Плавный градиент в 8 битах на канал идёт видимыми кольцами
//! (полосы Маха): соседние ступени отличаются на единицу, и глаз ловит их
//! границу. Округление со случайной добавкой (упорядоченный дизер 4×4)
//! размывает границу в шум, которого не видно.

use smithay::backend::allocator::Fourcc;
use smithay::backend::renderer::element::memory::MemoryRenderBuffer;
use smithay::utils::Transform;

use crate::обои::Палитра;

// Геометрия света — общий файл с минимальной сборкой (см. его шапку).
#[path = "свет_math.rs"]
mod math;
pub use math::{Источник, на_прямоугольник, источник};

/// Сторона картинки заливки в текселях.
pub const СТОРОНА: i32 = 256;

/// Потолок альфы заливки.
///
/// Свет ложится ПОВЕРХ обоев, и полная альфа означала бы «обоев больше не
/// видно». Треть — предел, за которым заливка перестаёт быть освещением
/// картинки и становится цветной плёнкой на ней.
const ПОТОЛОК: f32 = 0.34;

/// Матрица упорядоченного дизера 4×4 (Байер), значения 0…15.
const ДИЗЕР: [[f32; 4]; 4] = [
    [0.0, 8.0, 2.0, 10.0],
    [12.0, 4.0, 14.0, 6.0],
    [3.0, 11.0, 1.0, 9.0],
    [15.0, 7.0, 13.0, 5.0],
];

/// Готовая картинка заливки и то, при каких цвете и силе она построена.
pub struct Свет {
    буфер: Option<MemoryRenderBuffer>,
    ключ: Option<([f32; 3], u32)>,
}

impl std::fmt::Debug for Свет {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Свет").field("построено", &self.буфер.is_some()).finish()
    }
}

impl Default for Свет {
    fn default() -> Self {
        Self::new()
    }
}

impl Свет {
    pub fn new() -> Self {
        Self { буфер: None, ключ: None }
    }

    /// Буфер заливки под текущие обои. `None` — светить нечем (нет палитры или
    /// сила нулевая), и рисовать нечего.
    ///
    /// Пересобирается только на смене цвета или силы, то есть на смене обоев:
    /// в обычном кадре это одно сравнение.
    pub fn буфер(&mut self, палитра: Option<Палитра>, сила: f32) -> Option<&MemoryRenderBuffer> {
        let палитра = палитра?;
        let сила = сила.clamp(0.0, 1.0) * гашение(&палитра);
        if сила <= 0.001 {
            // Не забываем сбросить ключ: иначе обои сменились бы на светлые и
            // обратно, а заливка осталась бы построенной под старую силу.
            self.буфер = None;
            self.ключ = None;
            return None;
        }
        // Силу в ключ кладём округлённой до тысячных: она приходит из f32-
        // арифметики и в точности не повторяется, а перестраивать картинку из-за
        // разницы в шестом знаке незачем.
        let цвет = светящий(палитра.акцент);
        let ключ = (цвет, (сила * 1000.0) as u32);
        if self.ключ != Some(ключ) {
            let px = пиксели(цвет, сила);
            self.буфер = Some(MemoryRenderBuffer::from_slice(
                &px, Fourcc::Abgr8888, (СТОРОНА, СТОРОНА), 1, Transform::Normal, None,
            ));
            self.ключ = Some(ключ);
        }
        self.буфер.as_ref()
    }
}

/// Насколько свет гасится светлотой обоев.
///
/// Не в ноль, в отличие от каймы окна: кайма на светлом читается грязной
/// полосой, а освещение — просто бледнеет. Совсем убирать его на светлых обоях
/// значит терять ориентир на холсте там, где он нужен ровно так же.
pub fn гашение(п: &Палитра) -> f32 {
    1.0 - 0.7 * п.светлота()
}

/// Цвет, которым можно СВЕТИТЬ: тот же оттенок, но в полную яркость.
///
/// Заливка ложится на обои обычным смешиванием: результат равен
/// `обои·(1−a) + цвет·a`. Значит цвет темнее обоев их ГАСИТ — и заливка,
/// задуманная освещением, работает затенением. Именно это и было видно на
/// холсте: акцент приходит из палитры обоев как есть, у тёмных обоев он тёмный,
/// и при `set{ sun = 1.0 }` рабочий стол ровно темнел пятном во весь экран.
/// Ярик 05.09.2026: «затемнение рабочего стола», и притом ВНЕ куба — куб тут
/// действительно ни при чём, гасил свет.
///
/// Лечится не потолком альфы (он про меру, а не про знак) и не подмешиванием
/// белого (выбеленная середина — это и есть «нарисованное солнце», от которого
/// свет уходил, см. шапку). Лечится тем, что цвет берётся в ПОЛНУЮ яркость
/// своего оттенка: делим на максимальный канал. Оттенок и насыщенность при
/// этом сохраняются полностью — меняется только светлота, а она у источника
/// света и не должна зависеть от того, насколько тёмные обои.
///
/// Чёрный акцент (все каналы в нуле) вернётся собой: делить не на что, а
/// светить чёрным нечем — за такой случай отвечает `гашение` и потолок альфы.
fn светящий(акцент: [f32; 3]) -> [f32; 3] {
    let макс = акцент[0].max(акцент[1]).max(акцент[2]);
    if макс <= 1e-3 {
        return акцент;
    }
    [акцент[0] / макс, акцент[1] / макс, акцент[2] / макс]
}

/// Профиль яркости: 1 в центре, 0 на краю картинки.
///
/// Квадрат остатка — тот же спад, что у света на окнах
/// (`свет_math::на_прямоугольник`), и это не совпадение: сцена и окна обязаны
/// гаснуть одинаково, иначе окно у края охвата светится ярче холста под ним.
fn профиль(r: f32) -> f32 {
    if r >= 1.0 {
        return 0.0;
    }
    let s = 1.0 - r;
    s * s
}

/// Пиксели картинки: premultiplied RGBA, порядок байтов как у `Fourcc::Abgr8888`.
fn пиксели(акцент: [f32; 3], сила: f32) -> Vec<u8> {
    let n = СТОРОНА as usize;
    let mut px = Vec::with_capacity(n * n * 4);
    let центр = (СТОРОНА as f32 - 1.0) * 0.5;
    for y in 0..n {
        for x in 0..n {
            let dx = (x as f32 - центр) / центр;
            let dy = (y as f32 - центр) / центр;
            let r = (dx * dx + dy * dy).sqrt();
            // Чистый акцент без подмешанного белого: выбеленная середина — это
            // и есть «нарисованное солнце», от которого мы уходим.
            let a = (профиль(r) * сила * ПОТОЛОК).clamp(0.0, 1.0);
            let d = ДИЗЕР[y & 3][x & 3] / 16.0;
            let байт = |v: f32| -> u8 {
                // v уже premultiplied; дизер — та самая доля единицы младшего
                // разряда, из-за которой соседние ступени перестают идти
                // ровной границей.
                ((v * 255.0 + d).floor()).clamp(0.0, 255.0) as u8
            };
            px.extend_from_slice(&[
                байт(акцент[0] * a),
                байт(акцент[1] * a),
                байт(акцент[2] * a),
                байт(a),
            ]);
        }
    }
    px
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn палитра(фон: [f32; 3], акцент: [f32; 3]) -> Палитра {
        Палитра { акцент, фон }
    }

    #[test]
    fn центр_ярче_края_и_без_ядра() {
        let px = пиксели([0.6, 0.8, 0.4], 1.0);
        let n = СТОРОНА as usize;
        let альфа = |x: usize, y: usize| px[(y * n + x) * 4 + 3];
        assert_eq!(альфа(0, 0), 0, "угол картинки должен быть пуст: r > 1");
        assert!(альфа(n / 2, n / 2) > альфа(n / 2, n / 4), "яркость падает к краю");
        // Ровно то, что отличает свет от нарисованного солнца: даже в середине
        // заливка остаётся заливкой, сквозь неё видно обои.
        assert!(
            альфа(n / 2, n / 2) < 100,
            "в середине не должно быть плотного ядра: {}",
            альфа(n / 2, n / 2),
        );
    }

    #[test]
    fn белого_в_середине_нет() {
        // Красный акцент: если бы ядро выбеливалось, зелёный канал в середине
        // был бы заметно больше нуля — по нему и проверяем.
        let px = пиксели([1.0, 0.0, 0.0], 1.0);
        let n = СТОРОНА as usize;
        let i = ((n / 2) * n + n / 2) * 4;
        assert_eq!(px[i + 1], 0, "зелёного в чисто красном свете взяться неоткуда");
    }

    #[test]
    fn свет_не_гасит_обои() {
        // Тёмный акцент — тот случай, ради которого `светящий` и заведён.
        // Проверяем сразу два свойства: оттенок сохранён (пропорции каналов те
        // же) и цвет выведен в полную яркость. Второе и есть гарантия «свет
        // только прибавляет»: при смешивании `обои·(1−a) + цвет·a` темнее обоев
        // получится только от цвета темнее обоев, а ярче полной яркости своего
        // оттенка обоям взяться неоткуда.
        let тёмный = [0.10, 0.05, 0.02];
        let с = светящий(тёмный);
        assert!((с[0] - 1.0).abs() < 1e-6, "ведущий канал обязан выйти в единицу: {с:?}");
        let отн = |ц: [f32; 3]| (ц[1] / ц[0], ц[2] / ц[0]);
        let (g0, b0) = отн(тёмный);
        let (g1, b1) = отн(с);
        assert!((g0 - g1).abs() < 1e-6 && (b0 - b1).abs() < 1e-6, "оттенок поехал: {с:?}");
    }

    #[test]
    fn чёрным_не_светим() {
        // Делить не на что — возвращаем как есть, а не NaN на весь экран.
        let с = светящий([0.0, 0.0, 0.0]);
        assert_eq!(с, [0.0, 0.0, 0.0]);
    }

    #[test]
    fn цвет_предумножен() {
        let px = пиксели([1.0, 0.0, 0.0], 1.0);
        let n = СТОРОНА as usize;
        // Точка на полпути к краю: красный канал обязан быть НЕ БОЛЬШЕ альфы —
        // иначе цвет не предумножен и smithay покажет яркую кайму (та же
        // грабля, что с solid-цветами).
        let i = ((n / 2) * n + (n / 2 + n / 5)) * 4;
        assert!(px[i] <= px[i + 3] + 1, "R={} A={}", px[i], px[i + 3]);
    }

    #[test]
    fn на_светлых_обоях_бледнее() {
        let тёмные = гашение(&палитра([0.05, 0.06, 0.05], [0.6, 0.8, 0.4]));
        let светлые = гашение(&палитра([0.95, 0.96, 0.95], [0.6, 0.8, 0.4]));
        assert!(тёмные > 0.9, "на тёмных обоях свет в полную силу: {тёмные}");
        assert!(светлые < 0.35, "на светлых обоях гаснет: {светлые}");
        assert!(светлые > 0.0, "но не пропадает совсем");
    }

    #[test]
    fn буфер_строится_и_переиспользуется() {
        let mut с = Свет::new();
        assert!(с.буфер(None, 1.0).is_none(), "без палитры света нет");
        let п = Some(палитра([0.05, 0.06, 0.05], [0.6, 0.8, 0.4]));
        assert!(с.буфер(п, 1.0).is_some(), "с палитрой заливка строится");
        let ключ = с.ключ;
        assert!(с.буфер(п, 1.0).is_some());
        assert_eq!(с.ключ, ключ, "тот же цвет — картинка не пересобирается");
        assert!(с.буфер(п, 0.0).is_none(), "нулевая сила гасит свет");
        assert!(с.ключ.is_none(), "и сбрасывает ключ");
    }
}
