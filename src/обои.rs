//! Палитра ОБОЕВ — то, чем parallax красит свои эффекты в цвет картинки на
//! экране.
//!
//! Палитру считает не компоновщик, а plx-wall: он и так декодирует обои,
//! чтобы их показать, и по уменьшенной копии строит гистограмму (см.
//! `plx-wall/src/palette.rs`). Результат он кладёт файлом
//! `~/.cache/plx-wall/palette.json` и рассылает терминалам через OSC — тем же
//! файлом пользуемся и мы. Считать палитру второй раз здесь было бы и дороже
//! (полный кадр 4K вместо готового ответа), и хуже: цвета в оболочке, в меню
//! и в свечении окон разошлись бы на округлениях.
//!
//! Файла может не быть вовсе — plx-wall не обязан быть запущен, а у чужого
//! пользователя его может не быть в системе. Это не беда: `Палитра::прочесть`
//! вернёт `None`, и всё, что от неё зависит, просто не включится.
//!
//! Перечитываем по времени правки, а не по подписке на файл: обои меняются
//! раз в минуты, а inotify ради одного файла — отдельный дескриптор в цикле
//! событий и отдельный источник ошибок.

use std::path::PathBuf;
use std::time::SystemTime;

/// Цвета обоев, нужные компоновщику.
///
/// Их в файле больше (шестнадцать цветов ANSI, фон выделения), но эффектам
/// нужны ровно два: чем светить и насколько светло вокруг.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Палитра {
    /// Самый заметный цвет обоев — им и светим.
    pub акцент: [f32; 3],
    /// Фон: самый частый тёмный цвет. По нему считается [`Палитра::светлота`].
    pub фон: [f32; 3],
}

impl Палитра {
    /// Насколько светлы обои, 0…1.
    ///
    /// Берём воспринимаемую яркость фона (веса те же, что у Rec. 601 — на
    /// глаз зелёный много ярче синего). Ею гасится свечение: на светлых обоях
    /// цветная кайма вокруг окна выглядит грязью, на тёмных — тем самым
    /// сиянием, ради которого всё и заведено.
    pub fn светлота(&self) -> f32 {
        0.299 * self.фон[0] + 0.587 * self.фон[1] + 0.114 * self.фон[2]
    }

    /// Прочесть файл, если он с прошлого раза изменился.
    ///
    /// `когда` — время правки, с которым читали в прошлый раз; сюда же
    /// записывается новое. Ничего не поменялось — `None`, и вызывающий
    /// оставляет прежнюю палитру.
    pub fn перечесть(когда: &mut Option<SystemTime>) -> Option<Палитра> {
        let путь = путь_палитры()?;
        let правка = std::fs::metadata(&путь).and_then(|м| м.modified()).ok()?;
        if *когда == Some(правка) {
            return None;
        }
        *когда = Some(правка);
        let текст = std::fs::read_to_string(&путь).ok()?;
        let п = разобрать(&текст);
        if п.is_none() {
            tracing::warn!("plx/wallpaper: could not parse {:?}", путь);
        }
        п
    }
}

fn путь_палитры() -> Option<PathBuf> {
    let home = std::env::var("HOME").ok()?;
    Some(PathBuf::from(home).join(".cache/plx-wall/palette.json"))
}

/// Разбор `{"bg": "#131511", ..., "accent": "#9bc463", ...}`.
///
/// Свой, а не через serde: нужны два поля из восьми, формат пишет соседняя
/// программа в одну строку на ключ, и заводить ради этого структуру с
/// производными сериализации — больше кода, чем сам разбор.
fn разобрать(текст: &str) -> Option<Палитра> {
    let поле = |имя: &str| -> Option<[f32; 3]> {
        let ключ = format!("\"{имя}\"");
        let хвост = текст.split_once(&ключ)?.1;
        // Первая строка в кавычках после двоеточия — значение.
        let (_, после) = хвост.split_once(':')?;
        let (_, внутри) = после.split_once('"')?;
        let (цвет, _) = внутри.split_once('"')?;
        цвет_из_hex(цвет)
    };
    Some(Палитра { акцент: поле("accent")?, фон: поле("bg")? })
}

/// `#rrggbb` → три доли 0…1.
fn цвет_из_hex(s: &str) -> Option<[f32; 3]> {
    let s = s.strip_prefix('#').unwrap_or(s);
    if s.len() != 6 {
        return None;
    }
    let к = |от: usize| u8::from_str_radix(&s[от..от + 2], 16).ok().map(|v| v as f32 / 255.0);
    Some([к(0)?, к(2)?, к(4)?])
}

#[cfg(test)]
mod тесты {
    use super::*;

    /// Разбор настоящего файла plx-wall — того самого, что лежит у Ярика.
    #[test]
    fn разбирает_файл_plx_wall() {
        let текст = r##"{
  "bg": "#131511",
  "fg": "#dbddd9",
  "cursor": "#aeca85",
  "accent": "#9bc463",
  "sel_bg": "#566e35",
  "ansi": ["#21231e", "#8baf59"]
}
"##;
        let п = разобрать(текст).expect("палитра должна разобраться");
        // #9bc463
        assert!((п.акцент[0] - 0.607).abs() < 0.01, "красный акцента: {:?}", п.акцент);
        assert!((п.акцент[1] - 0.769).abs() < 0.01);
        assert!((п.акцент[2] - 0.388).abs() < 0.01);
        // Тёмные обои — светлота близка к нулю.
        assert!(п.светлота() < 0.1, "светлота тёмных обоев: {}", п.светлота());
    }

    /// Порядок ключей в файле не обязан совпадать с нашими ожиданиями, а
    /// «accent» не должен путаться с похожими именами.
    #[test]
    fn берёт_нужные_ключи_а_не_соседние() {
        let текст = r##"{"accent_bg": "#000000", "accent": "#ff8000", "bg": "#ffffff"}"##;
        let п = разобрать(текст).expect("должна разобраться");
        assert!((п.акцент[0] - 1.0).abs() < 0.01, "акцент: {:?}", п.акцент);
        assert!((п.акцент[1] - 0.502).abs() < 0.01, "акцент: {:?}", п.акцент);
        // Белые обои — светлота единица, свечение на них гасится.
        assert!(п.светлота() > 0.99, "светлота белых обоев: {}", п.светлота());
    }

    #[test]
    fn мусор_не_разбирается() {
        assert!(разобрать("").is_none());
        assert!(разобрать(r##"{"accent": "не цвет", "bg": "#000000"}"##).is_none());
    }
}
