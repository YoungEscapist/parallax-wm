//! Карусель колонок — обзор ленты (niri) в 3D.
//!
//! Куб в ленте показывает на грани кусок этажа шириной в экран, и колонки за
//! краем в обзоре не видны вовсе. Карусель раскладывает этаж ЦЕЛИКОМ: каждая
//! колонка — своя плоская панель, панели стоят по кругу барабана, и на него
//! смотрят чуть сверху, так что задняя половина кольца видна над передней.
//! Соседние этажи — такие же барабаны выше и ниже.
//!
//! **Задние панели развёрнуты ВНУТРЬ**, к зрителю: снаружи барабана зритель
//! видел бы их изнанкой, то есть окна зеркально. Разворот происходит там, где
//! панель стоит к камере ребром (угол ±90°), поэтому скачка не видно: обе
//! ориентации в этой точке — одна и та же полоска толщиной в ноль.
//!
//! **Вход и выход — одно превращение.** Параметр `раскрытие` (0…1) ведёт
//! каждую панель от места, где её колонка стоит на плоском экране, к месту на
//! кольце: при нуле панель лежит в плоскости `z = D − F`, где проекция один к
//! одному, — первый кадр входа попиксельно совпадает со столом, а последний
//! кадр выхода — со столом, на который приземляемся.
//!
//! Геометрия чистая: ни GL, ни состояния композитора. Рисует по ней udev.rs,
//! состоянием и вводом ведает overview.rs.

use crate::куб::{Куб, Плоскость};

/// Зазор между панелями по дуге, пиксели холста.
pub const ЗАЗОР: f64 = 56.0;
/// Шаг этажей по вертикали в долях высоты экрана.
pub const ШАГ_ЭТАЖЕЙ: f64 = 1.3;
/// Наклон по умолчанию: смотрим чуть сверху, иначе задняя половина кольца
/// пряталась бы за передней целиком.
pub const НАКЛОН: f64 = -0.32;
/// Пределы наклона (Ctrl+колесо). Вверх дальше почти горизонта смысла нет —
/// задний ряд уходит за передний.
pub const НАКЛОН_МИН: f64 = -1.2;
pub const НАКЛОН_МАКС: f64 = 0.1;

/// Этаж на входе: колонки (x0, x1 на холсте), верх этажа на холсте и x камеры,
/// которой он показывается НА ПЛОСКОМ ЭКРАНЕ (это место панели при нулевом
/// раскрытии).
#[derive(Clone, Debug)]
pub struct Этаж {
    pub колонки: Vec<(f64, f64)>,
    pub верх: f64,
    pub кадр_x: f64,
    /// Какая точка дуги смотрит на зрителя (пиксели дуги от начала кольца).
    pub фронт: f64,
}

/// Панель в кадре.
#[derive(Clone, Copy, Debug)]
pub struct Панель {
    pub этаж: usize,
    pub колонка: usize,
    pub плоскость: Плоскость,
    /// Прямоугольник колонки в координатах панели (центр — середина колонки).
    pub rect: (f32, f32, f32, f32),
    /// Центр колонки на холсте: `u = x − центр.0`, `v = y − центр.1`.
    pub центр: (f64, f64),
    pub яркость: f32,
    pub глубина: f32,
    /// Панель смотрит на зрителя своей лицевой стороной, а не развёрнута к
    /// нему с задней половины кольца. Карусель столов рисует окна только на
    /// таких (05.10.2026); у карусели колонок все панели лицом.
    pub лицом: bool,
}

/// Общие параметры кадра.
#[derive(Clone, Copy, Debug)]
pub struct Вид {
    /// Экран, пиксели.
    pub экран: (f64, f64),
    /// Фокусное расстояние в ширинах экрана (`cube_focal`).
    pub фокус: f64,
    /// 0 — плоский экран, 1 — карусель.
    pub раскрытие: f64,
    pub наклон: f64,
    /// Положение по этажам: индекс этажа, стоящего в центре (дробный во время
    /// переезда).
    pub этаж: f64,
    /// Затемнение дальнего края, как у куба.
    pub тень: f32,
}

/// Кольцо этажа: центры колонок по дуге и радиус.
///
/// Длина окружности — сумма колонок с зазорами, но не меньше двух с лишним
/// экранов: на этаже из одной-двух колонок кольцо иначе сжалось бы в столб, и
/// панели стояли бы друг к другу почти под прямым углом.
pub fn кольцо(колонки: &[(f64, f64)], ширина_экрана: f64) -> (Vec<f64>, f64) {
    let mut s = 0.0;
    let mut центры = Vec::with_capacity(колонки.len());
    for &(x0, x1) in колонки {
        let w = (x1 - x0).max(1.0);
        центры.push(s + w * 0.5);
        s += w + ЗАЗОР;
    }
    let окружность = s.max(ширина_экрана * 2.2);
    (центры, окружность / std::f64::consts::TAU)
}

/// Угол в (−π, π].
fn нормировать(a: f64) -> f64 {
    let tau = std::f64::consts::TAU;
    let mut a = a.rem_euclid(tau);
    if a > std::f64::consts::PI {
        a -= tau;
    }
    a
}

/// Ориентация панели, стоящей на угле `угол` кольца: передняя половина —
/// лицом наружу (как грань), задняя — внутрь, к зрителю (см. шапку).
pub fn ориентация(угол: f64) -> f64 {
    let n = нормировать(угол);
    let пол = std::f64::consts::FRAC_PI_2;
    if n.abs() <= пол {
        n
    } else {
        n - std::f64::consts::PI * n.signum()
    }
}

fn наклонить(β: f64, [x, y, z]: [f64; 3]) -> [f64; 3] {
    let (s, c) = β.sin_cos();
    [x, y * c - z * s, y * s + z * c]
}

fn f32x3(v: [f64; 3]) -> [f32; 3] {
    [v[0] as f32, v[1] as f32, v[2] as f32]
}

/// Где стоит панель на кольце (до наклона) и как развёрнута.
fn на_кольце(центр_дуги: f64, ширина: f64, фронт: f64, r: f64, y: f64) -> ([f64; 3], f64) {
    let угол = (центр_дуги - фронт) / r.max(1.0);
    // Хорда, а не дуга: панель плоская и касается окружности краями. Предел
    // на полуугол — колонка шире полукруга (одна на пустом этаже) иначе
    // вывернула бы апофему в минус.
    let апофема = r * (ширина / (2.0 * r.max(1.0))).min(1.3).cos();
    let (s, c) = угол.sin_cos();
    ([апофема * s, y, апофема * c], ориентация(угол))
}

/// Камера: расстояние, при котором кольцо этажа целиком укладывается в экран
/// (с полями), и СДВИГ картинки, ставящий кольцо в середину. Итерациями:
/// проекция нелинейна по расстоянию, но пяти шагов хватает до пикселя.
///
/// Сдвиг нужен из-за наклона: кольцо крутится вокруг своей оси, и передний
/// край наклонённого барабана уезжает вниз — на этаже из одной колонки панель
/// оказывалась у нижнего края экрана (тест поймал).
fn подобрать_камеру(вид: &Вид, этаж: &Этаж, f: f64) -> (f64, (f64, f64)) {
    let (w, h) = вид.экран;
    let (центры, r) = кольцо(&этаж.колонки, w);
    let mut d = r + f * 1.2;
    let mut сдвиг = (0.0, 0.0);
    for _ in 0..5 {
        let mut мин = (f64::MAX, f64::MAX);
        let mut макс = (f64::MIN, f64::MIN);
        for (i, &(x0, x1)) in этаж.колонки.iter().enumerate() {
            let ширина = x1 - x0;
            let (o, ψ) = на_кольце(центры[i], ширина, этаж.фронт, r, 0.0);
            let eu = [ψ.cos(), 0.0, -ψ.sin()];
            for (u, v) in [(-0.5, -0.5), (0.5, -0.5), (-0.5, 0.5), (0.5, 0.5)] {
                let p = [
                    o[0] + eu[0] * u * ширина,
                    o[1] + v * h,
                    o[2] + eu[2] * u * ширина,
                ];
                let p = наклонить(вид.наклон, p);
                let глубина = (d - p[2]).max(1.0);
                let x = f * p[0] / глубина;
                let y = f * p[1] / глубина;
                мин = (мин.0.min(x), мин.1.min(y));
                макс = (макс.0.max(x), макс.1.max(y));
            }
        }
        if мин.0 > макс.0 {
            break;
        }
        сдвиг = ((мин.0 + макс.0) * 0.5, (мин.1 + макс.1) * 0.5);
        // Поля: по ширине 8%, по высоте больше — там ещё соседние этажи.
        let k = (0.92 * w / (макс.0 - мин.0).max(1.0)).min(0.8 * h / (макс.1 - мин.1).max(1.0));
        d = (d / k).max(r + f * 0.3);
    }
    // Сдвиг посчитан при предпоследнем расстоянии; к пятому шагу k ≈ 1, и
    // разница меньше пикселя.
    (d, сдвиг)
}

/// Разложить кадр: камера и все панели всех этажей, от ближней к дальней.
///
/// `этажи` — по порядку ленты, `вид.этаж` — индекс в этом списке.
pub fn разложить(вид: &Вид, этажи: &[Этаж]) -> (Куб, Vec<Панель>) {
    let (w, h) = вид.экран;
    let f = вид.фокус.max(0.1) * w;
    // Камера — между подборами двух этажей, между которыми сейчас едем: этажи
    // бывают разной длины, и скачок расстояния на смене этажа был бы виден.
    let (d, сдвиг) = if этажи.is_empty() {
        (f, (0.0, 0.0))
    } else {
        let p = вид.этаж.clamp(0.0, (этажи.len() - 1) as f64);
        let (a, b) = (p.floor() as usize, p.ceil() as usize);
        let (da, ca) = подобрать_камеру(вид, &этажи[a], f);
        let (db, cb) = подобрать_камеру(вид, &этажи[b], f);
        let t = p - a as f64;
        (da + (db - da) * t, (ca.0 + (cb.0 - ca.0) * t, ca.1 + (cb.1 - ca.1) * t))
    };
    let e = вид.раскрытие.clamp(0.0, 1.0);
    // Радиус текущего этажа — для затемнения глубиной (шейдер меряет её от
    // ближней точки кольца `D − r` до дальней `D + r`).
    let r_тек = этажи
        .get(вид.этаж.round().max(0.0) as usize)
        .map(|э| кольцо(&э.колонки, w).1)
        .unwrap_or(w * 0.35);
    let камера = Куб {
        граней: 4,
        поворот: 0.0,
        радиус: r_тек as f32,
        камера: d as f32,
        фокус: f as f32,
        // Сдвиг картинки — только в раскрытой карусели: плоский экран обязан
        // стоять попиксельно на месте.
        ось: ((w * 0.5 - сдвиг.0 * e) as f32, (h * 0.5 - сдвиг.1 * e) as f32),
        тень: (вид.тень as f64 * e) as f32,
        наклон: 0.0,
    };

    let mut панели = Vec::new();
    for (i, этаж) in этажи.iter().enumerate() {
        let отступ = i as f64 - вид.этаж;
        let (центры, r) = кольцо(&этаж.колонки, w);
        for (k, &(x0, x1)) in этаж.колонки.iter().enumerate() {
            let ширина = (x1 - x0).max(1.0);
            let центр = ((x0 + x1) * 0.5, этаж.верх + h * 0.5);
            // Плоско: колонка там, где стоит на экране, в плоскости один к
            // одному; соседние этажи — ровно по экрану выше и ниже.
            let плоско = [центр.0 - этаж.кадр_x - w * 0.5, отступ * h, d - f];
            let (на, ψ) = на_кольце(центры[k], ширина, этаж.фронт, r, отступ * h * ШАГ_ЭТАЖЕЙ);
            let на = наклонить(вид.наклон, на);
            let o = [
                плоско[0] + (на[0] - плоско[0]) * e,
                плоско[1] + (на[1] - плоско[1]) * e,
                плоско[2] + (на[2] - плоско[2]) * e,
            ];
            let (ψe, βe) = (ψ * e, вид.наклон * e);
            let eu = наклонить(βe, [ψe.cos(), 0.0, -ψe.sin()]);
            let ev = наклонить(βe, [0.0, 1.0, 0.0]);
            let яркость = 1.0 - 0.45 * отступ.abs().min(1.0) * e;
            панели.push(Панель {
                этаж: i,
                колонка: k,
                плоскость: Плоскость {
                    начало: f32x3(o),
                    вдоль_u: f32x3(eu),
                    вдоль_v: f32x3(ev),
                },
                rect: (
                    (-ширина * 0.5) as f32,
                    (-h * 0.5) as f32,
                    (ширина * 0.5) as f32,
                    (h * 0.5) as f32,
                ),
                центр,
                яркость: яркость as f32,
                глубина: (d - o[2]) as f32,
                лицом: true,
            });
        }
    }
    // От ближней к дальней — так идёт список кадра (передний план первым).
    панели.sort_by(|a, b| a.глубина.total_cmp(&b.глубина));
    (камера, панели)
}

/// Какая панель под точкой экрана: первая по глубине, на которую попал луч.
pub fn под_точкой(камера: &Куб, панели: &[Панель], точка: (f32, f32)) -> Option<(usize, usize)> {
    панели.iter().find_map(|п| {
        let (u, v) = камера.обратно_на(&п.плоскость, точка)?;
        let (u0, v0, u1, v1) = п.rect;
        (u >= u0 && u <= u1 && v >= v0 && v <= v1).then_some((п.этаж, п.колонка))
    })
}

/// Сколько пикселей экрана даёт пиксель дуги у переднего края кольца — чтобы
/// драг вёл барабан за рукой один к одному.
pub fn масштаб_фронта(камера: &Куб) -> f64 {
    (камера.фокус / (камера.камера - камера.радиус).max(1.0)) as f64
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn этаж(колонок: usize) -> Этаж {
        Этаж {
            колонки: (0..колонок).map(|i| (i as f64 * 1300.0, i as f64 * 1300.0 + 1240.0)).collect(),
            верх: 0.0,
            кадр_x: 0.0,
            фронт: 620.0,
        }
    }

    fn вид(раскрытие: f64) -> Вид {
        Вид {
            экран: (2560.0, 1080.0),
            фокус: 2.2,
            раскрытие,
            наклон: НАКЛОН,
            этаж: 0.0,
            тень: 0.35,
        }
    }

    #[test]
    fn свёрнутая_карусель_это_плоский_экран() {
        // При нулевом раскрытии каждая колонка стоит там, где она на экране,
        // один к одному: первый кадр входа совпадает со столом.
        let (к, п) = разложить(&вид(0.0), &[этаж(5)]);
        for панель in &п {
            let (x0, _) = этаж(5).колонки[панель.колонка];
            let угол = к.проекция_на(&панель.плоскость, панель.rect.0, панель.rect.1).unwrap();
            assert!((угол.0 as f64 - x0).abs() < 0.05, "колонка {}: {угол:?}", панель.колонка);
            assert!(угол.1.abs() < 0.05, "верх этажа — верх экрана: {угол:?}");
        }
    }

    #[test]
    fn раскрытая_карусель_целиком_в_экране() {
        // Ради этого карусель и заведена: ВСЕ колонки этажа видны сразу.
        for колонок in [1, 3, 8, 14] {
            let (к, п) = разложить(&вид(1.0), &[этаж(колонок)]);
            assert_eq!(п.len(), колонок);
            for панель in &п {
                let (u0, v0, u1, v1) = панель.rect;
                for (u, v) in [(u0, v0), (u1, v0), (u0, v1), (u1, v1)] {
                    let (x, y) = к.проекция_на(&панель.плоскость, u, v).expect("перед камерой");
                    assert!(
                        (-2.0..=2562.0).contains(&x) && (-2.0..=1082.0).contains(&y),
                        "{колонок} колонок: угол панели {} вне экрана: ({x}, {y})",
                        панель.колонка,
                    );
                }
            }
        }
    }

    #[test]
    fn передняя_колонка_ближе_всех_и_лицом() {
        let (_, п) = разложить(&вид(1.0), &[этаж(6)]);
        // Фронт — середина нулевой колонки.
        assert_eq!(п[0].колонка, 0, "ближняя панель — та, что на фронте");
        let eu = п[0].плоскость.вдоль_u;
        assert!(eu[0] > 0.99, "передняя панель смотрит прямо на зрителя: {eu:?}");
    }

    #[test]
    fn задние_панели_не_зеркальны() {
        // Задняя панель развёрнута внутрь: её ось u на экране идёт ВПРАВО, как
        // у передней, — иначе окна сзади читались бы зеркально.
        let (к, п) = разложить(&вид(1.0), &[этаж(8)]);
        let задняя = п.last().unwrap();
        let л = к.проекция_на(&задняя.плоскость, задняя.rect.0, 0.0).unwrap();
        let пр = к.проекция_на(&задняя.плоскость, задняя.rect.2, 0.0).unwrap();
        assert!(пр.0 > л.0, "задняя панель зеркальна: {л:?} → {пр:?}");
    }

    #[test]
    fn клик_попадает_в_переднюю_колонку() {
        let (к, п) = разложить(&вид(1.0), &[этаж(6)]);
        let центр = к.проекция_на(&п[0].плоскость, 0.0, 0.0).unwrap();
        assert_eq!(под_точкой(&к, &п, центр), Some((0, 0)));
    }

    #[test]
    fn ориентация_непрерывна_на_ребре() {
        // Около ±90° обе ветви дают панель ребром — скачка не видно.
        let e = 1e-3;
        let пол = std::f64::consts::FRAC_PI_2;
        let до = ориентация(пол - e);
        let после = ориентация(пол + e);
        assert!((до.cos().abs() - после.cos().abs()).abs() < 1e-2);
    }
}
