//! Жесты тачпада таблицей биндов — модель driftwm, перенесённая в parallax.
//!
//! **Зачем это, если жесты и так работали.** Работали, но каждый был вписан в
//! `input.rs` отдельной веткой с собственным условием: Super+2 пальца — вести
//! окно, Alt+2 пальца — пан, щипок — зум, и так далее. Добавить свой жест было
//! нельзя вообще: только правкой исходника. В driftwm жесты — это таблица
//! `"Модификатор+N-finger-<тип>" = "действие"`, ровно как клавиатурные бинды, и
//! именно её Ярик просил перенести (30.08.2026).
//!
//! **Старое поведение не тронуто, и это устроено проверяемо.** Диспетчер
//! зовётся ПЕРВЫМ и возвращает `bool`: нашёл подходящий бинд — обработал сам и
//! сказал «да», не нашёл — сказал «нет», и управление уходит в прежние ветки
//! `input.rs` слово в слово. Пустая таблица жестов = поведение parallax до этой
//! правки, байт в байт.
//!
//! ## Из чего складывается жест
//!
//! * **Триггер** — тип и число пальцев: `3-finger-swipe`, `4-finger-swipe-up`,
//!   `2-finger-pinch-in`, `4-finger-hold`.
//! * **Модификаторы** — как у клавиатурных биндов (`alt`, `super`, `shift`, `ctrl`).
//! * **Контекст** — где начался жест: `window` (под курсором окно), `canvas`
//!   (пустой холст), `anywhere` (всё равно). Точное совпадение контекста
//!   сильнее, чем `anywhere`: `2-finger-pinch` на холсте зумит вид, а над окном
//!   может значить своё.
//! * **Действие** — либо непрерывное (едет за пальцами каждый кадр), либо
//!   пороговое (копим, пока не наберётся, и срабатывает один раз).
//!
//! ## Непрерывное против порогового — почему это разные списки
//!
//! Непрерывных действий ровно шесть, и каждое привязано к своему типу жеста:
//! пан и зум ведут камеру, три «оконных» — окно. Их нельзя повесить на
//! `pinch-in`, потому что `pinch-in` — это событие, а не поток: он срабатывает
//! один раз, когда пальцы сошлись достаточно. Пороговым же может быть ЛЮБОЕ
//! действие из `config.lua` — те же, что вешаются на клавиши.
//!
//! ## Два пальца — это не свайп libinput
//!
//! `GestureSwipe` libinput отдаёт только с ТРЁХ пальцев; два он считает
//! прокруткой и шлёт осью с `source = Finger`. Поэтому `2-finger-swipe`
//! ловится в ветке оси, а не в ветке жестов, — снаружи это один и тот же бинд,
//! разница видна только здесь.
//!
//! **`GesturePinch` — другое дело: он начинается с ДВУХ пальцев.** Значит
//! `2-finger-pinch` идёт обычным путём жестов, и никакого обходного манёвра
//! ему не нужно.

use crate::config::{Action, ModMask};

/// Тип жеста и число пальцев.
///
/// Числа пальцев не ограничены сверху намеренно: у тачпадов бывает и шесть
/// касаний, а бинд на несуществующее число просто никогда не сработает — это
/// честнее, чем отказ разбирать конфиг.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Триггер {
    Свайп { пальцы: u32 },
    СвайпВверх { пальцы: u32 },
    СвайпВниз { пальцы: u32 },
    СвайпВлево { пальцы: u32 },
    СвайпВправо { пальцы: u32 },
    ДвойнойТапСвайп { пальцы: u32 },
    Щипок { пальцы: u32 },
    ЩипокВнутрь { пальцы: u32 },
    ЩипокНаружу { пальцы: u32 },
    Удержание { пальцы: u32 },
}

impl Триггер {
    pub fn пальцы(&self) -> u32 {
        match *self {
            Триггер::Свайп { пальцы }
            | Триггер::СвайпВверх { пальцы }
            | Триггер::СвайпВниз { пальцы }
            | Триггер::СвайпВлево { пальцы }
            | Триггер::СвайпВправо { пальцы }
            | Триггер::ДвойнойТапСвайп { пальцы }
            | Триггер::Щипок { пальцы }
            | Триггер::ЩипокВнутрь { пальцы }
            | Триггер::ЩипокНаружу { пальцы }
            | Триггер::Удержание { пальцы } => пальцы,
        }
    }

    /// Разобрать имя вида `swipe`, `swipe-up`, `pinch-in`, `doubletap-swipe`,
    /// `hold`. Число пальцев приходит отдельным полем.
    pub fn разобрать(имя: &str, пальцы: u32) -> Option<Self> {
        Some(match имя.trim().to_ascii_lowercase().as_str() {
            "swipe" | "свайп" => Триггер::Свайп { пальцы },
            "swipe-up" | "свайп-вверх" => Триггер::СвайпВверх { пальцы },
            "swipe-down" | "свайп-вниз" => Триггер::СвайпВниз { пальцы },
            "swipe-left" | "свайп-влево" => Триггер::СвайпВлево { пальцы },
            "swipe-right" | "свайп-вправо" => Триггер::СвайпВправо { пальцы },
            "doubletap-swipe" | "двойной-тап-свайп" => Триггер::ДвойнойТапСвайп { пальцы },
            "pinch" | "щипок" => Триггер::Щипок { пальцы },
            "pinch-in" | "щипок-внутрь" => Триггер::ЩипокВнутрь { пальцы },
            "pinch-out" | "щипок-наружу" => Триггер::ЩипокНаружу { пальцы },
            "hold" | "удержание" => Триггер::Удержание { пальцы },
            _ => return None,
        })
    }
}

/// Где жест начался. Решается ОДИН раз, на первом кадре: пальцы едут, курсор
/// под ними может уехать с окна на пустоту, и жест, начатый как «двигаю окно»,
/// обязан остаться таким до конца.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Где {
    НаОкне,
    НаХолсте,
    Везде,
}

impl Где {
    pub fn разобрать(имя: &str) -> Option<Self> {
        Some(match имя.trim().to_ascii_lowercase().as_str() {
            "window" | "on-window" | "окно" => Где::НаОкне,
            "canvas" | "on-canvas" | "холст" => Где::НаХолсте,
            "anywhere" | "везде" | "" => Где::Везде,
            _ => return None,
        })
    }

    /// Подходит ли бинд к тому, что под курсором сейчас.
    fn подходит(self, сейчас_окно: bool) -> bool {
        match self {
            Где::Везде => true,
            Где::НаОкне => сейчас_окно,
            Где::НаХолсте => !сейчас_окно,
        }
    }
}

/// Действия, которые едут за пальцами каждый кадр.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Непрерывное {
    ПанВида,
    Зум,
    ВестиОкно,
    ВестиСоСнапом,
    РазмерОкна,
    РазмерСоСнапом,
}

/// Что делает жест.
///
/// Без `PartialEq` намеренно: его пришлось бы навесить на весь
/// `config::Action`, а тот несёт строки команд и параметры раскладок — сравнение
/// действий не нужно ни здесь, ни где-либо ещё, а лишний вывод обязывал бы
/// каждое новое поле уметь сравниваться.
#[derive(Clone, Debug)]
pub enum ДействиеЖеста {
    Непрерывно(Непрерывное),
    /// Свернуть вид к ближайшему окну; направление берётся из направления пана.
    ЦентрБлижайший,
    /// Любое действие из `config.lua` — срабатывает один раз, по порогу.
    Порогом(Action),
}

/// Одна строка таблицы жестов.
#[derive(Clone, Debug)]
pub struct БиндЖеста {
    pub mods: ModMask,
    pub триггер: Триггер,
    pub где: Где,
    pub действие: ДействиеЖеста,
}

/// Пороги распознавания. Имена и значения — из `config.reference.toml`
/// driftwm, чтобы настройки переносились между двумя композиторами один в один.
#[derive(Clone, Copy, Debug)]
pub struct Пороги {
    /// Сколько пикселей должны в сумме пройти пальцы, чтобы направленный свайп
    /// сработал.
    pub свайп: f64,
    /// Масштаб, ниже которого срабатывает `pinch-in`.
    pub щипок_внутрь: f64,
    /// Масштаб, выше которого срабатывает `pinch-out`.
    pub щипок_наружу: f64,
}

impl Default for Пороги {
    fn default() -> Self {
        Self { свайп: 12.0, щипок_внутрь: 0.85, щипок_наружу: 1.15 }
    }
}

/// Какой жест идёт прямо сейчас.
///
/// Одно поле на всё: физически на тачпаде идёт ровно один жест — libinput не
/// присылает свайп и щипок одновременно.
#[derive(Debug)]
pub struct Идёт {
    pub триггер_основа: ОсноваЖеста,
    pub пальцы: u32,
    pub на_окне: bool,
    /// Что нашлось в таблице на НЕПРЕРЫВНЫЙ вариант жеста (`swipe`/`pinch`).
    pub непрерывное: Option<Непрерывное>,
    /// Сумма пройденного — для направленных свайпов.
    pub накоплено: (f64, f64),
    /// Последний масштаб щипка.
    pub масштаб: f64,
    /// Пороговое действие уже сработало: второй раз за один жест не стреляем.
    pub порог_отработал: bool,
    /// Жест целиком наш: события не должны уходить ни в старые ветки, ни в
    /// приложение.
    pub наш: bool,
}

/// Свайп это или щипок — направленные варианты выводятся из накопленного.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ОсноваЖеста {
    Свайп,
    ДвойнойТапСвайп,
    Щипок,
    Удержание,
}

impl ОсноваЖеста {
    /// Непрерывный триггер этой основы — тот, что может нести
    /// [`Непрерывное`].
    fn непрерывный(self, пальцы: u32) -> Триггер {
        match self {
            ОсноваЖеста::Свайп => Триггер::Свайп { пальцы },
            ОсноваЖеста::ДвойнойТапСвайп => Триггер::ДвойнойТапСвайп { пальцы },
            ОсноваЖеста::Щипок => Триггер::Щипок { пальцы },
            ОсноваЖеста::Удержание => Триггер::Удержание { пальцы },
        }
    }
}

/// Найти бинд: точный контекст важнее, чем `anywhere`.
///
/// Порядок не косметика. `2-finger-pinch` на холсте зумит вид, а тот же щипок
/// над окном человек может повесить на «вписать окно» — и если бы `anywhere`
/// выигрывал по первому совпадению, второй бинд не сработал бы никогда, а
/// выглядело бы это как «мой жест не работает через раз».
pub fn найти<'а>(
    таблица: &'а [БиндЖеста],
    mods: ModMask,
    триггер: Триггер,
    на_окне: bool,
) -> Option<&'а БиндЖеста> {
    let подходящие = || {
        таблица
            .iter()
            .filter(move |б| б.mods == mods && б.триггер == триггер && б.где.подходит(на_окне))
    };
    подходящие()
        .find(|б| б.где != Где::Везде)
        .or_else(|| подходящие().next())
}

/// Направленный триггер по накопленному смещению — тот, чья ось больше.
///
/// Направление ФИЗИЧЕСКОЕ, как в driftwm: «пальцы вверх» это `swipe-up`,
/// независимо от того, куда при этом уехал вид.
pub fn направление(dx: f64, dy: f64, пальцы: u32) -> Триггер {
    if dx.abs() >= dy.abs() {
        if dx >= 0.0 {
            Триггер::СвайпВправо { пальцы }
        } else {
            Триггер::СвайпВлево { пальцы }
        }
    } else if dy >= 0.0 {
        Триггер::СвайпВниз { пальцы }
    } else {
        Триггер::СвайпВверх { пальцы }
    }
}

/// Есть ли в таблице хоть один бинд, который этот жест ещё может задеть.
///
/// Считается ОДИН раз, на первом кадре. Если нет ни одного — диспетчер сразу
/// отвечает «не моё», и жест целиком уходит в прежние ветки `input.rs`. Это и
/// есть гарантия, что старое поведение не тронуто: пустая таблица не может
/// перехватить ничего.
fn есть_бинды(
    таблица: &[БиндЖеста],
    mods: ModMask,
    основа: ОсноваЖеста,
    пальцы: u32,
    на_окне: bool,
) -> bool {
    let варианты: Vec<Триггер> = match основа {
        ОсноваЖеста::Свайп | ОсноваЖеста::ДвойнойТапСвайп => vec![
            основа.непрерывный(пальцы),
            Триггер::СвайпВверх { пальцы },
            Триггер::СвайпВниз { пальцы },
            Триггер::СвайпВлево { пальцы },
            Триггер::СвайпВправо { пальцы },
        ],
        ОсноваЖеста::Щипок => vec![
            Триггер::Щипок { пальцы },
            Триггер::ЩипокВнутрь { пальцы },
            Триггер::ЩипокНаружу { пальцы },
        ],
        ОсноваЖеста::Удержание => vec![Триггер::Удержание { пальцы }],
    };
    варианты.iter().any(|т| найти(таблица, mods, *т, на_окне).is_some())
}

// ── Диспетчер ────────────────────────────────────────────────────────────────

use crate::Parallax;

impl Parallax {
    /// Модификаторы, как их видит клавиатура хозяина машины.
    fn моды_сейчас(&self) -> ModMask {
        let m = self
            .seat
            .get_keyboard()
            .map(|kb| kb.modifier_state())
            .unwrap_or_default();
        ModMask { ctrl: m.ctrl, alt: m.alt, shift: m.shift, logo: m.logo || self.logo_held }
    }

    /// Под курсором окно?
    fn под_курсором_окно(&self) -> bool {
        self.space.element_under(self.pointer_location).is_some()
    }

    /// Начало жеста. `false` — в таблице ничего нет, пусть работают прежние ветки.
    pub fn жест_начало(&mut self, основа: ОсноваЖеста, пальцы: u32) -> bool {
        let mods = self.моды_сейчас();
        let на_окне = self.под_курсором_окно();
        if !есть_бинды(&self.lua_config.gestures, mods, основа, пальцы, на_окне) {
            self.жест = None;
            return false;
        }
        // Непрерывное ищем сразу: оно поедет с первого же кадра.
        let непрерывное = найти(
            &self.lua_config.gestures, mods, основа.непрерывный(пальцы), на_окне,
        )
        .and_then(|б| match б.действие {
            ДействиеЖеста::Непрерывно(н) => Some(н),
            _ => None,
        });

        if let Some(н) = непрерывное {
            self.жест_подготовить(н);
        }
        tracing::debug!(
            "plx/gestures: gesture {основа:?} {пальцы} finger(s), on_window={на_окне}, continuous={непрерывное:?}",
        );
        self.жест = Some(Идёт {
            триггер_основа: основа,
            пальцы,
            на_окне,
            непрерывное,
            накоплено: (0.0, 0.0),
            масштаб: 1.0,
            порог_отработал: false,
            наш: true,
        });
        true
    }

    /// Взять окно под курсором в оборот — для непрерывных «оконных» действий.
    ///
    /// Пользуемся ТЕМ ЖЕ состоянием, что и прежние ветки `input.rs`
    /// (`gesture_move_window`, `gesture_resize_group`): одно окно не может
    /// одновременно ехать по двум путям, а общее состояние гарантирует, что
    /// конец жеста приберёт за собой в одном месте.
    fn жест_подготовить(&mut self, н: Непрерывное) {
        let точка = self.pointer_location;
        match н {
            Непрерывное::ВестиОкно | Непрерывное::ВестиСоСнапом => {
                self.gesture_move_window = self.space.element_under(точка).map(|(w, _)| w.clone());
            }
            Непрерывное::РазмерОкна | Непрерывное::РазмерСоСнапом => {
                let окно = self.space.element_under(точка).map(|(w, _)| w.clone());
                self.gesture_resize_window = окно.clone();
                if let Some(окно) = окно {
                    // Из тайлинга вытаскиваем во float: иначе `arrange` вернёт
                    // окно на место сразу же, и жест выглядел бы сломанным.
                    if let Some(tw) = self.tagged_windows.iter_mut().find(|tw| tw.window == окно) {
                        tw.floating = true;
                    }
                    let mut группа = vec![окно.clone()];
                    if н == Непрерывное::РазмерСоСнапом {
                        группа.extend(self.group_drag_members_excluding(&окно));
                    }
                    self.gesture_resize_group = группа
                        .into_iter()
                        .map(|w| {
                            let s = crate::xwin::current_size(&w);
                            (w, s)
                        })
                        .collect();
                }
            }
            Непрерывное::ПанВида | Непрерывное::Зум => {}
        }
    }

    /// Кадр свайпа. `dx`/`dy` — дельта пальцев в пикселях.
    pub fn жест_свайп_шаг(&mut self, dx: f64, dy: f64, время: u32) -> bool {
        let Some(идёт) = self.жест.as_mut() else { return false };
        if !идёт.наш {
            return false;
        }
        идёт.накоплено.0 += dx;
        идёт.накоплено.1 += dy;
        let (нак_x, нак_y) = идёт.накоплено;
        let (пальцы, на_окне, непрерывное) = (идёт.пальцы, идёт.на_окне, идёт.непрерывное);
        let порог_отработал = идёт.порог_отработал;

        if let Some(н) = непрерывное {
            self.применить_непрерывное(н, dx, dy, время);
            return true;
        }
        // Направленный свайп: копим, пока не наберётся порог, потом стреляем
        // один раз за жест. Второй раз не стреляем намеренно — иначе долгий
        // свайп повторял бы действие десятки раз за один ход пальцев.
        if порог_отработал {
            return true;
        }
        let порог = self.lua_config.gesture_thresholds.свайп;
        if (нак_x * нак_x + нак_y * нак_y).sqrt() < порог {
            return true;
        }
        let триггер = направление(нак_x, нак_y, пальцы);
        let mods = self.моды_сейчас();
        if let Some(бинд) = найти(&self.lua_config.gestures, mods, триггер, на_окне) {
            let действие = бинд.действие.clone();
            self.выполнить_пороговое(действие, нак_x, нак_y);
        } else if let Some(бинд) = найти(
            &self.lua_config.gestures, mods, Триггер::Свайп { пальцы }, на_окне,
        ) {
            // Голый `N-finger-swipe` с ПОРОГОВЫМ действием: направление ему не
            // нужно, но сработать он обязан — на нём висит `center-nearest`.
            let действие = бинд.действие.clone();
            self.выполнить_пороговое(действие, нак_x, нак_y);
        }
        if let Some(идёт) = self.жест.as_mut() {
            идёт.порог_отработал = true;
        }
        true
    }

    /// Кадр щипка: `scale` — абсолютный масштаб от начала жеста.
    pub fn жест_щипок_шаг(&mut self, scale: f64) -> bool {
        if scale <= 0.0 {
            return self.жест.as_ref().is_some_and(|ж| ж.наш);
        }
        let Some(идёт) = self.жест.as_mut() else { return false };
        if !идёт.наш {
            return false;
        }
        let прежний = идёт.масштаб;
        идёт.масштаб = scale;
        let (пальцы, на_окне, непрерывное) = (идёт.пальцы, идёт.на_окне, идёт.непрерывное);
        let порог_отработал = идёт.порог_отработал;

        if непрерывное == Some(Непрерывное::Зум) {
            let factor = scale / прежний;
            self.зум_щипком(factor);
            return true;
        }
        if let Some(н) = непрерывное {
            // Щипком можно вести и размер окна: дельта берётся из изменения
            // масштаба, как в прежней ветке Super+щипок.
            let factor = scale / прежний;
            self.применить_непрерывное(н, factor, factor, 0);
            return true;
        }
        if порог_отработал {
            return true;
        }
        let пороги = self.lua_config.gesture_thresholds;
        let триггер = if scale <= пороги.щипок_внутрь {
            Триггер::ЩипокВнутрь { пальцы }
        } else if scale >= пороги.щипок_наружу {
            Триггер::ЩипокНаружу { пальцы }
        } else {
            return true;
        };
        let mods = self.моды_сейчас();
        if let Some(бинд) = найти(&self.lua_config.gestures, mods, триггер, на_окне) {
            let действие = бинд.действие.clone();
            self.выполнить_пороговое(действие, 0.0, 0.0);
        }
        if let Some(идёт) = self.жест.as_mut() {
            идёт.порог_отработал = true;
        }
        true
    }

    /// Конец жеста. `отменено` — про удержание: libinput говорит, было ли оно
    /// прервано движением.
    pub fn жест_конец(&mut self, отменено: bool) -> bool {
        let Some(идёт) = self.жест.take() else { return false };
        if !идёт.наш {
            return false;
        }
        // Удержание срабатывает НА ОТПУСКАНИИ — это его определение: пока
        // пальцы лежат, ещё неизвестно, удержание это или начало свайпа.
        if идёт.триггер_основа == ОсноваЖеста::Удержание && !отменено && !идёт.порог_отработал {
            let mods = self.моды_сейчас();
            let триггер = Триггер::Удержание { пальцы: идёт.пальцы };
            if let Some(бинд) = найти(&self.lua_config.gestures, mods, триггер, идёт.на_окне) {
                let действие = бинд.действие.clone();
                self.выполнить_пороговое(действие, 0.0, 0.0);
            }
        }
        match идёт.непрерывное {
            Some(Непрерывное::ПанВида) => self.momentum.launch(),
            Some(Непрерывное::ВестиОкно) | Some(Непрерывное::ВестиСоСнапом) => {
                self.gesture_move_window = None;
            }
            Some(Непрерывное::РазмерОкна) | Some(Непрерывное::РазмерСоСнапом) => {
                let группа = std::mem::take(&mut self.gesture_resize_group);
                self.gesture_resize_window = None;
                // Запоминаем итоговый размер каждому: иначе переход
                // Float→tiling→Float вернул бы доресайзные размеры.
                for (w, _) in группа {
                    let size = crate::xwin::current_size(&w);
                    if let Some(tw) = self.tagged_windows.iter_mut().find(|tw| tw.window == w) {
                        tw.float_size = Some(size);
                    }
                }
            }
            _ => {}
        }
        self.request_redraw();
        true
    }

    fn применить_непрерывное(&mut self, н: Непрерывное, dx: f64, dy: f64, время: u32) {
        match н {
            Непрерывное::ПанВида => {
                let zoom = self.viewport.zoom;
                let (dcam_x, dcam_y) = (dx / zoom, dy / zoom);
                self.pan_camera_by(dcam_x, dcam_y);
                self.momentum.accumulate(
                    smithay::utils::Point::from((-dcam_x, -dcam_y)),
                    время,
                );
                self.request_redraw();
            }
            Непрерывное::Зум => self.зум_щипком(1.0 + dx * 0.002),
            Непрерывное::ВестиОкно | Непрерывное::ВестиСоСнапом => {
                let Some(окно) = self.gesture_move_window.clone() else { return };
                let (сдвиг_x, сдвиг_y) = (dx.round() as i32, dy.round() as i32);
                let mut двигать = vec![окно.clone()];
                if н == Непрерывное::ВестиСоСнапом {
                    двигать.extend(self.group_drag_members_excluding(&окно));
                }
                for w in двигать {
                    let Some(geo) = self.space.element_geometry(&w) else { continue };
                    let новое = smithay::utils::Point::from((
                        geo.loc.x + сдвиг_x,
                        geo.loc.y + сдвиг_y,
                    ));
                    self.space.map_element(w.clone(), новое, true);
                    if let Some(tw) = self.tagged_windows.iter_mut().find(|tw| tw.window == w) {
                        tw.float_position = новое;
                        tw.position = новое;
                        tw.float_position_set = true;
                    }
                }
                self.request_redraw();
            }
            Непрерывное::РазмерОкна | Непрерывное::РазмерСоСнапом => {
                // Свайпом размер ведём по горизонтали: dx — ширина, dy — высота.
                self.жест_размер_шагом(dx, dy);
            }
        }
    }

    /// Зум камеры множителем с якорем под курсором — та же арифметика, что у
    /// щипка в `input.rs`, вынесенная сюда, чтобы жест из таблицы вёл камеру
    /// точно так же, как встроенный.
    fn зум_щипком(&mut self, factor: f64) {
        if !factor.is_finite() || factor <= 0.0 {
            return;
        }
        if !self.touchpad_camera_allowed() || self.zoom_locked() {
            return;
        }
        let cursor = self.pointer_location;
        self.zoom_glide = None;
        let old_zoom = self.viewport.zoom;
        let new_zoom = (old_zoom * factor).clamp(Parallax::ZOOM_MIN, Parallax::ZOOM_MAX);
        self.viewport.zoom = new_zoom;
        let screen_x = (cursor.x - self.viewport.cam_x) * old_zoom;
        let screen_y = (cursor.y - self.viewport.cam_y) * old_zoom;
        self.viewport.cam_x = cursor.x - screen_x / new_zoom;
        self.viewport.cam_y = cursor.y - screen_y / new_zoom;
        self.apply_camera();
        self.request_redraw();
    }

    /// Шаг размера окна свайпом. Пол — 1 px, как и у щипка в `input.rs`:
    /// нулевая поверхность недопустима, а «приличного минимума» у parallax нет
    /// нигде, и заводить его только здесь значило бы вести себя по-разному в
    /// двух путях одного и того же ресайза.
    fn жест_размер_шагом(&mut self, dw: f64, dh: f64) {
        // Усиление. Пиксель пальца = пиксель окна — это ровно то, на что Ярик
        // пожаловался словом «слабо»: накладка тачпада 1216 единиц в ширину, и
        // чтобы вырастить окно с 1200 до 2400, палец пришлось бы протащить
        // через весь тачпад дважды. Тот же множитель и по той же причине стоит
        // у щипка-ресайза в input.rs (`PINCH_GAIN`), так что два пути одного
        // действия остаются соразмерными.
        const УСИЛЕНИЕ: f64 = 3.0;
        let (dw, dh) = (dw * УСИЛЕНИЕ, dh * УСИЛЕНИЕ);
        let группа = self.gesture_resize_group.clone();
        for (окно, _) in группа {
            let текущий = crate::xwin::current_size(&окно);
            let новый = smithay::utils::Size::from((
                (текущий.w as f64 + dw).round().clamp(1.0, 20000.0) as i32,
                (текущий.h as f64 + dh).round().clamp(1.0, 20000.0) as i32,
            ));
            crate::xwin::set_size(&окно, Some(новый), crate::xwin::Tiled::Keep);
            crate::xwin::configure(&окно);
        }
        self.request_redraw();
    }

    fn выполнить_пороговое(&mut self, действие: ДействиеЖеста, нак_x: f64, нак_y: f64) {
        match действие {
            ДействиеЖеста::Порогом(a) => {
                tracing::debug!("plx/gestures: gesture → action {a:?}");
                self.dispatch_action(a);
            }
            ДействиеЖеста::ЦентрБлижайший => {
                // Направление ПАНА, а не пальцев: пальцы влево — вид едет
                // вправо, значит и смотрим мы вправо. Так же считает driftwm.
                let (dx, dy) = (-нак_x, -нак_y);
                let шаг = if dx.abs() >= dy.abs() {
                    (if dx >= 0.0 { 1 } else { -1 }, 0)
                } else {
                    (0, if dy >= 0.0 { 1 } else { -1 })
                };
                self.dispatch_action(crate::config::Action::FocusDirection(шаг.0, шаг.1));
            }
            ДействиеЖеста::Непрерывно(_) => {}
        }
    }

    /// Свести камеру на окно в фокусе. Действие `center_window`.
    pub fn center_window(&mut self) {
        let Some(окно) = self.focused_window() else { return };
        let Some(geo) = self.space.element_geometry(&окно) else { return };
        let экран = self.screen_size();
        let zoom = self.viewport.zoom.max(0.01);
        let центр_x = geo.loc.x as f64 + geo.size.w as f64 / 2.0;
        let центр_y = geo.loc.y as f64 + geo.size.h as f64 / 2.0;
        self.viewport.cam_x = центр_x - экран.w as f64 / (2.0 * zoom);
        self.viewport.cam_y = центр_y - экран.h as f64 / (2.0 * zoom);
        self.apply_camera();
        self.request_redraw();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn бинд(где: Где, триггер: Триггер) -> БиндЖеста {
        БиндЖеста {
            mods: ModMask::default(),
            триггер,
            где,
            действие: ДействиеЖеста::Непрерывно(Непрерывное::Зум),
        }
    }

    #[test]
    fn точный_контекст_сильнее_чем_везде() {
        let т = Триггер::Щипок { пальцы: 2 };
        let таблица = vec![бинд(Где::Везде, т), бинд(Где::НаОкне, т)];
        // Над окном обязан выиграть НаОкне, хотя Везде стоит в списке первым.
        let найденный = найти(&таблица, ModMask::default(), т, true).expect("бинд не найден");
        assert_eq!(найденный.где, Где::НаОкне);
        // На холсте точного нет — остаётся Везде.
        let найденный = найти(&таблица, ModMask::default(), т, false).expect("бинд не найден");
        assert_eq!(найденный.где, Где::Везде);
    }

    #[test]
    fn контекст_окна_не_срабатывает_на_холсте() {
        let т = Триггер::Свайп { пальцы: 3 };
        let таблица = vec![бинд(Где::НаОкне, т)];
        assert!(найти(&таблица, ModMask::default(), т, false).is_none());
        assert!(найти(&таблица, ModMask::default(), т, true).is_some());
    }

    #[test]
    fn модификаторы_различают_бинды() {
        let т = Триггер::Свайп { пальцы: 3 };
        let mut с_альтом = бинд(Где::Везде, т);
        с_альтом.mods = ModMask { alt: true, ..ModMask::default() };
        let таблица = vec![с_альтом];
        assert!(найти(&таблица, ModMask::default(), т, true).is_none());
        assert!(найти(&таблица, ModMask { alt: true, ..ModMask::default() }, т, true).is_some());
    }

    #[test]
    fn направление_берёт_большую_ось_и_знак() {
        assert_eq!(направление(30.0, 5.0, 4), Триггер::СвайпВправо { пальцы: 4 });
        assert_eq!(направление(-30.0, 5.0, 4), Триггер::СвайпВлево { пальцы: 4 });
        assert_eq!(направление(5.0, 30.0, 4), Триггер::СвайпВниз { пальцы: 4 });
        assert_eq!(направление(5.0, -30.0, 4), Триггер::СвайпВверх { пальцы: 4 });
        // Ровно по диагонали — горизонталь: лишь бы не «ни туда ни сюда».
        assert_eq!(направление(10.0, 10.0, 3), Триггер::СвайпВправо { пальцы: 3 });
    }

    #[test]
    fn имена_триггеров_разбираются() {
        assert_eq!(Триггер::разобрать("swipe", 3), Some(Триггер::Свайп { пальцы: 3 }));
        assert_eq!(Триггер::разобрать("swipe-up", 4), Some(Триггер::СвайпВверх { пальцы: 4 }));
        assert_eq!(Триггер::разобрать("pinch-in", 2), Some(Триггер::ЩипокВнутрь { пальцы: 2 }));
        assert_eq!(
            Триггер::разобрать("doubletap-swipe", 3),
            Some(Триггер::ДвойнойТапСвайп { пальцы: 3 }),
        );
        assert_eq!(Триггер::разобрать("hold", 4), Some(Триггер::Удержание { пальцы: 4 }));
        assert_eq!(Триггер::разобрать("невнятное", 3), None);
    }
}
