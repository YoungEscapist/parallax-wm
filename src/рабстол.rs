//! Иконки на рабочем столе: ярлыки прямо на обоях.
//!
//! Иконка — это НЕ окно и не клиент: у неё нет ни поверхности, ни процесса, она
//! живёт списком в `Рабстол` и рисуется кадром компоновщика между обоями и
//! окнами. Поэтому она ничего не стоит, когда её не трогают, и не мешает
//! раскладке: тайлинг о ней не знает вовсе.
//!
//! **Координаты — холста, а не экрана.** Иконка лежит на бесконечном холсте
//! parallax, как окно: уезжает с паном, мельчает на отдалении камеры. Это и
//! есть причина не делать «иконки как в Windows» (приклеенные к экрану сеткой):
//! на холсте, который больше экрана, приклеенная к экрану сетка означала бы, что
//! иконки едут вместе со взглядом и всё время лезут поверх окон.
//!
//! **У КАЖДОГО СТОЛА СВОИ ИКОНКИ** (просьба Ярика 17.09.2026). Одного лишь
//! места на холсте для этого мало: столы parallax — это ТЕГИ, а камера стола
//! восстанавливается из `tag_cameras` и запросто стоит там же, где камера
//! соседнего. Поэтому у иконки есть своя маска столов (`столы`, поле `tags` в
//! файле): показываем и ловим клики только на тех столах, чей бит в ней есть.
//! Ноль — «на всех столах», прежнее поведение; старый файл без поля читается
//! как стол 1. См. `виден_на`.
//!
//! **Что умеет.** Одиночный клик — запуск. Перетаскивание — перенести (порог в
//! пикселях экрана отличает перенос от клика). ПКМ по иконке — окошко свойств
//! (имя, картинка, команда, размер; там же удаление). ПКМ по пустому месту —
//! «новая иконка здесь». Всё сохраняется в `~/.local/state/parallax/icons.json`
//! сразу же, чтобы пережить перезапуск (Super+R) без отдельной команды.
//!
//! **Картинка** ищется так же, как значок приложения в панели: сперва как путь
//! к файлу (png/svg), потом как имя значка в теме, потом как app_id через
//! .desktop (см. icons.rs). Поэтому `картинка = "firefox"` работает без пути.

use std::collections::HashMap;
use std::path::PathBuf;

use serde::{Deserialize, Serialize};
use smithay::backend::renderer::element::memory::MemoryRenderBuffer;
use smithay::utils::{Logical, Point, Rectangle, Size};

use crate::state::Parallax;

/// Сколько места отведено подписи при иконке размером 64 (логические пиксели
/// холста). У других размеров считается пропорцией.
const ПОДПИСЬ_H: i32 = 18;

/// Пределы размера иконки. Нижний — чтобы иконка оставалась целью для мыши,
/// верхний — чтобы случайная опечатка не растянула её на пол-холста.
pub const МИН_РАЗМЕР: i32 = 24;
pub const МАКС_РАЗМЕР: i32 = 256;

/// Сколько пикселей ЭКРАНА должна пройти рука, чтобы нажатие стало переносом, а
/// не запуском. Меньше — и дрожь руки запускала бы приложение при попытке
/// сдвинуть иконку; больше — и короткий перенос выглядел бы как «иконка не
/// двигается, зато запустилась».
const ПОРОГ_ПЕРЕНОСА: f64 = 6.0;

/// Одна иконка рабочего стола.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Иконка {
    /// Подпись под картинкой.
    pub имя: String,
    /// Путь к файлу, имя значка в теме или app_id. Пусто — берём `имя`.
    #[serde(default)]
    pub картинка: String,
    /// Что запускать. Пусто — запускаем `имя` как команду.
    #[serde(default)]
    pub команда: String,
    /// Место на ХОЛСТЕ (левый верхний угол картинки).
    pub x: i32,
    pub y: i32,
    /// Сторона картинки в логических пикселях холста.
    #[serde(default = "размер_по_умолчанию")]
    pub размер: i32,
    /// На каких столах видна: маска тегов, 0 — на всех (см. `виден_на`).
    #[serde(rename = "tags", default = "стол_по_умолчанию")]
    pub столы: u32,
}

fn размер_по_умолчанию() -> i32 {
    64
}

/// Чему равна маска столов у иконки из СТАРОГО файла, где поля не было вовсе.
///
/// Первый стол, а не «все»: до появления столов у иконок человек расставлял их,
/// глядя на первый стол, — туда они и относятся. «Все столы» остаётся тем, что
/// выбирают руками (0 в поле «Столы»).
pub fn стол_по_умолчанию() -> u32 {
    1
}

/// Видна ли вещь с такой маской на столах `текущие`.
pub fn виден_на(столы: u32, текущие: u32) -> bool {
    столы == 0 || столы & текущие != 0
}

/// Номер стола из маски: 1…32, 0 — «все столы». Маска с несколькими битами
/// показывается по младшему — руками такую не задать, она приходит из ctl.
pub fn номер_стола(маска: u32) -> u32 {
    if маска == 0 { 0 } else { маска.trailing_zeros() + 1 }
}

/// Маска по номеру стола (0 — все столы).
pub fn маска_стола(номер: u32) -> u32 {
    if номер == 0 || номер > 32 { 0 } else { 1u32 << (номер - 1) }
}

/// Как показать маску в свойствах и в `ctl`.
pub fn столы_текстом(маска: u32) -> String {
    match номер_стола(маска) {
        0 => crate::т!("все", "all").to_string(),
        n => n.to_string(),
    }
}

impl Иконка {
    /// Что показывать как картинку, если поле пустое.
    pub fn ключ_картинки(&self) -> &str {
        if self.картинка.is_empty() { &self.имя } else { &self.картинка }
    }

    /// Что запускать, если команда не задана.
    pub fn что_запускать(&self) -> &str {
        if self.команда.is_empty() { &self.имя } else { &self.команда }
    }

    /// Высота подписи под картинкой в координатах холста.
    pub fn подпись_h(&self) -> i32 {
        (ПОДПИСЬ_H * self.размер / 64).max(10)
    }

    /// Прямоугольник иконки на ХОЛСТЕ — картинка плюс место под подпись.
    /// По нему же идёт хит-тест: щёлкать по подписи так же естественно, как по
    /// картинке.
    pub fn рамка(&self) -> Rectangle<i32, Logical> {
        Rectangle::new(
            Point::from((self.x, self.y)),
            Size::from((self.размер, self.размер + self.подпись_h())),
        )
    }
}

/// Незаконченное нажатие на иконку: пока не ясно, клик это или перенос.
pub struct Жест {
    pub индекс: usize,
    /// Держат не иконку, а встроенный виджет (см. виджеты_стола.rs): у него
    /// клик ничего не запускает, а перенос пишется в свой файл.
    pub виджет: bool,
    /// Где на холсте нажали и где иконка стояла в этот миг.
    pub старт: Point<f64, Logical>,
    pub откуда: (i32, i32),
    /// Рука уже прошла порог — это перенос, а не клик.
    pub переносим: bool,
}

/// Какое поле свойств правится.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Поле {
    Имя,
    Картинка,
    Команда,
    Размер,
    Столы,
}

impl Поле {
    pub const ВСЕ: [Поле; 5] =
        [Поле::Имя, Поле::Картинка, Поле::Команда, Поле::Размер, Поле::Столы];

    pub fn номер(self) -> usize {
        Поле::ВСЕ.iter().position(|p| *p == self).unwrap_or(0)
    }
}

/// Окошко свойств иконки.
pub struct Редактор {
    /// Какую иконку правим. `None` — новая, ещё не добавленная.
    pub индекс: Option<usize>,
    /// Черновик: правки идут сюда и попадают в список только по Enter, чтобы
    /// Escape означал «ничего не менялось» — в том числе для новой иконки.
    pub черновик: Иконка,
    pub поле: Поле,
    /// Прямоугольники строк на экране — по ним ловятся клики.
    pub строки: Vec<crate::bar::Rect>,
}

/// Меню по ПКМ на пустом месте рабочего стола.
///
/// Два шага: сперва «что ставим» (иконка или виджет), для виджета — какой
/// именно. Одним длинным списком «иконка, часы, календарь, …» было бы короче на
/// клик, но иконка там терялась бы среди виджетов, а список рос бы с каждым
/// новым родом.
pub struct Меню {
    /// Куда ставить — точка ХОЛСТА, где щёлкнули.
    pub место: Point<i32, Logical>,
    pub уровень: Уровень,
    /// Выбранная строка (стрелки вверх/вниз, Enter).
    pub выбор: usize,
    pub строки: Vec<crate::bar::Rect>,
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Уровень {
    /// «Иконка» / «Виджет».
    Корень,
    /// Роды виджетов (`виджеты_стола::Род::ВСЕ`).
    Виджеты,
}

impl Уровень {
    pub fn строк(self) -> usize {
        match self {
            Уровень::Корень => 2,
            Уровень::Виджеты => crate::виджеты_стола::Род::ВСЕ.len(),
        }
    }
}

/// Растеризованная картинка и её размеры. `None` — искали и не нашли: такой
/// ответ кэшируется тоже, иначе ненайденное искалось бы заново каждый кадр.
type Растр = Option<(MemoryRenderBuffer, (i32, i32))>;

#[derive(Default)]
pub struct Рабстол {
    pub иконки: Vec<Иконка>,
    pub жест: Option<Жест>,
    pub редактор: Option<Редактор>,
    pub меню: Option<Меню>,
    /// Картинки, растеризованные под нужный размер: ключ — «что рисуем» и
    /// сторона в ФИЗИЧЕСКИХ пикселях, округлённая до ступени (см.
    /// `ступень_растра`), иначе каждый щелчок зума растрировал бы всё заново.
    pub буферы: HashMap<(String, i32), Растр>,
    /// Встроенные виджеты: список, их окошко свойств и замер системы.
    pub виджеты: crate::виджеты_стола::Состояние,
}

fn путь_файла() -> Option<PathBuf> {
    let home = std::env::var("HOME").ok()?;
    Some(PathBuf::from(home).join(".local/state/parallax/icons.json"))
}

/// Ступени растра в физических пикселях. Между ступенями картинку растягивает
/// рендер — разницы на глаз нет, а растеризаций при панораме получаются
/// единицы вместо сотни.
fn ступень_растра(px: i32) -> i32 {
    const СТУПЕНИ: [i32; 9] = [32, 48, 64, 96, 128, 192, 256, 384, 512];
    *СТУПЕНИ.iter().find(|s| **s >= px).unwrap_or(СТУПЕНИ.last().unwrap())
}

impl Parallax {
    /// Прочитать иконки с диска. Зовётся один раз при старте.
    pub fn рабстол_загрузить(&mut self) {
        let Some(path) = путь_файла() else { return };
        let Ok(данные) = std::fs::read_to_string(&path) else { return };
        match serde_json::from_str::<Vec<Иконка>>(&данные) {
            Ok(список) => {
                self.рабстол.иконки = список
                    .into_iter()
                    .map(|mut и| {
                        и.размер = и.размер.clamp(МИН_РАЗМЕР, МАКС_РАЗМЕР);
                        и
                    })
                    .collect();
                tracing::info!(
                    "plx/desktop: {} icons loaded from {:?}",
                    self.рабстол.иконки.len(), path,
                );
            }
            Err(e) => tracing::warn!("plx/desktop: parsing {:?}: {}", path, e),
        }
    }

    /// Записать иконки на диск. Зовётся после КАЖДОЙ правки: список крошечный,
    /// а «перетащил иконку, перезапустил композитор, она вернулась на старое
    /// место» — жалоба, которой не должно возникать вовсе.
    pub fn рабстол_сохранить(&self) {
        let Some(path) = путь_файла() else { return };
        if let Some(родитель) = path.parent() {
            let _ = std::fs::create_dir_all(родитель);
        }
        match serde_json::to_string_pretty(&self.рабстол.иконки) {
            Ok(json) => match std::fs::write(&path, json) {
                Ok(()) => tracing::info!("plx/desktop: saved {:?}", path),
                Err(e) => tracing::warn!("plx/desktop: could not write {:?}: {}", path, e),
            },
            Err(e) => tracing::warn!("plx/desktop: serialisation: {}", e),
        }
    }

    /// Иконка под точкой холста — сверху вниз по списку (последняя добавленная
    /// лежит выше).
    pub fn рабстол_иконка_в_точке(&self, точка: Point<f64, Logical>) -> Option<usize> {
        let столы = self.viewport.current_tags();
        self.рабстол.иконки.iter().enumerate().rev().find_map(|(i, и)| {
            // Чужой стол — не цель: иконка соседнего стола не нарисована, и
            // ловить ею клики значило бы «щёлкнул по пустому месту, а
            // запустилось приложение с другого стола».
            if !виден_на(и.столы, столы) {
                return None;
            }
            let р = и.рамка();
            let внутри = точка.x >= р.loc.x as f64
                && точка.x < (р.loc.x + р.size.w) as f64
                && точка.y >= р.loc.y as f64
                && точка.y < (р.loc.y + р.size.h) as f64;
            внутри.then_some(i)
        })
    }

    /// Открыт ли орган рабочего стола (свойства или меню). По этому признаку
    /// ввод уходит ему, а не окну под курсором.
    pub fn рабстол_меню_открыто(&self) -> bool {
        self.рабстол.редактор.is_some()
            || self.рабстол.меню.is_some()
            || self.рабстол.виджеты.редактор.is_some()
    }

    /// Выполнить строку меню «что ставим».
    fn рабстол_меню_выбрать(&mut self, строка: usize) {
        let Some(меню) = self.рабстол.меню.as_mut() else { return };
        let место = меню.место;
        match (меню.уровень, строка) {
            (Уровень::Корень, 0) => {
                self.рабстол.меню = None;
                self.рабстол_новая(место);
            }
            (Уровень::Корень, _) => {
                меню.уровень = Уровень::Виджеты;
                меню.выбор = 0;
                self.text_cache.clear();
                self.request_redraw();
            }
            (Уровень::Виджеты, i) => {
                self.рабстол.меню = None;
                if let Some(род) = crate::виджеты_стола::Род::ВСЕ.get(i) {
                    self.виджет_поставить(*род, место);
                }
            }
        }
    }

    /// Идёт ли жест с иконкой (нажали и ещё не отпустили).
    pub fn рабстол_жест_идёт(&self) -> bool {
        self.рабстол.жест.is_some()
    }

    /// Клик по ЭКРАННЫМ органам рабочего стола: окошко свойств и меню «новая
    /// иконка». `true` — клик съеден.
    ///
    /// Приклеены к экрану, как и все меню parallax, поэтому и хит-тест здесь
    /// в экранных пикселях — как в `bt_click`/`search_click`.
    pub fn рабстол_клик_экранный(
        &mut self,
        точка: Point<f64, smithay::utils::Physical>,
    ) -> bool {
        if let Some(меню) = self.рабстол.меню.as_ref() {
            let попал = меню.строки.iter().position(|r| r.hit(точка.x, точка.y));
            match попал {
                Some(i) => self.рабстол_меню_выбрать(i),
                // Мимо строк — закрываем, как все меню parallax.
                None => {
                    self.рабстол.меню = None;
                    self.text_cache.clear();
                    self.request_redraw();
                }
            }
            return true;
        }

        if let Some(ред) = self.рабстол.виджеты.редактор.as_ref() {
            let попал = ред.строки.iter().position(|r| r.hit(точка.x, точка.y));
            self.виджет_редактор_клик(попал);
            return true;
        }

        if let Some(ред) = self.рабстол.редактор.as_ref() {
            let попал = ред.строки.iter().position(|r| r.hit(точка.x, точка.y));
            match попал {
                Some(i) if i < Поле::ВСЕ.len() => {
                    if let Some(ред) = self.рабстол.редактор.as_mut() {
                        ред.поле = Поле::ВСЕ[i];
                    }
                    self.text_cache.clear();
                    self.request_redraw();
                }
                // Клик мимо строк сохраняет и закрывает — то же, что Enter.
                // «Щёлкнул мимо, и правки пропали» было бы худшим поведением
                // для окошка, в котором только что набрали команду.
                _ => self.рабстол_редактор_применить(),
            }
            return true;
        }
        false
    }

    /// Нажатие/отпускание кнопки на ХОЛСТЕ — там, где под курсором нет окна.
    /// `true` — событие съедено рабочим столом.
    pub fn рабстол_кнопка(
        &mut self,
        точка: Point<f64, Logical>,
        правая: bool,
        нажата: bool,
    ) -> bool {
        // Отпускание завершает начатый жест ГДЕ УГОДНО: рука, ведущая иконку,
        // вполне могла увести её под окно, и требовать отпустить над пустым
        // местом значило бы терять иконку в захвате.
        if !нажата {
            let Some(жест) = self.рабстол.жест.take() else { return false };
            if жест.виджет {
                // У виджета клик ничего не значит — только перенос.
                if жест.переносим {
                    self.виджеты_сохранить();
                }
            } else if жест.переносим {
                self.рабстол_сохранить();
                if let Some(и) = self.рабстол.иконки.get(жест.индекс) {
                    let (имя, x, y) = (и.имя.clone(), и.x, и.y);
                    self.уведомить(&crate::тф!(
                        "«{}» здесь: {},{}", "‘{}’ moved to {},{}", имя, x, y
                    ));
                }
            } else if !правая {
                self.рабстол_запустить(жест.индекс);
            }
            self.request_redraw();
            return true;
        }

        let попал = self.рабстол_иконка_в_точке(точка);
        // Виджеты лежат под иконками — и ловятся после них. В обзоре столов их
        // не рисуют (как и иконки), значит и хватать там нечего.
        let виджет = if попал.is_none() && !self.overview_active {
            self.виджет_в_точке(точка)
        } else {
            None
        };
        if let Some(i) = виджет {
            if правая {
                self.виджет_свойства(i);
            } else {
                let в = &self.рабстол.виджеты.список[i];
                self.рабстол.жест = Some(Жест {
                    индекс: i,
                    виджет: true,
                    старт: точка,
                    откуда: (в.x, в.y),
                    переносим: false,
                });
            }
            self.request_redraw();
            return true;
        }
        match (попал, правая) {
            // ПКМ по иконке — её свойства.
            (Some(i), true) => {
                self.рабстол_свойства(i);
                true
            }
            // ЛКМ по иконке — запуск или перенос, решится на отпускании.
            (Some(i), false) => {
                let и = &self.рабстол.иконки[i];
                self.рабстол.жест = Some(Жест {
                    индекс: i,
                    виджет: false,
                    старт: точка,
                    откуда: (и.x, и.y),
                    переносим: false,
                });
                self.request_redraw();
                true
            }
            // ПКМ по пустому месту — меню «что поставить здесь».
            (None, true) => {
                self.рабстол.меню = Some(Меню {
                    место: (точка.x.round() as i32, точка.y.round() as i32).into(),
                    уровень: Уровень::Корень,
                    выбор: 0,
                    строки: Vec::new(),
                });
                self.text_cache.clear();
                self.request_redraw();
                true
            }
            // ЛКМ по пустому месту рабочего стола — не наше дело: там живут
            // рамка выделения и снятие фокуса.
            (None, false) => false,
        }
    }

    /// Движение мыши при начатом жесте: за порогом — ведём иконку.
    pub fn рабстол_движение(&mut self, точка: Point<f64, Logical>) {
        let zoom = self.viewport.zoom.max(0.05);
        let Some(жест) = self.рабстол.жест.as_mut() else { return };
        let (dx, dy) = (точка.x - жест.старт.x, точка.y - жест.старт.y);
        // Порог меряем в пикселях ЭКРАНА: на отдалённой камере тот же ход руки
        // проходит куда больше холста, и порог в координатах холста означал бы
        // «на зуме 0.3 иконка не хватается, на 3.0 не запускается».
        if !жест.переносим && (dx * dx + dy * dy).sqrt() * zoom < ПОРОГ_ПЕРЕНОСА {
            return;
        }
        жест.переносим = true;
        let индекс = жест.индекс;
        let (x, y) = (
            жест.откуда.0 + dx.round() as i32,
            жест.откуда.1 + dy.round() as i32,
        );
        if жест.виджет {
            if let Some(в) = self.рабстол.виджеты.список.get_mut(индекс) {
                в.x = x;
                в.y = y;
            }
        } else if let Some(и) = self.рабстол.иконки.get_mut(индекс) {
            и.x = x;
            и.y = y;
        }
        self.request_redraw();
    }

    /// Запустить иконку.
    fn рабстол_запустить(&mut self, индекс: usize) {
        let Some(и) = self.рабстол.иконки.get(индекс) else { return };
        let команда = и.что_запускать().trim().to_string();
        let имя = и.имя.clone();
        if команда.is_empty() {
            self.уведомить(&crate::тф!(
                "у «{}» нет команды", "‘{}’ has no command", имя
            ));
            return;
        }
        tracing::info!("plx/desktop: launching {:?} ({})", имя, команда);
        self.spawn(&команда);
    }

    /// Открыть свойства существующей иконки.
    pub fn рабстол_свойства(&mut self, индекс: usize) {
        let Some(и) = self.рабстол.иконки.get(индекс).cloned() else { return };
        self.рабстол.меню = None;
        self.рабстол.виджеты.редактор = None;
        self.рабстол.редактор = Some(Редактор {
            индекс: Some(индекс),
            черновик: и,
            поле: Поле::Имя,
            строки: Vec::new(),
        });
        self.text_cache.clear();
        self.request_redraw();
    }

    /// Свойства НОВОЙ иконки в заданной точке холста.
    pub fn рабстол_новая(&mut self, место: Point<i32, Logical>) {
        self.рабстол.редактор = Some(Редактор {
            индекс: None,
            черновик: Иконка {
                имя: String::new(),
                картинка: String::new(),
                команда: String::new(),
                x: место.x,
                y: место.y,
                размер: 64,
                // Новая иконка принадлежит тому столу, на котором её ставят.
                столы: self.viewport.current_tags(),
            },
            поле: Поле::Имя,
            строки: Vec::new(),
        });
        self.text_cache.clear();
        self.request_redraw();
    }

    /// Enter в свойствах: записать черновик в список и сохранить.
    fn рабстол_редактор_применить(&mut self) {
        let Some(ред) = self.рабстол.редактор.take() else { return };
        let иконка = ред.черновик;
        if иконка.имя.trim().is_empty() && иконка.команда.trim().is_empty() {
            // Пустую иконку не заводим: она была бы невидимой целью на холсте,
            // которую и удалить-то не за что схватить.
            self.text_cache.clear();
            self.request_redraw();
            return;
        }
        let (имя, x, y) = (иконка.имя.clone(), иконка.x, иконка.y);
        match ред.индекс {
            Some(i) if i < self.рабстол.иконки.len() => self.рабстол.иконки[i] = иконка,
            _ => self.рабстол.иконки.push(иконка),
        }
        self.рабстол_сохранить();
        self.уведомить(&crate::тф!(
            "«{}» сохранена: {},{}", "‘{}’ saved at {},{}", имя, x, y
        ));
        self.text_cache.clear();
        self.request_redraw();
    }

    /// Удалить иконку, которую правим.
    fn рабстол_редактор_удалить(&mut self) {
        let Some(ред) = self.рабстол.редактор.take() else { return };
        if let Some(i) = ред.индекс {
            if i < self.рабстол.иконки.len() {
                let имя = self.рабстол.иконки.remove(i).имя;
                self.рабстол_сохранить();
                self.уведомить(&crate::тф!("«{}» удалена", "‘{}’ removed", имя));
            }
        }
        self.text_cache.clear();
        self.request_redraw();
    }

    /// Клавиша при открытых свойствах или меню. `true` — клавиша съедена.
    ///
    /// Устроено как поиск окон (Super+F, см. switcher::search_key): буквы идут
    /// в выбранное поле, Tab и стрелки вверх/вниз переключают поля, Enter
    /// сохраняет, Escape отменяет, Delete удаляет. Размер правится стрелками
    /// влево/вправо и цифрами: слайдер мышью тянуть неудобнее, а цифра видна.
    pub fn рабстол_клавиша(&mut self, keysym: u32, ch: Option<char>) -> bool {
        use smithay::input::keyboard::keysyms;
        if let Some(меню) = self.рабстол.меню.as_mut() {
            let n = меню.уровень.строк();
            match keysym {
                // Escape из списка виджетов — на шаг назад, из корня — закрыть.
                keysyms::KEY_Escape | keysyms::KEY_BackSpace | keysyms::KEY_Left
                    if меню.уровень == Уровень::Виджеты =>
                {
                    меню.уровень = Уровень::Корень;
                    меню.выбор = 1;
                }
                keysyms::KEY_Escape => self.рабстол.меню = None,
                keysyms::KEY_Down | keysyms::KEY_Tab => меню.выбор = (меню.выбор + 1) % n,
                keysyms::KEY_Up | keysyms::KEY_ISO_Left_Tab => меню.выбор = (меню.выбор + n - 1) % n,
                keysyms::KEY_Return | keysyms::KEY_KP_Enter | keysyms::KEY_Right => {
                    let выбор = меню.выбор;
                    self.рабстол_меню_выбрать(выбор);
                    return true;
                }
                _ => {
                    // Цифра — строка по номеру, как в остальных меню.
                    if let Some(d) = ch.and_then(|c| c.to_digit(10)) {
                        if d >= 1 && (d as usize) <= n {
                            self.рабстол_меню_выбрать(d as usize - 1);
                            return true;
                        }
                    }
                }
            }
            self.text_cache.clear();
            self.request_redraw();
            return true;
        }
        if self.рабстол.виджеты.редактор.is_some() {
            return self.виджет_клавиша(keysym, ch);
        }
        if self.рабстол.редактор.is_none() {
            return false;
        }
        match keysym {
            keysyms::KEY_Escape => {
                self.рабстол.редактор = None;
                self.text_cache.clear();
                self.request_redraw();
            }
            keysyms::KEY_Return | keysyms::KEY_KP_Enter => self.рабстол_редактор_применить(),
            keysyms::KEY_Delete => self.рабстол_редактор_удалить(),
            keysyms::KEY_Down | keysyms::KEY_Tab => self.рабстол_поле(1),
            keysyms::KEY_Up | keysyms::KEY_ISO_Left_Tab => self.рабстол_поле(-1),
            keysyms::KEY_Left | keysyms::KEY_Right => {
                let вперёд = keysym == keysyms::KEY_Right;
                if let Some(ред) = self.рабстол.редактор.as_mut() {
                    match ред.поле {
                        // «Столы» стрелками идут по кругу 0 (все), 1…9: маску
                        // с несколькими битами руками не наберёшь, да и незачем.
                        Поле::Столы => {
                            let n = номер_стола(ред.черновик.столы) as i32;
                            let шаг = if вперёд { 1 } else { -1 };
                            ред.черновик.столы =
                                маска_стола((n + шаг).rem_euclid(10) as u32);
                        }
                        _ => {
                            let шаг = if вперёд { 8 } else { -8 };
                            ред.черновик.размер =
                                (ред.черновик.размер + шаг).clamp(МИН_РАЗМЕР, МАКС_РАЗМЕР);
                        }
                    }
                }
                self.text_cache.clear();
                self.request_redraw();
            }
            keysyms::KEY_BackSpace => {
                if let Some(ред) = self.рабстол.редактор.as_mut() {
                    match ред.поле {
                        Поле::Имя => { ред.черновик.имя.pop(); }
                        Поле::Картинка => { ред.черновик.картинка.pop(); }
                        Поле::Команда => { ред.черновик.команда.pop(); }
                        Поле::Размер => {
                            // У числа «стереть символ» — это отрезать младшую
                            // цифру: набирают его тоже цифрами.
                            ред.черновик.размер =
                                (ред.черновик.размер / 10).clamp(МИН_РАЗМЕР, МАКС_РАЗМЕР);
                        }
                        // У столов стирать нечего: это один номер. Backspace
                        // означает «на всех столах».
                        Поле::Столы => ред.черновик.столы = 0,
                    }
                }
                self.text_cache.clear();
                self.request_redraw();
            }
            _ => {
                let Some(c) = ch.filter(|c| !c.is_control()) else { return true };
                if let Some(ред) = self.рабстол.редактор.as_mut() {
                    match ред.поле {
                        Поле::Имя if ред.черновик.имя.chars().count() < 32 => {
                            ред.черновик.имя.push(c)
                        }
                        Поле::Картинка if ред.черновик.картинка.chars().count() < 200 => {
                            ред.черновик.картинка.push(c)
                        }
                        Поле::Команда if ред.черновик.команда.chars().count() < 200 => {
                            ред.черновик.команда.push(c)
                        }
                        // В размере набираются цифры, остальное молчит.
                        Поле::Размер => {
                            if let Some(d) = c.to_digit(10) {
                                let новый = ред.черновик.размер.saturating_mul(10) + d as i32;
                                ред.черновик.размер = новый.clamp(МИН_РАЗМЕР, МАКС_РАЗМЕР);
                            }
                        }
                        // Цифра — номер стола сразу (не приписывается справа,
                        // как в размере): столов девять, и «1» после «2»
                        // человек имеет в виду как стол 1, а не как стол 21.
                        Поле::Столы => {
                            if let Some(d) = c.to_digit(10) {
                                ред.черновик.столы = маска_стола(d);
                            }
                        }
                        _ => {}
                    }
                }
                self.text_cache.clear();
                self.request_redraw();
            }
        }
        true
    }

    fn рабстол_поле(&mut self, шаг: i32) {
        if let Some(ред) = self.рабстол.редактор.as_mut() {
            let n = Поле::ВСЕ.len() as i32;
            let i = (ред.поле.номер() as i32 + шаг).rem_euclid(n) as usize;
            ред.поле = Поле::ВСЕ[i];
        }
        self.text_cache.clear();
        self.request_redraw();
    }

    /// Растеризованная картинка иконки под нужный размер. `None` — картинку не
    /// нашли (кадр нарисует заглушку-букву).
    ///
    /// `цель_px` — сторона в ФИЗИЧЕСКИХ пикселях; округляется до ступени.
    pub fn рабстол_картинка(
        &mut self,
        ключ: &str,
        цель_px: i32,
    ) -> Option<&(MemoryRenderBuffer, (i32, i32))> {
        let px = ступень_растра(цель_px.clamp(16, 512));
        let k = (ключ.to_string(), px);
        if !self.рабстол.буферы.contains_key(&k) {
            let найденная = найти_картинку(&mut self.icon_cache, ключ, px as u32).map(|и| {
                let буфер = MemoryRenderBuffer::from_slice(
                    &и.rgba,
                    smithay::backend::allocator::Fourcc::Abgr8888,
                    (и.w, и.h),
                    1,
                    smithay::utils::Transform::Normal,
                    None,
                );
                (буфер, (и.w, и.h))
            });
            tracing::debug!(
                "plx/desktop: image {:?} at {}px — {}",
                ключ, px, if найденная.is_some() { "found" } else { "missing" },
            );
            self.рабстол.буферы.insert(k.clone(), найденная);
        }
        self.рабстол.буферы.get(&k).and_then(|v| v.as_ref())
    }

    /// `plx ctl icon add` — иконка из терминала и скриптов.
    pub fn рабстол_добавить(&mut self, иконка: Иконка) {
        self.рабстол.иконки.push(иконка);
        self.рабстол_сохранить();
        self.request_redraw();
    }
}

/// Картинка по ключу: сперва как ПУТЬ к файлу, потом как имя значка в теме,
/// потом как app_id через .desktop.
///
/// Порядок именно такой: путь ни с чем не спутать (он начинается со `/`, `~`
/// или `./`), а имя значка и app_id различить нельзя вовсе — значит, пробуем
/// оба, и дешёвый (тема) первым.
fn найти_картинку(
    кэш: &mut crate::icons::Кэш,
    ключ: &str,
    px: u32,
) -> Option<crate::sni::Icon> {
    let ключ = ключ.trim();
    if ключ.is_empty() {
        return None;
    }
    if ключ.starts_with('/') || ключ.starts_with('~') || ключ.starts_with("./") {
        let путь = if let Some(хвост) = ключ.strip_prefix('~') {
            PathBuf::from(std::env::var("HOME").unwrap_or_default())
                .join(хвост.trim_start_matches('/'))
        } else {
            PathBuf::from(ключ)
        };
        return crate::icons::прочитать_файл(&путь, px);
    }
    if let Some(и) = кэш.значок(ключ, px) {
        return Some(и.clone());
    }
    кэш.значок_приложения(ключ, px).cloned()
}
