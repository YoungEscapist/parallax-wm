#!/usr/bin/env python3
"""Эмулятор мода plx-mine: говорит по протоколу parallax (src/mine/proto.rs) вместо
Minecraft.

Нужен, чтобы проверять сторону композитора БЕЗ игры — так же, как симулятор
Monado заменяет шлем для vr/. Запуск Minecraft ради каждой правки в mine/ стоит
минуты и живого сеанса; здесь всё то же самое проверяется на харнессе за пять
секунд.

    ./harness.sh
    ./ctl.py 'action spawn cmd="alacritty"'
    ./ctl.py 'mine on'
    ./minesim.py                                  # смотреть: панели и пиксели
    ./minesim.py <сокет> клик|клавиша|хват|тяга|ресайз|ресайз-слева|крутить|приблизить|действие|указка|тап|лупа|жить
    ./minesim.py <сокет> коды 125:1 42:1 37:1 37:0 42:0 125:0   # Super+Shift+K

Сценарии: «клик» — ЛКМ в панель под лучом; «клавиша» — Super+Enter (бинд parallax
обязан сработать из игры); «хват» — взять панель и увести взглядом; «действие»
— попросить действие parallax по имени; «коды» — произвольное сочетание скан-кодами
(им проверяется КОНКРЕТНЫЙ бинд, см. ниже); «указка» — закрепить управление за окном
(ЛКМ по панели в игре) и повозить по нему стрелку мышью, ОТВЕДЯ взгляд: пока
закрепление держится, луч на наведение влиять не должен. Луч целится в центр первой панели: при двух
окнах взгляд прямо в −Z уходит МЕЖДУ ними, и проверять на нём нечего.

Путь dmabuf (протокол 3): `MINESIM_DMA=1 ./minesim.py ...` — сим заявляет в
«привете», что умеет dmabuf, принимает дескрипторы (SCM_RIGHTS), а в конце
читает каждый буфер ПРОЦЕССОРОМ (он линейный) и кладёт его в PNG рядом —
`MINESIM_DUMP=<каталог>` (по умолчанию /tmp). Так проверяется, что в буфере
лежит именно окно, без Minecraft и без EGL.
"""
import array, fcntl, mmap, os, socket, struct, sys, time, threading, zlib

СОКЕТ = sys.argv[1] if len(sys.argv) > 1 else "/tmp/parallax-harness/run/plx-mine.sock"
ВЕРСИЯ = 4
ДМА = os.environ.get("MINESIM_DMA") == "1"

ЗДРАВСТВУЙ, ПАНЕЛИ, ПИКСЕЛИ, КУРСОР, ПРОЩАЙ, БУФЕР, КАДР = 1, 2, 3, 4, 5, 6, 7
ПРИВЕТ, ЛУЧ, КНОПКА, КОЛЕСО, КЛАВИША, ХВАТ, ДЕЙСТВИЕ, ПОКА = 20, 21, 22, 23, 24, 25, 26, 27
УКАЗКА = 28


def кадр(тип, тело=b""):
    т = bytes([тип]) + тело
    return struct.pack("<I", len(т)) + т


def строка(s):
    b = s.encode()[:255]
    return bytes([len(b)]) + b


class Чтец:
    def __init__(self, b):
        self.b, self.i = b, 0

    def взять(self, n):
        o = self.b[self.i:self.i + n]
        assert len(o) == n, "сообщение обрезано"
        self.i += n
        return o

    def u8(self):  return self.взять(1)[0]
    def u16(self): return struct.unpack("<H", self.взять(2))[0]
    def u32(self): return struct.unpack("<I", self.взять(4))[0]
    def u64(self): return struct.unpack("<Q", self.взять(8))[0]
    def f32(self): return struct.unpack("<f", self.взять(4))[0]
    def вектор(self, n): return [self.f32() for _ in range(n)]
    def строка(self): return self.взять(self.u8()).decode("utf-8", "replace")


панели = {}
курсор = None
дескрипторы = []   # пришли вместе с байтами, в порядке прихода
буферы = {}        # ключ → (fd, ш, в, fourcc, модификатор, смещение, шаг)
кадров_дма = 0
байтов = 0
пикселей = 0


def разобрать(тело):
    global курсор, байтов, пикселей
    ч = Чтец(тело)
    т = ч.u8()
    if т == ЗДРАВСТВУЙ:
        return ("здравствуй", ч.u16(), ч.f32(), ч.f32())
    if т == ПАНЕЛИ:
        n = ч.u16()
        сп = []
        for _ in range(n):
            сп.append(dict(ключ=ч.u64(), место=ч.вектор(3), поворот=ч.вектор(4),
                           пш=ч.f32(), пв=ч.f32(), ш=ч.u16(), в=ч.u16(), заголовок=ч.строка()))
        панели.clear()
        for п in сп:
            панели[п["ключ"]] = п
        return ("панели", сп)
    if т == ПИКСЕЛИ:
        ключ = ч.u64()
        x, y, ш, в = ч.u16(), ч.u16(), ч.u16(), ч.u16()
        данные = ч.взять(ш * в * 4)
        байтов += len(данные)
        пикселей += 1
        return ("пиксели", ключ, x, y, ш, в)
    if т == КУРСОР:
        курсор = (ч.u64(), ч.f32(), ч.f32(), ч.u8() != 0)
        return ("курсор",) + курсор
    if т == ПРОЩАЙ:
        return ("прощай",)
    if т == БУФЕР:
        ключ, ш, в = ч.u64(), ч.u16(), ч.u16()
        fourcc, мод, смещение, шаг = ч.u32(), ч.u64(), ч.u32(), ч.u32()
        fd = дескрипторы.pop(0) if дескрипторы else None
        прежний = буферы.get(ключ)
        if прежний and прежний[0] is not None:
            os.close(прежний[0])
        буферы[ключ] = (fd, ш, в, fourcc, мод, смещение, шаг)
        return ("буфер", ключ, ш, в, hex(fourcc), hex(мод), смещение, шаг, "fd" if fd is not None else "БЕЗ fd")
    if т == КАДР:
        global кадров_дма
        кадров_дма += 1
        return ("кадр", ч.u64())
    return ("неизвестно", т)


с = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
с.connect(СОКЕТ)
с.sendall(кадр(ПРИВЕТ, struct.pack("<H", ВЕРСИЯ) + строка("modsim") + struct.pack("<I", 1 if ДМА else 0)))

буфер = bytearray()
события = []
стоп = False


def читать():
    global буфер, стоп
    while not стоп:
        кусок, fds, _, _ = socket.recv_fds(с, 1 << 20, 16)
        дескрипторы.extend(fds)
        if not кусок:
            события.append(("обрыв",))
            return
        буфер.extend(кусок)
        while len(буфер) >= 4:
            длина = struct.unpack("<I", буфер[:4])[0]
            if len(буфер) < 4 + длина:
                break
            тело = bytes(буфер[4:4 + длина])
            del буфер[:4 + длина]
            события.append(разобрать(тело))


п = threading.Thread(target=читать, daemon=True)
п.start()


def луч(о, н):
    return кадр(ЛУЧ, struct.pack("<6f", *о, *н))


сценарий = sys.argv[2] if len(sys.argv) > 2 else "смотреть"

time.sleep(1.0)
# Целимся в центр ПЕРВОЙ панели, если parallax уже прислала список: при двух окнах
# взгляд прямо в −Z уходит между ними, и проверять на нём клик бессмысленно.
глаз = (0.0, 1.6, 0.0)
цель = next(iter(панели.values()), None)
if цель:
    м = цель["место"]
    н = (м[0] - глаз[0], м[1] - глаз[1], м[2] - глаз[2])
else:
    н = (0.0, 0.0, -1.0)
с.sendall(луч(глаз, н))
time.sleep(1.0)

if сценарий == "клик":
    с.sendall(кадр(КНОПКА, struct.pack("<IB", 0x110, 1)))
    time.sleep(0.3)
    с.sendall(кадр(КНОПКА, struct.pack("<IB", 0x110, 0)))
    time.sleep(0.5)
if сценарий == "пкм":
    # ПКМ по панели: контекстное меню. Хозяйская клавиатура обязана остаться у
    # игры (`mine status` — «клавиатура хозяина: игры»), иначе Minecraft встаёт
    # на паузу. Меню видно в кадре, пока держится связь (SIM_HOLD).
    с.sendall(кадр(КНОПКА, struct.pack("<IB", 0x111, 1)))
    time.sleep(0.1)
    с.sendall(кадр(КНОПКА, struct.pack("<IB", 0x111, 0)))
    time.sleep(1.0)
if сценарий == "клавиша":
    # Super+Enter — бинд parallax: терминал.
    for код, наж in ((125, 1), (28, 1), (28, 0), (125, 0)):
        с.sendall(кадр(КЛАВИША, struct.pack("<IB", код, наж)))
        time.sleep(0.05)
    time.sleep(2.0)
if сценарий == "текст":
    # Набор в панель под взглядом. Проверяет ровно то, ради чего у мода своё
    # место (см. mine/seat.rs): фокус клавиатуры едет за взглядом, и клавиши
    # доходят до клиента, а не до окна, которое лежит поверх всех.
    for код in (18, 46, 35, 24, 57, 32, 50, 23, 49, 18, 28):  # "echo plx-mine\n"
        for наж in (1, 0):
            с.sendall(кадр(КЛАВИША, struct.pack("<IB", код, наж)))
            time.sleep(0.03)
    time.sleep(1.0)
if сценарий == "хват":
    # Берём панель под лучом и уводим взгляд вбок: панель обязана уехать за ним.
    с.sendall(кадр(ХВАТ, bytes([1, 0])))
    for i in range(1, 11):
        с.sendall(луч(глаз, (н[0] + 0.08 * i, н[1], н[2])))
        time.sleep(0.05)
    с.sendall(кадр(ХВАТ, bytes([0, 0])))
    time.sleep(0.5)
if сценарий == "тяга":
    # Колесо при зажатом хвате: панель обязана уехать ОТ игрока и вернуться,
    # никуда не сдвинувшись вбок. Меряется по полю «место» в списке панелей —
    # взгляд всё время один и тот же, поэтому меняться там может только длина
    # вектора от глаза до панели.
    #
    # Заодно это проверка, что зона больше не держит: ±4 блока по X и ±3 по Z
    # (`mine{}` по умолчанию 8 на 6) панель обязана проходить насквозь.
    с.sendall(кадр(ХВАТ, bytes([1, 0])))
    time.sleep(0.3)
    for _ in range(12):  # от себя
        с.sendall(кадр(КОЛЕСО, struct.pack("<2fB", 0.0, 1.0, 0)))
        time.sleep(0.08)
    time.sleep(0.4)
    for _ in range(20):  # и обратно к себе
        с.sendall(кадр(КОЛЕСО, struct.pack("<2fB", 0.0, -1.0, 0)))
        time.sleep(0.08)
    time.sleep(0.4)
    с.sendall(кадр(ХВАТ, bytes([0, 0])))
    time.sleep(0.5)
if сценарий == "далеко":
    # Зона: панель обязана выйти за ящик ±4 по X и ±3 по Z (`mine{}` по
    # умолчанию 8 на 6 блоков) и подняться выше 3 метров — до правки 02.09.2026
    # её там держало `Зона::зажать`, и это жалоба «у окон ограниченная
    # территория переноса».
    #
    # Сначала отталкиваем колесом: хват держит панель на ПОСТОЯННОМ расстоянии,
    # и с радиусом в метр никакой взгляд её за четыре метра не унесёт — упрётся
    # не ящик, а сфера. Меряется по «место» последней строки.
    с.sendall(кадр(ХВАТ, bytes([1, 0])))
    time.sleep(0.3)
    for _ in range(18):
        с.sendall(кадр(КОЛЕСО, struct.pack("<2fB", 0.0, 1.0, 0)))
        time.sleep(0.06)
    for i in range(1, 21):
        с.sendall(луч(глаз, (н[0] + 0.25 * i, н[1] + 0.15 * i, н[2])))
        time.sleep(0.05)
    с.sendall(кадр(ХВАТ, bytes([0, 0])))
    time.sleep(0.5)
if сценарий == "ресайз":
    # Super+ПКМ: ХВАТ с видом «размер» (протокол 3; Super ещё и зажат, как
    # в живой игре) — parallax обязана менять РАЗМЕР окна под взглядом, а не
    # двигать панель. Взгляд
    # уводим вправо-вниз, то есть тянем правый нижний угол: окно обязано
    # вырасти по обеим сторонам (`./ctl.py windows` до и после).
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 1)))  # Super зажат
    time.sleep(0.1)
    с.sendall(кадр(ХВАТ, bytes([1, 1])))
    for i in range(1, 11):
        с.sendall(луч(глаз, (н[0] + 0.02 * i, н[1] - 0.02 * i, н[2])))
        time.sleep(0.05)
    с.sendall(кадр(ХВАТ, bytes([0, 1])))
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 0)))
    time.sleep(0.5)
if сценарий == "ресайз-слева":
    # ТА ЖЕ тяга, но за ЛЕВУЮ половину панели и взглядом ВЛЕВО — то есть
    # наружу с другой стороны. Ровно этот случай и работал наоборот («ресайз
    # инвертирован», жалоба 05.09.2026): окно ужималось, хотя край тянули от
    # середины. Теперь обязано вырасти ровно так же, как в сценарии «ресайз».
    #
    # Сперва переводим взгляд на левую половину и только потом жмём Super+ПКМ:
    # точка захвата — это и есть та половина, за которую взялись.
    с.sendall(луч(глаз, (н[0] - 0.06, н[1], н[2])))
    time.sleep(0.3)
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 1)))
    time.sleep(0.1)
    с.sendall(кадр(ХВАТ, bytes([1, 1])))
    for i in range(1, 11):
        с.sendall(луч(глаз, (н[0] - 0.06 - 0.02 * i, н[1], н[2])))
        time.sleep(0.05)
    с.sendall(кадр(ХВАТ, bytes([0, 1])))
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 0)))
    time.sleep(0.5)
if сценарий == "крутить":
    # Super+СКМ (протокол 4, вид 2): взялись правее центра, повели прицел
    # вверх по дуге — панель обязана повернуться вокруг своей нормали
    # (`./ctl.py 'mine panels'` — поворот; размер окна не меняется).
    с.sendall(луч(глаз, (н[0] + 0.08, н[1], н[2])))
    time.sleep(0.3)
    с.sendall(кадр(ХВАТ, bytes([1, 2])))
    for i in range(1, 11):
        a = 0.15 * i
        import math
        с.sendall(луч(глаз, (н[0] + 0.08 * math.cos(a), н[1] + 0.08 * math.sin(a), н[2])))
        time.sleep(0.05)
    с.sendall(кадр(ХВАТ, bytes([0, 2])))
    time.sleep(0.5)
if сценарий == "приблизить":
    # Super+колесо без хвата: панель под прицелом уезжает дальше (6 зубцов от
    # себя) и доезжает плавно; потом 6 к себе — обратно почти туда же.
    for _ in range(6):
        с.sendall(кадр(КОЛЕСО, struct.pack("<2fB", 0.0, 1.0, 1)))
        time.sleep(0.05)
    time.sleep(1.0)
    print("после от себя — смотри mine panels", flush=True)
    time.sleep(3.0)
    for _ in range(6):
        с.sendall(кадр(КОЛЕСО, struct.pack("<2fB", 0.0, -1.0, 1)))
        time.sleep(0.05)
    time.sleep(1.0)
if сценарий == "жить":
    # Держим связь и луч пять минут: столько нужно, чтобы снаружи (`./ctl.py
    # 'action mine_grab'`, `'mine panels'`) проверить действия parallax — сцена
    # существует только пока мод на связи, поэтому без этого сценария любая
    # проверка хвата и раскладок упирается в пустой список панелей.
    for _ in range(3000):
        с.sendall(луч(глаз, н))
        time.sleep(0.1)
if сценарий == "указка":
    # Закрепляем управление за панелью под лучом и уводим взгляд в сторону:
    # наведение обязано остаться на закреплённом окне и ходить за «мышью».
    ключ = next(iter(панели), 0)
    for x, y in ((10.0, 10.0), (200.0, 120.0), (400.0, 300.0)):
        с.sendall(кадр(УКАЗКА, struct.pack("<Qff", ключ, x, y)))
        с.sendall(луч(глаз, (н[0] + 3.0, н[1], н[2])))  # взгляд мимо всех панелей
        time.sleep(0.3)
    time.sleep(0.5)
    print("закреплено за окном", ключ)
    # Отпускаем: указка возвращается взгляду.
    с.sendall(кадр(УКАЗКА, struct.pack("<Qff", 0, 0.0, 0.0)))
    time.sleep(0.5)
if сценарий == "тап":
    # Чистый тап по Super — обзор столов. Проверяет, что клавиши из игры идут
    # тем же разбором, что и с железной клавиатуры: обзора НЕТ в таблице
    # биндов, он живёт в самом разборе (см. input::разобрать_клавишу).
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 1)))
    time.sleep(0.15)
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 0)))
    time.sleep(1.0)
if сценарий == "лупа":
    # Super+Space — режим лупы, стрелки в нём панорамируют вид. Тоже мимо
    # таблицы биндов: и тумблер, и пан живут в разборе клавиш.
    for код, наж in ((125, 1), (57, 1), (57, 0)):
        с.sendall(кадр(КЛАВИША, struct.pack("<IB", код, наж)))
        time.sleep(0.05)
    for _ in range(3):
        for наж in (1, 0):
            с.sendall(кадр(КЛАВИША, struct.pack("<IB", 106, наж)))  # стрелка вправо
            time.sleep(0.05)
    с.sendall(кадр(КЛАВИША, struct.pack("<IB", 125, 0)))
    time.sleep(1.0)
if сценарий == "действие":
    с.sendall(кадр(ДЕЙСТВИЕ, строка("overview")))
    time.sleep(1.5)
if сценарий == "коды":
    # Произвольное сочетание скан-кодами evdev: `./minesim.py <сокет> коды
    # 125:1 42:1 37:1 37:0 42:0 125:0` — это Super+Shift+K (ресайз окна).
    # Заведено под жалобу 01.09.2026 «в игре не работает ресайз»: остальные
    # сценарии жёстко зашиты, а проверять надо КОНКРЕТНЫЙ бинд, причём тот же
    # самый до и после правки.
    #
    # ПАУЗА `~<секунды>` между кодами — не украшение. Всё, что копится ОТ
    # НАЖАТИЯ К НАЖАТИЮ (перебор фокуса Super+J, Alt+Tab), проверяется только
    # внутри ОДНОЙ связи: второму моду parallax отказывает («мод уже подключён»), а
    # каждый новый запуск сима заново наводит взгляд — и фокус откатывается на
    # панель под лучом, то есть кольцо не сдвигается никогда. Пауза даёт
    # прочитать `./ctl.py windows` между нажатиями, пока связь жива:
    #   ./minesim.py <сокет> коды 125:1 36:1 36:0 125:0 ~4 125:1 36:1 36:0 125:0
    for пара in sys.argv[3:]:
        if пара.startswith("~"):
            print("пауза", пара[1:], flush=True)
            time.sleep(float(пара[1:]))
            continue
        код, _, наж = пара.partition(":")
