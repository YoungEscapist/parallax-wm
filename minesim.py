def png(путь, ш, в, rgba):
    сырые = b"".join(b"\x00" + rgba[y * ш * 4:(y + 1) * ш * 4] for y in range(в))
    def кусок(т, д):
        return struct.pack(">I", len(д)) + т + д + struct.pack(">I", zlib.crc32(т + д))
    with open(путь, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + кусок(b"IHDR", struct.pack(">IIBBBBB", ш, в, 8, 6, 0, 0, 0))
                + кусок(b"IDAT", zlib.compress(сырые, 3)) + кусок(b"IEND", b""))


