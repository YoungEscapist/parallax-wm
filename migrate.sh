#!/usr/bin/env bash
# migrate.sh — перенести настройки со старых имён (dawn/dwall) на новые
# (parallax/plx-wall).
#
# Переименование затронуло НЕ только код: композитор читает конфиг из
# ~/.config/parallax, состояние сессии кладёт в ~/.local/state/parallax, а обои
# держат свой выбор и палитру в ~/.config/plx-wall и ~/.cache/plx-wall. Пока
# каталоги лежат под старыми именами, новые бинари их не найдут и молча
# начнут с нуля: config.lua подменится встроенным по умолчанию, а обои забудут
# выбранную картинку.
#
# ЗАПУСКАТЬ ИЗ ТЕКСТОВОЙ КОНСОЛИ, А НЕ ИЗНУТРИ ИДУЩЕГО СЕАНСА. Уводить конфиг
# из-под работающего композитора незачем: он держит открытыми файлы в этих
# каталогах, и часть правок (например, сохранение сессии при выходе) уедет по
# старому пути уже после переноса.
#
# Скрипт ничего не удаляет и ничего не перезаписывает: если новый каталог уже
# существует, старый остаётся на месте и печатается предупреждение.
set -u

# ВНИМАНИЕ: имена переменных здесь только латиницей. Кириллическое имя bash
# не считает идентификатором — `local старое=...` падает с «not a valid
# identifier», а `$старое` остаётся текстом. Скрипт при этом НЕ обрывается
# (set -u на это не ловит) и выходит с кодом 0: раньше он честно печатал
# «нет, пропускаю» для каждого каталога и не переносил ничего. Имена функций
# кириллицей bash допускает — их трогать не нужно.
перенести() {
    local src="$1" dst="$2"
    if [[ ! -e $src ]]; then
        printf '  ·  %s — нет, пропускаю\n' "$src"
        return
    fi
    if [[ -e $dst ]]; then
        printf '  !  %s уже есть — %s НЕ трогаю, разберись руками\n' "$dst" "$src"
        return
    fi
    mkdir -p "$(dirname "$dst")"
    if mv -- "$src" "$dst"; then
        printf '  ✓  %s → %s\n' "$src" "$dst"
    else
        printf '  ✗  не удалось перенести %s\n' "$src" >&2
    fi
}

echo "Перенос настроек на новые имена:"
перенести "$HOME/.config/dawn"        "$HOME/.config/parallax"
перенести "$HOME/.local/state/dawn"   "$HOME/.local/state/parallax"
перенести "$HOME/.config/dwall"       "$HOME/.config/plx-wall"
перенести "$HOME/.cache/dwall"        "$HOME/.cache/plx-wall"

# Старые команды в ~/.local/bin: их ставили прошлые сборки, и они остались бы
# рядом с новыми — лишний повод перепутать, какая из них свежая.
echo "Старые команды в ~/.local/bin (удалить можно вручную):"
for old in dwall dwall-themes dshare dawn-share; do
    [[ -e "$HOME/.local/bin/$old" ]] && printf '  ·  ~/.local/bin/%s\n' "$old"
done

# Файлы портала под старым именем. Вреда от них нет: фронтенд ищет
# `$XDG_CURRENT_DESKTOP-portals.conf`, а рабочий стол теперь зовётся parallax,
# так что старые лежат мёртвым грузом. Но найти их потом, разбираясь, почему
# «демонстрация экрана уходит не туда», будет некому — проще показать сразу.
# Новые parallax.* композитор пишет сам при старте (см. install_portal_files).
echo "Старые файлы портала (удалить можно вручную):"
for old in "$HOME/.local/share/xdg-desktop-portal/portals/dawn.portal" \
           "$HOME/.config/xdg-desktop-portal/dawn-portals.conf"; do
    [[ -e $old ]] && printf '  ·  %s\n' "$old"
done

echo
echo "Готово. Дальше: ./build.sh, затем перелогиниться."
